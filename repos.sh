#!/usr/bin/env bash
# repos.sh — перечень репозиториев продукта ВЫВОДИТСЯ ИЗ ДЕРЕВА, а не выписывается руками.
#
# Почему выводится. Рукописный перечень был причиной того, что модель распространения
# оснастки не выполнялась ни разу и это было ненаблюдаемо: три скрипта несли ТРИ копии
# одного списка, они уже разошлись между собой (в sync-all.sh не хватало kacho-geo), а
# ни одно имя из них не пересекалось с тем, что реально склонировано. Список, который
# нужно помнить и править в трёх местах, рано или поздно расходится с деревом — и
# расхождение молчит, потому что «имени нет на диске» выглядит как штатный skip.
#
# Единица счёта здесь — РАБОЧАЯ КОПИЯ (каталог с собственным .git), а не «репозиторий»:
# двух рабочих копий одного origin бывает больше одной, и оснастка нужна каждой из них
# по отдельности. Число различных репозиториев печатается рядом, чтобы эти две величины
# нельзя было спутать.
#
# Источник: sync-tooling.sh, sync-all.sh. Не исполняется сам по себе — только `source`.

# Владелец, под которым живут репозитории продукта. Переопределяется в тестах, где
# remote'ы — локальные bare-репо без владельца в URL.
KACHO_REPO_OWNER="${KACHO_REPO_OWNER:-PRO-Robotech}"

# kacho_repo_identity <dir> — печатает «owner/name» рабочей копии продукта, либо ничего.
#
# Предикат «является рабочей копией репозитория продукта» — четыре условия, и каждое
# отсекает реально встретившийся в дереве случай, а не воображаемый:
#
#   1. каталог САМ является корнем рабочей копии    → отсекает `beget-hbf` (чужой продукт,
#                                                     разложен файлами, .git нет вовсе);
#   2. рабочая копия ОСНОВНАЯ, а не присоединённая  → отсекает `kacho-wt-disabled-sa`
#                                                     (git worktree того же самого репо:
#                                                     .git — файл-указатель, git-dir не
#                                                     совпадает с git-common-dir). Оснастка
#                                                     в присоединённую копию не раскатывается:
#                                                     она приезжает туда из git вместе с
#                                                     веткой, а запись поверх дала бы
#                                                     локальную правку в чужом дереве;
#   3. origin принадлежит владельцу продукта        → отсекает клон ЧУЖОГО репозитория,
#                                                     как бы ни назывался каталог;
#   4. имя В ORIGIN — имя репозитория продукта      → отсекает `PRO-Robotech/beget-hbf`:
#                                                     тот же владелец, другой продукт.
#
# Условие 1 сверяет КОРЕНЬ рабочей копии с самим каталогом, а не просто «git здесь
# отвечает». Первая редакция спрашивала `git -C "$d" rev-parse` и считала успех
# признаком репозитория — а git делает walkup к родителю, поэтому `project/beget-hbf`,
# где нет ни одного файла git, опознавался как… рабочая копия самого воркспейса. Проверка
# имела форму и не имела предмета; поймал её контроль, а не чтение.
#
# Опознание идёт по origin, а не по имени КАТАЛОГА: имя каталога — произвольная метка
# (`kacho-wt-disabled-sa` назван как репозиторий, но им не является; клон нашего репо
# можно положить в каталог с любым именем — контроль это проверяет). Имя в условии 4 —
# сегмент самого origin, то есть часть неизменяемой идентичности репозитория, а не
# локальная метка. Это то же правило, что core #15 применяет к ресурсам — адресация по
# идентичности, а не по мутабельному имени; здесь оно применено к собственной оснастке.
kacho_repo_identity() {
  local d="$1" toplevel gitdir commondir url path owner name

  # 1. каталог сам является корнем рабочей копии (а не лежит ВНУТРИ чужой)
  toplevel="$(git -C "$d" rev-parse --show-toplevel 2>/dev/null)" || return 1
  [ -n "$toplevel" ] || return 1
  [ "$(cd "$d" 2>/dev/null && pwd -P)" = "$(cd "$toplevel" 2>/dev/null && pwd -P)" ] || return 1

  # 2. основная рабочая копия, а не присоединённая
  gitdir="$(git -C "$d" rev-parse --path-format=absolute --absolute-git-dir 2>/dev/null)" || return 1
  commondir="$(git -C "$d" rev-parse --path-format=absolute --git-common-dir 2>/dev/null)" || return 1
  [ "$gitdir" = "$commondir" ] || return 1

  url="$(git -C "$d" remote get-url origin 2>/dev/null)" || return 1
  [ -n "$url" ] || return 1

  # Нормализация к «owner/name»: берём два последних сегмента пути URL и снимаем .git.
  # Форма URL при этом роли не играет — https, ssh (scp-like) и file:// дают одно и то же.
  path="${url%.git}"
  path="${path%/}"
  name="${path##*/}"
  path="${path%/*}"
  owner="${path##*[:/]}"

  [ -n "$owner" ] && [ -n "$name" ] || return 1
  [ "$owner" = "$KACHO_REPO_OWNER" ] || return 1

  # 4. имя В ORIGIN — репозиторий продукта: монорепо `kacho` либо полирепо `kacho-<part>`
  # (naming convention, core §Naming: имена репо — `kacho-<part>` через дефис).
  case "$name" in
    kacho | kacho-*) ;;
    *) return 1 ;;
  esac

  printf '%s/%s\n' "$owner" "$name"
}

# kacho_discover_worktrees <project_dir> — печатает по строке на рабочую копию продукта:
# «<абсолютный путь>\t<owner/name>». Порядок — лексикографический по пути (детерминизм:
# вывод гейта не должен зависеть от порядка обхода каталога).
kacho_discover_worktrees() {
  local project_dir="$1" d id
  [ -d "$project_dir" ] || return 0
  for d in "$project_dir"/*/; do
    d="${d%/}"
    [ -d "$d" ] || continue
    if id="$(kacho_repo_identity "$d")"; then
      printf '%s\t%s\n' "$d" "$id"
    fi
  done | sort
}
