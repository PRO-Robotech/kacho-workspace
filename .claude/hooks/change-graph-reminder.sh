#!/usr/bin/env bash
# PostToolUse hook — напоминание контура изменения В МОМЕНТ, когда оно действует.
#
# ТРИ МОМЕНТА, И БОЛЬШЕ НИКАКИХ. Хук молчит на всём остальном намеренно: строка,
# печатающаяся всегда, перестаёт читаться на третий день, и вместе с ней
# перестают читать настоящую находку.
#
#   1. записан ПОРОЖДЁННЫЙ файл  → это производное, предмет правки во входе;
#   2. записан канонический ВХОД → производное разошлось (проверяется, а не
#      предполагается: регенерация во временный каталог и побайтовое сравнение);
#   3. записана ПРИЁМКА          → вердикт привязан к отпечатку, и отпечаток
#      только что изменился.
#
# ПОЧЕМУ ВТОРОЙ МОМЕНТ ПРОВЕРЯЕТСЯ, А НЕ ОБЪЯВЛЯЕТСЯ. «Правишь вход — не забудь
# перегенерировать» срабатывало бы на КАЖДОЙ правке оснастки, в том числе на
# правке, которая производное не меняет вовсе. Порог, срабатывающий на штатном
# состоянии, читать перестают. Здесь хук говорит только тогда, когда расхождение
# ЕСТЬ, и замолкает сам, как только его перегенерировали.
#
# Запись НЕ блокируется (PostToolUse срабатывает после неё). Код 2 означает
# «есть что сказать» — stderr доезжает до автора немедленно.
#
# СОБСТВЕННАЯ ПОЛОМКА ЭТОГО СКРИПТА — ГРОМКАЯ. Молчаливый выход нулём здесь
# запрещён: он неотличим от «проверил и сошлось», а это ровно тот класс, который
# контур и ловит (мягкий проход, не различающий настройку и сбой).
set -u

_src="${BASH_SOURCE[0]}"
HOOK_DIR="$(cd "${_src%/*}" 2>/dev/null && pwd)" || HOOK_DIR="."
ROOT="$(cd "$HOOK_DIR/../.." 2>/dev/null && pwd)" || ROOT="."

PY="$(command -v python3 || true)"
if [ -z "$PY" ]; then
  {
    echo "╔══ CHANGE-GRAPH СЛОМАН ══════════════════════════════════════════"
    echo "║ python3 не найден в PATH — путь правки не разобран, ничего не проверено."
    echo "║ Это НАСТРОЙКА, а не сбой: она не чинится сама и не истечёт."
    echo "╚═════════════════════════════════════════════════════════════════"
  } >&2
  exit 2
fi

# Полезная нагрузка читается со stdin ОДИН РАЗ и дальше передаётся аргументом.
#
# Не «так короче»: `python3 -` берёт ПРОГРАММУ со stdin, и heredoc, которым её
# удобно писать, занимает stdin целиком — полезная нагрузка до разбора не
# доезжает вовсе. Хук при этом молчит на всех трёх моментах и выглядит
# исправным: молчание неотличимо от «нечего сказать». Поймано прогоном, не
# чтением.
PAYLOAD="$(cat)"

REL="$("$PY" -c '
import json, os, sys
try:
    payload = json.loads(sys.argv[1])
except Exception:
    sys.exit(0)
path = (payload.get("tool_input") or {}).get("file_path") or ""
if not path:
    sys.exit(0)
try:
    rel = os.path.relpath(os.path.abspath(path), sys.argv[2])
except ValueError:
    sys.exit(0)
if not rel.startswith(".."):
    sys.stdout.write(rel.replace(os.sep, "/"))
' "$PAYLOAD" "$ROOT" 2>/dev/null)"

[ -n "$REL" ] || exit 0

MANIFEST="$ROOT/.claude/adapters.yaml"

# ── момент 3: приёмка ────────────────────────────────────────────────────────
case "$REL" in
  docs/specs/*-acceptance.md)
    DIGEST="$("$PY" -c "
import hashlib,sys
print(hashlib.sha256(open(sys.argv[1],'rb').read()).hexdigest())
" "$ROOT/$REL" 2>/dev/null)"
    {
      echo "╔══ контур изменения · приёмка ═══════════════════════════════════"
      echo "║ $REL"
      echo "║"
      echo "║ Вердикт привязан к ОТПЕЧАТКУ содержимого, а не к имени документа."
      echo "║ Отпечаток после этой правки:"
      echo "║   ${DIGEST:-<не посчитан>}"
      echo "║"
      echo "║ Значит: прежнее одобрение осталось одобрением ПРЕЖНЕЙ редакции."
      echo "║ Слово в шапке — не действующий вердикт; действующий выводится из"
      echo "║ внешнего события и ДОБАВЛЯЕМОЙ записи. Прежнюю не переписывай —"
      echo "║ новая редакция получает соседнюю."
      echo "║"
      echo "║ Норма: .claude/rules/change-graph.md §Вердикт привязан"
      echo "╚═════════════════════════════════════════════════════════════════"
    } >&2
    exit 2
    ;;
esac

# ── момент 1: записан порождённый файл ───────────────────────────────────────
case "$REL" in
  AGENTS.md|.agents/*|.codex/*)
    {
      echo "╔══ контур изменения · это ПРОИЗВОДНОЕ ═══════════════════════════"
      echo "║ $REL"
      echo "║"
      echo "║ Файл порождается из канонической оснастки. Правка уедет при"
      echo "║ следующей регенерации, а гейт назовёт её расхождением."
      echo "║ ПРЕДМЕТ ПРАВКИ ВСЕГДА ВО ВХОДЕ: CLAUDE.md либо .claude/**."
      echo "║"
      echo "║   python3 scripts/adapter/generate.py     # перегенерировать"
      echo "║   ./scripts/adapter-gate/run-all.sh       # сверить с деревом"
      echo "║"
      echo "║ Владение: .claude/adapters.yaml"
      echo "║ Норма: .claude/rules/change-graph.md §Оснастка"
      echo "╚═════════════════════════════════════════════════════════════════"
    } >&2
    exit 2
    ;;
esac

# ── момент 2: записан канонический вход ──────────────────────────────────────
#
# Каноничность спрашивается У МАНИФЕСТА, а не выписывается здесь: второй перечень
# входов разошёлся бы с первым молча.
[ -f "$MANIFEST" ] || exit 0

IS_INPUT="$("$PY" -c '
import sys
try:
    import yaml
    with open(sys.argv[1], encoding="utf-8") as handle:
        doc = yaml.safe_load(handle) or {}
except Exception:
    sys.exit(0)
rel = sys.argv[2]
for entry in doc.get("canonical_inputs") or []:
    if rel == entry or rel.startswith(entry.rstrip("/") + "/"):
        sys.stdout.write("да")
        break
' "$MANIFEST" "$REL" 2>/dev/null)"

[ "$IS_INPUT" = "да" ] || exit 0

# Расхождение ПРОВЕРЯЕТСЯ. Молчим, пока его нет.
OUT="$("$PY" "$ROOT/scripts/adapter-gate/probe.py" derived-drift 2>&1)"
RC=$?

case "$RC" in
  0) exit 0 ;;                     # производное сошлось — говорить не о чем
  2) exit 0 ;;                     # сверять не с чем: это не момент хука
  *)
    {
      echo "╔══ контур изменения · производное РАЗОШЛОСЬ ═════════════════════"
      echo "║ правлен канонический вход: $REL"
      echo "║"
      printf '%s\n' "$OUT" | grep -v '^CENSUS ' | sed 's/^/║ /'
      echo "║"
      echo "║   python3 scripts/adapter/generate.py"
      echo "║"
      echo "║ Отслеживаемое производное обязано совпадать с регенерацией"
      echo "║ побайтово: иначе расхождение входа и выхода не обнаруживается"
      echo "║ ничем, а выход читается как утверждение об оснастке."
      echo "║ Норма: .claude/rules/change-graph.md §Оснастка"
      echo "╚═════════════════════════════════════════════════════════════════"
    } >&2
    exit 2
    ;;
esac
