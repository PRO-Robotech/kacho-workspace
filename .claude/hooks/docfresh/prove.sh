else
  echo "  ✘ вердикт без ревизии — неотличим от вердикта о продукте"; FAIL=$((FAIL+1))
fi
# Предупреждение об отставании обязано появляться ТОЛЬКО когда отставание есть,
# иначе оно шум и его перестанут читать.
#
# И спрашивать надо ПРО ТО ЖЕ ДЕРЕВО, про которое меришь. Прежняя редакция мерила
# отставание ОДНОГО дерева (продукта), а искала предупреждение во ВСЕЙ строке
# провенанса — где их два, продукта и воркспейса. На любой ветке, отставшей от
# ствола воркспейса (то есть на каждой рабочей ветке между синхронизациями), проба
# краснела при полностью исправном хуке. Теперь у каждого дерева спрашивается его
# СОБСТВЕННЫЙ отрезок строки — утверждение и измерение снова об одном предмете.
prov_segment() { # prov_segment <строка переписи> <mono|ws> → отрезок провенанса дерева
  local line="$1" tag="$2" head tail
  head="${line%%· воркспейс *}"
  tail="${line#*· воркспейс }"
  if [ "$tag" = mono ]; then printf '%s' "$head"
  elif [ "$tail" != "$line" ]; then printf '%s' "${tail%%· осмотрено документов*}"
  fi
}
behind_of() { # behind_of <корень> → на сколько коммитов копия позади ствола
  # Отставание спрашивается У САМОГО ХУКА, а не считается второй раз своей
  # командой. Прежняя редакция мерила `HEAD..main` — локальную ветку, — тогда как
  # хук с 2026-08-19 берёт наиболее продвинутого кандидата, включая ветки
  # слежения. Два предиката об одном предмете разошлись бы ровно там, где
  # расхождение и опасно: на копии, чей локальный `main` отстал, проба говорила
  # «отставания нет», а перепись — «отстаёт на 302», и красным оказался бы
  # исправный хук. Один предикат на страж, самоотчёт и пробу — норма корпуса.
  local root="$1" n
  n="$(python3 - "$GUARD" "$root" <<'PY' 2>/dev/null
import importlib.util, sys, pathlib
spec = importlib.util.spec_from_file_location("dfb", sys.argv[1])
m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
print(m._provenance(pathlib.Path(sys.argv[2]))["behind"])
PY
)" || n=0
  printf '%s' "${n:-0}"
}
for tree in mono ws; do
  case "$tree" in
    mono) root="$WS/project/kacho"; human="дерево продукта" ;;
    ws)   root="$WS";               human="воркспейс" ;;
  esac
  seg="$(prov_segment "$out" "$tree")"
  behind="$(behind_of "$root")"
  if [ -z "$seg" ]; then
    notrun "провенанс не назвал отрезок «$human» — сверять предупреждение не с чем"
  elif [ "$behind" -gt 0 ]; then
    # ДВЕ ФОРМЫ ОДНОГО ПРЕДУПРЕЖДЕНИЯ, и обе годятся. Копия, у которой есть и
    # неподтянутые чужие коммиты, и свои неотправленные, РАСХОДИТСЯ со стволом —
    # и хук честно печатает «РАСХОДИТСЯ … позади N, впереди M», что точнее, чем
    # «ОТСТАЁТ на N». Прежняя редакция искала вторую формулировку ДОСЛОВНО и
    # краснела на первой, то есть утверждала ФОРМУ СТРОКИ вместо свойства.
    #
    # Свойство здесь одно: перепись обязана НАЗВАТЬ отставание числом. Молчание
    # и слово «вровень» его не выполняют — на них проба по-прежнему краснеет.
    if printf '%s' "$seg" | grep -qE 'ОТСТАЁТ от|РАСХОДИТСЯ со стволом'; then
      echo "  ✔ (+) $human отстаёт на $behind — перепись предупреждает"; PASS=$((PASS+1))
    else
      echo "  ✘ (+) $human отстаёт на $behind, а перепись молчит"; FAIL=$((FAIL+1))
    fi
  else
    if printf '%s' "$seg" | grep -qF 'ОТСТАЁТ от'; then
      echo "  ✘ (−) $human не отстаёт, а перепись предупреждает — предупреждение всегда"; FAIL=$((FAIL+1))
    else
      echo "  ✔ (−) $human не отстаёт — предупреждения нет"; PASS=$((PASS+1))
    fi
  fi
done

# (+) ВХОД СТРОИТСЯ, а не берётся из состояния копии запускающего.
#
# Обе половины выше ветвятся по ФАКТИЧЕСКОМУ отставанию, поэтому на машине, где
# копии вровень, исполняется только (−) — и свойство «перепись НАЗЫВАЕТ отставание
# ЧИСЛОМ» там не проверяется ВОВСЕ. У ранера копии вровень ВСЕГДА (свежий клон),
# значит в конвейере эта половина не исполнялась ни разу: замер прогона ствола
# 2026-08-27 — обе строки «(−) не отстаёт». Проба, чей вход зависит от того, что
# лежит на диске у запускающего, измеряет диск, а не свойство.
#
# Приём тот же, что этажом ниже у выбора ствола: клон `--shared` (объекты общие,
# запись своя), откат локальной ветки в СВОЕЙ копии — чужое дерево не трогается.
# Мера идёт по НАСТОЯЩЕМУ отставшему репозиторию: `_provenance` его считает, а
# `tree_provenance` рендерит — обе половины цепочки прод-кода, а не выдуманная
# строка.
prov_behind="$TMP/prov-behind"
if [ ! -d "$WS/project/kacho/.git" ]; then
  notrun "дерева продукта нет — отставшую копию строить не из чего"
elif ! { git clone -q --shared --no-checkout "$WS/project/kacho" "$prov_behind" 2>/dev/null &&
         git -C "$prov_behind" rev-parse --verify --quiet 'HEAD~1^{commit}' >/dev/null; }; then
  notrun "отставшую копию не построить: у дерева продукта нет предка вершины — вход взять неоткуда"
else
  git -C "$prov_behind" update-ref refs/remotes/origin/main "$(git -C "$prov_behind" rev-parse HEAD)"
  git -C "$prov_behind" update-ref refs/heads/main "$(git -C "$prov_behind" rev-parse 'HEAD~1')"
  prov_out="$(unset DOCFRESH_INTEGRATION_REF; python3 - "$GUARD" "$prov_behind" <<'PY' 2>/dev/null
import importlib.util, sys, pathlib, types
spec = importlib.util.spec_from_file_location("dfpv", sys.argv[1])
m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
p = m._provenance(pathlib.Path(sys.argv[2]))
print("BEHIND", p.get("behind") or 0)
print("LINE", m.tree_provenance(types.SimpleNamespace(prov={"mono": p})))
PY
)"
  prov_n="$(printf '%s\n' "$prov_out" | awk '$1=="BEHIND"{print $2}')"
  prov_line="$(printf '%s\n' "$prov_out" | sed -n 's/^LINE //p')"
  if [ "${prov_n:-0}" -eq 0 ]; then
    notrun "построенная копия отставшей не оказалась — измерять предупреждение не на чем"
  elif printf '%s' "$prov_line" | grep -qE "(ОТСТАЁТ от ствола|РАСХОДИТСЯ со стволом)[^·]*$prov_n"; then
    echo "  ✔ (+) ПОСТРОЕННАЯ отставшая копия (позади $prov_n) — перепись называет отставание числом"; PASS=$((PASS+1))
  else
    echo "  ✘ (+) копия позади $prov_n, а перепись числа не называет: «$prov_line»"; FAIL=$((FAIL+1))
  fi
  # (−) ЗАКОННЫЙ БЛИЗНЕЦ ТОЙ ЖЕ ПОСТРОЙКИ: та же копия, приведённая к стволу,
  # обязана читаться «вровень». Без него «называет отставание» было бы
  # неотличимо от «предупреждает всегда» — и на ранере, где копии вровень,
  # предупреждение шло бы на каждом прогоне.
  git -C "$prov_behind" update-ref refs/heads/main "$(git -C "$prov_behind" rev-parse refs/remotes/origin/main)"
  prov_line="$(unset DOCFRESH_INTEGRATION_REF; python3 - "$GUARD" "$prov_behind" <<'PY' 2>/dev/null
import importlib.util, sys, pathlib, types
spec = importlib.util.spec_from_file_location("dfpv", sys.argv[1])
m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
p = m._provenance(pathlib.Path(sys.argv[2]))
print(m.tree_provenance(types.SimpleNamespace(prov={"mono": p})))
PY
)"
  if printf '%s' "$prov_line" | grep -qF 'вровень со стволом'; then
    echo "  ✔ (−) та же копия, приведённая к стволу, — «вровень», предупреждения нет"; PASS=$((PASS+1))
  else
    echo "  ✘ (−) копия вровень, а перепись не сказала «вровень»: «$prov_line»"; FAIL=$((FAIL+1))
  fi
  rm -rf "$prov_behind"
fi

echo
echo "== M. полоса ствола: живое на стволе — НЕ находка (обе стороны) =="
# Резолв идёт по ВЫПИСАННОЙ копии, а у продукта их много — worktree на задачу.
# Копия в `project/kacho` может стоять на сотню коммитов позади линии интеграции,
# и тогда путь, живущий в стволе, читается как несуществующий: гейт краснеет
# ровно на свежей работе. Пара обязана быть двусторонней — иначе «молчит» было бы
# неотличимо от мёртвого предиката.
