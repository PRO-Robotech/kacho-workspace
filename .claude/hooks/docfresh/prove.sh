#!/usr/bin/env bash
# Доказательство docfresh ИНЪЕКЦИЕЙ, в обе стороны — по каждому предикату.
#
# Запрет стоит чего-то, только если проверен с двух сторон:
#   (+) верни НАСТОЯЩЕЕ расхождение → хук КРАСНЕЕТ и НАЗЫВАЕТ координату;
#   (−) поставь рядом ЗАКОННУЮ конструкцию той же формы → хук МОЛЧИТ.
# Без (−) хук ловит форму, а не существо, и первый же ложный срабат его отключит.
#
# Вход обеих сторон — НАСТОЯЩИЕ фрагменты дерева, а не выдуманные строки. Пробные
# ДОКУМЕНТЫ пишутся во временный каталог (DOCFRESH_DOC_ROOT), рабочее дерево не
# трогается; ОСНОВАНИЕ ИСТИНЫ при этом остаётся настоящим — подменённое основание
# доказывало бы лишь, что регулярное выражение совпадает само с собой.
#
# Запуск: bash .claude/hooks/docfresh/prove.sh    (код 0 — все пары сошлись)
#
# shellcheck disable=SC2016
# Одинарные кавычки в телах проб — НАМЕРЕННЫЕ и снимать их нельзя. Тело пробы
# состоит из координат в обратных кавычках; в двойных кавычках shell исполнил бы
# их как подстановку команды, и проба ушла бы в хук уже без координаты, оставаясь
# при этом зелёной на стороне (−). Класс известен по журналу корпуса: обратные
# кавычки в сообщении коммита исполнялись, идентификатор исчезал молча.
set -uo pipefail

HOOK="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/docfresh.sh"
# Проба обязана быть СПОСОБНОЙ упасть, и это проверяется наведением её на
# ревизию ДО починки — иначе «зелено» доказывает лишь, что проба существует.
# Отсюда единственная точка подмены исполняемого хука; она ГРОМКАЯ, потому что
# молча наведённый на чужую ревизию набор доказывал бы не то, что читают.
if [ -n "${DOCFRESH_PROVE_HOOK:-}" ]; then
  HOOK="$DOCFRESH_PROVE_HOOK"
  echo "!! ВНИМАНИЕ: набор наведён на ПОДМЕНЁННЫЙ хук: $HOOK"
  echo "!! Вердикт относится к нему, а не к тому, что провязан в settings.json."
fi
WS="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
# Разбор ВЫВОДИТСЯ ИЗ ХУКА, а не из места этого файла. Пробы, зовущие модуль
# напрямую (списки кандидатов, провенанс, предпосылки), иначе грузят разбор
# рядом с собой — и подмена `DOCFRESH_PROVE_HOOK` их не касается: набор,
# наведённый на ревизию ДО починки, отчитывается по ним зелёным, доказывая не то.
# Замер 2026-08-19: из девяти проб секции M' три остались зелёными на дофиксовом
# хуке ровно по этой причине. Один предикат «какой разбор исполняется» — и на
# страж, и на пробу; координата берётся так же, как её берёт сам `docfresh.sh`.
GUARD="$(cd "$(dirname "$HOOK")" && pwd)/docfresh/docfresh.py"
export CLAUDE_PROJECT_DIR="$WS"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
DOCS="$TMP/docs"; mkdir -p "$DOCS"

PASS=0; FAIL=0; NOTRUN=0

# --- предмет проб: живость входа проверяется ПЕРЕД пробами ------------------
#
# Инъекция «настоящим расхождением» перестаёт быть настоящей в тот день, когда
# расхождение починят. Тогда проба (+) начнёт зеленеть на исправленном дереве и
# будет молча доказывать не то. Поэтому вход каждой (+)-пробы проверяется
# отдельно, и «предмета больше нет» — ТРЕТИЙ исход, а не успех.
absent_path() { [ ! -e "$WS/$1" ] && [ ! -e "$WS/project/kacho/$1" ]; }
present_path() { [ -e "$WS/$1" ] || [ -e "$WS/project/kacho/$1" ]; }

run_doc() { # run_doc <относительный путь пробы> <содержимое> → stderr+stdout хука
  local body="$2" abs="$DOCS/$1"
  mkdir -p "$(dirname "$abs")"
  printf '%s\n' "$body" > "$abs"
  DOCFRESH_DOC_ROOT="$DOCS" printf '{"hook_event_name":"PostToolUse","tool_name":"Write","tool_input":{"file_path":"%s"}}' "$abs" \
    | DOCFRESH_DOC_ROOT="$DOCS" bash "$HOOK" 2>&1
  rm -f "$abs"
}

expect_fires() { # expect_fires <метка> <проба-путь> <тело> <искомая координата>
  local label="$1" out
  out="$(run_doc "$2" "$3")"
  if printf '%s' "$out" | grep -qF -- "$4"; then
    echo "  ✔ (+) $label — краснеет и называет координату"; PASS=$((PASS+1))
  else
    echo "  ✘ (+) $label — НЕ сработал на настоящем расхождении"; FAIL=$((FAIL+1))
    printf '%s\n' "$out" | sed 's/^/      /' | head -6
  fi
}

expect_silent() { # expect_silent <метка> <проба-путь> <тело> <координата-близнец>
  local label="$1" out
  out="$(run_doc "$2" "$3")"
  if printf '%s' "$out" | grep -qF -- "$4"; then
    echo "  ✘ (−) $label — ЛОЖНЫЙ СРАБАТ на законной конструкции той же формы"; FAIL=$((FAIL+1))
    printf '%s\n' "$out" | sed 's/^/      /' | head -6
  else
    echo "  ✔ (−) $label — молчит"; PASS=$((PASS+1))
  fi
}

notrun() { echo "  ⊘ НЕ ВЫПОЛНИЛОСЬ: $1"; NOTRUN=$((NOTRUN+1)); }

# Объём осмотренного печатается ОДНОЙ функцией, а не двумя копиями строк: у
# набора теперь два выхода — обычный конец и ранний отказ по предпосылке, — и
# две копии разошлись бы молча ровно в том исходе, который случается редко.
census() {
  echo "══ предпосылок объявлено и проверено: $PREMISE_SEEN · мёртвых: $PREMISE_DEAD ══"
  echo "══ проб: $((PASS+FAIL)) · сошлось: $PASS · разошлось: $FAIL · НЕ ВЫПОЛНИЛОСЬ: $NOTRUN ══"
}

# --- предпосылка объявляется РЯДОМ с пробой и проверяется ПЕРЕД ней -----------
#
# Проба, чей исход объясняется не только формой, но и ЖИВОСТЬЮ названной
# координаты, обязана эту живость объявить. Иначе переезд файла в чужом дереве
# читается как поломка хука — и читается громко: 2026-08-11 глава `ARCHITECTURE.md`
# уехала на уровень ниже, и отрицательная проба относительной ссылки отчиталась
# «ЛОЖНЫЙ СРАБАТ на законной конструкции» при полностью исправном хуке, который
# назвал координату верно. Ствол воркспейса простоял красным пять прогонов, и ни
# один PR в это время не был судим — «сломал я» стало неотличимо от «было сломано».
#
# Мёртвая предпосылка — ТРЕТИЙ исход («не выполнилось»), а не разошедшаяся проба:
# она называет, что переанкерить, и не обвиняет механизм в чужом переезде. Зелёной
# она при этом НЕ считается: вердикт требует нуля и по этой категории тоже.
PREMISE_SEEN=0; PREMISE_DEAD=0
premise_live() { # premise_live <координата> → 0, если координата ЖИВА в дереве
  PREMISE_SEEN=$((PREMISE_SEEN+1))
  present_path "$1" && return 0
  PREMISE_DEAD=$((PREMISE_DEAD+1)); return 1
}
premise_dead() { # premise_dead <координата> → 0, если координаты в дереве НЕТ
  PREMISE_SEEN=$((PREMISE_SEEN+1))
  absent_path "$1" && return 0
  PREMISE_DEAD=$((PREMISE_DEAD+1)); return 1
}
expect_silent_live() { # <метка> <док-путь> <тело> <needle> <координата, обязанная ЖИТЬ>
  if premise_live "$5"; then expect_silent "$1" "$2" "$3" "$4"
  else notrun "вход (−) «$1» мёртв: '$5' в дереве не резолвится — близнец больше не законный. Переанкерить пробу на нынешнюю координату (не ослаблять утверждение и не заносить в исключения)"; fi
}
expect_silent_dead() { # <метка> <док-путь> <тело> <needle> <координата, обязанная ОТСУТСТВОВАТЬ>
  if premise_dead "$5"; then expect_silent "$1" "$2" "$3" "$4"
  else notrun "вход (−) «$1» испорчен: '$5' появился в дереве — молчание объяснялось бы живостью координаты, а не проверяемой формой. Переанкерить пробу"; fi
}
expect_fires_dead() { # <метка> <док-путь> <тело> <needle> <координата, обязанная ОТСУТСТВОВАТЬ>
  if premise_dead "$5"; then expect_fires "$1" "$2" "$3" "$4"
  else notrun "вход (+) «$1» починен: '$5' появился в дереве — расхождение больше не настоящее. Переанкерить пробу на живое расхождение (не ослаблять утверждение)"; fi
}

# --- ПРЕДПОСЫЛКА НАБОРА: хук вообще ВЫНОСИТ вердикт --------------------------
#
# Хук судит координаты по ДВУМ деревьям и, не найдя дерева продукта рядом,
# отказывается работать ЦЕЛИКОМ — вслух, своей рамкой: «ноль находок» без
# основания истины означало бы «ноль прочитанного», и он это говорит сам.
#
# Набор ниже этого не читал, и обе его половины лгали в РАЗНЫЕ стороны. Проба
# (+) видела молчание отказавшегося хука как «НЕ сработал на настоящем
# расхождении» — то есть третья категория подавалась КРАСНЫМ; проба (−) видела
# то же молчание как «молчит» — то есть третья категория подавалась ЗЕЛЁНЫМ, и
# доказывала она ровно ничего. Замер на копии без `project/kacho` (2026-08-27,
# хук полностью исправен): разошлось 41, вакуумных «✔ (−)» 32, код возврата 1 —
# «дефект в доказываемом» там, где дефекта нет вовсе.
#
# Поэтому отказ распознаётся ЗДЕСЬ, один раз и ДО первой пробы, и переводит
# набор в ТРЕТИЙ исход (код 2). Вызывающий (`scripts/hook-proofs.sh`) уже
# различает 1 и 2 и печатает по коду 2 «доказательство НЕПОЛНО» — зелёным это
# не станет, но и дефектом называться перестанет.
#
# Детектор доказан в обе стороны прямо здесь: он обязан УЗНАТЬ отказ на
# синтетическом воркспейсе без дерева продукта и обязан НЕ узнать его там, где
# хук вердикт выносит. Проба (+) переехала сюда из раздела I — она обязана
# исполниться раньше всех прочих, иначе доказывать её будет уже поздно.
HOOK_DECLINE='ОТКАЗЫВАЕТСЯ РАБОТАТЬ'
hook_declined() { printf '%s' "$1" | grep -qF -- "$HOOK_DECLINE"; }

echo "== предпосылка НАБОРА: основание истины хука =="
NOBASE="$TMP/nobase"; mkdir -p "$NOBASE/.claude"
nb_out="$(printf '{"hook_event_name":"PostToolUse","tool_name":"Write","tool_input":{"file_path":"%s/x.md"}}' "$NOBASE" \
  | CLAUDE_PROJECT_DIR="$NOBASE" bash "$HOOK" 2>&1)"
if hook_declined "$nb_out"; then
  echo "  ✔ (+) без дерева продукта хук ОТКАЗЫВАЕТСЯ, и отказ РАСПОЗНАЁТСЯ"; PASS=$((PASS+1))
else
  echo "  ✘ (+) отказ хука не распознан — набор ниже судил бы молчание как исход"; FAIL=$((FAIL+1))
  printf '%s\n' "$nb_out" | sed 's/^/      /' | head -4
fi
# Вход (−) — НАСТОЯЩЕЕ расхождение, а не чистый документ: чистый даёт молчание,
# которое неотличимо от молчания отказавшегося хука, то есть ровно ту слепоту,
# ради которой блок и заведён. `absent_path` здесь напрямую, а не `premise_dead`:
# ту же координату считает перечень предпосылок ниже, и двойной счёт сделал бы
# печатаемый объём осмотренного неверным.
if absent_path sync-tooling.sh; then
  live_out="$(run_doc premise-base.md 'Копии генерируются `sync-tooling.sh`.')"
  if hook_declined "$live_out"; then
    echo "  ⊘ хук ОТКАЗАЛСЯ работать и на настоящем воркспейсе — его причина:"
    printf '%s\n' "$live_out" | sed 's/^/      /' | head -6
    echo
    echo "  Основание истины пусто, поэтому НИ ОДНА проба ниже ничего не докажет:"
    echo "  молчание отказавшегося хука неотличимо от молчания исправного. Это"
    echo "  ТРЕТИЙ исход («не выполнилось»), а НЕ расхождение — дефект в хуке"
    echo "  искать не нужно, его вердикт здесь просто не производится."
    echo "  Условие создаётся выкладкой дерева продукта рядом (project/kacho) —"
    echo "  так его создаёт и конвейер: см. .github/workflows/ci.yaml, job hook-proofs."
    NOTRUN=$((NOTRUN+1))
    echo
    census
    exit 2
  elif printf '%s' "$live_out" | grep -qF 'sync-tooling.sh'; then
    echo "  ✔ (−) на настоящем воркспейсе хук выносит вердикт и называет координату"; PASS=$((PASS+1))
  else
    echo "  ✘ (−) хук не вынес ни вердикта, ни отказа — молчание ниже неотличимо от исхода"; FAIL=$((FAIL+1))
    printf '%s\n' "$live_out" | sed 's/^/      /' | head -4
  fi
else
  notrun "'sync-tooling.sh' появился в дереве — предпосылку НАБОРА проверять этим входом больше нельзя, заменить вход"
fi

# Общие входы объявляются здесь ОДИН раз — они несут не одну пробу, а целые разделы
# ниже (ловушка момента, полоса ствола, воспроизводимость находки, канал Stop). Пробы,
# у которых вход СВОЙ, объявляют его сами, рядом с собой: общий список для них был бы
# местом, куда забывают дописать, — что и случилось с относительной ссылкой.
echo "== предпосылки проб (живость входа) =="
for dead in sync-tooling.sh tests/sync-tooling.bats; do
  if premise_dead "$dead"; then echo "  ✔ вход (+) жив: '$dead' в дереве отсутствует"
  else notrun "'$dead' появился в дереве — проба (+) по нему больше не настоящая, заменить вход"; fi
done
for alive in sync-all.sh .claude/rules/vault.md pkg/ids/ids.go; do
  if premise_live "$alive"; then echo "  ✔ вход (−) жив: '$alive' в дереве присутствует"
  else notrun "'$alive' исчез из дерева — близнец (−) больше не законный, заменить вход"; fi
done

# Инъекция в САМ механизм предпосылки, в обе стороны. Без неё «мёртвый вход
# отличим от поломки хука» остаётся объявлением: проверка, которую не проверили,
# отчитывается одинаково и когда работает, и когда сломана.
echo "  — инъекция в механизм предпосылки:"
inj="$(expect_silent_live "инъекция: мёртвая предпосылка" pi1.md \
        'Живой путь — `sync-all.sh`.' 'sync-all.sh' 'pkg/ids/ids-never-existed.go' 2>&1)"
PASS=$((PASS+1)); if grep -qF 'мёртв' <<<"$inj" && ! grep -qF 'ЛОЖНЫЙ СРАБАТ' <<<"$inj" && ! grep -qF '✔' <<<"$inj"; then
  echo "    ✔ (+) мёртвая предпосылка (−)-пробы названа мёртвой, а не ложным сработом"
else
  echo "    ✘ (+) мёртвая предпосылка (−)-пробы НЕ отличена от поломки хука"; PASS=$((PASS-1)); FAIL=$((FAIL+1))
  printf '%s\n' "$inj" | sed 's/^/        /'
fi
inj="$(expect_silent_live "инъекция: живая предпосылка" pi2.md \
        'Живой путь — `sync-all.sh`.' 'sync-all.sh' 'sync-all.sh' 2>&1)"
PASS=$((PASS+1)); if grep -qF '✔ (−)' <<<"$inj"; then
  echo "    ✔ (−) живая предпосылка пробу не задерживает — она исполняется как обычно"
else
  echo "    ✘ (−) живая предпосылка задержала пробу — механизм ловит форму, а не существо"; PASS=$((PASS-1)); FAIL=$((FAIL+1))
  printf '%s\n' "$inj" | sed 's/^/        /'
fi
inj="$(expect_fires_dead "инъекция: воскресшая предпосылка" pi3.md \
        'Копии генерируются `sync-tooling.sh`.' 'sync-tooling.sh' 'sync-all.sh' 2>&1)"
PASS=$((PASS+1)); if grep -qF 'починен' <<<"$inj" && ! grep -qF 'НЕ сработал' <<<"$inj"; then
  echo "    ✔ (+) ожившая координата (+)-пробы названа починкой входа, а не пропуском хука"
else
  echo "    ✘ (+) ожившая координата (+)-пробы прочиталась как пропуск хука"; PASS=$((PASS-1)); FAIL=$((FAIL+1))
  printf '%s\n' "$inj" | sed 's/^/        /'
fi
inj="$(expect_fires_dead "инъекция: мёртвая координата" pi4.md \
        'Копии генерируются `sync-tooling.sh`.' 'sync-tooling.sh' 'sync-tooling.sh' 2>&1)"
PASS=$((PASS+1)); if grep -qF '✔ (+)' <<<"$inj"; then
  echo "    ✔ (−) настоящее расхождение той же формы по-прежнему ловится"
else
  echo "    ✘ (−) настоящее расхождение той же формы перестало ловиться"; PASS=$((PASS-1)); FAIL=$((FAIL+1))
  printf '%s\n' "$inj" | sed 's/^/        /'
fi

echo
echo "== A. путь =="
expect_fires "снятый скрипт раскатки" a1.md \
  'Копии генерируются `sync-tooling.sh`, гейт `tests/sync-tooling.bats` в CI.' 'sync-tooling.sh'
expect_silent "живой скрипт того же каталога" a2.md \
  'Обновить рабочие копии — `sync-all.sh`.' 'sync-all.sh'
# Пара отличается ОДНОЙ буквой расширения — обе формы реальны, обе встречаются в
# конвейерах, и различить их можно только обращением к дереву. Обе стороны объявляют
# свою предпосылку: переименуй конвейер — и без объявления (+) молча перестала бы
# краснеть, а (−) покраснела бы «ложным сработом» на правоте хука.
expect_fires_dead "workflow с расширением, которого в дереве нет" a3.md \
  'Конвейер — `.github/workflows/ci.yml`.' '.github/workflows/ci.yml' \
  '.github/workflows/ci.yml'
expect_silent_live "тот же workflow с нынешним расширением" a4.md \
  'Конвейер — `.github/workflows/ci.yaml`.' '.github/workflows/ci.yaml' \
  '.github/workflows/ci.yaml'

echo
echo "== A'. регрессии нормализации пути =="
# `lstrip("./")` снимает точку КАК СИМВОЛ КЛАССА и превращает `.claude/rules/x`
# в `claude/rules/x`. Воспроизведено трижды подряд при написании предиката,
# поэтому проба стоит отдельно и с обеих сторон.
expect_silent_live "ведущая точка каталога оснастки не съедена" b1.md \
  'Полные правила — `.claude/rules/vault.md`.' '.claude/rules/vault.md' \
  '.claude/rules/vault.md'
expect_silent_live "маркер импорта @ не часть пути" b2.md \
