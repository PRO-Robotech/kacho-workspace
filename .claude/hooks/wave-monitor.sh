# wave-monitor.sh — монитор флоу срабатывает МЕХАНИЧЕСКИ, а не по усмотрению.
#
# # Предмет
#
# Решение владельца 2026-09-19, дословно: «Ставь монитор на триггер завершения
# волны. Мне нужна не сводка а модификация .claude/ для исправления флоу».
#
# Из него два требования, и второе важнее первого. Первое: срабатывание —
# наблюдаемый признак, а не память диспетчера. Второе: ИСХОД полосы монитора —
# изменение в `.claude/**` либо ЗАМЕРЕННОЕ доказательство, что правка не нужна;
# прозаическая сводка исходом не является. Норма и предикат снятия —
# `.claude/rules/multi-agent-flow.md` §«Седьмой шаг: монитор волны»; здесь они не
# пересказываются, потому что два места об одном предмете расходятся молча.
#
# # Три оси, и у каждой свой наблюдаемый признак
#
# 1. ВОЛНА СВЕДЕНА, МОНИТОР НЕ ОТРАБОТАЛ. Признак — строка ведомости
#    `.claude/wave-monitor/ledger.tsv` с заполненным полем «сведена» и «—» в поле
#    «монитор». Строку открывает `git-operator` в момент сведения волны (шаг 5),
#    закрывает `tooling-maintainer` полосой монитора.
#
# 2. СТРОКИ О ВОЛНЕ НЕТ ВОВСЕ. Ось 1 слепа к строке, которой нет: сумма по
#    строкам не видит отсутствующую (тот же класс, что у арифметического гейта —
#    нужен ЗНАМЕНАТЕЛЬ ОБХОДА, а не сумма). Знаменатель здесь — ствол: последняя
#    строка ведомости несёт ревизию ствола воркспейса, и посадки после неё
#    считаются напрямую. Порог — 4, НИЖНЯЯ ГРАНИЦА ВИЛКИ ВОЛНЫ (4–8 полос,
#    `multi-agent-flow.md` §«Размер волны»): каждая полоса садится своим
#    схлопнутым коммитом, поэтому набравшиеся четыре посадки — это волна, о
#    которой никто не объявил. Порог ВЫШЕ штатного состояния намеренно: посадка
#    самой полосы монитора даёт одну, и кричать на ней значит перестать читаться.
#
# 3. МОДЕЛЬ ИСПОЛНЕНИЯ (LLM) НЕ ТА, НА КОТОРОЙ СНЯТЫ ОРИЕНТИРЫ. Термин назван
#    полностью не ради многословия: «модель загрузки правил» в корпусе уже занят
#    (`CLAUDE.md` §«Модель загрузки», решение владельца 2026-09-17), и короткое
#    «модель» здесь прочиталось бы как он. Признак — `message.model` в записях
#    транскрипта сессии; путь приезжает хуку сам, полем `transcript_path`
#    полезной нагрузки. Базовая модель объявлена в
#    `.claude/wave-monitor/model-baseline.tsv`.
#
# # На чём держится третья ось — ИЗМЕРЕНО, а не предположено
#
# Проба свежим процессом `claude -p` (Claude Code 2.1.277, 2026-09-19):
#   · полезная нагрузка `UserPromptSubmit` несёт `session_id`, `transcript_path`,
#     `cwd`, `prompt_id`, `permission_mode`, `hook_event_name`, `prompt` —
#     идентификатора модели в ней НЕТ;
#   · в окружении хука его тоже нет: `env | grep -iE 'claude|model|anthropic'`
#     даёт версию харнесса и координаты сессии, модель — ни разу;
#   · транскрипт, на который указывает `transcript_path`, несёт `message.model` у
#     КАЖДОЙ ассистентской записи: прогон, которому модель задали флагом, записал
#     в своём транскрипте именно её.
# Значит транскрипт — единственный доступный хуку источник, и других не искали
# не по лени: их в этой поверхности нет.
#
# Признак — ПОСЛЕДНЯЯ ассистентская запись главного потока (`isSidechain` ложно):
# «чем идёт работа сейчас». Рядом считается число РАЗЛИЧНЫХ моделей в
# транскрипте, и оно не украшение: транскрипт этой сессии нёс `claude-opus-4-8`
# (683 записи) и `claude-opus-5` (305), перемешанные по строкам, — то есть смена
# внутри одной сессии уже случилась, молча, и числа такой сессии принадлежат
# двум разным моделям. Поэтому «моделей больше одной» — самостоятельная находка,
# даже когда последняя совпала с базовой.
#
# # Форма
#
# Исполняется на КАЖДОМ обращении к сессии (`UserPromptSubmit`) и МОЛЧИТ, пока
# находок нет. Молчание выбрано намеренно: строка, печатающаяся всегда,
# перестаёт читаться на третий день.
#
# Отсюда обязанность, которую молчание накладывает: хук ОБЯЗАН заговорить, когда
# ему нечего осмотреть. «Ноль находок» и «ноль прочитанного» дают один и тот же
# пустой вывод, поэтому второе называется ОТДЕЛЬНОЙ строкой и другим значком:
# ведомости нет, транскрипт не читается, разборщика нет — это «не проверяли», а
# не «монитор отработал».
#
# Сессию не роняет НИКОГДА (выход 0 при любом исходе): это указатель, а не гейт.
# Гейт на него самого — `scripts/tooling-gate/check-10-wave-monitor-fires.sh`:
# он подставляет хуку ведомость, базу и транскрипт и читает, что хук напечатал.
#
# # Кому адресован вывод
#
# `UserPromptSubmit` — событие ГЛАВНОГО ПОТОКА, значит текст читает диспетчер, у
# которого нет ни `Bash`, ни `Read`, ни `Edit`. Ни замерить, ни править он не
# может — он ставит полосу. Поэтому каждая находка названа АГЕНТОМ и ПРЕДМЕТОМ, а
# команда остаётся предметом задания, а не поручением читающему.
set -uo pipefail

ws="${CLAUDE_PROJECT_DIR:-}"
[ -n "$ws" ] || ws="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

# Каталог состояния. Переопределяется `KACHO_WAVE_MONITOR_DIR` — этим пользуется
# ТОЛЬКО гейт, доказывающий хук: он кладёт свои ведомость и базу и читает исход,
# не трогая рабочую копию.
state="${KACHO_WAVE_MONITOR_DIR:-$ws/.claude/wave-monitor}"
ledger="$state/ledger.tsv"
baseline="$state/model-baseline.tsv"

# Полезная нагрузка читается со stdin ОДИН РАЗ. `-t 0` отделяет запуск из
# терминала (руками, при разборе) от запуска хуком: без него `cat` на пустом
# терминале ждал бы ввода вечно, и хук вешал бы сессию.
payload=""
if [ ! -t 0 ]; then payload="$(cat)"; fi

signals=()     # находки: предмет есть, и он открыт
unexamined=()  # «не проверяли»: осматривать было нечем

# ── ОСЬ 1: открытая строка ведомости ─────────────────────────────────────────
#
# Разбор ведомости — на awk, а не на python3: у первых двух осей не должно быть
# общей точки отказа с третьей. Формат объявляет сама ведомость своей шапкой.
waves_open=0
waves_rows=0
cursor=""
if [ ! -r "$ledger" ]; then
    unexamined+=("ведомость волн $ledger не читается — об открытых волнах не известно НИЧЕГО")
else
    # `|| [ -n "$wave" ]` — последняя строка без завершающего перевода строки
    # иначе теряется молча, и именно она свежайшая.
    while IFS=$'\t' read -r wave merged trunk lanes monitor _rest || [ -n "$wave" ]; do
        case "$wave" in ''|'#'*) continue ;; esac
        waves_rows=$((waves_rows + 1))
        # Курсор — ревизия ПОСЛЕДНЕЙ прочитанной строки: ведомость пишется
        # дописыванием, поэтому последняя строка и есть свежайшая.
        if [ -n "$trunk" ] && [ "$trunk" != "—" ]; then cursor="$trunk"; fi
        if [ -z "$merged" ] || [ "$merged" = "—" ]; then continue; fi
        if [ -z "$monitor" ] || [ "$monitor" = "—" ]; then
            waves_open=$((waves_open + 1))
            signals+=("волна «$wave» сведена $merged (полос $lanes), монитор по ней не отработал")
        fi
    done < "$ledger"
    if [ "$waves_rows" -eq 0 ]; then
        unexamined+=("ведомость волн $ledger не несёт НИ ОДНОЙ строки — сверять не с чем")
    fi
fi

# ── ОСЬ 2: строки о волне нет вовсе ──────────────────────────────────────────
#
# Спрашивается только тогда, когда ось 1 молчит: открытая волна уже названа, и
# второе утверждение о том же предмете было бы шумом.
WAVE_MIN=4   # нижняя граница вилки волны; порог, а не вкус — см. шапку
if [ "$waves_open" -eq 0 ] && [ -n "$cursor" ]; then
    if landed="$(git -C "$ws" rev-list --count "$cursor..main" 2>/dev/null)"; then
        if [ "$landed" -ge "$WAVE_MIN" ]; then
            signals+=("в стволе посадок $landed после последней объявленной волны ($cursor), а строки о новой волне в ведомости НЕТ")
        fi
    else
        unexamined+=("ревизия $cursor из ведомости в этом дереве не разрешается — посадки после неё не считаны")
    fi
fi

# ── ОСЬ 3: модель исполнения (LLM) ───────────────────────────────────────────
base_model=""
if [ ! -r "$baseline" ]; then
    unexamined+=("база модели исполнения $baseline не читается — ориентиры сверять не с чем")
else
    while IFS=$'\t' read -r m _rest || [ -n "$m" ]; do
        case "$m" in ''|'#'*) continue ;; esac
        base_model="$m"
        break
    done < "$baseline"
    [ -n "$base_model" ] || unexamined+=("база модели исполнения $baseline не несёт строки — ориентиры сверять не с чем")
fi

if [ -n "$base_model" ]; then
    if ! command -v python3 >/dev/null 2>&1; then
        unexamined+=("python3 нет — транскрипт не разобран, модель исполнения НЕ проверялась")
    elif [ -z "$payload" ]; then
        unexamined+=("полезной нагрузки на входе нет — транскрипт не назван, модель исполнения НЕ проверялась")
    else
        # Разбор печатает три поля через табуляцию: последняя модель главного
        # потока, число различных моделей, их перечень. «Прочитать не удалось»
        # обозначается ЯВНЫМ маркером `-`, а не пустым полем, и это не вкус:
        # табуляция — разделитель, ведущее пустое поле `read` съедает вместе с
        # ним, и «не прочитано» приезжало сюда как модель по имени «0» —
        # то есть третья категория выдавала себя за смену модели. Поймано
        # собственной пробой отсутствующего транскрипта, а не чтением.
        read_model="$(python3 -c '
import json, sys

try:
    payload = json.loads(sys.argv[1])
except Exception:
    print("-\t0\t-"); raise SystemExit(0)

path = payload.get("transcript_path") or ""
last, seen = "", []
try:
    with open(path, encoding="utf-8", errors="ignore") as fh:
        for line in fh:
            try:
                rec = json.loads(line)
            except Exception:
                continue
            if rec.get("type") != "assistant" or rec.get("isSidechain"):
                continue
            model = (rec.get("message") or {}).get("model") or ""
            # `<synthetic>` — не модель, а отметка записи, сочинённой харнессом:
            # принять её за модель значило бы объявить смену на пустом месте.
            if not model or model.startswith("<"):
                continue
            last = model
            if model not in seen:
                seen.append(model)
except OSError:
    print("-\t0\t-"); raise SystemExit(0)

print("%s\t%d\t%s" % (last or "-", len(seen), " · ".join(seen) or "-"))
' "$payload" 2>/dev/null)"
        IFS=$'\t' read -r now_model models_n models_all <<< "$read_model"
        now_model="${now_model:--}"; models_n="${models_n:-0}"; models_all="${models_all:--}"

        if [ "$now_model" = "-" ]; then
            unexamined+=("транскрипт сессии не прочитан либо не несёт ассистентских записей — модель исполнения НЕ проверялась")
        else
            if [ "$base_model" = "не-записана" ]; then
                signals+=("модель исполнения (LLM), на которой сняты ориентиры цены полосы и волны, НЕ ЗАПИСАНА; идёт «$now_model» — сверить не с чем")
            elif [ "$base_model" != "$now_model" ]; then
                signals+=("модель исполнения (LLM) сменилась «$base_model» → «$now_model»; замеренные ориентиры цены полосы и волны обесценены")
            fi
            if [ "$models_n" -gt 1 ]; then
                signals+=("в ОДНОЙ сессии работали разные модели исполнения ($models_all) — числа этой сессии принадлежат разным моделям и ориентиром не являются")
            fi
        fi
    fi
fi

# ── ВЫВОД ────────────────────────────────────────────────────────────────────
if [ "${#signals[@]}" -ne 0 ]; then
    echo "🌊 МОНИТОР ФЛОУ: предмет открыт — находок ${#signals[@]}"
    printf '   · %s\n' "${signals[@]}"
    echo "   → tooling-maintainer, полоса монитора (замер + правка оснастки)."
    echo "   Полоса НЕ снята, пока не произведено одно из двух: (а) изменение в"
    echo "   .claude/**, исправляющее флоу, либо (б) ЗАМЕРЕННОЕ доказательство,"
    echo "   что правка не нужна — числа до/после и почему они в пределах нормы."
    echo "   Прозаическая сводка исходом НЕ является."
    echo "   Норма и предикат снятия — .claude/rules/multi-agent-flow.md"
    echo "   §«Седьмой шаг: монитор волны». Состояние закрывает он же:"
    echo "   .claude/wave-monitor/ledger.tsv (поля «монитор», «исход») и"
    echo "   .claude/wave-monitor/model-baseline.tsv (модель и дата замера)."
    echo "   Строку о СВЕДЁННОЙ волне открывает git-operator при сборке — если её"
    echo "   нет, это его предмет, а не отсутствие волны."
fi

if [ "${#unexamined[@]}" -ne 0 ]; then
    echo "🌊 монитор флоу: осмотреть удалось НЕ ВСЁ — по перечисленному вердикта НЕТ"
    printf '   · %s\n' "${unexamined[@]}"
    echo "   Молчание монитора по этим осям означает «не проверяли», а не «чисто»."
    echo "   → scout: почему состояние не читается; правка оснастки — tooling-maintainer."
fi

exit 0
