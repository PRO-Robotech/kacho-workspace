#!/usr/bin/env bash
# UserPromptSubmit — настройки харнесса в КОРНЕ отстают от ствола (ws#796).
#
# Харнесс читает `.claude/settings.json` корня при старте сессии. Корень стоит на
# чьей-то ветке; если она старше настройки, настройка не действует, и сигнала об этом
# не было: замер 2026-09-27 — в корне нет `attribution` (он есть на стволе с #715), и
# запрет трейлеров атрибуции держался вниманием исполнителя.
#
# Что считается и почему так — `lib/settings_lag.py`. Здесь — маршрут диспетчеру:
# у него нет ни `Read`, ни `Bash`, поэтому сигнал называет агента, а не команду.
# Молчит, пока корень не отстаёт; «судить не по чему» — отдельный сигнал, чтобы
# молчание не читалось как «вровень».
#
# Граница: хук исполняется из корня, значит только там, где ветка корня его уже
# несёт. Корень, отставший раньше, чем хук появился, сигнала не получит.
set -uo pipefail

# Оболочка признака дельты. Провал `source` громкий и fail-open: тело печатается
# целиком. Заглушки здесь — по причине начальной загрузки (страхуют отсутствие того
# файла, в котором иначе бы лежали).
_sig="$(dirname "${BASH_SOURCE[0]}")/lib/hook_signal.sh"
# shellcheck source-path=SCRIPTDIR source=lib/hook_signal.sh
. "$_sig" 2>/dev/null || {
  echo "[сигнал] признак дельты НЕ применён: не найден $_sig. Тело печатается ПОЛНОСТЬЮ каждый ход. → tooling-maintainer" >&2
  signal_stdin() { :; }
  signal_sha() { echo "ревизия не читается"; }
  signal_emit() { cat; echo "[сигнал \`$1\`] признак дельты НЕ применён (нет $_sig) · адресат: $2 · предикат снятия предмета: $3"; }
}
signal_stdin

ws="${CLAUDE_PROJECT_DIR:-}"
[ -n "$ws" ] || ws="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
lib="$(dirname "${BASH_SOURCE[0]}")/lib/settings_lag.py"

err="$(mktemp)"
trap 'rm -f "$err"' EXIT
lagging="$(python3 "$lib" "$ws" 2>"$err")"; rc=$?

if [ "$rc" -ne 0 ]; then
  signal_emit settings-lag-unjudged "scout (почему ствол или настройки корня не читаются)" \
    "python3 .claude/hooks/lib/settings_lag.py <корень> выходит нулём" \
    "$(signal_sha "$ws")" <<EOF2
⚙️  НАСТРОЙКИ КОРНЯ против ствола — НЕ СУДИЛИСЬ: $(cat "$err")
   Молчание этого хука сейчас значит «не проверяли», а не «вровень». → scout.
EOF2
  exit 0
fi

if [ -n "$lagging" ]; then
  n="$(printf '%s\n' "$lagging" | grep -c .)"
  signal_emit settings-lag "git-operator (влить ствол в ветку корня — если ветка чужая, решение диспетчера)" \
    "python3 .claude/hooks/lib/settings_lag.py <корень> печатает «отставших листьев 0»" \
    "$(signal_sha "$ws")" <<EOF2
⚙️  НАСТРОЙКИ КОРНЯ ОТСТАЮТ ОТ СТВОЛА — харнесс этой сессии их НЕ применяет ($n):
$(printf '%s\n' "$lagging" | head -8 | sed 's/^/   · /')
   Всё, что держится этими настройками (атрибуция, хуки, исключения корпуса), в сессии
   держится только вниманием, пока ветка корня не догонит ствол.
   → git-operator: влить ствол в ветку корня. Корень занят чужой работой — очередь и
     владельца ветки решает диспетчер.
EOF2
fi
exit 0
