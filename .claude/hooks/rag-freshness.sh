#!/usr/bin/env bash
# rag-freshness.sh — ОТСТАЛ ЛИ индекс от рабочих копий. Общий счётчик двух хуков.
#
# # Предмет
#
# Индекс — снимок НАЗВАННОЙ ревизии (её кладёт в манифест коллекции
# `kacho_rag/index/build.py`), а рабочая копия стоит там, где её оставила чужая
# сессия. Пока эти два состояния совпадают, координата из выдачи указывает туда,
# где строка и лежит. Как только разошлись — координата продолжает выглядеть
# верной и указывает в прошлое, и отличить это от исправной работы нельзя ничем.
#
# # Почему НЕ обновляет молча
#
# Пересборка стоит десятки минут (эмбеддинг ~50 мин на оба корпуса). Хук,
# запускающий её сам, отобрал бы у машины столько времени без спроса. Поэтому
# он ГОВОРИТ и не делает: решение — за человеком.
#
# # Почему не зовёт bin/rag
#
# `bin/rag status` дал бы тот же ответ, но стоит ~0.6 с на связывание бэкенда
# (замер: импорт kacho_rag.mcp.backend 0.63 с, kacho_rag.retrieve 1.60 с).
# Хук обязан укладываться в миллисекунды, поэтому спрашивает НАПРЯМУЮ: манифест
# у Qdrant одним HTTP, ревизию у git одним `rev-parse`. Замер 10 проходов: 8.6 мс
# на проход. Цена — второе место, знающее идентификатор точки манифеста; она
# названа ниже и сверяется предикатом в шапке.
#
# # Молчание
#
# Пока индекс совпадает с деревом — НИ ОДНОЙ строки. Строка, печатающаяся
# всегда, перестаёт читаться на третий день.
# Отсюда обязанность, которую молчание накладывает: когда осмотреть НЕЧЕГО
# (Qdrant не отвечает, манифеста нет, git не отвечает), хук говорит об этом
# отдельно — иначе «свежо» и «не проверяли» дают один и тот же пустой вывод.
#
# Сессию не роняет НИКОГДА (выход 0 при любом исходе): это указатель, а не гейт.
set -uo pipefail

QDRANT="${KACHO_RAG_QDRANT:-http://127.0.0.1:6333}"
WS="${KACHO_RAG_WORKSPACE_ROOT:-/home/dk/workspace/github/PRO-Robotech/cloud-demo/kacho-workspace}"
PR="${KACHO_RAG_PRODUCT_ROOT:-$WS/project/kacho}"

# Идентификатор точки манифеста. Он ВЫЧИСЛЯЕТСЯ индексатором как
# uuid5(6f9d2c6e-6a2f-5b7a-9f1a-2b7c9d0e1f23, "collection-manifest") — здесь
# стоит его значение, потому что хук не вправе поднимать python.
# Это ВТОРОЕ МЕСТО об одном предмете, и оно разойдётся молча, если индексатор
# сменит соль. Предикат сверки (прогонять при правке kacho_rag/index/manifest.py):
#   python3 -c "import uuid;print(uuid.uuid5(uuid.UUID('6f9d2c6e-6a2f-5b7a-9f1a-2b7c9d0e1f23'),'collection-manifest'))"
# Расхождение видно СРАЗУ: манифест не читается, и хук говорит «нечего осмотреть».
MANIFEST_ID="94556e53-55f2-5616-a7dc-788451064f81"

# Корпусные расширения — из kacho_rag/chunking/common.py (CODE_LANGS+DOCS_LANGS).
# Единица счёта здесь несущая: правка .png индекс не старит, а правка .go старит.
CORPUS_RE='\.(go|ts|tsx|py|sh|sql|proto|yaml|json|md|mdx)$'

blind=()      # что осмотреть НЕ удалось
stale=()      # что разошлось

# Ревизии индекса читаем у ОДНОЙ коллекции: обе пишутся одним проходом
# индексатора и объявляют один и тот же набор. Разойдись они — это скажет
# `bin/rag status`, у которого есть обе; хук о свежести, а не о согласии корпусов.
man="$(curl -s --max-time 2 -X POST "$QDRANT/collections/kacho_code/points" \
        -H 'Content-Type: application/json' \
        -d "{\"ids\":[\"$MANIFEST_ID\"],\"with_payload\":true,\"with_vector\":false}" 2>/dev/null)"

if [ -z "$man" ]; then
  blind+=("Qdrant $QDRANT не ответил за 2 с — свежесть индекса НЕ проверена")
elif ! printf '%s' "$man" | grep -q '"revisions"'; then
  blind+=("коллекция kacho_code не объявляет ревизий (манифеста нет либо сменился его идентификатор) — свежесть НЕ проверена")
fi

# Разбор без jq: он есть не везде, а форма ответа здесь узкая и своя.
rev_of() {  # $1 — имя репозитория в манифесте
  printf '%s' "$man" | tr ',{}' '\n\n\n' | grep -o "\"$1\"[[:space:]]*:[[:space:]]*\"[0-9a-f]\{40\}\"" \
    | head -1 | grep -o '[0-9a-f]\{40\}'
}

check() {   # $1 — имя, $2 — корень рабочей копии
  local name="$1" root="$2" idx head ahead behind files dirty
  idx="$(rev_of "$name")"
  [ -n "$idx" ] || { [ "${#blind[@]}" -eq 0 ] && blind+=("$name: ревизия в манифесте не названа"); return; }
  [ -d "$root/.git" ] || [ -f "$root/.git" ] || { blind+=("$name: $root не рабочая копия git"); return; }
  head="$(git -C "$root" rev-parse HEAD 2>/dev/null)"
  [ -n "$head" ] || { blind+=("$name: git в $root не ответил"); return; }
  [ "$head" = "$idx" ] && return   # совпало — молчим

  # Отставание и расхождение — РАЗНЫЕ состояния, и лечатся они по-разному.
  # `rev-list --count a...b` (три точки) даёт обе стороны симметрично; если
  # ревизия индекса вообще не в этом дереве (ветка снята, копия перекачана),
  # команда откажет — и это третье состояние, его нельзя звать отставанием.
  if ! read -r behind ahead < <(git -C "$root" rev-list --left-right --count "$idx...$head" 2>/dev/null); then
    stale+=("$name: индекс собран по ${idx:0:10}, копия на ${head:0:10} — РОДСТВО НЕ УСТАНОВЛЕНО (ревизии индекса нет в этом дереве)")
    return
  fi
  files="$(git -C "$root" diff --name-only "$idx" "$head" 2>/dev/null | grep -cE "$CORPUS_RE")"
  dirty="$(git -C "$root" status --porcelain 2>/dev/null | grep -cE "$CORPUS_RE")"
  local what
  if [ "${ahead:-0}" -gt 0 ] && [ "${behind:-0}" -eq 0 ]; then
    what="копия УШЛА ВПЕРЁД на $ahead коммит(ов)"
  elif [ "${behind:-0}" -gt 0 ] && [ "${ahead:-0}" -eq 0 ]; then
    what="копия ОТКАТИЛАСЬ на $behind коммит(ов) назад"
  else
    what="РАЗОШЛИСЬ: индекс +$behind, копия +$ahead"
  fi
  stale+=("$name: $what · корпусных файлов различается $files · не закоммичено $dirty · индекс ${idx:0:10} → копия ${head:0:10} ($(git -C "$root" rev-parse --abbrev-ref HEAD 2>/dev/null))")
}

check product   "$PR"
check workspace "$WS"

if [ "${#stale[@]}" -gt 0 ]; then
  echo "🔎 RAG-ИНДЕКС ОТСТАЛ от рабочей копии — координаты из него указывают в прошлое:"
  printf '   · %s\n' "${stale[@]}"
  echo "   И для ИМЁН тоже важно: rag symbol с 2026-09-07 ищет по РЕВИЗИИ ИНДЕКСА, а не по дереву —
     имя, заведённое после неё, он не найдёт (прежде находил, и это расходилось с заголовком)."
  echo "   Для смыслового поиска — перепроверяй координату чтением файла перед правкой."
  echo "   Пересборка стоит десятки минут и НЕ запускается сама; когда решишь — запусти сам."
fi

if [ "${#blind[@]}" -gt 0 ]; then
  echo "🔎 RAG-индекс: свежесть НЕ проверена — молчание этого хука сейчас означает"
  echo "   «не проверяли», а не «свежо»:"
  printf '   · %s\n' "${blind[@]}"
fi

exit 0
