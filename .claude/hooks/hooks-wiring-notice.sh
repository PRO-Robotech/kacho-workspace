# UserPromptSubmit hook — НЕПРОВЯЗАННЫЙ КЛОН ВИДЕН БЕЗ ЗАПУСКА КОМАНДЫ.
#
# ПРЕДМЕТ (#462). Правило «перед отправкой ветки — обязательный локальный прогон»
# объявлено держащимся хуком отправки. Хук лежал в дереве и не был провязан ни в
# одном из двух клонов: в продукте не было команды установки, в воркспейсе
# `core.hooksPath` указывал на каталог, которого нет. Провязку починили — но
# осталась вторая половина дефекта, и она важнее первой:
#
#   ЧТОБЫ УЗНАТЬ ОБ ОТСУТСТВИИ ЗАЩИТЫ, ЕЁ НАДО БЫЛО СПЕЦИАЛЬНО СПРОСИТЬ.
#
# `git push` проходит молча в обоих случаях; `scripts/hooks/install.sh check`
# отвечает честно, но его надо позвать. То есть контроль, чьё отсутствие
# ненаблюдаемо, — ровно тот класс, который корпус ловит в продуктовом коде
# («контроль присутствует, объявлен и не отказал ни разу, потому что не
# исполнялся»).
#
# ПОЧЕМУ ИМЕННО ЭТОТ МЕХАНИЗМ, а не два очевидных соседних:
#
#   · «уронить первый же вызов цели сборки» — отвергнуто. Провязка хука не
#     свойство кода, и отказ сборки из-за настройки клона останавливает работу
#     там, где нечего чинить. Запрет, мешающий делу, снимают первым.
#   · «гейт в дереве» (проба, утверждающая, что клон провязан) — отвергнуто по
#     построению: провязка живёт в `.git/config`, которого в дереве нет, а в
#     конвейере хуки бессмысленны — проверку пришлось бы там отключить. Проверка,
#     которая не исполняется там, где она зелёная, упасть не может.
#   · напоминание на целях `make test*` (продукт, уже есть) — остаётся, но
#     закрывает лишь того, кто гоняет пробы через make. Прямой `go test` и прямой
#     `git push` его не касаются.
#
# Здесь окно срабатывания — САМА СЕССИЯ: сообщение приходит до первого действия,
# ничего не роняет и молчит, когда провязано. Это единственная поверхность,
# которая не требует, чтобы о защите вспомнили.
#
# ПЕРЕЧЕНЬ КЛОНОВ ВЫВОДИТСЯ ИЗ ДЕРЕВА, а не выписывается: рукописный список путей
# в этом репозитории уже однажды разошёлся сам с собой в трёх скриптах. Осмотрено
# печатается всегда, когда есть о чём сказать, — «ноль находок» обязано быть
# отличимо от «ноль прочитанного».
set -uo pipefail

WS="${CLAUDE_PROJECT_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"

# Кандидаты: сам воркспейс и каждая рабочая копия под `project/` (она под
# gitignore, поэтому в индексе её нет — ищем по признаку каталога `.git`).
candidates=("$WS")
if [ -d "$WS/project" ]; then
    for d in "$WS"/project/*/; do
        [ -e "$d/.git" ] || continue
        candidates+=("${d%/}")
    done
fi

seen=0
unwired=()
for repo in "${candidates[@]}"; do
    inst="$repo/scripts/hooks/install.sh"
    # Клон без своего механизма провязки под это правило не подпадает: у него нет
    # предмета. Молчать про него — не послабление, а отсутствие вопроса.
    [ -f "$inst" ] || continue
    seen=$((seen + 1))
    if ! ( cd "$repo" && bash "$inst" check ) >/dev/null 2>&1; then
        unwired+=("$repo")
    fi
done

# Ни одного клона с механизмом — это НЕ «всё хорошо». Либо признак разошёлся с
# деревом, либо механизм из него исчез; и то и другое надо сказать вслух, иначе
# молчание хука будет означать сразу две разные вещи.
if [ "$seen" -eq 0 ]; then
    cat >&2 <<EOF

⚠️  ХУКИ GIT: осмотрено клонов 0 — проверить было НЕЧЕГО.
    Ни в воркспейсе, ни в рабочих копиях под project/ не найдено
    scripts/hooks/install.sh. Это находка, а не тишина: механизм локального
    прогона либо переехал, либо снят, а правило на него ещё ссылается.
EOF
    exit 0
fi

[ "${#unwired[@]}" -gt 0 ] || exit 0

{
    echo
    echo "⚠️  ХУКИ GIT НЕ ПРОВЯЗАНЫ — отправка ветки НЕ будет проверена локально (#462)"
    echo "────────────────────────────────────────────────────────────────────────────"
    echo "Конвейер станет первым читателем кода и ответит через двадцать минут,"
    echo "заняв ранер, которого не хватает."
    echo
    echo "Клонов осмотрено: $seen; без провязки: ${#unwired[@]}"
    for repo in "${unwired[@]}"; do
        echo "  • $repo"
        echo "      cd \"$repo\" && bash scripts/hooks/install.sh install"
    done
    echo
    echo "Подробности отказа: bash scripts/hooks/install.sh check"
    echo "────────────────────────────────────────────────────────────────────────────"
} >&2
