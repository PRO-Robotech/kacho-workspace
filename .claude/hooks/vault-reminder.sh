#!/usr/bin/env bash
# UserPromptSubmit hook — сигнал маршрутизации про vault.
#
# Вывод уходит в окно ГЛАВНОГО ПОТОКА, то есть диспетчеру, а у него нет ни Read, ни
# Bash, ни Edit. Поэтому здесь нет ни одного императива: «прочитай записку» и «обнови
# trail» он не исполнит by construction — он может только поставить полосу. Названы
# агенты, которые это закрывают; текст обязан читаться как повод завести полосу, а не
# как поручение читающему.
#
# Норма — `.claude/rules/vault.md` (закреплена за `vault-scribe`). Пересказывать её
# здесь нельзя: это второе место об одном предмете, и оно уже разошлось однажды —
# хук печатал потолок «1-3KB», снятый владельцем 2026-08-05, и ссылался на раздел
# «Obsidian vault — обязательно» корневого CLAUDE.md, которого в нём нет.
#
# # Почему тело идёт через признак дельты (2026-09-20)
#
# До этой правки хук печатал полный экран на КАЖДОМ обращении и сам про себя писал
# «это фон, сам по себе полосы не требует»: источник признавал нулевую дельту и всё
# равно занимал канал, которым приходят находки. Повторённый сигнал неотличим от
# новой находки — значит новая находка терялась в фоне.
#
# Дельта у этой карты маршрута ровно одна: она НУЖНА ОДИН РАЗ ЗА СЕССИЮ. Поэтому
# тело отдаётся `signal_emit`: первый ход сессии — полностью, дальше одна строка
# «без изменений». Утверждение не снято и не урезано — свёрнут ПОВТОР, а полное тело
# каждого прогона лежит в журнале сигнала.
set -uo pipefail

. "$(dirname "${BASH_SOURCE[0]}")/lib/signal.sh"
signal_stdin

ws="${CLAUDE_PROJECT_DIR:-}"
[ -n "$ws" ] || ws="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

signal_emit vault-discipline "scout (до кода) · vault-scribe (после работы)" \
  'у сигнала есть отпечаток этой сессии в .claude/hooks/.state/signal/<сессия>/vault-discipline.json — карта маршрута нужна ОДИН раз за сессию, дальше повтор свёрнут' \
  "$(signal_sha "$ws")" <<'EOF'

📔 KACHO VAULT DISCIPLINE — сигнал, а не поручение главному потоку
─────────────────────────────────────────────────────────────────────────────
Vault закрывают двое, и адресат зависит от момента:

  ДО кода — контекст по предмету                            → scout
    1-2 узкие записки из obsidian/kacho/{resources,rpc,packages,edges}/;
    INDEX.md — когда адрес неизвестен; KAC/issue-<N>.md — по задаче в работе.
    Нужно больше трёх записок — это уже не разведка, а пересмотр объёма.

  ПОСЛЕ работы — записка и trail                            → vault-scribe
    единственный, кто пишет в obsidian/kacho/**: resources · rpc · packages ·
    edges по затронутому и KAC/issue-<N>.md («Затронутые сущности vault»,
    PR-URL, status).

Перечень затронутого даёт не этот хук, а строка «затронуто в vault» возврата
полосы: она и есть задание для vault-scribe.

Чего не закрывает ничьё внимание: trail, не обновлённый после вливания; секрет
в записке (vault git-committed и ПУБЛИЧЕН); один предмет, изложенный дважды —
и в README, и в узкой записке.

Норма: .claude/rules/vault.md · оболочка записки: obsidian/kacho/CLAUDE.md
─────────────────────────────────────────────────────────────────────────────
EOF
exit 0
