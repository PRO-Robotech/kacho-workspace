#!/usr/bin/env bash
# Хук свежести документации. Ловит класс «утверждение документа пережило свой
# предмет»: документ называет файл/маршрут/переменную/цель/метод, предмет исчез
# или переехал, документ продолжает утверждать.
#
# Провязан на ДВА события, потому что момент устаревания и момент правки — разные:
#   PostToolUse (Write|Edit|MultiEdit) — правлен документ → проверить его;
#                                        правлен файл дерева → проверить документы,
#                                        которые его называют;
#   Stop                              — досмотр за ход: удаления, переименования и
#                                        правки мимо Write/Edit (сверка с git status).
#
# Запись НЕ блокируется, конец хода НЕ блокируется. Код 2 на PostToolUse означает
# «есть что сказать» — stderr доезжает до автора; на Stop код 0 — кроме собственной
# поломки хука (ниже), которая громкая на ЛЮБОМ событии.
#
# На Stop канал зависит от исхода: находка идёт `additionalContext`-ом (её обязан
# увидеть агент), а перепись «сказать нечего» — в stderr и в журнал
# `.state/census.log`. Отданная каналом впрыска, перепись поднимала бы агента на
# каждом ходу — «ход → впрыск → ход», конец хода не наступал бы.
#
# Собственная поломка этого скрипта — ГРОМКАЯ. Молчаливый выход с нулём здесь
# запрещён: он неотличим от «прогнал и чисто», а это ровно тот класс, который
# хук и ловит (мягкий проход, не различающий настройку и сбой).
set -u

# Без внешних команд: `dirname` может отсутствовать ровно в том сценарии, ради
# которого этот блок написан (обрезанный PATH), и тогда диагностика соврала бы
# про причину.
_src="${BASH_SOURCE[0]}"
HOOK_DIR="$(cd "${_src%/*}" 2>/dev/null && pwd)" || HOOK_DIR="."
GUARD="$HOOK_DIR/docfresh/docfresh.py"

if [ ! -f "$GUARD" ]; then
  {
    echo "╔══ DOCFRESH СЛОМАН ══════════════════════════════════════════════"
    echo "║ не найден $GUARD"
    echo "║ Свежесть документации по этой правке НЕ проверялась. Это не «чисто»."
    echo "╚═════════════════════════════════════════════════════════════════"
  } >&2
  exit 2
fi

PY="$(command -v python3 || true)"
if [ -z "$PY" ]; then
  {
    echo "╔══ DOCFRESH СЛОМАН ══════════════════════════════════════════════"
    echo "║ python3 не найден в PATH — не прогнан ни один предикат."
    echo "║ Это НАСТРОЙКА, а не сбой: она не чинится сама и не истечёт."
    echo "╚═════════════════════════════════════════════════════════════════"
  } >&2
  exit 2
fi

exec "$PY" "$GUARD"
