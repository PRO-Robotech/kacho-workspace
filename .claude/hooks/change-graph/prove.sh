#!/usr/bin/env bash
# Доказательство того, что хук change-graph-reminder ГОВОРИТ в свои три момента
# и МОЛЧИТ во всех остальных.
#
# ЗАЧЕМ ОТДЕЛЬНАЯ ПРОБА. Хук молчалив по замыслу, поэтому «ничего не напечатал»
# — его штатное поведение. Сломанный хук выглядит ТОЧНО ТАК ЖЕ. Различить два
# молчания можно только подав ему вход, на котором он обязан заговорить.
#
# И это не гипотеза: первая редакция хука молчала на ВСЕХ трёх моментах сразу.
# Причина — `python3 -` берёт программу со stdin, а heredoc занимал stdin
# целиком, поэтому полезная нагрузка до разбора не доезжала. Чтение исходника
# этого не показывало: программа была верной, ей просто не давали данных.
#
# Коды выхода: 0 — все утверждения сошлись; 1 — хотя бы одно нет.

set -uo pipefail

HOOK_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ROOT="$(cd "$HOOK_DIR/../.." && pwd)"
HOOK="$HOOK_DIR/change-graph-reminder.sh"

pass=0; fail=0

# speaks <путь> — код возврата хука на записи этого файла.
speaks() {
    printf '{"tool_input":{"file_path":"%s/%s"}}' "$ROOT" "$1" \
        | bash "$HOOK" >/dev/null 2>&1
    echo $?
}

# says <путь> <образец> — содержит ли сказанное образец.
#
# Вывод СНАЧАЛА захватывается, и только потом ищется образец. Первая редакция
# искала прямо в конвейере — и под `pipefail` вердикт брался из кода ХУКА (он
# выходит двойкой, когда ему есть что сказать), а не из кода поиска. Образец
# находился, а утверждение читалось как несошедшееся.
says() {
    local said
    said="$(printf '{"tool_input":{"file_path":"%s/%s"}}' "$ROOT" "$1" \
        | bash "$HOOK" 2>&1)"
    if printf '%s' "$said" | grep -qF -- "$2"; then echo да; else echo нет; fi
}

assert() {
    if [ "$1" = "$2" ]; then
        echo "  [OK]   $3"
        pass=$((pass + 1))
    else
        echo "  [FAIL] $3 — ожидалось «$1», получено «$2»" >&2
        fail=$((fail + 1))
    fi
}

if [ ! -f "$HOOK" ]; then
    echo "проба change-graph: хука $HOOK нет — доказывать нечего" >&2
    exit 1
fi

echo "== ГОВОРИТ в свои моменты =="
assert 2 "$(speaks AGENTS.md)"                 "момент 1: записан порождённый корневой указатель"
assert 2 "$(speaks .codex/hooks.json)"         "момент 1: записан порождённый файл второй среды"
assert 2 "$(speaks .agents/skills/evgeniy/SKILL.md)" "момент 1: записан порождённый пакет скила"
assert да "$(says AGENTS.md 'ПРЕДМЕТ ПРАВКИ ВСЕГДА ВО ВХОДЕ')" \
    "момент 1: назван предмет правки, а не просто «нельзя»"

ACC="docs/specs/sub-phase-SDD-1-kacho-change-graph-acceptance.md"
if [ -f "$ROOT/$ACC" ]; then
    assert 2 "$(speaks "$ACC")" "момент 3: записана приёмка"
    assert да "$(says "$ACC" 'Вердикт привязан к ОТПЕЧАТКУ')" \
        "момент 3: названа привязка вердикта к отпечатку"
else
    echo "  [SKIP] момента 3 не проверить: приёмки $ACC нет в дереве" >&2
fi

echo
echo "== МОЛЧИТ там, где не его момент =="
assert 0 "$(speaks README.md)"            "посторонний файл в корне"
assert 0 "$(speaks docs/specs/00-обзор.md)" "документ, не являющийся приёмкой"
assert 0 "$(speaks scripts/adapter/generate.py)" "код, не являющийся ни входом, ни выходом"

echo
echo "== МОЛЧИТ на каноническом входе, пока производное сошлось =="
# Предпосылка утверждения: производное действительно сошлось. Иначе «молчит»
# было бы доказано на дереве, где хук обязан говорить, — то есть не доказано.
if python3 "$ROOT/scripts/adapter-gate/probe.py" derived-drift >/dev/null 2>&1; then
    assert 0 "$(speaks .claude/rules/ui.md)" "правка входа при сошедшемся производном"
else
    echo "  [SKIP] производное сейчас РАЗОШЛОСЬ — это утверждение проверять не на чем" >&2
fi

echo
echo "== ГОВОРИТ на каноническом входе, когда производное разошлось =="
BACKUP="$(mktemp)"
cp "$ROOT/AGENTS.md" "$BACKUP"
printf '\nвнесённое расхождение\n' >> "$ROOT/AGENTS.md"
assert 2 "$(speaks .claude/rules/ui.md)" "правка входа при разошедшемся производном"
assert да "$(says .claude/rules/ui.md 'РАЗОШЛОСЬ')" "названо, что именно не сходится"
cp "$BACKUP" "$ROOT/AGENTS.md"
rm -f "$BACKUP"
# Откат ДОКАЗЫВАЕТСЯ, а не заявляется: проба, оставившая дерево изменённым,
# создаёт находку у следующего прогона и выглядит его дефектом.
assert 0 "$(speaks .claude/rules/ui.md)" "после отката расхождения хук снова молчит"

echo
echo "перепись пробы: утверждений $((pass + fail)); сошлось $pass, разошлось $fail"
if [ "$((pass + fail))" -eq 0 ]; then
    echo "проба change-graph: не прогнано ни одного утверждения — это НЕ успех" >&2
    exit 1
fi
[ "$fail" -eq 0 ] || exit 1
exit 0
