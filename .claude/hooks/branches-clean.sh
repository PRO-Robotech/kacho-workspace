# branches-clean.sh — влитая локальная ветка видна БЕЗ ЗАПУСКА КОМАНДЫ.
#
# # Предмет
#
# Висяк — это ССЫЛКА, а не коммит. До 2026-09-22 вливали схлопыванием: у
# squash-коммита нет родителя-ветки, исходный коммит предком ствола не стал
# НИКОГДА, и пока локальная ветка его держит, `git log --all --graph` рисует
# оборванную линию, неотличимую от брошенной работы. С решения владельца
# 2026-09-22 (п.4) серверное вливание — только коммитом слияния: сквош выключен
# хостингом во всех четырёх репозиториях (`allow_squash_merge=false`, замер
# 2026-09-26), и голова влитой ветки — предок приёмника. Ссылку это не снимает:
# влитая ветка переживает вливание и выглядит живой работой, пока её не снять.
#
# `delete_branch_on_merge` включён во всех четырёх репозиториях (kacho, kaname,
# corelib, kacho-workspace; замер 2026-09-26) и снимает head-ветку PR НА ORIGIN —
# только её. Ветки задач, сведённые в сборку, всё влитое переносом или черри-пиком
# он не видит by construction; локальных копий — тем более. Их снятие — шаг
# вливания у git-operator (`git-issues.md#gi-prune-same-pass`), а этот хук —
# заметность пропущенного шага, и не во всех клонах: `project/kaname` и
# `project/corelib` он не осматривает.
# Замер 2026-08-16 на монорепо продукта: 37 локальных веток при 4 на origin, из
# них 20 влиты (сегодняшнее число даёт `scripts/branch-audit.sh`).
#
# Перепись, которая это чинит, существует и доказана инъекцией — и НЕ ВЫЗЫВАЕТСЯ
# ничем: узнать, что мусор накопился, мог лишь тот, кто и так о ней помнил. Этот
# хук закрывает именно заметность, а не саму уборку.
#
# # Форма
#
# Исполняется на КАЖДОМ обращении к сессии (`UserPromptSubmit`) и МОЛЧИТ, пока
# влитых локальных веток нет. Молчание выбрано намеренно: строка, печатающаяся
# всегда, перестаёт читаться на третий день.
#
# Отсюда обязанность, которую молчание накладывает: хук ОБЯЗАН заговорить, когда
# ему нечего осмотреть. «Ноль находок» и «ноль прочитанного» дают один и тот же
# пустой вывод, поэтому второе называется отдельной строкой.
#
# # Почему признак ЗДЕСЬ дешевле, чем в переписи, и это сказано вслух
#
# Хук считает только ветки, чей HEAD — ПРЕДОК ствола (первый признак): это одна
# дешёвая операция на ветку. Предок — ещё не «влита»: голова на ПЕРВОЙ ЛИНИИ
# ствола (`git rev-list --first-parent`) — ветка без своего коммита, влито
# нечего, и пока она есть на origin (живая волна) или её ссылка двигалась в
# окне `BRANCH_AUDIT_FRESH_MIN` (свежая ветка), `branch-audit.sh --prune-merged`
# её не снимает (ws#847, круг 2) — и в счёт она не идёт: иначе хук звал бы к
# уборке, которой не будет, на каждом обращении, а порог на штатном состоянии
# перестаёт читаться. Только локальная, без копии и вне окна — идёт (круг 3):
# исключение без срока держало бы её вечно, и хук молчал бы о ней по
# построению. «Есть на origin» хук берёт из `refs/remotes`, без сети: ссылка,
# снятая на origin после последнего `git fetch`, для него ещё есть — это
# недосчёт, а не лишняя находка.
# Ствол у него один — `origin/main`: влитое в ветку эпика или волны он НЕ видит,
# его находит перепись конца сессии по целям каскада
# (`git-issues.md#gi-prune-session-zero`). Схлопнутые и поглощённые пофайлово он
# тоже НЕ видит — их находит `branch-audit.sh` пятым и шестым признаками, и он же
# их снимает. Поэтому число хука — НИЖНЯЯ ГРАНИЦА, и он это печатает: иначе «две
# влитых» читалось бы как «всего две».
#
# Сессию не роняет НИКОГДА (выход 0 при любом исходе): это указатель, а не гейт.
#
# # Кому адресован вывод
#
# `UserPromptSubmit` — событие ГЛАВНОГО ПОТОКА, значит текст читает диспетчер, у
# которого нет ни Bash, ни Read. «Гони перепись» он исполнить не может; он ставит
# полосу. Поэтому вывод называет агента (снятие и вливание — `git-operator`,
# состояние ветки — `scout`), а команда остаётся предметом задания, а не поручением
# читающему.
set -uo pipefail

ws="${CLAUDE_PROJECT_DIR:-}"
[ -n "$ws" ] || ws="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

findings=()
examined_repos=0
examined_branches=0
unreadable=()
now=$(date +%s)
fresh_min="${BRANCH_AUDIT_FRESH_MIN:-45}"
case "$fresh_min" in ''|*[!0-9]*) fresh_min=45 ;; esac

# moved_ct $1 = клон, $2 = ссылка → $moved: время последней записи журнала
# ссылки, без журнала — время коммита головы (то же, что у переписи).
moved_ct() {
  moved=$(git -C "$1" reflog show --date=unix --format=%gd -n 1 "$2" -- 2>/dev/null)
  moved=${moved##*@\{}; moved=${moved%\}}
  case "$moved" in ''|*[!0-9]*) moved=$(git -C "$1" log -1 --format=%ct "$2" 2>/dev/null || echo 0) ;; esac
  case "$moved" in ''|*[!0-9]*) moved=0 ;; esac
}

check_repo() { # $1 = путь, $2 = как называть в выводе
  local path=$1 label=$2 trunk="origin/main" n=0 occupied=() b

  [ -d "$path/.git" ] || [ -f "$path/.git" ] || { unreadable+=("$label: не репозиторий"); return; }
  git -C "$path" rev-parse --verify --quiet "$trunk^{commit}" >/dev/null 2>&1 || {
    unreadable+=("$label: ствол $trunk не разрешается — осмотр беспредметен"); return; }

  examined_repos=$((examined_repos + 1))

  local -A first_line=()
  local c h
  while read -r c; do first_line["$c"]=1; done < <(git -C "$path" rev-list --first-parent "$trunk" 2>/dev/null)

  # Ветку, занятую рабочей копией, снимать нельзя, и звать о ней бессмысленно.
  while read -r br; do
    [ -n "$br" ] && occupied+=("$br")
  done < <(git -C "$path" worktree list --porcelain 2>/dev/null |
           awk '/^branch /{b=$2; sub("refs/heads/","",b); print b}')

  while read -r b; do
    [ -n "$b" ] || continue
    [ "$b" = "main" ] && continue
    examined_branches=$((examined_branches + 1))
    local skip=0 o
    for o in ${occupied[@]+"${occupied[@]}"}; do [ "$o" = "$b" ] && skip=1; done
    [ "$skip" = 1 ] && continue
    git -C "$path" merge-base --is-ancestor "$b" "$trunk" 2>/dev/null || continue
    h=$(git -C "$path" rev-parse --verify --quiet "refs/heads/$b" 2>/dev/null) || continue
    if [ -z "${first_line[$h]+x}" ]; then n=$((n + 1)); continue; fi
    # Без своего коммита: держится, пока есть на origin или ссылка двигалась в окне.
    git -C "$path" rev-parse --verify --quiet "refs/remotes/origin/$b" >/dev/null 2>&1 && continue
    moved_ct "$path" "refs/heads/$b"
    [ "$moved" -gt 0 ] && [ $(( (now - moved) / 60 )) -lt "$fresh_min" ] && continue
    n=$((n + 1))
  done < <(git -C "$path" branch --format='%(refname:short)' 2>/dev/null)

  [ "$n" -gt 0 ] && findings+=("$label: не менее $n локальных веток уже в стволе")
  return 0
}

check_repo "$ws" "воркспейс"
[ -d "$ws/project/kacho" ] && check_repo "$ws/project/kacho" "продукт"

if [ "${#findings[@]}" -ne 0 ]; then
  echo "🌿 ВЛИТЫЕ ЛОКАЛЬНЫЕ ВЕТКИ — они и рисуют «повисшие куски» в git log --all --graph"
  printf '   %s\n' "${findings[@]}"
  echo "   Это НИЖНЯЯ ГРАНИЦА: считаны предки ствола со своим коммитом и без него, но только локальные"
  echo "   и вне окна свежести. Схлопнутые и поглощённые пофайлово хук не видит — их находит перепись"
  echo "   по байтам, не по предку, она же их и снимает."
  echo "   Ветки к разбору → git-operator, переписью и снятием В ОДНОЙ полосе:"
  echo "     ./scripts/branch-audit.sh [project/kacho]                 # посмотреть"
  echo "     ./scripts/branch-audit.sh --prune-merged [project/kacho]  # снять влитые"
  echo "   Вердикт переписи устаревает за минуты, поэтому снимают по вердикту той же"
  echo "   полосы, а не по этой строке: она называет предмет, а не состояние."
  echo "   Состояние ветки — чья работа, влита ли остальными признаками → scout."
  echo "   Перепись НИКОГДА не трогает работу в единственном экземпляре и занятые"
  echo "   рабочей копией ветки."
fi

if [ "$examined_repos" -eq 0 ]; then
  echo "🌿 branches-clean: не осмотрено НИ ОДНОГО репозитория — молчание этого хука"
  echo "   означает «не проверяли», а не «чисто»."
  printf '   %s\n' ${unreadable[@]+"${unreadable[@]}"}
  echo "   → scout: почему рабочие копии не читаются. Снятие веток до его возврата"
  echo "     не назначается — снимать пришлось бы по вердикту, которого нет."
elif [ "${#unreadable[@]}" -ne 0 ]; then
  echo "🌿 branches-clean: осмотрено репозиториев $examined_repos, веток $examined_branches;"
  echo "   часть осмотреть не удалось — вердикт по ним НЕ вынесен:"
  printf '   %s\n' "${unreadable[@]}"
  echo "   → scout: почему. «Влитых нет» из неосмотренного не читается."
fi

exit 0
