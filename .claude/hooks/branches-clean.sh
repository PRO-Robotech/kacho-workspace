# branches-clean.sh — влитая локальная ветка видна БЕЗ ЗАПУСКА КОМАНДЫ.
#
# # Предмет
#
# Висяк — это ССЫЛКА, а не коммит. Здесь вливают схлопыванием: squash-коммит не
# имеет родителя-ветки, поэтому исходный коммит не становится предком ствола
# НИКОГДА. Пока локальная ветка его держит, `git log --all --graph` рисует
# оборванную линию, неотличимую от брошенной работы, — и владелец, глядя на
# историю, видит куски разработки, повисшие в воздухе.
#
# `delete_branch_on_merge` включён в обоих репозиториях и снимает head-ветку PR
# НА ORIGIN — только её. Всё, что вливалось переносом, черри-пиком или через
# накопительную ветку, он не видит by construction; локальных копий — тем более.
# Замер 2026-08-16 на монорепо продукта: 37 локальных веток при 4 на origin, из
# них 20 влиты (сегодняшнее число даёт `scripts/branch-audit.sh`).
#
# Перепись, которая это чинит, существует и доказана инъекцией — и НЕ ВЫЗЫВАЕТСЯ
# ничем: узнать, что мусор накопился, мог лишь тот, кто и так о ней помнил. Этот
# хук закрывает именно заметность, а не саму уборку.
#
# # Форма
#
# Исполняется на КАЖДОМ обращении к сессии (`UserPromptSubmit`) и МОЛЧИТ, пока
# влитых локальных веток нет. Молчание выбрано намеренно: строка, печатающаяся
# всегда, перестаёт читаться на третий день.
#
# Отсюда обязанность, которую молчание накладывает: хук ОБЯЗАН заговорить, когда
# ему нечего осмотреть. «Ноль находок» и «ноль прочитанного» дают один и тот же
# пустой вывод, поэтому второе называется отдельной строкой.
#
# # Почему признак ЗДЕСЬ дешевле, чем в переписи, и это сказано вслух
#
# Хук считает только ветки, чей HEAD — ПРЕДОК ствола (первый признак): это одна
# дешёвая операция на ветку, и ложных срабатываний у неё нет by construction.
# Схлопнутые и поглощённые пофайлово он НЕ видит — их находит `branch-audit.sh`
# пятым и шестым признаками, и он же их снимает. Поэтому число хука — НИЖНЯЯ
# ГРАНИЦА, и он это печатает: иначе «две влитых» читалось бы как «всего две».
#
# Сессию не роняет НИКОГДА (выход 0 при любом исходе): это указатель, а не гейт.
#
# # Признак дельты (2026-09-20)
#
# Хук печатал ЧИСЛО, которым нельзя действовать, и печатал его каждый ход: «не менее
# 7» и «не менее 19» без ревизии и без времени замера, с оговоркой «вердикт устаревает
# за минуты» в том же блоке. Нижняя граница без координаты во времени — не дельта.
#
# Починено двумя правками, и обе нужны: ревизия и время замера названы В САМОЙ строке
# находки (число стало привязано к состоянию), а тело отдано `signal_emit` — при том же
# числе на следующем ходу выходит одна строка «без изменений», при ИЗМЕНИВШЕМСЯ —
# полный блок. Молчание при нуле влитых сохранено, перепись неосмотренного — тоже:
# у неё свой предмет и свой сигнал, и пустой обход первого второго не отменяет.
#
# # Кому адресован вывод
#
# `UserPromptSubmit` — событие ГЛАВНОГО ПОТОКА, значит текст читает диспетчер, у
# которого нет ни Bash, ни Read. «Гони перепись» он исполнить не может; он ставит
# полосу. Поэтому вывод называет агента (снятие и вливание — `git-operator`,
# состояние ветки — `scout`), а команда остаётся предметом задания, а не поручением
# читающему.
set -uo pipefail

# Оболочка признака дельты. Провал `source` ОБЯЗАН быть слышен и НЕ вправе проглотить
# находку: замер 2026-09-20 — при неверном имени файла хук напечатал НОЛЬ строк, то
# есть находки исчезли молча, а это ровно тот мягкий проход, который оснастка и ловит.
# Заглушки объявлены ЗДЕСЬ, а не в общем файле, по причине начальной загрузки: они
# страхуют отсутствие того самого файла, в котором иначе бы лежали.
_sig="$(dirname "${BASH_SOURCE[0]}")/lib/hook_signal.sh"
# shellcheck source=lib/hook_signal.sh
. "$_sig" 2>/dev/null || {
  echo "[сигнал] признак дельты НЕ применён: не найден $_sig. Тело печатается ПОЛНОСТЬЮ каждый ход. → tooling-maintainer" >&2
  signal_stdin() { :; }
  signal_sha() { echo "ревизия не читается"; }
  signal_emit() { cat; echo "[сигнал \`$1\`] признак дельты НЕ применён (нет $_sig) · адресат: $2 · предикат снятия предмета: $3"; }
}
signal_stdin

ws="${CLAUDE_PROJECT_DIR:-}"
[ -n "$ws" ] || ws="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

findings=()
examined_repos=0
examined_branches=0
unreadable=()

check_repo() { # $1 = путь, $2 = как называть в выводе
  local path=$1 label=$2 trunk="origin/main" n=0 occupied=() b

  [ -d "$path/.git" ] || [ -f "$path/.git" ] || { unreadable+=("$label: не репозиторий"); return; }
  git -C "$path" rev-parse --verify --quiet "$trunk^{commit}" >/dev/null 2>&1 || {
    unreadable+=("$label: ствол $trunk не разрешается — осмотр беспредметен"); return; }

  examined_repos=$((examined_repos + 1))

  # Ветку, занятую рабочей копией, снимать нельзя, и звать о ней бессмысленно.
  while read -r br; do
    [ -n "$br" ] && occupied+=("$br")
  done < <(git -C "$path" worktree list --porcelain 2>/dev/null |
           awk '/^branch /{b=$2; sub("refs/heads/","",b); print b}')

  while read -r b; do
    [ -n "$b" ] || continue
    [ "$b" = "main" ] && continue
    examined_branches=$((examined_branches + 1))
    local skip=0 o
    for o in ${occupied[@]+"${occupied[@]}"}; do [ "$o" = "$b" ] && skip=1; done
    [ "$skip" = 1 ] && continue
    git -C "$path" merge-base --is-ancestor "$b" "$trunk" 2>/dev/null && n=$((n + 1))
  done < <(git -C "$path" branch --format='%(refname:short)' 2>/dev/null)

  local trunk_sha at
  trunk_sha="$(git -C "$path" rev-parse --short "$trunk" 2>/dev/null || echo 'ствол не читается')"
  at="$(date +%H:%M:%S)"
  [ "$n" -gt 0 ] && findings+=("$label: не менее $n локальных веток уже в стволе \
$trunk_sha, замер $at — число привязано к ЭТОЙ ревизии и этому времени")
  return 0
}

check_repo "$ws" "воркспейс"
[ -d "$ws/project/kacho" ] && check_repo "$ws/project/kacho" "продукт"

if [ "${#findings[@]}" -ne 0 ]; then
  signal_emit branches-merged "git-operator (перепись и снятие В ОДНОЙ полосе) · scout (чья работа, влита ли остальными признаками)" \
    './scripts/branch-audit.sh [project/kacho] печатает «влитых 0» — тогда предмета нет и сигнал уходит сам' \
    "$(signal_sha "$ws")" <<EOF
🌿 ВЛИТЫЕ ЛОКАЛЬНЫЕ ВЕТКИ — они и рисуют «повисшие куски» в git log --all --graph
$(printf '   %s\n' "${findings[@]}")
   Это НИЖНЯЯ ГРАНИЦА: считаны только предки ствола. Схлопнутые и поглощённые
   пофайлово хук не видит — их находит перепись, она же их и снимает.
   Ветки к разбору → git-operator, переписью и снятием В ОДНОЙ полосе:
     ./scripts/branch-audit.sh [project/kacho]                 # посмотреть
     ./scripts/branch-audit.sh --prune-merged [project/kacho]  # снять влитые
   Вердикт переписи устаревает за минуты, поэтому снимают по вердикту той же
   полосы, а не по этой строке: она называет предмет и ревизию замера, а не
   нынешнее состояние.
   Перепись НИКОГДА не трогает работу в единственном экземпляре и занятые
   рабочей копией ветки.
EOF
fi

# Неосмотренное — ОТДЕЛЬНЫЙ предмет и отдельный сигнал: «влитых нет» и «не смотрели»
# закрываются разными полосами, и свёртка одного не вправе свернуть другой.
if [ "$examined_repos" -eq 0 ]; then
  signal_emit branches-unreadable "scout" \
    'git -C <копия> rev-parse --verify origin/main разрешается в обеих рабочих копиях' \
    "$(signal_sha "$ws")" <<EOF
🌿 branches-clean: не осмотрено НИ ОДНОГО репозитория — молчание этого хука
   означает «не проверяли», а не «чисто».
$(printf '   %s\n' ${unreadable[@]+"${unreadable[@]}"})
   → scout: почему рабочие копии не читаются. Снятие веток до его возврата
     не назначается — снимать пришлось бы по вердикту, которого нет.
EOF
elif [ "${#unreadable[@]}" -ne 0 ]; then
  signal_emit branches-unreadable "scout" \
    'git -C <копия> rev-parse --verify origin/main разрешается в обеих рабочих копиях' \
    "$(signal_sha "$ws")" <<EOF
🌿 branches-clean: осмотрено репозиториев $examined_repos, веток $examined_branches;
   часть осмотреть не удалось — вердикт по ним НЕ вынесен:
$(printf '   %s\n' "${unreadable[@]}")
   → scout: почему. «Влитых нет» из неосмотренного не читается.
EOF
fi

exit 0
