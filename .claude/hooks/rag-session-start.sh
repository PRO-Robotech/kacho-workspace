#!/usr/bin/env bash
# rag-session-start.sh — событие SessionStart: сказать ОДИН раз, отстал ли индекс.
#
# Почему SessionStart, а не UserPromptSubmit (как остальные хуки воркспейса):
# предмет здесь меняется РЕДКО (индекс пересобирают раз в сутки-двое), а
# UserPromptSubmit срабатывает на каждом обращении. Строка о свежести, печатаемая
# по двадцать раз за сессию, перестаёт читаться на третий день — и вместе с ней
# перестают читать настоящую находку.
#
# Новая сессия узнаёт состояние ВСЕГДА, без подавления повторов: подавление
# здесь означало бы, что сессия, начатая при отставшем индексе, о нём не узнает
# только потому, что о нём сказали предыдущей.
#
# Сессию не роняет никогда: выход 0 при любом исходе.
set -uo pipefail
exec bash "$(dirname "${BASH_SOURCE[0]}")/rag-freshness.sh"
