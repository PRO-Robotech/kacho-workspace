# hooks-wired.sh — непровязанная рабочая копия видна БЕЗ ЗАПУСКА КОМАНДЫ.
#
# # Предмет
#
# Правило «перед отправкой ветки — обязательный локальный прогон» объявлено
# держащимся хуком, а не вниманием. Проверить это можно было только позвав
# `install.sh check` — то есть узнать, что защиты нет, мог лишь тот, кто и так
# о ней помнил. Цена измерена: за одну сессию конвейер девятнадцать раз стал
# первым читателем кода, три прогона упали на том, что локальный прогон нашёл
# бы за секунды, а очередь ранеров дошла до 32 прогонов.
#
# Провязка и заметность — РАЗНЫЕ вещи, и вторая важнее. Провязку чинят один раз;
# она разваливается снова при свежем клоне, при переезде каталога, при
# выставленном `core.hooksPath`, ведущем в никуда, — и каждый раз молча.
#
# # Форма
#
# Хук исполняется на КАЖДОМ обращении к сессии (`UserPromptSubmit`) и молчит,
# пока всё в порядке. Молчание выбрано намеренно: строка, печатающаяся всегда,
# перестаёт читаться на третий день, и заметность превращается в шум.
#
# Отсюда обязанность, которую молчание накладывает: хук ОБЯЗАН заговорить, когда
# ему нечего осмотреть. «Ноль находок» и «ноль прочитанного» здесь дают один и
# тот же пустой вывод, поэтому второе названо отдельной строкой.
#
# Сессию не роняет НИКОГДА (выход 0 при любом исходе): это указатель, а не гейт.
# Гейт — сам `pre-push`, и он отказывает в отправке.
#
# # Кому адресован вывод
#
# `UserPromptSubmit` — событие ГЛАВНОГО ПОТОКА: текст читает диспетчер, у которого нет
# ни Bash, ни Read. Провязать хуки он не может; он ставит полосу — поэтому находка
# названа агентом (`git-operator` — провязка, `scout` — почему копии не читаются), а
# команда стоит предметом задания, а не поручением читающему.
#
# # Признак дельты (2026-09-20)
#
# Находка этого хука живёт до полосы `git-operator` — то есть много ходов, и каждый
# ход печаталась целиком. Повторённая, она неотличима от новой, поэтому тело идёт
# через `signal_emit`: полностью на первом ходу и при ИЗМЕНЕНИИ перечня, одной
# строкой на повторе. Молчание при провязанных хуках сохранено, «не осмотрено ни
# одной копии» осталось отдельным предметом со своим сигналом.
set -uo pipefail

# Оболочка признака дельты. Провал `source` fail-open и громкий: тело печатается
# целиком, находка не теряется. Заглушки объявлены здесь по причине начальной
# загрузки — они страхуют отсутствие того файла, в котором иначе бы лежали.
_sig="$(dirname "${BASH_SOURCE[0]}")/lib/hook_signal.sh"
# shellcheck source=lib/hook_signal.sh
. "$_sig" 2>/dev/null || {
  echo "[сигнал] признак дельты НЕ применён: не найден $_sig. Тело печатается ПОЛНОСТЬЮ каждый ход. → tooling-maintainer" >&2
  signal_stdin() { :; }
  signal_sha() { echo "ревизия не читается"; }
  signal_emit() { cat; echo "[сигнал \`$1\`] признак дельты НЕ применён (нет $_sig) · адресат: $2 · предикат снятия предмета: $3"; }
}
signal_stdin

ws="${CLAUDE_PROJECT_DIR:-}"
[ -n "$ws" ] || ws="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

marker="kacho-hook-stub v1"
findings=()
examined=0

# check_clone <корень> <как называть в отчёте>
check_clone() {
    local root="$1" name="$2"
    [ -d "$root" ] || return 0

    local common
    common="$(git -C "$root" rev-parse --git-common-dir 2>/dev/null)" || return 0
    case "$common" in /*) ;; *) common="$root/$common" ;; esac
    examined=$((examined + 1))

    # Настройка, уводящая git от `.git/hooks`, — отдельный вид поломки: она
    # выглядит настроенной и при этом отключает ВСЁ, что там лежит.
    local cfg
    cfg="$(git -C "$root" config --get core.hooksPath 2>/dev/null || true)"
    if [ -n "$cfg" ]; then
        local abs="$cfg"
        case "$abs" in /*) ;; *) abs="$root/$abs" ;; esac
        if [ ! -d "$abs" ]; then
            findings+=("$name: core.hooksPath ведёт в НЕСУЩЕСТВУЮЩИЙ «$cfg» — хуков нет ни одного")
            return 0
        fi
    fi

    # Отслеживаемые хуки — то же множество, что увидит свежий клон.
    local tracked=()
    while IFS= read -r rel; do
        local base="${rel##*/}"
        case "$base" in *.*) continue ;; esac
        tracked+=("$base")
    done < <(git -C "$root" ls-files scripts/hooks 2>/dev/null)

    if [ "${#tracked[@]}" -eq 0 ]; then
        findings+=("$name: в scripts/hooks нет НИ ОДНОГО отслеживаемого хука — отправка не проверяется")
        return 0
    fi

    local h target
    for h in "${tracked[@]}"; do
        target="$common/hooks/$h"
        if [ ! -e "$target" ]; then
            findings+=("$name: хук «$h» НЕ провязан — отправка идёт без локального прогона")
        elif ! grep -qF "$marker" "$target" 2>/dev/null; then
            findings+=("$name: «$h» в .git/hooks — посторонний файл, наш прогон им не исполняется")
        elif [ ! -x "$target" ]; then
            findings+=("$name: «$h» провязан, но НЕ исполняемый — git его пропустит молча")
        elif [ ! -x "$root/scripts/hooks/$h" ]; then
            findings+=("$name: «$h» провязан в пустоту — scripts/hooks/$h не исполняемый или отсутствует")
        fi
    done
}

check_clone "$ws" "воркспейс"
check_clone "$ws/project/kacho" "монорепо"

if [ "$examined" -eq 0 ]; then
    signal_emit hooks-unreadable "scout" \
      'git -C <копия> rev-parse --git-common-dir разрешается хотя бы в одной рабочей копии' \
      "$(signal_sha "$ws")" >&2 <<EOF
ХУКИ: не осмотрено НИ ОДНОЙ рабочей копии — этот указатель сейчас ничего не значит.
     Ни \$CLAUDE_PROJECT_DIR, ни каталог рядом с ним репозиторием не оказались.
     → scout: почему копии не читаются. Это «не проверяли», а не «чисто».
EOF
    exit 0
fi

if [ "${#findings[@]}" -gt 0 ]; then
    signal_emit hooks-not-wired "git-operator (ДО любой отправки)" \
      'bash <корень>/scripts/hooks/install.sh check выходит нулём в каждой рабочей копии' \
      "$(signal_sha "$ws")" >&2 <<EOF
ХУКИ НЕ ПРОВЯЗАНЫ — отправка ветки НЕ проверяется локально:
$(printf '  · %s\n' "${findings[@]}")
  → git-operator, ДО любой отправки: bash <корень>/scripts/hooks/install.sh install
    (в монорепо есть и цель: make install-hooks).
  Пока он не вернулся, отправка не назначается: pre-push здесь не исполняется,
  и первым читателем кода снова станет конвейер.
EOF
fi

exit 0
