#!/usr/bin/env bash
# PostToolUse hook — class-guard. Прогоняет по ТОЛЬКО ЧТО записанному файлу
# предикаты классов из скилов code-authoring / gate-authoring /
# measurement-discipline / verdict-and-landing, чей вердикт зависит только от
# содержимого этого файла.
#
# Запись НЕ блокируется (PostToolUse срабатывает после неё). Код 2 означает
# «есть что сказать» — stderr доезжает до автора немедленно.
#
# Собственная поломка этого скрипта — ГРОМКАЯ. Молчаливый выход с нулём здесь
# запрещён: он неотличим от «прогнал и чисто», а это ровно тот класс, который
# гейт и ловит (мягкий проход, не различающий настройку и сбой).
set -u

# Без внешних команд: `dirname` может отсутствовать ровно в том сценарии, ради
# которого этот блок написан (обрезанный PATH), и тогда диагностика соврала бы
# про причину — сказала бы «не найден guard.py» вместо «нет python3».
_src="${BASH_SOURCE[0]}"
HOOK_DIR="$(cd "${_src%/*}" 2>/dev/null && pwd)" || HOOK_DIR="."
GUARD="$HOOK_DIR/class-guard/guard.py"

if [ ! -f "$GUARD" ]; then
  {
    echo "╔══ CLASS-GUARD СЛОМАН ═══════════════════════════════════════════"
    echo "║ не найден $GUARD"
    echo "║ Предикаты по этой правке НЕ прогонялись. Это не «чисто»."
    echo "╚═════════════════════════════════════════════════════════════════"
  } >&2
  exit 2
fi

PY="$(command -v python3 || true)"
if [ -z "$PY" ]; then
  {
    echo "╔══ CLASS-GUARD СЛОМАН ═══════════════════════════════════════════"
    echo "║ python3 не найден в PATH — гейт не прогнан ни по одному предикату."
    echo "║ Это НАСТРОЙКА, а не сбой: она не чинится сама и не истечёт."
    echo "╚═════════════════════════════════════════════════════════════════"
  } >&2
  exit 2
fi

exec "$PY" "$GUARD"
