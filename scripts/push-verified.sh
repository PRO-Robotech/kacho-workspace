# push-verified.sh — отправка, вердикт которой берётся У СЕРВЕРА, а не у кода
# команды, плюс keepalive на транспорте, без которого длинный хук рвёт соединение.
#
# ПОЧЕМУ ЗАВЕДЕНО. Замер 2026-09-22: отправка ветки отчиталась `exit code 0`,
# настоящий код был 128 (`send-pack: unexpected disconnect`). Хук отправки
# отработал зелёным за 831 секунду; всё это время соединение молчало, и его
# оборвали по простою — пакет не ушёл. Ноль принадлежал ОБЁРТКЕ, а не операции:
# отсутствие ветки на сервере заметили только отдельным `git ls-remote`.
# Отсюда два разных предмета, и оба держатся ЗДЕСЬ:
#
#   1. КОД ОБЁРТКИ ≠ ИСХОД ОПЕРАЦИИ. «Команда вернула ноль» и «операция
#      состоялась» — разные утверждения, и у второго есть проверяемый машиной
#      признак: ССЫЛКА НА СЕРВЕРЕ РАВНА ОТПРАВЛЕННОЙ sha. Он и спрашивается —
#      ВСЕГДА, независимо от того, что вернул `git push`. Зелёное этого скрипта
#      означает ровно одно: сервер сам назвал ту sha, которую мы отправляли.
#
#      ПРЕДМЕТ — ПОСТУСЛОВИЕ, А НЕ ОБРЫВ. В тот же день тот же ложный ноль пришёл
#      ДРУГИМ путём: хук гнал 25 групп проверок, перешагнул порог харнесса в 120 с,
#      команду перевели в фон и прислали «exit code 0». Настоящий код там тоже был
#      нулём — совпадение, а не доказательство; порог этот хук перешагивает почти
#      всегда, то есть код посредника будет приходить ВСЕГДА. Путей к ложному нулю
#      больше одного и будет ещё, поэтому спрашивается исход операции, а не её
#      причина, и вердикт печатается СЛОВОМ: код у читателя могут отнять, печать —
#      нет.
#   2. ПОЧЕМУ РВЁТСЯ. `git push` соединяется и ВЫЯСНЯЕТ ССЫЛКИ ДО хука (их старые
#      sha хук получает на вход), затем молчит всё время его работы и только
#      потом шлёт пакет. Молчание длиной в прогон проверок переживает не всякий
#      путь: простойные таймауты стоят и в NAT, и у посредников. Лечится трафиком
#      — `ServerAliveInterval`, — а не обходом проверок: `--no-verify` без
#      дословного разрешения владельца не применяется (`git-issues.md`).
#
# ОТКУДА 20 СЕКУНД (величина названа замером, а не «поставил побольше»):
#   · верхняя граница — самый короткий простойный таймаут на пути. Измеренного
#     значения у нас нет; известно, что он МЕНЬШЕ 831 с (в этом молчании
#     соединение умерло, замер 2026-09-22). Самое короткое окно, которое мы
#     обязаны пережить, принято равным 60 с — это ДОПУЩЕНИЕ про мобильный NAT,
#     нашей машиной не измеренное, и оно названо допущением намеренно;
#   · `ServerAliveCountMax` на этой машине равен 3 — ЗАМЕР, а не умолчание из
#     памяти: `ssh -G github.com | grep -i serveralive`. Три пакета обязаны
#     уложиться в окно: 60/3 = 20;
#   · нижняя граница — стоимость. При 20 с прогон наборов воркспейса даёт 6
#     пакетов (115 с — замер 2026-09-22, `time bash scripts/hooks/pre-push
#     < /dev/null`), хук продукта (831 с, замер оператора) — 41. Ничтожно.
#   Перепроверить: `ssh -G <хост> | grep -i serveralive` (что ДЕЙСТВУЕТ сейчас)
#   и повтор отправки с хуком длиннее измеренного окна.
#
# ЧУЖУЮ НАСТРОЙКУ ТРАНСПОРТА НЕ ПЕРЕБИВАЕТ. Если `GIT_SSH_COMMAND` или
# `core.sshCommand` уже заданы, там может стоять ключ, порт или прокси, без
# которых отправка не состоится вовсе. Тогда keepalive не навязывается, а
# состояние НАЗЫВАЕТСЯ строкой — «в чужой команде keepalive нет» читается и
# чинится, молчаливая подмена — нет. Постоянное место настройки для клона —
# `scripts/hooks/install.sh` (`make install-hooks`), он выставляет её один раз.
#
# ТРИ ИСХОДА, А НЕ ДВА:
#   0 — ПОДТВЕРЖДЕНО: сервер назвал ту же sha;
#   1 — НАХОДКА: ссылка на сервере не равна отправленной (в том числе её нет);
#   2 — БЕЗ ПРЕДМЕТА: сервер не опрошен (сеть, доступ, нет такой ветки локально).
#       Это НЕ успех: «не подтверждено» и «подтверждено» не одно и то же.
#
# Предмет — отправка ВЕТКИ. Снятие ссылки (`--delete`), теги и произвольные
# refspec сюда не входят: у них другой признак состоявшегося, и делать вид, что
# он тот же, значило бы завести второй молчаливый ноль.
#
# Способность упасть доказана `scripts/push-verified-inject.sh`; что обёртка
# исполняет этот признак на каждом прогоне — `scripts/tooling-gate/check-16-*`.
set -uo pipefail

KEEPALIVE_INTERVAL=20
KEEPALIVE_COUNT=3

usage() {
    cat >&2 <<'EOF'
push-verified.sh [-C <рабочая копия>] [<remote>] [<ветка>] [-- <флаги git push>]
  по умолчанию: remote = origin, ветка = текущая
  0 — подтверждено сервером · 1 — ссылка не равна отправленной · 2 — не опрошено
EOF
}

repo="."
while [ $# -gt 0 ]; do
    case "$1" in
        -C) repo="${2:-}"; shift 2 || { usage; exit 2; } ;;
        -h|--help) usage; exit 0 ;;
        --) shift; break ;;
        *) break ;;
    esac
done

remote="${1:-origin}"; [ $# -gt 0 ] && shift
branch="${1:-}";       [ $# -gt 0 ] && shift
[ "${1:-}" = "--" ] && shift
flags=("$@")

root="$(git -C "$repo" rev-parse --show-toplevel 2>/dev/null)" || {
    echo "push-verified: БЕЗ ПРЕДМЕТА — «$repo» не рабочая копия git" >&2
    exit 2
}
cd "$root" || exit 2

# Переменные окружения git, унаследованные от вызывающего хука, сильнее рабочего
# каталога: с выставленным GIT_DIR все команды ниже писали бы в ЧУЖОЙ репозиторий.
unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
      GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_COMMON_DIR GIT_PREFIX

if [ -z "$branch" ]; then
    branch="$(git rev-parse --abbrev-ref HEAD 2>/dev/null)"
    if [ -z "$branch" ] || [ "$branch" = "HEAD" ]; then
        echo "push-verified: БЕЗ ПРЕДМЕТА — ветка не названа, а HEAD отделён" >&2
        exit 2
    fi
fi

local_sha="$(git rev-parse --verify "refs/heads/$branch" 2>/dev/null)" || {
    echo "push-verified: БЕЗ ПРЕДМЕТА — локальной ветки «$branch» нет" >&2
    exit 2
}

# ── keepalive: свой выставляем, чужой НЕ трогаем, состояние называем ──────────
transport="${GIT_SSH_COMMAND:-}"
source_of=окружение
if [ -z "$transport" ]; then
    transport="$(git config --get core.sshCommand 2>/dev/null || true)"
    source_of="core.sshCommand клона"
fi
if [ -z "$transport" ]; then
    export GIT_SSH_COMMAND="ssh -o ServerAliveInterval=$KEEPALIVE_INTERVAL -o ServerAliveCountMax=$KEEPALIVE_COUNT"
    echo "push-verified: keepalive выставлен этой отправке — ServerAliveInterval=$KEEPALIVE_INTERVAL, ServerAliveCountMax=$KEEPALIVE_COUNT" >&2
    echo "push-verified: постоянное место настройки клона — make install-hooks (scripts/hooks/install.sh)" >&2
elif [[ "${transport,,}" == *serveraliveinterval* ]]; then
    echo "push-verified: keepalive уже задан снаружи ($source_of): $transport" >&2
else
    echo "push-verified: ВНИМАНИЕ — транспорт задан снаружи ($source_of) и keepalive в нём НЕТ:" >&2
    echo "  $transport" >&2
    echo "  чужая команда не перебивается (в ней могут быть ключ, порт, прокси)." >&2
    echo "  добавьте в неё: -o ServerAliveInterval=$KEEPALIVE_INTERVAL -o ServerAliveCountMax=$KEEPALIVE_COUNT" >&2
fi

echo "push-verified: отправляю $branch = $local_sha в $remote" >&2

git push "${flags[@]+"${flags[@]}"}" "$remote" "$branch"
push_rc=$?

# КОД ОТПРАВКИ НАЗЫВАЕТСЯ, НО ВЕРДИКТОМ НЕ СЛУЖИТ. Он печатается, потому что
# ненулевой код рядом с подтверждённой ссылкой — отдельный факт (например, отказ
# при обновлении upstream-настройки), и молчать о нём нечестно.
echo "push-verified: код команды отправки — $push_rc (это НЕ вердикт: вердикт ниже, от сервера)" >&2

remote_line="$(git ls-remote "$remote" "refs/heads/$branch" 2>/dev/null)"
ls_rc=$?
if [ "$ls_rc" -ne 0 ]; then
    echo "push-verified: БЕЗ ПРЕДМЕТА — сервер не опрошен ($remote, код ls-remote $ls_rc)." >&2
    echo "  Отправка НЕ подтверждена. Повторить подтверждение: git ls-remote $remote refs/heads/$branch" >&2
    exit 2
fi

remote_sha="$(printf '%s' "$remote_line" | awk 'NR==1 {print $1}')"

if [ "$remote_sha" = "$local_sha" ]; then
    echo "push-verified: ПОДТВЕРЖДЕНО — $remote refs/heads/$branch = $local_sha (спрошено у сервера)"
    exit 0
fi

echo "push-verified: ОТКАЗ — операция НЕ состоялась, хотя команда вернула $push_rc." >&2
echo "  отправляли: $local_sha" >&2
echo "  на сервере: ${remote_sha:-ссылки НЕТ}" >&2
echo "  Ссылка на сервере не равна отправленной — это и есть признак того, что" >&2
echo "  пакет не доехал. Повторить отправку; разошлось после чужой записи —" >&2
echo "  разбирать расхождение, а не пересылать поверх." >&2
exit 1
