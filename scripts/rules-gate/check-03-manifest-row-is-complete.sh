#!/usr/bin/env bash
# check-03 — СТРОКА МАНИФЕСТА ПОЛНА: у КАЖДОГО правила названы все три предмета.
#
# ЧТО УТВЕРЖДАЕТ. Каждая строка живой таблицы `.claude/rules/MANIFEST.md` называет
# действие, которым правило включается; то, чем соблюдение держится; и агентов, за
# которыми правило закреплено предзагрузкой. Все три ячейки непусты. Прочерк,
# неразрывный пробел, пустой код-спан и `TODO` пустотой считаются — человек читает
# их как пустоту, и распознаватель обязан читать так же.
#
# ТРЕТЬЯ ЯЧЕЙКА — ПРАВКА 2026-09-17, И ОНА НЕСУЩАЯ, А НЕ ОФОРМИТЕЛЬСКАЯ. По решению
# владельца корпус не грузится никому автоматически: правило попадает в окно только
# через агента, у которого оно перечислено во frontmatter `skills:`. Строка, не
# назвавшая ни одного агента, объявляет правило, которого НЕ ПРОЧТЁТ НИКТО, — и
# отличить такое правило от соблюдаемого по поведению нельзя ничем. Пустота здесь
# дороже прежних двух: те отнимали у человека вход в таблицу, эта отменяет само
# действие правила, ничего не меняя ни в одном файле продукта.
#
# ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ check-01, И ПОЧЕМУ ПРОВЕРОК ДВЕ. check-01 сверяет
# МНОЖЕСТВА: файл без строки и строка без файла. Множества сходятся и при пустых
# ячейках — состав от содержимого ячейки не меняется ни на один файл. То есть
# «полнота строки» из «состав сошёлся» НЕ ВЫВОДИТСЯ, и наоборот: таблица из
# тридцати полностью заполненных строк про несуществующие правила
# удовлетворяет здешнему утверждению целиком.
#
# ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ ПРОВЕРКИ ПРИВЯЗКИ. Здесь судится ТОЛЬКО непустота ячейки:
# названо ли хоть одно имя. Существует ли такой агент, сходится ли перечень с его
# `skills:` и есть ли у правила скилл-ссылка — предмет соседней проверки набора, и
# он отдельный не для симметрии: ячейка, полная имён несуществующих агентов,
# здешнему утверждению удовлетворяет целиком, а правило при этом не грузится
# по-прежнему никому.
#
# ЧТО ИЗМЕНИЛОСЬ 2026-09-13. Проверка звалась «манифест покрывает свод» и сверяла
# каталог `.claude/rulebook/` со строками таблицы. Каталог СНЯТ: его предмета в
# дереве нет, и проверка, которой нечего проверять, отчитывалась беспредметным
# обходом. Сверка множеств при этом никуда не делась — она перешла в check-01
# вместе с новым объявлением состава. Здесь остался предмет, которого у check-01
# нет и быть не может.
#
# ПОЧЕМУ ЯЧЕЙКИ — ПРЕДМЕТ ГЕЙТА, А НЕ ВКУСА. Колонка «включается действием» отвечает
# на вопрос ЧТО ОТНОСИТСЯ К ДЕЛУ, когда ты тронул этот путь: по ней диспетчер
# понимает, чья это область, а ревьюер волны судит, смотрела ли полоса туда, куда
# следовало. Пустая ячейка отнимает у обоих единственный машинно-читаемый вход.
# Колонка «чем соблюдение держится» от раскладки не зависела никогда: правило, за
# которым не стоит ни гейта, ни названного ВСЛУХ «держится вниманием», проверяется
# ничем. Поэтому прочерк считается ПУСТОТОЙ, а не ответом: «держится вниманием»
# пишется словами (`.claude/rules/multi-agent-flow.md` §11 — «называй механизм; если
# механизма нет — так и напиши»). Колонка «закреплено за агентами» — единственное
# ОБЪЯВЛЕНИЕ того, кому правило доезжает: исполнение живёт во frontmatter агента, и
# сверять исполнение не с чем, пока объявления нет.
#
# ИСКЛЮЧЁННЫХ СТРОК НЕТ НИ ОДНОЙ. Прежняя редакция пропускала строку про сам
# `MANIFEST.md`: он лежал в своде, но правилом не считался. Теперь манифест —
# файл корпуса, закреплённый за агентами наравне с прочими, и своя полная строка
# ему нужна ровно как всем. Список прощённых не заводится: каждая запись в нём —
# место, куда пустоту вносят незамеченной.
#
# РАЗБОР ТАБЛИЦЫ — ОБЩИЙ С check-01, файлом `manifest-rows.awk`. Грамматика у
# таблицы одна, и две её копии разошлись бы молча: строка, видимая одной проверке
# и невидимая другой, не дала бы ни красного, ни вопроса. Перечень форм, на
# которых грамматика ловилась противником (фенс, HTML-комментарий, экранированная
# труба, четыре вида «пустой для человека» ячейки), — в шапке разборщика.
#
# ПРЕДПОСЫЛКА И ЕЁ ГРАНИЦА. VOID (код 2) — только когда предмета нет ВОВСЕ:
# каталога `.claude/rules/` в дереве не существует, то есть корпуса здесь нет.
# Снятый манифест и снятая таблица VOID-ом НЕ являются: послабление не выдаётся
# удалением предмета — иначе достаточно было бы стереть таблицу, чтобы гейт
# перестал блокировать отправку, а именно от этого он и заведён.
#
# Коды выхода: 0 — каждая строка полна по всем трём ячейкам; 1 — находка либо
# пустой обход (о таблице не прочитано ничего); 2 — предмета нет.

set -uo pipefail

NAME="check-03-manifest-row-is-complete"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PARSER="$SCRIPT_DIR/manifest-rows.awk"

gate_pass()   { echo "[PASS] $NAME${1:+ — $1}"; }
gate_fail()   { echo "[FAIL] $NAME${1:+ — $1}" >&2; }
gate_void()   { echo "[VOID] $NAME${1:+ — $1}" >&2; }   # «проверять нечего» ≠ «находок 0»
gate_census() { echo "[CENSUS] $NAME: $1"; }

# Корень воркспейса. `RULES_GATE_ROOT` переопределяет его — этим пользуется ТОЛЬКО
# inject.sh, чтобы прогонять гейт по временному дереву с внесённым дефектом и не
# трогать рабочее (`.claude/rules/testing.md` §«Гейт на класс» п.2). Разборщик
# берётся из СВОЕГО каталога, а не из песочницы: предмет инъекции — манифест, а не
# текст проверки.
if [ -n "${RULES_GATE_ROOT:-}" ]; then
    WS="$(cd "$RULES_GATE_ROOT" 2>/dev/null && pwd)" || {
        gate_void "RULES_GATE_ROOT=$RULES_GATE_ROOT не открывается — читать неоткуда"
        exit 2
    }
else
    WS="$(cd "$SCRIPT_DIR/../.." && pwd)"
fi

RULES_REL=".claude/rules"
MAN_REL="$RULES_REL/MANIFEST.md"
MAN="$WS/$MAN_REL"

# ── предпосылка 0: разборщик таблицы на месте ────────────────────────────────
# Его отсутствие — «не выполнилось», а не «находок 0»: без него строк ноль, и
# «каждая строка полна» стало бы истинным на пустом множестве.
if [ ! -f "$PARSER" ]; then
    gate_census "разбор не запускался: $PARSER не существует; строк манифеста 0, строк таблицы 0"
    gate_void "разборщика таблицы manifest-rows.awk нет рядом с проверкой — читать таблицу нечем; это НЕ «находок 0»"
    exit 2
fi

# ── предпосылка 1: корпус в этом дереве есть ─────────────────────────────────
if [ ! -d "$WS/$RULES_REL" ]; then
    gate_census "каталога $RULES_REL нет; строк манифеста 0, строк таблицы 0"
    gate_void "каталога $RULES_REL в $WS нет — корпуса правил в этом дереве не существует, предмета у проверки нет"
    exit 2
fi

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

man_lines=0
: > "$TMP/rows"
if [ -f "$MAN" ]; then
    man_lines="$(wc -l < "$MAN" | tr -d ' ')"
    LC_ALL=C awk -f "$PARSER" "$MAN" > "$TMP/rows"
fi

rows_n="$(wc -l < "$TMP/rows" | tr -d ' ')"
full_n="$(awk -F'\t' '$3 == "A" && $4 == "H" && $5 != ""' "$TMP/rows" | wc -l | tr -d ' ')"
# Имена агентов НЕ разбираются: здешний предмет — непустота ячейки. Число имён
# печатается переписью, чтобы «названы агенты» было отличимо от «названо слово».
bound_n="$(awk -F'\t' '$5 != "" { s += split($5, a, / · /) } END { print s + 0 }' "$TMP/rows")"

# ── ПЕРЕПИСЬ ОБЪЁМА ──────────────────────────────────────────────────────────
# Печатается ВСЕГДА и до вердикта: «ноль находок» обязано быть отличимо от «ноль
# прочитанного» (`.claude/rules/testing.md` §«Гейт на класс» п.3).
gate_census "$MAN_REL — строк $man_lines, строк таблицы разобрано $rows_n, ячеек осмотрено $((rows_n * 3)), строк со всеми тремя названными $full_n, закреплений названо $bound_n"

# ── ПУСТОЙ ОБХОД — НАХОДКА, А НЕ УСПЕХ ───────────────────────────────────────
if [ ! -f "$MAN" ]; then
    gate_fail "$MAN_REL в дереве нет при существующем каталоге правил — единственное объявление состава снято; судить полноту строк не по чему, и это находка, а не отсутствие предмета"
    exit 1
fi
if [ "$rows_n" -eq 0 ]; then
    gate_fail "в $MAN_REL не разобрано НИ ОДНОЙ строки таблицы — таблица снята либо её форма сменилась; «каждая строка полна» на пустом множестве истинно by construction, поэтому здесь это находка, а не успех"
    exit 1
fi

# ── ПОЛНОТА КАЖДОЙ СТРОКИ ────────────────────────────────────────────────────
#
# НАЗЫВАЮТСЯ ВСЕ ПУСТЫЕ ЯЧЕЙКИ СТРОКИ, А НЕ ПЕРВАЯ. Находка, назвавшая одну
# половину из трёх, посылает чинить треть: правку внесут, гейт покраснеет снова, и
# круг оплачен зря. Поэтому `miss` копится, а не возвращается на первом попадании.
rc=0
incomplete=0
while IFS=$'\t' read -r ln name a h bind; do
    [ -n "${name:-}" ] || continue
    miss=""
    [ "$a" = "-" ] && miss="не названо действие, которым правило включается"
    [ "$h" = "-" ] && miss="${miss:+$miss; }не названо, чем соблюдение держится"
    # Пустота четвёртой ячейки приведена РАЗБОРЩИКОМ: прочерк, `TODO`, пустой
    # код-спан и неразрывный пробел доезжают сюда пустой строкой. Второго списка
    # заглушек здесь нет намеренно — он разошёлся бы с первым молча.
    [ -z "${bind:-}" ] && miss="${miss:+$miss; }не названо, за какими агентами правило закреплено — его не прочтёт никто"
    if [ -n "$miss" ]; then
        if [ "$incomplete" -eq 0 ]; then
            echo "  строка манифеста называет правило, но не называет своих предметов:" >&2
            incomplete=1
        fi
        echo "    $MAN_REL:$ln — $name: $miss" >&2
        rc=1
    fi
done < "$TMP/rows"

if [ "$rc" -ne 0 ]; then
    gate_fail "строк таблицы $rows_n, из них полных $full_n — остальные объявляют правило и молчат о его предметах"
    exit 1
fi

gate_pass "каждая строка таблицы полна: строк $rows_n, у каждой названы действие, держатель и агенты ($bound_n закреплений)"
exit 0
