#!/usr/bin/env bash
# shellcheck disable=SC2016
#   Вносимые строки — markdown: обратные кавычки в них разметка, а не подстановка
#   команды. Одинарные кавычки здесь намеренны на весь файл, как и в inject.sh.
# ЧАСТЬ инъекции набора: доказательство check-11 «адрес правила и скила-привязки
# резолвится там, где написан» по трём осям находки и трём законным близнецам.
#
# Оси находки различны по СУЩЕСТВУ, а не по букве: новая поломка (имени нет в
# объявленном долге), рост долга (имя есть, вхождений стало больше) и зажившая
# запись (в долге числится, в дереве не осталось). Третья — самоистечение: база
# не вправе пережить свой предмет, иначе гейт зеленеет на записи, которой нечего
# исключать.
#
# Файл ПОДКЛЮЧАЕТСЯ (`.`) из `inject.sh` и пользуется его оснасткой.
if [ "${BASH_SOURCE[0]}" = "$0" ]; then
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — ЧАСТЬ инъекции, а не самостоятельная проба." >&2
    echo "       Запускать: bash scripts/rules-gate/inject.sh" >&2
    exit 2
fi
for _i11_fn in sandbox capture assert_code assert_fixture_changed sandbox_digest; do
    command -v "$_i11_fn" >/dev/null 2>&1 && continue
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — оснастки inject.sh нет: функция" \
         "«$_i11_fn» не определена" >&2
    exit 2
done
unset -v _i11_fn
if [ -z "${GATE:-}" ] || [ ! -d "$GATE" ] || [ -z "${TMP:-}" ] || [ ! -d "$TMP" ]; then
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — \$GATE либо \$TMP не определён" >&2
    exit 2
fi

C11=check-11-rule-address-exists-as-written.sh
BL11="$GATE/rule-address-baseline.txt"

# ЖЕРТВА И ЗАКОННАЯ ЦЕЛЬ ВЫВОДЯТСЯ ИЗ ДЕРЕВА, а не выписываются именем: имя в
# коде рассыпалось бы вместе с раскладкой, а предмет осей от него не зависит.
V11=""
while IFS= read -r _v; do
    [ -f "$_v" ] || continue
    V11=".claude/agents/$(basename "$_v")"; break
done < <(printf '%s\n' "$WS"/.claude/agents/*.md | LC_ALL=C sort)
unset -v _v
LIVE_RULE=""; LIVE_SKILL=""
while IFS= read -r _r; do
    [ -f "$_r" ] || continue
    LIVE_RULE="$(basename "$_r")"
    [ -e "$WS/.claude/skills/rule-${LIVE_RULE%.md}/SKILL.md" ] || { LIVE_RULE=""; continue; }
    LIVE_SKILL="rule-${LIVE_RULE%.md}"; break
done < <(printf '%s\n' "$WS"/.claude/rules/*.md | LC_ALL=C sort)
unset -v _r
if [ -z "$V11" ] || [ -z "$LIVE_SKILL" ]; then
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — в дереве нет агента либо нет правила" \
         "с парным скилом-ссылкой: ни дефект вписать некуда, ни законную цель взять" >&2
    exit 2
fi
# Имя из объявленного долга берётся ИЗ САМОЙ БАЗЫ: выписанное здесь разошлось бы
# с ней молча ровно в тот день, когда долг сократят.
DEBT_SKILL="$(awk '$2=="Skill"{print $3; exit}' "$BL11")"
if [ -z "$DEBT_SKILL" ]; then
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — в объявленном долге нет ни одной" \
         "записи формы Skill: ось «долг вырос» беспредметна" >&2
    exit 2
fi

# ── ось A: НОВАЯ ПОЛОМКА — имени нет в объявленном долге ─────────────────────
d="$(sandbox i11_new)"
printf '\n| правишь что-нибудь | `Skill rule-takogo-skila-net-v-dereve` | § |\n' >> "$d/$V11"
capture "$d" "$C11"
assert_code 1 "ДЕФЕКТ: вызов скила, которого в дереве нет и в долге не объявлено — краснеет"

# ── ось A2: та же поломка ДРУГОЙ ЗАКОННОЙ ФОРМОЙ — путь к файлу правила ──────
# Распознаватель, знающий лишь одну форму записи адреса, молчит на остальных, и
# это слепая зона, а не успех.
d="$(sandbox i11_new_path)"
printf '\nНорма — `.claude/rules/takogo-pravila-net-v-dereve.md` §«Раздел».\n' >> "$d/$V11"
capture "$d" "$C11"
assert_code 1 "ДЕФЕКТ: путь к правилу, которого нет — краснеет той же осью"

# ── ось B: ДОЛГ ВЫРОС — имя объявлено, вхождений стало больше ────────────────
d="$(sandbox i11_grew)"
printf '\n| ещё одно условие | `Skill %s` | § |\n' "$DEBT_SKILL" >> "$d/$V11"
capture "$d" "$C11"
assert_code 1 "ДЕФЕКТ: объявленный долг вырос на одно вхождение — краснеет"

# ── ось C: ЗАЖИВШАЯ ЗАПИСЬ — в долге числится, в дереве не осталось ──────────
# Подменная база — законный шов проверки: настоящую база сокращает отдельная
# полоса, и ждать её, чтобы доказать самоистечение, значило бы не доказать его.
d="$(sandbox i11_healed)"
cp "$BL11" "$TMP/bl11.healed.txt"
printf '1 Skill rule-etogo-imeni-v-dereve-net\n' >> "$TMP/bl11.healed.txt"
capture "$d" "$C11" RULES_GATE_RULE_ADDRESS_BASELINE="$TMP/bl11.healed.txt"
assert_code 1 "ДЕФЕКТ: запись долга, которой нечего исключать — краснеет и требует убрать её"

# ── БЛИЗНЕЦ 1: те же две формы, но цель в дереве ЕСТЬ ────────────────────────
d="$(sandbox i11_twin_live)"; b="$(sandbox_digest "$d")"
printf '\n| правишь что-нибудь | `Skill %s` | § |\nНорма — `.claude/rules/%s` §«Раздел».\n' \
    "$LIVE_SKILL" "$LIVE_RULE" >> "$d/$V11"
assert_fixture_changed "$d" "$b" "близнец: ссылка на существующие скил и правило"
capture "$d" "$C11"
assert_code 0 "БЛИЗНЕЦ: те же формы на СУЩЕСТВУЮЩУЮ цель — молчит"

# ── БЛИЗНЕЦ 2: тот же висячий адрес В АРХИВЕ ────────────────────────────────
# Архив называет координаты, верные на момент снятия, и живым предписанием не
# является. Гейт, краснеющий и здесь, требовал бы чинить историю.
d="$(sandbox i11_twin_archive)"; b="$(sandbox_digest "$d")"
printf '\n`Skill rule-takogo-skila-net-v-dereve` — координата на момент снятия.\n' \
    >> "$d/.claude/backup/README.md"
assert_fixture_changed "$d" "$b" "близнец: тот же висячий адрес в архиве"
capture "$d" "$C11"
assert_code 0 "БЛИЗНЕЦ: висячий адрес в объявленном архиве — молчит"

# ── ось D: РОЛЬ ПРОИЗВОДИТЕЛЯ — ТРИ ПАРЫ, В КАЖДОЙ РОВНО ОДИН ОТЛИЧАЮЩИЙСЯ ФАКТ
#
# До 2026-09-21 производители фикстур исключались закрытым списком `inject*` и
# `prove.sh`. Список — не свойство роли: полоса завела производителя той же роли
# под третьим именем, и гейт покраснел на координате, правилом не являющейся.
# Роль выведена тремя барьерами (`rule-address-refs.py`, `builds_fixture_tree`),
# и каждый доказывается своей парой. Пары СТРОЯТСЯ ОДНОЙ ФУНКЦИЕЙ с двумя
# параметрами — иначе «отличие в одном факте» держалось бы тем, что автор
# аккуратно переписал вторую фикстуру.
#
# РОЛЬ САМОГО ЭТОГО ФАЙЛА ВЫДАНА НАМЕРЕННО, А НЕ СЛУЧАЙНО. Строки ниже создают
# `"$1/.claude/hooks/…"` ЛИТЕРАЛЬНЫМ путём, а не через переменную: этим файл
# получает роль производителя по тому же признаку, что и все прочие, и его
# собственные синтетические имена (`rule-takogo-skila-net-v-dereve` и соседи) не
# считаются висячими адресами. Спрячь путь в переменную — роль пропадёт, и гейт
# покраснеет на самой инъекции.
I11_ADDR=".claude/rules/probe-roli-net-v-dereve.md"

# i11_role_file <каталог> <имя файла> <первая строка> <префикс перед актом>
# Содержимое у всех фикстур роли ОДНО И ТО ЖЕ и строится здесь: что именно
# отличает пару, видно по её аргументам, а не по глазам читающего.
i11_role_file() {
    mkdir -p "$1/.claude/hooks"
    {   printf '%s\n' "$3"
        printf 'd="$(mktemp -d)"\n'
        printf '%smkdir -p "$d/.claude/rules"\n' "$4"
        printf 'echo "норма — %s"\n' "$I11_ADDR"
    } > "$1/.claude/hooks/$2"
}
I11_SCRIPT=zz-proba-roli-proizvoditelya.sh
I11_MARKUP=zz-proba-roli-proizvoditelya.md

# ── ПАРА 1 (барьер 3): создающий акт в КОММЕНТАРИИ против него же в КОДЕ ─────
# Отличие фикстур — префикс `# ` на одной строке, и больше ничего.
d="$(sandbox i11_role_prose)"
i11_role_file "$d" "$I11_SCRIPT" '#!/usr/bin/env bash' '# '
capture "$d" "$C11"
assert_code 1 "ДЕФЕКТ: создающий акт в КОММЕНТАРИИ роли не даёт — висячий адрес краснеет"

d="$(sandbox i11_role_code)"; b="$(sandbox_digest "$d")"
i11_role_file "$d" "$I11_SCRIPT" '#!/usr/bin/env bash' ''
assert_fixture_changed "$d" "$b" "близнец: тот же файл, создающий акт в ИСПОЛНЯЕМОЙ строке"
capture "$d" "$C11"
assert_code 0 "БЛИЗНЕЦ: файл СОЗДАЁТ дерево .claude/ — координата в нём вход, а не адрес; имя роли не решает"

# ── ПАРА 2 (барьер 1): роль есть только у того, что ИСПОЛНЯЕТСЯ ──────────────
# Отличие фикстур — ПЕРВАЯ СТРОКА: shebang либо обычный комментарий. Создающий
# акт в обеих стоит в исполняемой строке, координата в обеих одна и та же.
d="$(sandbox i11_role_noshebang)"
i11_role_file "$d" "$I11_SCRIPT" '# пояснение, а не запуск' ''
capture "$d" "$C11"
assert_code 1 "ДЕФЕКТ: без shebang файл не исполняется — роли производителя нет, адрес краснеет"

d="$(sandbox i11_role_shebang)"; b="$(sandbox_digest "$d")"
i11_role_file "$d" "$I11_SCRIPT" '#!/usr/bin/env bash' ''
assert_fixture_changed "$d" "$b" "близнец: та же фикстура с shebang первой строкой"
capture "$d" "$C11"
assert_code 0 "БЛИЗНЕЦ: shebang — файл исполняется, роль выдана, молчит"

# ── ПАРА 3 (барьер 1 В РАЗМЕТКЕ): воспроизведение найденного дефекта ────────
# Фикстура в РАЗМЕТКЕ, а не в оболочке, и это несущее: в markdown `#` — заголовок,
# а не комментарий, поэтому барьер 3 там не значит ничего и всю прозу пришлось бы
# считать исполняемой. КРАСНОЕ ЗДЕСЬ ДАЁТ БАРЬЕР 1 (строки запуска в фикстуре
# нет), и подписано это так намеренно: пара воспроизводит найденный дефект, а
# барьер 2 держит СВОЯ пара ниже. Измерено 2026-09-22 на предыдущей редакции: у агента
# ломается одна строка `skills:` — код 1; в тот же файл дописывается ОДНА СТРОКА
# ПРОЗЫ с командой копирования каталога — код 0, перепись падает с 315 по 22 до
# 306 по 22, сломанная привязка жива. Ниже создающий акт стоит прозой в ОБЕИХ
# фикстурах, и отличаются они ровно ИМЕНЕМ скила: висячее либо живое.
I11_PROSE='Опыт ставится так: копируем каталог правил — `cp -a "$WS/.claude/rules" "$dir/.claude/"` — и прогон.'

d="$(sandbox i11_markup_dangling)"
printf '\n%s\n\n| правишь что-нибудь | `Skill rule-razmetka-sebya-ne-izymaet` | § |\n' \
    "$I11_PROSE" >> "$d/$V11"
capture "$d" "$C11"
assert_code 1 "ДЕФЕКТ: проза с создающим актом роли разметке не даёт — висячая привязка краснеет"

d="$(sandbox i11_markup_live)"; b="$(sandbox_digest "$d")"
printf '\n%s\n\n| правишь что-нибудь | `Skill %s` | § |\n' \
    "$I11_PROSE" "$LIVE_SKILL" >> "$d/$V11"
assert_fixture_changed "$d" "$b" "близнец: та же проза, скил СУЩЕСТВУЮЩИЙ"
capture "$d" "$C11"
assert_code 0 "БЛИЗНЕЦ: та же проза с создающим актом при живом скиле — молчит; краснело ИМЯ, а не проза"

# ── ПАРА 4 (барьер 2): РАЗМЕТКА НЕ СКРИПТ, ЧТО БЫ НИ СТОЯЛО В ПЕРВОЙ СТРОКЕ ──
#
# Единственный отличающийся факт — РАСШИРЕНИЕ файла. Каталог один и тот же,
# содержимое строит одна функция, строка запуска стоит в ОБЕИХ фикстурах,
# создающий акт в обеих исполняемый. Поэтому красное приходит от формата и ни от
# чего другого — и барьер 2 доказан отдельно от барьера 1, а не вместе с ним.
#
# ПОЧЕМУ ЭТА ПАРА ВООБЩЕ ЕСТЬ. До 2026-09-22 барьер 2 был перечнем каталогов, и
# снятие его двух строк инъекция не ловила ВОВСЕ: 403 из 403, код 0. Барьер,
# снятие которого не ловится ничем, барьером не является. Каталог фикстуры здесь
# НЕ из домов корпуса — `.claude/hooks/`, — и это тоже несущее: барьер судит
# формат, а не место, и пара обязана это показывать.
d="$(sandbox i11_markup_shebang)"
i11_role_file "$d" "$I11_MARKUP" '#!/usr/bin/env bash' ''
capture "$d" "$C11"
assert_code 1 "ДЕФЕКТ: разметка со строкой запуска скриптом не становится — роли нет, адрес краснеет"

d="$(sandbox i11_script_shebang)"; b="$(sandbox_digest "$d")"
i11_role_file "$d" "$I11_SCRIPT" '#!/usr/bin/env bash' ''
assert_fixture_changed "$d" "$b" "близнец: тот же каталог и то же содержимое, формат скрипта"
capture "$d" "$C11"
assert_code 0 "БЛИЗНЕЦ: то же самое в формате скрипта — роль выдана, молчит; решает ФОРМАТ, не место"

# ── ПРЕДПОСЫЛКА: файлов оснастки нет — VOID, а не успех ─────────────────────
d="$(sandbox i11_void)"
rm -rf "$d/.claude" "$d/CLAUDE.md"
capture "$d" "$C11"
assert_code 2 "ПРЕДПОСЫЛКА: файлов оснастки нет — VOID, а не успех"
