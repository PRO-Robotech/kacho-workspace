#!/usr/bin/env bash
# check-11 — АДРЕС ПРАВИЛА И СКИЛА-ПРИВЯЗКИ РЕЗОЛВИТСЯ ТАМ, ГДЕ ОН НАПИСАН.
#
# НОМЕР 11, А НЕ 10, И ЭТО НЕ КОСМЕТИКА. Проверка заведена 2026-09-21 19:23
# (06453e38) десятым номером; десятым же номером восемью часами раньше (11:19,
# 59cb5c9f) заведён сосед `check-10-owner-escalation-list-is-closed.sh`. В дереве
# каждой полосы номер был уникален, и увидеть столкновение могло только сведение.
# Цена столкновения не косметическая: прибор `measure-monotonicity.sh` связывает
# пробу с проверкой ПО НОМЕРУ, и на совпавшем номере проба соседа прогонялась по
# этой проверке, печатая о ней положительное утверждение («монотонна»), которого
# никто не измерял. Номер уступает ПОЗЖЕ ПРИШЕДШИЙ — признак, выводимый из дерева
# (даты коммитов), а не из предпочтения.
#
# Существо, разборщик и объявленный долг — в соседних файлах: `rule-address-refs.py`
# (шапка объясняет, чем это отличается от check-07 и почему одного не хватило) и
# `rule-address-baseline.txt` (откуда взялся остаток и какой исход у каждого имени).
#
# Корень и база переопределяются средой: инъекция гоняет проверку на КОПИИ дерева,
# и без обоих швов ось «запись базы пережила свой предмет» была бы недоказуема.
#
# КОРЕНЬ ВЫВОДИТСЯ ИЗ СВОЕГО РАСПОЛОЖЕНИЯ, А НЕ ИЗ ТЕКУЩЕГО КАТАЛОГА (2026-09-22).
# Здесь стояло `root="${RULES_GATE_ROOT:-$(git rev-parse --show-toplevel)}"`, и
# ИЗМЕРЕНО: этот самый файл, запущенный с cwd в соседнем worktree полосы, судил
# ЧУЖОЕ дерево — «строк 85 613» против собственных «85 763» — и выходил НУЛЁМ.
# Из постороннего репозитория выходило 2, то есть безопасно; опасен ровно случай
# соседней полосы, где `.claude/` и `scripts/` на месте. Это тот же класс, что
# «полоса получает чужой вердикт»: вердикт относится к дереву, которого автор
# правки не трогал, и выглядит зелёным. Образец решения взят у соседей набора —
# `check-02:196` и `scripts/tooling-gate/check-12:65`: оба выводят корень из
# `BASH_SOURCE` и, запущенные с чужого cwd, отчитались о СВОЁМ дереве.
#
# КОРЕНЬ ПЕЧАТАЕТСЯ ПЕРЕПИСЬЮ. Без этого подмена не видна и постфактум: два
# прогона одного файла давали разные числа, и ни один не называл, какое дерево
# обошёл. Признак проверяется парой: запуск из своего и из чужого cwd обязан дать
# одинаковые числа И одинаковый напечатанный корень.
#
# САМОИМЯ ПЕЧАТАЕТСЯ НЕ ЛИТЕРАЛОМ, А ВЫВОДИТСЯ ИЗ ИМЕНИ ЭТОГО ФАЙЛА. Разборщик
# общий, зовут его отсюда, и своего номера он знать не может; вписанный в него
# литерал пережил бы переномерацию молча — файл `check-11-…` печатал бы
# `[PASS] check-10 …`, и читающий вердикт пошёл бы искать несуществующий гейт.
# Признак проверяется переименованием, а не чтением: имя в выводе обязано меняться
# вместе с именем файла.
set -euo pipefail
SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
root="${RULES_GATE_ROOT:-$(cd "$SELF_DIR/../.." && pwd)}"
exec python3 "$SELF_DIR/rule-address-refs.py" \
    --gate "$(basename "${BASH_SOURCE[0]}" .sh)" \
    --root "$root" \
    --baseline "${RULES_GATE_RULE_ADDRESS_BASELINE:-$SELF_DIR/rule-address-baseline.txt}"
