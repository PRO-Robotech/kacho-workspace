#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Предмет: ОБЪЁМ и ФОРМА корпуса `.claude/rules/*.md` как целого.

Объём и форма читаются ОДНИМ обходом, потому что оба — свойства корпуса, а не
файла: объём складывается, а строка-норма формы «id · императив · держатель ·
red: признак» проверяется у каждой. Гейт называет ось, а не «что-то не так».

ОБЪЁМ БОЛЬШЕ НЕ БЛОКИРУЕТ — 2026-09-22, и это не послабление, а смена предмета.
Блокирующим был предел на СУММУ корпуса. Замер показал, что сумму не грузит
НИКТО: решением владельца 2026-09-17 корпус снят с автозагрузки, и агент
получает ровно перечисленное в своём `skills:`. На `978cc66c`: максимум по
агенту 85 559 символов при сумме 197 784 — наибольшая доля корпуса, доезжающая
одному, 33,5 %; медиана 49 585. Предел судил величину без адресата.

Хуже: он анти-коррелирован с вредом. Полоса восстановления координат добавила в
СУММУ 31 776 символов и связующему агенту `rpc-implementer` — НОЛЬ (ни одно её
правило за ним не закреплено); соседняя доливка добавила 37 032 в сумму и до
+26 238 в реальную загрузку. Сумма наказывала текст, не доходящий до края, и не
замечала роста, доходящего до всех.

Поэтому объём здесь ОСТАЁТСЯ — наблюдением с напечатанным числом, а не барьером:
он ловит рост, у которого адресата пока нет, но который его получит, как только
правило закрепят ещё за кем-то. Решение принимает величина с адресатом —
`check-13-agent-window-load.sh`, и у неё порог сегодня НЕ ЗАДАН осознанно:
выводить его не из чего (четыре основания проверены и отвергнуты), а число,
притворяющееся выведенным, дороже честно отсутствующего.

ПРЕЖНИЙ ПРЕДЕЛ 200 000 ОСТАЁТСЯ В ПЕЧАТИ КАК ОРИЕНТИР, и его происхождение
названо прямо: он был ВЫБРАН (решение владельца 2026-09-19), а не выведен. Ровно
этим он и дорог: число, ни из чего не следующее, полсессии стоило работы, и
сохранить его молча значило бы повторить.

ОТКАЗ (код 2) СОХРАНЁН И НЕ СМЯГЧЁН: обход, увидевший меньше 17 файлов правил
либо ни одной строки-нормы, беспредметен — он судит не объём, а ПРОЧИТАННОСТЬ
дерева, и на нём форма строки-нормы проверялась бы по недочитанному корпусу.
"""
import glob
import sys

# ОРИЕНТИР, а не барьер: число выбрано (владелец, 2026-09-19), не выведено.
REFERENCE = 200_000
# ПОРОГ ПРОЧИТАННОСТИ — судит другое и держится: см. шапку.
FLOOR_FILES = 17


def rows_of(path):
    with open(path, encoding='utf-8') as fh:
        return [l.rstrip('\n') for l in fh if ' · ' in l]


def main():
    files = sorted(glob.glob('.claude/rules/*.md'))
    total = sum(len(open(f, encoding='utf-8').read()) for f in files)
    rows = [(f, l) for f in files for l in rows_of(f)]

    print('осмотрено файлов правил: %d; строк-норм: %d; объём: %d'
          % (len(files), len(rows), total))

    if len(files) < FLOOR_FILES or not rows:
        print('ОТКАЗ — файлов правил %d (ожидалось не меньше %d), строк-норм %d: обход'
              ' усечён, сумма меньше настоящей, вердикт о потолке беспредметен'
              % (len(files), FLOOR_FILES, len(rows)))
        return 2

    rc = 0
    # НАБЛЮДЕНИЕ, А НЕ НАХОДКА. Печатается в обе стороны — и когда ориентир
    # перейдён, и когда нет: строка, появляющаяся только при перевесе, читается
    # как барьер, которым она больше не является.
    if total > REFERENCE:
        print('НАБЛЮДЕНИЕ объём — %d символов, прежний ориентир %d перейдён на %d;'
              ' НЕ блокирует: сумму не грузит никто, решает загрузка окна агента'
              ' (check-13)' % (total, REFERENCE, total - REFERENCE))
    else:
        print('НАБЛЮДЕНИЕ объём — %d символов, до прежнего ориентира %d остаётся %d;'
              ' ориентир не блокирует ни в какую сторону'
              % (total, REFERENCE, REFERENCE - total))

    # ── форма строки-нормы: каждая ось названа отдельно ──────────────────────
    def red(axis, predicate):
        nonlocal rc
        hits = [(f, l) for f, l in rows if predicate(l)]
        if not hits:
            return
        rc = 1
        print('КРАСНОЕ %s — строк %d' % (axis, len(hits)))
        for f, l in hits[:5]:
            print('  %s: %s' % (f, l[:120]))

    def field(l, i):
        parts = l.split(' · ')
        return parts[i].strip() if len(parts) > i else ''

    red('строка без поля red:', lambda l: 'red:' not in l)
    red('нечётный backtick', lambda l: l.count('`') % 2 == 1)
    red('пустой императив (поле 2)', lambda l: field(l, 1) in ('—', ''))
    red('пустой держатель (поле 3)', lambda l: field(l, 2) in ('—', ''))
    red('пустой признак красноты', lambda l: l.rstrip().endswith('red: —'))
    # «держится» — слово отчёта о себе, а не императив: норма либо несёт
    # названный механизм в поле 3, либо стоит в долге с `ЗАВЕСТИ`.
    held = [(f, l) for f, l in rows if 'держится' in l]
    if held:
        rc = 1
        print('КРАСНОЕ слово «держится» вместо названного механизма — строк %d' % len(held))
        for f, l in held[:5]:
            print('  %s: %s' % (f, l[:120]))
    return rc


if __name__ == '__main__':
    sys.exit(main())
