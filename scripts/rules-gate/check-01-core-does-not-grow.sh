#!/usr/bin/env bash
# check-01 — ЯДРО НЕ РАСТЁТ: в `.claude/rules/` лежит ровно объявленный набор.
#
# ЧТО УТВЕРЖДАЕТ. Множество файлов каталога ядра побайтово совпадает с множеством
# имён, объявленных в `.claude/rulebook/MANIFEST.md` §«Ядро». Лишний файл и
# недостающий — ОБЕ находки, и обе печатаются координатой.
#
# ПОЧЕМУ В ОБЕ СТОРОНЫ. Совпадение ЧИСЛА не доказывает ничего: множества равной
# мощности бывают разными, и ровно так каталог расходится с объявлением молча.
# Лишний файл возвращает свою цену в окно КАЖДОГО агента волны; недостающий
# означает, что правило ядра пропало, а окно при этом выглядит здоровым.
#
# ПОЧЕМУ ЭТО ВООБЩЕ ГЕЙТ, А НЕ АБЗАЦ. Раскладка «ядро + rulebook» выбрана
# замером: преамбула 368 600 токенов вместо 1 988 800. Одна невнимательная правка
# возвращает четверть окна каждому агенту — и не проявляется НИЧЕМ: прогон
# зелёный, поведение прежнее, дороже стало только всё. Заметить это без
# исполняемого вопроса к дереву нечем (`testing.md` §«Гейт на класс»).
#
# ИСТОЧНИК ИСТИНЫ ОДИН — МАНИФЕСТ. Перечень ядра здесь НЕ выписан: выписанный
# список есть второе место об одном предмете, и расходится он в ту сторону, где
# гейт перестаёт ловить, — правило перенесли, список остался, находок ноль
# (`doc-truthfulness` §«Два места об одном предмете»). Отсюда следствие, которое
# надо назвать прямо, а не подразумевать.
#
# ЧЕГО ЭТА ПРОВЕРКА НЕ ДЕРЖИТ. Она не запрещает ОБЪЯВИТЬ пятое правило ядром: тот,
# кто допишет имя в §«Ядро» и положит файл, получит зелёное. Держится ею другое —
# невозможность разойтись МОЛЧА: рост ядра становится правкой манифеста, видимой
# в диффе рядом с фразой «Ядро не растёт», то есть решением человека, а не
# побочным эффектом чужой правки. Гейта на «решение принято верно» здесь нет и
# быть не может.
#
# ПРЕДПОСЫЛКА ПРОВЕРКИ (исход VOID, код 2): в дереве есть каталог `.claude/rules/`
# И манифест с §«Ядро». Нет любого из двух — раскладки в этом дереве не
# существует, сверять не с чем, и это НЕ «находок 0». На стволе до посадки этой
# линии проверка обязана давать именно 2.
#
# ПУСТОЕ ОБЪЯВЛЕНИЕ — НАХОДКА, А НЕ VOID, и это антимаска. Манифест на месте, но
# §«Ядро» не называет ни одного правила — предмет есть, испорчено само
# объявление. Отдай проверка здесь VOID, и выпотрошенная секция стала бы способом
# погасить гейт, не роняя отправку.
#
# ЕДИНИЦА СЧЁТА — ЗАПИСЬ КАТАЛОГА НА ДИСКЕ, а не запись индекса git: ядро читает
# загрузчик, и читает он диск. Поэтому файл, скрытый от git через `.gitignore`,
# из-под наблюдения НЕ уходит — он остаётся находкой и называется отдельно: в
# свежем клоне его нет, то есть ядро различается между машинами.
#
# ЗАПИСЬЮ СЧИТАЕТСЯ И СИМВОЛЬНАЯ ССЫЛКА, и это правка по находке противника
# (2026-09-07). Прежняя редакция собирала набор через `find -type f`, а `-type f`
# ссылок не видит ВОВСЕ — ни как файл, ни как подкаталог. Замер на временной
# копии: живая ссылка `.claude/rules/testing.md -> ../rulebook/testing.md`,
# 1326 читаемых через неё строк, вердикт гейта — «прочитано файлов ядра 3 …
# лишних 0, недостающих 0», код 0. То есть шапка объявляла единицей счёта диск, а
# разбор считал подмножество диска, и расхождение шло в МОЛЧАЛИВУЮ сторону
# (`testing.md` §«Гейт на класс», п.7: форма, которой распознаватель не знает, не
# даёт ни красного, ни зелёного — она даёт невидимость). Git такую запись хранит
# (режим 120000), значит она переживает клон и молчала бы на каждой машине.
#
# Коды выхода: 0 — осмотрено N, находок 0; 1 — находка либо пустой обход;
# 2 — предмета нет (каталога ядра либо манифеста в этом дереве не существует).

set -uo pipefail

NAME="check-01-core-does-not-grow"

# Корень воркспейса. `RULES_GATE_ROOT` переопределяет его — этим пользуется
# ТОЛЬКО inject.sh, чтобы прогнать гейт по временному дереву с внесённым дефектом
# и не тронуть рабочее (`gate-authoring` §Инъекция).
if [ -n "${RULES_GATE_ROOT:-}" ]; then
    WS="$(cd "$RULES_GATE_ROOT" 2>/dev/null && pwd)" || WS=""
else
    WS="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." 2>/dev/null && pwd)" || WS=""
fi

gate_pass()   { echo "[PASS] $NAME${1:+ — $1}"; }
gate_fail()   { echo "[FAIL] $NAME${1:+ — $1}" >&2; }
gate_void()   { echo "[VOID] $NAME${1:+ — $1}" >&2; }   # «сверять не с чем» ≠ «находок 0»
gate_census() { echo "[CENSUS] $NAME: $1"; }

CORE_DIR="$WS/.claude/rules"
MANIFEST="$WS/.claude/rulebook/MANIFEST.md"

# ── предпосылка 1: каталог ядра ──────────────────────────────────────────────
if [ -z "$WS" ] || [ ! -d "$CORE_DIR" ]; then
    gate_census "каталог ядра .claude/rules НЕ существует; файлов прочитано 0, строк 0"
    gate_void "каталога .claude/rules нет в '${WS:-<корень не резолвится>}' — раскладки «ядро + rulebook» в этом дереве не существует, сверять не с чем"
    exit 2
fi

# ── что лежит в ядре ФАКТИЧЕСКИ ──────────────────────────────────────────────
# Набор — то, что загрузчик может открыть ПО ИМЕНИ: обычные файлы И ссылки.
# `-type f` в одиночку оставлял ссылку вне наблюдения молча (см. шапку), поэтому
# ссылка входит в набор наравне с файлом и вдобавок называется своей осью ниже.
mapfile -t ACTUAL < <(cd "$CORE_DIR" && find . -mindepth 1 \( -type f -o -type l \) -printf '%P\n' 2>/dev/null | sort)
mapfile -t ACTUAL_DIRS < <(cd "$CORE_DIR" && find . -mindepth 1 -type d -printf '%P\n' 2>/dev/null | sort)
mapfile -t ACTUAL_LINKS < <(cd "$CORE_DIR" && find . -mindepth 1 -type l -printf '%P\n' 2>/dev/null | sort)

lines=0
for f in ${ACTUAL+"${ACTUAL[@]}"}; do
    # Нечитаемую запись (битая ссылка) пропускаем ЯВНО: `2>/dev/null` у `wc` её
    # не покрывает — перенаправление `<` отказывает в САМОМ шелле, до запуска
    # команды, и его жалоба уехала бы в вердикт сырой строкой поверх находки.
    # Диагностика — часть свойства: находка, обросшая чужим шумом, посылает
    # читателя искать не там (`testing.md` §«Гейт на класс», п.8).
    [ -r "$CORE_DIR/$f" ] || continue
    n="$(wc -l < "$CORE_DIR/$f" 2>/dev/null)" || n=0
    lines=$((lines + n))
done

# ── предпосылка 2: манифест ──────────────────────────────────────────────────
if [ ! -f "$MANIFEST" ]; then
    gate_census "прочитано файлов ядра ${#ACTUAL[@]}, строк $lines; объявление НЕ читалось — манифеста нет"
    gate_void ".claude/rulebook/MANIFEST.md в этом дереве нет — источника истины о составе ядра не существует, сверять не с чем"
    exit 2
fi

# ── что ядром ОБЪЯВЛЕНО ──────────────────────────────────────────────────────
#
# Секция §«Ядро» манифеста, дословно: `## Ядро — читают все, всегда`.
#
# ОБЪЯВЛЕНИЕ — ПЕРВЫЙ АБЗАЦ СЕКЦИИ, а не вся секция, и это решение, а не лень
# разбора. Ниже объявления в той же секции стоит проза («перенос сюда
# четырнадцатого правила возвращает …»), и она вправе называть координаты — в том
# числе `.md`. Читай гейт всю секцию, любое такое упоминание становилось бы
# объявленным именем ядра, то есть ЛОЖНОЙ находкой на законной правке текста, — а
# первый же ложный срабат гейт отключает (`gate-authoring` §Законный близнец).
#
# У выбранной границы отказ идёт В КРАСНУЮ сторону, и это проверено: перепиши
# кто-нибудь объявление так, что первый абзац перестанет называть часть правил, —
# недоназванные немедленно всплывут как ЛИШНИЕ файлы, а вычистит он абзац целиком
# — проверка скажет «объявление пусто». Молча ослепнуть распознаватель не может
# ни при одной из двух правок (`testing.md` §«Гейт на класс», п.7).
#
# Имена — inline-код, кончающийся на `.md`. Фильтр по суффиксу, а не по «всё в
# обратных кавычках»: иначе токен вроде `rules-gate` попал бы в объявление.
#
# Путь `.claude/rules/<имя>.md` принимается наравне с голым именем: манифест волен
# назвать координату целиком, и распознаватель, знающий одну форму из двух, молча
# недобирает (там же).
mapfile -t DECLARED < <(
    awk '
        /^[[:space:]]*##[[:space:]]/ { inside = ($0 ~ /Ядро/); started = 0; ended = 0; next }
        !inside || ended { next }
        /^[[:space:]]*$/ { if (started) ended = 1; next }
        { started = 1; print }
    ' "$MANIFEST" \
    | grep -oE '`[^`]+`' \
    | tr -d '`' \
    | sed -E 's#^\.claude/rules/##' \
    | grep -E '^[^/]+\.md$' \
    | sort -u
)

declared_list="$(printf '%s · ' ${DECLARED+"${DECLARED[@]}"} | sed 's/ · $//')"
gate_census "прочитано файлов ядра ${#ACTUAL[@]}, строк $lines; MANIFEST §«Ядро» объявляет ${#DECLARED[@]}${declared_list:+ ($declared_list)}"

# ── обход беспредметен: объявление пусто ─────────────────────────────────────
if [ "${#DECLARED[@]}" -eq 0 ]; then
    gate_fail "в MANIFEST §«Ядро» не распознано НИ ОДНОГО имени правила — объявление пусто, сверять каталог не с чем; это находка, а не отсутствие предмета: манифест на месте, испорчено само объявление"
    exit 1
fi

# ── обход беспредметен: каталог пуст ─────────────────────────────────────────
if [ "${#ACTUAL[@]}" -eq 0 ]; then
    gate_fail "обход беспредметен: в .claude/rules/ прочитано 0 файлов при ${#DECLARED[@]} объявленных — ядро пропало целиком, о его составе не прочитано ничего"
    exit 1
fi

# ── сверка в обе стороны ─────────────────────────────────────────────────────
findings=0

for f in "${ACTUAL[@]}"; do
    found=0
    for d in "${DECLARED[@]}"; do [ "$f" = "$d" ] && { found=1; break; }; done
    if [ "$found" -eq 0 ]; then
        gate_fail "ЛИШНИЙ в ядре: .claude/rules/$f — в MANIFEST §«Ядро» не объявлен; он возвращает свою цену в окно КАЖДОГО агента волны"
        findings=$((findings + 1))
    fi
done

for d in "${DECLARED[@]}"; do
    found=0
    for f in "${ACTUAL[@]}"; do [ "$f" = "$d" ] && { found=1; break; }; done
    if [ "$found" -eq 0 ]; then
        gate_fail "НЕДОСТАЁТ в ядре: .claude/rules/$d — объявлен в MANIFEST §«Ядро», файла нет; правило ядра пропало"
        findings=$((findings + 1))
    fi
done

for dir in ${ACTUAL_DIRS+"${ACTUAL_DIRS[@]}"}; do
    gate_fail "ПОДКАТАЛОГ в ядре: .claude/rules/$dir — ядро плоское, вложенность здесь означает, что кто-то завёл второй дом для правил"
    findings=$((findings + 1))
done

# Символьная ссылка в ядре. Находка НЕЗАВИСИМО от того, объявлено ли имя: что
# именно прочитает загрузчик, решает ЦЕЛЬ, а она вправе лежать вне объявленного
# набора, вне репозитория и не резолвиться вовсе. Тот же класс, что у скрытого от
# git, и потому та же форма: отдельная ось, а не молчание внутри «лишнего».
for f in ${ACTUAL_LINKS+"${ACTUAL_LINKS[@]}"}; do
    tgt="$(readlink "$CORE_DIR/$f" 2>/dev/null)"
    if [ -e "$CORE_DIR/$f" ]; then
        why="содержимое правила лежит по цели, вне объявленного набора"
    else
        why="цель НЕ резолвится — правило не читается вовсе"
    fi
    gate_fail "ССЫЛКА В ЯДРЕ: .claude/rules/$f -> ${tgt:-<цель не читается>} — не обычный файл; $why, а ядро обязано быть одинаковым на всех машинах"
    findings=$((findings + 1))
done

# Файл ядра, скрытый от git. Находка независимо от того, объявлен он или нет: в
# свежем клоне его нет, то есть ядро различается между машинами, а гейт на чужой
# машине судил бы другой каталог.
if git -C "$WS" rev-parse --git-dir >/dev/null 2>&1; then
    for f in "${ACTUAL[@]}"; do
        if git -C "$WS" check-ignore -q ".claude/rules/$f" 2>/dev/null; then
            gate_fail "СКРЫТ ОТ GIT: .claude/rules/$f лежит в ядре, но исключён .gitignore — в свежем клоне его нет, ядро различается между машинами"
            findings=$((findings + 1))
        fi
    done
fi

if [ "$findings" -gt 0 ]; then
    gate_fail "находок $findings; прочитано файлов ${#ACTUAL[@]}, объявлено ${#DECLARED[@]}"
    exit 1
fi

gate_pass "ядро сверено с MANIFEST §«Ядро» в обе стороны: прочитано файлов ${#ACTUAL[@]} ($lines строк), объявлено ${#DECLARED[@]}, лишних 0, недостающих 0"
exit 0
