#!/usr/bin/env bash
# check-16 — ОБЪЁМ ТАБЛИЦЫ МАНИФЕСТА, ОБЪЯВЛЕННЫЙ В ID НОРМЫ, РАВЕН ЧИСЛУ ЕЁ СТРОК.
#
# Предмет (ws#710 п.3). `.claude/rules/MANIFEST.md` несёт норму
# `mf-registry-table-<N>-rows`: число в id — объём таблицы реестра. С 2026-09-19 id
# называл 30 при 18 строках-записях, и держало его одно внимание: число не сверялось
# ничем, что могло бы упасть (приёмка ws#714, круг 2 — «предикат п.3 в написанном виде
# не выполнен»). Предикат задачи — «число в id равно числу строк таблицы, и равенство
# сверяет гейт, а не человек».
#
# ПОЧЕМУ ЧИСЛО ОСТАЁТСЯ В ID, а не снимается. Сверка превращает рост корпуса в правку
# объявления, видимую в диффе: правило заводится строкой таблицы И объёмом в id одним
# изменением. Состав (файл ↔ строка) сверяет check-01; эта проверка его не повторяет и
# от него не выводится — таблица может сойтись с каталогом при любом числе в id.
#
# СТРОКИ СЧИТАЕТ ОБЩИЙ РАЗБОРЩИК `manifest-rows.awk` (тот же, что у check-01 и check-03):
# второй подсчёт строк таблицы разошёлся бы с первым молча.
#
# Исходы — в КОДЕ ВЫХОДА: 0 — объявлено N, строк N; 1 — разошлось, норма снята либо
# объявлена дважды (сверять число не с чем — находка, а не «предмета нет»: объявление
# снято при живой таблице); 2 — нет манифеста либо разборщика, либо таблица пуста
# (объёма, который сверять, в дереве нет — это НЕ «находок 0»).
set -uo pipefail

NAME="check-16-manifest-volume-declared"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PARSER="$SCRIPT_DIR/manifest-rows.awk"
if [ -n "${RULES_GATE_ROOT:-}" ]; then
    WS="$(cd "$RULES_GATE_ROOT" 2>/dev/null && pwd)" || WS=""
else
    WS="$(cd "$SCRIPT_DIR/../.." 2>/dev/null && pwd)" || WS=""
fi
MANIFEST="$WS/.claude/rules/MANIFEST.md"
ID_RE='^mf-registry-table-[0-9]+-rows '

if [ ! -f "$PARSER" ]; then
    echo "[CENSUS] $NAME: разбор не запускался — $PARSER нет; строк таблицы 0, объявлений 0"
    echo "[VOID] $NAME — разборщика таблицы нет рядом с проверкой: считать строки нечем" >&2
    exit 2
fi
if [ -z "$WS" ] || [ ! -f "$MANIFEST" ]; then
    echo "[CENSUS] $NAME: манифеста ${MANIFEST:-<корень не резолвится>} нет; строк таблицы 0, объявлений 0"
    echo "[VOID] $NAME — манифеста нет: объёма, который сверять, в дереве не существует" >&2
    exit 2
fi

rows="$(LC_ALL=C awk -f "$PARSER" "$MANIFEST" | wc -l | tr -d ' ')"
mapfile -t VOL < <(grep -nE "$ID_RE" "$MANIFEST")
echo "[CENSUS] $NAME: MANIFEST.md — строк таблицы разобрано $rows; объявлений объёма (mf-registry-table-<N>-rows) ${#VOL[@]}"

if [ "$rows" -eq 0 ]; then
    echo "[VOID] $NAME — в таблице не разобрано ни одной строки: объём сверять не с чем (состав судит check-01)" >&2
    exit 2
fi
if [ "${#VOL[@]}" -eq 0 ]; then
    echo "[FAIL] $NAME — ОБЪЁМ ТАБЛИЦЫ НЕ ОБЪЯВЛЕН: в MANIFEST.md нет нормы mf-registry-table-<N>-rows при $rows строках таблицы — рост корпуса перестаёт быть видимой правкой объявления" >&2
    exit 1
fi
if [ "${#VOL[@]}" -gt 1 ]; then
    echo "[FAIL] $NAME — ОБЪЁМ ТАБЛИЦЫ ОБЪЯВЛЕН ${#VOL[@]} РАЗА (строки $(printf '%s ' "${VOL[@]%%:*}")) — два места об одном числе расходятся молча" >&2
    exit 1
fi
ln="${VOL[0]%%:*}"
id="${VOL[0]#*:}"; id="${id%% *}"
n="${id#mf-registry-table-}"; n="${n%-rows}"
if [ "$n" -ne "$rows" ]; then
    echo "[FAIL] $NAME — ОБЪЁМ ТАБЛИЦЫ РАЗОШЁЛСЯ: MANIFEST.md:$ln объявляет $id, а строк таблицы $rows — правило заведено или снято без правки объявления объёма (ws#710)" >&2
    exit 1
fi
echo "[PASS] $NAME — MANIFEST.md:$ln объявляет $id, строк таблицы $rows"
exit 0
