#!/usr/bin/env bash
# ЧАСТЬ инъекции набора: доказательство check-06 «у величины есть производитель».
#
# Файл ПОДКЛЮЧАЕТСЯ (`.`) из `inject.sh` и пользуется его оснасткой — `sandbox`,
# `capture`, `assert_code`, `assert_says`, `assert_lacks`,
# `assert_fixture_changed`, `sandbox_digest`, счётчиками `pass`/`fail`.
#
# ЗАЧЕМ ЭТА ЧАСТЬ. Проверка заведена 2026-09-19 после того, как рукописный
# перечень «над ориентиром» объявил ЧЕТВЕРЫХ при ПЯТИ. Доказывать её зелёным на
# починенном дереве нельзя: ровно так же выглядит перепись, потерявшая
# способность краснеть, — и тогда рукописная копия вернётся молча, а её
# расхождение опять никто не поймает.
#
# ОСЬ «УМЕЕТ ОТВЕЧАТЬ НЕТ» ЗДЕСЬ ОТДЕЛЬНАЯ, И ОНА НЕ ПРО КОД ВОЗВРАТА. Главный
# продукт этой проверки — не вердикт, а ПЕРЕПИСЬ: поимённый список над
# ориентиром. Перепись, которая печатает одно и то же независимо от дерева,
# бесполезна ровно так же, как гейт, который не краснеет. Поэтому ось E
# подсовывает агенту лишние байты и требует, чтобы список ИЗМЕНИЛСЯ: до правки
# `wave-reviewer` под ориентиром и в списке его нет, после — есть.
#
# ПО КАЖДОЙ ОСИ — НАСТОЯЩИЙ ДЕФЕКТ И ЗАКОННЫЙ БЛИЗНЕЦ ТОЙ ЖЕ ФОРМЫ. Ярлык
# перечня ищется в первой ячейке строки ТАБЛИЦЫ, поэтому близнецы — те же слова
# в прозе и в блоке кода: раздел обязан уметь объяснять, что такое ориентир, и
# показывать форму строки примером, не краснея на собственном объяснении.
#
# ОБЕ ЗАКОННЫЕ ФОРМЫ ЯРЛЫКА ДОКАЗЫВАЮТСЯ ПОРОЗНЬ (`testing.md` §«Гейт на класс»
# п.7): «над бюджетом» — редакция контракта до 2026-09-19, «над ориентиром» —
# после. Форма, о которой распознаватель не знает, не даёт ни красного, ни
# зелёного: она молчит, и заметить это нечем.

# ── СТРАЖ ПОДКЛЮЧЕНИЯ: часть НЕ исполняется самостоятельно ───────────────────
#
# Своей оснастки у части нет, а пути вида `"$d/…"` без песочницы становятся
# относительными и уезжают в рабочую копию. Отказ — код 2: ноль исполненных
# утверждений не находка и не успех.
if [ "${BASH_SOURCE[0]}" = "$0" ]; then
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — ЧАСТЬ инъекции, а не самостоятельная проба." >&2
    echo "       Она подключается (\`.\`) из scripts/rules-gate/inject.sh и пользуется его" >&2
    echo "       оснасткой; самостоятельно не исполнила бы ни одного утверждения и писала бы" >&2
    echo "       в рабочее дерево. Запускать: bash scripts/rules-gate/inject.sh" >&2
    exit 2
fi
for _inj_fn in sandbox capture assert_code assert_says assert_lacks assert_fixture_changed sandbox_digest; do
    command -v "$_inj_fn" >/dev/null 2>&1 && continue
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — оснастки inject.sh нет: функция" \
         "«$_inj_fn» не определена; часть подключена не оттуда, доказывать нечем" >&2
    exit 2
done
unset -v _inj_fn

CH06=check-06-preload-budget-census.sh

# Файл, который держит ориентир и таблицу переписи. Координата берётся один раз:
# две её копии в этой части разошлись бы молча.
CONTRACT=".claude/rules/01-wave-contract.md"

echo "== ось A: РУКОПИСНЫЙ ПЕРЕЧЕНЬ строкой таблицы — форма «над ориентиром» =="
d="$(sandbox a06)"
# shellcheck disable=SC2016  # обратные кавычки — разметка markdown, а не подстановка
printf '%s\n' '| над ориентиром, всего четверо | `git-operator` · `qa-test-engineer` | 269 984 · 263 714 | — |' >> "$d/$CONTRACT"
capture "$d" "$CH06"
assert_code 1 "ДЕФЕКТ: перечень над ориентиром выписан строкой таблицы"
assert_says "рукописным перечнем над ориентиром" "  ...и вердикт назван своим именем"
assert_says "$CONTRACT:" "  ...и координата названа файлом со строкой"

echo "== ось B: ВТОРАЯ законная форма ярлыка — «над бюджетом» =="
d="$(sandbox b06)"
# shellcheck disable=SC2016  # обратные кавычки — разметка markdown
printf '%s\n' '| над бюджетом без довода | `git-operator` | 269 984 | 1/3,8 |' >> "$d/$CONTRACT"
capture "$d" "$CH06"
assert_code 1 "ДЕФЕКТ: та же копия под прежним ярлыком — распознаватель знает ОБЕ формы"
assert_says "$CONTRACT:" "  ...и координата названа"

echo "== ось C: БЛИЗНЕЦ — те же слова В ПРОЗЕ, а не строкой таблицы =="
d="$(sandbox c06)"
b="$(sandbox_digest "$d")"
printf '%s\n' '' 'Кто именно над ориентиром и над бюджетом — печатает перепись набора,' \
    'а не этот абзац; здесь названо только то, что ориентир есть.' >> "$d/$CONTRACT"
assert_fixture_changed "$d" "$b" "БЛИЗНЕЦ: «над ориентиром» и «над бюджетом» в предложении"
capture "$d" "$CH06"
assert_code 0 "БЛИЗНЕЦ: проза о предмете — не перечень, гейт молчит"

echo "== ось D: БЛИЗНЕЦ — строка таблицы В БЛОКЕ КОДА (форма показана примером) =="
d="$(sandbox d06)"
b="$(sandbox_digest "$d")"
{ printf '%s\n' '' '```' '| над ориентиром | <агент> | <байт> | — |' '```'; } >> "$d/$CONTRACT"
assert_fixture_changed "$d" "$b" "БЛИЗНЕЦ: та же строка внутри ограды кода"
capture "$d" "$CH06"
assert_code 0 "БЛИЗНЕЦ: пример формы в блоке кода — не живая таблица"

echo "== ось E: ПЕРЕПИСЬ УМЕЕТ ОТВЕЧАТЬ «НЕТ» — список над порогом ЗАВИСИТ от дерева =="
d="$(sandbox e06)"
capture "$d" "$CH06"
assert_code 0 "контроль: нетронутая копия — гейт молчит"
assert_lacks "wave-reviewer" '  ...и агент wave-reviewer под ориентиром — в списке его НЕТ'
b="$(sandbox_digest "$d")"
# Запас `wave-reviewer` до ориентира — около двух килобайт; пять добавленных
# делают превышение. Байты идут в правило, которое он держит, а не в случайное:
# перепись обязана считать ПО ЗАКРЕПЛЕНИЮ, а не по каталогу.
head -c 5000 /dev/zero | tr '\0' 'x' >> "$d/$CONTRACT"
assert_fixture_changed "$d" "$b" "агенту подсунуты лишние байты в держимое им правило"
capture "$d" "$CH06"
assert_code 0 "перепись не считает превышение находкой — ориентир объявлен ориентиром"
assert_says "wave-reviewer" "  ...и список над порогом ИЗМЕНИЛСЯ: агент в нём появился"

echo "== ось F: ОРИЕНТИР СНЯТ — величину пришлось бы вшить в проверку =="
d="$(sandbox f06)"
sed -i 's/≤ 250 000 Б на агента/ориентир назван где-то ещё/' "$d/$CONTRACT"
capture "$d" "$CH06"
assert_code 1 "ДЕФЕКТ: объявления ориентира в корпусе не осталось"
assert_says "ориентир не объявлен" "  ...и вердикт назван своим именем"

echo "== ось G: ДВА РАЗНЫХ ОРИЕНТИРА — два места об одном предмете =="
d="$(sandbox g06)"
printf '%s\n' '' 'Бюджет — ориентир, а не запрет: ≤ 300 000 Б на агента.' >> "$d/$CONTRACT"
capture "$d" "$CH06"
assert_code 1 "ДЕФЕКТ: ориентир объявлен двумя разными значениями"
assert_says "РАЗНЫМИ значениями" "  ...и вердикт называет именно расхождение"

echo "== ось H: ПУСТОЙ ОБХОД — «над ориентиром 0» истинно by construction =="
d="$(sandbox h06)"
# Таблица снята, файл остался: закреплений ноль, и сумма не посчитана никому.
sed -i '/^| /d' "$d/.claude/rules/MANIFEST.md"
capture "$d" "$CH06"
assert_code 1 "ДЕФЕКТ: из таблицы не прочитано ни одного закрепления"
assert_says "пустой обход" "  ...и это НАХОДКА, а не «над ориентиром 0»"

echo "== ось I: предмета нет — код 2, и это НЕ успех =="
d="$(sandbox i06)"
rm -rf "$d/.claude/rules"
capture "$d" "$CH06"
assert_code 2 "корпуса правил в дереве нет вовсе — код 2, не 0 и не 1"
