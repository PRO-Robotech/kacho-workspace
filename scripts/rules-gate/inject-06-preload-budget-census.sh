#!/usr/bin/env bash
# ЧАСТЬ инъекции набора: доказательство check-06 «у величины есть производитель».
#
# Файл ПОДКЛЮЧАЕТСЯ (`.`) из `inject.sh` и пользуется его оснасткой — `sandbox`,
# `capture`, `assert_code`, `assert_says`, `assert_lacks`,
# `assert_fixture_changed`, `sandbox_digest`, счётчиками `pass`/`fail`.
#
# ЗАЧЕМ. Проверка заведена 2026-09-19 после того, как рукописный перечень «над
# ориентиром» объявил ЧЕТВЕРЫХ при ПЯТИ. Доказывать её зелёным на починенном
# дереве нельзя: ровно так же выглядит перепись, потерявшая способность
# краснеть, — и тогда копия вернётся молча.
#
# НИ ОДНА ФИКСТУРА НЕ НАЗЫВАЕТ АГЕНТА ПО ИМЕНИ, И ЭТО ПРАВКА ПО ЗАМЕРУ. Прежняя
# редакция оси E утверждала, что `wave-reviewer` под ориентиром, — и держалась
# это утверждение только его СЕГОДНЯШНИМ запасом. Опыт приёмки: +3 835 Б в
# правило, которое он держит ЗАКОННО, оставлял check-06 зелёным (превышение
# принято) и ронял инъекцию — 327 из 328. Получалось противоречие: гейт объявляет
# рост списка принятым состоянием, а его доказательство запрещает расти ровно
# одному агенту. Цена измерена: эта же полоса подняла его на 3 566 Б за пять
# коммитов — вдвое больше остававшегося запаса, — и следующая полоса по правилам
# роняла бы конвейер на дереве БЕЗ дефекта.
#
# Поэтому контрольный агент выбирается ПО ВЫВОДУ ПЕРЕПИСИ на контроле: она сама
# печатает строку «ближайший под ориентиром: <агент> <сумма> (запас N)», и байты
# идут в правило, которое ЭТОТ агент держит по таблице закрепления. Снять
# утверждение вместо починки было нельзя: вместе с ним ушло бы единственное
# доказательство, что перепись умеет отвечать «нет».
#
# ФОРМЫ КОПИИ ДОКАЗЫВАЮТСЯ ПО СВОЙСТВУ, А НЕ ПО СЛОВУ: тождество с выводом и
# величина набора рядом с именем агента. Близнецы — те же числа в прозе, та же
# строка в ограде кода и под HTML-комментарием, и строка с именем агента при
# малом числе.

# ── СТРАЖ ПОДКЛЮЧЕНИЯ: часть НЕ исполняется самостоятельно ───────────────────
if [ "${BASH_SOURCE[0]}" = "$0" ]; then
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — ЧАСТЬ инъекции, а не самостоятельная проба." >&2
    echo "       Она подключается (\`.\`) из scripts/rules-gate/inject.sh и пользуется его" >&2
    echo "       оснасткой; самостоятельно не исполнила бы ни одного утверждения и писала бы" >&2
    echo "       в рабочее дерево. Запускать: bash scripts/rules-gate/inject.sh" >&2
    exit 2
fi
for _inj_fn in sandbox capture assert_code assert_says assert_lacks assert_fixture_changed sandbox_digest; do
    command -v "$_inj_fn" >/dev/null 2>&1 && continue
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — оснастки inject.sh нет: функция" \
         "«$_inj_fn» не определена; часть подключена не оттуда, доказывать нечем" >&2
    exit 2
done
unset -v _inj_fn

CH06=check-06-preload-budget-census.sh
MANREL=".claude/rules/MANIFEST.md"

# Правило, которое названный агент держит ПО ТАБЛИЦЕ ЗАКРЕПЛЕНИЯ песочницы.
# Разбор — общий `manifest-rows.awk`, а не свой: грамматика таблицы одна.
rule_of() {   # <каталог песочницы> <агент>
    LC_ALL=C awk -f "$GATE/manifest-rows.awk" "$1/$MANREL" \
        | awk -F'\t' -v a="$2" 'index($5, a) > 0 { print $2; exit }'
}

echo "== ось A: КОПИЯ ВЫВОДА — тождество величины в живой строке таблицы =="
d="$(sandbox a06)"
capture "$d" "$CH06"
sum="$(printf '%s\n' "$OUT" | sed -n 's/.*ближайший под ориентиром: [^ ]* \([0-9]*\) .*/\1/p')"
printf '| произвольный ярлык | предзагрузка | %s | — |\n' "$sum" >> "$d/.claude/rules/01-wave-contract.md"
capture "$d" "$CH06"
assert_code 1 "ДЕФЕКТ: строка таблицы несёт число, равное величине из вывода переписи"
assert_says "тождество с выводом" "  ...и названа ПОЛОВИНА, которой находка поймана"
assert_says "01-wave-contract.md:" "  ...и координата названа файлом со строкой"

echo "== ось B: КОПИЯ, УЖЕ РАЗОШЕДШАЯСЯ — имя агента рядом с величиной набора =="
d="$(sandbox b06)"
capture "$d" "$CH06"
agent="$(printf '%s\n' "$OUT" | sed -n 's/.*ближайший под ориентиром: \([^ ]*\) .*/\1/p')"
# Число НЕ равно ни одной произведённой величине (взято заведомо между минимумом
# набора и ориентиром и смещено на простое), поэтому ловится только половиной B.
printf '| прошлый снимок | `%s` | 137 777 | 1/7 |\n' "$agent" >> "$d/.claude/rules/01-wave-contract.md"
capture "$d" "$CH06"
assert_code 1 "ДЕФЕКТ: имя агента рядом с величиной набора — копия, уже разошедшаяся с деревом"
assert_says "рядом с величиной набора" "  ...и названа ПОЛОВИНА, которой находка поймана"

echo "== ось C: БЛИЗНЕЦ — имя агента при МАЛОМ числе (не величина набора) =="
d="$(sandbox c06)"
capture "$d" "$CH06"
agent="$(printf '%s\n' "$OUT" | sed -n 's/.*ближайший под ориентиром: \([^ ]*\) .*/\1/p')"
b="$(sandbox_digest "$d")"
printf '| пустой контекст, ban #18 | `%s` | 0 | 0 |\n' "$agent" >> "$d/.claude/rules/01-wave-contract.md"
assert_fixture_changed "$d" "$b" "БЛИЗНЕЦ: имя агента и число, не являющееся величиной набора"
capture "$d" "$CH06"
assert_code 0 "БЛИЗНЕЦ: доля, счёт и ноль рядом с именем — не копия вывода"

echo "== ось D: БЛИЗНЕЦ — те же числа В ПРОЗЕ, а не строкой таблицы =="
d="$(sandbox d06)"
capture "$d" "$CH06"
sum="$(printf '%s\n' "$OUT" | sed -n 's/.*ближайший под ориентиром: [^ ]* \([0-9]*\) .*/\1/p')"
b="$(sandbox_digest "$d")"
printf '\nЗамер 2026-09-19 давал %s Б — снимок с названной датой, а не таблица.\n' "$sum" \
    >> "$d/.claude/rules/01-wave-contract.md"
assert_fixture_changed "$d" "$b" "БЛИЗНЕЦ: датированный замер в предложении"
capture "$d" "$CH06"
assert_code 0 "БЛИЗНЕЦ: проза цитирует датированный замер — судятся строки ТАБЛИЦЫ"

echo "== ось E: БЛИЗНЕЦ — та же строка в ОГРАДЕ КОДА (форма показана примером) =="
d="$(sandbox e06)"
capture "$d" "$CH06"
sum="$(printf '%s\n' "$OUT" | sed -n 's/.*ближайший под ориентиром: [^ ]* \([0-9]*\) .*/\1/p')"
b="$(sandbox_digest "$d")"
{ printf '\n```\n'; printf '| ярлык | агент | %s | — |\n' "$sum"; printf '```\n'; } \
    >> "$d/.claude/rules/01-wave-contract.md"
assert_fixture_changed "$d" "$b" "БЛИЗНЕЦ: та же строка внутри ограды кода"
capture "$d" "$CH06"
assert_code 0 "БЛИЗНЕЦ: пример формы в ограде — не живая таблица"

echo "== ось F: БЛИЗНЕЦ — та же строка под HTML-КОММЕНТАРИЕМ (снята автором) =="
d="$(sandbox f06)"
capture "$d" "$CH06"
sum="$(printf '%s\n' "$OUT" | sed -n 's/.*ближайший под ориентиром: [^ ]* \([0-9]*\) .*/\1/p')"
b="$(sandbox_digest "$d")"
printf '\n<!-- | ярлык | агент | %s | — | -->\n' "$sum" >> "$d/.claude/rules/01-wave-contract.md"
assert_fixture_changed "$d" "$b" "БЛИЗНЕЦ: та же строка под HTML-комментарием"
capture "$d" "$CH06"
assert_code 0 "БЛИЗНЕЦ: строка, снятая в комментарий, живой таблицей не является"

echo "== ось G: ПЕРЕПИСЬ УМЕЕТ ОТВЕЧАТЬ «НЕТ» — список над порогом ЗАВИСИТ от дерева =="
#
# Контрольный агент и его запас берутся ИЗ ВЫВОДА ПЕРЕПИСИ, а не из имени в
# фикстуре: иначе доказательство сцеплялось бы с преходящим запасом одного
# агента и падало бы на законном росте соседней полосы.
d="$(sandbox g06)"
capture "$d" "$CH06"
assert_code 0 "контроль: нетронутая копия — гейт молчит"
agent="$(printf '%s\n' "$OUT" | sed -n 's/.*ближайший под ориентиром: \([^ ]*\) .*/\1/p')"
slack="$(printf '%s\n' "$OUT" | sed -n 's/.*(запас \([0-9]*\) Б).*/\1/p')"
if [ -z "${agent:-}" ] || [ -z "${slack:-}" ]; then
    echo "  [FAIL] перепись не назвала ближайшего под ориентиром — выбрать контрольного агента не по чему" >&2
    fail=$((fail + 1))
else
    echo "  [OK]   перепись назвала ближайшего под ориентиром: $agent (запас $slack Б)"; pass=$((pass + 1))
    assert_lacks "над ориентиром 5: $agent" "  ...и в перечне над ориентиром его НЕТ"
    victim="$(rule_of "$d" "$agent")"
    if [ -z "${victim:-}" ]; then
        echo "  [FAIL] за $agent не закреплено ни одного правила — подсунуть байты некуда" >&2
        fail=$((fail + 1))
    else
        echo "  [OK]   байты пойдут в правило, которое он держит ЗАКОННО: $victim"; pass=$((pass + 1))
        b="$(sandbox_digest "$d")"
        head -c "$((slack + 2000))" /dev/zero | tr '\0' 'x' >> "$d/.claude/rules/$victim"
        assert_fixture_changed "$d" "$b" "агенту подсунут запас +2000 Б в держимое им правило"
        capture "$d" "$CH06"
        assert_code 0 "перепись не считает превышение находкой — ориентир объявлен ориентиром"
        assert_says "$agent" "  ...и список над порогом ИЗМЕНИЛСЯ: агент в нём появился"
    fi
fi

echo "== ось H: ОРИЕНТИР СНЯТ В КОММЕНТАРИЙ — не объявлен, и ноль НЕ измерен =="
d="$(sandbox h06)"
sed -i 's|\(.*≤ 250 000 Б на агента.*\)|<!-- \1 -->|' "$d/.claude/rules/01-wave-contract.md"
capture "$d" "$CH06"
assert_code 1 "ДЕФЕКТ: единственное объявление ориентира снято в HTML-комментарий"
assert_says "ориентир не объявлен" "  ...и вердикт назван своим именем"
assert_says "НЕ ИЗМЕРЕНО" "  ...и перепись НЕ печатает неизмеренного нуля"
assert_lacks "над ориентиром 0 — измерено" '  ...и измеренного нуля не объявлено'
# Утверждение сужено до ФОРМУЛЫ измеренного нуля намеренно: широкое «над
# ориентиром 0» совпадало с собственным объяснением переписи, которая этими же
# словами говорит, что ноль здесь НЕ измерен, — тот же класс, из-за которого
# снята половина по ярлыку.

echo "== ось I: БЛИЗНЕЦ — ориентир ПОКАЗАН ПРИМЕРОМ в ограде рядом с настоящим =="
d="$(sandbox i06)"
b="$(sandbox_digest "$d")"
{ printf '\n```\n'; printf 'Бюджет — ориентир, а не запрет: ≤ 400 000 Б на агента.\n'; printf '```\n'; } \
    >> "$d/.claude/rules/01-wave-contract.md"
assert_fixture_changed "$d" "$b" "БЛИЗНЕЦ: объявление показано примером в ограде кода"
capture "$d" "$CH06"
assert_code 0 "БЛИЗНЕЦ: пример в ограде объявлением не является — право то же, что у строки таблицы"

echo "== ось J: ДВА ОДИНАКОВЫХ ОБЪЯВЛЕНИЯ — два места об одном предмете =="
#
# Значение СОВПАДАЕТ с действующим: прежняя редакция считала РАЗЛИЧНЫЕ значения и
# давала такой паре «объявлений 1» с кодом 0 — то есть пропускала её молча.
d="$(sandbox j06)"
printf '\nБюджет — ориентир, а не запрет: ≤ 250 000 Б на агента.\n' >> "$d/.claude/rules/MANIFEST.md"
capture "$d" "$CH06"
assert_code 1 "ДЕФЕКТ: то же значение объявлено ВТОРОЙ раз в другом файле"
assert_says "два места об одном предмете" "  ...и вердикт называет именно это"

echo "== ось K: ПУСТОЙ ОБХОД — всякий ноль был бы истинным by construction =="
d="$(sandbox k06)"
sed -i '/^| /d' "$d/$MANREL"
capture "$d" "$CH06"
assert_code 1 "ДЕФЕКТ: из таблицы закрепления не прочитано ни одного закрепления"
assert_says "пустой обход" "  ...и это НАХОДКА, а не «над ориентиром 0»"

echo "== ось L: предмета нет — код 2, и это НЕ успех =="
d="$(sandbox l06)"
rm -rf "$d/.claude/rules"
capture "$d" "$CH06"
assert_code 2 "корпуса правил в дереве нет вовсе — код 2, не 0 и не 1"
