#!/usr/bin/env bash
# ЧАСТЬ инъекции набора: доказательство check-06 «объём и форма корпуса» по восьми
# осям — перевес потолка, перевес РОВНО НА ОДИН символ, строка без `red:`, нечётный
# backtick, пустой императив, пустой держатель, пустой признак, слово «держится» —
# плюс отказ по усечённому обходу и законные близнецы той же формы.
#
# Файл ПОДКЛЮЧАЕТСЯ (`.`) из `inject.sh` и пользуется его оснасткой.
#
# ── ВЫПИСАННЫЙ РАЗМЕР ФИКСТУРЫ ЕСТЬ ВТОРОЙ ПОТОЛОК ───────────────────────────
#
# До 2026-09-22 законный близнец оси A дописывал 840 символов ЧИСЛОМ В КОДЕ. Это
# молча вводило ВТОРОЙ порог, которого никто не объявлял: корпус, потолка НЕ
# превысивший, но подошедший к нему ближе 841 символа, ронял не проверку, а её
# ЗАКОННОГО БЛИЗНЕЦА — `check-06` объявлялась недоказанной, инъекция краснела
# РАНЬШЕ потолка, и текст её красного («гейт не доказан») уводил от настоящей
# причины (объём). Измерено на этом дереве: при корпусе 199 313 из 200 000 —
# то есть при ЗЕЛЁНОМ потолке — близнец давал 200 154 и падал.
#
# Решение владельца 2026-09-22: порог доказуемости не объявляется второй нормой
# (две нормы об одном предмете разойдутся), а РАЗМЕР ФИКСТУРЫ ВЫВОДИТСЯ ИЗ
# ЗАПАСА. Близнец добирает ВЕСЬ остаток: итог равен потолку РОВНО, сравнение в
# проверке строгое (`total > CEILING`), поэтому молчание на самой границе и есть
# требуемое утверждение — и оно сильнее прежнего, выписанного.
#
# ПАРА К НЕМУ — ось A': тот же расчёт ПЛЮС ОДИН символ обязан краснеть и назвать
# «перевес 1». Врозь ни одна из двух сторон расчёт не проверяет: близнец, взявший
# на символ меньше, зеленел бы и при сдвинутой границе, а дефект, взявший на
# символ больше, краснел бы и при ней же. Вместе они прибивают границу к одному
# символу — и тем самым проверяют САМ РАСЧЁТ, а не только проверку.
#
# ── ТОТ ЖЕ ПОРОК БЫЛ У ВСЕХ ОСЕЙ, КОТОРЫЕ ДОПИСЫВАЮТ ─────────────────────────
#
# Добор от запаса чинит ОДНУ ось. Осталось бы семь: близнец формы дописывает
# строку-норму (~130 символов), а каждая из осей B…G — свою дефектную строку.
# Измерено на дереве с запасом 1 символ:
#   · близнец формы ПАДАЛ — «КРАСНОЕ объём … перевес 130» вместо молчания;
#   · ось B при этом печатала ДВА вердикта разом — «КРАСНОЕ объём … перевес 76»
#     И «КРАСНОЕ строка без поля red:», — а `assert_code 1` их не различает:
#     ось зеленела ОТ СОСЕДА (`testing.md` injection-drops-only-its-subject,
#     и `assert_lacks` в `inject.sh` заведён ровно под «ДИАГНОЗ ОДИН»).
# Скрытый порог не исчезал бы — он переезжал бы с 840 на 130 и становился
# НЕИЗВЕСТНЫМ. Поэтому чинится КЛАСС:
#
#   1. `room6` освобождает в песочнице место ПОД РАЗМЕР САМОЙ ФИКСТУРЫ, снимая
#      ЦЕЛЫЕ строки-нормы с конца жертвы. Снятие строки объём уменьшает, формы
#      не нарушает и числа файлов не трогает — то есть ось объёма гасит, а свою
#      не задевает. Сколько снимать, фикстура спрашивает у СЕБЯ (длина её текста),
#      а не берёт числом.
#   2. Каждая дописывающая ось несёт КОНТРОЛЬ: нормализованная песочница обязана
#      МОЛЧАТЬ до внесения дефекта. Без контроля «покраснело» неотличимо от
#      «краснело и до нас».
#   3. Каждая ось формы утверждает ТЕКСТ своей находки и ОТСУТСТВИЕ чужой
#      («КРАСНОЕ объём»): красное обязано прийти от внесённого факта.
#
# ОСТАТКА НЕТ. `room6` вызывается и близнецом оси A, поэтому он исполним даже
# когда корпус стоит на потолке РОВНО. Порог доказуемости с этого изменения
# СОВПАДАЕТ с объявленным потолком, и второго числа о нём в дереве не лежит.

# ── СТРАЖ ПОДКЛЮЧЕНИЯ ────────────────────────────────────────────────────────
if [ "${BASH_SOURCE[0]}" = "$0" ]; then
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — ЧАСТЬ инъекции, а не самостоятельная проба." >&2
    echo "       Она подключается из scripts/rules-gate/inject.sh и пользуется его оснасткой;" >&2
    echo "       самостоятельно писала бы в рабочее дерево. Запускать:" >&2
    echo "       bash scripts/rules-gate/inject.sh" >&2
    exit 2
fi
for _i06_fn in sandbox capture assert_code assert_says assert_number assert_fixture_changed sandbox_digest; do
    command -v "$_i06_fn" >/dev/null 2>&1 && continue
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — оснастки inject.sh нет: функция" \
         "«$_i06_fn» не определена; часть подключена не оттуда" >&2
    exit 2
done
unset -v _i06_fn

C6=check-06-corpus-ceiling.sh

# ── ПОТОЛОК БЕРЁТСЯ У ПРОВЕРКИ, А НЕ ВЫПИСЫВАЕТСЯ ЗДЕСЬ ──────────────────────
# Число, выписанное и в проверке, и в её инъекции, есть два дома одной величины:
# они разойдутся, и разойдутся молча — инъекция продолжит зеленеть, меряя чужой
# потолок. Источник ОДИН и импортируется, а не вычитывается из текста.
CEIL6="$(python3 - "$GATE/corpus_ceiling.py" <<'PY'
import importlib.util
import sys
spec = importlib.util.spec_from_file_location('c6src', sys.argv[1])
mod = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mod)
print(mod.CEILING)
PY
)"
if ! printf '%s' "$CEIL6" | grep -qE '^[0-9]+$'; then
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — потолок у проверки не прочитан" \
         "(получено «$CEIL6»): расчёт фикстуры беспредметен" >&2
    exit 2
fi

# vol6 <каталог песочницы> — объём её корпуса В СИМВОЛАХ, тем же счётом, что и
# проверка: байт и символ здесь расходятся вдвое, и ошибка была бы тихой.
vol6() {
    ( cd "$1" && python3 -c '
import glob
print(sum(len(open(f, encoding="utf-8").read()) for f in glob.glob(".claude/rules/*.md")))' )
}

# room6 <каталог песочницы> <текст фикстуры> — освободить места БОЛЬШЕ, чем
# займёт этот текст, снимая ЦЕЛЫЕ строки-нормы с конца жертвы.
#
# Почему снимаются строки-нормы, а не режется хвост файла: обрезанная строка
# стала бы строкой-нормой НЕВЕРНОЙ ФОРМЫ, то есть фикстура внесла бы ВТОРОЙ
# факт — ровно то, от чего эта функция и лечит. Снятая целиком строка не
# нарушает ничего: форма оставшихся цела, число файлов не менялось, а строки-
# нормы в корпусе остаются — их несут остальные семнадцать файлов, и обход
# беспредметным не становится.
room6() {
    python3 - "$1/$V6" "$(vol6 "$1")" "$CEIL6" "$2" <<'PY'
import sys
path, vol, ceiling, text = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), sys.argv[4]
need = max(1, len(text) + 2)          # printf '\n%s\n' добавляет два перевода
room = ceiling - vol
if room > need:
    sys.exit(0)
lines = open(path, encoding='utf-8').read().split('\n')
keep, freed = [], 0
for line in reversed(lines):
    if room + freed <= need and ' \u00b7 ' in line:
        freed += len(line) + 1
        continue
    keep.append(line)
if room + freed <= need:
    print('room6: в %s не хватило строк-норм — освобождено %d, нужно больше %d'
          % (path, freed, need - room), file=sys.stderr)
    sys.exit(1)
open(path, 'w', encoding='utf-8').write('\n'.join(reversed(keep)))
PY
}
# Жертва выводится ИЗ ДЕРЕВА: имя в коде рассыпалось бы вместе с раскладкой.
# Порядок глоба зависит от ЛОКАЛИ, а жертва обязана быть одной и той же на всякой
# машине: сортировка — в C.
V6=""
while IFS= read -r _v; do
    [ -e "$_v" ] || continue
    V6=".claude/rules/$(basename "$_v")"
    break
done < <(printf '%s\n' "$WS"/.claude/rules/*.md | LC_ALL=C sort)
unset -v _v
if [ -z "$V6" ]; then
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — в .claude/rules нет ни одного файла;" \
         "строку-норму вписывать некуда" >&2
    exit 2
fi

# row <ось> <строка> <утверждение> <дословная находка> — одна дефектная
# строка-норма, ОДИН вердикт и ОДИН диагноз.
#
# Три шага, и ни один не лишний: освободить место под саму фикстуру · убедиться,
# что нормализованная песочница МОЛЧИТ · внести один факт и потребовать, чтобы
# напечатано было про НЕГО, а не про объём.
row() {
    local d; d="$(sandbox "i06_$1")"
    room6 "$d" "$2" || { echo "  [FAIL] ось $1: room6 не освободил места" >&2; fail=$((fail + 1)); return; }
    capture "$d" "$C6"
    assert_code 0 "КОНТРОЛЬ оси $1: песочница до внесения дефекта молчит"
    printf '\n%s\n' "$2" >> "$d/$V6"
    capture "$d" "$C6"
    assert_code 1 "$3"
    assert_says "$4" "ДИАГНОЗ оси $1: находка называет ИМЕННО эту ось"
    assert_lacks "КРАСНОЕ объём" "ДИАГНОЗ оси $1: объём в вердикт не примешан"
}

# ── ось A: перевес потолка ───────────────────────────────────────────────────
# Добор считается ОТ ФАКТИЧЕСКОГО объёма копии, а не от числа в коде: иначе проба
# зеленела бы сама собой, как только корпус подрос, и «перевес» перестал бы быть
# внесённым ею.
#
# КОНТРОЛЬ И ДИАГНОЗ ЗДЕСЬ — ПРАВКА ПО ПРИЁМКЕ 2026-09-22. До неё ось несла ОДНО
# утверждение `assert_code 1` и потому удовлетворялась КРАСНЫМ ЛЮБОГО
# ПРОИСХОЖДЕНИЯ: подсади дефект в сам расчёт так, чтобы предмет оси не
# находился вовсе, а красноту дай соседней осью — ось всё равно объявит успех.
# Парная ось A' спаслась тогда именно диагнозом («перевес 1»), эта — нет.
# Теперь три утверждения вместо одного: чистая песочница МОЛЧИТ до дописывания ·
# после дописывания краснеет · печатает про ОБЪЁМ и ни про какую чужую ось
# (находка формы печатается как «КРАСНОЕ <ось> — строк N», отсюда и предикат).
d="$(sandbox i06_ceiling)"
capture "$d" "$C6"
assert_code 0 "КОНТРОЛЬ оси A: песочница до добора молчит"
NEED=$(( CEIL6 - $(vol6 "$d") + 1000 ))
[ "$NEED" -ge 1 ] || NEED=1
python3 - "$d/$V6" "$NEED" <<'PY'
import sys
p, n = sys.argv[1], int(sys.argv[2])
with open(p, 'a', encoding='utf-8') as fh:
    fh.write('\n' + ('доборный текст перевеса. ' * ((n // 25) + 1)))
PY
capture "$d" "$C6"
# Потолок в МЕТКЕ утверждения берётся из источника: выписанный текстом, он
# печатал бы неверное число ровно тогда, когда потолок подменён, — то есть в
# единственном прогоне, ради которого метку читают.
assert_code 1 "ДЕФЕКТ: корпус перевесил потолок $CEIL6 — краснеет"
assert_says "КРАСНОЕ объём" "ДИАГНОЗ оси A: находка называет ИМЕННО объём"
assert_lacks "— строк " "ДИАГНОЗ оси A: находка формы в вердикт не примешана"

# ── оси B…G: форма строки-нормы ──────────────────────────────────────────────
row nored 'probe-bez-red · императив пробы · ЗАВЕСТИ probe-bez-red · признак без метки' \
    "ДЕФЕКТ: строка-норма без поля red: — краснеет" 'КРАСНОЕ строка без поля red:'
row oddbt 'probe-odd-bt · императив с `незакрытым обратным апострофом · ЗАВЕСТИ probe-odd-bt · red: признак' \
    "ДЕФЕКТ: нечётный backtick в строке-норме — краснеет" 'КРАСНОЕ нечётный backtick'
row noimp 'probe-pustoj-imperativ · — · ЗАВЕСТИ probe-pustoj-imperativ · red: признак' \
    "ДЕФЕКТ: пустой императив (поле 2) — краснеет" 'КРАСНОЕ пустой императив (поле 2)'
row nohold 'probe-pustoj-derzhatel · императив пробы · — · red: признак' \
    "ДЕФЕКТ: пустой держатель (поле 3) — краснеет" 'КРАСНОЕ пустой держатель (поле 3)'
row nosign 'probe-pustoj-priznak · императив пробы · ЗАВЕСТИ probe-pustoj-priznak · red: —' \
    "ДЕФЕКТ: пустой признак красноты — краснеет" 'КРАСНОЕ пустой признак красноты'
row held 'probe-derzhitsya · императив пробы · держится вниманием · red: признак' \
    "ДЕФЕКТ: «держится» вместо названного механизма — краснеет" 'КРАСНОЕ слово «держится»'

# ── ось VOID: усечённый обход — ОТКАЗ, а не зелёный потолок ──────────────────
# Недочитанное дерево даёт сумму МЕНЬШЕ настоящей: «находок 0» здесь неотличимо
# от «в потолок уложились».
d="$(sandbox i06_trunc)"
_left=0
for _f in "$d"/.claude/rules/*.md; do
    [ -e "$_f" ] || continue
    _left=$((_left + 1))
    [ "$_left" -le 3 ] || rm -f "$_f"
done
unset -v _f _left
capture "$d" "$C6"
assert_code 2 "ДЕФЕКТ: усечённый обход — ОТКАЗ по предмету, не зелёный потолок"

# ── БЛИЗНЕЦ осей B…G: строка-норма ТОЙ ЖЕ формы, но полная ──────────────────
d="$(sandbox i06_twin_row)"
TWIN_ROW="probe-polnaya-stroka · императив пробы в \`кавычках\` целиком · scripts/rules-gate/check-06-corpus-ceiling.sh · red: признак назван"
# Код возврата `room6` ЧИТАЕТСЯ: его молчаливый отказ уронил бы близнеца ниже с
# диагнозом «молчит», то есть с текстом, уводящим от причины.
if ! room6 "$d" "$TWIN_ROW"; then
    echo "  [FAIL] БЛИЗНЕЦ формы: room6 не освободил места — вердикт ниже был бы о потолке, не о форме" >&2
    fail=$((fail + 1))
fi
b="$(sandbox_digest "$d")"
printf '\n%s\n' "$TWIN_ROW" >> "$d/$V6"
assert_fixture_changed "$d" "$b" "БЛИЗНЕЦ: строка-норма добавлена, все четыре поля полны"
capture "$d" "$C6"
assert_code 0 "БЛИЗНЕЦ: полная строка-норма — молчит"

# ── БЛИЗНЕЦ оси A: корпус ВЫРОС РОВНО ДО ПОТОЛКА — молчит ──────────────────
# Добор равен ВСЕМУ запасу (довод — врезка «ВЫПИСАННЫЙ РАЗМЕР ФИКСТУРЫ» в шапке):
# `'\n' + текст` даёт ровно `room` символов, итог равен потолку, ни символом
# больше. При запасе в один символ дописывается одна пустая строка — рост всё
# ещё есть, и `assert_fixture_changed` это подтверждает.
d="$(sandbox i06_twin_grow)"
if ! room6 "$d" ""; then          # гарантирует запас даже на самом потолке
    echo "  [FAIL] БЛИЗНЕЦ оси A: room6 не освободил места — «молчит» ниже стало бы ложным диагнозом" >&2
    fail=$((fail + 1))
fi
b="$(sandbox_digest "$d")"
grow6=$(( CEIL6 - $(vol6 "$d") ))
if [ "$grow6" -lt 1 ]; then
    echo "  [FAIL] БЛИЗНЕЦ оси A НЕИСПОЛНИМ: запас $grow6 символов — корпус стоит" \
         "на потолке $CEIL6 ровно либо выше, и «рост, потолка не достающий»" \
         "беспредметен. Это НЕ зелёное: check-06 останется без законного" \
         "близнеца, и inject.sh объявит её недоказанной" >&2
    fail=$((fail + 1))
else
    python3 - "$d/$V6" "$grow6" <<'PY'
import sys
path, room = sys.argv[1], int(sys.argv[2])
with open(path, 'a', encoding='utf-8') as fh:
    fh.write('\n' + 'д' * (room - 1))
PY
    assert_fixture_changed "$d" "$b" "БЛИЗНЕЦ: добран ВЕСЬ запас — $grow6 символов до потолка $CEIL6"
    capture "$d" "$C6"
    assert_code 0 "БЛИЗНЕЦ: объём равен потолку РОВНО — молчит (сравнение строгое)"
    assert_says "из $CEIL6" "БЛИЗНЕЦ: перепись называет потолок, о котором молчит"
fi

# ── ось A': тот же расчёт ПЛЮС ОДИН символ — краснеет и называет перевес 1 ──
# Пара к близнецу выше. Она проверяет НЕ проверку, а РАСЧЁТ: сдвинься граница на
# символ в любую сторону — падает ровно одна из двух сторон, и видно, какая.
d="$(sandbox i06_over_by_one)"
if ! room6 "$d" ""; then
    echo "  [FAIL] ось A': room6 не освободил места — «плюс один» считался бы от чужого запаса" >&2
    fail=$((fail + 1))
fi
over6=$(( CEIL6 - $(vol6 "$d") ))
python3 - "$d/$V6" "$over6" <<'PY'
import sys
path, room = sys.argv[1], int(sys.argv[2])
with open(path, 'a', encoding='utf-8') as fh:
    fh.write('\n' + 'д' * room)
PY
capture "$d" "$C6"
assert_code 1 "ДЕФЕКТ: объём выше потолка на ОДИН символ — краснеет"
assert_number "перевес" 1 "ДЕФЕКТ: находка называет перевес ЧИСЛОМ, а не «слишком много»"

# ── ось N: ФОРМА ЗАПИСИ вердикта не меняет ─────────────────────────────────
# Символ как единица счёта определён только вместе с формой нормализации: `й` —
# один символ в NFC и два в NFD. Замер 2026-09-22 на этом корпусе: NFC 198 613,
# NFD 200 412, разница 1 799 — БОЛЬШЕ всего запаса (1 387), то есть вердикт
# переворачивался от формы, в которой файл сохранён, БЕЗ ЕДИНОЙ ИЗМЕНЁННОЙ БУКВЫ.
# Форма закреплена в самом приборе (`corpus_ceiling.FORM`), и вот проба на это.
# Перемерить: `python3 -c "import glob,unicodedata as u; fs=sorted(glob.glob(
# '.claude/rules/*.md')); print([sum(len(u.normalize(F,open(f,encoding='utf-8')
# .read())) for f in fs) for F in ('NFC','NFD')])"`.
#
# Пара, а не одно утверждение: близнец доказывает, что смена формы вердикта не
# меняет, а дефект — что путь NFD не ослеп (перевес на нём находится так же).
#
# ── ЧЕГО ЭТА ОСЬ НЕ УТВЕРЖДАЕТ, И ЭТО ИЗМЕРЕНО, А НЕ ОГОВОРЕНО ──────────────
#
# Она НЕ утверждает, что подмена `corpus_ceiling.FORM` роняет ЕЁ, а не соседнюю
# ось. Такое заявление здесь стояло бы ложью: измерено 2026-09-22 подстановкой
# `FORM = 'NFD'` в прибор и полным прогоном инъекции — разошлось 21 утверждение
# из 466, в 14 осях и близнецах (контрольный цикл; контроль оси A; оси nored,
# oddbt, noimp, nohold, nosign, held; близнец формы; близнец оси A; ось A';
# обе половины оси N; ось Z). Причина СТРУКТУРНАЯ, а не конструктивная: запас
# корпуса (1 387) МЕНЬШЕ дельты формы (1 799), поэтому подмена формы сама по себе
# переводит корпус за потолок — и всякая ось, чей контроль или близнец требует
# молчания, падает от объёма, ничего не зная о форме. Обратная сторона того же
# замера: при запасе 2 610 > дельты 1 791 тот же дефект ронял 2 утверждения.
# Изоляции оси N на ЭТОМ корпусе не добиться ничем, и «починить разброс» нечего;
# сузить его может только рост запаса — то есть снятие текста из корпуса.
#
# ЧТО ОСЬ ВСЁ-ТАКИ ДЕРЖИТ И ЧЕМ ЭТО ПРОВЕРЕНО. Держит она ЧИСЛО: на NFD перевес
# обязан называться тем же, что на NFC. До 2026-09-22 это не проверялось —
# `assert_says "перевес 1"` есть подстрока, и её удовлетворяло чужое «перевес
# 1800» (`inject.sh`, врезка у `assert_number`). Дефектная половина оси к смене
# формы была слепа ЦЕЛИКОМ: код 1 совпадал, число не сверялось. С помощником
# `assert_number` та же подстановка роняет именно её, с диагнозом «в вердикте нет
# «перевес 1» ЦЕЛЫМ числом» — измерено тем же прогоном.
d="$(sandbox i06_nfd)"
nfc_vol="$(vol6 "$d")"
python3 - "$d" <<'PY'
import glob, os, sys, unicodedata
os.chdir(sys.argv[1])
for f in sorted(glob.glob('.claude/rules/*.md')):
    text = open(f, encoding='utf-8').read()
    open(f, 'w', encoding='utf-8').write(unicodedata.normalize('NFD', text))
PY
capture "$d" "$C6"
assert_code 0 "БЛИЗНЕЦ: корпус переписан в NFD — ни одной изменённой буквы — молчит"
assert_says "объём: $nfc_vol из" "БЛИЗНЕЦ: на NFD напечатано ТО ЖЕ число, что на NFC ($nfc_vol)"

d="$(sandbox i06_nfd_over)"
python3 - "$d" "$CEIL6" <<'PY'
import glob, os, sys, unicodedata
os.chdir(sys.argv[1])
files = sorted(glob.glob('.claude/rules/*.md'))
for f in files:
    text = open(f, encoding='utf-8').read()
    open(f, 'w', encoding='utf-8').write(unicodedata.normalize('NFD', text))
vol = sum(len(unicodedata.normalize('NFC', open(f, encoding='utf-8').read())) for f in files)
open(files[0], 'a', encoding='utf-8').write('\n' + 'д' * (int(sys.argv[2]) - vol))
PY
capture "$d" "$C6"
assert_code 1 "ДЕФЕКТ: NFD-корпус на символ выше потолка — краснеет"
assert_number "перевес" 1 "ДЕФЕКТ: на пути NFD перевес назван тем же числом"

