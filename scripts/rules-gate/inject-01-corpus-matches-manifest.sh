#!/usr/bin/env bash
# ЧАСТЬ инъекции набора: доказательство check-01 «состав корпуса сходится
# с манифестом в обе стороны».
#
# Файл ПОДКЛЮЧАЕТСЯ (`.`) из `inject.sh` и пользуется его оснасткой — `sandbox`,
# `capture`, `assert_code`, `assert_says`, `assert_fixture_changed`, счётчиками
# `pass`/`fail`. Отдельным файлом, а не секцией общего: три полосы, писавшие один
# файл в один час, уже затёрли друг друга дважды; часть переживает чужую правку
# общего входа.
#
# Здесь по каждой оси вносится НАСТОЯЩИЙ дефект — гейт обязан покраснеть И
# НАЗВАТЬ КООРДИНАТУ, — а рядом ставится ЗАКОННЫЙ БЛИЗНЕЦ той же формы, на
# котором гейт обязан смолчать. Без близнеца гейт ловил бы форму, а не существо
# (`.claude/rules/testing.md` §«Гейт на класс», п.2).
#
# ОТДЕЛЬНО ДОКАЗЫВАЕТСЯ НЕЗАВИСИМОСТЬ ОТ check-03. Строка с ПУСТЫМИ ячейками
# здесь — законный близнец: состав от содержимого ячейки не меняется ни на один
# файл, и краснеть на ней обязан сосед, а не эта проверка. Без такого близнеца
# две проверки набора незаметно слились бы в одну, и снятие любой из них не
# уронило бы ничего.
#
# Ни одной пробы, меняющей два факта, кроме одной — «двадцатое правило заведено И
# объявлено». Это один поступок, и её предмет ровно в том, что он законен.

# ── СТРАЖ ПОДКЛЮЧЕНИЯ: часть НЕ исполняется самостоятельно ───────────────────
#
# Своей оснастки (`sandbox`, `capture`, `assert_*`, счётчики) у части нет. В
# обход `inject.sh` она не просто ничего не доказывает — она ПОРТИТ дерево, из
# которого запущена: каталог песочницы не определён, поэтому путь вида
# `"$d/CLAUDE.md"` становится ОТНОСИТЕЛЬНЫМ и правка уезжает в рабочую копию, а
# `git -C "$d" add -A` стажирует в её индекс чужие незакоммиченные правки.
# Испорченный индекс делает лживыми ИМЕННО те проверки, что читают дерево:
# «ноль находок» превращается в «ноль прочитанного» и выглядит настоящей
# находкой (`.claude/rules/multi-agent-flow-shared-tree.md` §13 «Неприкосновенность чужого
# состояния»).
#
# ИЗМЕРЕНО ДО СТРАЖА, на изолированной копии с чистым деревом: прямой запуск
# inject-02 → rc=127 и ` M CLAUDE.md`; прямой запуск inject-03 → rc=0 при НУЛЕ
# исполненных утверждений и превращал чужое ` M` в `M ` (стажировал). То есть
# «не выполнилось» отчитывалось успехом, и в том же прогоне портилось дерево.
#
# Отказ — код 2, а не 1: ноль исполненных утверждений не является находкой в
# дереве и не является успехом (`.claude/rules/testing.md` §«Чтение вердикта»).
#
# Бит исполнения намеренно ОСТАВЛЕН: без него `./inject-NN-….sh` отвечал бы
# «Permission denied» — диагностика хуже, чем у этого отказа, который называет
# и причину, и команду, которую звать вместо.
if [ "${BASH_SOURCE[0]}" = "$0" ]; then
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — ЧАСТЬ инъекции, а не самостоятельная проба." >&2
    echo "       Она подключается (\`.\`) из scripts/rules-gate/inject.sh и пользуется его" >&2
    echo "       оснасткой; самостоятельно не исполнила бы ни одного утверждения и писала бы" >&2
    echo "       в рабочее дерево. Запускать: bash scripts/rules-gate/inject.sh" >&2
    exit 2
fi
for _inj_fn in sandbox capture assert_code assert_says assert_fixture_changed sandbox_digest; do
    command -v "$_inj_fn" >/dev/null 2>&1 && continue
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — оснастки inject.sh нет: функция" \
         "«$_inj_fn» не определена; часть подключена не оттуда, доказывать нечем" >&2
    exit 2
done
unset -v _inj_fn
if [ -z "${WS:-}" ] || [ ! -d "$WS" ]; then
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — корень дерева \$WS не определён либо не" \
         "каталог; жертву фикстуры выводить не из чего" >&2
    exit 2
fi

C01="check-01-corpus-matches-manifest.sh"

# ── ЖЕРТВЫ И ЧИСЛА ВЫВОДЯТСЯ ИЗ ДЕРЕВА, А НЕ ВЫПИСЫВАЮТСЯ ───────────────────
#
# Выписанное имя переживает свой предмет МОЛЧА — ровно тот класс, ради которого
# набор и заведён. Измерено на переезде правила между каталогами: фикстура
# близнеца «переименование, доехавшее и до манифеста» становилась ПУСТОЙ — её
# `mv` отвечал «нет такого файла», замена имени не находила подстроки, md5
# манифеста до и после совпадал, — а печатала она дословно то же `[OK]`, что и на
# нетронутой копии.
#
# ЖЕРТВА — первое правило, у которого есть ОБЕ стороны: строка в таблице манифеста
# и файл в каталоге. Фикстуры и переименовывают её в манифесте, и двигают на
# диске, поэтому годится только имя с обеими сторонами.
inj01_victim="$(python3 - "$WS" <<'PY'
import io, os, re, sys
ws = sys.argv[1]
man = os.path.join(ws, '.claude', 'rules', 'MANIFEST.md')
for line in io.open(man, encoding='utf-8'):
    m = re.match(r'^\|\s*`?([^|`]+?)`?\s*\|', line)
    if not m:
        continue
    name = re.sub(r'^\.claude/rules/', '', m.group(1).strip())
    if name.endswith('.md') and os.path.isfile(os.path.join(ws, '.claude', 'rules', name)):
        print(name)
        break
PY
)"
if [ -z "$inj01_victim" ]; then
    echo "[VOID] inject-01 — в таблице MANIFEST.md нет ни одного имени, которому отвечает" \
         "файл в .claude/rules/; жертву выводить не из чего" >&2
    exit 2
fi
echo "-- жертва выведена из дерева: «$inj01_victim» --"

# ЧИСЛО ЗАПИСЕЙ КОРПУСА считается ТЕМ ЖЕ населением, что и гейтом: обычные файлы И
# ссылки, рекурсивно. Выписанное число («прочитано записей 19») стало бы ложным на
# первом же ЗАКОННОМ изменении состава, а состав меняться вправе: рост,
# объявленный человеком, назван законным в шапке самой check-01.
inj01_entries() {   # <каталог песочницы>
    find "$1/.claude/rules" -mindepth 1 \( -type f -o -type l \) 2>/dev/null | wc -l
}

# ── ПРАВКА ТАБЛИЦЫ МАНИФЕСТА В ПЕСОЧНИЦЕ ────────────────────────────────────
#
# ВСЯКАЯ ОПЕРАЦИЯ ОБЯЗАНА ЧТО-ТО ИЗМЕНИТЬ и отказывает, если не изменила: замена
# по подстроке молча вырождается в no-op, когда имя переехало, — и утверждение,
# ради которого фикстура ставилась, начинает относиться к нетронутому дереву.
inj01_table() {   # <каталог песочницы> <операция> [аргумент]
    python3 - "$1/.claude/rules/MANIFEST.md" "$2" "${3-}" <<'PY'
import io, re, sys
path, op, arg = sys.argv[1], sys.argv[2], sys.argv[3]
before = io.open(path, encoding='utf-8').read()
lines = before.split('\n')


def rows():
    out = []
    for i, l in enumerate(lines):
        m = re.match(r'^\|\s*`?([^|`]+?)`?\s*\|', l)
        if m and m.group(1).strip().endswith('.md'):
            out.append((i, re.sub(r'^\.claude/rules/', '', m.group(1).strip())))
    return out


idx = rows()
if op == 'gut':                       # снять все строки таблицы
    for i, _ in reversed(idx):
        del lines[i]
elif op == 'drop':                    # снять строку названного правила
    i = next(k for k, n in idx if n == arg)
    del lines[i]
elif op == 'rename':                  # переименовать правило В СТРОКЕ
    i = next(k for k, n in idx if n == arg)
    lines[i] = lines[i].replace(arg, arg[:-3] + '-local.md')
elif op == 'declare':                 # дописать строку про новое правило
    i = idx[-1][0]
    lines.insert(i + 1, '| `%s` | проба инъекции | гейт-свидетель |' % arg)
elif op == 'empty-cells':             # ячейки строки выпотрошены, имя на месте
    i = next(k for k, n in idx if n == arg)
    lines[i] = '| `%s` |  |  |' % arg
elif op == 'prose-names-md':          # проза манифеста называет координаты
    lines += ['', 'Состав объявляет таблица выше; `%s` лежит в `.claude/rules/`.' % arg]
elif op == 'fenced-row':              # ПРИМЕР строки в блоке кода, не живая строка
    lines += ['', '## Форма строки', '', '```',
              '| `%s` | действие | держатель |' % arg, '```']
else:
    raise SystemExit('unknown op ' + op)
after = '\n'.join(lines)
if after == before:
    raise SystemExit(
        'ФИКСТУРА ВАКУУМНА: операция «%s» с аргументом «%s» не изменила таблицу '
        'MANIFEST.md; утверждение о вердикте гейта относилось бы к нетронутому '
        'дереву' % (op, arg))
io.open(path, 'w', encoding='utf-8').write(after)
PY
}

# Утверждение об ОТСУТСТВИИ строки в вердикте. Помощник живёт в ЧАСТИ, а не в
# общем входе: общий вход за час переписывали дважды, и добавленный туда помощник
# уехал бы с чужой правкой (см. шапку файла).
inj01_assert_lacks() {   # <подстрока> <утверждение>
    if printf '%s\n' "$OUT" | grep -qF -- "$1"; then
        echo "  [FAIL] $2 — в вердикте есть лишнее «$1»" >&2
        printf '%s\n' "$OUT" | sed 's/^/         | /' >&2
        fail=$((fail + 1))
    else
        echo "  [OK]   $2"; pass=$((pass + 1))
    fi
}

# Вердикт состоит ТОЛЬКО из строк гейта. Утверждение по форме строки, а не по
# тексту жалобы: текст шелла зависит от локали и на другой машине не совпал бы.
inj01_assert_only_gate_lines() {   # <утверждение>
    local stray
    stray="$(printf '%s\n' "$OUT" | grep -vE '^\[(PASS|FAIL|VOID|CENSUS)\] ' | grep -v '^$')"
    if [ -n "$stray" ]; then
        echo "  [FAIL] $1 — в вердикте посторонние строки" >&2
        printf '%s\n' "$stray" | sed 's/^/         | /' >&2
        fail=$((fail + 1))
    else
        echo "  [OK]   $1"; pass=$((pass + 1))
    fi
}

echo "-- ось: корпус вырос молча --"
d01="$(sandbox c01_extra)"
printf '# ещё одно правило\n' > "$d01/.claude/rules/inj01-undeclared.md"
capture "$d01" "$C01"
assert_code 1 "ДЕФЕКТ: файл в .claude/rules/ без строки в таблице"
assert_says "ЛИШНИЙ В КОРПУСЕ: .claude/rules/inj01-undeclared.md" "  ...и координата названа"
assert_says "прочитано записей .claude/rules $(inj01_entries "$d01")" \
    "  ...и перепись печатается НА НАХОДКЕ: «ноль находок» отличимо от «ноль прочитанного»"

echo "-- ось: правило корпуса пропало, строка осталась --"
d01="$(sandbox c01_missing)"
rm -f "$d01/.claude/rules/$inj01_victim"
capture "$d01" "$C01"
assert_code 1 "ДЕФЕКТ: объявленного правила нет в каталоге"
assert_says "НЕДОСТАЁТ В КОРПУСЕ" "  ...и вердикт назван своим именем"
assert_says "называет $inj01_victim" "  ...и координата названа"
assert_says "MANIFEST.md:" "  ...и названа СТРОКА манифеста, где обещание живёт"

echo "-- ось: строка снята, файл остался --"
# Обратная сторона той же сверки, и её надо доказать отдельно: множества равной
# мощности бывают разными, а односторонний разбор давал бы зелёное на подмене.
d01="$(sandbox c01_row_dropped)"
inj01_table "$d01" drop "$inj01_victim"
capture "$d01" "$C01"
assert_code 1 "ДЕФЕКТ: строка снята из таблицы, файл на месте"
assert_says "ЛИШНИЙ В КОРПУСЕ: .claude/rules/$inj01_victim" "  ...и координата названа"

echo "-- ось: ВТОРОЙ ДОМ ПРАВИЛ заведён заново --"
# Ось лежит ВНЕ каталога правил, и сверка множеств её не видит by construction.
d01="$(sandbox c01_second_home)"
mkdir -p "$d01/.claude/rulebook"
printf '# правило, которое не грузится ни одной сессией\n' > "$d01/.claude/rulebook/observability.md"
capture "$d01" "$C01"
assert_code 1 "ДЕФЕКТ: .claude/rulebook/ заведён заново"
assert_says "ВТОРОЙ ДОМ ПРАВИЛ: .claude/rulebook" "  ...и координата названа"
assert_says "не грузится ни одной сессией" "  ...и следствие названо, а не только факт"

echo "-- ось: пустой второй дом — тоже находка --"
# Пустой каталог вреда ещё не принёс, и ровно поэтому он опасен: это место, куда
# следующий кладёт ПЕРВЫЙ файл, и до того момента красного не будет ни от чего.
# Проба не синтетическая: такой остаток от `git mv` лежал в рабочем дереве
# 2026-09-13 и был снят по находке этого же гейта.
d01="$(sandbox c01_second_home_empty)"
mkdir -p "$d01/.claude/rulebook"
capture "$d01" "$C01"
assert_code 1 "ДЕФЕКТ: .claude/rulebook/ существует, хоть и пуст"
assert_says "ВТОРОЙ ДОМ ПРАВИЛ" "  ...и вердикт назван своим именем"

echo "-- ось: файл корпуса скрыт .gitignore --"
# ФАКТ, ОТНОСЯЩИЙСЯ К НАХОДКЕ, ОДИН: запись корпуса невидима git. Всё остальное в
# фикстуре поставлено ради того, чтобы он был ОДИН: новичок объявлен строкой,
# поэтому состав сходится и «ЛИШНИЙ» не звучит — это утверждается отдельно.
#
# ОДНОЙ ПРАВКОЙ ЭТУ ОСЬ НЕ ВНЕСТИ, и причина в предикате, а не в лени. `git
# check-ignore` СМОТРИТ В ИНДЕКС: отслеживаемый файл он ignored не назовёт, даже
# когда правило игнора под него подходит, — и это верно по существу, потому что
# отслеживаемый файл в свежем клоне ЕСТЬ. Проба «дописать игнор на существующее
# правило» поэтому давала зелёное, и зелёное было ПРАВИЛЬНЫМ: измерено здесь же,
# первая редакция этой оси разошлась ровно так.
d01="$(sandbox c01_hidden)"
printf '# правило, невидимое в свежем клоне\n' > "$d01/.claude/rules/inj01-hidden.md"
inj01_table "$d01" declare inj01-hidden.md
printf '.claude/rules/inj01-hidden.md\n' >> "$d01/.gitignore"
capture "$d01" "$C01"
assert_code 1 "ДЕФЕКТ: объявленная запись корпуса исключена .gitignore"
assert_says "СКРЫТ ОТ GIT: .claude/rules/inj01-hidden.md" "  ...и координата названа"
inj01_assert_lacks "ЛИШНИЙ В КОРПУСЕ" "  ...и диагноз ОДИН: строка есть, дело не в составе"

echo "-- ось: выпотрошенная таблица — НАХОДКА, а не VOID (антимаска) --"
# Отдай гейт здесь VOID, и пустая таблица стала бы способом его погасить.
d01="$(sandbox c01_gutted)"
inj01_table "$d01" gut
capture "$d01" "$C01"
assert_code 1 "ДЕФЕКТ: таблица не объявляет ни одного правила"
assert_says "не разобрано НИ ОДНОГО имени правила" "  ...и названо, что объявление пусто"

echo "-- ось: снятый манифест при живом каталоге — НАХОДКА, а не VOID --"
# Правка против прежней редакции: она отдавала здесь код 2, то есть отсутствие
# объявления при наличии объявляемого называла «предмета нет».
d01="$(sandbox c01_noman)"
rm -f "$d01/.claude/rules/MANIFEST.md"
capture "$d01" "$C01"
assert_code 1 "ДЕФЕКТ: манифест снят, каталог правил стоит"
assert_says "единственное объявление состава снято" "  ...и названо, что снято именно объявление"

echo "-- ось: пустой обход — ОТКАЗ, а не «находок 0» --"
d01="$(sandbox c01_empty)"
rm -f "$d01"/.claude/rules/*
capture "$d01" "$C01"
assert_code 1 "записей корпуса не прочитано ни одной ⇒ код 1"
assert_says "прочитано записей .claude/rules 0" "  ...и перепись называет ноль прочитанного"

echo "-- ось: предмета нет — код 2, и это НЕ успех --"
d01="$(sandbox c01_nodir)"
rm -rf "$d01/.claude/rules"
capture "$d01" "$C01"
assert_code 2 "каталога правил нет вовсе — корпуса в этом дереве не существует"

# ── ось: СИМВОЛЬНАЯ ССЫЛКА — тоже запись каталога ────────────────────────────
#
# Заведена 2026-09-07 по находке противника. До неё набор собирался через
# `find -type f`, а `-type f` ссылок не видит ВОВСЕ: живая ссылка на правило
# лежала в каталоге, читалась, тянула 1326 строк в окно — и гейт печатал
# «прочитано файлов ядра 3 … лишних 0», код 0. Молчание, а не красное: ровно
# класс `.claude/rules/testing.md` §«Гейт на класс», п.7.
#
# ПЕРВАЯ проба — ОДНО-ФАКТНАЯ (там же, п.2в). Она не заводит новой записи, а
# снимает у существующей ТОЛЬКО новое свойство: имя жертвы объявлено и на месте,
# набор по-прежнему сходится с манифестом, изменился один факт — запись перестала
# быть обычным файлом. Значит краснеет ровно новая ось, и её красное не одолжено
# у соседней.
echo "-- ось: ссылка в корпусе --"
#
# ДВЕ ПРОБЫ, А НЕ ОДНА: у ссылки два исхода, и вердикт обязан их различать.
# Резолвящаяся ссылка читается — содержимое правила при этом лежит ВНЕ
# объявленного набора; битая не читается вовсе. Одна проба оставила бы вторую
# ветку сообщения без единого прогона, а непрогнанная ветка диагностики врёт ровно
# так же, как непрогнанная проверка.
#
# Первая — ОДНО-ФАКТНАЯ (`.claude/rules/testing.md` §«Гейт на класс», п.2в): имя
# жертвы объявлено, набор по-прежнему сходится с манифестом, изменился один факт —
# запись перестала быть обычным файлом, а её содержимое уехало наружу.
