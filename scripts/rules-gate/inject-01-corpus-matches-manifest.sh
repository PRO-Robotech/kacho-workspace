echo "-- законные близнецы: гейт обязан смолчать --"
#
# У КАЖДОГО БЛИЗНЕЦА ОТДЕЛЬНО УТВЕРЖДАЕТСЯ, ЧТО ЕГО ФИКСТУРА НЕ ПУСТА. Молчание
# гейта на дереве, которого фикстура не тронула, доказывает ровно ничего, а
