# ничем. Дефектной фикстуре такое утверждение не нужно: она, ничего не изменив,
# оставит гейт зелёным и уронит собственное `assert_code 1` (вакуумный дефект
# ГРОМОК by construction, вакуумный близнец МОЛЧАЛИВ).

