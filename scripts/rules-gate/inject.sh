#!/usr/bin/env bash
#
# Обратные кавычки во вносимых строках — РАЗМЕТКА markdown, а не подстановка
# команды, и одинарные кавычки вокруг них намеренны. До 2026-09-18 это стояло
# здесь глобальным `disable=SC2016` НА ВЕСЬ ФАЙЛ — и вместе с разметкой гасило бы
# настоящую пропущенную подстановку в любой будущей строке: отвод, который не
# называет места, перестаёт быть решением и становится слепотой. Теперь отвод
# стоит АДРЕСНО у каждой фикстуры, где разметка живёт, и с доводом на месте.
#
# Доказательство набора rules-gate ИНЪЕКЦИЕЙ В ОБЕ СТОРОНЫ — на ВРЕМЕННОЙ копии
# дерева. Рабочее дерево не читается на запись и не меняется ни одной пробой.
#
# ЗАЧЕМ. Зелёные проверки на сошедшемся дереве не доказывают ничего: ровно так же
# выглядит набор, потерявший способность краснеть. Моделью загрузки (решение
# владельца 2026-09-17) держится ВСЁ поведение агентов, и всякий её разрыв
# молчалив: правило, вернувшееся в `@import` корневого CLAUDE.md, приезжает каждому
# агенту всегда; шаблон исключения, снятый из настроек, возвращает в окно весь
# корпус; настройка `agent`, потерянная одной правкой JSON, отдаёт главному потоку
# Read и Bash обратно. Ни одно из этих состояний не ломает ни одного прогона
# продукта. Поэтому по каждой оси сюда вносится НАСТОЯЩИЙ дефект (проверка обязана
# покраснеть И НАЗВАТЬ координату) и рядом ставится ЗАКОННЫЙ БЛИЗНЕЦ той же формы
# (проверка обязана смолчать). Без близнеца проверка ловила бы форму, а не
# существо, и первый ложный срабат отключил бы её вместе с настоящими находками.
#
# ПРЕДМЕТ ИНВЕРТИРОВАН ВМЕСТЕ С НАБОРОМ, и старые фикстуры не переписаны, а
# ПЕРЕВЁРНУТЫ. То, что до 2026-09-17 было дефектом, стало законным близнецом, и
# наоборот:
#   · правило БЕЗ строки `@import` — было «НЕ ИМПОРТИРОВАН» (код 1), стало нормой;
#   · правило в подкаталоге и правило с расширением `.MD` без объявления — были
#     находками, стали близнецами: они не грузятся, и так и задумано;
#   · ссылка на снятый дом ВНУТРИ файла правила — была находкой транзитивно, стала
#     близнецом: файл правила в замыкание не входит, его текст никто не вычисляет;
#   · строка `@.claude/rules/…` в CLAUDE.md — была объявлением, стала дефектом.
# Перевёрнутая пара сильнее новой: она доказывает, что проверка сменила ПРЕДМЕТ, а
# не потеряла чувствительность.
#
# ПРОВЕРЯЕТСЯ НЕ ТОЛЬКО КОД, НО И ЧТО НАПЕЧАТАНО. Находка, называющая симптом
# вместо координаты, посылает читателя искать не там; на неё тратят прогон, а
# потом снимают гейт как непонятный. Поэтому у каждого дефекта есть утверждение
# о ТЕКСТЕ вердикта, а не только о его коде.
#
# ОДИН ФАКТ НА ИНЪЕКЦИЮ. Каждая проба меняет ровно одно и меняет это там, где
# живёт предмет проверки. Инъекция вида «завести ещё один элемент» отвергнута
# намеренно: новый элемент нарушает всё, что требуется от элементов вообще, и
# красное пришло бы неизвестно от чего.
#
# КОНТРАКТ НАБОРА. Проверка обязана читать корень из `RULES_GATE_ROOT` — иначе её
# нельзя прогнать во временной копии, а инъекция в настоящем дереве не инъекция,
# а порча. Контрольный прогон идёт по ВСЕМ проверкам набора, выведенным глобом из
# дерева, а не по выписанному списку: выписанный разошёлся бы молча.
#
# ПЕСОЧНИЦА НЕСЁТ ВСЮ МОДЕЛЬ, А НЕ ОДИН КАТАЛОГ ПРАВИЛ. Копируются `CLAUDE.md`,
# `.claude/rules`, `.claude/agents`, `.claude/skills` и `.claude/settings.json`:
# предмет набора после 2026-09-17 — связка «правило → скилл-ссылка → `skills:`
# агента → база диспетчера → настройки», и проверка, которой в копии не дали
# половину связки, отчитывалась бы беспредметностью, а не молчанием.
#
# ПЕРЕПИСЬ СВЕРЯЕТСЯ, А НЕ ПЕЧАТАЕТСЯ. Два числа рядом («проверок на контроле»
# и «подключено частей») переписью не являются, пока их никто не сличает: до
# 2026-09-07 инъекция печатала их и выходила НУЛЁМ на дереве, где четвёртая
# проверка не доказана НИЧЕМ, — заведомо мёртвая (всегда PASS) проверка не
# изменила ни кода, ни текста «гейт доказан в обе стороны». Поэтому теперь по
# КАЖДОЙ проверке набора требуется пара: ≥1 удавшееся утверждение о НАХОДКЕ
# (ожидался код 1) и ≥1 о ЗАКОННОМ БЛИЗНЕЦЕ (ожидался 0) ВНЕ контрольного цикла.
#
#   Почему «имя проверки встречается в утверждениях» негодный предикат — это
#   измерено, а не предположено: контрольный цикл ниже прогоняет ВСЕ проверки
#   глоба с `assert_code 0`, поэтому имя любой новой проверки фигурирует в
#   утверждении ПО ПОСТРОЕНИЮ. Такой предикат удовлетворён у мёртвой проверки и
#   не доказывает ничего.
#
# ЧАСТИ НЕ ИСПОЛНЯЮТСЯ САМОСТОЯТЕЛЬНО, и каждая несёт стража подключения: в
# обход этого файла у части нет ни песочницы, ни утверждений, а пути в ней
# становятся относительными и уезжают в РАБОЧЕЕ дерево. Подробности и замер — в
# шапке любой из частей.
#
# Коды выхода: 0 — все утверждения сошлись; 1 — хотя бы одно нет либо проверка
# набора не доказана ни одной частью; 2 — не исполнено ни одного утверждения
# (это НЕ успех).

set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WS="$(cd "$HERE/../.." && pwd)"
GATE="$HERE"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

pass=0; fail=0
OUT=""; RC=0

# ── УЧЁТ ДОКАЗАННОСТИ ПО КАЖДОЙ ПРОВЕРКЕ ─────────────────────────────────────
#
# Ключ — имя файла проверки, как его выдаёт глоб дерева. Учёт ведёт `capture`
# (ей имя приходит вторым параметром) и `assert_code`, потому что доказательство
# — это ОЖИДАЕМЫЙ КОД удавшегося утверждения, а не упоминание имени в тексте.
declare -A proof_find=()   # ожидался 1 и сошлось: проверка УМЕЕТ находить
declare -A proof_twin=()   # ожидался 0 и сошлось: проверка УМЕЕТ молчать
declare -A proof_void=()   # ожидался 2 и сошлось: проверка УМЕЕТ отказать по предмету
LAST_CHECK=""
# Контрольный цикл в доказательство НЕ идёт: он утверждает 0 у КАЖДОЙ проверки
# глоба, поэтому засчитывать его близнецом значит доказывать по построению.
PROOF_ON=0

# sandbox <имя> — свежая копия ВСЕЙ модели загрузки со своим git-индексом.
#
# ЧТО КОПИРУЕТСЯ И ПОЧЕМУ ИМЕННО ЭТО. `CLAUDE.md` — корень замыкания автозагрузки;
# `.claude/rules` — корпус; `.claude/agents` — база маршрутизации и определения
# исполнителей; `.claude/skills` — скилл-ссылки `rule-*`, которыми правило доезжает
# до агента; `.claude/settings.json` — исключение автозагрузки и настройка главного
# потока. Выкинь любое из пяти — и проверка, чей предмет там живёт, ответит
# беспредметностью, а перепись покажет ноль прочитанного: «находок 0» станет
# неотличимо от «не смотрели» в самой фикстуре.
#
# КОПИРУЕТСЯ ОДИН ДОМ ПРАВИЛ, и это не упрощение. До 2026-09-13 сюда копировался
# ещё `.claude/rulebook`; каталог снят, и копирование его «на всякий случай»
# завело бы в КАЖДОЙ песочнице ровно тот второй дом, который check-01 обязан
# находить, — то есть контрольный прогон краснел бы на фикстуре набора.
#
# `cp -a`, А НЕ `cp -r`: `.claude/skills/rule-*/SKILL.md` — СИМВОЛЬНЫЕ ССЫЛКИ в
# `../../rules/`, и ими правило закрепляется за агентом. Копирование, которое их
# разыменует, отдаёт в песочницу обычные файлы — и проверка привязки судила бы
# дерево, которого нет ни на одной машине.
sandbox() {
    local dir="$TMP/s.$1"
    rm -rf "$dir"; mkdir -p "$dir/.claude"
    cp "$WS/CLAUDE.md" "$dir/"
    cp -a "$WS/.claude/rules" "$dir/.claude/"
    cp -a "$WS/.claude/agents" "$dir/.claude/" 2>/dev/null || true
    cp -a "$WS/.claude/skills" "$dir/.claude/" 2>/dev/null || true
    cp -a "$WS/.claude/settings.json" "$dir/.claude/" 2>/dev/null || true
    # АРХИВ — ЧАСТЬ ПРЕДМЕТА check-07: адрес, указывающий в `.claude/backup/`, верен,
    # потому что норма там лежит. Копия без архива сделала бы 182 законных адреса
    # висячими и красила бы нетронутое дерево.
    cp -a "$WS/.claude/backup" "$dir/.claude/" 2>/dev/null || true
    cp "$WS/.gitignore" "$dir/" 2>/dev/null || true
    git -C "$dir" init -q >/dev/null 2>&1
    git -C "$dir" add -A >/dev/null 2>&1
    echo "$dir"
}

# capture <каталог> <имя проверки> — заполняет RC и OUT; имя запоминается, по
# нему `assert_code` ведёт учёт доказанности этой проверки.
capture() {
    LAST_CHECK="$2"
    OUT="$( cd "$1" && RULES_GATE_ROOT="$1" bash "$GATE/$2" 2>&1 )"
    RC=$?
}

assert_code() {   # <ожидаемый> <утверждение>
    if [ "$1" = "$RC" ]; then
        echo "  [OK]   $2"; pass=$((pass + 1))
        if [ "$PROOF_ON" = 1 ] && [ -n "$LAST_CHECK" ]; then
            case "$1" in
                0) proof_twin["$LAST_CHECK"]=$(( ${proof_twin["$LAST_CHECK"]:-0} + 1 )) ;;
                2) proof_void["$LAST_CHECK"]=$(( ${proof_void["$LAST_CHECK"]:-0} + 1 )) ;;
                *) proof_find["$LAST_CHECK"]=$(( ${proof_find["$LAST_CHECK"]:-0} + 1 )) ;;
            esac
        fi
    else
        echo "  [FAIL] $2 — ожидался код $1, получен $RC" >&2
        printf '%s\n' "$OUT" | sed 's/^/         | /' >&2
        fail=$((fail + 1))
    fi
}

assert_says() {   # <подстрока> <утверждение>
    if printf '%s\n' "$OUT" | grep -qF -- "$1"; then
        echo "  [OK]   $2"; pass=$((pass + 1))
    else
        echo "  [FAIL] $2 — в вердикте нет «$1»" >&2
        printf '%s\n' "$OUT" | sed 's/^/         | /' >&2
        fail=$((fail + 1))
    fi
}

# assert_lacks <подстрока> <утверждение> — ДИАГНОЗ ОДИН.
#
# Находка, назвавшая две оси разом, посылает чинить две вещи там, где сломана
# одна: правку внесут по обеим, гейт покраснеет снова (или перестанет краснеть на
# настоящей причине), и круг оплачен зря. Помощник общий, потому что предмет общий
# у всех частей набора, а не у одной.
assert_lacks() {
    if printf '%s\n' "$OUT" | grep -qF -- "$1"; then
        echo "  [FAIL] $2 — в вердикте есть лишнее «$1»" >&2
        printf '%s\n' "$OUT" | sed 's/^/         | /' >&2
        fail=$((fail + 1))
    else
        echo "  [OK]   $2"; pass=$((pass + 1))
    fi
}

# ── ФИКСТУРА ОБЯЗАНА ИЗМЕНИТЬ ПЕСОЧНИЦУ ──────────────────────────────────────
#
# Правка, ничего не изменившая, делает утверждение ВАКУУМНЫМ: гейт молчит на
# дереве, которого никто не трогал, а `[OK]` его близнеца дословно совпадает с
# `[OK]` на нетронутой копии. Измерено на дереве, где `writing.md` ЗАКОННО
# переехал в свод: близнец «переименование, доехавшее и до манифеста» печатал
# `[OK]`, при том что его `mv` отвечал «нет такого файла», а замена имени в
# §«Ядро» не находила подстроки — md5 манифеста до и после совпадал.
#
# Отпечаток берётся по СОДЕРЖИМОМУ и ТИПУ каждой записи, а не по mtime: часть
# фикстур подменяет файл ссылкой, и различие типа обязано считаться правкой.
sandbox_digest() {   # <каталог песочницы>
    (
        cd "$1" 2>/dev/null || exit 0
        find . -path ./.git -prune -o -print0 2>/dev/null \
        | LC_ALL=C sort -z \
        | while IFS= read -r -d '' e; do
              if [ -L "$e" ]; then printf 'l %s -> %s\n' "$e" "$(readlink "$e")"
              elif [ -f "$e" ]; then printf 'f %s %s\n' "$e" "$(md5sum < "$e" | cut -d' ' -f1)"
              else printf 'd %s\n' "$e"; fi
          done
    ) | md5sum | cut -d' ' -f1
}

# assert_fixture_changed <каталог> <отпечаток ДО> <утверждение>
#
# Ставится у ЗАКОННЫХ БЛИЗНЕЦОВ (ожидаемый код 0). Дефектной фикстуре она не
# нужна: та, ничего не изменив, оставит гейт зелёным, и её собственное
# `assert_code 1` покраснеет — вакуумный дефект ГРОМОК by construction, вакуумный
# близнец МОЛЧАЛИВ.
assert_fixture_changed() {
    local now; now="$(sandbox_digest "$1")"
    if [ "$now" = "$2" ]; then
        echo "  [FAIL] ФИКСТУРА ВАКУУМНА · $3 — правка не изменила песочницу $1;" \
             "утверждение о молчании гейта относится к НЕТРОНУТОМУ дереву" >&2
        fail=$((fail + 1))
    else
        echo "  [OK]   фикстура изменила песочницу · $3"; pass=$((pass + 1))
    fi
}

# ── КОНТРОЛЬ: нетронутая копия — молчат ВСЕ проверки набора ──────────────────
#
# Перечень проверок выводится глобом из дерева: набор растёт, и выписанный
# список отстал бы от него молча. Пустой глоб — ОТКАЗ, а не молчаливый успех:
# инъекция, потерявшая свои проверки, вышла бы нулём и объявила доказанным то,
# чего не прогоняла ни разу.
echo "== контроль: нетронутая копия — все проверки набора молчат =="
d="$(sandbox control)"
checks=0
for c in "$GATE"/check-*; do
    [ -f "$c" ] || continue
    checks=$((checks + 1))
    n="$(basename "$c")"
    capture "$d" "$n"
    assert_code 0 "нетронутая копия · $n"
done
if [ "$checks" -eq 0 ]; then
    echo "инъекция rules-gate: проверок в $GATE не найдено — доказывать нечего" >&2
    exit 2
fi
PROOF_ON=1     # дальше идут утверждения, которые ЧТО-ТО доказывают

# ── имена берутся ИЗ ДЕРЕВА, а не выписываются ──────────────────────────────
#
# Жертвой первой оси намеренно выбрано правило, чью координату CLAUDE.md УЖЕ
# называет в прозе в обратных кавычках. Пара на ней самая острая в наборе, потому
# что различие между дефектом и близнецом — две обратные кавычки: с ними это
# координата, которую читает человек, без них — импорт правила в окно каждого
# агента. Проверка обязана покраснеть на второй и смолчать на первой.
prose_rule="$(python3 - "$WS" <<'PY'
import os, re, sys
ws = sys.argv[1]
claude = open(os.path.join(ws, "CLAUDE.md"), encoding="utf-8").read()
names = sorted(n for n in os.listdir(os.path.join(ws, ".claude", "rules"))
               if n.endswith(".md"))
for n in names:
    # координата правила, названная В ПРОЗЕ: в обратных кавычках и БЕЗ `@`
    if re.search(r"`\.claude/rules/" + re.escape(n) + r"`", claude):
        print(n); break
else:
    print(names[0] if names else "")
PY
)"
# Имена берутся ГЛОБОМ ОБОЛОЧКИ, а не разбором `ls`: разбор вывода `ls` спотыкается
# на не-алфавитных именах, а корпус русский (shellcheck SC2012).
corpus_rule=""
for _f in "$WS"/.claude/rules/*.md; do
    [ -f "$_f" ] || continue
    case "$(basename "$_f")" in MANIFEST*) continue ;; esac
    corpus_rule="$(basename "$_f")"; break
done
unset -v _f
if [ -z "$corpus_rule" ] || [ -z "$prose_rule" ]; then
    echo "инъекция rules-gate: в .claude/rules/ нет ни одного правила помимо манифеста — жертву выводить не из чего" >&2
    exit 2
fi

# Жертва оси «определение агента в автозагрузке» — ЛЮБОЙ исполнитель, а не
# диспетчер: у базы диспетчера есть своя проверка и свой объём, и находка на ней
# читалась бы как находка о бюджете. Имя выводится глобом по той же причине.
agent_file=""
for _a in "$WS"/.claude/agents/*.md; do
    [ -f "$_a" ] || continue
    case "$(basename "$_a")" in dispatcher.md) continue ;; esac
    agent_file="$(basename "$_a")"; break
done
unset -v _a
if [ -z "$agent_file" ]; then
    echo "инъекция rules-gate: в .claude/agents/ нет ни одного исполнителя — ось «агент в автозагрузке» доказывать нечем" >&2
    exit 2
fi

# ИМЯ ВО ВТОРОМ ДОМЕ — СИНТЕТИЧЕСКОЕ, И ЭТО НЕСУЩЕЕ. Каталог `.claude/rulebook/`
# снят решением владельца 2026-09-13, значит настоящего имени оттуда взять неоткуда
# by construction. Оно обязано НЕ пересекаться с корпусом: возьми мы имя живого
# правила, фикстура меняла бы два факта — ссылку во второй дом и совпадение с
# существующим файлом, — и красное пришло бы неизвестно от чего.
ghost_rule="inj00-second-home.md"
if [ -e "$WS/.claude/rules/$ghost_rule" ]; then
    echo "инъекция rules-gate: «$ghost_rule» существует в корпусе — синтетическое имя перестало быть синтетическим" >&2
    exit 2
fi
echo
echo "жертвы выведены из дерева: правило в прозе «$prose_rule», правило корпуса «$corpus_rule»," \
     "исполнитель «$agent_file»; имя во втором доме синтетическое: «$ghost_rule»"

