# ═════════════════════════════════════════════════════════════════════════════
# ТОЧКА РАСШИРЕНИЯ: части соседних проверок набора
# ═════════════════════════════════════════════════════════════════════════════
#
# Файл общий на все проверки; тот, кто не хочет править его посередине, кладёт
# рядом `inject-NN-<предмет>.sh` и получает здешнюю оснастку готовой: `sandbox`,
# `sandbox_digest`, `capture`, `assert_code`, `assert_says`, `assert_lacks`,
# `assert_fixture_changed`, счётчики `pass`/`fail`, корень `$WS` и каталог
# песочниц `$TMP`.
#
# ПОДКЛЮЧЕНИЕ ИДЁТ ГЛОБОМ, А НЕ СПИСКОМ, и это несущее: части
# `inject-04-rule-agent-binding.sh` (привязка правило↔агент) и
# `inject-05-dispatcher-routes-every-agent.sh` (маршрутизация диспетчера) пишутся
# отдельной полосой и подхватываются здесь БЕЗ единой правки этого файла — ровно
# в тот момент, когда файл появляется рядом. Выписанный список пришлось бы править
# в двух местах, а расходятся такие списки молча и в ту сторону, где часть
# перестаёт прогоняться: сверка доказанности ниже покраснела бы «проверка не
# доказана», и починкой выглядело бы снятие проверки, а не подключение части.
parts=0
for part in "$HERE"/inject-*.sh; do
    [ -f "$part" ] || continue
    parts=$((parts + 1))
    echo
    echo "== часть: $(basename "$part") =="
    # shellcheck disable=SC1090
    . "$part"
done

echo
# ═════════════════════════════════════════════════════════════════════════════
# СВЕРКА ПЕРЕПИСИ: у каждой проверки набора обязана быть пара доказательств
# ═════════════════════════════════════════════════════════════════════════════
#
# Перепись, которую никто не сличает, переписью не является — это форма без
# содержания. До 2026-09-07 два числа ниже печатались рядом и не сверялись, и
# заведомо мёртвая четвёртая проверка (всегда PASS, ни одной части) давала
# «на контроле 4; подключено частей 3» при коде 0 и вердикте «доказан в обе
# стороны». Сверять при этом надо не сами числа: частей вправе быть меньше, чем
# проверок (общие оси check-02 живут в этом файле, а не в части), и равенство
# 3=3 ничего не значило бы. Сверяется ДОКАЗАННОСТЬ КАЖДОЙ ПРОВЕРКИ ПОИМЁННО.
uncovered=0
for c in "$GATE"/check-*; do
    [ -f "$c" ] || continue
    n="$(basename "$c")"
    f_find=${proof_find["$n"]:-0}
    f_twin=${proof_twin["$n"]:-0}
    f_void=${proof_void["$n"]:-0}
    echo "[CENSUS] доказательство $n: находок $f_find, законных близнецов $f_twin," \
         "отказов по предмету $f_void"
    if [ "$f_find" -eq 0 ] || [ "$f_twin" -eq 0 ]; then
        echo "[FAIL] ПРОВЕРКА НЕ ДОКАЗАНА: scripts/rules-gate/$n — удавшихся утверждений" \
             "о находке $f_find, о законном близнеце $f_twin (нужно ≥1 каждого, ВНЕ" \
             "контрольного цикла: он утверждает 0 у каждой проверки глоба и потому" \
             "удовлетворён по построению). Проверка, чью способность падать и молчать" \
             "никто не доказал, садится молча — и приезжает в ствол с зелёным" \
             "конвейером: инъекцию зовёт .github/workflows/ci.yaml" >&2
        uncovered=$((uncovered + 1))
    fi
done

echo
# Перепись объёма — отдельным утверждением, а не подразумеваемым: «утверждений 0,
# разошлось 0» иначе печаталось бы как успех.
echo "[CENSUS] инъекция rules-gate: проверок набора на контроле $checks;" \
     "подключено частей $parts; из проверок не доказано $uncovered;" \
     "утверждений $((pass + fail)) — сошлось $pass, разошлось $fail"
if [ "$((pass + fail))" -eq 0 ]; then
    echo "[VOID] инъекция rules-gate — не прогнано ни одного утверждения; это НЕ успех" >&2
    exit 2
fi
if [ "$fail" -gt 0 ]; then
    echo "[FAIL] инъекция rules-gate — гейт не доказан: разошлось $fail из $((pass + fail))" >&2
    exit 1
fi
if [ "$uncovered" -gt 0 ]; then
    echo "[FAIL] инъекция rules-gate — гейт не доказан: проверок набора $checks, из них" \
         "без пары доказательств $uncovered; утверждений $pass, разошлось 0 —" \
         "но не обо всём, что набор прогоняет" >&2
    exit 1
fi
echo "[PASS] инъекция rules-gate — гейт доказан в обе стороны: проверок $checks," \
     "у каждой есть находка и законный близнец; утверждений $pass, разошлось 0"
exit 0
