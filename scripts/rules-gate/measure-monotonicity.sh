# Пробы `probe_10` здесь НЕТ, и это не пропуск. Её предметом была проверка
# `check-10-owner-escalation-list-is-closed.sh`, снятая 2026-09-21 вместе с
# ведомостью и инъекцией: механизм отпечатка перенесён к остающемуся держателю
# `scripts/tooling-gate/check-11-owner-escalation-list-is-closed.sh` (ось D).
# Проба, пережившая свой предмет, попала бы в строку «НЕ ИЗМЕРЕНО» о проверке,
# которой в дереве нет, — то есть прибор докладывал бы о несуществующем.

# СТРОКА ТАБЛИЦЫ ВЫРАВНИВАЕТСЯ ПО СИМВОЛАМ, А НЕ ПО БАЙТАМ. `printf %-10s`
# считает байты, а «нет» в UTF-8 весит шесть, — колонки разъезжались, и таблицу,
# ради которой прибор и заведён, становилось трудно читать.
row() {   # <гейт> <вердикт> <чем проверил>
    local a="$1" b="$2" c="$3" pa="" pb="" i
    for (( i = ${#a}; i < 48; i++ )); do pa="$pa "; done
    for (( i = ${#b}; i < 11; i++ )); do pb="$pb "; done
    printf '%s%s | %s%s | %s\n' "$a" "$pa" "$b" "$pb" "$c"
}

# ── ЗАМЕР ────────────────────────────────────────────────────────────────────
checks=0; mono=0; nonmono=0; unmeasured=0; broken=0
row "гейт" "монотонен" "чем проверил"
printf -- '---\n'
for c in "$HERE"/check-*; do
    [ -f "$c" ] || continue
    checks=$((checks + 1))
    name="$(basename "$c")"
    num="$(printf '%s' "$name" | sed -n 's/^check-\([0-9][0-9]*\)-.*/\1/p')"
    fn="probe_$num"

    if ! command -v "$fn" > /dev/null 2>&1; then
        unmeasured=$((unmeasured + 1))
        row "$name" "НЕ ИЗМЕРЕНО" \
            "пробы дописывания для неё не объявлено — замер по ней НЕ вынесен"
        continue
    fi

    # Контроль и проба идут на ОДНОЙ песочнице: вывод проверки сравнивается с
    # выводом на ней же до правки, и разница каталогов в него не подмешивается.
    d="$(sandbox "prb$num")"
    run_check "$d" "$name"
    if [ "$RC" != 0 ]; then
        broken=$((broken + 1))
        row "$name" "ЗАМЕР НЕГОДЕН" \
            "на нетронутой копии код $RC — вердикт после пробы был бы не о пробе"
        continue
    fi
    ctl_out="$OUT"

    # Предпосылка постусловия: вывод проверки детерминирован. Иначе «вывод
    # изменился» верно всегда, и второй страж не стоит ничего.
    run_check "$d" "$name"
    if [ "$OUT" != "$ctl_out" ]; then
        broken=$((broken + 1))
        row "$name" "ЗАМЕР НЕГОДЕН" \
            "вывод недетерминирован: два прогона на нетронутой копии разошлись"
        continue
    fi

    before="$(digest "$d")"
    if ! "$fn" "$d" > /dev/null 2>&1; then
        unmeasured=$((unmeasured + 1))
        row "$name" "НЕ ИЗМЕРЕНО" \
            "проба не исполнилась (предпосылка не создалась) — замер НЕ вынесен"
        continue
    fi
    if [ "$(digest "$d")" = "$before" ]; then
        unmeasured=$((unmeasured + 1))
        row "$name" "НЕ ИЗМЕРЕНО" \
            "проба ВАКУУМНА — песочница не изменилась; зелёное относилось бы к нетронутой копии"
        continue
    fi
    run_check "$d" "$name"
    if [ "$OUT" = "$ctl_out" ]; then
        unmeasured=$((unmeasured + 1))
        row "$name" "НЕ ИЗМЕРЕНО" \
            "проба ПРОМАХНУЛАСЬ МИМО ПРЕДМЕТА: песочница изменилась, вывод проверки — нет"
        continue
    fi
    if [ "$RC" = 0 ]; then
        mono=$((mono + 1))
        row "$name" "ДА" \
            "дописывание ($fn) оставило код 0 — вставка, роняющая её, НЕ НАЙДЕНА"
    else
        nonmono=$((nonmono + 1))
        row "$name" "нет" \
            "дописывание ($fn) дало код $RC"
    fi
done

echo
if [ "$checks" -eq 0 ]; then
    echo "[VOID] замер монотонности — проверок в $HERE не найдено: мерить нечего" >&2
    exit 2
fi
echo "[CENSUS] замер монотонности по дописыванию: проверок набора $checks;" \
     "немонотонных $nonmono; монотонных (вставка не найдена) $mono;" \
     "НЕ ИЗМЕРЕНО $unmeasured; замер негоден $broken."
