#!/usr/bin/env bash
# check-06 — У ВЕЛИЧИНЫ «СУММА ПРЕДЗАГРУЗКИ НА АГЕНТА» ЕСТЬ ПРОИЗВОДИТЕЛЬ.
#
# ЧТО УТВЕРЖДАЕТ. Сумма набора считается ПО ДЕРЕВУ, ориентир читается из живого
# текста корпуса, а перечень над ориентиром ПЕЧАТАЕТСЯ здесь. Рукописной копии
# этого вывода в корпусе нет.
#
# ЗАЧЕМ ЗАВЕДЕНА, И ЦЕНА ИЗМЕРЕНА. Пока производителя не было, перечень считало
# внимание — и 2026-09-19 насчитало ЧЕТВЕРЫХ при ПЯТИ: `landing-reviewer`
# пересёк ориентир той же правкой, что записывала этот класс, и в прозу не попал.
# Первая редакция проверки судила ЯРЛЫК первой ячейки («над ориентиром», «над
# бюджетом») — и пропускала таблицу переписи, стоявшую четырьмя строками выше
# абзаца, который её запрещает: у той таблицы ярлыка нет, а числа — дословный
# вывод этой же проверки. Ярлык есть ОПИСАНИЕ копии, а не сама копия.
#
# ПОЭТОМУ СУДИТСЯ СВОЙСТВО, А НЕ СЛОВО. Копия узнаётся ДВУМЯ половинами, и ни
# одна из них не смотрит на слова:
#
#   A. ТОЖДЕСТВО С ВЫВОДОМ. Живая строка таблицы несёт число, РАВНОЕ одной из
#      величин, которые эта перепись производит сейчас (сумма любого набора либо
#      размер корпуса). Свежая копия ловится по построению — сравнением с
#      собственным выводом, а не с догадкой о том, как её назовут.
#   B. ВЕЛИЧИНА РЯДОМ С ИМЕНЕМ. Живая строка таблицы называет агента из таблицы
#      закрепления И несёт число не меньше наименьшей измеренной суммы набора.
#      Ловит копию, УЖЕ РАЗОШЕДШУЮСЯ с деревом: её числа тождеству не равны, но
#      порядок величины выдаёт байты набора, а не долю, счёт или процент.
#   ТРЕТЬЕЙ ПОЛОВИНЫ — ПО ЯРЛЫКУ ЯЧЕЙКИ — НЕТ, И ОНА СНЯТА ПО ЗАМЕРУ. Она искала
#   слова «над ориентиром», «над бюджетом», «превышают ориентир» в любой ячейке
#   и на этом дереве дала ДВЕ находки, ОБЕ ЛОЖНЫЕ: ячейку манифеста, которая
#   объясняет, что перечень над ориентиром печатает ЭТА проверка, и строку
#   `multi-agent-flow.md`, говорящую, что набор агента держится ПОД ориентиром.
#   Первая — ровно класс `testing.md` §«Гейт на класс» п.4: проверка краснеет на
#   собственном объяснении. Гейт, краснеющий на верном тексте, отключают первым,
#   и вместе с ним уходит производитель числа.
#
#   ГРАНИЦ ТРИ, и все три измерены контролями в обе стороны.
#
#   (1) Перечисление одних ИМЁН без чисел копией вывода не считается: вывод
#       переписи есть ЧИСЛА, и строка без них ничего из него не повторяет.
#   (2) Копия, уже разошедшаяся с деревом И несущая величину МЕНЬШЕ сегодняшнего
#       минимума набора, не ловится ни одной половиной: она отстала бы на
#       порядок, а не на правку.
#   (3) РАЗОШЕДШАЯСЯ КОПИЯ, НЕ НАЗЫВАЮЩАЯ АГЕНТА, НЕ ЛОВИТСЯ НИЧЕМ — ПРИ ЛЮБОЙ
#       ВЕЛИЧИНЕ. Половина A требует ТОЧНОГО равенства произведённой величине,
#       половина B — имени агента в строке; копия без имени, разошедшаяся хоть на
#       байт, не подпадает ни под одну. Контроли (2026-09-19, дописыванием строки
#       в живую таблицу): точная сумма набора без имени — код 1; она же мимо на
#       369 Б без имени — код 0; то же мимо, но С именем агента — код 1.
#
#       Запись строки двигает величину корпуса, но СДВИГ ПОСТОЯНЕН — длина строки
#       от значения не зависит, пока число той же разрядности, — поэтому
#       «значение = база + длина строки» решается подстановкой и сходится ЗА ОДНУ
#       ИТЕРАЦИЮ: контроль 2026-09-19 дал базу 1 031 007, длину 39 Б, неподвижную
#       точку 1 031 046 и код 1 «тождество с выводом». Тождество для величины
#       корпуса ДОСТИЖИМО, и прежняя редакция этой шапки, объявлявшая его
#       недостижимым, была ложной: она сама называла приём («свели к неподвижной
#       точке») и тут же объявляла его случайностью — два утверждения об одном
#       предмете в четырёх предложениях, и верным оказалось то, которое не
#       исполняется.
#
# ПОЧЕМУ ПРЕВЫШЕНИЕ САМО ПО СЕБЕ — НЕ НАХОДКА. Ориентир объявлен ориентиром, а не
# запретом, и превышения приняты решением владельца (2026-09-19: полоса крупного
# сжатия НЕ санкционирована). Гейт, краснеющий на принятом состоянии дерева,
# отключают первым — и вместе с ним уходит единственный производитель числа.
#
# ЖИВОЙ ТЕКСТ — ОДНО ПОНЯТИЕ НА ВСЕ РАСПОЗНАВАТЕЛИ. Ограда кода и HTML-комментарий
# снимаются ОДИН раз, и результат читают обе половины И поиск объявления
# ориентира. Прежняя редакция держала три разных понятия «живого»: объявление
# ориентира, показанное примером в ограде, роняло гейт, а снятое в комментарий —
# засчитывалось за действующее. Право «пример не есть объявление» принадлежит
# всякому предмету этой проверки, а не одной строке таблицы.
#
# ОБЪЯВЛЕНИЕ ОРИЕНТИРА СЧИТАЕТСЯ ВХОЖДЕНИЯМИ, А НЕ ЗНАЧЕНИЯМИ. Два ОДИНАКОВЫХ
# объявления в разных файлах — два места об одном предмете, и расходятся они
# молча ровно так же, как разные: счёт по различным значениям давал им «1» и
# зелёное.
#
# ТРИ НАХОДКИ, И НИ ОДНА НЕ ВЫВОДИТСЯ ИЗ ДРУГОЙ:
#   1. ПУСТОЙ ОБХОД — из таблицы закрепления не прочитано ни одного закрепления
#      либо не открылось ни одного файла правила.
#   2. ОРИЕНТИР объявлен не ровно один раз (ноль — вшивать величину в проверку;
#      больше одного — второе место об одном предмете).
#   3. РУКОПИСНАЯ КОПИЯ вывода переписи в живой таблице корпуса.
#
# ЧТО ЗДЕСЬ ДЕРЖИТСЯ ВНИМАНИЕМ — НАЗВАНО, А НЕ СМЯГЧЕНО (2026-09-19). Свойство
# «перепись умеет отвечать НЕТ», то есть что перечень над порогом ЗАВИСИТ от
# дерева, доказательством БОЛЬШЕ НЕ ПОКРЫТО: ось инъекции, его утверждавшая,
# снята — её утверждение судило слово по всему выводу и упасть не могло
# (разбор — в шапке `inject-06-preload-budget-census.sh`). Сегодня свойство
# держится ДВУМЯ вещами, и обе слабее гейта: перепись считает суммы обходом
# дерева, а не читает их откуда-либо, — то есть зависимость от дерева у неё by
# construction; и человек, читающий вывод, видит имена с числами и может сверить
# их предикатом из `01-wave-contract.md`. Это честнее оси, которая не может
# упасть: та занимала слот и отчитывалась зелёным.
#
# ШЕСТОЙ ЭКЗЕМПЛЯР КЛАССА «УТВЕРЖДЕНИЕ СУДИТ СЛОВО ПО ВСЕМУ ВЫВОДУ» ЖИВЁТ В ЭТОМ
# ЖЕ НАБОРЕ, и координаты названы, пока не потеряны: `inject-02-nothing-lost.sh`
# строки 325 и 326, `inject.sh` строка 335. Все три зелены при ОБЕЗВРЕЖЕННОЙ
# находке — их удовлетворяет строка переписи, которая печатает нужные слова
# ВСЕГДА, ровно как удовлетворяла снятую ось G. Доказано подменой жертвы
# (2026-09-19). ЧИНИТЬ ЭТИМ ЗАХОДОМ НЕ ТРЕБУЕТСЯ — решение владельца; запись
# стоит здесь, чтобы следующий не открывал класс заново.
#
# ЧЕГО НЕ СУДИТ. Не судит, велик ли набор, не судит довода под превышением и не
# судит, сослалась ли проза на перепись: последнее есть суждение о смысле, и
# машинного признака у него нет.
#
# Коды выхода: 0 — производитель на месте, копий нет; 1 — находка либо пустой
# обход; 2 — предмета нет (корпуса правил в дереве не существует).

set -uo pipefail

NAME="check-06-preload-budget-census"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PARSER="$SCRIPT_DIR/manifest-rows.awk"

gate_void() { echo "[VOID] $NAME${1:+ — $1}" >&2; }

if [ -n "${RULES_GATE_ROOT:-}" ]; then
    WS="$(cd "$RULES_GATE_ROOT" 2>/dev/null && pwd)" || {
        gate_void "RULES_GATE_ROOT=$RULES_GATE_ROOT не открывается — читать неоткуда"
        exit 2
    }
else
    WS="$(cd "$SCRIPT_DIR/../.." && pwd)"
fi

# ── предпосылка 0: разборщик таблицы закрепления на месте ────────────────────
# Он же держит грамматику таблицы для check-01 и check-03; своего разбора здесь
# не заводится — две копии грамматики расходятся молча.
if [ ! -f "$PARSER" ]; then
    echo "[CENSUS] $NAME: разбор не запускался: manifest-rows.awk не существует; закреплений 0"
    gate_void "разборщика таблицы нет рядом с проверкой — читать закрепления нечем; это НЕ «находок 0»"
    exit 2
fi

# ── предпосылка 1: корпус в этом дереве есть ─────────────────────────────────
if [ ! -d "$WS/.claude/rules" ]; then
    echo "[CENSUS] $NAME: каталога .claude/rules нет; правил 0, закреплений 0"
    gate_void "каталога .claude/rules в $WS нет — корпуса правил в этом дереве не существует"
    exit 2
fi

python3 - "$WS" "$PARSER" "$NAME" <<'PY'
import os, re, subprocess, sys

WS, PARSER, NAME = sys.argv[1], sys.argv[2], sys.argv[3]
RULES = os.path.join(WS, ".claude", "rules")
MAN_REL = ".claude/rules/MANIFEST.md"
MAN = os.path.join(WS, MAN_REL)

def census(msg): print("[CENSUS] %s: %s" % (NAME, msg))
def fail(msg):   print("[FAIL] %s — %s" % (NAME, msg), file=sys.stderr)
def pass_(msg):  print("[PASS] %s — %s" % (NAME, msg))

# ── ЖИВОЙ ТЕКСТ: одно понятие на все распознаватели ──────────────────────────
# Снимается ограда кода и HTML-комментарий. То же делает manifest-rows.awk для
# таблицы закрепления, поэтому все читатели корпуса видят один и тот же текст.
FENCE = re.compile(r"^\s*(```|~~~)")
def live_lines(path):
    out, fence, incom = [], False, False
    try:
        raw = open(path, encoding="utf-8", errors="replace").read().split("\n")
    except OSError:
        return out
    for i, s in enumerate(raw, 1):
        if FENCE.match(s):
            fence = not fence
            continue
        if fence:
            continue
        if incom:
            if "-->" in s:
                s = s.split("-->", 1)[1]; incom = False
            else:
                continue
        while "<!--" in s:
            head, rest = s.split("<!--", 1)
            if "-->" in rest:
                s = head + rest.split("-->", 1)[1]
            else:
                s = head; incom = True; break
        out.append((i, s))
    return out

rule_files = sorted(f for f in os.listdir(RULES) if f.endswith(".md"))
live = {f: live_lines(os.path.join(RULES, f)) for f in rule_files}

# ── ЗАКРЕПЛЕНИЕ И СУММЫ ──────────────────────────────────────────────────────
rows = []
if os.path.isfile(MAN):
    env = dict(os.environ, LC_ALL="C")
    try:
        out = subprocess.run(["awk", "-f", PARSER, MAN], capture_output=True,
                             text=True, env=env).stdout
    except OSError:
        out = ""
    for line in out.split("\n"):
        if not line.strip():
            continue
        parts = line.split("\t")
        if len(parts) >= 5:
            rows.append((parts[0], parts[1], parts[4]))

sums, read_n, missing_n, bind_n = {}, 0, 0, 0
for _ln, name, bind in rows:
    path = os.path.join(RULES, name)
    if not os.path.isfile(path):
        missing_n += 1          # предмет check-01, не здешний; печатается переписью
        continue
    read_n += 1
    size = os.path.getsize(path)
    for a in bind.split("·"):
        a = a.strip()
        if not a:
            continue
        bind_n += 1
        sums[a] = sums.get(a, 0) + size

corpus = sum(os.path.getsize(os.path.join(RULES, f)) for f in rule_files)
agents = set(sums)
ordered = sorted(sums.items(), key=lambda kv: -kv[1])

# ── ОРИЕНТИР: вхождения в ЖИВОМ тексте, а не различные значения ──────────────
DECL = re.compile(r"≤\s*(\d[\d\s ]*\d|\d)\s*Б на агента")
decls = []
for f in rule_files:
    for ln, s in live[f]:
        for m in DECL.finditer(s):
            decls.append((".claude/rules/%s:%d" % (f, ln),
                          int(re.sub(r"[\s ]", "", m.group(1)))))
decl_n = len(decls)
values = sorted({v for _c, v in decls})
budget = values[0] if decl_n == 1 else None

over = [(a, s) for a, s in ordered if budget is not None and s > budget]
under = [(a, s) for a, s in ordered if budget is not None and s <= budget]

# ── КОПИИ ВЫВОДА: три половины ───────────────────────────────────────────────
produced = set(sums.values()) | {corpus}
floor = min(sums.values()) if sums else None
NUM = re.compile(r"\d[\d\s ]*\d|\d")

def numbers(s):
    return {int(re.sub(r"[\s ]", "", n)) for n in NUM.findall(s)}

copies = []
for f in rule_files:
    for ln, s in live[f]:
        if not s.lstrip().startswith("|"):
            continue
        nums = numbers(s)
        named = sorted(a for a in agents if a in s)
        why = None
        if produced & nums:
            why = "тождество с выводом: %s" % ", ".join(
                str(n) for n in sorted(produced & nums))
        elif named and floor is not None and any(n >= floor for n in nums):
            why = "имя набора «%s» рядом с величиной набора" % named[0]
        if why:
            copies.append((".claude/rules/%s:%d" % (f, ln), why, s.strip()[:90]))

# ── ПЕРЕПИСЬ ОБЪЁМА — ВСЕГДА И ДО ВЕРДИКТА ───────────────────────────────────
census("строк таблицы %d, правил прочитано %d (не найдено %d), закреплений %d, "
       "агентов %d, корпус %d Б, объявлений ориентира %d%s"
       % (len(rows), read_n, missing_n, bind_n, len(agents), corpus, decl_n,
          (" (=%d)" % budget) if budget is not None else
          (" — значения: %s" % ", ".join(map(str, values)) if values else "")))

# «Ноль измеренный» и «ноль неизмеренный» — РАЗНЫЕ строки. Прежняя редакция
# печатала «над ориентиром 0 … при ориентире 250000» на дереве, где над порогом
# было пятеро: цикл не исполнялся, а перепись отчитывалась измеренным нулём.
if budget is None:
    census("над ориентиром НЕ ИЗМЕРЕНО: ориентир не разрешён (объявлений %d) — "
           "сравнивать не с чем; это НЕ «над ориентиром 0»" % decl_n)
elif over:
    census("над ориентиром %d: %s"
           % (len(over), " · ".join("%s %d" % (a, s) for a, s in over)))
else:
    census("над ориентиром 0 — измерено: %d агентов сверены с ориентиром %d Б"
           % (len(agents), budget))

# Ближайший ПОД ориентиром — опора доказательства: инъекция выбирает
# контрольного агента отсюда, а не по имени. Имя в фикстуре сцепило бы
# доказательство с преходящим запасом ровно одного агента.
if budget is not None and under:
    a, s = under[0]
    census("ближайший под ориентиром: %s %d (запас %d Б)" % (a, s, budget - s))
elif budget is not None:
    census("ближайших под ориентиром нет: все %d агентов над ним" % len(agents))

# ── НАХОДКА 1: ПУСТОЙ ОБХОД ──────────────────────────────────────────────────
if not rows or not bind_n or not read_n:
    fail("пустой обход: строк таблицы %d, прочитано правил %d, закреплений %d — "
         "сумма набора не посчитана НИ ОДНОМУ агенту, и всякий ноль ниже был бы "
         "истинным by construction, а не измеренным" % (len(rows), read_n, bind_n))
    sys.exit(1)

rc = 0

# ── НАХОДКА 2: ОРИЕНТИР ──────────────────────────────────────────────────────
if decl_n == 0:
    fail("ориентир не объявлен в живом тексте корпуса в форме «≤ <число> Б на "
         "агента» — величину пришлось бы вшить в проверку, и она перестала бы "
         "быть решением корпуса (пример в ограде кода и строка под "
         "HTML-комментарием объявлением НЕ считаются)")
    rc = 1
elif decl_n > 1:
    for coord, val in decls:
        print("    %s — ≤ %d" % (coord, val), file=sys.stderr)
    fail("ориентир объявлен %d раза — два места об одном предмете; они расходятся "
         "молча и тогда, когда значения сегодня совпадают (различных значений "
         "%d)" % (decl_n, len(values)))
    rc = 1

# ── НАХОДКА 3: РУКОПИСНАЯ КОПИЯ ──────────────────────────────────────────────
if copies:
    print("  вывод переписи выписан РУКОЙ в живой таблице корпуса:", file=sys.stderr)
    for coord, why, text in copies:
        print("    %s — %s | %s" % (coord, why, text), file=sys.stderr)
    fail("строк-копий вывода переписи %d — их значения производит эта проверка, "
         "и 2026-09-19 копия уже разошлась с ней. Ссылайся на перепись, а не "
         "повторяй её" % len(copies))
    rc = 1

if rc:
    sys.exit(1)

pass_("производитель величины на месте: осмотрено агентов %d по %d правилам; "
      "ориентир %d Б прочитан из живого текста ровно одним объявлением; над ним "
      "%d — перечень напечатан переписью; живых строк таблицы, несущих число из "
      "вывода переписи либо величину набора рядом с именем, — 0 (сверено с %d "
      "произведёнными значениями, нижняя граница величины набора %d Б)"
      % (len(agents), read_n, budget, len(over), len(produced), floor))
PY
exit $?
