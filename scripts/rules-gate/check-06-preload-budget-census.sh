#!/usr/bin/env bash
# check-06 — У ВЕЛИЧИНЫ «СУММА ПРЕДЗАГРУЗКИ НА АГЕНТА» ЕСТЬ ПРОИЗВОДИТЕЛЬ.
#
# ЧТО УТВЕРЖДАЕТ. Сумма набора считается ПО ДЕРЕВУ, ориентир читается из текста
# корпуса, а поимённый список тех, кто над ориентиром, ПЕЧАТАЕТСЯ здесь. Проза о
# превышениях обязана ссылаться на эту перепись, а не держать свою копию списка.
#
# ЗАЧЕМ ЭТА ПРОВЕРКА ЗАВЕДЕНА, И ЦЕНА ИЗМЕРЕНА. Контракт волны
# (`.claude/rules/01-wave-contract.md` §«Кто какое правило держит») с 2026-09-17
# сам объявлял эту ось словами «проверка объявлена … и на день этой редакции НЕ
# поставлена». Пока её не было, число превышений считало ВНИМАНИЕ — и 2026-09-19
# насчитало ЧЕТЫРЕ при ПЯТИ: `landing-reviewer` пересёк ориентир той же правкой,
# что этот класс записывала, и в прозу не попал. Рукописный перечень над порогом
# есть второе место об одном предмете: расходится молча, потому что ни одна
# проверка дерева от него не зависит.
#
# ПОЧЕМУ ПРЕВЫШЕНИЕ САМО ПО СЕБЕ — НЕ НАХОДКА. Ориентир объявлен ориентиром, а не
# запретом, и превышения приняты решением владельца (2026-09-19: полоса крупного
# сжатия НЕ санкционирована). Гейт, краснеющий на принятом состоянии дерева,
# отключают первым — и вместе с ним уходит единственный производитель числа.
# Поэтому список над порогом идёт ПЕРЕПИСЬЮ, а вердикт судит другое: есть ли у
# величины производитель и не завели ли рядом рукописную копию его вывода.
#
# ТРИ НАХОДКИ, И НИ ОДНА НЕ ВЫВОДИТСЯ ИЗ ДРУГОЙ:
#   1. ПУСТОЙ ОБХОД — из таблицы манифеста не прочитано ни одного закрепления либо
#      не открылось ни одного файла правила. «Над ориентиром ноль» на пустом
#      множестве истинно by construction, поэтому здесь это находка, а не успех.
#   2. ОРИЕНТИР НЕ ОБЪЯВЛЕН либо объявлен РАЗНЫМИ значениями. Величина, которую
#      проверка вшила бы в себя, перестала бы быть решением корпуса; два разных
#      объявления — два места об одном предмете, и угадывать, какое из них
#      действующее, проверка не вправе.
#   3. РУКОПИСНЫЙ ПЕРЕЧЕНЬ НАД ПОРОГОМ — строка таблицы, чья ПЕРВАЯ ячейка
#      объявляет перечень над ориентиром. Это копия вывода этой переписи, и
#      именно она разошлась 2026-09-19.
#
# РАСПОЗНАВАТЕЛЬ НАХОДКИ 3 ЗНАЕТ ОБЕ ЗАКОННЫЕ ФОРМЫ ЯРЛЫКА, и обе стояли в дереве
# живьём (`.claude/rules/testing.md` §«Гейт на класс» п.7): «над бюджетом» —
# редакция 2026-09-19 до этой правки, «над ориентиром» — редакция того же дня
# после неё. Форма, о которой распознаватель не знает, не даёт ни красного, ни
# зелёного: она молчит.
#
# СУДИТСЯ СТРОКА ТАБЛИЦЫ, А НЕ ПРОЗА, и это несущее. Те же слова в предложении —
# законный и нужный текст: раздел обязан объяснять, что такое ориентир и почему
# превышение принято. Проверка, краснеющая на собственном объяснении предмета, —
# класс, который корпус ловит (`testing.md` §«Гейт на класс» п.4). Блок кода тоже
# не таблица: контракт вправе показать форму строки примером.
#
# РАЗБОР ТАБЛИЦЫ МАНИФЕСТА — ОБЩИЙ С check-01 и check-03, файлом
# `manifest-rows.awk`. Своего разбора здесь не заводится: грамматика у таблицы
# одна, и две её копии расходятся молча — строка, видимая одной проверке и
# невидимая другой, не даёт ни красного, ни вопроса.
#
# ЧЕГО ЭТА ПРОВЕРКА НЕ СУДИТ. Она не судит, ВЕЛИК ли набор, не судит довода под
# превышением и не судит, сослалась ли проза на перепись: последнее есть суждение
# о смысле русского текста, а машинного признака у него нет. Она обеспечивает
# ровно одно — чтобы число производила машина и чтобы рядом не завелось
# рукописного дубля.
#
# Коды выхода: 0 — производитель на месте, рукописного перечня нет; 1 — находка
# либо пустой обход; 2 — предмета нет (корпуса правил в дереве не существует).

set -uo pipefail

NAME="check-06-preload-budget-census"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PARSER="$SCRIPT_DIR/manifest-rows.awk"

gate_pass()   { echo "[PASS] $NAME${1:+ — $1}"; }
gate_fail()   { echo "[FAIL] $NAME${1:+ — $1}" >&2; }
gate_void()   { echo "[VOID] $NAME${1:+ — $1}" >&2; }   # «проверять нечего» ≠ «находок 0»
gate_census() { echo "[CENSUS] $NAME: $1"; }

# Корень воркспейса. `RULES_GATE_ROOT` переопределяет его — этим пользуется ТОЛЬКО
# inject.sh, чтобы прогонять гейт по временному дереву с внесённым дефектом.
if [ -n "${RULES_GATE_ROOT:-}" ]; then
    WS="$(cd "$RULES_GATE_ROOT" 2>/dev/null && pwd)" || {
        gate_void "RULES_GATE_ROOT=$RULES_GATE_ROOT не открывается — читать неоткуда"
        exit 2
    }
else
    WS="$(cd "$SCRIPT_DIR/../.." && pwd)"
fi

RULES_REL=".claude/rules"
MAN_REL="$RULES_REL/MANIFEST.md"

# ── предпосылка 0: разборщик таблицы на месте ────────────────────────────────
if [ ! -f "$PARSER" ]; then
    gate_census "разбор не запускался: $PARSER не существует; закреплений 0"
    gate_void "разборщика таблицы manifest-rows.awk нет рядом с проверкой — читать закрепления нечем; это НЕ «находок 0»"
    exit 2
fi

# ── предпосылка 1: корпус в этом дереве есть ─────────────────────────────────
if [ ! -d "$WS/$RULES_REL" ]; then
    gate_census "каталога $RULES_REL нет; правил 0, закреплений 0"
    gate_void "каталога $RULES_REL в $WS нет — корпуса правил в этом дереве не существует, предмета у проверки нет"
    exit 2
fi

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# ── ОРИЕНТИР: читается из текста корпуса, а не вшит сюда ─────────────────────
#
# Форма объявления — «≤ <число> Б на агента». Число нормализуется до цифр:
# разделитель тысяч в корпусе — обычный пробел, и сравнивать надо величину, а не
# её запись.
: > "$TMP/budgets"
while IFS= read -r hit; do
    printf '%s\n' "$hit" | sed -E 's/.*≤[[:space:]]*([0-9][0-9[:space:]]*[0-9])[[:space:]]*Б на агента.*/\1/' \
        | tr -d '[:space:]' >> "$TMP/budgets"
    echo >> "$TMP/budgets"
done < <(grep -ho '≤[[:space:]]*[0-9][0-9[:space:]]*[0-9][[:space:]]*Б на агента' "$WS/$RULES_REL"/*.md 2>/dev/null)
sed -i '/^$/d' "$TMP/budgets" 2>/dev/null || true
budget_n="$(sort -u "$TMP/budgets" | wc -l | tr -d ' ')"
budget="$(sort -u "$TMP/budgets" | head -1)"

# ── СУММЫ НАБОРОВ: по строкам таблицы, разбор общий ──────────────────────────
rows_n=0
read_n=0
missing_n=0
: > "$TMP/pairs"
if [ -f "$WS/$MAN_REL" ]; then
    LC_ALL=C awk -f "$PARSER" "$WS/$MAN_REL" > "$TMP/rows"
    rows_n="$(wc -l < "$TMP/rows" | tr -d ' ')"
    while IFS=$'\t' read -r _ln name _a _h bind; do
        [ -n "${name:-}" ] || continue
        f="$WS/$RULES_REL/$name"
        if [ ! -f "$f" ]; then
            # Файла нет — это предмет check-01, а не здешний. Считаем и печатаем,
            # чтобы «прочитано меньше, чем названо» не осталось невидимым.
            missing_n=$((missing_n + 1))
            continue
        fi
        read_n=$((read_n + 1))
        sz="$(stat -c%s "$f" 2>/dev/null || echo 0)"
        [ -n "${bind:-}" ] || continue
        # Разделитель имён — « · » (U+00B7). Разбор идёт awk по СТРОКЕ, а не `tr`:
        # `tr` работает побайтово и разорвал бы многобайтный знак на два.
        printf '%s\n' "$bind" | awk -v sz="$sz" '{
            n = split($0, a, "·")
            for (i = 1; i <= n; i++) {
                gsub(/^[ \t]+|[ \t]+$/, "", a[i])
                if (a[i] != "") printf "%s\t%s\n", a[i], sz
            }
        }' >> "$TMP/pairs"
    done < "$TMP/rows"
fi

bind_n="$(wc -l < "$TMP/pairs" | tr -d ' ')"
agents_n="$(cut -f1 "$TMP/pairs" | sort -u | wc -l | tr -d ' ')"
corpus="$(cat "$WS/$RULES_REL"/*.md 2>/dev/null | wc -c | tr -d ' ')"

# Суммы на агента, по убыванию: перепись печатает ВСЕ, вердикт судит не их.
awk -F'\t' '{s[$1]+=$2} END{for(k in s) printf "%d\t%s\n", s[k], k}' "$TMP/pairs" \
    | sort -rn > "$TMP/sums"

over_list=""
over_n=0
if [ "$budget_n" -eq 1 ] && [ -n "${budget:-}" ]; then
    while IFS=$'\t' read -r sum ag; do
        [ -n "${ag:-}" ] || continue
        if [ "$sum" -gt "$budget" ]; then
            over_n=$((over_n + 1))
            over_list="${over_list:+$over_list · }$ag $sum"
        fi
    done < "$TMP/sums"
fi

# ── РУКОПИСНЫЙ ПЕРЕЧЕНЬ НАД ПОРОГОМ: строка таблицы, а не проза ──────────────
#
# Ярлык ищется в ПЕРВОЙ ячейке строки живой таблицы. Блок кода пропускается: он
# документирует форму, а не объявляет её.
: > "$TMP/handwritten"
for f in "$WS/$RULES_REL"/*.md; do
    [ -f "$f" ] || continue
    rel="$RULES_REL/$(basename "$f")"
    awk -v rel="$rel" '
        /^[[:space:]]*(```|~~~)/ { fence = !fence; next }
        fence { next }
        /^[[:space:]]*\|/ {
            line = $0
            n = split(line, c, "|")
            if (n < 3) next
            cell = c[2]
            gsub(/[`*]/, "", cell)
            if (cell ~ /над ориентиром/ || cell ~ /над бюджетом/)
                printf "%s:%d\t%s\n", rel, NR, cell
        }
    ' "$f" >> "$TMP/handwritten"
done
hand_n="$(wc -l < "$TMP/handwritten" | tr -d ' ')"

# ── ПЕРЕПИСЬ ОБЪЁМА — ПЕЧАТАЕТСЯ ВСЕГДА И ДО ВЕРДИКТА ───────────────────────
gate_census "строк таблицы $rows_n, правил прочитано $read_n (не найдено $missing_n), закреплений $bind_n, агентов $agents_n, корпус $corpus Б, объявлений ориентира $budget_n${budget:+ (=$budget)}"
if [ "$over_n" -gt 0 ]; then
    gate_census "над ориентиром $over_n: $over_list"
else
    gate_census "над ориентиром 0 — при ориентире ${budget:-не объявлен} и $agents_n осмотренных агентах"
fi

# ── НАХОДКА 1: ПУСТОЙ ОБХОД ──────────────────────────────────────────────────
if [ "$rows_n" -eq 0 ] || [ "$bind_n" -eq 0 ] || [ "$read_n" -eq 0 ]; then
    gate_fail "пустой обход: строк таблицы $rows_n, прочитано правил $read_n, закреплений $bind_n — сумма набора не посчитана НИ ОДНОМУ агенту, и «над ориентиром 0» здесь истинно by construction, а не измерено"
    exit 1
fi

rc=0

# ── НАХОДКА 2: ОРИЕНТИР ──────────────────────────────────────────────────────
if [ "$budget_n" -eq 0 ]; then
    gate_fail "ориентир не объявлен ни в одном файле $RULES_REL в форме «≤ <число> Б на агента» — величину пришлось бы вшить в проверку, и она перестала бы быть решением корпуса"
    rc=1
elif [ "$budget_n" -gt 1 ]; then
    gate_fail "ориентир объявлен $budget_n РАЗНЫМИ значениями ($(sort -u "$TMP/budgets" | tr '\n' ' ')) — два места об одном предмете; какое из них действующее, проверка угадывать не вправе"
    rc=1
fi

# ── НАХОДКА 3: РУКОПИСНЫЙ ПЕРЕЧЕНЬ ───────────────────────────────────────────
if [ "$hand_n" -gt 0 ]; then
    echo "  перечень над ориентиром выписан РУКОЙ — это копия вывода переписи выше:" >&2
    while IFS=$'\t' read -r coord cell; do
        echo "    $coord — ячейка «$(printf '%s' "$cell" | sed -E 's/^[[:space:]]+|[[:space:]]+$//g')»" >&2
    done < "$TMP/handwritten"
    gate_fail "строк таблицы с рукописным перечнем над ориентиром $hand_n — их вывод производит эта перепись, и 2026-09-19 копия уже разошлась с ней (в прозе стояло четверо при пяти). Ссылайся на перепись, а не повторяй её"
    rc=1
fi

[ "$rc" -eq 0 ] || exit 1

gate_pass "производитель величины на месте: осмотрено агентов $agents_n по $read_n правилам, ориентир $budget Б прочитан из корпуса, над ним $over_n — список напечатан переписью, рукописных копий 0"
exit 0
