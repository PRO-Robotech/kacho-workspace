# ── ЗАМЫКАНИЕ АВТОЗАГРУЗКИ: обход графа импортов от корневого CLAUDE.md ──────
findings = []
lines_read = 0
lines_skipped = 0
files_read = 0
evaluated_total = 0
span_total = 0
declared = {}          # ПРИВЕДЁННАЯ координата -> (номер строки, как написано)
declared_lines = 0     # СТРОК-объявлений, а не уникальных целей
closure = []           # порядок обхода
offbook = []           # рёбра замыкания ЗА пределы CLAUDE.md
offlimit_seen = set()  # (файл, приведённая цель) — находка уже названа
unreadable = 0

# Обход графа ограничен сверху НАМЕРЕННО. Символьная ссылка на каталог даёт
# бесконечное семейство различных путей к одному файлу (`a/b/a/b/…`), а гейт,
# который висит, хуже гейта, который врёт: висящий не даёт вердикта вовсе и его
# снимают первым. Упор в предел — НАХОДКА, а не молчаливое усечение обхода.
CLOSURE_CAP = 200

queue = [CLAUDE_REL]
seen_files = set()
capped = False
while queue:
    if len(seen_files) >= CLOSURE_CAP:
        capped = True
        break
    rel = queue.pop(0)
    if rel in seen_files:
        continue
    seen_files.add(rel)
    path = os.path.join(root, rel)
    try:
        lines = read_lines(path)
    except OSError as exc:
        findings.append(
            f"НЕЧИТАЕМ ФАЙЛ ЗАМЫКАНИЯ: {rel} — {exc}; он грузится, а разобрать "
            f"его не удалось, поэтому по нему «находок 0» ничего не значит"
        )
        unreadable += 1
        continue
    files_read += 1
    lines_read += len(lines)
    closure.append(rel)
    evaluated, in_span, skipped, fence_open, routes = scan(lines)
    lines_skipped += skipped
    evaluated_total += len(evaluated)
    span_total += in_span

    if fence_open:
        findings.append(
            f"ОГРАДА НЕ ЗАКРЫТА: {rel} — хвост файла ушёл из-под разбора целиком; "
            f"по нему «находок 0» означает «не смотрели», а не «чисто»"
        )

    # ── ОСИ ПО ВЫЧИСЛЯЕМЫМ ССЫЛКАМ ──────────────────────────────────────────
    # Идёт ПЕРВЫМ и до маршрутов: находка с координатой `файл:строка` дороже
    # находки «куда-то ведёт», и второй раз та же цель уже не называется.
    for num, raw, target, whole in evaluated:
        if whole:
            declared_lines += 1
        # Написание, отличное от приведённого, называется В ТОЙ ЖЕ находке: без
        # этого читатель ищет в файле строку, которой там нет.
        spelled = f"«@{raw}»" if raw == target else f"«@{raw}» (та же цель, что «{target}»)"
        axis = offlimit_axis(target)
        if axis:
            findings.append(offlimit_text(axis, f"{rel}:{num}", spelled))
            offlimit_seen.add((rel, target))
            continue   # внутрь гейт не спускается: ответ уже получен
        if rel == CLAUDE_REL:
            if whole:
                declared.setdefault(target, (num, raw))
            else:
                findings.append(
                    f"ИМПОРТ В СЕРЕДИНЕ ПРЕДЛОЖЕНИЯ: {rel}:{num} {spelled} — "
                    f"@ вне code span вычисляется как импорт; то, что грузится "
                    f"безусловно, обязано стоять строкой целиком, иначе оно "
                    f"неотличимо от прозы и меняется следующей её правкой"
                )

    # ── МАРШРУТ ОБХОДА: идём по КАЖДОМУ вычисляемому импорту, который резолвится
    # в файл. Прежняя редакция шла только по `@.claude/…`, поэтому
    # `@docs/extra.md` в CLAUDE.md не читался вовсе — и голый импорт правила
    # внутри него не попадал ни в находки, ни в перепись. Нерезолвящиеся ссылки
    # маршрутом не становятся: читать нечего.
    for target in routes:
        t = norm(target)
        # Решение по ПРИВЕДЁННОЙ координате: на сырой `@./.claude/rules/<имя>.md`
        # гейт спускался туда, писал файл оттуда в собственную перепись — и в той
        # же строке отчитывался, что таких импортов ноль.
        axis = offlimit_axis(t)
        if axis:
            if (rel, t) not in offlimit_seen:
                findings.append(offlimit_text(axis, rel, f"«@{target}» (приведено: «{t}»)"))
                offlimit_seen.add((rel, t))
            continue
        resolved, _cands = resolve(rel, target)
        if not resolved:
            continue
        # Цель, УВОДЯЩАЯ в запретный каталог не своим написанием (`@docs/../.claude/
        # rules/<имя>.md`), ловится по РАЗРЕШЁННОМУ пути: распознаватель координат её
        # не видит by construction, а загрузчик читает именно этот файл.
        axis = offlimit_axis(resolved.replace(os.sep, "/"))
        if axis:
            if (rel, resolved) not in offlimit_seen:
                findings.append(
                    offlimit_text(axis, rel, f"«@{target}» (резолвится в «{resolved}»)")
                )
                offlimit_seen.add((rel, resolved))
            continue
        if resolved not in seen_files and resolved not in queue:
            queue.append(resolved)
            if resolved != CLAUDE_REL:
                offbook.append(f"{rel} → {resolved}")

if capped:
    findings.append(
        f"ОБХОД УПЁРСЯ В ПРЕДЕЛ: прочитано {len(seen_files)} файлов замыкания при "
        f"пределе {CLOSURE_CAP}, в очереди осталось {len(queue)}; замыкание "
        f"обойдено НЕ ЦЕЛИКОМ, поэтому «находок 0» по остатку ничего не значит"
    )

# ── НАСТРОЙКИ: ИСКЛЮЧЕНИЕ И ГЛАВНЫЙ ПОТОК ───────────────────────────────────
#
# Файл читается ОДИН раз на две оси, а оси остаются двумя: без исключения корпус
# грузится всем, без диспетчера главный поток разведывает сам. Одно не выводится
# из другого ни в какую сторону, и чинятся они разными правками.
settings_abs = os.path.join(root, SETTINGS_REL)
settings = None
settings_note = "прочитан"
if not os.path.isfile(settings_abs):
    settings_note = "файла нет"
else:
    try:
        with open(settings_abs, encoding="utf-8") as fh:
            settings = json.load(fh)
        if not isinstance(settings, dict):
            settings, settings_note = None, "корень не объект"
    except (OSError, ValueError) as exc:
        settings_note = f"не разбирается ({type(exc).__name__})"


def glob_re(pat):
    """Шаблон исключения → выражение. `**` пересекает `/`, `*` и `?` — нет.

    Разворачивается САМ шаблон, а не путь: сверка «есть ли в списке такая строка»
    отвечала бы на вопрос о тексте настроек, а гейту нужен ответ о ПУТИ.
    """
    out, i, n = [], 0, len(pat)
    while i < n:
        if pat.startswith("**/", i):
            out.append("(?:.*/)?")   # `**/x` покрывает и `x`, и `a/b/x`
            i += 3
        elif pat.startswith("**", i):
            out.append(".*")
            i += 2
        elif pat[i] == "*":
            out.append("[^/]*")
            i += 1
        elif pat[i] == "?":
            out.append("[^/]")
            i += 1
        else:
            out.append(re.escape(pat[i]))
            i += 1
    return re.compile("".join(out))


# ПРОБНЫХ ПУТЕЙ ДВА, И ВТОРОЙ НЕ ДЛЯ КРАСОТЫ: шаблон `.claude/rules/*.md` покрывает
# правило в корне каталога и НЕ покрывает доменное — а корпус населяется
# рекурсивно (см. выше), значит такое правило осталось бы в автозагрузке одно.
PROBES = [RULES_REL + "/x.md", RULES_REL + "/domain/x.md"]
# Спеллингов два, потому что достоверно неизвестно, к какому виду пути харнесс
# прикладывает шаблон. Покрытие засчитывается по ЛЮБОМУ — выбор в сторону
# молчания сделан осознанно: ложная находка на работающем исключении отключила бы
# гейт вместе с настоящими, а неработающее исключение ловится ещё и тем, что
# правило в такой сборке попадает в замыкание (ось CORPUS-AUTOLOADED).
excludes = settings.get("claudeMdExcludes") if isinstance(settings, dict) else None
if not isinstance(excludes, list):
    excludes = []
patterns = [(p, glob_re(p)) for p in excludes if isinstance(p, str)]
uncovered = []
for probe in PROBES:
    spellings = (os.path.join(root, probe), probe)
    if not any(rx.fullmatch(s) for _p, rx in patterns for s in spellings):
        uncovered.append(probe)

if uncovered:
    if settings is None:
        why = f"{SETTINGS_REL}: {settings_note}"
    elif not patterns:
        why = f"в {SETTINGS_REL} нет ни одного шаблона claudeMdExcludes"
    else:
        shown = ", ".join("«%s»" % p for p, _rx in patterns[:6])
        why = f"шаблоны claudeMdExcludes ({len(patterns)}: {shown}) этот путь не покрывают"
    findings.append(
        f"ИСКЛЮЧЕНИЕ НЕ ПОКРЫВАЕТ КОРПУС: {why}; пробный путь "
        f"{', '.join(uncovered)} остаётся в автозагрузке. Все `.md` внутри "
        f"{RULES_REL}/ Claude Code грузит сам, рекурсивно, без единого @import "
        f"(измерено), и снять это умеет только claudeMdExcludes — значит корпус "
        f"приезжает каждому агенту целиком, а закрепление правил за агентами "
        f"становится украшением: ни один файл дерева этого не показывает"
    )

# ── `.claude/backup/` — ОБЪЯВЛЕННЫЙ АРХИВ, А НЕ ВТОРОЙ ДОМ ───────────────────
#
# Решение владельца 2026-09-20 держит снятые процессные правила в
# `.claude/backup/`, а не выкидывает их, — и у архива тот же ВИД, что у
# корпуса (файлы `<имя>.md` с текстом норм). Разница «архив / второй дом»
# — не в содержимом файла, а в том, ГРУЗИТСЯ ли он, поэтому предмет здесь не
# текст, а два предиката, и оба обязаны выполняться ОДНОВРЕМЕННО:
#   (а) `.claude/backup/**` покрыт claudeMdExcludes — тем же механизмом, что
#       {RULES_REL}/. Не покрыт — грузится сам, и архив становится вторым
#       домом текстуально неотличимым от {SECOND_HOME_REL}/;
#   (б) ни один агент не тянет файл архива предзагрузкой `skills:` — она
#       делает архивный текст РАБОЧИМ правилом при каждом запуске, а не
#       справкой, которую открывают вручную.
# Каталога может не быть вовсе (архив снят целиком или ещё не заведён) —
# тогда предикату не по чему судить, и это отсутствие предмета, а не
# находка; проверка ниже идёт ТОЛЬКО если каталог существует на диске.
BACKUP_REL = ".claude/backup"
backup_abs = os.path.join(root, BACKUP_REL)
backup_uncovered = []
archive_refs = []

if os.path.isdir(backup_abs):
    backup_probes = [BACKUP_REL + "/x.md", BACKUP_REL + "/domain/x.md"]
    for probe in backup_probes:
        spellings = (os.path.join(root, probe), probe)
        if not any(rx.fullmatch(s) for _p, rx in patterns for s in spellings):
            backup_uncovered.append(probe)
    if backup_uncovered:
        if settings is None:
            why = f"{SETTINGS_REL}: {settings_note}"
        elif not patterns:
            why = f"в {SETTINGS_REL} нет ни одного шаблона claudeMdExcludes"
        else:
            shown = ", ".join("«%s»" % p for p, _rx in patterns[:6])
            why = f"шаблоны claudeMdExcludes ({len(patterns)}: {shown}) этот путь не покрывают"
        findings.append(
            f"АРХИВ БЕЗ ИСКЛЮЧЕНИЯ (предикат а): {why}; пробный путь "
            f"{', '.join(backup_uncovered)} остаётся вне claudeMdExcludes. "
            f"{BACKUP_REL}/ объявлен архивом, а не вторым домом корпуса, ровно "
            f"ПОТОМУ что исключён из автозагрузки тем же механизмом, что и "
            f"{RULES_REL}/; без покрытия он лишь текстом отличается от второго дома"
        )

    # предикат (б): ни один `skills:` агента не резолвится файлом из архива.
    # `skills:` предзагружает скиллу САБагенту (измерено в check-02 выше),
    # значит символьная ссылка `.claude/skills/<имя>/SKILL.md`, ведущая внутрь
    # {BACKUP_REL}/, доставляет архивный текст РЕГУЛЯРНО — то есть он второй
    # дом с доставкой не через @import, а через skills:.
    FM_YAML = re.compile(r"(?ms)\A---\r?\n(.*?)\r?\n---\r?\n")
    SKILLS_BLOCK = re.compile(r"(?ms)^skills:[ \t]*\r?\n((?:[ \t]*-[ \t]*\S+[ \t]*\r?\n?)+)")
    SKILL_ITEM = re.compile(r"(?m)^[ \t]*-[ \t]*(\S+)[ \t]*$")
    agents_abs_probe = os.path.join(root, AGENTS_REL)
    if os.path.isdir(agents_abs_probe):
        for aname in sorted(os.listdir(agents_abs_probe)):
            if not aname.lower().endswith(".md"):
                continue
            try:
                atext = open(os.path.join(agents_abs_probe, aname), encoding="utf-8").read()
            except OSError:
                continue
            fm = FM_YAML.match(atext)
            if not fm:
                continue
            block = SKILLS_BLOCK.search(fm.group(1))
            if not block:
                continue
            for item in SKILL_ITEM.finditer(block.group(1)):
                skill_md = os.path.join(root, ".claude/skills", item.group(1), "SKILL.md")
                if not os.path.islink(skill_md):
                    continue
                target = os.path.realpath(skill_md)
                if target == backup_abs or target.startswith(backup_abs + os.sep):
