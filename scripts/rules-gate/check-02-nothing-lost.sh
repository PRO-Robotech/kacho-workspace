def glob_re(pat):
    """Шаблон исключения → выражение. `**` пересекает `/`, `*` и `?` — нет.

    Разворачивается САМ шаблон, а не путь: сверка «есть ли в списке такая строка»
    отвечала бы на вопрос о тексте настроек, а гейту нужен ответ о ПУТИ.
    """
    out, i, n = [], 0, len(pat)
    while i < n:
        if pat.startswith("**/", i):
            out.append("(?:.*/)?")   # `**/x` покрывает и `x`, и `a/b/x`
            i += 3
        elif pat.startswith("**", i):
            out.append(".*")
            i += 2
        elif pat[i] == "*":
            out.append("[^/]*")
            i += 1
        elif pat[i] == "?":
            out.append("[^/]")
            i += 1
        else:
            out.append(re.escape(pat[i]))
            i += 1
    return re.compile("".join(out))


