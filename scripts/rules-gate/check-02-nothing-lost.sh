    """Разбор одного файла.

    Возвращает (вычисляемые, внутри_span, пропущено_как_код, ограда_осталась,
    маршруты). Вычисляемая ссылка — (номер строки, НАПИСАННАЯ координата,
    ПРИВЕДЁННАЯ координата, объявление ли это): решение об оси принимает вторая,
    а в текст находки идёт первая — читатель ищет строку по тому, что в файле
    написано. Маршруты — все вычисляемые импорты любого вида, по ним строится
    обход.
    """
    evaluated, in_span, skipped, routes = [], 0, 0, []
    fenced = False
    for num, line in enumerate(lines, 1):
        if FENCE.match(line):
            fenced = not fenced
            skipped += 1
            continue
        if fenced:
            skipped += 1
            continue
        raw_hits = len(REF.findall(line))
        bare = SPAN.sub("", line)
        hits = list(REF.finditer(bare))
        in_span += raw_hits - len(hits)
        decl = DECL.match(bare.strip())
        for m in hits:
            if decl and m.group(1) == decl.group(1):
                raw = decl.group(1)
                evaluated.append((num, raw, norm(raw), True))
            else:
                raw = m.group(1).rstrip(TAIL)
                evaluated.append((num, raw, norm(raw), False))
        for m in ANYREF.finditer(bare):
            routes.append(m.group(1).rstrip(TAIL))
    return evaluated, in_span, skipped, fenced, routes


def git(*args):
    try:
        out = subprocess.run(
            ["git", "-C", root, *args],
            capture_output=True, text=True, timeout=20,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    return out.stdout if out.returncode == 0 else None


def resolve(importer_rel, target):
    """Кандидаты разрешения ссылки: от каталога файла и от корня дерева.

    База не угадывается — перебираются обе, и берётся та, что резолвится.
    Возвращает (rel_путь_или_None, перебранные_кандидаты).
    """
    cands = []
    base = os.path.dirname(importer_rel)
    if base:
        cands.append(os.path.normpath(os.path.join(base, target)))
    cands.append(os.path.normpath(target))
    seen = list(dict.fromkeys(cands))
    for c in seen:
        if not c.startswith("..") and os.path.isfile(os.path.join(root, c)):
            return c, seen
    return None, seen


# ── ТРИ КАТАЛОГА, КОТОРЫМ В ЗАМЫКАНИИ НЕ МЕСТО ──────────────────────────────
#
# Порядок в кортеже — порядок диагноза: цель, попавшая в снятый дом, называется
# снятым домом, а не правилом в автозагрузке. Одна координата даёт РОВНО ОДНУ
# находку: диагноз, назвавший два предмета, посылает чинить два, а починка одна.
OFFLIMITS = (
    (SECOND_HOME_REL, "SECOND-HOME"),
    (RULES_REL, "CORPUS-AUTOLOADED"),
    (AGENTS_REL, "AGENT-IN-BASE"),
)


def offlimit_axis(target):
    """Какую ось нарушает ПРИВЕДЁННАЯ координата (или None)."""
    for rel_dir, code in OFFLIMITS:
        if target == rel_dir or target.startswith(rel_dir + "/"):
            return code
    return None


def offlimit_text(code, where, spelled):
    if code == "SECOND-HOME":
        return (
            f"ИМПОРТ ИЗ СНЯТОГО ДОМА: {where} {spelled} — каталог "
            f"{SECOND_HOME_REL}/ снят 2026-09-13, дом правил один. Либо цель не "
            f"существует и правило не читается вовсе, либо каталог завели "
            f"заново — тогда у корпуса два дома при одном объявлении состава"
        )
    if code == "CORPUS-AUTOLOADED":
        return (
            f"ПРАВИЛО В АВТОЗАГРУЗКЕ: {where} {spelled} — правило вернулось в "
            f"замыкание {CLAUDE_REL} и грузится КАЖДОМУ агенту безусловно, минуя "
            f"закрепление за агентом. Решением владельца 2026-09-17 правило "
            f"доезжает только предзагрузкой `skills: rule-<имя>`; импорт отменяет "
            f"это молча — ни манифест, ни определение агента не меняются"
        )
    return (
        f"ОПРЕДЕЛЕНИЕ АГЕНТА В АВТОЗАГРУЗКЕ: {where} {spelled} — файл из "
        f"{AGENTS_REL}/ попал в замыкание {CLAUDE_REL}. Определение агента читает "
        f"ХАРНЕСС, а импорт кладёт его ещё и текстом в окно всякого, кто видит "
        f"{CLAUDE_REL}: база маршрутизации приезжает исполнителям, которым она не "
        f"адресована, и платится за каждый запуск"
    )


# ── население оси «правило»: `*.md` в каталоге правил, РЕКУРСИВНО ────────────
#
# То же население, что у check-01, и это сверено намеренно: до 2026-09-13 две
# проверки судили вложенность по-разному — check-02 звала объявленное правило в
