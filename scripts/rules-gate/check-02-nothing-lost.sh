offbook = []           # рёбра замыкания ЗА пределы CLAUDE.md + каталога правил
unreadable = 0

# Обход графа ограничен сверху НАМЕРЕННО. Символьная ссылка на каталог даёт
# бесконечное семейство различных путей к одному файлу (`a/b/a/b/…`), а гейт,
# который висит, хуже гейта, который врёт: висящий не даёт вердикта вовсе и его
# снимают первым. Упор в предел — НАХОДКА, а не молчаливое усечение обхода.
CLOSURE_CAP = 200

queue = [CLAUDE_REL]
seen_files = set()
capped = False
while queue:
    if len(seen_files) >= CLOSURE_CAP:
        capped = True
        break
    rel = queue.pop(0)
    if rel in seen_files:
        continue
    seen_files.add(rel)
    path = os.path.join(root, rel)
    try:
        lines = read_lines(path)
    except OSError as exc:
        findings.append(
            f"НЕЧИТАЕМ ФАЙЛ ЗАМЫКАНИЯ: {rel} — {exc}; он грузится, а разобрать "
            f"его не удалось, поэтому по нему «находок 0» ничего не значит"
        )
        unreadable += 1
        continue
    files_read += 1
    lines_read += len(lines)
    closure.append(rel)
    evaluated, in_span, skipped, fence_open, routes = scan(lines)
    lines_skipped += skipped
    evaluated_total += len(evaluated)
    span_total += in_span
    scanned[rel] = evaluated

    # ── МАРШРУТ ОБХОДА: идём по КАЖДОМУ вычисляемому импорту, который резолвится
    # в файл. Прежняя редакция шла только по `@.claude/…`, поэтому
    # `@docs/extra.md` в CLAUDE.md не читался вовсе — и голый импорт rulebook
    # внутри него не попадал ни в находки, ни в перепись. Нерезолвящиеся ссылки
    # маршрутом не становятся: читать нечего.
    for target in routes:
        # Решение по ПРИВЕДЁННОЙ координате: на сырой `@./.claude/rulebook/x.md`
        # гейт спускался в свод, писал его файл в собственную перепись — и в той
        # же строке отчитывался «импортов rulebook 0».
        if norm(target).startswith(f"{BOOK_REL}/") or norm(target) == BOOK_REL:
            continue          # находка уже названа; внутрь rulebook не спускаемся
        resolved, _cands = resolve(rel, target)
        if resolved and resolved not in seen_files and resolved not in queue:
            queue.append(resolved)
            if not resolved.startswith(f"{RULES_REL}/") and resolved != CLAUDE_REL:
                offbook.append(f"{rel} → {resolved}")

    if fence_open:
        findings.append(
            f"ОГРАДА НЕ ЗАКРЫТА: {rel} — хвост файла ушёл из-под разбора целиком; "
            f"по нему «находок 0» означает «не смотрели», а не «чисто»"
        )

    for num, raw, target, whole in evaluated:
        if whole:
            declared_lines += 1
        # Написание, отличное от приведённого, называется В ТОЙ ЖЕ находке: без
        # этого читатель ищет в файле строку, которой там нет.
        spelled = f"«@{raw}»" if raw == target else f"«@{raw}» (та же цель, что «{target}»)"
        if target.startswith(f"{BOOK_REL}/") or target == BOOK_REL:
            findings.append(
                f"ИМПОРТ RULEBOOK: {rel}:{num} {spelled} — rulebook читается "
                f"файлом по требованию, а не автозагрузкой; импорт возвращает его "
                f"в окно каждого агента волны"
            )
            continue  # внутрь rulebook гейт не спускается: ответ уже получен
        if rel == CLAUDE_REL:
            if whole:
                declared.setdefault(target, (num, raw))
            else:
                findings.append(
                    f"ИМПОРТ В СЕРЕДИНЕ ПРЕДЛОЖЕНИЯ: {rel}:{num} {spelled} — "
                    f"@ вне code span вычисляется как импорт; объявление обязано "
                    f"стоять строкой целиком, иначе перечень автозагрузки "
                    f"неотличим от прозы"
                )
        elif target.startswith(f"{RULES_REL}/"):
            # Правило, импортированное НЕ корневым CLAUDE.md. Оно грузится, не
            # будучи объявленным, — перечень автозагрузки перестаёт быть перечнем.
            findings.append(
                f"ТЕНЕВОЙ ИМПОРТ ПРАВИЛА: {rel}:{num} {spelled} — правило "
                f"грузится в обход перечня в {CLAUDE_REL}: объявление обязано "
                f"стоять там, иначе состав автозагрузки не виден ни в одном месте"
            )

if capped:
    findings.append(
        f"ОБХОД УПЁРСЯ В ПРЕДЕЛ: прочитано {len(seen_files)} файлов замыкания при "
        f"пределе {CLOSURE_CAP}, в очереди осталось {len(queue)}; замыкание "
        f"обойдено НЕ ЦЕЛИКОМ, поэтому «находок 0» по остатку ничего не значит"
    )

# ── ось «ничего не потеряно»: файл есть, объявления нет ──────────────────────
#
# Формулировка следствия РАЗНАЯ у двух случаев, и это не косметика: файл,
# импортированный теневым путём, ГРУЗИТСЯ. Прежняя редакция говорила о нём
# «не грузится ни одной сессией» — то есть противоречила собственной посылке о
# рекурсивности импортов и посылала читателя искать не то.
for name in core_files:
    target = f"{RULES_REL}/{name}"
    if target in declared:
        continue
    if target in seen_files:
        findings.append(
            f"НЕ ИМПОРТИРОВАН: {target} — строки «@{target}» в {CLAUDE_REL} нет; "
            f"файл при этом ГРУЗИТСЯ теневым импортом (см. находку о нём выше): "
            f"состав автозагрузки не виден в перечне"
        )
    else:
        findings.append(
            f"НЕ ИМПОРТИРОВАН: {target} — файл лежит в каталоге правил, "
            f"а строки «@{target}» в {CLAUDE_REL} нет: он не грузится ни одной "
            f"сессией"
        )

# ── ось «ничего не забыто»: объявление есть, файла нет ───────────────────────
#
# Отсутствие проверяется НА ДИСКЕ и по обеим базам разрешения. Утверждать
# «файла в дереве нет», не спросив дерево, — то же самое, что «ноль находок»
# без переписи.
present = {f"{RULES_REL}/{n}" for n in core_files}
for target, (num, raw) in sorted(declared.items(), key=lambda kv: kv[1][0]):
    if target in present:
        continue
    spelled = f"«@{raw}»" if raw == target else f"«@{raw}» (та же цель, что «{target}»)"
    resolved, cands = resolve(CLAUDE_REL, target)
    if resolved is None:
        findings.append(
            f"ИМПОРТ В НИКУДА: {CLAUDE_REL}:{num} {spelled} — не резолвится ни "
            f"от корня, ни от каталога файла (пробовано: {', '.join(cands)}): "
            f"правило переименовали или увезли, а объявление осталось"
        )
    elif target.startswith(f"{RULES_REL}/"):
        findings.append(
            f"ИМПОРТ МИМО ПЕРЕЧНЯ: {CLAUDE_REL}:{num} {spelled} — файл на диске "
            f"есть ({resolved}), но в население каталога правил не попал; "
            f"обход правил и объявление считают разное"
        )

# ── перепись объёма: «ноль находок» ≠ «ноль прочитанного» ≠ «ноль осмотренного»
# ЧИСЛА ТОЧНЫЕ, ПЕРЕЧИСЛЕНИЕ УСЕЧЁННОЕ — и усечение названо вслух. Перепись,
# которую невозможно прочитать, переписью не является: символьная ссылка на
# каталог дала замыкание в 46 файлов и строку в несколько тысяч знаков, где
# счёт находок утонул. Счёт печатается всегда; состав — первые LIST_CAP имён,
# дальше «…и ещё N».
LIST_CAP = 6


def listing(items, cap=LIST_CAP):
    if not items:
        return "—"
    if len(items) <= cap:
        return ", ".join(items)
    return ", ".join(items[:cap]) + f", …и ещё {len(items) - cap}"


census = (
    f"[CENSUS] {NAME}: осмотрено файлов {files_read} "
    f"(замыкание от {CLAUDE_REL}: {listing(closure)}"
    f"{f'; непрочитанных {unreadable}' if unreadable else ''}); "
    f"правил ядра {len(core_files)}, {tracked_note}; "
    f"строк прочитано {lines_read}, из них разобрано {lines_read - lines_skipped}, "
    f"пропущено как код {lines_skipped}; "
    f"@-ссылок вычисляемых {evaluated_total}, внутри code span {span_total}; "
    f"рёбер замыкания за пределы ядра {len(offbook)}"
    f"{' (' + listing(offbook, 3) + ')' if offbook else ''}; "
    f"строк-объявлений {declared_lines}, уникальных целей {len(declared)}"
)
print(census, flush=True)   # перепись печатается ПЕРВОЙ и на пустом обходе тоже

if files_read == 0 or lines_read == 0 or not core_files:
    print(
        f"[FAIL] {NAME} — ОБХОД БЕСПРЕДМЕТЕН: файлов прочитано {files_read}, "
        f"строк {lines_read}, правил ядра {len(core_files)}. "
        f"О дереве не прочитано ничего, поэтому «находок 0» здесь ничего не значит",
        file=sys.stderr,
    )
    sys.exit(1)

for f in findings:
    print(f"[FAIL] {NAME} — {f}", file=sys.stderr)

if findings:
    print(
        f"[FAIL] {NAME} — находок {len(findings)} при осмотренных "
        f"{files_read} файлах и {lines_read} строках",
        file=sys.stderr,
    )
    sys.exit(1)

print(
    f"[PASS] {NAME} — автозагрузка сходится с деревом: правил ядра "
    f"{len(core_files)}, объявлений {len(declared)}, импортов rulebook 0, "
    f"импортов в середине предложения 0, теневых импортов 0"
)
sys.exit(0)
