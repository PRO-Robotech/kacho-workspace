#!/usr/bin/env bash
# check-02 — НИЧЕГО НЕ ПОТЕРЯНО И НИЧЕГО НЕ ЗАБЫТО: автозагрузка = ровно ядро.
#
# ЧТО УТВЕРЖДАЕТ (шесть осей, у каждой свой код находки):
#
#   NOT-IMPORTED     — файл лежит в `.claude/rules/`, а строки-объявления в
#                      корневом CLAUDE.md нет. Файл не грузится и невидим:
#                      правило написано, положено в каталог правил и не читается
#                      ни одной сессией. Это и есть «потеряно».
#   DANGLING-IMPORT  — строка-объявление есть, файла нет. Это «забыто»: правило
#                      переименовали или увезли, а объявление осталось.
#   RULEBOOK-IMPORT  — в замыкании автозагрузки есть ВЫЧИСЛЯЕМАЯ ссылка на
#                      `.claude/rulebook/…`. Rulebook читается ФАЙЛОМ по
#                      требованию; импорт оттуда возвращает правило в окно
#                      каждого агента и отменяет всю раскладку разом.
#   MIDLINE-IMPORT   — вычисляемая ссылка `@.claude/…` стоит НЕ строкой целиком.
#                      Она ЯВЛЯЕТСЯ импортом (см. предпосылку ниже), но не
#                      является объявлением: перечень автозагрузки становится
#                      неотличим от прозы, и следующая правка прозы меняет то,
#                      что грузится, никого об этом не спросив.
#   SHADOW-IMPORT    — правило ядра импортирует ДРУГОЕ правило ядра. Тогда файл
#                      грузится, не будучи объявленным в CLAUDE.md: перечень
#                      автозагрузки перестаёт быть перечнем.
#   UNCLOSED-FENCE   — в автозагружаемом файле ограда не закрыта. Хвост такого
#                      файла целиком уходит из-под разбора, и «находок 0» по нему
#                      означает «не смотрели» (см. про перепись ниже).
#
# КООРДИНАТА ПРИВОДИТСЯ К ОДНОЙ ФОРМЕ, А ОСЬ РЕШАЕТСЯ ПО ПРИВЕДЁННОЙ. Одна и та
# же цель законно пишется четырьмя способами — `@./x`, `@a//b`, `@a/./b`,
# `@a/c/../b`, — и загрузчик резолвит их в ОДИН файл. Гейт, знающий одну форму,
# на остальных МОЛЧИТ: ни красного, ни зелёного, предмет просто уходит из-под
# наблюдения. Измерено: голая строка `@.claude/rulebook/<правило>` давала код 1,
# три её переписи — 0, и две из трёх были хуже молчания (гейт засчитывал их
# объявлением и спускался по ним в свод, называя его файл в собственной
# переписи). В текст находки идёт НАПИСАННОЕ, приведённое называется рядом.
#
# ЗАМЫКАНИЕ ВЫЧИСЛЯЕТСЯ, А НЕ ВЫПИСЫВАЕТСЯ. Импорты в Claude Code рекурсивны,
# поэтому предмет трёх последних осей — всё, что грузится безусловно, а это
# получается ОБХОДОМ ГРАФА от корневого CLAUDE.md по вычисляемым ссылкам, а не
# чтением заранее известного набора файлов.
#
#   Прежняя редакция читала фиксированный набор «CLAUDE.md + .claude/rules/*.md»
#   и звала его замыканием. Проба: `@docs/extra.md` строкой целиком в CLAUDE.md,
#   а внутри `docs/extra.md` — голый `@.claude/rulebook/testing.md`. Гейт выходил
#   НУЛЁМ и печатал «импортов rulebook 0»: файл не читался, и его ссылка не
#   попадала даже в перепись (REF знает только `@.claude/…`). То есть самый
#   дорогой класс уезжал за один лишний хоп, и перепись этого не показывала.
#
#   БАЗА РАЗРЕШЕНИЯ ССЫЛКИ НЕ ДОГАДЫВАЕТСЯ, А ПЕРЕБИРАЕТСЯ. Относительный путь
#   Claude Code резолвит от каталога импортирующего файла; здесь корневой
#   CLAUDE.md и файлы `.claude/rules/` дают РАЗНЫЕ базы для одной и той же
#   строки. Достоверного способа проверить базу из скрипта нет, поэтому гейт
#   пробует ОБЕ (от каталога файла и от корня) и идёт по той, что резолвится.
#   Выбор консервативный намеренно: он может прочитать лишний файл и не может
#   пропустить импорт, который на самом деле грузится.
#
#   В rulebook гейт НЕ СПУСКАЕТСЯ: его импорт — уже находка, а обход четырнадцати
#   модулей стоил бы дороже, чем стоит ответ, который уже получен. Сказано
#   вслух, потому что это граница обхода, а не свойство дерева.
#
# ПРЕДПОСЫЛКА, НА КОТОРОЙ ГЕЙТ СТОИТ, И ОНА ОБЪЯВЛЯЕТСЯ ВСЛУХ. Claude Code
# вычисляет `@path` где угодно в тексте — и НЕ вычисляет внутри markdown code
# span и ограждённого блока. Отсюда два следствия, и оба несущие:
#   (а) `@.claude/rulebook/testing.md` в обратных кавычках — законная координата,
#       а не импорт; гейт обязан на ней МОЛЧАТЬ, иначе первый ложный срабат его
#       отключит вместе с настоящими находками;
#   (б) то же самое без кавычек — импорт на 143 КБ в окно каждого агента.
# Поэтому гейт читает ИСПОЛНЯЕМУЮ часть текста, а не текст: снимает ограждённые
# блоки и code span, и лишь потом ищет ссылку.
#
#   ОТСТУП В ЧЕТЫРЕ ПРОБЕЛА КОДОМ НЕ СЧИТАЕТСЯ, И ЭТО ИЗМЕРЕННЫЙ ВЫБОР, а не
#   недосмотр разборщика. В markdown такой отступ бывает блоком кода, но в ЭТОМ
#   корпусе он почти всегда — продолжение элемента списка: замер
#   `grep -c '^    .*@\.claude' .claude/rules/00-kacho-core.md` → 4, и все
#   четыре суть живые координаты rulebook в обратных кавычках внутри
#   пронумерованных пунктов. Признай отступ кодом — и эти четыре строки уйдут
#   из-под наблюдения: снятые с них кавычки перестанут быть находкой. Цена
#   обратного выбора — ложная находка на настоящем блоке кода с отступом;
#   таких в замыкании ноль (тот же предикат), а появятся — их оградой и
#   оформят.
#
# ОБЪЯВЛЕНИЕ — ЭТО ВСЯ СТРОКА И НИЧЕГО КРОМЕ, ВКЛЮЧАЯ ЗНАКИ ПРЕПИНАНИЯ.
# Прежняя редакция считала объявлением всё, что подходило под `^\s*@\S+\s*$`, и
# срезала хвостовую пунктуацию. Проба: абзац прозы, где координата существующего
# правила легла на свою строку и кончает предложение —
#   «…изложение целиком вынесено в\n@.claude/rules/writing.md.\n» —
# читался как ОБЪЯВЛЕНИЕ, гейт выходил нулём и печатал «импортов в середине
# предложения 0». Проходили все семь хвостов `. , ; : ) » ).`. Это ровно тот
# дефект, ради которого ось заведена, и ровно та форма, в которой он приходит:
# проза этого корпуса переносится по ~90 знаков, и координата регулярно
# оказывается на строке одна. Теперь объявление опознаётся по СОВПАДЕНИЮ ВСЕЙ
# строки с `@<путь>`, без срезки хвоста; хвост срезается только у прозаических
# ссылок, где он и вправду принадлежит предложению.
#
# ИСТОЧНИК ИСТИНЫ ОДИН. Перечень правил ядра не выписан в скрипте: он ВЫВОДИТСЯ
# обходом `.claude/rules/` (рекурсивно — правило в подкаталоге тоже правило),
# перечень объявлений — разбором CLAUDE.md. Выписанный список был бы вторым
# местом об одном предмете и разошёлся бы молча.
#
# ЕДИНИЦА СЧЁТА — ФАЙЛ НА ДИСКЕ, А НЕ ЗАПИСЬ ИНДЕКСА, и это выбор, а не небрежность.
# Claude Code грузит с ДИСКА, поэтому предмет гейта — диск. Правило, заведённое
# волной и ещё не добавленное в git, грузится (или не грузится) уже сейчас: обход
# по `git ls-files` пропустил бы его молча — то есть недомерил бы ровно в тот
# момент, ради которого гейт и заведён. Отслеживаемость печатается ВТОРОЙ
# величиной переписи, чтобы расхождение единиц было названо, а не спрятано.
#
# ИСКЛЮЧЕНИЙ ПО `.gitignore` ЗДЕСЬ НЕТ, И ЭТО РЕШЕНИЕ. Игнорируемое правило с
# диска грузится, значит звать его импорт «импортом в никуда» неверно. Черновик,
# положенный в каталог правил, — тоже находка, а не мелочь: он либо грузится
# каждой сессией, либо не грузится, и оба состояния надо увидеть.
#
# ПЕРЕПИСЬ НАЗЫВАЕТ ОСМОТРЕННОЕ, А НЕ ТОЛЬКО ПРОЧИТАННОЕ. Строки внутри оград
# читаются, но не разбираются, — поэтому печатаются ОБЕ величины. Прежняя
# редакция печатала одну («строк прочитано»), и незакрытая ограда уводила хвост
# файла из-под разбора, ничего не изменив в переписи: «ноль находок» становилось
# неотличимо от «ноль осмотренного» на один уровень ниже, чем гейт это
# декларировал. Ссылки печатаются двумя числами по той же причине: разборщик,
# снимающий лишнее, обнулит вычисляемые и уронит NOT-IMPORTED; разборщик, не
# снимающий ничего, обнулит внутрикавычечные и уронит MIDLINE-IMPORT.
#
# КОДЫ ВЫХОДА — ТРИ, И ТРЕТИЙ НЕ ЗАСЧИТЫВАЕТСЯ В УСПЕХ:
#   0 — осмотрено N файлов и L строк, находок 0;
#   1 — НАХОДКА либо ПУСТОЙ ОБХОД (о дереве не прочитано ничего);
#   2 — БЕЗ ПРЕДМЕТА: каталога `.claude/rules/` или CLAUDE.md в корне нет.
#
# Корень берётся из `RULES_GATE_ROOT` — иначе инъекцию нельзя было бы прогнать во
# временной копии, а инъекция в настоящем дереве не инъекция, а порча.

