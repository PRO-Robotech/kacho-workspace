# ── ПОТОЛОК БАЗЫ: ОДНО МЕСТО, ОДНО ЧИСЛО ─────────────────────────────────────
#
# ЧТО ЭТИ ДВА ЧИСЛА СТОРОЖАТ. `CLAUDE.md` доезжает ОБОИМ концам — диспетчеру и
# каждому исполнителю, — и платится за каждый запуск агента; тело базы заменяет
# системный промпт главного потока и читается им целиком в начале всякой сессии.
# Оба файла растут одинаково: абзацем, который «дешевле дописать сюда, чем завести
# правило». Потолок и есть та точка, где дописать становится решением.
#
# ОТКУДА ЧИСЛА. `CLAUDE.md` — 12 000 Б: замер установленного протокола 10 152 Б
# (`wc -c CLAUDE.md`) плюс запас на абзац, но не на раздел. Тело базы — ИЗНАЧАЛЬНО
# 96 000 Б (врезки ниже поднимают это число адресно): замер установленного тела
# 88 238 Б (файл 89 176 Б минус frontmatter 938 Б).
# ЭТИ ТРИ ЧИСЛА — ПРОВЕНАНС ПОТОЛКА, А НЕ ТЕКУЩИЙ РАЗМЕР: они сняты в момент, когда
# потолок назначался, и с тех пор росли оба — и база, и сам потолок. Действующее
# значение живёт в ОДНОМ месте, `BUDGET` ниже, а текущее тело печатает сам гейт
# строкой переписи «<файл> — тело N Б при потолке N Б» на КАЖДОМ прогоне; второго
