#!/usr/bin/env bash
# check-02 — АВТОЗАГРУЗКА ПУСТА, А БАЗА МАРШРУТИЗАЦИИ НА МЕСТЕ.
#
# ПРЕДМЕТ ИНВЕРТИРОВАН 2026-09-17, И ЭТО НЕ ПРАВКА ЧИСЛА. До сих пор проверка
# утверждала «автозагрузка = ровно корпус»: каждое правило обязано было стоять
# строкой `@import` в `CLAUDE.md`, и отсутствие строки звалось «потеряно». Решение
# владельца отменило раскладку целиком: «все рулы свести к агентам которые должны
# их использовать… Мастер процесс загружает только базу которая позволит определить
# какого агента в какой момент запускать». Теперь истинно ОБРАТНОЕ — в автозагрузке
# не должно быть НИ ОДНОГО правила, — и проверка ищет ровно противоположное тому,
# что искала. Имя файла оставлено прежним намеренно: координата
# `scripts/rules-gate/check-02-nothing-lost.sh` названа в манифесте, в конвейере и
# в текстах правил, а переименование — отдельный поступок, который стоит своей
# волны и своего диффа.
#
# МЕХАНИКА, НА КОТОРОЙ ВСЁ СТОИТ (измерено пробами в `claude -p`, Claude Code
# 2.1.274; перечень замеров — в проектной записке §2):
#   · ВСЕ `.md` внутри `.claude/rules/` грузятся САМИ, рекурсивно, без единого
#     `@import`. Снять это, не трогая адреса файлов, умеет только
#     `claudeMdExcludes` в `.claude/settings.json`;
#   · тело агента, названного в настройке `agent`, ЗАМЕНЯЕТ системный промпт
#     главного потока и является единственной базой маршрутизации;
#   · `skills:` во frontmatter САБагента предзагружает полный текст скилла, а у
#     агента главного потока — НЕ предзагружает. Отсюда: правило доезжает
#     исполнителю скилл-ссылкой, а диспетчеру — ничем, и его база самодостаточна.
# Из этих трёх фактов и выведены оси ниже: каждая сторожит одно звено, и ни одно
# из них не проявляется в прогоне продукта ничем.
#
# ЧТО УТВЕРЖДАЕТ (восемь осей, у каждой свой код находки):
#
#   CORPUS-AUTOLOADED   — в замыкании `CLAUDE.md` есть файл из `.claude/rules/`.
#                         Правило вернулось в автозагрузку: оно приезжает КАЖДОМУ
#                         агенту всегда, минуя закрепление, а решения об этом никто
#                         не принимал. Это в точности прежняя ось «НЕ ИМПОРТИРОВАН»,
#                         повёрнутая на 180°: тот же обход, тот же разбор, обратный
#                         вердикт.
#   AGENT-IN-BASE       — в замыкание `CLAUDE.md` попал файл из `.claude/agents/**`.
#                         Определение агента читает харнесс, а не импорт: доставка
#                         его ещё и текстом кладёт тело агента в окно каждого, кто
#                         видит `CLAUDE.md`, — а тело базы одно только на 88 КБ.
#   EXCLUDE-MISSING     — `.claude/settings.json` не покрывает `.claude/rules/`
#                         шаблоном `claudeMdExcludes`. Тогда корпус грузится сам,
#                         целиком и всем, а ни один файл дерева этого не показывает:
#                         `CLAUDE.md` по-прежнему без импортов, манифест по-прежнему
#                         раздаёт правила агентам, и модель держится только словами.
#   DISPATCHER-NOT-MAIN — в настройках нет `"agent": "dispatcher"` либо нет файла
#                         базы. Главный поток становится обычным агентом с полным
#                         набором инструментов: он читает и правит сам, а
#                         «диспетчер ничего не разведывает» остаётся фразой.
#   BASE-BUDGET         — `CLAUDE.md` или тело базы больше объявленного потолка.
#   SECOND-HOME         — в замыкании есть ВЫЧИСЛЯЕМАЯ ссылка на `.claude/rulebook/`.
#                         Каталог снят 2026-09-13, дом правил ОДИН; ссылка туда
#                         означает либо несуществующую цель, либо второй дом при
#                         одном объявлении состава.
#   MIDLINE-IMPORT      — вычисляемая ссылка `@.claude/…` стоит в `CLAUDE.md` НЕ
#                         строкой целиком. Она ЯВЛЯЕТСЯ импортом, но не является
#                         объявлением: то, что грузится, становится неотличимо от
#                         прозы, и следующая правка прозы меняет окно, никого не
#                         спросив.
#   UNCLOSED-FENCE      — в файле замыкания ограда не закрыта. Хвост такого файла
#                         целиком уходит из-под разбора, и «находок 0» по нему
#                         означает «не смотрели».
#
# ОСЬ `SHADOW-IMPORT` СНЯТА, И СНЯТА ЯВНО. Она краснела на правиле, импортирующем
# другое правило: файл грузился, не будучи объявленным в перечне `CLAUDE.md`.
# Предмета у неё не осталось ни на грамм — перечня автозагрузки больше нет вовсе,
# ни одно правило не объявлено, и «грузится в обход перечня» нечему. Ссылка одного
# правила на другое теперь ЗАКОННА и ничего не грузит: файл правила в замыкание не
# входит, его текст никто не вычисляет. Молча оставить ось значило бы держать
# проверку, которая не может ни покраснеть, ни доказать своего молчания, — а такая
# проверка садится незамеченной (`.claude/rules/testing.md` §«Гейт на класс»).
# По той же причине снята ось `DANGLING-IMPORT` («объявление есть, файла нет»): её
# предмет — объявление ПРАВИЛА, которого не существует, а объявлений правил не
# осталось ни одного. Координата `@.claude/rules/…`, которая всё же появится в
# базе, краснеет теперь как CORPUS-AUTOLOADED — резолвится она или нет, безразлично:
# находкой её делает то, что она ВООБЩЕ там стоит.
#
# ПОТОЛОК БАЗЫ ОБЪЯВЛЕН ОДИН РАЗ — в `BUDGET` ниже — и называется в тексте находки
# числом. Два места об одном числе разошлись бы молча, а находка без потолка
# («база велика») не говорит, велика ли она на байт или вдвое.
#
# КООРДИНАТА ПРИВОДИТСЯ К ОДНОЙ ФОРМЕ, А ОСЬ РЕШАЕТСЯ ПО ПРИВЕДЁННОЙ. Одна и та
# же цель законно пишется четырьмя способами — `@./x`, `@a//b`, `@a/./b`,
# `@a/c/../b`, — и загрузчик резолвит их в ОДИН файл. Гейт, знающий одну форму,
# на остальных МОЛЧИТ: ни красного, ни зелёного, предмет просто уходит из-под
# наблюдения. Измерено на дофиксовой редакции: голая строка давала код 1, три её
# переписи — 0, и две из трёх были хуже молчания (гейт засчитывал их объявлением и
# спускался по ним внутрь, называя тамошний файл в собственной переписи). В текст
# находки идёт НАПИСАННОЕ, приведённое называется рядом.
#
# ЗАМЫКАНИЕ ВЫЧИСЛЯЕТСЯ, А НЕ ВЫПИСЫВАЕТСЯ. Импорты в Claude Code рекурсивны,
# поэтому предмет осей — всё, что грузится безусловно, а это получается ОБХОДОМ
# ГРАФА от корневого `CLAUDE.md` по вычисляемым ссылкам, а не чтением заранее
# известного набора файлов.
#
#   Прежняя редакция читала фиксированный набор «CLAUDE.md + .claude/rules/*.md»
#   и звала его замыканием. Проба: `@docs/extra.md` строкой целиком в CLAUDE.md,
#   а внутри `docs/extra.md` — голый импорт из второго дома. Гейт выходил НУЛЁМ
#   и печатал, что таких импортов ноль: файл не читался, и его ссылка не
#   попадала даже в перепись. То есть самый дорогой класс уезжал за один лишний
#   хоп, и перепись этого не показывала. После инверсии класс тот же и цена та же:
#   правило возвращается в автозагрузку ровно так — не строкой в `CLAUDE.md`, где
#   её увидит любой ревьюер, а импортом внутри файла, который `CLAUDE.md` тянет.
#
#   БАЗА РАЗРЕШЕНИЯ ССЫЛКИ НЕ ДОГАДЫВАЕТСЯ, А ПЕРЕБИРАЕТСЯ. Относительный путь
#   Claude Code резолвит от каталога импортирующего файла; корневой `CLAUDE.md` и
#   файл в подкаталоге дают РАЗНЫЕ базы для одной строки. Достоверного способа
#   проверить базу из скрипта нет, поэтому гейт пробует ОБЕ (от каталога файла и
#   от корня) и идёт по той, что резолвится. Выбор консервативный намеренно: он
#   может прочитать лишний файл и не может пропустить импорт, который грузится.
#
#   В ЗАПРЕТНЫЕ КАТАЛОГИ ГЕЙТ НЕ СПУСКАЕТСЯ: импорт правила, определения агента и
#   снятого дома — уже находки, и что лежит по ту сторону, ответа не меняет.
#   Сказано вслух, потому что это граница обхода, а не свойство дерева: «находок 0»
#   внутри них означает «не смотрели», и смотреть туда незачем. Побочная польза
#   названа отдельно: не спускаясь, гейт не тащит 143 КБ корпуса в собственную
#   перепись и не выдаёт прочитанное за законное.
#
# ПРЕДПОСЫЛКА, НА КОТОРОЙ ГЕЙТ СТОИТ, И ОНА ОБЪЯВЛЯЕТСЯ ВСЛУХ. Claude Code
# вычисляет `@path` где угодно в тексте — и НЕ вычисляет внутри markdown code
# span и ограждённого блока. Отсюда два следствия, и оба несущие:
#   (а) `@.claude/rules/testing.md` в обратных кавычках — законная координата,
#       а не импорт; гейт обязан на ней МОЛЧАТЬ, иначе первый ложный срабат его
#       отключит вместе с настоящими находками;
#   (б) то же самое без кавычек — импорт правила в окно каждого агента.
# Поэтому гейт читает ИСПОЛНЯЕМУЮ часть текста, а не текст: снимает ограждённые
# блоки и code span, и лишь потом ищет ссылку.
#
#   ОТСТУП В ЧЕТЫРЕ ПРОБЕЛА КОДОМ НЕ СЧИТАЕТСЯ, И ЭТО ИЗМЕРЕННЫЙ ВЫБОР, а не
#   недосмотр разборщика. В markdown такой отступ бывает блоком кода, но в ЭТОМ
#   корпусе он почти всегда — продолжение элемента списка: замер
#   `grep -c '^    .*@\.claude' .claude/rules/00-kacho-core.md` → 4, и все
#   четыре суть живые координаты правил в обратных кавычках внутри
#   пронумерованных пунктов. Признай отступ кодом — и эти четыре строки уйдут
#   из-под наблюдения: снятые с них кавычки перестанут быть находкой. Цена
#   обратного выбора — ложная находка на настоящем блоке кода с отступом;
#   таких в замыкании ноль (тот же предикат), а появятся — их оградой и
#   оформят.
#
# ОБЪЯВЛЕНИЕ — ЭТО ВСЯ СТРОКА И НИЧЕГО КРОМЕ, ВКЛЮЧАЯ ЗНАКИ ПРЕПИНАНИЯ.
# Прежняя редакция считала объявлением всё, что подходило под `^\s*@\S+\s*$`, и
# срезала хвостовую пунктуацию. Проба: абзац прозы, где координата правила легла
# на свою строку и кончает предложение —
#   «…изложение целиком вынесено в\n@.claude/backup/writing.md.\n» —
# читался как ОБЪЯВЛЕНИЕ. Тогда это гасило ось «в середине предложения»; теперь
# цена выше: такая строка есть ИМПОРТ ПРАВИЛА, и зачесть её объявлением значило бы
# сказать «так и задумано» ровно о том, чего модель не допускает. Проходили все
# семь хвостов `. , ; : ) » ).`. Проза этого корпуса переносится по ~90 знаков, и
# координата регулярно оказывается на строке одна.
#
# ИСТОЧНИК ИСТИНЫ ОДИН. Перечень правил корпуса не выписан в скрипте: он ВЫВОДИТСЯ
# обходом `.claude/rules/` (рекурсивно — правило в подкаталоге тоже правило),
# перечень исключений — разбором `.claude/settings.json`. Выписанный список был бы
# вторым местом об одном предмете и разошёлся бы молча.
#
# ИСКЛЮЧЕНИЕ ПРОВЕРЯЕТСЯ ПОКРЫТИЕМ ПУТИ, А НЕ СОВПАДЕНИЕМ СТРОКИ. Шаблон пишется
# десятком способов (`**/.claude/rules/**`, `.claude/rules/**`, `**/rules/*.md`),
# и сверка «есть ли в списке такая строка» отвечала бы на вопрос о тексте настроек,
# а не о том, грузится ли корпус. Гейт разворачивает каждый шаблон в выражение и
# спрашивает ПРОБНЫМ ПУТЁМ — правилом в корне каталога и правилом в подкаталоге:
# шаблон, покрывающий только первое, оставляет доменное правило в автозагрузке, и
# это ровно тот класс, что уезжает молча.
#
# ЕДИНИЦА СЧЁТА — ФАЙЛ НА ДИСКЕ, А НЕ ЗАПИСЬ ИНДЕКСА, и это выбор, а не небрежность.
# Claude Code грузит с ДИСКА, поэтому предмет гейта — диск. Правило, заведённое
# волной и ещё не добавленное в git, живёт (или не живёт) в окне уже сейчас: обход
# по `git ls-files` пропустил бы его молча. Отслеживаемость печатается ВТОРОЙ
# величиной переписи, чтобы расхождение единиц было названо, а не спрятано.
#
# ПЕРЕПИСЬ НАЗЫВАЕТ ОСМОТРЕННОЕ, А НЕ ТОЛЬКО ПРОЧИТАННОЕ. Строки внутри оград
# читаются, но не разбираются, — поэтому печатаются ОБЕ величины. Прежняя
# редакция печатала одну («строк прочитано»), и незакрытая ограда уводила хвост
# файла из-под разбора, ничего не изменив в переписи: «ноль находок» становилось
# неотличимо от «ноль осмотренного» на один уровень ниже, чем гейт это
# декларировал. Ссылки печатаются двумя числами по той же причине: разборщик,
# снимающий лишнее, обнулит вычисляемые и уронит CORPUS-AUTOLOADED; разборщик, не
# снимающий ничего, обнулит внутрикавычечные и уронит MIDLINE-IMPORT. Размеры базы
# печатаются рядом с потолком: «бюджет сошёлся» без числа не отличимо от «не мерили».
#
# КОДЫ ВЫХОДА — ТРИ, И ТРЕТИЙ НЕ ЗАСЧИТЫВАЕТСЯ В УСПЕХ:
#   0 — осмотрено N файлов и L строк, находок 0;
#   1 — НАХОДКА либо ПУСТОЙ ОБХОД (о дереве не прочитано ничего);
#   2 — БЕЗ ПРЕДМЕТА: каталога `.claude/rules/` или CLAUDE.md в корне нет.
#
# СНЯТЫЕ НАСТРОЙКИ И СНЯТАЯ БАЗА VOID-ом НЕ ЯВЛЯЮТСЯ, и это антимаска: послабление
# не выдаётся удалением предмета, иначе достаточно было бы стереть
# `.claude/settings.json`, чтобы гейт перестал блокировать отправку, — а именно от
# этого он и заведён. Без файла настроек корпус грузится ВСЕМ, то есть модель
# нарушена сильнее, чем при неверном шаблоне.
#
# Корень берётся из `RULES_GATE_ROOT` — иначе инъекцию нельзя было бы прогнать во
# временной копии, а инъекция в настоящем дереве не инъекция, а порча.

