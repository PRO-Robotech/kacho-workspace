# ── БЮДЖЕТ БАЗЫ ─────────────────────────────────────────────────────────────
#
# Меряется ТЕЛО, а не файл: frontmatter — метаданные харнесса (имя, описание,
# перечень инструментов), в окно он попадает не как текст базы. У `CLAUDE.md`
# frontmatter нет, и тело равно файлу; функция одна на оба, чтобы «тело» значило
# одно и то же в обеих строках переписи.
FM = re.compile(rb"^---[ \t]*\r?\n.*?\r?\n---[ \t]*\r?\n", re.S)


def body_bytes(abs_path):
    with open(abs_path, "rb") as fh:
        data = fh.read()
    m = FM.match(data)
    return data[m.end():] if m else data


def body_size(abs_path):
    return len(body_bytes(abs_path))


# МЕДИАННЫЙ АБЗАЦ ТЕЛА — ЕДИНИЦА ЗАПАСА, И ОНА МЕРЯЕТСЯ, А НЕ ПОМНИТСЯ.
# Абзац — блок между пустыми строками; заголовки исключены (иначе «# » считался
# бы абзацем в 2 знака и тянул медиану вниз). Считается по ТЕЛУ: потолок
# сторожит тело, и frontmatter, попав в выборку, уводит медиану на чужой текст
# (у базы — с 756 Б на 818 Б). Таблица в выборке остаётся, но на медиану почти
# не влияет: она у максимума, а не в середине, — поэтому берётся медиана, а не
# среднее и не максимум («запас на абзац, но не на раздел»).
def median_paragraph(abs_path):
    text = body_bytes(abs_path).decode("utf-8", "replace")
    sizes_b = sorted(
        len(par.encode("utf-8"))
        for par in text.split("\n\n")
        if par.strip() and not par.lstrip().startswith("#")
    )
    if not sizes_b:
        return None, 0
    return sizes_b[len(sizes_b) // 2], len(sizes_b)


