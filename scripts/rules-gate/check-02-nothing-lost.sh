FENCE = re.compile(r"^\s*(?:```|~~~)")
SPAN = re.compile(r"``[^`]*``|`[^`]*`")

# Путь — ЛЮБЫЕ непробельные знаки, а не латиница с цифрами. Корпус русский, и
# класс `[A-Za-z0-9_\-./]` обрезал кириллическое имя файла молча: ссылка
# `@.claude/rules/новое.md` давала координату «@.claude/rules/» — находка
# приходила с УСЕЧЁННЫМ адресом и посылала читателя в каталог вместо файла.
PATH = r"[^\s`]+"

# ОДНА ЦЕЛЬ ПИШЕТСЯ НЕСКОЛЬКИМИ ЗАКОННЫМИ ФОРМАМИ, и загрузчик резолвит их в
# ОДИН файл: `@./.claude/rules/x.md`, `@.claude//rules/x.md`,
# `@.claude/./rules/x.md`, `@.claude/agents/../rules/x.md`. Распознаватель,
# знающий одну форму из четырёх, на остальных МОЛЧИТ — не краснеет и не зеленеет,
# а перестаёт видеть предмет (`.claude/rules/testing.md` §«Гейт на класс», п.7).
# Поэтому: (а) шаблон принимает необязательный ведущий `./`; (б) РЕШЕНИЕ об оси
# принимается по ПРИВЕДЁННОЙ координате, а координата в тексте находки остаётся
# ТОЙ, ЧТО НАПИСАНА, — иначе читатель не найдёт строку в файле.
LEAD = r"(?:\./)?"
REF = re.compile(r"@(" + LEAD + r"\.claude/" + PATH + r")")
# Любой вычисляемый импорт, а не только `@.claude/…`: по нему строится обход
# графа. Оси по-прежнему ключуются на REF — здесь только маршрут.
ANYREF = re.compile(r"@([A-Za-z0-9_.\-/][^\s`]*)")


def norm(target):
    """Координата, приведённая к одной форме: `./`, `//`, `/./`, `/../` сняты.

    Приведение — ЧИСТО ТЕКСТОВОЕ (posixpath, не файловая система): решение об
    оси обязано быть одинаковым на любой машине и не зависеть от того, лежит ли
    файл на диске. Форма, приведение которой выводит за корень (`../x`), остаётся
    как есть: нашим предметом она не является ни в одной записи.
    """
    return posixpath.normpath(target)


TAIL = ".,;:)»"
# Объявление — ВСЯ строка и ничего кроме, И БЕЗ ХВОСТОВОЙ ПУНКТУАЦИИ. Последнее
# несущее: точка и запятая входят в класс пути, поэтому «строка целиком» без
# этого условия принимала `@.claude/rules/writing.md.` — предложение прозы,
# перенесённое так, что координата легла на строку одна.
DECL = re.compile(r"^@(" + LEAD + r"\.claude/" + PATH + r"(?<![" + re.escape(TAIL) + r"]))$")


def read_lines(path):
    with open(path, encoding="utf-8") as fh:
        return fh.readlines()


def scan(lines):
    """Разбор одного файла.

    Возвращает (вычисляемые, внутри_span, пропущено_как_код, ограда_осталась,
    маршруты). Вычисляемая ссылка — (номер строки, НАПИСАННАЯ координата,
    ПРИВЕДЁННАЯ координата, объявление ли это): решение об оси принимает вторая,
    а в текст находки идёт первая — читатель ищет строку по тому, что в файле
    написано. Маршруты — все вычисляемые импорты любого вида, по ним строится
    обход.
    """
    evaluated, in_span, skipped, routes = [], 0, 0, []
    fenced = False
    for num, line in enumerate(lines, 1):
        if FENCE.match(line):
            fenced = not fenced
            skipped += 1
            continue
        if fenced:
            skipped += 1
            continue
        raw_hits = len(REF.findall(line))
        bare = SPAN.sub("", line)
        hits = list(REF.finditer(bare))
        in_span += raw_hits - len(hits)
        decl = DECL.match(bare.strip())
        for m in hits:
            if decl and m.group(1) == decl.group(1):
                raw = decl.group(1)
                evaluated.append((num, raw, norm(raw), True))
            else:
                raw = m.group(1).rstrip(TAIL)
                evaluated.append((num, raw, norm(raw), False))
        for m in ANYREF.finditer(bare):
            routes.append(m.group(1).rstrip(TAIL))
    return evaluated, in_span, skipped, fenced, routes


def git(*args):
    try:
        out = subprocess.run(
            ["git", "-C", root, *args],
            capture_output=True, text=True, timeout=20,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    return out.stdout if out.returncode == 0 else None


def resolve(importer_rel, target):
    """Кандидаты разрешения ссылки: от каталога файла и от корня дерева.

    База не угадывается — перебираются обе, и берётся та, что резолвится.
    Возвращает (rel_путь_или_None, перебранные_кандидаты).
    """
    cands = []
    base = os.path.dirname(importer_rel)
    if base:
        cands.append(os.path.normpath(os.path.join(base, target)))
    cands.append(os.path.normpath(target))
    seen = list(dict.fromkeys(cands))
    for c in seen:
        if not c.startswith("..") and os.path.isfile(os.path.join(root, c)):
            return c, seen
    return None, seen


