#!/usr/bin/env bash
# check-06 — ОБЪЁМ И ФОРМА КОРПУСА. Потолок 200 000 символов (решение владельца
# 2026-09-19) и форма строки-нормы. Вердикт — в КОДЕ ВЫХОДА: 0 молчит, 1 находка,
# 2 отказ по беспредметному обходу.
#
# Разборщик берётся РЯДОМ С СОБОЙ, а дерево — из корня: инъекция гоняет проверку
# на КОПИИ дерева, куда `scripts/` не копируется.
set -euo pipefail
SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# КОРЕНЬ ВЫВОДИТСЯ ИЗ СВОЕГО РАСПОЛОЖЕНИЯ, А НЕ ИЗ ТЕКУЩЕГО КАТАЛОГА (2026-09-22).
# Здесь стоял `cd "$(git rev-parse --show-toplevel)"`, и это тот же класс, что
# измерен на `check-11`: проверка, запущенная с cwd в соседнем worktree полосы,
# МОЛЧА судит чужое дерево и выходит нулём — «полоса получает чужой вердикт».
# Образец решения взят у соседей — `check-02:196` и
# `scripts/tooling-gate/check-12:65`. Шов `RULES_GATE_ROOT` остаётся первым:
# инъекция гоняет проверку на КОПИИ дерева, и без него ось была бы недоказуема
# (контракт набора, `run-all.sh` §«КОНТРАКТ НАБОРА ДЛЯ ЕГО ПРОВЕРОК», п. «а»).
# Корень ПЕЧАТАЕТСЯ переписью: без имени дерева все прочие числа не читаются.
root="${RULES_GATE_ROOT:-$(cd "$SELF_DIR/../.." && pwd)}"
cd "$root" 2>/dev/null || {
    echo "[VOID] check-06-corpus-ceiling — корень «$root» не открывается; обходить нечего" >&2
    exit 2
}
# Корень передаётся РАЗБОРЩИКУ явно, а не оставляется на cwd: до 2026-09-22 он
# читал `.claude/rules/*.md` относительным глобом, и корнем обоих был текущий
# каталог. `cd` оставлен, чтобы координаты в находках печатались от корня.
exec python3 "$SELF_DIR/corpus_ceiling.py" "$root"
