#!/usr/bin/env bash
# ЧАСТЬ инъекции набора: доказательство check-03 «строка манифеста полна».
#
# Файл ПОДКЛЮЧАЕТСЯ (`.`) из `inject.sh` и пользуется его оснасткой — `sandbox`,
# `capture`, `assert_code`, `assert_says`, `assert_fixture_changed`, счётчиками
# `pass`/`fail`.
#
# ЗАЧЕМ ОТДЕЛЬНАЯ ЧАСТЬ, И ЭТО ИЗМЕРЕНО. До неё набор давал 50 утверждений и
# сошёлся 50 из 50 на гейте, где ЖИЛИ ПЯТЬ ДЕФЕКТОВ, четыре из них МАСКИ: пример
# строки в блоке кода и строка в HTML-комментарии зачитывались за живую; `\|`
# внутри ячейки съезжал колонками и прятал пустого держателя; неразрывный пробел,
# пустой код-спан и `TODO` проходили за названного держателя. Доказательство,
# зелёное и на починенном, и на дырявом, доказывает не то, что объявляет.
#
# ЧТО ИЗМЕНИЛОСЬ 2026-09-13. Проверка сверяла каталог `.claude/rulebook/` со
# строками таблицы; каталог снят, сверка множеств перешла в check-01 вместе с
# новым объявлением состава. Здесь остался предмет, которого у check-01 нет:
# ПОЛНОТА ЯЧЕЕК. Оси про формы записи строки (фенс, комментарий, экранированная
# труба, «пустой для человека» держатель) сохранены целиком — они про грамматику
# таблицы, а грамматика не менялась.
#
# НЕЗАВИСИМОСТЬ ОТ check-01 ДОКАЗЫВАЕТСЯ ИСХОДОМ, А НЕ СЛОВАМИ. Два близнеца ниже
# — расхождение множеств в обе стороны — обязаны оставить ЭТУ проверку зелёной.
# Без них две проверки набора незаметно слились бы в одну, и снятие любой из них
# не уронило бы ничего.
#
# По каждой оси — НАСТОЯЩИЙ дефект (гейт краснеет И называет координату) и рядом
# ЗАКОННЫЙ БЛИЗНЕЦ той же формы, на котором гейт обязан смолчать. Ни одна проба
# не меняет двух фактов сразу.

# ── СТРАЖ ПОДКЛЮЧЕНИЯ: часть НЕ исполняется самостоятельно ───────────────────
#
# Своей оснастки (`sandbox`, `capture`, `assert_*`, счётчики) у части нет. В
# обход `inject.sh` она не просто ничего не доказывает — она ПОРТИТ дерево, из
# которого запущена: каталог песочницы не определён, поэтому путь вида
# `"$d/CLAUDE.md"` становится ОТНОСИТЕЛЬНЫМ и правка уезжает в рабочую копию, а
# `git -C "$d" add -A` стажирует в её индекс чужие незакоммиченные правки.
# Испорченный индекс делает лживыми ИМЕННО те проверки, что читают дерево:
# «ноль находок» превращается в «ноль прочитанного» и выглядит настоящей
# находкой (`.claude/rules/multi-agent-flow.md` §13 «Неприкосновенность чужого
# состояния»).
#
# ИЗМЕРЕНО ДО СТРАЖА, на изолированной копии с чистым деревом: прямой запуск
# inject-02 → rc=127 и ` M CLAUDE.md`; прямой запуск inject-03 → rc=0 при НУЛЕ
# исполненных утверждений и превращал чужое ` M` в `M ` (стажировал). То есть
# «не выполнилось» отчитывалось успехом, и в том же прогоне портилось дерево.
#
# Отказ — код 2, а не 1: ноль исполненных утверждений не является находкой в
# дереве и не является успехом (`.claude/rules/testing.md` §«Чтение вердикта»).
#
# Бит исполнения намеренно ОСТАВЛЕН: без него `./inject-NN-….sh` отвечал бы
# «Permission denied» — диагностика хуже, чем у этого отказа, который называет
# и причину, и команду, которую звать вместо.
if [ "${BASH_SOURCE[0]}" = "$0" ]; then
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — ЧАСТЬ инъекции, а не самостоятельная проба." >&2
    echo "       Она подключается (\`.\`) из scripts/rules-gate/inject.sh и пользуется его" >&2
    echo "       оснасткой; самостоятельно не исполнила бы ни одного утверждения и писала бы" >&2
    echo "       в рабочее дерево. Запускать: bash scripts/rules-gate/inject.sh" >&2
    exit 2
fi
for _inj_fn in sandbox capture assert_code assert_says assert_fixture_changed sandbox_digest; do
    command -v "$_inj_fn" >/dev/null 2>&1 && continue
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — оснастки inject.sh нет: функция" \
         "«$_inj_fn» не определена; часть подключена не оттуда, доказывать нечем" >&2
    exit 2
done
unset -v _inj_fn
if [ -z "${WS:-}" ] || [ ! -d "$WS" ]; then
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — корень дерева \$WS не определён либо не" \
         "каталог; жертву фикстуры выводить не из чего" >&2
    exit 2
fi

CH03=check-03-manifest-row-is-complete.sh

# Жертва берётся ИЗ ДЕРЕВА, а не выписывается: набор правил растёт. Годится любая
# строка таблицы — предмет проверки в её ячейках, а не в имени.
inj03_victim="$(python3 - "$WS" <<'PY'
import io, os, re, sys
ws = sys.argv[1]
man = os.path.join(ws, '.claude', 'rules', 'MANIFEST.md')
for line in io.open(man, encoding='utf-8'):
    m = re.match(r'^\|\s*`?([^|`]+?)`?\s*\|', line)
    if not m:
        continue
    name = re.sub(r'^\.claude/rules/', '', m.group(1).strip())
    if name.endswith('.md'):
        print(name)
        break
PY
)"
if [ -z "$inj03_victim" ]; then
    echo "[VOID] inject-03 — в таблице MANIFEST.md нет ни одной строки про правило;" \
         "жертву выводить не из чего" >&2
    exit 2
fi
echo "-- жертва выведена из дерева: «$inj03_victim» --"

# Заменить/снять/переписать строку жертвы в манифесте песочницы.
inj03_row() {   # <каталог> <имя правила> <операция> [текст]
    python3 - "$1/.claude/rules/MANIFEST.md" "$2" "$3" "${4-}" <<'PY'
import io, re, sys
path, name, op, arg = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4]
before = io.open(path, encoding='utf-8').read()
lines = before.split('\n')
i = next(k for k, l in enumerate(lines)
         if re.match(r'^\|\s*`?' + re.escape(name) + r'`?\s*\|', l))
row = lines[i]
if op == 'gut_table':                    # снять ВСЕ строки таблицы
    keep = [l for l in lines
            if not re.match(r'^\|\s*`?[^|`]+\.md`?\s*\|', l)]
    lines = keep
elif op == 'fence':                      # снять строку и оставить её же ПРИМЕРОМ в блоке кода
    lines[i:i+1] = []
    lines += ['', '## Форма строки', '', '```', row, '```']
elif op == 'comment':                    # снять строку, закомментировав её
    lines[i:i+1] = ['<!-- снято на время переезда', row, '-->']
elif op == 'hold':                       # подменить ячейку держателя
    c = row.split('|'); c[3] = arg; lines[i] = '|'.join(c)
elif op == 'act':                        # подменить ячейку действия
    c = row.split('|'); c[2] = arg; lines[i] = '|'.join(c)
elif op == 'both':                       # выпотрошить обе ячейки
    c = row.split('|'); c[2] = '  '; c[3] = '  '; lines[i] = '|'.join(c)
elif op == 'hold_named':                 # ячейка, пустая для ЧЕЛОВЕКА, но не для байтов
    cell = {'nbsp': '   ', 'span': ' `` ', 'todo': ' TODO ', 'dash': ' `—` '}[arg]
    c = row.split('|'); c[3] = cell; lines[i] = '|'.join(c)
elif op == 'escaped_pipe':               # держатель пуст, в действии — законная `\|`
    lines[i] = '| `%s` | правка `x/**` `grep -E \'a\\|b\'` |  |' % name
else:
    raise SystemExit('unknown op ' + op)
after = '\n'.join(lines)
if after == before:
    raise SystemExit(
        'ФИКСТУРА ВАКУУМНА: операция «%s» с аргументом «%s» не изменила '
        'MANIFEST.md; утверждение о вердикте гейта относилось бы к нетронутому '
        'дереву' % (op, arg))
io.open(path, 'w', encoding='utf-8').write(after)
PY
}

echo "== ось G: держатель, пустой ДЛЯ ЧЕЛОВЕКА =="
# Форма ИМЕНУЕТСЯ, а ячейка собирается внутри python: неразрывный пробел,
# пронесённый через слово оболочки, съедается разбиением по пробелу — и проба
# начинает подставлять ПУСТУЮ ячейку, то есть проверять уже покрытый случай под
# чужим заголовком. Поймано на себе: такая проба была зелена на дофиксовом гейте.
for tag in nbsp span todo dash; do
    d="$(sandbox "c03_hold_$tag")"
    inj03_row "$d" "$inj03_victim" hold_named "$tag"
    capture "$d" "$CH03"
    assert_code 1 "держатель вида «$tag» — пустота, а не ответ"
    assert_says "чем соблюдение держится" "  ...находка вида «$tag» называет ИМЕННО держателя"
    assert_says "MANIFEST.md:" "  ...и названа строка, где пустота живёт"
done

echo "== ось G′: БЛИЗНЕЦ — «держится вниманием» словами =="
d="$(sandbox c03_hold_words)"; b03="$(sandbox_digest "$d")"
inj03_row "$d" "$inj03_victim" hold " держится вниманием ревьюера волны "
assert_fixture_changed "$d" "$b03" "БЛИЗНЕЦ: держатель назван словами"
capture "$d" "$CH03"
assert_code 0 "названный вслух отсутствующий механизм — законный ответ (§11)"

echo "== ось H: пустое ДЕЙСТВИЕ — вторая половина строки =="
# Ячейка «включается действием» после снятия свода перестала быть предписанием
# «что открыть» и стала указателем «что относится к делу». Пустая, она отнимает у
# ревьюера волны единственный машинно-читаемый вход.
d="$(sandbox c03_act_empty)"
inj03_row "$d" "$inj03_victim" act "  "
capture "$d" "$CH03"
assert_code 1 "пустое действие — находка наравне с пустым держателем"
assert_says "не названо действие, которым правило включается" "  ...и названа ИМЕННО эта половина"

echo "== ось H′: обе ячейки пусты — названы ОБЕ, а не первая =="
# Находка, назвавшая одну половину из двух, посылает чинить половину: правку
# внесут, гейт покраснеет снова, и круг оплачен зря.
d="$(sandbox c03_both_empty)"
inj03_row "$d" "$inj03_victim" both
capture "$d" "$CH03"
assert_code 1 "обе ячейки пусты — находка"
assert_says "не названо действие" "  ...названа первая половина"
assert_says "не названо, чем соблюдение держится" "  ...и НАЗВАНА ВТОРАЯ — иначе чинили бы по одной"

echo "== ось I: пустой держатель при законной \\| в соседней ячейке =="
d="$(sandbox c03_escpipe)"
inj03_row "$d" "$inj03_victim" escaped_pipe
capture "$d" "$CH03"
assert_code 1 "экранированная труба не скрывает пустого держателя"
assert_says "чем соблюдение держится" "  ...находка называет ИМЕННО пустого держателя"

echo "== ось I′: БЛИЗНЕЦ — \\| в ячейке при ПОЛНОЙ строке =="
# У близнеца отдельно утверждается, что его правка НЕ ПУСТА: `inj03_row` подменяет
# ячейку по имени правила, и на переехавшем имени подмена выродилась бы в no-op —
# тогда `[OK]` относился бы к нетронутому дереву и был бы дословно тем же, что на
# контроле. Дефектной фикстуре это не нужно: пустая правка оставит гейт зелёным и
# уронит собственное `assert_code 1`.
d="$(sandbox c03_escpipe_twin)"; b03="$(sandbox_digest "$d")"
inj03_row "$d" "$inj03_victim" hold " гейт \`grep -E 'a\\|b'\` "
assert_fixture_changed "$d" "$b03" "БЛИЗНЕЦ: труба внутри держателя"
capture "$d" "$CH03"
assert_code 0 "труба внутри держателя — содержимое ячейки, а не её граница"

echo "== ось J: ПРИМЕР строки — не строка (блок кода) =="
# Строка снята, а её копия оставлена примером в фенсе. Зачти гейт пример за живую
# строку — и снятие строки перестало бы краснеть вовсе. Здесь проверка обязана
# дать ноль находок ПО СВОЕМУ предмету (ячейки живых строк полны), а сам факт
# снятия строки ловит check-01: это и есть разделение предметов.
d="$(sandbox c03_fence)"; b03="$(sandbox_digest "$d")"
inj03_row "$d" "$inj03_victim" fence
assert_fixture_changed "$d" "$b03" "ФИКСТУРА: строка снята, пример оставлен в фенсе"
capture "$d" "$CH03"
assert_code 0 "пример в блоке кода живой строкой НЕ становится — молчит по своему предмету"

echo "== ось J′: пример В ФЕНСЕ С ПУСТЫМИ ячейками — не находка =="
# Ключевая проба грамматики: строка в фенсе НЕПОЛНА. Читай гейт фенс, он покраснел
# бы на документации собственной формы — тот самый первый ложный срабат, после
# которого гейт снимают вместе с настоящими находками.
d="$(sandbox c03_fence_empty)"; b03="$(sandbox_digest "$d")"
python3 - "$d/.claude/rules/MANIFEST.md" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8').read()
io.open(p, 'w', encoding='utf-8').write(
    s + '\n## Форма строки\n\n```\n| `primer.md` |  |  |\n```\n')
PY
assert_fixture_changed "$d" "$b03" "БЛИЗНЕЦ: пример с пустыми ячейками в блоке кода"
capture "$d" "$CH03"
assert_code 0 "пустые ячейки ВНУТРИ фенса предметом гейта не являются"

echo "== ось K: закомментированная строка =="
d="$(sandbox c03_comment)"; b03="$(sandbox_digest "$d")"
inj03_row "$d" "$inj03_victim" comment
assert_fixture_changed "$d" "$b03" "ФИКСТУРА: строка убрана в HTML-комментарий"
capture "$d" "$CH03"
assert_code 0 "строка в комментарии живой не является — по ячейкам молчим"

echo "== ось K′: комментарий с ПУСТЫМИ ячейками — не находка =="
d="$(sandbox c03_comment_empty)"; b03="$(sandbox_digest "$d")"
printf '\n<!-- набросок: | `future.md` |  |  | -->\n' >> "$d/.claude/rules/MANIFEST.md"
assert_fixture_changed "$d" "$b03" "БЛИЗНЕЦ: набросок строки в комментарии"
capture "$d" "$CH03"
assert_code 0 "пустые ячейки внутри HTML-комментария предметом гейта не являются"

echo "== ось L: таблица снята целиком — НАХОДКА, а не успех =="
# «Каждая строка полна» на пустом множестве истинно by construction. Отдай гейт
# здесь ноль — и снятие таблицы стало бы способом его погасить.
d="$(sandbox c03_gut)"
inj03_row "$d" "$inj03_victim" gut_table
capture "$d" "$CH03"
assert_code 1 "строк таблицы ноль ⇒ код 1, а не 0"
assert_says "не разобрано НИ ОДНОЙ строки таблицы" "  ...и сказано, что обход беспредметен"

echo "== ось L′: манифест снят при живом каталоге — НАХОДКА, а не VOID =="
d="$(sandbox c03_noman)"
rm -f "$d/.claude/rules/MANIFEST.md"
capture "$d" "$CH03"
assert_code 1 "манифеста нет, каталог правил стоит ⇒ код 1"
assert_says "единственное объявление состава снято" "  ...и названо, что снято именно объявление"

echo "== ось M: предмета нет — код 2, и это НЕ успех =="
d="$(sandbox c03_nodir)"
rm -rf "$d/.claude/rules"
capture "$d" "$CH03"
assert_code 2 "каталога правил нет вовсе — корпуса в этом дереве не существует"

echo "== ось N: НЕЗАВИСИМОСТЬ ОТ check-01, доказанная исходом =="
# Расхождение множеств в обе стороны обязано оставить ЭТУ проверку зелёной: её
# предмет — ячейки, а не состав. Без этих двух близнецов две проверки набора
# незаметно слились бы в одну.
d="$(sandbox c03_orphan_file)"; b03="$(sandbox_digest "$d")"
printf '# правило без строки\n' > "$d/.claude/rules/zzz-inj03-orphan.md"
assert_fixture_changed "$d" "$b03" "БЛИЗНЕЦ: файл без строки в таблице"
capture "$d" "$CH03"
assert_code 0 "правило без строки — предмет check-01, здесь ноль находок"

d="$(sandbox c03_orphan_row)"; b03="$(sandbox_digest "$d")"
python3 - "$d/.claude/rules/MANIFEST.md" <<'PY'
import io, re, sys
p = sys.argv[1]
lines = io.open(p, encoding='utf-8').read().split('\n')
i = max(k for k, l in enumerate(lines) if re.match(r'^\|\s*`?[^|`]+\.md`?\s*\|', l))
lines.insert(i + 1, '| `zzz-inj03-no-such-rule.md` | всегда | гейт-свидетель |')
io.open(p, 'w', encoding='utf-8').write('\n'.join(lines))
PY
assert_fixture_changed "$d" "$b03" "БЛИЗНЕЦ: ПОЛНАЯ строка про несуществующее правило"
capture "$d" "$CH03"
assert_code 0 "строка без файла — предмет check-01; ячейки полны, здесь ноль находок"
