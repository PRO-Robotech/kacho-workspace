#!/usr/bin/env bash
# ЧАСТЬ инъекции набора: доказательство check-06 «форма корпуса и полнота обхода»
# по осям B…G — строка без `red:`, нечётный backtick, пустой императив, пустой
# держатель, пустой признак, слово «держится»; S — состав (снятый файл правил —
# находка, снятый вместе со строкой таблицы — молчание, снятая таблица — отказ);
# N — форма записи напечатанного объёма не меняет; Z — нетронутая копия молчит.
# У каждой оси — законный близнец той же формы.
#
# ЕДИНИЦА СЧЁТА ОСЕЙ — буква в разметке секций (`# ── ось S`, `# ── оси B…G`);
# предикат — `grep -cE '^# ── ос(ь|и) ' scripts/rules-gate/inject-06-corpus-form.sh`.
#
# ОСЕЙ ОБЪЁМА (A, A' и половины N о перевесе) БОЛЬШЕ НЕТ: совокупный потолок корпуса
# снят (ws#1084, владелец 2026-10-14), окно агента доказывает `inject-13`. Вместе с
# потолком снят и `room6`: освобождать место под фикстуру больше не под что.
#
# Файл ПОДКЛЮЧАЕТСЯ (`.`) из `inject.sh` и пользуется его оснасткой.

# ── СТРАЖ ПОДКЛЮЧЕНИЯ ────────────────────────────────────────────────────────
if [ "${BASH_SOURCE[0]}" = "$0" ]; then
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — ЧАСТЬ инъекции, а не самостоятельная проба." >&2
    echo "       Она подключается из scripts/rules-gate/inject.sh и пользуется его оснасткой;" >&2
    echo "       самостоятельно писала бы в рабочее дерево. Запускать:" >&2
    echo "       bash scripts/rules-gate/inject.sh" >&2
    exit 2
fi
for _i06_fn in sandbox capture assert_code assert_says assert_number assert_fixture_changed sandbox_digest; do
    command -v "$_i06_fn" >/dev/null 2>&1 && continue
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — оснастки inject.sh нет: функция" \
         "«$_i06_fn» не определена; часть подключена не оттуда" >&2
    exit 2
done
unset -v _i06_fn

C6=check-06-corpus-form.sh

# vol6 <каталог песочницы> — объём её корпуса В СИМВОЛАХ, тем же счётом, что и
# проверка: байт и символ здесь расходятся вдвое, и ошибка была бы тихой.
vol6() {
    ( cd "$1" && python3 -c '
import glob
print(sum(len(open(f, encoding="utf-8").read()) for f in glob.glob(".claude/rules/*.md")))' )
}

# Жертва выводится ИЗ ДЕРЕВА: имя в коде рассыпалось бы вместе с раскладкой.
# Порядок глоба зависит от ЛОКАЛИ, а жертва обязана быть одной и той же на всякой
# машине: сортировка — в C.
V6=""
while IFS= read -r _v; do
    [ -e "$_v" ] || continue
    V6=".claude/rules/$(basename "$_v")"
    break
done < <(printf '%s\n' "$WS"/.claude/rules/*.md | LC_ALL=C sort)
unset -v _v
if [ -z "$V6" ]; then
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — в .claude/rules нет ни одного файла;" \
         "строку-норму вписывать некуда" >&2
    exit 2
fi

# row <ось> <строка> <утверждение> <дословная находка> — одна дефектная
# строка-норма, ОДИН вердикт и ОДИН диагноз.
#
# Два шага: убедиться, что песочница МОЛЧИТ до дефекта · внести один факт и
# потребовать, чтобы напечатано было про НЕГО.
row() {
    local d; d="$(sandbox "i06_$1")"
    capture "$d" "$C6"
    assert_code 0 "КОНТРОЛЬ оси $1: песочница до внесения дефекта молчит"
    printf '\n%s\n' "$2" >> "$d/$V6"
    capture "$d" "$C6"
    assert_code 1 "$3"
    assert_says "$4" "ДИАГНОЗ оси $1: находка называет ИМЕННО эту ось"
    assert_lacks "КРАСНОЕ состав" "ДИАГНОЗ оси $1: чужая ось в вердикт не примешана"
}

# ── оси B…G: форма строки-нормы ──────────────────────────────────────────────
row nored 'probe-bez-red · императив пробы · ЗАВЕСТИ probe-bez-red · признак без метки' \
    "ДЕФЕКТ: строка-норма без поля red: — краснеет" 'КРАСНОЕ строка без поля red:'
row oddbt 'probe-odd-bt · императив с `незакрытым обратным апострофом · ЗАВЕСТИ probe-odd-bt · red: признак' \
    "ДЕФЕКТ: нечётный backtick в строке-норме — краснеет" 'КРАСНОЕ нечётный backtick'
row noimp 'probe-pustoj-imperativ · — · ЗАВЕСТИ probe-pustoj-imperativ · red: признак' \
    "ДЕФЕКТ: пустой императив (поле 2) — краснеет" 'КРАСНОЕ пустой императив (поле 2)'
row nohold 'probe-pustoj-derzhatel · императив пробы · — · red: признак' \
    "ДЕФЕКТ: пустой держатель (поле 3) — краснеет" 'КРАСНОЕ пустой держатель (поле 3)'
row nosign 'probe-pustoj-priznak · императив пробы · ЗАВЕСТИ probe-pustoj-priznak · red: —' \
    "ДЕФЕКТ: пустой признак красноты — краснеет" 'КРАСНОЕ пустой признак красноты'
row held 'probe-derzhitsya · императив пробы · держится вниманием · red: признак' \
    "ДЕФЕКТ: «держится» вместо названного механизма — краснеет" 'КРАСНОЕ слово «держится»'

# ── ось S: обход не дошёл до объявленного файла — находка, а не зелёная форма
# Недочитанное дерево не судит строк-норм пропущенного файла: «находок 0» здесь
# неотличимо от «формы целы». До ws#854 ось держал пол `FLOOR_FILES = 17` при 18
# файлах, и проба снимала ПЯТНАДЦАТЬ файлов из восемнадцати: снятие ОДНОГО
# (корпус 190 619 из 200 000) проверка не видела, код 0. Теперь ожидаемый состав —
# таблица `MANIFEST.md`, и пар три, каждая меняет один факт:
#   (1) снят один файл правил, строка таблицы о нём стоит — код 1, файл назван;
#   (2) снят тот же файл ВМЕСТЕ со своей строкой таблицы (законное снятие
#       правила) — объявленное и осмотренное совпадают, ось молчит;
#   (3) снята сама таблица — объявления нет, код 2: сверять полноту не с чем.
# Жертва выводится ИЗ ДЕРЕВА: последний файл в порядке C, кроме таблицы и кроме
# `V6` (его правят оси формы). Строка таблицы о ней находится ОБЩИМ разборщиком
# набора — он печатает номер строки, — а не своим шаблоном: вторая грамматика
# таблицы разошлась бы с первой молча.
DROP6=""
while IFS= read -r _v; do
    [ -e "$_v" ] || continue
    case "$(basename "$_v")" in MANIFEST.md|"$(basename "$V6")") continue ;; esac
    DROP6="$(basename "$_v")"
done < <(printf '%s\n' "$WS"/.claude/rules/*.md | LC_ALL=C sort)
unset -v _v
if [ -z "$DROP6" ]; then
    echo "  [FAIL] ось S НЕИСПОЛНИМА: в .claude/rules нет файла, кроме таблицы и жертвы" \
         "осей формы — снимать нечего, и полнота обхода осталась бы недоказанной" >&2
    fail=$((fail + 1))
else
    d="$(sandbox i06_drop_one)"; b="$(sandbox_digest "$d")"
    rm -f "$d/.claude/rules/$DROP6"
    assert_fixture_changed "$d" "$b" "ДЕФЕКТ: снят один файл правил ($DROP6), строка таблицы стоит"
    capture "$d" "$C6"
    assert_code 1 "ДЕФЕКТ: снят один файл правил — краснеет сама, без опоры на check-01"
    assert_says "КРАСНОЕ состав" "ДИАГНОЗ оси S: находка называет ИМЕННО состав"
    assert_says "($DROP6)" "  ...и называет снятый файл по имени"

    d="$(sandbox i06_drop_twin)"; b="$(sandbox_digest "$d")"
    _row="$(LC_ALL=C awk -f "$GATE/manifest-rows.awk" "$d/.claude/rules/MANIFEST.md" \
        | awk -F'\t' -v n="$DROP6" '$2 == n { print $1 }')"
    if ! grep -qE '^[0-9]+$' <<<"$_row"; then
        echo "  [FAIL] БЛИЗНЕЦ оси S: строка таблицы о $DROP6 не найдена разборщиком" \
             "(получено «$_row») — законное снятие не собрать" >&2
        fail=$((fail + 1))
    else
        rm -f "$d/.claude/rules/$DROP6"
        sed -i "${_row}d" "$d/.claude/rules/MANIFEST.md"
        assert_fixture_changed "$d" "$b" "БЛИЗНЕЦ: снят файл $DROP6 и его строка таблицы (строка $_row)"
        capture "$d" "$C6"
        assert_code 0 "БЛИЗНЕЦ: правило снято вместе со строкой таблицы — объявленное совпало с осмотренным, молчит"
        assert_lacks "КРАСНОЕ состав" "  ...и ось состава молчит именно потому, что строки о файле больше нет"
    fi
    unset -v _row

    d="$(sandbox i06_no_manifest)"
    rm -f "$d/.claude/rules/MANIFEST.md"
    capture "$d" "$C6"
    assert_code 2 "ПРЕДПОСЫЛКА: таблицы состава нет — ОТКАЗ, полноту обхода сверить не с чем"
    assert_says "объявления состава нет" "  ...и отказ назван своей причиной"
fi

# ── БЛИЗНЕЦ осей B…G: строка-норма ТОЙ ЖЕ формы, но полная ──────────────────
d="$(sandbox i06_twin_row)"
TWIN_ROW="probe-polnaya-stroka · императив пробы в \`кавычках\` целиком · scripts/rules-gate/check-06-corpus-form.sh · red: признак назван"
b="$(sandbox_digest "$d")"
printf '\n%s\n' "$TWIN_ROW" >> "$d/$V6"
assert_fixture_changed "$d" "$b" "БЛИЗНЕЦ: строка-норма добавлена, все четыре поля полны"
capture "$d" "$C6"
assert_code 0 "БЛИЗНЕЦ: полная строка-норма — молчит"

# ── ось N: ФОРМА ЗАПИСИ напечатанного объёма не меняет ────────────────────
# `й` — один символ в NFC и два в NFD; объём печатается переписью, и число в ней
# обязано не зависеть от формы, в которой файл сохранён (`corpus_form.FORM`).
d="$(sandbox i06_nfd)"
nfc_vol="$(vol6 "$d")"
python3 - "$d" <<'PY'
import glob, os, sys, unicodedata
os.chdir(sys.argv[1])
for f in sorted(glob.glob('.claude/rules/*.md')):
    text = open(f, encoding='utf-8').read()
    open(f, 'w', encoding='utf-8').write(unicodedata.normalize('NFD', text))
PY
capture "$d" "$C6"
assert_code 0 "БЛИЗНЕЦ: корпус переписан в NFD — ни одной изменённой буквы — молчит"
assert_number "объём:" "$nfc_vol" "БЛИЗНЕЦ: на NFD напечатано ТО ЖЕ число, что на NFC ($nfc_vol)"

# ── ось Z: нетронутая копия — молчит ────────────────────────────────────────
d="$(sandbox i06_clean)"
capture "$d" "$C6"
assert_code 0 "БЛИЗНЕЦ: нетронутая копия — молчит"
