#!/usr/bin/env bash
# check-04 — ПРИВЯЗКА ПРАВИЛА К АГЕНТУ СХОДИТСЯ В ОБЕ СТОРОНЫ.
#
# ЧТО УТВЕРЖДАЕТ. Каждое правило корпуса закреплено хотя бы за одним СУЩЕСТВУЮЩИМ
# агентом (4-я ячейка строки манифеста), и это объявление совпадает с исполнением:
# множество `skills: rule-*` во frontmatter агента равно множеству правил,
# закреплённых за ним таблицей, — в обе стороны. Сверх того сходится сам
# ПЕРЕХОДНИК, которым правило доезжает в окно: `.claude/skills/rule-<имя>/SKILL.md`
# существует, является символьной ссылкой и указывает на своё правило.
#
# ПОЧЕМУ ЭТО ГЕЙТ, А НЕ АБЗАЦ. Решением владельца 2026-09-17 правила сняты с
# автозагрузки: `.claude/settings.json` исключает `.claude/rules/**`, а `CLAUDE.md`
# не импортирует ничего. Единственный путь правила в окно — предзагрузка агенту,
# за которым оно закреплено. Значит РАЗРЫВ ПРИВЯЗКИ не проявляется НИЧЕМ: файл на
# месте, строка в манифесте на месте, дифф безобиден, прогон зелен, — а правило не
# читает никто и никогда, и нарушают его не по небрежности. Прежняя раскладка
# («весь корпус каждому») от этого класса защищала by construction: не закрепить
# правило было невозможно. Теперь защищает только исполняемый вопрос к дереву
# (`.claude/rules/testing.md` §«Гейт на класс»).
#
# ЧЕТЫРЕ РАЗНЫХ МЕСТА ОБ ОДНОМ ПРЕДМЕТЕ, И ГЕЙТ СВОДИТ ИХ ВСЕ:
#   таблица манифеста (ОБЪЯВЛЕНИЕ — кому грузится) · frontmatter агента
#   (ИСПОЛНЕНИЕ — что грузится) · каталог `.claude/skills/rule-*` (ПЕРЕХОДНИК —
#   чем грузится) · каталог `.claude/rules/` (ПРЕДМЕТ — что именно).
# Расходятся они молча и поодиночке: снятый агент оставляет строку манифеста;
# дописанная строка не доезжает до frontmatter; переименованное правило оставляет
# ссылку, указывающую в пустоту. Каждая из этих правок выглядит в диффе местной.
#
# ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ СОСЕДЕЙ, И ПОЧЕМУ ПРОВЕРОК ЧЕТЫРЕ.
#   · check-01 сверяет СОСТАВ: файл без строки и строка без файла. Состав сходится
#     и при пустой 4-й ячейке — от содержимого ячейки он не меняется ни на файл.
#   · check-03 судит ПОЛНОТУ ЯЧЕЕК как текста: ячейка непуста и не заглушка.
#     Непустая ячейка бывает ЛОЖНОЙ: «все исполнители» — текст, но не имена;
#     `qa-test-enginer` — имя, но не агент. Здесь ячейка РАЗБИРАЕТСЯ на имена и
#     каждое имя спрашивается у каталога агентов.
#   · check-02 судит АВТОЗАГРУЗКУ: в замыкании `CLAUDE.md` правил нет. Оттуда не
#     следует, что правило доезжает хоть кому-то: «никому не грузится» его
#     утверждению удовлетворяет полностью.
# Ни одно из четырёх утверждений не выводится из трёх остальных.
#
# ПОЧЕМУ В ОБЕ СТОРОНЫ. Совпадение ЧИСЕЛ не доказывает ничего: множества равной
# мощности бывают разными. Правило, закреплённое манифестом и не доехавшее до
# frontmatter, не читает НИКТО — при зелёном манифесте. Правило, стоящее во
# frontmatter и не объявленное в таблице, грузится агенту БЕЗ РЕШЕНИЯ: колонка
# «закреплено за агентами» перестаёт отвечать на вопрос «кому это грузится», а
# именно ради этого ответа она заведена.
#
# АГЕНТ БЕЗ ЕДИНОГО ПРАВИЛА — НЕ НАХОДКА, И ЭТО ОБЪЯВЛЯЕТСЯ ПРЯМО. Пустой контекст
# бывает ПРЕДМЕТОМ роли: `client-simulator` имитирует клиента и обязан не знать
# внутренних правил (у него и `omitClaudeMd`). Требовать правил от каждого агента
# значило бы ломать роль ради симметрии. Несимметрично здесь другое: находка —
# ПРАВИЛО без агента (его не прочтёт никто), а не агент без правил.
#
# ССЫЛКА-ПЕРЕХОДНИК — ПРЕДМЕТ, А НЕ УКРАШЕНИЕ. Харнесс грузит `skills:` по
# каталогу `.claude/skills/`, а правило живёт в `.claude/rules/`. Связывает их
# ровно одна символьная ссылка `SKILL.md -> ../../rules/<имя>.md`. Подмена ссылки
# ОБЫЧНЫМ ФАЙЛОМ — самый тихий из отказов: агент получает предзагрузкой КОПИЮ,
# которая расходится с правилом молча и навсегда, и дифф правила остаётся зелёным.
# Поэтому предикат — `os.path.islink`, а не существование пути, и цель ещё
# разыменовывается и сверяется со СВОИМ правилом: ссылка на чужое правило даёт
# агенту не то, что объявлено, и тоже ничем не проявляется.
#
# РАЗБОР ТАБЛИЦЫ — ОБЩИЙ С check-01 и check-03, файлом `manifest-rows.awk`.
# Грамматика у таблицы одна, и две её копии разошлись бы молча: строка, видимая
# одной проверке и невидимая другой, не даёт ни красного, ни вопроса. Разборщик
# остаётся ЕДИНСТВЕННЫМ арбитром того, какая строка живая и как зовётся правило.
#
#   ПЕРЕХОДНАЯ ОПОРА, названная вслух. 4-ю ячейку разборщик печатает ПЯТЫМ полем.
#   Пока он его не печатает (старая форма из четырёх полей), текст ячейки снимается
#   ЗДЕСЬ — но не поиском строк заново, а ПО НОМЕРУ СТРОКИ, которую живой признал
#   САМ разборщик. Второго решения о грамматике таблицы не заводится: фенс,
#   HTML-комментарий и `\|` внутри ячейки остаются его предметом. Опора отмирает
#   сама в тот день, когда пятое поле появится, — и код её не заметит.
#
# ИМЯ СКИЛА ВЫВОДИТСЯ ИЗ ИМЕНИ ПРАВИЛА: `rule-` + имя без `.md`. Правило во
# ВЛОЖЕННОМ каталоге (`domain/vpc.md`) даст имя со слэшем, то есть путь, которого
# в `.claude/skills/` нет, — и это находка RULE-SKILL-MISSING с точной
# координатой, а не молчание. Списка прощённых не заводится.
#
# ПРЕДПОСЫЛКА (VOID, код 2) — ровно три: нет разборщика таблицы, нет каталога
# `.claude/rules/`, нет каталога `.claude/agents/`. Тогда одной из сторон привязки
# в этом дереве не существует вовсе, и сверять нечего.
#
# СНЯТЫЙ МАНИФЕСТ, ВЫПОТРОШЕННАЯ ТАБЛИЦА И ПУСТОЙ КАТАЛОГ АГЕНТОВ — НАХОДКИ, А НЕ
# VOID. Послабление не выдаётся удалением предмета: иначе достаточно было бы
# стереть таблицу или унести агентов, чтобы гейт перестал блокировать отправку, а
# именно от этого он заведён.
#
# Коды выхода: 0 — привязка сошлась в обе стороны, находок 0; 1 — находка либо
# пустой обход; 2 — предмета нет.

set -uo pipefail

NAME="check-04-rule-agent-binding"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Корень воркспейса. `RULES_GATE_ROOT` переопределяет его — этим пользуется ТОЛЬКО
# инъекция, чтобы прогонять гейт по временному дереву с внесённым дефектом и не
# трогать рабочее (`.claude/rules/testing.md` §«Гейт на класс»). Разборщик берётся
# из СВОЕГО каталога, а не из песочницы: предмет инъекции — дерево, а не текст
# проверки.
if [ -n "${RULES_GATE_ROOT:-}" ]; then
    if ! WS="$(cd "$RULES_GATE_ROOT" 2>/dev/null && pwd)"; then
        echo "[CENSUS] $NAME: разбор не запускался; правил 0, строк таблицы 0, агентов 0"
        echo "[VOID] $NAME — RULES_GATE_ROOT=$RULES_GATE_ROOT не открывается — читать неоткуда" >&2
        exit 2
    fi
else
    WS="$(cd "$SCRIPT_DIR/../.." && pwd)"
fi

CHECK_NAME="$NAME" RULES_GATE_WS="$WS" RULES_GATE_PARSER="$SCRIPT_DIR/manifest-rows.awk" \
python3 - <<'PY'
import os
import re
import subprocess
import sys

NAME = os.environ["CHECK_NAME"]
root = os.environ["RULES_GATE_WS"]
parser = os.environ["RULES_GATE_PARSER"]

RULES_REL = ".claude/rules"
AGENTS_REL = ".claude/agents"
SKILLS_REL = ".claude/skills"
MAN_REL = RULES_REL + "/MANIFEST.md"

rules_abs = os.path.join(root, RULES_REL)
agents_abs = os.path.join(root, AGENTS_REL)
skills_abs = os.path.join(root, SKILLS_REL)
man_abs = os.path.join(root, MAN_REL)


def census(msg):
    print("[CENSUS] %s: %s" % (NAME, msg))


def fail(msg):
    print("[FAIL] %s — %s" % (NAME, msg), file=sys.stderr)


def void(msg):
    print("[VOID] %s — %s" % (NAME, msg), file=sys.stderr)
    sys.exit(2)


def read(path):
    with open(path, encoding="utf-8", errors="replace") as fh:
        return fh.read()


# ── предпосылка 0: разборщик таблицы на месте ────────────────────────────────
# Его отсутствие — «не выполнилось», а не «находок 0»: без него строк ноль, и
# «каждое правило закреплено» стало бы истинным на пустом множестве.
if not os.path.isfile(parser):
    census("разбор не запускался: %s не существует; правил 0, строк таблицы 0, агентов 0" % parser)
    void("разборщика таблицы manifest-rows.awk нет рядом с проверкой — читать объявление "
         "нечем; это НЕ «находок 0»")

# ── предпосылка 1: обе стороны привязки существуют ───────────────────────────
if not os.path.isdir(rules_abs):
    census("каталога %s нет; правил 0, строк таблицы 0, агентов 0" % RULES_REL)
    void("каталога %s нет в %s — корпуса правил в этом дереве не существует, "
         "закреплять нечего" % (RULES_REL, root))
if not os.path.isdir(agents_abs):
    census("каталога %s нет; строк таблицы 0, агентов 0" % AGENTS_REL)
    void("каталога %s нет в %s — исполнителей в этом дереве не существует, "
         "закреплять не за кем" % (AGENTS_REL, root))

# ── что лежит в корпусе ФАКТИЧЕСКИ ───────────────────────────────────────────
# Единица счёта — запись `*.md` НА ДИСКЕ, рекурсивно, относительным путём: имя
# правила в таблице пишется именно так, и вложенное правило законно (check-01
# сверяет его тем же относительным путём).
rules = []
for base, dirs, files in os.walk(rules_abs):
    for f in files:
        if f.endswith(".md"):
            rel = os.path.relpath(os.path.join(base, f), rules_abs)
            rules.append(rel.replace(os.sep, "/"))
rules.sort()
rules_set = set(rules)

# ── кто в дереве исполнитель ─────────────────────────────────────────────────
# Диспетчер — агент наравне с прочими и из сверки НЕ исключается: правило,
# закреплённое за ним, обязано краснеть (он правил не грузит вовсе, `skills:` у
# него нет), а эту находку даёт ровно BINDING-DRIFT.
agent_files = sorted(f for f in os.listdir(agents_abs)
                     if f.endswith(".md") and os.path.isfile(os.path.join(agents_abs, f)))
agents = [f[:-3] for f in agent_files]
agents_set = set(agents)

FM = re.compile(r"\A---\r?\n(.*?)\r?\n---\r?\n", re.S)


def frontmatter(path):
    """Головной блок `---…---`. Нет его — нет и объявленных скилов."""
    m = FM.match(read(path))
    return m.group(1) if m else ""


def declared_skills(fm):
    """Значение ключа `skills:` во frontmatter — обе законные формы YAML.

    Блочная (`skills:\\n  - rule-x`) и поточная (`skills: [rule-x, rule-y]`)
    читаются харнессом одинаково; распознаватель, знающий одну, на второй МОЛЧИТ —
    ни красного, ни зелёного, а невидимость (`.claude/rules/testing.md` §«Гейт на
    класс», п.7).
    """
    m = re.search(r"^skills:[ \t]*(.*)$", fm, re.M)
    if not m:
        return []
    inline = m.group(1).strip()
    if inline.startswith("["):
        return [x.strip().strip("\"'") for x in inline[1:-1].split(",") if x.strip()]
    if inline:
        return [x.strip().strip("\"'") for x in inline.split(",") if x.strip()]
    out = []
    for line in fm[m.end():].split("\n"):
        # `-` и пробел ОБЯЗАТЕЛЬНЫ: иначе закрывающая черта frontmatter (`---`)
        # зачитывается за элемент списка. Поймано инъекцией: разбор отдавал скил
        # с именем `--`, и хотя фильтр `rule-*` его отбрасывал, тот же промах в
        # фикстуре сносил половину блока.
        item = re.match(r"^\s*-[ \t]+(\S+)[ \t]*$", line)
        if item:
            out.append(item.group(1).strip("\"'"))
        elif line.strip() and not line.startswith((" ", "\t")):
            break
    return out


# ── что корпусом ОБЪЯВЛЕНО ───────────────────────────────────────────────────
man_lines = 0
rows = []
if os.path.isfile(man_abs):
    man_lines = read(man_abs).count("\n")
    out = subprocess.run(["awk", "-f", parser, man_abs],
                         capture_output=True, text=True,
                         env=dict(os.environ, LC_ALL="C")).stdout
    man_src = read(man_abs).split("\n")
    for line in out.split("\n"):
        if not line.strip():
            continue
        f = line.split("\t")
        if len(f) < 2:
            continue
        ln, name = f[0], f[1]
        cell = ""
        # Пятое поле разборщика — текст 4-й ячейки. Одиночная буква-признак
        # (`A`/`H`/`B`/`-`) текстом ячейки не является: это флаг, и имён в нём нет.
        if len(f) >= 5 and f[4] not in ("-", "A", "H", "B"):
            cell = f[4]
        else:
            # ПЕРЕХОДНАЯ ОПОРА (см. шапку): строку выбрал разборщик, здесь снимается
            # только ячейка. `\|` — содержимое ячейки, а не её граница.
            try:
                raw = man_src[int(ln) - 1]
            except (ValueError, IndexError):
                raw = ""
            c = raw.replace("\\|", "\001").split("|")
            cell = c[4].replace("\001", "|").strip() if len(c) > 4 else ""
        rows.append((ln, name, cell))

# ── имена агентов из ячейки ──────────────────────────────────────────────────
# Обратные кавычки — объявленная форма (`MANIFEST.md`, шапка таблицы), и если они
# есть, читаются ТОЛЬКО они. Их нет — ячейка режется по разделителям, и каждый
# кусок обязан быть именем файла агента. Кусок, именем быть не могущий («все
# исполнители», «—»), молча НЕ отбрасывается: он приходит находкой AGENT-UNKNOWN,
# потому что перечень поимённый, а шаблон подхватывает нового агента незаметно.
NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")


def cell_names(cell):
    if "`" in cell:
        return [x.strip() for x in re.findall(r"`([^`]*)`", cell) if x.strip()]
    return [x.strip() for x in re.split(r"[·,;]", cell) if x.strip()]


bound = {}          # агент -> множество правил, закреплённых за ним таблицей
declared_rows = 0
unbound_rows = []
unknown = []        # (строка, правило, имя)
for ln, name, cell in rows:
    declared_rows += 1
    names = cell_names(cell)
    if not names:
        unbound_rows.append((ln, name))
        continue
    for a in names:
        if a in agents_set:
            bound.setdefault(a, set()).add(name)
        else:
            unknown.append((ln, name, a))

# ── переходники `.claude/skills/rule-*` ──────────────────────────────────────
skill_dirs = []
if os.path.isdir(skills_abs):
    skill_dirs = sorted(d for d in os.listdir(skills_abs)
                        if d.startswith("rule-")
                        and os.path.isdir(os.path.join(skills_abs, d)))

# ── ПЕРЕПИСЬ ОБЪЁМА — печатается ВСЕГДА и до вердикта ────────────────────────
# «Ноль находок» обязано быть отличимо от «ноль прочитанного»
# (`.claude/rules/testing.md` §«Гейт на класс», п.3).
census("правил в %s — %d; %s: строк %d, строк таблицы разобрано %d; "
       "агентов в %s — %d; закреплений прочитано %d, из них за существующими агентами %d; "
       "переходников %s/rule-* — %d"
       % (RULES_REL, len(rules), MAN_REL, man_lines, declared_rows,
          AGENTS_REL, len(agents),
          sum(len(cell_names(c)) for _, _, c in rows),
          sum(len(v) for v in bound.values()),
          SKILLS_REL, len(skill_dirs)))

# ── ПУСТОЙ ОБХОД — НАХОДКА, А НЕ УСПЕХ ───────────────────────────────────────
if not os.path.isfile(man_abs):
    fail("%s в дереве нет при %d правилах и %d агентах — единственное объявление "
         "привязки снято; кому что грузится, не сказано нигде, и это находка, а не "
         "отсутствие предмета" % (MAN_REL, len(rules), len(agents)))
    sys.exit(1)
if declared_rows == 0:
    fail("в %s не разобрано НИ ОДНОЙ строки таблицы при %d правилах в каталоге — "
         "таблица снята либо её форма сменилась; «каждое правило закреплено» на пустом "
         "множестве истинно by construction, поэтому здесь это находка, а не успех"
         % (MAN_REL, len(rules)))
    sys.exit(1)
if not agents:
    fail("обход беспредметен: в %s прочитано 0 файлов агентов при %d строках таблицы — "
         "исполнители унесены целиком, предзагружать правила некому"
         % (AGENTS_REL, declared_rows))
    sys.exit(1)

findings = 0

# ── ОСЬ RULE-UNBOUND: правило, которое не прочтёт никто ──────────────────────
for ln, name in unbound_rows:
    fail("RULE-UNBOUND: %s:%s — строка про %s не называет НИ ОДНОГО агента; "
         "правила сняты с автозагрузки, и незакреплённое правило не попадает в окно "
         "ни одной сессии — его не прочтёт никто" % (MAN_REL, ln, name))
    findings += 1

# ── ОСЬ AGENT-UNKNOWN: закрепление за тем, кого нет ──────────────────────────
for ln, name, a in unknown:
    fail("AGENT-UNKNOWN: %s:%s — правило %s закреплено за «%s», а файла %s/%s.md нет; "
         "закрепление за несуществующим агентом ничем не отличается от отсутствия "
         "закрепления, но выглядит выполненным"
         % (MAN_REL, ln, name, a, AGENTS_REL, a))
    findings += 1

# ── ОСЬ BINDING-DRIFT: объявление разошлось с исполнением ────────────────────
# Сверяются МНОЖЕСТВА и называются ОБЕ разности: находка, назвавшая одну сторону,
# посылает чинить половину — правку внесут, гейт покраснеет снова, круг оплачен зря.
drift = 0
for a in agents:
    fm = frontmatter(os.path.join(agents_abs, a + ".md"))
    got = {s for s in declared_skills(fm) if s.startswith("rule-")}
    want = {"rule-" + r[:-3] for r in bound.get(a, set())}
    if got == want:
        continue
    drift += 1
    only_man = sorted(want - got)
    only_agent = sorted(got - want)
    parts = []
    if only_man:
        parts.append("манифест закрепил, а во frontmatter нет: %s (правило агенту НЕ "
                     "грузится, при зелёном объявлении)" % ", ".join(only_man))
    if only_agent:
        parts.append("frontmatter грузит, а манифест не закреплял: %s (правило доезжает "
                     "БЕЗ решения, и колонка перестаёт отвечать, кому что грузится)"
                     % ", ".join(only_agent))
    fail("BINDING-DRIFT: %s/%s.md — %s" % (AGENTS_REL, a, "; ".join(parts)))
    findings += 1

# ── ОСЬ RULE-SKILL-MISSING: переходника нет либо он ведёт не туда ────────────
for r in rules:
    skill = "rule-" + r[:-3]
    p = os.path.join(skills_abs, skill, "SKILL.md")
    rel = "%s/%s/SKILL.md" % (SKILLS_REL, skill)
    if not os.path.lexists(p):
        fail("RULE-SKILL-MISSING: %s нет — правило %s нечем предзагрузить: харнесс "
             "грузит `skills:` по каталогу скилов, и без переходника закрепление в "
             "манифесте остаётся обещанием" % (rel, r))
        findings += 1
        continue
    if not os.path.islink(p):
        fail("RULE-SKILL-MISSING: %s — не символьная ссылка, а обычная запись; агент "
             "получает предзагрузкой КОПИЮ, которая расходится с %s/%s молча и навсегда, "
             "а дифф правила остаётся зелёным" % (rel, RULES_REL, r))
        findings += 1
        continue
    tgt = os.readlink(p)
    want = os.path.realpath(os.path.join(rules_abs, r))
    have = os.path.realpath(os.path.join(os.path.dirname(p), tgt))
    if not os.path.exists(p):
        fail("RULE-SKILL-MISSING: %s -> %s — цель НЕ резолвится; правило %s не читается "
             "вовсе, а закрепление объявлено" % (rel, tgt, r))
        findings += 1
    elif have != want:
        fail("RULE-SKILL-MISSING: %s -> %s — ведёт не на своё правило (ожидалось "
             "%s/%s); агент грузит не то, что объявлено, и различие не видно ниоткуда"
             % (rel, tgt, RULES_REL, r))
        findings += 1

# ── ОСЬ RULE-SKILL-ORPHAN: переходник без правила ────────────────────────────
# Имя `rule-*` зарезервировано под привязку. Каталог, которому правила не
# соответствует, — либо след переименования (агент грузит пустоту), либо заведённая
# под зарезервированным именем экспертиза; обе починки называются одной находкой.
for d in skill_dirs:
    r = d[len("rule-"):] + ".md"
    if r not in rules_set:
        fail("RULE-SKILL-ORPHAN: %s/%s/ существует, а правила %s/%s нет — имя `rule-*` "
             "занято привязкой; это либо след переименования правила, либо экспертиза, "
             "заведённая под зарезервированным именем" % (SKILLS_REL, d, RULES_REL, r))
        findings += 1

# ── ОСЬ AGENT-RULE-DANGLING: агент грузит несуществующее правило ─────────────
# Предмет — ПРАВИЛО, которого нет в корпусе. Отсутствие переходника при живом
# правиле сюда не относится: его называет RULE-SKILL-MISSING один раз, а не по
# разу на каждого закреплённого агента.
for a in agents:
    fm = frontmatter(os.path.join(agents_abs, a + ".md"))
    for s in declared_skills(fm):
        if not s.startswith("rule-"):
            continue
        r = s[len("rule-"):] + ".md"
        if r not in rules_set:
            fail("AGENT-RULE-DANGLING: %s/%s.md перечисляет `%s`, а правила %s/%s в "
                 "корпусе нет — агент стартует с ссылкой в пустоту, и объявленного "
                 "правила у него нет ни в каком виде" % (AGENTS_REL, a, s, RULES_REL, r))
            findings += 1

if findings:
    fail("находок %d; правил %d, строк таблицы %d, агентов %d, переходников %d"
         % (findings, len(rules), declared_rows, len(agents), len(skill_dirs)))
    sys.exit(1)

print("[PASS] %s — привязка сверена в обе стороны: правил %d, строк таблицы %d, "
      "агентов %d, закреплений %d, переходников %d; незакреплённых правил 0, "
      "неизвестных агентов 0, расхождений frontmatter 0, битых переходников 0"
      % (NAME, len(rules), declared_rows, len(agents),
         sum(len(v) for v in bound.values()), len(skill_dirs)))
sys.exit(0)
