#!/usr/bin/env bash
# Прогон набора rules-gate. Вердикт стоит в КОДЕ ВЫХОДА, а не в печати.
#
# ПРЕДМЕТ НАБОРА — МОДЕЛЬ ЗАГРУЗКИ, ДЕЙСТВУЮЩАЯ С 2026-09-17. Решение владельца:
# «все рулы свести к агентам которые должны их использовать… Мастер процесс
# загружает только базу которая позволит определить какого агента в какой момент
# запускать». Отсюда четыре звена, и набор сторожит каждое:
#   · корпус `.claude/rules/` НЕ грузится автоматически никому — ни диспетчеру, ни
#     исполнителю: каталог снят с автозагрузки `claudeMdExcludes`, а `CLAUDE.md` не
#     импортирует ни одного правила;
#   · главный поток — агент `dispatcher`, и тело `.claude/agents/dispatcher.md`
#     заменяет ему системный промпт, оставаясь единственной базой маршрутизации;
#   · правило доезжает до агента предзагрузкой: скилл-ссылка
#     `.claude/skills/rule-<имя>/SKILL.md` и `skills:` во frontmatter агента;
#   · кому какое правило закреплено, объявляет ЧЕТВЁРТАЯ колонка таблицы
#     `.claude/rules/MANIFEST.md`.
# Держится это НАБОРОМ, а не фразой в CLAUDE.md. Всякий разрыв здесь МОЛЧАЛИВ:
# правило без строки манифеста не закреплено ни за кем и не приезжает никому;
# правило, вернувшееся в `@import`, приезжает всем и всегда; снятый шаблон
# исключения возвращает в окно 143 КБ корпуса — и ни то, ни другое, ни третье не
# меняет ни одного прогона продукта и выглядит в диффе безобидно.
#
# ТРИ РАЗНЫХ УТВЕРЖДЕНИЯ, НИ ОДНО НЕ ВЫВОДИТСЯ ИЗ ДРУГОГО:
#   check-01 — СОСТАВ: множество записей `.claude/rules/` равно множеству имён,
#              объявленных строками таблицы манифеста; второй дом правил
#              (`.claude/rulebook/`), заведённый заново, — находка;
#   check-02 — АВТОЗАГРУЗКА ПУСТА, БАЗА НА МЕСТЕ: в замыкании `@import` от
#              `CLAUDE.md` нет ни правила, ни определения агента; исключение
#              покрывает каталог правил; главный поток — `dispatcher`; база и
#              протокол не больше объявленного потолка;
#   check-03 — ПОЛНОТА СТРОКИ: у каждого правила названы «включается действием»,
#              «чем соблюдение держится» и «закреплено за агентами» — все три
#              ячейки непусты.
#
# Почему третье не следует из первого: множества сходятся и при ПУСТЫХ ячейках —
# состав от содержимого ячейки не меняется ни на один файл. Почему второе не
# следует из первого: состав каталога сходится с манифестом и тогда, когда каждое
# правило вернули в `@import`, — объявление при этом не меняется ни на строку.
#
# ПЕРЕЧЕНЬ ПРОВЕРОК ЗДЕСЬ НЕ ВЫПИСАН, И ЭТО НЕСУЩЕЕ. Прогон находит их ГЛОБОМ (см.
# цикл ниже), а названы выше только те три, что судят объявление состава и
# автозагрузку. Привязку «правило ↔ агент ↔ скилл-ссылка» и маршрутизацию
# диспетчера судят соседние проверки набора: они подхватываются тем же глобом, и
# выписанный список отстал бы от них молча — ровно тот класс, ради которого набор
# и заведён.
#
# ТРИ ИСХОДА, А НЕ ДВА:
#   0 — рассмотрено N проверок, находок 0, у каждой был предмет;
#   1 — НАХОДКА: проверка упала, либо обход пуст (о дереве не прочитано ничего);
#   2 — БЕЗ ПРЕДМЕТА: находок нет, но часть проверок не с чем было сверять.
# Третий исход НЕ засчитывается за успех и печатается отдельной строкой: один и
# тот же ноль иначе означал бы и сошедшуюся раскладку, и каталог, который
# переехал, — а это разные вещи, и вторая опаснее.
#
# КОНТРАКТ НАБОРА ДЛЯ ЕГО ПРОВЕРОК. Проверка обязана (а) читать корень из
# `RULES_GATE_ROOT`, иначе её нельзя прогнать во временной копии и доказать
# инъекцией; (б) печатать перепись объёма — сколько файлов и строк рассмотрено;
# (в) отдавать 2 при отсутствии предмета, а не 0 и не 1.
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

ok=0; bad=0; void=0; count=0
# Глоб намеренно шире `check-*.sh`: проверка набора может быть и python-разбором,
# и прогонщик обязан находить её по РОЛИ в имени, а не по расширению.
for c in "$SCRIPT_DIR"/check-*; do
    # Глоб без совпадений подставляет САМ СЕБЯ: без этой строки `count`
    # становился бы единицей на пустом каталоге, и ветка «ни одной проверки не
    # найдено» стала бы недостижимой.
    [ -f "$c" ] || continue
    count=$((count + 1))
    case "$c" in
        *.py) python3 "$c" ;;
        *)    bash "$c" ;;
    esac
    case $? in
        0) ok=$((ok + 1)) ;;
        2) void=$((void + 1)) ;;
        *) bad=$((bad + 1)) ;;
    esac
done

if [ "$count" -gt 0 ]; then
    echo
    echo "rules-gate: рассмотрено проверок $count; пройдено $ok, провалено $bad, без предмета $void"
else
    echo "rules-gate: рассмотрено проверок 0 в $SCRIPT_DIR — предпосылка не резолвится, прогонять нечего" >&2
fi

# ── ВЕРДИКТ: ТРИ ИСХОДА, И У КАЖДОГО СВОЙ КОД ────────────────────────────────
#
# ПОРЯДОК ПРОВЕРКИ КОДОВ — НЕСУЩИЙ, А НЕ КОСМЕТИЧЕСКИЙ. Находка объявляется
# ПЕРВОЙ: набор, где есть и находка, и беспредметная проверка, обязан выйти
# единицей. Обратный порядок сделал бы «без предмета» маской — достаточно было бы
# одной беспредметной проверки, чтобы настоящая находка перестала блокировать.
#
# ПУСТОЙ ОБХОД ОСТАЁТСЯ НАХОДКОЙ (код 1), а не «без предмета»: ноль рассмотренных
# проверок означает, что каталог переехал и о дереве не прочитано НИЧЕГО, — это
# отказ самого набора, а не отсутствие условия у отдельной проверки.

[ "$count" -gt 0 ] || exit 1
[ "$bad" -eq 0 ] || exit 1
[ "$void" -eq 0 ] || exit 2
exit 0
