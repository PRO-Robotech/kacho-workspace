#!/usr/bin/env bash
# rules-gate #03 — МАНИФЕСТ ПОЛОН В ОБЕ СТОРОНЫ.
#
# ЧТО УТВЕРЖДАЕТ, двумя половинами, и обе несущие:
#
#   · у КАЖДОГО правила `.claude/rulebook/*.md` (кроме самого `MANIFEST.md`) есть
#     строка в манифесте, и эта строка называет ОБА своих предмета — действие,
#     которым правило включается, и то, чем соблюдение держится;
#   · КАЖДАЯ строка манифеста называет правило, которое в rulebook есть.
#
# ПОЧЕМУ ОБЕ. Без первой правило невидимо оркестратору: `rulebook` автоматически
# не читается (`.claude/rules/01-wave-contract.md` §Где лежит регламент), правило
# кладётся в задание полосы ПО СТРОКЕ МАНИФЕСТА — значит правило без строки не
# будет доставлено ни одной полосе ни разу, и заметить это нечем: дерево цело,
# файл на месте, прогон зелёный. Без второй манифест обещает несуществующее:
# оркестратор называет полосе координату, которой в дереве нет.
#
# ПОЧЕМУ ЯЧЕЙКИ, А НЕ ТОЛЬКО ИМЯ. Строка, называющая правило и молчащая о том,
# КОГДА оно включается, доставку не производит: оркестратору нечем сопоставить
# правило с действием полосы. Строка, молчащая о том, чем соблюдение держится, —
# та же форма без содержания, что корпус ловит в коде: правило, за которым не
# стоит ни гейта, ни названного вслух «держится вниманием», проверяется ничем.
# Поэтому прочерк в ячейке считается ПУСТОТОЙ, а не ответом: «держится вниманием»
# пишется словами (`rulebook/multi-agent-flow.md` §11 — «называй механизм; если
# механизма нет — так и напиши»).
#
# ЗАЧЕМ ЭТО ГЕЙТ, А НЕ ВНИМАТЕЛЬНОСТЬ. Раскладка «ядро + rulebook по требованию»
# выбрана замером (`scripts/compliance/`): преамбула волны из восьми полос — 368 600
# токенов против 1 988 800 при правилах у каждого исполнителя. Одна невнимательная
# правка манифеста возвращает четверть окна каждому агенту либо тихо выводит
# правило из обращения, и НИ ОДНО из двух состояний себя не выдаёт: оба выглядят
# как исправное дерево.
#
# ИСТОЧНИК ИСТИНЫ ОДИН. Перечень правил здесь НЕ выписан — он читается из индекса
# git, перечень строк — из самого манифеста. Выписанный список был бы вторым
# местом об одном предмете и разошёлся бы с деревом молча, ровно в ту сторону, в
# которую гейт перестаёт ловить (`rulebook/testing.md` §«Гейт на класс» п.7).
#
# ЧТО ЧИТАЕТСЯ ЗА СТРОКУ ТАБЛИЦЫ. Строка ЖИВОЙ таблицы: начинается с `|`, первая
# ячейка — имя файла на `.md` (в обратных кавычках или без; ведущий путь
# `rulebook/` либо `.claude/rulebook/` снимается). Шапка таблицы и разделитель под
# неё не подпадают — в них нет `.md`. Имя правила, названное В ПРОЗЕ (например,
# ядро в §«Ядро — читают все, всегда»), строкой таблицы НЕ является и предметом
# гейта не становится: иначе гейт запретил бы манифесту говорить о чём-либо, кроме
# rulebook, — в том числе о ядре, которое лежит в `.claude/rules/`.
#
# ЖИВОЙ — значит НЕ внутри блока кода и НЕ внутри HTML-комментария, а `\|` внутри
# ячейки — её содержимое, а не граница. Все три формы законны и все три ловились
# на противнике (2026-09-07); каждая давала МАСКУ, а не ложную находку:
#   · пример строки в ```-фенсе (манифест документирует свою же форму) зачитывался
#     за живую строку и покрывал снятую — правило не доставлялось НИ ОДНОЙ полосе,
#     гейт зелен. Это `rulebook/testing.md` §«Гейт на класс» п.4 в чистом виде:
#     проверка читала ТЕКСТ вместо исполняемой части;
#   · закомментированная строка объявлена автором снятой — и зачитывалась;
#   · `\|` — обязательная форма GFM для литеральной трубы, а держатели здесь суть
#     предикаты (`grep -E 'a|b'`), где труба обычна: разбиение по сырому `|`
#     съезжало колонками, и ПУСТОЙ держатель проходил незамеченным.
# Перепись это измеряет: на пробе с фенсом «строк таблицы разобрано» 14 → 13.
#
# ЯЧЕЙКА НОРМАЛИЗУЕТСЯ ДО СВЕРКИ С ЗАГЛУШКАМИ. Неразрывный пробел, пустой код-спан
# и прочерк в обратных кавычках человек читает как пустоту — распознаватель обязан
# читать так же; `TODO`/`FIXME` добавлены к заглушкам как обещание вместо предмета
# (ban #11). Каждая из четырёх форм проходила за названного держателя.
#
# СОРТИРОВКА — БАЙТОВАЯ (`LC_ALL=C`), И ЭТО НЕСУЩЕЕ. `sort` в ru_RU.UTF-8
# упорядочивает не так, как сравнивает байтовый `comm`; расхождение начинается на
# первом же имени с заглавной буквы (`README.md` рядом с `rag.md` — форма
# ординарная). Тогда слияние разъезжается и печатает по ЛИШНЕМУ обвинению в каждую
# сторону, оба на НЕВИНОВНОЕ правило, причём взаимно противоречивых: один и тот же
# файл объявляется и «есть в rulebook, строки нет», и «строка есть, файла нет».
# Измерено: одна настоящая находка превращалась в три. Пропуска этот дефект не
# давал, но инструмент, у которого две находки из трёх ложные, перестают читать.
#
# ПРЕДПОСЫЛКА И ЕЁ ГРАНИЦА. VOID (код 2) — только когда предмета нет ВОВСЕ:
# каталога `rulebook` в дереве не существует либо это не рабочая копия git.
# Снятый манифест и снятая таблица VOID-ом НЕ являются: послабление не выдаётся
# удалением предмета — иначе достаточно было бы стереть таблицу, чтобы гейт
# перестал блокировать отправку, а именно от этого он и заведён.
#
# Коды выхода: 0 — множества сошлись, каждая строка полна; 1 — находка либо пустой
# обход (о дереве не прочитано ничего); 2 — предмета нет.
#
# Своего `_lib.sh` проверка не заводит намеренно: соседние проверки набора пишутся
# параллельными полосами, и общий файл, заведённый двумя авторами разом, — то
# самое столкновение, которое ловится только на сборке волны
# (`rulebook/multi-agent-flow.md` §14). Помощники здесь локальные и короткие.

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
NAME="check-03-manifest-covers-rulebook"

gate_pass() { echo "[PASS] $NAME${1:+ — $1}"; }
gate_fail() { echo "[FAIL] $NAME${1:+ — $1}" >&2; }
gate_void() { echo "[VOID] $NAME${1:+ — $1}" >&2; }   # «проверять нечего» ≠ «находок 0»

# Корень воркспейса. `RULES_GATE_ROOT` переопределяет его — этим пользуется ТОЛЬКО
# inject.sh, чтобы прогонять гейт по временному дереву с внесённым дефектом и не
# трогать рабочее (`rulebook/testing.md` §«Гейт на класс» п.2).
if [ -n "${RULES_GATE_ROOT:-}" ]; then
    WS="$(cd "$RULES_GATE_ROOT" 2>/dev/null && pwd)" || {
        gate_void "RULES_GATE_ROOT=$RULES_GATE_ROOT не открывается — читать неоткуда"
        exit 2
    }
else
    WS="$(cd "$SCRIPT_DIR/../.." && pwd)"
fi

RB=".claude/rulebook"
MAN_REL="$RB/MANIFEST.md"
MAN="$WS/$MAN_REL"

if ! git -C "$WS" rev-parse --git-dir >/dev/null 2>&1; then
    gate_void "$WS — не рабочая копия git: состав правил читать неоткуда"
    exit 2
fi
if [ ! -d "$WS/$RB" ]; then
    gate_void "каталога $RB в $WS нет — раскладка «ядро + rulebook» не заведена, предмета у проверки нет"
    exit 2
fi

# Состав правил — из индекса git, а не с диска: посторонний файл рядом иначе
# влияет на вердикт. `--others --exclude-standard` добавляет ЕЩЁ НЕ закоммиченное,
# но и не игнорируемое правило: иначе новое правило не проверяется ровно в тот
# день, когда его пишут, — а гейт молчит, и это неотличимо от чистого дерева.
mapfile -t TRACKED < <(
    git -C "$WS" ls-files --cached --others --exclude-standard -- "$RB/*.md" 2>/dev/null | LC_ALL=C sort -u
)

# Правилом считается то, что git знает И что лежит на диске. Обе половины
# несущие: индекс отсекает посторонний файл рядом с репозиторием, диск —
# УДАЛЁННОЕ, но ещё числящееся в индексе. Без второй половины правило, снятое из
# рабочей копии, продолжало бы считаться покрытым: строка манифеста на месте,
# файла нет, оркестратор назовёт полосе координату, которой не существует.
RULES=()
RULE_PATHS=()
for p in "${TRACKED[@]:-}"; do
    [ -n "$p" ] || continue
    [ -f "$WS/$p" ] || continue
    rel="${p#"$RB"/}"
    [ "$rel" = "MANIFEST.md" ] && continue
    RULES+=("$rel")
    RULE_PATHS+=("$p")
done

rules_n="${#RULES[@]}"
rules_lines=0
if [ "$rules_n" -gt 0 ]; then
    rules_lines="$( (cd "$WS" && wc -l -- "${RULE_PATHS[@]}") | tail -1 | awk '{print $1}')"
fi

man_lines=0
[ -f "$MAN" ] && man_lines="$(wc -l < "$MAN" | tr -d ' ')"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# ── разбор таблицы манифеста ─────────────────────────────────────────────────
# Печатает по строке на разобранный ряд: «номер строки \t имя \t A|- \t H|-».
# Прочерк в ячейке читается как ПУСТОТА (см. шапку): сверка идёт по точному
# равенству со списком заглушек, а не по классу символов, — mawk байтовый, и
# длинное тире в скобочном выражении разъехалось бы по байтам.
if [ -f "$MAN" ]; then
    LC_ALL=C awk '
        # `\|` внутри ячейки — ЗАКОННАЯ и обязательная форма GFM: так пишется
        # литеральная труба, а держатели этого манифеста суть предикаты
        # (`grep -E "a|b"`), где труба встречается постоянно. Разбиение по сырому
        # `|` рвало такую ячейку, колонки съезжали, и ПУСТОЙ держатель проходил
        # незамеченным. Прячем экранированную трубу до разбиения и возвращаем после.
        BEGIN { ESC = "\001"; NBSP = "\302\240" }
        function trim(s) { gsub(/^[[:space:]]+|[[:space:]]+$/, "", s); return s }
        # Ячейка нормализуется ДО сверки: неразрывный и узкий пробелы человек
        # читает как пустоту, обратные кавычки — как оформление. Без этого
        # `&nbsp;` и пустой код-спан проходили за названного держателя.
        function norm(s) {
            gsub(ESC, "|", s)
            gsub(NBSP, " ", s)
            gsub(/`/, "", s)
            return trim(s)
        }
        function unnamed(s) {
            return (s == "" || s == "-" || s == "--" || s == "—" || s == "–" ||
                    s == "?" || s == "??" || s == "..." || s == "…" ||
                    s == "TBD" || s == "tbd" || s == "n/a" || s == "N/A" ||
                    s == "TODO" || s == "todo" || s == "FIXME" || s == "fixme")
        }
        # Блок кода — НЕ таблица. Манифест документирует форму строки примером, и
        # пример, зачтённый за живую строку, МАСКИРУЕТ снятую строку: правило не
        # доставляется ни одной полосе, а гейт зелен.
        /^[[:space:]]*(```|~~~)/ { fence = !fence; next }
        fence { next }
        # HTML-комментарий — тоже не таблица: закомментированная строка объявлена
        # снятой, и зачитывать её значит не краснеть на снятии строки.
        {
            line = $0
            if (incomment) {
                if (line ~ /-->/) { sub(/^.*-->/, "", line); incomment = 0 } else next
            }
            while (match(line, /<!--/)) {
                head = substr(line, 1, RSTART - 1)
                rest = substr(line, RSTART)
                if (match(rest, /-->/)) { line = head substr(rest, RSTART + 3) }
                else { line = head; incomment = 1; break }
            }
        }
        line ~ /^[[:space:]]*\|/ {
            gsub(/\\\|/, ESC, line)
            n = split(line, c, "|")
            if (n < 4) next
            name = norm(c[2]); act = norm(c[3]); hold = norm(c[4])
            sub(/^\.claude\/rulebook\//, "", name)
            sub(/^rulebook\//, "", name)
            if (name !~ /\.md$/) next
            # Строка про сам манифест предметом сверки не является: он лежит в
            # rulebook, но правилом не считается ни одной стороной, и его имя в
            # первой колонке дало бы находку с ЛОЖНЫМ текстом («правила нет в
            # rulebook») — то есть послало бы читателя искать не там.
            if (name == "MANIFEST.md") next
            printf "%d\t%s\t%s\t%s\n", NR, name, (unnamed(act) ? "-" : "A"), (unnamed(hold) ? "-" : "H")
        }
    ' "$MAN" > "$TMP/rows"
else
    : > "$TMP/rows"
fi

rows_n="$(wc -l < "$TMP/rows" | tr -d ' ')"

# ── ПЕРЕПИСЬ ОБЪЁМА ──────────────────────────────────────────────────────────
# Печатается ВСЕГДА и до вердикта: «ноль находок» обязано быть отличимо от «ноль
# прочитанного» (`rulebook/testing.md` §«Гейт на класс» п.3).
echo "[CENSUS] $NAME: правил в $RB/ — $rules_n, строк в них $rules_lines; $MAN_REL — строк $man_lines, строк таблицы разобрано $rows_n"

# ── ПУСТОЙ ОБХОД — НАХОДКА, А НЕ УСПЕХ ───────────────────────────────────────
if [ "$rules_n" -eq 0 ]; then
    gate_fail "обход беспредметен: в $RB не прочитано НИ ОДНОГО правила — сверять манифест не с чем"
    exit 1
fi
if [ ! -f "$MAN" ]; then
    gate_fail "$MAN_REL в дереве нет: ни одно из $rules_n правил не объявлено — оркестратор не доставит ни одного"
    exit 1
fi
if [ "$rows_n" -eq 0 ]; then
    gate_fail "в $MAN_REL не разобрано НИ ОДНОЙ строки таблицы при $rules_n правилах — таблица снята либо её форма сменилась; в обоих случаях правила невидимы"
    exit 1
fi

# ── СВЕРКА В ОБЕ СТОРОНЫ ─────────────────────────────────────────────────────
printf '%s\n' "${RULES[@]}" | LC_ALL=C sort -u > "$TMP/tree"
cut -f2 "$TMP/rows" | LC_ALL=C sort -u > "$TMP/named"

rc=0

only_tree="$(LC_ALL=C comm -23 "$TMP/tree" "$TMP/named")"
if [ -n "$only_tree" ]; then
    echo "  правило есть в rulebook, строки в манифесте нет (не будет доставлено ни одной полосе):" >&2
    while IFS= read -r r; do
        [ -n "$r" ] && echo "    $RB/$r" >&2
    done <<< "$only_tree"
    rc=1
fi

only_man="$(LC_ALL=C comm -13 "$TMP/tree" "$TMP/named")"
if [ -n "$only_man" ]; then
    echo "  манифест называет правило, которого в rulebook нет (обещание без предмета):" >&2
    while IFS= read -r r; do
        [ -n "$r" ] || continue
        ln="$(awk -F'\t' -v n="$r" '$2 == n { print $1; exit }' "$TMP/rows")"
        echo "    $MAN_REL:$ln — $r" >&2
    done <<< "$only_man"
    rc=1
fi

incomplete=0
while IFS=$'\t' read -r ln name a h; do
    [ -n "${name:-}" ] || continue
    miss=""
    [ "$a" = "-" ] && miss="не названо действие, которым правило включается"
    [ "$h" = "-" ] && miss="${miss:+$miss; }не названо, чем соблюдение держится"
    if [ -n "$miss" ]; then
        if [ "$incomplete" -eq 0 ]; then
            echo "  строка манифеста называет правило, но не называет своих предметов:" >&2
            incomplete=1
        fi
        echo "    $MAN_REL:$ln — $name: $miss" >&2
        rc=1
    fi
done < "$TMP/rows"

if [ "$rc" -ne 0 ]; then
    gate_fail "манифест и rulebook разошлись"
    exit 1
fi

gate_pass "манифест покрывает rulebook в обе стороны: правил $rules_n, строк $rows_n, у каждой названы действие и держатель"
exit 0
