#!/usr/bin/env bash
# check-01 — СОСТАВ КОРПУСА СХОДИТСЯ С МАНИФЕСТОМ В ОБЕ СТОРОНЫ.
#
# ЧТО УТВЕРЖДАЕТ. Множество записей каталога `.claude/rules/` побайтово совпадает
# с множеством имён, объявленных СТРОКАМИ ТАБЛИЦЫ `.claude/rules/MANIFEST.md`.
# Лишний файл и недостающий — ОБЕ находки, и обе печатаются координатой. Сюда же
# третья ось того же утверждения: `.claude/rulebook/`, заведённый заново, —
# находка, потому что дом правил ОДИН.
#
# ЧТО ИЗМЕНИЛОСЬ 2026-09-13, и почему это не переименование. Прежняя редакция
# звалась «ядро не растёт» и сверяла каталог с разделом манифеста §«Ядро»: три
# правила грузились автозагрузкой, четырнадцать лежали в своде и читались файлом
# по требованию. Решением владельца свод снят, весь корпус грузится каждому
# агенту, объявляет состав ТАБЛИЦА и покрывает она все девятнадцать
# (`@.claude/rules/01-wave-contract.md` §«Что стоит „весь корпус каждому“»).
# Раздела §«Ядро» в манифесте больше нет — сверять было НЕ С ЧЕМ, и проверка
# краснела на пустом объявлении, то есть не о том.
#
# ПОЧЕМУ В ОБЕ СТОРОНЫ. Совпадение ЧИСЛА не доказывает ничего: множества равной
# мощности бывают разными, и ровно так каталог расходится с объявлением молча.
# Лишний файл возвращает свою цену в окно КАЖДОГО агента волны — теперь буквально,
# потому что грузится всё; недостающий означает, что правило пропало, а окно при
# этом выглядит здоровым.
#
# ПОЧЕМУ ЭТО ГЕЙТ, А НЕ АБЗАЦ. Дом правил один, и загрузчик читает его целиком.
# Файл, попавший туда без объявления, не проявляется НИЧЕМ: прогон зелёный,
# поведение прежнее, дороже стало только всё. Файл, унесённый оттуда, тоже не
# проявляется ничем: агент просто не видит правила и нарушает его не по
# небрежности. Заметить оба состояния без исполняемого вопроса к дереву нечем
# (`.claude/rules/testing.md` §«Гейт на класс»).
#
# ИСТОЧНИК ИСТИНЫ ОДИН — МАНИФЕСТ. Перечень правил здесь НЕ выписан: выписанный
# список есть второе место об одном предмете, и расходится он в ту сторону, где
# гейт перестаёт ловить, — правило завели, список остался прежним, находок ноль
# (скил `doc-truthfulness` §«Два места об одном предмете»).
#
# РАЗБОР ТАБЛИЦЫ — ОБЩИЙ С check-03, файлом `manifest-rows.awk`. Грамматика у
# таблицы одна; две её копии разошлись бы молча. Довод и перечень форм, на которых
# грамматика ловилась противником, — в шапке самого разборщика.
#
# ЧЕГО ЭТА ПРОВЕРКА НЕ ДЕРЖИТ, названо прямо:
#   · она не запрещает ЗАВЕСТИ двадцатое правило: кто допишет строку таблицы и
#     положит файл — получит зелёное. Держится ею другое — невозможность
#     разойтись МОЛЧА: рост корпуса становится правкой манифеста, видимой в
#     диффе, то есть решением человека, а не побочным эффектом чужой правки;
#   · она не судит ОБЪЁМ корпуса в токенах. Проверено опытом: правило на 60 022
#     символа со строкой в манифесте даёт зелёное. Величину держит внимание, и
#     `.claude/rules/01-wave-contract.md` говорит это прямо;
#   · она не судит ПОЛНОТУ строки — множества сходятся и при пустых ячейках. Это
#     предмет check-03, и он отдельный не для симметрии: пустая ячейка не меняет
#     состава ни на один файл.
#
# ПОДКАТАЛОГ БОЛЬШЕ НЕ ЯВЛЯЕТСЯ ОСЬЮ САМ ПО СЕБЕ, и это снятие противоречия,
# а не послабление. Прежняя редакция звала всякую вложенность находкой («ядро
# плоское»), при том что соседняя check-02 населяет правила РЕКУРСИВНО и считает
# объявленное правило в подкаталоге законным. Замер на ревизии HEAD до этой
# правки, одно дерево, два вердикта: `.claude/rules/domain/vpc.md` плюс строка
# `@.claude/rules/domain/vpc.md` в CLAUDE.md → check-02 код 0, check-01 код 1.
# Хуже того, объявить такое правило в §«Ядро» было НЕВОЗМОЖНО by construction:
# отбор имён требовал `^[^/]+\.md$`. Теперь населения совпадают: вложенное
# правило сверяется своим относительным путём, и законно оно ровно тогда, когда
# у него есть и строка, и объявление.
#
# ПРЕДПОСЫЛКА ПРОВЕРКИ (исход VOID, код 2) — ровно одна: в дереве нет каталога
# `.claude/rules/`. Тогда корпуса в этом дереве не существует вовсе, сверять
# нечего, и это НЕ «находок 0».
#
# СНЯТЫЙ МАНИФЕСТ И ВЫПОТРОШЕННАЯ ТАБЛИЦА — НАХОДКИ, А НЕ VOID. Это антимаска:
# послабление не выдаётся удалением предмета, иначе достаточно было бы стереть
# таблицу, чтобы гейт перестал блокировать отправку, а именно от этого он заведён.
# Правка против прежней редакции: та отдавала на снятый манифест код 2 при живом
# каталоге правил — то есть отсутствие объявления при наличии объявляемого
# называла «предмета нет».
#
# ЕДИНИЦА СЧЁТА — ЛЮБАЯ ЗАПИСЬ КАТАЛОГА НА ДИСКЕ, а не только `*.md` и не запись
# индекса git.
#
#   ПОЧЕМУ НЕ ТОЛЬКО `.md`, хотя грузятся только они. Предмет проверки — ДОМ
#   правил, а таблица объявляет его состав целиком. Черновик, положенный сюда «на
#   минуту», от чтения не защищён ничем, кроме расширения, и переживает эту минуту
#   на годы. Расхождение с check-02 здесь мнимое: та судит, ЧТО ГРУЗИТСЯ, и
#   молчит на `.txt` верно; эта судит, ЧТО ОБЪЯВЛЕНО, и краснеет верно. Обе
#   починки — снять файл либо завести ему строку — одни и те же.
#
# Корпус читает загрузчик, и читает он диск. Поэтому файл, скрытый от git через `.gitignore`,
# из-под наблюдения НЕ уходит — он остаётся находкой и называется отдельной осью:
# в свежем клоне его нет, то есть корпус различается между машинами.
#
# ЗАПИСЬЮ СЧИТАЕТСЯ И СИМВОЛЬНАЯ ССЫЛКА, и это правка по находке противника
# (2026-09-07). Прежняя редакция собирала набор через `find -type f`, а `-type f`
# ссылок не видит ВОВСЕ — ни как файл, ни как подкаталог. Замер на временной
# копии: живая ссылка `.claude/rules/testing.md -> ../rulebook/testing.md`,
# 1326 читаемых через неё строк, вердикт гейта — «прочитано файлов ядра 3 …
# лишних 0, недостающих 0», код 0. То есть шапка объявляла единицей счёта диск, а
# разбор считал подмножество диска, и расхождение шло в МОЛЧАЛИВУЮ сторону
# (`.claude/rules/testing.md` §«Гейт на класс», п.7: форма, которой распознаватель
# не знает, не даёт ни красного, ни зелёного — она даёт невидимость). Git такую
# запись хранит (режим 120000), значит она переживает клон и молчала бы на каждой
# машине.
#
# Коды выхода: 0 — осмотрено N, находок 0; 1 — находка либо пустой обход;
# 2 — предмета нет (каталога правил в этом дереве не существует).

set -uo pipefail

NAME="check-01-corpus-matches-manifest"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PARSER="$SCRIPT_DIR/manifest-rows.awk"

# Корень воркспейса. `RULES_GATE_ROOT` переопределяет его — этим пользуется
# ТОЛЬКО inject.sh, чтобы прогнать гейт по временному дереву с внесённым дефектом
# и не тронуть рабочее (скил `gate-authoring` §Инъекция). Разборщик при этом
# берётся из СВОЕГО каталога, а не из песочницы: предмет инъекции — дерево
# правил, а не текст проверки.
if [ -n "${RULES_GATE_ROOT:-}" ]; then
    WS="$(cd "$RULES_GATE_ROOT" 2>/dev/null && pwd)" || WS=""
else
    WS="$(cd "$SCRIPT_DIR/../.." 2>/dev/null && pwd)" || WS=""
fi

gate_pass()   { echo "[PASS] $NAME${1:+ — $1}"; }
gate_fail()   { echo "[FAIL] $NAME${1:+ — $1}" >&2; }
gate_void()   { echo "[VOID] $NAME${1:+ — $1}" >&2; }   # «сверять не с чем» ≠ «находок 0»
gate_census() { echo "[CENSUS] $NAME: $1"; }

RULES_DIR="$WS/.claude/rules"
MANIFEST="$RULES_DIR/MANIFEST.md"
SECOND_HOME_REL=".claude/rulebook"

# ── предпосылка 0: разборщик таблицы на месте ────────────────────────────────
# Его отсутствие — «не выполнилось», а не «находок 0»: без него таблица не
# читается вовсе, и любой вердикт о составе был бы вердиктом о пустом множестве.
if [ ! -f "$PARSER" ]; then
    gate_census "разбор не запускался: $PARSER не существует; файлов прочитано 0, строк таблицы 0"
    gate_void "разборщика таблицы manifest-rows.awk нет рядом с проверкой — читать объявление нечем; это НЕ «находок 0»"
    exit 2
fi

# ── предпосылка 1: каталог правил ────────────────────────────────────────────
if [ -z "$WS" ] || [ ! -d "$RULES_DIR" ]; then
    gate_census "каталог правил .claude/rules НЕ существует; файлов прочитано 0, строк 0, строк таблицы 0"
    gate_void "каталога .claude/rules нет в '${WS:-<корень не резолвится>}' — корпуса правил в этом дереве не существует, сверять не с чем"
    exit 2
fi

# ── что лежит в корпусе ФАКТИЧЕСКИ ───────────────────────────────────────────
# Набор — то, что загрузчик может открыть ПО ИМЕНИ: обычные файлы И ссылки,
# РЕКУРСИВНО, относительным путём. `-type f` в одиночку оставлял ссылку вне
# наблюдения молча (см. шапку), поэтому ссылка входит в набор наравне с файлом и
# вдобавок называется своей осью ниже.
mapfile -t ACTUAL < <(cd "$RULES_DIR" && find . -mindepth 1 \( -type f -o -type l \) -printf '%P\n' 2>/dev/null | LC_ALL=C sort)
mapfile -t ACTUAL_LINKS < <(cd "$RULES_DIR" && find . -mindepth 1 -type l -printf '%P\n' 2>/dev/null | LC_ALL=C sort)

lines=0
for f in ${ACTUAL+"${ACTUAL[@]}"}; do
    # Нечитаемую запись (битая ссылка) пропускаем ЯВНО: `2>/dev/null` у `wc` её
    # не покрывает — перенаправление `<` отказывает в САМОМ шелле, до запуска
    # команды, и его жалоба уехала бы в вердикт сырой строкой поверх находки.
    # Диагностика — часть свойства: находка, обросшая чужим шумом, посылает
    # читателя искать не там (`.claude/rules/testing.md` §«Гейт на класс», п.8).
    [ -r "$RULES_DIR/$f" ] || continue
    n="$(wc -l < "$RULES_DIR/$f" 2>/dev/null)" || n=0
    lines=$((lines + n))
done

# ── что корпусом ОБЪЯВЛЕНО ───────────────────────────────────────────────────
man_lines=0
declared_rows=0
DECLARED=()
if [ -f "$MANIFEST" ]; then
    man_lines="$(wc -l < "$MANIFEST" | tr -d ' ')"
    mapfile -t DECLARED < <(LC_ALL=C awk -f "$PARSER" "$MANIFEST" | cut -f2 | LC_ALL=C sort -u)
    declared_rows="$(LC_ALL=C awk -f "$PARSER" "$MANIFEST" | wc -l | tr -d ' ')"
fi

# ── ПЕРЕПИСЬ ОБЪЁМА — печатается ВСЕГДА и до вердикта ────────────────────────
gate_census "прочитано записей .claude/rules ${#ACTUAL[@]} (строк $lines), из них ссылок ${#ACTUAL_LINKS[@]}; MANIFEST.md — строк $man_lines, строк таблицы разобрано $declared_rows, уникальных имён ${#DECLARED[@]}"

# ── снятый манифест и выпотрошенная таблица — НАХОДКИ, а не VOID ─────────────
if [ ! -f "$MANIFEST" ]; then
    gate_fail ".claude/rules/MANIFEST.md в дереве нет при ${#ACTUAL[@]} записях в каталоге правил — единственное объявление состава снято, а объявляемое стоит; это находка, а не отсутствие предмета"
    exit 1
fi
if [ "${#DECLARED[@]}" -eq 0 ]; then
    gate_fail "в таблице MANIFEST.md не разобрано НИ ОДНОГО имени правила при ${#ACTUAL[@]} записях в каталоге — таблица снята либо её форма сменилась; сверять каталог не с чем, и это находка: манифест на месте, испорчено само объявление"
    exit 1
fi

# ── обход беспредметен: каталог пуст ─────────────────────────────────────────
if [ "${#ACTUAL[@]}" -eq 0 ]; then
    gate_fail "обход беспредметен: в .claude/rules/ прочитано 0 записей при ${#DECLARED[@]} объявленных — корпус пропал целиком, о его составе не прочитано ничего"
    exit 1
fi

# ── сверка в обе стороны ─────────────────────────────────────────────────────
findings=0

for f in "${ACTUAL[@]}"; do
    found=0
    for d in "${DECLARED[@]}"; do [ "$f" = "$d" ] && { found=1; break; }; done
    if [ "$found" -eq 0 ]; then
        gate_fail "ЛИШНИЙ В КОРПУСЕ: .claude/rules/$f — строки в таблице MANIFEST.md нет; он грузится КАЖДОМУ агенту волны, и решения об этом никто не принимал"
        findings=$((findings + 1))
    fi
done

for d in "${DECLARED[@]}"; do
    found=0
    for f in "${ACTUAL[@]}"; do [ "$f" = "$d" ] && { found=1; break; }; done
    if [ "$found" -eq 0 ]; then
        ln="$(LC_ALL=C awk -f "$PARSER" "$MANIFEST" | awk -F'\t' -v n="$d" '$2 == n { print $1; exit }')"
        gate_fail "НЕДОСТАЁТ В КОРПУСЕ: MANIFEST.md:${ln:-?} называет $d — файла в .claude/rules/ нет; манифест обещает правило, которого не существует"
        findings=$((findings + 1))
    fi
done

# ── ВТОРОЙ ДОМ ПРАВИЛ ────────────────────────────────────────────────────────
#
# Ось своя, а не частный случай «лишнего»: предмет лежит ВНЕ каталога правил, и
# сверка множеств его не видит by construction. Правило, положенное в снятый
# каталог, не грузится НИ ОДНОЙ сессией — ни автозагрузкой, ни по требованию, —
# и по поведению агента это неотличимо от правила, которого он не соблюдает.
#
# СПРАШИВАЕТСЯ ДИСК, А НЕ ИНДЕКС, и здесь это несущее. Второй дом заводит агент
# посреди работы, и в индексе его нет: `git ls-files .claude/rulebook` ответил бы
# пусто на дереве, где каталог уже лежит и уже собирает правила. Единица счёта
# названа в шапке — запись на диске, потому что загрузчик читает диск.
#
# ЧИСЛО ЗАПИСЕЙ ВНУТРИ НЕ ПЕЧАТАЕТСЯ: перечисление содержимого ничего не решает —
# находка объявлена уже самим существованием пути, — а стоило бы обхода диска,
# который на другой машине даёт другое. Тип записи (каталог или файл) берётся
# `test`, то есть одним stat, и он в находке нужен: от него зависит, что читателю
# сносить.
if [ -e "$WS/$SECOND_HOME_REL" ]; then
    if [ -d "$WS/$SECOND_HOME_REL" ]; then kind="каталог"; else kind="файл"; fi
    gate_fail "ВТОРОЙ ДОМ ПРАВИЛ: $SECOND_HOME_REL существует ($kind) — снят решением владельца 2026-09-13, дом правил ОДИН; положенное туда не грузится ни одной сессией, а по поведению агента это неотличимо от несоблюдения"
    findings=$((findings + 1))
fi

# ── СИМВОЛЬНАЯ ССЫЛКА В КОРПУСЕ ──────────────────────────────────────────────
#
# Находка НЕЗАВИСИМО от того, объявлено ли имя: что именно прочитает загрузчик,
# решает ЦЕЛЬ, а она вправе лежать вне объявленного набора, вне репозитория и не
# резолвиться вовсе. Тот же класс, что у скрытого от git, и потому та же форма:
# отдельная ось, а не молчание внутри «лишнего».
for f in ${ACTUAL_LINKS+"${ACTUAL_LINKS[@]}"}; do
    tgt="$(readlink "$RULES_DIR/$f" 2>/dev/null)"
    if [ -e "$RULES_DIR/$f" ]; then
        why="содержимое правила лежит по цели, вне объявленного набора"
    else
        why="цель НЕ резолвится — правило не читается вовсе"
    fi
    gate_fail "ССЫЛКА В КОРПУСЕ: .claude/rules/$f -> ${tgt:-<цель не читается>} — не обычный файл; $why, а корпус обязан быть одинаковым на всех машинах"
    findings=$((findings + 1))
done

# ── ФАЙЛ КОРПУСА, СКРЫТЫЙ ОТ GIT ─────────────────────────────────────────────
# Находка независимо от того, объявлен он или нет: в свежем клоне его нет, то
# есть корпус различается между машинами, а гейт на чужой машине судил бы другой
# каталог.
if git -C "$WS" rev-parse --git-dir >/dev/null 2>&1; then
    for f in "${ACTUAL[@]}"; do
        if git -C "$WS" check-ignore -q ".claude/rules/$f" 2>/dev/null; then
            gate_fail "СКРЫТ ОТ GIT: .claude/rules/$f лежит в корпусе, но исключён .gitignore — в свежем клоне его нет, корпус различается между машинами"
            findings=$((findings + 1))
        fi
    done
fi

if [ "$findings" -gt 0 ]; then
    gate_fail "находок $findings; прочитано записей ${#ACTUAL[@]}, объявлено ${#DECLARED[@]}"
    exit 1
fi

gate_pass "состав корпуса сверен с таблицей MANIFEST.md в обе стороны: записей ${#ACTUAL[@]} ($lines строк), объявлено ${#DECLARED[@]}, лишних 0, недостающих 0, второго дома нет"
exit 0
