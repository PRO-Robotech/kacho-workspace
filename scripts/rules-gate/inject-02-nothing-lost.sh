# ГРАНИЦА ЗАПАСА — ПОВЕДЕНЧЕСКАЯ ПАРА, и она нужна отдельно от трёх выше: те
# судят ОБЪЯВЛЕНИЕ, а эта — то, что объявленное число и есть барьер. Дописывается
# РОВНО столько байт, сколько медианный абзац (молчит: тело становится равно
# потолку), и на один больше (краснеет с перебором 1 Б). Прежний прибор на той же паре давал
# молчание на +131 Б и красное на +132 Б — то есть барьер стоял там, где его
# никто не мерил.
inj02_append_bytes() {   # <файл> <сколько байт дописать>
    python3 - "$1" "$2" <<'PY'
import io, sys
path, n = sys.argv[1], int(sys.argv[2])
# n-1 знаков + перевод строки = ровно n байт, В ПОСЛЕДНИЙ абзац (см. inj02_append_to_last_par)
assert n >= 2
data = io.open(path, "rb").read()
if not data.endswith(b"\n") or data.endswith(b"\n\n"):
    raise SystemExit("ФИКСТУРА БЕСПРЕДМЕТНА: %s не кончается ровно одним переводом строки" % path)
txt = ("x" * (n - 1)) + "\n"
assert len(txt.encode()) == n, len(txt.encode())
io.open(path, "a", encoding="utf-8").write(txt)
PY
}

inj02_median() {   # <каталог> <относительный путь> → медианный абзац тела, в байтах
    sandbox_ceiling "$1" "$2" MEDIAN | sed 's/.*+//; s:/.*::'
}

