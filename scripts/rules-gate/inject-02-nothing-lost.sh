#!/usr/bin/env bash
# ЧАСТЬ инъекции набора: доказательство check-02 «ничего не потеряно и не забыто»
# по осям, ЗАВЕДЁННЫМ ПОСЛЕ первой редакции. Четыре первые оси (A…F) доказаны в
# общем `inject.sh`; здесь — то, что она пропускала МОЛЧА либо называла неверно.
#
# Файл ПОДКЛЮЧАЕТСЯ (`.`) из `inject.sh` и пользуется его оснасткой — `sandbox`,
# `capture`, `assert_code`, `assert_says`, счётчиками `pass`/`fail`.
#
# Каждая проба меняет РОВНО ОДИН факт и ставит рядом ЗАКОННОГО БЛИЗНЕЦА той же
# формы, на котором гейт обязан смолчать. Проверяется НЕ ТОЛЬКО КОД, НО И ТЕКСТ:
# находка, называющая не ту ось, посылает читателя чинить не то — а по трём из
# пяти здешних осей прежняя редакция краснела именно так.

# ── СТРАЖ ПОДКЛЮЧЕНИЯ: часть НЕ исполняется самостоятельно ───────────────────
#
# Своей оснастки (`sandbox`, `capture`, `assert_*`, счётчики) у части нет. В
# обход `inject.sh` она не просто ничего не доказывает — она ПОРТИТ дерево, из
# которого запущена: каталог песочницы не определён, поэтому путь вида
# `"$d/CLAUDE.md"` становится ОТНОСИТЕЛЬНЫМ и правка уезжает в рабочую копию, а
# `git -C "$d" add -A` стажирует в её индекс чужие незакоммиченные правки.
# Испорченный индекс делает лживыми ИМЕННО те проверки, что читают дерево:
# «ноль находок» превращается в «ноль прочитанного» и выглядит настоящей
# находкой (`rulebook/multi-agent-flow.md` §13 «Неприкосновенность чужого
# состояния»).
#
# ИЗМЕРЕНО ДО СТРАЖА, на изолированной копии с чистым деревом: прямой запуск
# inject-02 → rc=127 и ` M CLAUDE.md`; прямой запуск inject-03 → rc=0 при НУЛЕ
# исполненных утверждений и превращал чужое ` M` в `M ` (стажировал). То есть
# «не выполнилось» отчитывалось успехом, и в том же прогоне портилось дерево.
#
# Отказ — код 2, а не 1: ноль исполненных утверждений не является находкой в
# дереве и не является успехом (`rulebook/testing.md` §«Чтение вердикта»).
#
# Бит исполнения намеренно ОСТАВЛЕН: без него `./inject-NN-….sh` отвечал бы
# «Permission denied» — диагностика хуже, чем у этого отказа, который называет
# и причину, и команду, которую звать вместо.
if [ "${BASH_SOURCE[0]}" = "$0" ]; then
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — ЧАСТЬ инъекции, а не самостоятельная проба." >&2
    echo "       Она подключается (\`.\`) из scripts/rules-gate/inject.sh и пользуется его" >&2
    echo "       оснасткой; самостоятельно не исполнила бы ни одного утверждения и писала бы" >&2
    echo "       в рабочее дерево. Запускать: bash scripts/rules-gate/inject.sh" >&2
    exit 2
fi
for _inj_fn in sandbox capture assert_code assert_says assert_fixture_changed; do
    command -v "$_inj_fn" >/dev/null 2>&1 && continue
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — оснастки inject.sh нет: функция" \
         "«$_inj_fn» не определена; часть подключена не оттуда, доказывать нечем" >&2
    exit 2
done
unset -v _inj_fn
if [ -z "${WS:-}" ] || [ ! -d "$WS" ]; then
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — корень дерева \$WS не определён либо не" \
         "каталог; жертву фикстуры выводить не из чего" >&2
    exit 2
fi

C2N=check-02-nothing-lost.sh

# ── ось G: координата, ПЕРЕНЕСЁННАЯ на свою строку, — не объявление ──────────
#
# Самая дорогая из здешних: она молчала. Проза корпуса переносится по ~90 знаков,
# поэтому координата регулярно оказывается на строке одна, а предложение
# кончается точкой после неё. Прежняя редакция считала такую строку объявлением
# («строка целиком» + срезка хвоста) и выходила НУЛЁМ, напечатав «импортов в
# середине предложения 0» — то есть отчитывалась о ненайденном ровно тем числом,
# ради которого ось заведена. Проходили все семь хвостов `. , ; : ) » ).`.
echo "== ось G: координата, перенесённая на свою строку, объявлением НЕ является =="

inj02_wrap() {   # <каталог> <хвост> ; вставляет абзац прозы с координатой на своей строке
    python3 - "$1" "$2" <<'PY'
import io, os, re, sys
d, tail = sys.argv[1], sys.argv[2]
p = os.path.join(d, "CLAUDE.md")
lines = io.open(p, encoding="utf-8").readlines()
# жертва — ЛЮБОЕ объявленное правило из дерева, а не выписанное имя
rule = next(re.match(r"^@(\.claude/rules/\S+?)\s*$", l).group(1)
            for l in lines if re.match(r"^@\.claude/rules/\S+\s*$", l))
lines.insert(0, "Как писать отчёт и задачу — изложение целиком вынесено в\n")
lines.insert(1, f"@{rule}{tail}\n")
lines.insert(2, "Договор волны при этом читается отдельно.\n")
io.open(p, "w", encoding="utf-8").writelines(lines)
PY
}

for tail in '.' ',' ';' ':' ')' '»'; do
    d="$(sandbox g_"$(printf '%d' "'$tail")")"
    inj02_wrap "$d" "$tail"
    capture "$d" "$C2N"
    assert_code 1 "ДЕФЕКТ: координата на своей строке с хвостом «$tail»"
done
assert_says "ИМПОРТ В СЕРЕДИНЕ ПРЕДЛОЖЕНИЯ" "  ...и названа ТА ось, а не «импорт в никуда»"

d="$(sandbox g_twin)"
python3 - "$d" <<'PY'
import io, os, re, sys
d = sys.argv[1]
p = os.path.join(d, "CLAUDE.md")
lines = io.open(p, encoding="utf-8").readlines()
rule = next(re.match(r"^@(\.claude/rules/\S+?)\s*$", l).group(1)
            for l in lines if re.match(r"^@\.claude/rules/\S+\s*$", l))
lines.insert(0, "Как писать отчёт и задачу — изложение целиком вынесено в\n")
lines.insert(1, f"`@{rule}`.\n")
io.open(p, "w", encoding="utf-8").writelines(lines)
PY
capture "$d" "$C2N"
assert_code 0 "БЛИЗНЕЦ: тот же абзац, координата в обратных кавычках — молчит"

# ── ось H: замыкание ВЫЧИСЛЯЕТСЯ, а не выписывается ─────────────────────────
#
# Прежняя редакция читала фиксированный набор «CLAUDE.md + .claude/rules/*.md» и
# звала его замыканием. Импорт rulebook за ОДИН лишний хоп уезжал молча, и
# перепись этого не показывала: `@docs/…` не попадал даже в счёт ссылок.
echo
echo "== ось H: rulebook за лишний хоп — замыкание обязано за ним пойти =="

d="$(sandbox h_hop)"
mkdir -p "$d/docs"
printf '@.claude/rulebook/%s\n' "$book_rule" > "$d/docs/extra.md"
printf '@docs/extra.md\n' >> "$d/CLAUDE.md"
capture "$d" "$C2N"
assert_code 1 "ДЕФЕКТ: rulebook импортирован через промежуточный файл"
assert_says "ИМПОРТ RULEBOOK: docs/extra.md" "  ...и координата — ФАЙЛ, где ссылка живёт"
assert_says "рёбер замыкания за пределы ядра 1" "  ...и перепись назвала ребро наружу"

d="$(sandbox h_twin)"
mkdir -p "$d/docs"
printf '# заметка без импортов\n' > "$d/docs/extra.md"
printf '@docs/extra.md\n' >> "$d/CLAUDE.md"
capture "$d" "$C2N"
assert_code 0 "БЛИЗНЕЦ: тот же лишний хоп, но rulebook внутри нет — молчит"

d="$(sandbox h_mail)"
printf '\nПишите на admin@in-cloud.io либо позовите @claude.\n' >> "$d/CLAUDE.md"
capture "$d" "$C2N"
assert_code 0 "БЛИЗНЕЦ: почта и @имя в прозе маршрутом не становятся"

# ── ось I: правило, ГРУЗЯЩЕЕСЯ в обход перечня ──────────────────────────────
#
# Прежняя редакция говорила о таком файле «он не грузится ни одной сессией» —
# то есть противоречила собственной посылке о рекурсивности импортов и посылала
# читателя дописывать объявление вместо того, чтобы снять теневой импорт.
echo
echo "== ось I: теневой импорт правила — грузится, не будучи объявленным =="

d="$(sandbox i_shadow)"
printf '# правило\n' > "$d/.claude/rules/inj02-shadow.md"
printf '\n@.claude/rules/inj02-shadow.md\n' >> "$d/.claude/rules/00-kacho-core.md"
capture "$d" "$C2N"
assert_code 1 "ДЕФЕКТ: правило импортировано ядровым файлом, а не CLAUDE.md"
assert_says "ТЕНЕВОЙ ИМПОРТ ПРАВИЛА" "  ...названо: перечень перестал быть перечнем"
assert_says "ГРУЗИТСЯ теневым импортом" "  ...и следствие названо ВЕРНО, а не «не грузится»"

d="$(sandbox i_cyr)"
printf '# правило\n' > "$d/.claude/rules/инъекция.md"
printf '\n@.claude/rules/инъекция.md\n' >> "$d/.claude/rules/00-kacho-core.md"
capture "$d" "$C2N"
assert_code 1 "ДЕФЕКТ: то же с именем кириллицей — корпус русский"
assert_says "«@.claude/rules/инъекция.md»" "  ...и координата НЕ усечена на первом не-ASCII"

# ── ось J: население правил берётся РЕКУРСИВНО ──────────────────────────────
#
# Прежняя редакция обходила каталог плоско и на законно объявленном правиле в
# подкаталоге утверждала «файла в дереве нет» — при файле, который лежит на
# диске и виден одной командой `ls`.
echo
echo "== ось J: правило в подкаталоге — правило, а не «файла нет» =="

d="$(sandbox j_sub)"
mkdir -p "$d/.claude/rules/domain"
printf '# доменное правило\n' > "$d/.claude/rules/domain/inj02.md"
capture "$d" "$C2N"
assert_code 1 "ДЕФЕКТ: правило в подкаталоге без объявления"
assert_says "НЕ ИМПОРТИРОВАН: .claude/rules/domain/inj02.md" "  ...названо своим путём"

d="$(sandbox j_twin)"
mkdir -p "$d/.claude/rules/domain"
printf '# доменное правило\n' > "$d/.claude/rules/domain/inj02.md"
printf '@.claude/rules/domain/inj02.md\n' >> "$d/CLAUDE.md"
capture "$d" "$C2N"
assert_code 0 "БЛИЗНЕЦ: то же правило, объявленное законно — молчит"

d="$(sandbox j_case)"
printf '# правило\n' > "$d/.claude/rules/INJ02.MD"
capture "$d" "$C2N"
assert_code 1 "ДЕФЕКТ: правило с расширением .MD — тоже правило"

# ── ось K: перепись называет ОСМОТРЕННОЕ, а не только прочитанное ───────────
#
# Незакрытая ограда уводит хвост файла из-под разбора целиком. Прежняя редакция
# печатала одну величину («строк прочитано») и молчала: «находок 0» становилось
# неотличимо от «не смотрели» на один уровень ниже, чем гейт это декларировал.
echo
echo "== ось K: незакрытая ограда — хвост файла ушёл из-под разбора =="

d="$(sandbox k_fence)"
printf '\n```\nпример\n\n@.claude/rulebook/%s\n' "$book_rule" >> "$d/CLAUDE.md"
capture "$d" "$C2N"
assert_code 1 "ДЕФЕКТ: ограда не закрыта, за ней голый импорт rulebook"
assert_says "ОГРАДА НЕ ЗАКРЫТА" "  ...и сказано, что по хвосту вердикта нет"

d="$(sandbox k_twin)"
printf '\n```\n@.claude/rulebook/%s\n```\n' "$book_rule" >> "$d/CLAUDE.md"
capture "$d" "$C2N"
assert_code 0 "БЛИЗНЕЦ: та же ограда, но ЗАКРЫТАЯ — пример, а не импорт"

d="$(sandbox k_census)"
capture "$d" "$C2N"
assert_says "пропущено как код" "перепись называет пропущенное как код отдельным числом"
assert_says "строк-объявлений" "перепись отличает СТРОКИ-объявления от уникальных целей"

# ── ось L: ОДНА цель — НЕСКОЛЬКО законных написаний ─────────────────────────
#
# Загрузчик резолвит `@./x`, `@a//b`, `@a/./b` и `@a/c/../b` в ОДИН файл.
# Распознаватель, знающий одну форму, на остальных МОЛЧИТ — ни красного, ни
# зелёного, предмет просто уходит из-под наблюдения (§«Гейт на класс», п.7).
#
# Измерено на дофиксовом гейте, одной командой на форму: голая
# `@.claude/rulebook/<правило>` давала код 1, три её переписи — 0. Две из трёх
# были ХУЖЕ молчания: гейт засчитывал их ОБЪЯВЛЕНИЕМ и спускался по ним в свод —
# его собственная перепись называла файл свода прочитанным, а вердикт в той же
# строке говорил «импортов rulebook 0». Поэтому здесь утверждается ТРОЙКА:
# код · названная ось · то, что замыкание НЕ выросло.
echo
echo "== ось L: та же цель, написанная иначе, — тот же импорт свода =="

# Население замыкания на НЕТРОНУТОЙ копии берётся ПРОГОНОМ, а не выписывается:
# оно меняется вместе с деревом, и выписанное число состарилось бы молча.
d="$(sandbox l_base)"
capture "$d" "$C2N"
inj02_closure="$(printf '%s\n' "$OUT" | sed -n 's/.*осмотрено файлов \([0-9][0-9]*\).*/\1/p' | head -1)"

for form in "./.claude/rulebook" ".claude//rulebook" ".claude/./rulebook" ".claude/rules/../rulebook"; do
    d="$(sandbox "l_$(printf '%s' "$form" | tr -c 'a-z' '_')")"
    printf '\n@%s/%s\n' "$form" "$book_rule" >> "$d/CLAUDE.md"
    capture "$d" "$C2N"
    assert_code 1 "ДЕФЕКТ: импорт свода, написанный как «@$form/…»"
    assert_says "ИМПОРТ RULEBOOK" "  ...и названа ТА ось, а не «импорт в никуда»"
    assert_says "@$form/$book_rule" "  ...и координата названа ТАК, КАК НАПИСАНА в файле"
    assert_says "«.claude/rulebook/$book_rule»" "  ...и рядом названа приведённая цель"
    assert_says "осмотрено файлов $inj02_closure" "  ...и гейт НЕ спустился в свод по этой ссылке"
done

# Законный близнец у каждой формы: та же строка в обратных кавычках. Без него
# гейт ловил бы форму, а не существо, и первая координата в прозе его отключила
# бы вместе с настоящими находками.
for form in "./.claude/rulebook" ".claude//rulebook" ".claude/./rulebook" ".claude/rules/../rulebook"; do
    d="$(sandbox "lt_$(printf '%s' "$form" | tr -c 'a-z' '_')")"
    printf '\nПодробности — `@%s/%s` §«класс».\n' "$form" "$book_rule" >> "$d/CLAUDE.md"
    capture "$d" "$C2N"
    assert_code 0 "БЛИЗНЕЦ: «@$form/…» в обратных кавычках — координата, не импорт"
done
