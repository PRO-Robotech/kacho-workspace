#!/usr/bin/env bash
# ЧАСТЬ инъекции набора: доказательство check-02 «автозагрузка пуста, база на
# месте» по осям, которых нет в общем `inject.sh`. Оси A…F (правило вернулось в
# автозагрузку, определение агента в автозагрузке, снятый дом, середина
# предложения, пустой обход, отсутствие предмета) доказаны там; здесь — формы
# записи координаты, лишний хоп замыкания и три оси, живущие ВНЕ текста
# `CLAUDE.md`: исключение автозагрузки, главный поток и бюджет базы.
#
# Файл ПОДКЛЮЧАЕТСЯ (`.`) из `inject.sh` и пользуется его оснасткой — `sandbox`,
# `capture`, `assert_code`, `assert_says`, `assert_lacks`, `assert_fixture_changed`,
# счётчиками `pass`/`fail`.
#
# Каждая проба меняет РОВНО ОДИН факт и ставит рядом ЗАКОННОГО БЛИЗНЕЦА той же
# формы, на котором гейт обязан смолчать. Проверяется НЕ ТОЛЬКО КОД, НО И ТЕКСТ:
# находка, называющая не ту ось, посылает читателя чинить не то — а три оси ниже
# ловятся ОДНОЙ правкой одного JSON, и спутать их особенно легко.

# ── СТРАЖ ПОДКЛЮЧЕНИЯ: часть НЕ исполняется самостоятельно ───────────────────
#
# Своей оснастки (`sandbox`, `capture`, `assert_*`, счётчики) у части нет. В
# обход `inject.sh` она не просто ничего не доказывает — она ПОРТИТ дерево, из
# которого запущена: каталог песочницы не определён, поэтому путь вида
# `"$d/CLAUDE.md"` становится ОТНОСИТЕЛЬНЫМ и правка уезжает в рабочую копию, а
# `git -C "$d" add -A` стажирует в её индекс чужие незакоммиченные правки.
# Испорченный индекс делает лживыми ИМЕННО те проверки, что читают дерево:
# «ноль находок» превращается в «ноль прочитанного» и выглядит настоящей
# находкой (`.claude/rules/multi-agent-flow-shared-tree.md` §13 «Неприкосновенность чужого
# состояния»).
#
# ИЗМЕРЕНО ДО СТРАЖА, на изолированной копии с чистым деревом: прямой запуск
# inject-02 → rc=127 и ` M CLAUDE.md`; прямой запуск inject-03 → rc=0 при НУЛЕ
# исполненных утверждений и превращал чужое ` M` в `M ` (стажировал). То есть
# «не выполнилось» отчитывалось успехом, и в том же прогоне портилось дерево.
#
# Отказ — код 2, а не 1: ноль исполненных утверждений не является находкой в
# дереве и не является успехом (`.claude/rules/testing.md` §«Чтение вердикта»).
#
# Бит исполнения намеренно ОСТАВЛЕН: без него `./inject-NN-….sh` отвечал бы
# «Permission denied» — диагностика хуже, чем у этого отказа, который называет
# и причину, и команду, которую звать вместо.
if [ "${BASH_SOURCE[0]}" = "$0" ]; then
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — ЧАСТЬ инъекции, а не самостоятельная проба." >&2
    echo "       Она подключается (\`.\`) из scripts/rules-gate/inject.sh и пользуется его" >&2
    echo "       оснасткой; самостоятельно не исполнила бы ни одного утверждения и писала бы" >&2
    echo "       в рабочее дерево. Запускать: bash scripts/rules-gate/inject.sh" >&2
    exit 2
fi
for _inj_fn in sandbox capture assert_code assert_says assert_lacks assert_fixture_changed sandbox_digest; do
    command -v "$_inj_fn" >/dev/null 2>&1 && continue
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — оснастки inject.sh нет: функция" \
         "«$_inj_fn» не определена; часть подключена не оттуда, доказывать нечем" >&2
    exit 2
done
unset -v _inj_fn
if [ -z "${WS:-}" ] || [ ! -d "$WS" ]; then
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — корень дерева \$WS не определён либо не" \
         "каталог; жертву фикстуры выводить не из чего" >&2
    exit 2
fi
# Жертвы фикстуры выводит ИЗ ДЕРЕВА сам inject.sh (`corpus_rule` — правило корпуса,
# `ghost_rule` — синтетическое имя в снятом доме); часть их только читает. Здесь они
# перепривязываются к себе — и это не косметика: без привязки часть, подключённая
# оснасткой БЕЗ жертв, молча писала бы в фикстуру `@.claude/rules/` и `@.claude/
# rulebook/` с ПУСТЫМ хвостом, а утверждения о коде и о тексте вердикта относились
# бы к координате, которой в дереве нет. Пустое имя — не находка и не успех: код 2,
# тем же доводом, что у стража оснастки выше.
corpus_rule="${corpus_rule:-}"
ghost_rule="${ghost_rule:-}"
if [ -z "$corpus_rule" ] || [ -z "$ghost_rule" ]; then
    echo "[VOID] $(basename "${BASH_SOURCE[0]}") — жертвы inject.sh не заведены" \
         "(«corpus_rule», «ghost_rule»); координату фикстуры строить не из чего" >&2
    exit 2
fi

C2N=check-02-nothing-lost.sh

# ── ПРАВКА НАСТРОЕК В ПЕСОЧНИЦЕ ─────────────────────────────────────────────
#
# JSON правится РАЗБОРОМ, а не `sed`: текстовая подмена в настройках вырождается в
# no-op на первой же перестановке ключей, и утверждение о вердикте начинает
# относиться к нетронутой копии. Всякая операция обязана что-то изменить и
# отказывает, если не изменила, — тем же доводом, что и правка таблицы манифеста.
inj02_settings() {   # <каталог> <операция> [аргумент]
    python3 - "$1/.claude/settings.json" "$2" "${3-}" <<'PY'
import io, json, sys
path, op, arg = sys.argv[1], sys.argv[2], sys.argv[3]
before = io.open(path, encoding='utf-8').read()
data = json.loads(before)
if op == 'drop_excludes':
    data.pop('claudeMdExcludes', None)
elif op == 'set_excludes':                 # arg — один шаблон
    data['claudeMdExcludes'] = [arg]
elif op == 'add_exclude':                  # arg — шаблон ВДОБАВОК к имеющимся
    data['claudeMdExcludes'] = list(data.get('claudeMdExcludes') or []) + [arg]
elif op == 'drop_agent':
    data.pop('agent', None)
elif op == 'set_agent':
    data['agent'] = arg
elif op == 'other_key':                    # правка, к предмету не относящаяся
    data['outputStyle'] = arg or 'inj02'
else:
    raise SystemExit('unknown op ' + op)
after = json.dumps(data, ensure_ascii=False, indent=2) + '\n'
if json.loads(after) == json.loads(before):
    raise SystemExit(
        'ФИКСТУРА ВАКУУМНА: операция «%s» с аргументом «%s» не изменила '
        '.claude/settings.json; утверждение о вердикте гейта относилось бы к '
        'нетронутому дереву' % (op, arg))
io.open(path, 'w', encoding='utf-8').write(after)
PY
}

# Дописать в файл N килобайт прозы. Единица — КИЛОБАЙТ, потому что предмет оси
# числовой: потолок объявлен в байтах, и фикстура обязана его переступить заведомо,
# а не на грани, где проба начинает зависеть от длины имени в шапке.
inj02_grow() {   # <файл> <килобайт>
    python3 - "$1" "$2" <<'PY'
import io, sys
path, kb = sys.argv[1], int(sys.argv[2])
line = 'Дописанный абзац базы, который никто не решал вносить.\n'
with io.open(path, 'a', encoding='utf-8') as fh:
    written = 0
    while written < kb * 1024:
        fh.write(line)
        written += len(line.encode('utf-8'))
PY
}

# ── ось G: ОДНА цель — НЕСКОЛЬКО законных написаний ─────────────────────────
#
# Загрузчик резолвит `@./x`, `@a//b`, `@a/./b` и `@a/c/../b` в ОДИН файл.
# Распознаватель, знающий одну форму, на остальных МОЛЧИТ — ни красного, ни
# зелёного, предмет просто уходит из-под наблюдения (§«Гейт на класс», п.7).
#
# Измерено на дофиксовом гейте, одной командой на форму: голая ссылка давала код 1,
# три её переписи — 0. Две из трёх были ХУЖЕ молчания: гейт засчитывал их
# ОБЪЯВЛЕНИЕМ и спускался по ним внутрь — его собственная перепись называла
# тамошний файл прочитанным, а вердикт в той же строке говорил, что таких импортов
# ноль. После инверсии предмета цена та же, знак обратный: правило, возвращённое в
# автозагрузку одной из трёх «неизвестных» форм, приезжало бы каждому агенту при
# зелёном гейте. Поэтому здесь утверждается ЧЕТВЁРКА:
# код · названная ось · координата КАК НАПИСАНА · то, что замыкание НЕ выросло.
echo "== ось G: та же цель, написанная иначе, — то же правило в автозагрузке =="

# Население замыкания на НЕТРОНУТОЙ копии берётся ПРОГОНОМ, а не выписывается:
# оно меняется вместе с деревом, и выписанное число состарилось бы молча.
d="$(sandbox l_base)"
capture "$d" "$C2N"
inj02_closure="$(printf '%s\n' "$OUT" | sed -n 's/.*осмотрено файлов \([0-9][0-9]*\).*/\1/p' | head -1)"

for form in "./.claude/rules" ".claude//rules" ".claude/./rules" ".claude/agents/../rules"; do
    # shellcheck disable=SC2018  # `a-z` ЗДЕСЬ И ЕСТЬ ПРЕДМЕТ: имя песочницы
    #   сводится к ASCII нарочно. Подставь `[:lower:]`, как советует правило, — и
    #   не-ASCII буква формы уехала бы в ИМЯ КАТАЛОГА нетронутой, а песочницы двух
    #   разных форм сошлись бы в одну на первой же кириллической координате.
    d="$(sandbox "g_$(printf '%s' "$form" | tr -c 'a-z' '_')")"
    printf '\n@%s/%s\n' "$form" "$corpus_rule" >> "$d/CLAUDE.md"
    capture "$d" "$C2N"
    assert_code 1 "ДЕФЕКТ: правило в автозагрузке, написанное как «@$form/…»"
    assert_says "ПРАВИЛО В АВТОЗАГРУЗКЕ" "  ...и названа ТА ось, а не «в середине предложения»"
    assert_says "@$form/$corpus_rule" "  ...и координата названа ТАК, КАК НАПИСАНА в файле"
    assert_says "«.claude/rules/$corpus_rule»" "  ...и рядом названа приведённая цель"
    assert_says "осмотрено файлов $inj02_closure" "  ...и гейт НЕ спустился в корпус по этой ссылке"
done

# Законный близнец у каждой формы: та же строка в обратных кавычках. Без него
# гейт ловил бы форму, а не существо, и первая координата в прозе его отключила
# бы вместе с настоящими находками.
for form in "./.claude/rules" ".claude//rules" ".claude/./rules" ".claude/agents/../rules"; do
    # shellcheck disable=SC2018  # тот же довод, что у дефектной формы выше: имя
    #   песочницы сводится к ASCII нарочно, и `[:lower:]` слил бы близнеца с ним.
    d="$(sandbox "gt_$(printf '%s' "$form" | tr -c 'a-z' '_')")"
    # shellcheck disable=SC2016  # Обратные кавычки — РАЗМЕТКА вносимого markdown:
    #   в них вся суть близнеца (координата в код-спане импортом не является).
    #   Двойные кавычки потребовали бы экранировать разметку, а фикстура обязана
    #   лечь в CLAUDE.md БАЙТ В БАЙТ так, как её пишут люди.
    printf '\nПодробности — `@%s/%s` §«класс».\n' "$form" "$corpus_rule" >> "$d/CLAUDE.md"
    capture "$d" "$C2N"
    assert_code 0 "БЛИЗНЕЦ: «@$form/…» в обратных кавычках — координата, не импорт"
done

# ── ось H: замыкание ВЫЧИСЛЯЕТСЯ, а не выписывается ─────────────────────────
#
# Прежняя редакция читала фиксированный набор «CLAUDE.md + .claude/rules/*.md» и
# звала его замыканием. Ссылка за ОДИН лишний хоп уезжала молча, и перепись этого
# не показывала: `@docs/…` не попадал даже в счёт ссылок. Класс не изменился с
# инверсией предмета — изменилось, что именно за хопом прячут: раньше туда уезжал
# второй дом, теперь так возвращают правило в автозагрузку, минуя дифф CLAUDE.md.
echo
echo "== ось H: правило за лишний хоп — замыкание обязано за ним пойти =="

d="$(sandbox h_hop)"
mkdir -p "$d/docs"
printf '@.claude/rules/%s\n' "$corpus_rule" > "$d/docs/extra.md"
printf '@docs/extra.md\n' >> "$d/CLAUDE.md"
capture "$d" "$C2N"
assert_code 1 "ДЕФЕКТ: правило импортировано через промежуточный файл"
assert_says "ПРАВИЛО В АВТОЗАГРУЗКЕ: docs/extra.md" "  ...и координата — ФАЙЛ, где импорт живёт"
assert_says "рёбер замыкания за пределы CLAUDE.md 1" "  ...и перепись назвала ребро наружу"

d="$(sandbox h_home)"
mkdir -p "$d/docs"
printf '@.claude/rulebook/%s\n' "$ghost_rule" > "$d/docs/extra.md"
printf '@docs/extra.md\n' >> "$d/CLAUDE.md"
capture "$d" "$C2N"
assert_code 1 "ДЕФЕКТ: снятый дом импортирован через промежуточный файл"
assert_says "ИМПОРТ ИЗ СНЯТОГО ДОМА: docs/extra.md" "  ...и названа ТА ось, а не «правило в автозагрузке»"

d="$(sandbox h_twin)"; b="$(sandbox_digest "$d")"
mkdir -p "$d/docs"
printf '# заметка без импортов\n' > "$d/docs/extra.md"
printf '@docs/extra.md\n' >> "$d/CLAUDE.md"
assert_fixture_changed "$d" "$b" "БЛИЗНЕЦ: тот же лишний хоп без импорта внутри"
capture "$d" "$C2N"
assert_code 0 "БЛИЗНЕЦ: посторонний файл в замыкании сам по себе законен — молчит"

d="$(sandbox h_mail)"; b="$(sandbox_digest "$d")"
printf '\nПишите на admin@in-cloud.io либо позовите @claude.\n' >> "$d/CLAUDE.md"
assert_fixture_changed "$d" "$b" "БЛИЗНЕЦ: почта и @имя в прозе"
capture "$d" "$C2N"
assert_code 0 "БЛИЗНЕЦ: почта и @имя в прозе маршрутом не становятся"

# ── ось I: ИСКЛЮЧЕНИЕ автозагрузки ──────────────────────────────────────────
#
# Ось новая и самая молчаливая в наборе: в дереве не меняется ни один markdown.
# Снятый шаблон возвращает в окно КАЖДОГО агента весь корпус (143 КБ) — и ни
# CLAUDE.md, ни манифест, ни определения агентов об этом не говорят ничего, потому
# что автозагрузку Claude Code делает САМ, без единого `@import` (измерено).
#
# ПОКРЫТИЕ, А НЕ ТЕКСТ: шаблон пишется десятком способов, и сверка «есть ли такая
# строка» отвечала бы на вопрос о тексте настроек. Поэтому дефектов здесь два —
# «шаблона нет вовсе» и «шаблон есть, но мимо», — а близнецов два зеркально:
# «другое написание того же покрытия» и «лишний шаблон рядом».
echo
echo "== ось I: исключение автозагрузки не покрывает корпус =="

d="$(sandbox i_drop)"
inj02_settings "$d" drop_excludes
capture "$d" "$C2N"
assert_code 1 "ДЕФЕКТ: ключ claudeMdExcludes снят из настроек"
assert_says "ИСКЛЮЧЕНИЕ НЕ ПОКРЫВАЕТ КОРПУС" "  ...и вердикт назван своим именем"
assert_says "нет ни одного шаблона claudeMdExcludes" "  ...и названа причина: шаблона нет вовсе"
assert_lacks "ГЛАВНЫЙ ПОТОК НЕ ДИСПЕТЧЕР" "  ...и диагноз ОДИН: настройка agent не тронута"

d="$(sandbox i_miss)"
inj02_settings "$d" set_excludes '**/.claude/rulebook/**'
capture "$d" "$C2N"
assert_code 1 "ДЕФЕКТ: шаблон есть, но покрывает ДРУГОЙ каталог"
assert_says "ИСКЛЮЧЕНИЕ НЕ ПОКРЫВАЕТ КОРПУС" "  ...и вердикт назван своим именем"
assert_says ".claude/rules/x.md" "  ...и назван пробный путь, оставшийся в автозагрузке"

d="$(sandbox i_flat)"
# Шаблон покрывает правило в КОРНЕ каталога и не покрывает доменное. Проба ловит
# ровно то, ради чего пробных путей два: население корпуса рекурсивно, и одно
# правило осталось бы в автозагрузке при зелёном гейте, знай он один путь.
inj02_settings "$d" set_excludes '**/.claude/rules/*.md'
capture "$d" "$C2N"
assert_code 1 "ДЕФЕКТ: шаблон покрывает только плоский корпус"
assert_says ".claude/rules/domain/x.md" "  ...и назван ИМЕННО непокрытый путь — правило в подкаталоге"
assert_lacks ".claude/rules/x.md," "  ...и не назван покрытый: диагноз указывает на дыру, а не на всё"

d="$(sandbox i_twin_rel)"; b="$(sandbox_digest "$d")"
inj02_settings "$d" set_excludes '.claude/rules/**'
assert_fixture_changed "$d" "$b" "БЛИЗНЕЦ: то же покрытие, другое написание шаблона"
capture "$d" "$C2N"
assert_code 0 "БЛИЗНЕЦ: покрытие то же, написание другое — судится ПУТЬ, а не строка"

d="$(sandbox i_twin_extra)"; b="$(sandbox_digest "$d")"
inj02_settings "$d" add_exclude '**/vendor/**'
assert_fixture_changed "$d" "$b" "БЛИЗНЕЦ: лишний шаблон рядом с действующим"
capture "$d" "$C2N"
assert_code 0 "БЛИЗНЕЦ: посторонний шаблон в списке покрытия не отменяет — молчит"

# ── ось J: ГЛАВНЫЙ ПОТОК ────────────────────────────────────────────────────
#
# Вторая ось того же файла и потому доказывается ОТДЕЛЬНО: исключение и настройка
# `agent` чинятся разными правками, и находка, назвавшая обе, послала бы чинить
# две вещи там, где сломана одна. Предмет: тело агента, названного настройкой,
# ЗАМЕНЯЕТ системный промпт главного потока (измерено) — без него главный поток
# получает обратно Read, Bash и Edit, и «диспетчер ничего не разведывает сам»
# перестаёт держаться чем бы то ни было.
echo
echo "== ось J: главный поток — диспетчер =="

d="$(sandbox j_noagent)"
inj02_settings "$d" drop_agent
capture "$d" "$C2N"
assert_code 1 "ДЕФЕКТ: настройка agent снята"
assert_says "ГЛАВНЫЙ ПОТОК НЕ ДИСПЕТЧЕР" "  ...и вердикт назван своим именем"
assert_lacks "ИСКЛЮЧЕНИЕ НЕ ПОКРЫВАЕТ КОРПУС" "  ...и диагноз ОДИН: исключение не тронуто"

d="$(sandbox j_other)"
