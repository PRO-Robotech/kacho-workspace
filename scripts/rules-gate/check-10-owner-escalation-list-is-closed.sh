#!/usr/bin/env bash
# check-10 — ПЕРЕЧЕНЬ ПОВОДОВ ОБРАТИТЬСЯ К ВЛАДЕЛЬЦУ СУДИТСЯ ОТПЕЧАТКОМ.
#
# ПРЕДМЕТ. Раздел «Когда спрашивать владельца» в `.claude/agents/dispatcher.md`
# объявляет ЗАКРЫТЫЙ перечень поводов остановить полосу и спросить человека.
# Перечень закрыт по существу: диспетчер не разведывает сам, и всё, чего нет в
# этом списке, он обязан решить по базе и возвратам. Дописанный пункт «а ещё
# можно спросить про…» и дописанная оговорка «перечень — ориентир» стоят одного:
# они превращают закрытый список в открытый, и с этого момента к владельцу идёт
# всё подряд либо не идёт ничего.
#
# ПОЧЕМУ ЭТО ГЕЙТ, А НЕ АБЗАЦ — И ПОЧЕМУ ИМЕННО ОТПЕЧАТОК.
#
#   До 2026-09-21 норму не держало НИЧЕГО: перемерено на свежей базе 6e5b9a60 —
#   ослабляющая вставка в раздел оставляла набор зелёным (код 0, проверок 9,
#   находок 0), и удаление раздела ЦЕЛИКОМ оставляло его зелёным тем же кодом.
#
#   Очевидный способ — «искать в разделе обязательные подстроки» — негоден, и
#   негоден не по вкусу, а по арифметике. ПРИСУТСТВИЕ ПОДСТРОКИ МОНОТОННО ПО
#   ДОПИСЫВАНИЮ: если подстрока есть в тексте T, она есть и в T + X при любом X.
#   А всякое ослабление нормы и ЕСТЬ дописывание: оговорку, исключение, «кроме
#   случаев», новый пункт добавляют, не трогая ни одной старой буквы. Предикат
#   на присутствии ловит ровно противоположный класс — удаление нормы, — и слеп
#   к тому, ради чего норму сторожат.
#
#   Отпечаток немонотонен: sha256 раздела меняется от ЛЮБОЙ правки — добавления,
#   удаления, перестановки, правки пробелов. Дописать что-либо, не уронив гейт,
#   нельзя by construction.
#
# ГРАНИЦА ЭТОГО ГЕЙТА, НАЗВАННАЯ ЧЕСТНО. Он ловит ИЗМЕНЕНИЕ нормы и НЕ отличает
# ослабление от усиления. Машина этого не умеет: «перечень — ориентир, а не
# закрытый список» и «перечень закрыт, добавление — решение владельца» для неё
# два разных текста и больше ничего. Судит ослабление РЕЦЕНЗЕНТ — человек либо
# роль, которой вердикт поручен, — и гейт обязан его позвать: он печатает, ЧТО
# именно изменилось, старый и новый отпечаток и прямое требование вынести
# вердикт. Выдавать одно за другое нельзя: «гейт зелёный» здесь значит «норму
# не трогали», а не «правка безопасна».
#
# УЗАКОНИВАНИЕ — ОТДЕЛЬНЫЙ ПОСТУПОК, А НЕ ПОБОЧНЫЙ ЭФФЕКТ. Законная правка нормы
# идёт вместе с обновлением ожидаемого отпечатка в `owner-escalation-fingerprint.txt`,
# и в диффе это видно строкой, которую кто-то написал руками. Генератора
# ведомости в наборе НЕТ намеренно: скрипт «обнови отпечаток» превратил бы
# поступок обратно в побочный эффект — его запускали бы не глядя. Гейт печатает
# готовые строки, вписывает их человек.
#
# ЧТО ОСМАТРИВАЕТСЯ (объём объявлен, потому что «находок 0» обязано быть отличимо
# от «не смотрели»): раздел целиком — от строки заголовка `## <N>. Когда
# спрашивать владельца` включительно до следующей строки, начинающейся с `## `,
# исключительно. Целиком, а не «только маркированные пункты»: преамбула раздела
# («`AskUserQuestion` — когда решение не выводится ни из базы, ни из возвратов»)
# задаёт условие применения перечня, и ослабить норму, правя её, ровно так же
# легко. Перегляд здесь дешевле недогляда: лишнее красное зовёт рецензента,
# лишнее зелёное отпускает правку молча.
#
# ТРИ ИСХОДА:
#   0 — раздел найден, отпечаток сошёлся;
#   1 — НАХОДКА: отпечаток разошёлся, либо раздела нет при существующей базе,
#       либо ведомости ожидаемого отпечатка нет или она нечитаема;
#   2 — БЕЗ ПРЕДМЕТА: файла базы нет вовсе. Это не «норма цела» — это «судить
#       нечего»; отсутствие самой базы — предмет check-02, а не этой проверки.
#
# ПОЧЕМУ «РАЗДЕЛА НЕТ» — КОД 1, А НЕ 2. Удаление охраняемой нормы обязано быть
# находкой: иначе самый дешёвый способ погасить гейт — снять раздел, и проверка
# сама подсказала бы этот путь, отвечая «без предмета».
set -euo pipefail
SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# КОРЕНЬ ДЕРЕВА — ИЗ `RULES_GATE_ROOT`, и это контракт набора, а не удобство:
# проверку, знающую только свой рабочий каталог, нельзя прогнать на временной
# копии, а инъекция в настоящем дереве — не инъекция, а порча. Запасной путь —
# корень git: в CI переменная не задана.
cd "${RULES_GATE_ROOT:-$(git rev-parse --show-toplevel)}"

# Ведомость лежит РЯДОМ С ПРОВЕРКОЙ, а дерево берётся из корня: инъекция гоняет
# проверку на копии дерева, куда `scripts/` не копируется. Шов средой — той же
# природы, что `RULES_GATE_ADDRESS_BASELINE` у check-07: ось «ведомость пропала»
# иначе недоказуема, а в CI переменная не задана и ведомость берётся рядом.
LEDGER="${RULES_GATE_OWNER_LEDGER:-$SELF_DIR/owner-escalation-fingerprint.txt}"

exec python3 - "$LEDGER" <<'PY'
import hashlib
import os
import re
import sys

LEDGER = sys.argv[1]
BASE = ".claude/agents/dispatcher.md"


def here(path):
    """Координата ведомости, ЧИТАЕМАЯ ЧЕЛОВЕКОМ.

    `os.path.relpath` от корня дерева выдаёт на ведомости вне дерева цепочку
    `../../..` в дюжину звеньев — координату, по которой никто не пойдёт. Внутри
    дерева путь относительный, снаружи (шов среды у инъекции) — абсолютный.
    """
    rel = os.path.relpath(path)
    return rel if not rel.startswith("..") else os.path.abspath(path)
HEADING = re.compile(r"^##\s+\d+\.\s+Когда спрашивать владельца\s*$")
NEXT_SECTION = re.compile(r"^##\s")
LABEL_CAP = 64


def h64(s):
    return hashlib.sha256(s.encode("utf-8")).hexdigest()


def h16(s):
    return h64(s)[:16]


# ── предмет ──────────────────────────────────────────────────────────────────
if not os.path.isfile(BASE):
    print(f"ОТКАЗ — нет {BASE}: базы маршрутизации в дереве не существует, и "
          f"охраняемой нормы вместе с ней. Судить нечего; отсутствие базы — "
          f"предмет check-02, а не этой проверки")
    sys.exit(2)

text = open(BASE, encoding="utf-8").read()
lines = text.split("\n")

start = None
for i, ln in enumerate(lines):
    if HEADING.match(ln):
        start = i
        break

if start is None:
    print(f"КРАСНОЕ {BASE} — раздела «Когда спрашивать владельца» в базе НЕТ.")
    print("  Норма удалена целиком либо её заголовок переписан. И то и другое —")
    print("  находка: на §11 ссылаются другие разделы базы, а закрытый перечень")
    print("  поводов остановить полосу перестал существовать. Осмотрено строк"
          f" базы: {len(lines)}.")
    print("  Законный путь, если снятие нормы — решение: снять её ВМЕСТЕ с этой")
    print(f"  проверкой и её ведомостью {here(LEDGER)} одним изменением.")
    sys.exit(1)

end = len(lines)
for j in range(start + 1, len(lines)):
    if NEXT_SECTION.match(lines[j]):
        end = j
        break

section = lines[start:end]
body = "\n".join(section)
total_now = h64(body)

norm_lines = [ln.rstrip() for ln in section]
norm_lines = [ln for ln in norm_lines if ln]
entries_now = [(h16(ln), ln[:LABEL_CAP]) for ln in norm_lines]

# ── ведомость ожидаемого отпечатка ──────────────────────────────────────────
def expected_ledger_text():
    out = ["ИТОГО\t" + total_now]
    out += [f"{hh}\t{lb}" for hh, lb in entries_now]
    return "\n".join(out)


if not os.path.isfile(LEDGER):
    print(f"КРАСНОЕ — ведомости ожидаемого отпечатка нет: {LEDGER}")
    print("  Без неё проверке не с чем сверять, и молчание означало бы «не")
    print("  смотрели». Носитель гейта снимают ВМЕСТЕ с гейтом, а не отдельно.")
    print(f"  Осмотрено строк раздела: {len(section)}, из них норм {len(norm_lines)}.")
    sys.exit(1)

raw = open(LEDGER, encoding="utf-8").read().split("\n")
total_want = None
entries_want = []
sanction = ""
for ln in raw:
    if ln.startswith("#"):
        m = re.match(r"#\s*узаконено:\s*(.+?)\s*$", ln)
        if m:
            sanction = m.group(1)
        continue
    if not ln.strip():
        continue
    if "\t" not in ln:
        continue
    left, right = ln.split("\t", 1)
    if left == "ИТОГО":
        total_want = right.strip()
    else:
        entries_want.append((left.strip(), right))

problems = []
if total_want is None:
    problems.append("нет строки «ИТОГО <sha256>» — отпечатка раздела не объявлено")
if not entries_want:
    problems.append("нет ни одной построчной записи — перестановку ловить нечем")
if not sanction:
    problems.append("нет строки «# узаконено: <дата> · <основание>» — "
                    "отпечаток обновлён без названного основания")
if problems:
    print(f"КРАСНОЕ — ведомость {here(LEDGER)} не годится как ожидание:")
    for p in problems:
        print(f"  · {p}")
    print("  Ведомость, которой нечего утверждать, делает проверку всегда зелёной.")
    sys.exit(1)

# ── вердикт ─────────────────────────────────────────────────────────────────
print(f"[CENSUS] check-10-owner-escalation-list-is-closed: {BASE} — строк {len(lines)};"
      f" раздел найден со строки {start + 1} по {end}, строк в нём {len(section)},"
      f" из них норм {len(norm_lines)}; ведомость {here(LEDGER)} —"
      f" записей {len(entries_want)}, узаконено: {sanction}")

if total_want == total_now:
    print("[PASS] check-10-owner-escalation-list-is-closed — отпечаток охраняемой"
          f" нормы сошёлся: {total_now[:16]}…, норм {len(norm_lines)}."
          " ЭТО ЗНАЧИТ «норму не трогали», а НЕ «правка безопасна»:"
          " ослабление от усиления гейт не отличает — их судит рецензент.")
    sys.exit(0)

want_h = [hh for hh, _ in entries_want]
now_h = [hh for hh, _ in entries_now]
want_label = dict(entries_want)
now_label = dict(entries_now)

added = [hh for hh in now_h if hh not in set(want_h)]
removed = [hh for hh in want_h if hh not in set(now_h)]

print(f"КРАСНОЕ {BASE} — ОХРАНЯЕМАЯ НОРМА ИЗМЕНЕНА.")
print(f"  раздел: «{section[0].strip()}»")
print(f"  отпечаток ожидался {total_want}")
print(f"  отпечаток в дереве {total_now}")

if added:
    print(f"  ДОПИСАНО строк: {len(added)} — и это класс, ради которого проверка"
          " судит отпечаток, а не присутствие слов:")
    for hh in added:
        print(f"    + [{hh}] {now_label.get(hh, '')}")
if removed:
    print(f"  СНЯТО строк: {len(removed)}:")
    for hh in removed:
        print(f"    - [{hh}] {want_label.get(hh, '')}")
if not added and not removed:
    if want_h != now_h:
        print("  ПЕРЕСТАВЛЕНО: состав строк тот же, порядок другой — перечень"
              " читается иначе, хотя ни одной буквы не изменилось.")
    else:
        print("  ПРАВКА РАЗМЕТКИ: состав и порядок норм те же, различаются пустые"
              " строки либо хвостовые пробелы.")

print()
print("  ЧЕМ ЭТО УЗАКОНИВАЕТСЯ. Правка нормы законна, если вердикт о ней вынес"
      " РЕЦЕНЗЕНТ:")
print("  гейт назвал, ЧТО изменилось, но ослабление от усиления НЕ отличает —"
      " это не в его силах.")
print("  Узаконив правку, впиши ожидаемый отпечаток ТЕМ ЖЕ изменением, что и её,"
      " в")
print(f"  {here(LEDGER)} — строками ниже, и обнови «# узаконено:».")
print("  ── ожидаемая ведомость целиком ──")
for ln in expected_ledger_text().split("\n"):
    print("  " + ln)
sys.exit(1)
PY
