#!/usr/bin/env bash
# check-07 — АДРЕС НОРМЫ РЕЗОЛВИТСЯ, id УНИКАЛЕН.
# Предмет: перенос текста между файлами рвёт ссылку молча. Область ШИРЕ, чем у
# `skills-gate/check-01`: агенты, правила, `CLAUDE.md` и гейты продукта.
#
# РАЗБОРЩИК И БАЗА БЕРУТСЯ РЯДОМ С СОБОЙ, а дерево — из корня. Инъекция гоняет
# проверку на КОПИИ дерева, куда `scripts/` не копируется: путь от корня дал бы
# «нет такого файла» и код 2, а харнесс ждёт 0 на нетронутой копии.
set -euo pipefail
SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# КОРЕНЬ ВЫВОДИТСЯ ИЗ СВОЕГО РАСПОЛОЖЕНИЯ, А НЕ ИЗ ТЕКУЩЕГО КАТАЛОГА (2026-09-22).
# Здесь стоял `cd "$(git rev-parse --show-toplevel)"`, и это тот же класс, что
# измерен на `check-11`: проверка, запущенная с cwd в соседнем worktree полосы,
# МОЛЧА судит чужое дерево и выходит нулём — «полоса получает чужой вердикт».
# Образец решения взят у соседей — `check-02:196` и
# `scripts/tooling-gate/check-12:65`. Шов `RULES_GATE_ROOT` остаётся первым:
# инъекция гоняет проверку на КОПИИ дерева, и без него ось была бы недоказуема
# (контракт набора, `run-all.sh` §«КОНТРАКТ НАБОРА ДЛЯ ЕГО ПРОВЕРОК», п. «а»).
# Корень ПЕЧАТАЕТСЯ переписью: без имени дерева все прочие числа не читаются.
root="${RULES_GATE_ROOT:-$(cd "$SELF_DIR/../.." && pwd)}"
cd "$root" 2>/dev/null || {
    echo "[VOID] check-07-address-resolves — корень «$root» не открывается; обходить нечего" >&2
    exit 2
}
echo "[CENSUS] check-07-address-resolves: корень $root"
# Путь базы переопределяем средой: ось «адрес из базы зажил» инъекции иначе не
# доказуема — все 18 её записей живут в `project/kacho/**`, которого в песочнице
# нет, и подставить заживший адрес можно только своей базой. Шов той же природы,
# что `RULES_GATE_ROOT`: в CI переменная не задана, база берётся рядом с собой.
exec python3 "$SELF_DIR/address-refs.py" \
    --baseline "${RULES_GATE_ADDRESS_BASELINE:-$SELF_DIR/address-baseline.txt}"
