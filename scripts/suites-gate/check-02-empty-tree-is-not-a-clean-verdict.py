#!/usr/bin/env python3
"""check-02 — на пустом дереве каждая проверка каждого набора отвечает «без предмета» и называет причину.

ЧТО УТВЕРЖДАЕТ (ws#762 п.3). Каждая проверка, направленная на ПУСТОЕ дерево, выходит
кодом 2 («без предмета») и печатает причину. Любой другой исход — находка:

  * ноль — проверка объявила «чисто», ничего не прочитав, и читатель, не
    заглядывая в её исходник, отличить это от настоящего зелёного не может;
  * единица — проверка объявила НАРУШЕНИЕ там, где условие не создано. Вызывающий
    принимает по двум кодам противоположные решения: находку чинят в дереве,
    отсутствие предмета создают условием. Единица на пустом дереве посылает чинить
    то, чего нет (решение диспетчера 2026-09-28: на пустом дереве — «без
    предмета» с названной причиной; прежде этот исход проверка считала
    допустимым и печатала его в переписи исходов, не называя находкой);
  * двойка МОЛЧА — третья категория без причины: чего не хватает, не сказано, и
    создать условие не по чему;
  * двойка БЕЗ СТРОКИ `[VOID] <причина>` — код 2 отдаёт и сам интерпретатор
    (синтаксическая ошибка оболочки, отказ разбора аргументов у python), и его
    текст («syntax error») причиной не является: сломанная проверка иначе
    засчитывается за «без предмета», как прежде и было;
  * предел времени и код вне трёх исходов — проверка не отчиталась вовсе.

«Причина» — строка `[VOID]` с непустым текстом после метки, в любом из двух
потоков: та же метка, по которой общий прогонщик (`scripts/lib/suite-runner.sh`)
отличает «без предмета» от поломки. Что текст после метки — именно причина, а не
шум, проба не судит: нижняя граница формы, и это названо, а не подразумевается.

ПРОБА ПОВЕДЕНЧЕСКАЯ. Проверку зовут с общим переопределением `GATE_ROOT` на пустой
git-репозиторий, из него же как рабочего каталога, сняв указатели на клоны продукта
(`_lib.world_env`). Судится код и вывод, а не текст исходника.

ГРАНИЦА С СОСЕДЯМИ — названа, чтобы проверки об одном не разошлись:
  * `check-01` судит, из какого дерева проверка берёт корень; проверку, которая
    берёт его из рабочего каталога И выходит нулём на пустом, ловит ЭТА: в обоих
    её прогонах исход одинаков, а здесь ноль — находка;
  * проверку, не читающую переопределение корня вовсе, ловит тоже эта: она судит
    своё настоящее дерево, выходит нулём, и находка говорит об обеих причинах;
  * печатает ли проверка объём на НАСТОЯЩЕМ дереве, судит общий прогонщик
    (`scripts/lib/suite-runner.sh`), а что каждый прогонщик набора это умеет —
    `check-03-runner-demands-a-printed-volume.py`.

Коды: 0 — каждая проверка на пустом дереве отвечает «без предмета» строкой [VOID] с причиной;
1 — находка; 2 — осматривать нечего.
"""
import os
import re
import shutil
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import _lib  # noqa: E402

NAME = "check-02-empty-tree-is-not-a-clean-verdict"
VOID = 2
VOID_LINE = re.compile(r"\[VOID\]\s*\S")


def verdict(rel, rc, out):
    """Текст находки либо None, если исход на пустом дереве законен."""
    if rc == VOID:
        if VOID_LINE.search(out):
            return None
        if out.strip():
            return ("%s — на пустом дереве код 2 без строки «[VOID] <причина>»: код 2 "
                    "отдал интерпретатор либо проверка не объявила третью категорию — "
                    "вывод «%s» причиной не является" % (rel, out.strip().split("\n")[0][:100]))
        return ("%s — на пустом дереве код 2 без единого слова: третья категория без "
                "причины, создавать условие не по чему" % rel)
    if rc == 0:
        return ("%s — направлена на пустое дерево и вышла нулём: ноль осмотренного "
                "выдан за ноль находок (либо проверка не читает переопределение "
                "корня и судит не то дерево, на которое её направили)" % rel)
    if rc == 1:
        return ("%s — на пустом дереве вышла кодом находки (1): условие не создано, а "
                "объявлено нарушение — ждали «без предмета» (2) с причиной" % rel)
    if rc == "timeout":
        return ("%s — на пустом дереве не уложилась в %d с: исхода нет вовсе"
                % (rel, _lib.TIMEOUT))
    return ("%s — на пустом дереве код %s: вне трёх исходов (0 · 1 · 2), вызывающий его "
            "не прочтёт" % (rel, rc))


def main():
    ws = _lib.root(__file__)
    names, by_suite = _lib.suite_census(NAME, ws)
    total = sum(len(v) for v in by_suite.values())
    if not names:
        _lib.void(NAME, "наборов scripts/*/run-all.sh в %s нет — осматривать нечего" % ws)
        return 2
    if total == 0:
        _lib.void(NAME, "наборов %d, проверок check-* в них 0 — осматривать нечего" % len(names))
        return 2

    empty = _lib.empty_world()
    outcomes = {}
    findings = []
    try:
        env = _lib.world_env(empty)
        for s in names:
            for rel in by_suite[s]:
                rc, out = _lib.run_check_output(ws, rel, empty, env)
                outcomes[rc] = outcomes.get(rc, 0) + 1
                f = verdict(rel, rc, out)
                if f:
                    findings.append(f)
    finally:
        shutil.rmtree(empty, ignore_errors=True)

    _lib.census(NAME, "наборов %d; проверок %d, каждая направлена на пустое дерево; "
                "исходы — %s; находок %d"
                % (len(names), total,
                   ", ".join("код %s: %d" % (k, outcomes[k]) for k in sorted(outcomes, key=str)),
                   len(findings)))
    if findings:
        for f in findings:
            _lib.finding(f)
        _lib.fail(NAME, "проверок, отвечающих на пустом дереве не «без предмета с причиной»: %d"
                  % len(findings))
        return 1
    _lib.passed(NAME, "все %d проверок в %d наборах на пустом дереве отвечают «без предмета» "
                "и называют причину" % (total, len(names)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
