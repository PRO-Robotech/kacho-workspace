#!/usr/bin/env python3
"""check-06 — раздел неисполненного распознан в каждой законной форме, а близнец остаётся полным.

ЗАЧЕМ (ws#1320, возврат check-verifier). Раздел неисполненного — вторая форма частичного
доказательства: строка комментария вне кода, начатая словом «Не» и словом-исходом работы
(`_dod_unmet_line` в `scripts/lib/dod_proof.jq`). Прежнее выражение знало лишь маркер `-`,
`*`, `+`, заголовок и `**`; нумерованный пункт ws#1225 «7. Не сделано здесь: … остаток задачи,
`Refs`.» генератор тела засчитал полным и поставил `Closes`, а «Не покрыто …» не видел вовсе.

ЧТО УТВЕРЖДАЕТ. Таблица ниже — каждая форма начала строки и каждое слово-исход перечня
`_dod_unmet_stems` хотя бы одним случаем; формы взяты из переписи настоящих комментариев
(координата — в метке случая) и из синтетики, где формы в переписи нет. Случай судится
НАСТОЯЩИМ распознавателем дерева одним вызовом `jq` и обоими входами распознавателя, которыми судят
судьи: `dod_proof_marks` (строка-доказательство частичная или полная) и `dod_proof_closes`
(закрывает ли комментарий задачу). Частичная форма обязана дать «частичное, не закрывает»,
законный близнец — «полное, закрывает»: слова посреди строки, ячейка таблицы, цитата,
блок кода, фрагмент кода в начале, «не требуется», проверка, не гонявшаяся здесь (граница
зелёного, а не неисполненный пункт), и нумерованный пункт без «Не».

Генератор тела конец в конец на форме ws#1225 судит `check-01`; здесь — распознаватель:
его мутанты (`inject.sh`, M88–M100) обязаны краснить эту пробу своим случаем.
Коды: 0 — пробы прошли; 1 — проба провалена; 2 — предпосылки нет (jq, распознаватель в дереве).
"""
import json
import os
import shutil
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import _probe as P  # noqa: E402

LIB = os.path.join(P.ROOT, "scripts", "lib")
HEAD = "DoD-proof @aaaaaaa\nкод 0\n"

# (метка, хвост комментария после строки-доказательства, частичное ли).
PARTIAL = (
    ("нумерованный «N.» — форма ws#1225", "1. проба — код 0\n7. Не сделано здесь: остаток задачи, `Refs`."),
    ("нумерованный «N)»", "1) проба — код 0\n2) Не доказано: п.2"),
    ("флажок задачи «- [ ]»", "- [ ] Не закрыто: п.3"),
    ("флажок задачи «- [X]»", "- [X] Не закрыто: п.3"),
    ("вложенный пункт с отступом — форма kaname#747", "- проба\n    - Не покрыто здесь: п. 5, п. 8"),
    ("продолжение пункта отступом", "1. проба — код 0\n   Не сошлось: п.2"),
    ("заголовок «###»", "### Не выполнено: п.2"),
    ("знак перед словом «⛔»", "⛔ Не пройдено — п.4"),
    ("выделение после слова «**Не**» — форма kaname#853", "**Не** починены здесь: K2"),
    ("выделение «*…*»", "*Не выполнено:* п.2"),
    ("выделение «__…__»", "__Не исполнено:__ п.2"),
    ("регистр «- НЕ пройдено» — форма kacho#3061", "- НЕ пройдено — п.4: браузерные пробы"),
    ("регистр «НЕ ВЫПОЛНЕНО»", "НЕ ВЫПОЛНЕНО: п.2"),
    ("строка без маркера — форма kaname#916", "\nНе сошлось (предикат задачи): п.2"),
    ("выделение «**…:**» — форма kacho#3229", "**Не доказано этим комментарием:** церемония"),
    ("маркер «-» строчным — форма kacho#3230", "- не выполнилось, условие не создано — 2"),
)
FULL = (
    ("нумерованный пункт без «Не»", "1. проба — код 0\n2. всё сделано"),
    ("цитата «>»", "> Не сошлось: цитата чужого"),
    ("ячейка таблицы", "| Не сошлось | п.2 |"),
    ("блок кода", "```\nНе сошлось: вывод чужого прогона\n```"),
    ("слова посреди строки", "всё сошлось; не исполнено лишнего ничего"),
    ("«не требуется» — форма kaname#833", "Не сделано и не требуется предикатом: кнопка"),
    ("фрагмент кода в начале", "- `**` не сошлось с образцом → отказ PF-BOLD"),
    ("проверка, не гонявшаяся здесь — форма kaname#725", "Не проверялось здесь: -race — конвейер PR"),
    ("нумерованный пункт с границей зелёного", "7. Не проверялось здесь: стенд"),
    ("регистр с границей зелёного — форма kaname#197", "НЕ гонялось локально: детектор гонок"),
)

PROGRAM = ('include "dod_proof"; [.[] | . as $b | {partial: ([dod_proof_marks[].partial] | any),'
           ' closes: ([{body: $b}] | dod_proof_closes)}]')


def body(pr):
    if shutil.which("jq") is None:
        raise P.Void("нет jq — распознаватель не исполнить")
    if not os.path.isfile(os.path.join(LIB, "dod_proof.jq")):
        raise P.Void("нет %s — распознавателя в дереве нет" % os.path.join(LIB, "dod_proof.jq"))
    cases = [(label, tail, True) for label, tail in PARTIAL] + [(label, tail, False) for label, tail in FULL]
    texts = [HEAD + tail for _, tail, _ in cases]
    p = subprocess.run(["jq", "-c", "-L", LIB, PROGRAM], input=json.dumps(texts, ensure_ascii=False),
                       capture_output=True, text=True)
    if p.returncode != 0:
        pr.ok("распознаватель исполнен", False, "jq код %d: %s" % (p.returncode, p.stderr))
        return
    got = json.loads(p.stdout)
    if len(got) != len(cases):
        pr.ok("ответов распознавателя столько же, сколько случаев", False, p.stdout)
        return
    for (label, tail, want), res in zip(cases, got):
        if want:
            pr.ok("частичное: %s" % label, res["partial"] and not res["closes"],
                  "получено %s на «%s»" % (res, tail))
        else:
            pr.ok("близнец, полное: %s" % label, not res["partial"] and res["closes"],
                  "получено %s на «%s»" % (res, tail))


if __name__ == "__main__":
    sys.exit(P.main("check-06-dod-unmet-forms", body))
