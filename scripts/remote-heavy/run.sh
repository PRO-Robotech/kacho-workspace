    if [ $(( $(now) - T0 )) -ge "$WAIT_START_S" ]; then
        say "pod не готов принять исходники за $WAIT_START_S с${SCHED:+: $SCHED}${WAITR:+ ($WAITR)} — не выполнилось"; exit 75
