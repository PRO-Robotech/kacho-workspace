# install.sh — провязать хуки этого дерева в клон и сказать, провязаны ли они.
#   bash scripts/hooks/install.sh [install | check | notice]
#
# ПОЧЕМУ НЕ `core.hooksPath`. Одна строка настройки выглядит проще всего и имеет
# цену, которую видно не сразу: git начинает искать хуки ТОЛЬКО по указанному
# пути, и всё, что уже лежит в `.git/hooks`, перестаёт исполняться — молча, без
# единого сообщения. И второе, решающее: ревизию, в которой хука нет, git при
# такой настройке ПРОПУСКАЕТ МОЛЧА — отказать ему нечем, потому что между git и
# хуком никого нет. Поэтому настройка здесь не поддерживается вовсе: выставленная,
# она даёт отказ установщика с названной причиной, а не «исполняется напрямую».
#
# Поэтому в `.git/hooks` кладётся ПЕРЕХОДНИК: короткий файл, который находит
# рабочую копию и исполняет отслеживаемый скрипт из неё. Следствия названы, чтобы
# их не пришлось выяснять:
#
#   · посторонние хуки продолжают работать — переходник ставится только под
#     своим именем, чужой файл не затирается НИКОГДА (это отказ, а не перезапись);
#   · переходник берёт скрипт из ТОЙ рабочей копии, из которой идёт операция,
#     поэтому в worktree исполняется его собственная версия хука;
#   · путей машины в переходнике нет — переезд клона его не ломает (настроенный
#     абсолютный путь, переживший переезд, — наблюдавшийся отдельный класс:
#     настройка указывает в никуда и при этом выглядит настроенной);
#   · цена: новый отслеживаемый хук требует повторного `install`. Цена
#     наблюдаемая, а не молчаливая, — её называет `check`.
#
# ПЕРЕХОДНИК, НЕ НАШЕДШИЙ АДРЕСАТА, ОТКАЗЫВАЕТ (v2, ws#751). Первая редакция (v1)
# печатала «проверок НЕ БЫЛО» и выходила УСПЕХОМ. Провязка выглядела исполненной,
# а отправка проходила при нуле проверок в трёх клонах из трёх; в этом клоне —
# переходник `commit-msg`, заведённый чужой веткой, звал несуществующий в стволе
# скрипт и молча пропускал каждый коммит. Отсутствие адресата — «условие не
# создано», и в успех оно не засчитывается: переходник выходит 1 с этой причиной,
# а законный обход один и явный — `--no-verify` той команды, которую он охраняет.
# Условие зависит от РЕВИЗИИ рабочей копии, а не от клона: переходник общий для
# всех worktree, адресат — у каждой свой, и ревизия, предшествующая появлению
# хука, получает отказ, а не молчаливый пропуск.
#
# ИМЕНА ХУКОВ ТОЧКИ НЕ СОДЕРЖАТ. Отсюда правило отбора: в `scripts/hooks` хуком
# считается отслеживаемый файл, в имени которого нет точки. Этот скрипт под
# правило не подпадает и хуком не станет.
#
# Способность упасть доказана `scripts/push-gate/check-01-hook-stub-refuses-without-target.sh`
# (песочница с bare-«сервером»), его собственная — `scripts/push-gate/inject.sh`.
set -uo pipefail

mode="${1:-install}"

die() { printf '%s\n' "$@" >&2; exit 1; }

root="$(git rev-parse --show-toplevel 2>/dev/null)" ||
    die "install-hooks: это не рабочая копия git — провязывать не во что."
common="$(git rev-parse --git-common-dir 2>/dev/null)" ||
    die "install-hooks: git не назвал общий каталог репозитория."
case "$common" in /*) ;; *) common="$root/$common" ;; esac

src="$root/scripts/hooks"
dst="$common/hooks"

# Отслеживаемые хуки. `git ls-files` — то же множество, что увидит свежий клон:
# файл, лежащий на диске и не добавленный в индекс, провязывать нечестно.
hooks=()
while IFS= read -r rel; do
    base="${rel##*/}"
    case "$base" in *.*) continue ;; esac
    hooks+=("$base")
done < <(git -C "$root" ls-files scripts/hooks)

# Пустой обход — отказ, а не «нечего делать»: он означал бы зелёный вывод при
# непровязанном клоне. Объявляется ПОСЛЕ переписи переходников (раздел 2): в
# ревизии без единого хука наш переходник под снятым именем остаётся лежать, и
# отказ обязан назвать и его, а не только пустоту.

# Маркер несёт ВЕРСИЮ: переходник прежней редакции — наш (перезаписывается и
# снимается установщиком), но ведёт себя иначе, и `check` обязан его назвать.
marker_prefix="kacho-hook-stub v"
marker="${marker_prefix}2"

stub_version() {  # <файл> → номер версии нашего переходника либо пусто
    local line
    line="$(grep -o "${marker_prefix}[0-9][0-9]*" "$1" 2>/dev/null | head -1)"
    printf '%s' "${line#"$marker_prefix"}"
}

# ── 1. Куда git на самом деле смотрит ────────────────────────────────────────
#
# Выставленный `core.hooksPath` перебивает `.git/hooks` целиком, а ревизию без
# хука git при нём пропускает молча (шапка). Любое значение — отказ всех режимов:
# и провязки, и проверки. Молчать нельзя в обе стороны: переходники легли бы туда,
# куда никто не заглядывает, а «исполняется напрямую» есть fail-open by construction.
configured="$(git config --get core.hooksPath 2>/dev/null || true)"
if [ -n "$configured" ]; then
    die "ОТКАЗ: core.hooksPath = «$configured»." \
        "" \
        "При этой настройке git ищет хуки ТОЛЬКО там, а ревизию, в которой хука нет," \
        "пропускает МОЛЧА: отказать некому, переходника между git и хуком нет. Это" \
        "тот же молчаливый пропуск, который снят у переходника (ws#751)." \
        "" \
        "  git config --unset core.hooksPath   # затем: bash scripts/hooks/install.sh install"
fi

# ── 2. Состояние переходников ───────────────────────────────────────────────
mkdir -p "$dst" || die "install-hooks: не создать $dst"

# bypass_for <хук> — законный обход, который называет отказ. `--no-verify`
# снимает ровно эти хуки; у прочих обхода нет, и это сказано, а не выдумано.
bypass_for() {
    case "$1" in
        pre-push)                  echo "git push --no-verify" ;;
        pre-commit|commit-msg)     echo "git commit --no-verify" ;;
        pre-merge-commit)          echo "git merge --no-verify" ;;
        *)                         echo "законного обхода у этого хука нет — верните адресата" ;;
    esac
}

stub_for() {
    local bypass; bypass="$(bypass_for "$1")"
    cat <<STUB
#!/usr/bin/env bash
# СГЕНЕРИРОВАН scripts/hooks/install.sh — правится НЕ здесь, а в scripts/hooks/$1.
# $marker
set -uo pipefail
top="\$(git rev-parse --show-toplevel 2>/dev/null)" || top=""
[ -n "\$top" ] || top="\$PWD"
real="\$top/scripts/hooks/$1"
if [ ! -f "\$real" ] || [ ! -x "\$real" ]; then
    {
        echo "$1: ОТКАЗ — условие не создано: адресата нет (\$real)."
        echo "  В этой ревизии рабочей копии хука $1 нет либо он не исполним, поэтому"
        echo "  проверок НЕ было ни одной — и операция остановлена: молчаливый пропуск"
        echo "  здесь неотличим от прохода."
        echo "  Обход только явный, и он называется в отчёте: $bypass"
    } >&2
    exit 1
fi
exec "\$real" "\$@"
STUB
}

wired=0
missing=()     # адресат отслеживается, переходника нет либо он не исполним
stale=()       # переходник наш, но прежней редакции (v1 выходит успехом без адресата)
foreign=()     # под именем хука лежит чужой файл
orphans=()     # наш переходник под именем, которого в дереве нет
not_exec=()    # адресат отслеживается, но в рабочей копии не исполним
for name in "${hooks[@]+"${hooks[@]}"}"; do
    target="$dst/$name"
    [ -x "$src/$name" ] || not_exec+=("$name")
    if [ ! -e "$target" ]; then
        missing+=("$name")
        continue
    fi
    v="$(stub_version "$target")"
    if [ -z "$v" ]; then
        foreign+=("$name")
    elif [ "$v" != "2" ]; then
        stale+=("$name (v$v)")
    elif [ ! -x "$target" ]; then
        missing+=("$name")
    else
        wired=$((wired + 1))
    fi
done

# Посторонние хуки, которых мы не предоставляем, — их провязка не касается, и
# сказать это надо прямо: именно ради их сохранности выбран переходник. НАШ
# переходник под чужим именем посторонним НЕ является: его адресата в дереве нет,
# и прежняя редакция называла его «посторонним» — ровно так в этом клоне прожил
# переходник `commit-msg`, молча пропускавший каждый коммит.
kept=()
for f in "$dst"/*; do
    [ -e "$f" ] || continue
    b="${f##*/}"
    case "$b" in *.sample) continue ;; esac
    ours=0
    for name in "${hooks[@]+"${hooks[@]}"}"; do [ "$b" = "$name" ] && ours=1; done
    [ "$ours" = 1 ] && continue
    v="$(stub_version "$f")"
    if [ -n "$v" ]; then
        orphans+=("$b (v$v)")
    else
        kept+=("$b")
    fi
done

no_hooks() {
    if [ "${#hooks[@]}" -eq 0 ]; then
        echo "ОТКАЗ: в scripts/hooks нет НИ ОДНОГО отслеживаемого хука — провязывать нечего," >&2
        echo "  а зелёный вывод здесь означал бы непровязанный клон." >&2
        return 0
    fi
    return 1
}

# report — ДВА состояния на каждый хук, а не одно (ws#729 п.3): «переходник
# есть» и «адресат исполним». Зелёное — только когда верно и то и другое.
report() {
    local name st_stub st_real v
    for name in "${hooks[@]+"${hooks[@]}"}"; do
        if [ -e "$dst/$name" ]; then
            v="$(stub_version "$dst/$name")"
            if [ -z "$v" ]; then st_stub="ЧУЖОЙ файл"
            elif [ "$v" != 2 ]; then st_stub="переходник v$v (устаревший)"
            elif [ -x "$dst/$name" ]; then st_stub="переходник v2 есть"
            else st_stub="переходник v2 НЕ исполним"
            fi
        else
            st_stub="переходника НЕТ"
        fi
        if [ -x "$src/$name" ]; then st_real="адресат исполним"; else st_real="адресат НЕ исполним"; fi
        echo "  $name: $st_stub · $st_real (scripts/hooks/$name)"
    done
    echo "хуки: провязано $wired из ${#hooks[@]} ($dst)"
    [ "${#kept[@]}" -eq 0 ] ||
        printf 'посторонних хуков оставлено нетронутыми: %s\n' "${kept[*]}"
}

refusals() {  # печатает отказы режима check; код — число причин
    local n=0
    no_hooks && n=$((n + 1))
    if [ "${#foreign[@]}" -gt 0 ]; then
        echo "ОТКАЗ: под именем хука лежит ЧУЖОЙ файл: ${foreign[*]}" >&2
        echo "  Он не перезаписывается — уберите его сами либо слейте с scripts/hooks/<имя>." >&2
        n=$((n + 1))
    fi
    if [ "${#missing[@]}" -gt 0 ]; then
        echo "ОТКАЗ: не провязаны: ${missing[*]}" >&2
        echo "  Операция НЕ проверяется локально: конвейер станет первым читателем." >&2
        n=$((n + 1))
    fi
    if [ "${#stale[@]}" -gt 0 ]; then
        echo "ОТКАЗ: переходник прежней редакции: ${stale[*]}" >&2
        echo "  v1 без адресата выходит УСПЕХОМ («проверок НЕ БЫЛО», код 0) — перепровяжите." >&2
        n=$((n + 1))
    fi
    if [ "${#orphans[@]}" -gt 0 ]; then
        echo "ОТКАЗ: наш переходник без адресата в дереве: ${orphans[*]}" >&2
        echo "  Хука с этим именем в scripts/hooks НЕТ: v1 пропускает операцию молча," >&2
        echo "  v2 отказывает каждой. Снимается провязкой: bash scripts/hooks/install.sh install" >&2
        n=$((n + 1))
    fi
    if [ "${#not_exec[@]}" -gt 0 ]; then
        echo "ОТКАЗ: адресат не исполним в этой рабочей копии: ${not_exec[*]}" >&2
        echo "  Переходник откажет каждой операции; бит исполнения — в индексе: git update-index --chmod=+x" >&2
        n=$((n + 1))
    fi
    return "$n"
}

case "$mode" in
check)
    report
    refusals && exit 0
    echo "  bash scripts/hooks/install.sh install" >&2
    exit 1
    ;;
notice)
    # Тихий режим для чужих целей: он ничего не роняет и говорит ровно тогда,
    # когда сказать есть о чём. Молчание означает «провязано» — положительное
    # утверждение печатает `check`, а не каждый прогон тестов.
    if [ "${#hooks[@]}" -eq 0 ] || [ "${#missing[@]}" -gt 0 ] || [ "${#foreign[@]}" -gt 0 ] ||
       [ "${#stale[@]}" -gt 0 ] || [ "${#orphans[@]}" -gt 0 ]; then
        echo "ВНИМАНИЕ: хуки git провязаны не так, как требует дерево (${#missing[@]} не провязано, ${#foreign[@]} занято чужим, ${#stale[@]} устаревших, ${#orphans[@]} без адресата)." >&2
        echo "  Подробно: bash scripts/hooks/install.sh check · чинит: bash scripts/hooks/install.sh install" >&2
    fi
    exit 0
    ;;
install) ;;
*) die "install-hooks: неизвестный режим «$mode» (install | check | notice)" ;;
esac

# ── 3. Провязка ─────────────────────────────────────────────────────────────
if [ "${#foreign[@]}" -gt 0 ]; then
    die "ОТКАЗ: под именем хука уже лежит ЧУЖОЙ файл: ${foreign[*]}" \
        "" \
        "Он НЕ перезаписывается: чужой хук мог быть заведён осознанно, и его тихая" \
        "пропажа — тот самый класс, ради которого здесь не выставляется core.hooksPath." \
        "Уберите файл сами либо слейте его с scripts/hooks/<имя>, затем повторите."
fi

# Наши переходники без адресата снимаются: маркер доказывает, что файл
# сгенерирован этим установщиком, а не заведён человеком. Их хука в дереве этой
# ревизии нет, и оставить их значило бы оставить молчаливый пропуск (v1) либо
# отказ каждой операции (v2) — ни то ни другое не провязка.
removed=()
for entry in "${orphans[@]+"${orphans[@]}"}"; do
    b="${entry%% *}"
    rm -f "$dst/$b" && removed+=("$b")
done
orphans=()

if no_hooks; then
    [ "${#removed[@]}" -eq 0 ] ||
        printf 'сняты наши переходники без адресата в дереве: %s\n' "${removed[*]}" >&2
    exit 1
fi

installed=()
for name in "${hooks[@]+"${hooks[@]}"}"; do
    target="$dst/$name"
    stub_for "$name" > "$target" || die "install-hooks: не записать $target"
    chmod +x "$target" || die "install-hooks: не сделать исполняемым $target"
    installed+=("$name")
done

wired=${#installed[@]}
stale=(); missing=()
report
printf 'провязаны переходниками v2: %s\n' "${installed[*]}"
[ "${#removed[@]}" -eq 0 ] ||
    printf 'сняты наши переходники без адресата в дереве: %s\n' "${removed[*]}"
echo "проверить в любой момент: bash scripts/hooks/install.sh check"
