# Прогон набора push-gate — механизм отправки воркспейса, судимый поведением
# (переходники хуков, суждение по отправляемому диапазону, выведение соседних
# домов, постусловие отправки, знаменатель доказательства сохранности).
#
# Вердикт стоит в КОДЕ ВЫХОДА. Три исхода, а не два:
#   0 — исполнено N, находок 0, у каждой проверки был предмет;
#   1 — НАХОДКА: проверка упала, либо обход пуст (о дереве не прочитано ничего);
#   2 — БЕЗ ПРЕДМЕТА: находок нет, но часть проверок не с чем было сверять.
# Находка объявляется ПЕРВОЙ: набор, где есть и находка, и беспредметная
# проверка, выходит единицей — иначе «без предмета» стало бы маской.
set -uo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

ok=0; bad=0; void=0; ran=0
for check in "$here"/check-*.sh; do
    [ -f "$check" ] || continue
    ran=$((ran + 1))
    bash "$check" </dev/null
    case $? in
        0) ok=$((ok + 1)) ;;
        2) void=$((void + 1)) ;;
        *) bad=$((bad + 1)) ;;
    esac
done

if [ "$ran" -eq 0 ]; then
    echo "[FAIL] push-gate — ни одной проверки не найдено в $here; о механизме отправки не прочитано ничего" >&2
    exit 1
fi

echo "push-gate: рассмотрено проверок $ran; пройдено $ok, провалено $bad, без предмета $void"

if [ "$bad" -gt 0 ]; then
    echo "[FAIL] push-gate — набор красный: находок $bad" >&2
    exit 1
fi
if [ "$void" -gt 0 ]; then
    echo "[VOID] push-gate — без предмета $void из $ran; находок нет, но эти проверки не выполнялись" >&2
    exit 2
fi
echo "[PASS] push-gate — исполнено $ran, все зелёные"
