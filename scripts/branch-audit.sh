# --- ПЯТЫЙ ПРИЗНАК: дельта слияния во временной копии -------------------------
# Сливает ветку в ствол БЕЗ рабочей копии и БЕЗ индекса (`merge-tree --write-tree`
# пишет только объекты) и сравнивает получившееся дерево с деревом ствола.
# Равны ⇒ ветка не добавляет стволу ничего ⇒ её содержимое уже там, каким бы
# способом оно туда ни попало.
# Конфликт (ненулевой код) означает, что ветка несёт изменения, которых в стволе
# нет, — то есть «не пусто», а не «неизвестно».
merge_delta_empty() { # $1 = ref → 0 если дельта пуста
  local ref=$1 out
  out=$(git merge-tree --write-tree "$TRUNK" "$ref" 2>/dev/null) || return 1
  [ "$(printf '%s\n' "$out" | head -1)" = "$TRUNK_TREE" ]
}

# --- ШЕСТОЙ ПРИЗНАК -----------------------------------------------------------
# Печатает пути, содержимое которых не найдено НИ В ОДНОМ стволе. Пустой вывод ⇒
# ветка поглощена (снимать безопасно). Непустой ⇒ отсутствие доказательства
# поглощения — НЕ доказательство потери: судит человек по именам.
#
# Асимметрия названа намеренно. Никакой из двух проверок по отдельности верить
# нельзя: (а) ложно отрицает на файле, который ствол правил после вливания;
# (б) молчит, когда PR правился по ревью. Вместе они закрывают обе дыры, и
# именно поэтому объединяются, а не выбираются.
#
# ИМЕНА ПЕЧАТАЮТСЯ, СПИСОК НЕ ФИЛЬТРУЕТСЯ. Перечень «снимать нельзя» без состава
# — стена из имён, и человек, которому нечем отличить сданную работу от
# сгенерированной строки указателя, перестаёт его читать. Замер 2026-08-16 на
# воркспейсе: из 24 веток с непустой дельтой у 14 она состояла ТОЛЬКО из
# машинно-собираемого obsidian/kacho/INDEX.md, то есть авторской работы в них не
# было вовсе. Подавлять «заведомо генерируемые» пути нельзя: это маска, которая
# однажды скроет настоящую работу. Судит человек — по именам.
# Нормализация строки для переписи: обрезать поля, выбросить пустые, оставить
# различимые. Сравниваются МНОЖЕСТВА строк, а не порядок: порядок в файле мог
# законно поменяться при переработке, и требовать его значило бы объявлять
# находкой перестановку.
# Считаются МУЛЬТИМНОЖЕСТВА, а не множества: `sort -u` схлопывал повторы, и ветка,
# добавившая ДВА экземпляра строки, которая в стволе есть в одном, читалась как
# поглощённая. `comm` сравнивает повторы попарно — надо лишь не отбрасывать
# кратность при нормализации.
#
# ЧЕСТНАЯ ГРАНИЦА ЭТОГО УСИЛЕНИЯ: оно НЕ делает перепись доказательством. Она
# сверяет ДОБАВЛЕННЫЕ веткой строки со стволовым файлом, поэтому строка, добавленная
# в единственном экземпляре, находится в стволе всегда, если такая строка там уже
# есть где угодно, — а обычная правка кода («пропущенная проверка ошибки») из таких
# строк и состоит целиком. Проверено инъекцией W: такая ветка даёт «отсутствует 0»
# и всё равно НЕ становится влитой — её удерживает седьмой признак и запрет
# переписи влиять на снятие, а не кратность.
ba_norm() { sed 's/^[[:space:]]*//;s/[[:space:]]*$//' | grep -v '^$' | LC_ALL=C sort; }

# --- ТРЕТИЙ ЗАМЕР ФАЙЛА (6в): ПОСТРОЧНАЯ ПЕРЕПИСЬ -----------------------------
# (6а) и (6б) сравнивают БАЙТЫ: первая — весь патч файла, вторая — весь блоб.
# Обе молчат, как только ствол правил файл после вливания хотя бы одной строкой,
# — а это штатный ход событий, а не редкость. Перепись спрашивает о СОДЕРЖИМОМ:
#
#   * каждая непустая строка, которую ветка ДОБАВИЛА, обязана найтись в
#     стволовой версии файла;
#   * ни одна непустая строка, которую ветка СНЯЛА, не имеет права в ней уцелеть.
#
# Вторая половина не украшение: без неё ветка, чья работа — удаление, объявлялась
# бы поглощённой при живом удалённом коде, то есть перепись молча санкционировала
# бы снятие ветки, чью работу ствол не принял.
#
# Файла может не быть в стволе по ЭТОМУ пути — реализация переезжает в другой
# каталог. Тогда целью переписи берётся файл с тем же именем; путь цели
# печатается, чтобы подстановка была видна, а не подразумевалась.
CENSUS_ADD=0; CENSUS_MISS=0; CENSUS_DEL=0; CENSUS_STAY=0; CENSUS_TARGET=""
CENSUS_MOVED=0
census_file() { # $1=ref $2=base $3=путь → 0, если содержимое найдено в стволе
  local ref=$1 base=$2 f=$3 tr bn cand target miss stay best=-1
  CENSUS_ADD=0; CENSUS_MISS=0; CENSUS_DEL=0; CENSUS_STAY=0; CENSUS_TARGET=""
  # CENSUS_MOVED=1 означает: содержимое найдено НЕ по тому пути, по которому его
  # писала ветка, — то есть реализация переехала. Это единственный законный способ
  # для содержимого попасть в ствол, не тронув исходный путь, и потому он обязан
  # быть отличим от «нашлось там же».
  CENSUS_MOVED=0

  git diff "$base" "$ref" -- "$f" > "$PATCH_TMP" 2>/dev/null || return 1
  grep '^+' "$PATCH_TMP" | grep -v '^+++' | sed 's/^+//' | ba_norm > "$BA_TMP/c.add" || true
  grep '^-' "$PATCH_TMP" | grep -v '^---' | sed 's/^-//' | ba_norm > "$BA_TMP/c.del" || true
  CENSUS_ADD=$(grep -c . "$BA_TMP/c.add" || true)
  CENSUS_DEL=$(grep -c . "$BA_TMP/c.del" || true)

  for tr in "${TRUNKS[@]}"; do
    target=""
    if git cat-file -e "$tr:$f" 2>/dev/null; then
      target="$tr:$f"
    else
      bn=${f##*/}
      cand=$(git ls-tree -r --name-only "$tr" 2>/dev/null | grep -- "/${bn}$" | head -1 || true)
      [ -n "$cand" ] && target="$tr:$cand"
    fi
    [ -n "$target" ] || continue
    git show "$target" 2>/dev/null | ba_norm > "$BA_TMP/c.tr" || true
    # LC_ALL=C и здесь, и в ba_norm: сортировка и сравнение обязаны идти в ОДНОЙ
    # раскладке, иначе comm объявляет вход неотсортированным и молча врёт.
    miss=$(LC_ALL=C comm -23 "$BA_TMP/c.add" "$BA_TMP/c.tr" | grep -c . || true)
    stay=$(LC_ALL=C comm -12 "$BA_TMP/c.del" "$BA_TMP/c.tr" | grep -c . || true)
    if [ "$miss" -eq 0 ] && [ "$stay" -eq 0 ]; then
      CENSUS_MISS=0; CENSUS_STAY=0; CENSUS_TARGET="$target"
      [ "$target" = "$tr:$f" ] || CENSUS_MOVED=1
      return 0
    fi
    if [ "$best" -lt 0 ] || [ "$miss" -lt "$best" ]; then
      best=$miss; CENSUS_MISS=$miss; CENSUS_STAY=$stay; CENSUS_TARGET="$target"
    fi
  done

  if [ "$best" -lt 0 ]; then
    CENSUS_MISS=$CENSUS_ADD; CENSUS_STAY=0; CENSUS_TARGET="файла нет ни в одном стволе"
  fi
  return 1
}

# --- СЕДЬМОЙ ПРИЗНАК: касался ли ствол ПУТИ после ответвления -----------------
# Не о содержимом, а о возможности. Если ни один ствол этого пути после
# ответвления не касался, содержимое ветки туда попасть НЕ МОГЛО — непоглощение
# доказано. Если касался, то отличить ранний черновик от второго предмета
# содержанием нельзя, и вердикт обязан быть назван неустановленным, а не выдан
# за находку.
trunk_touched_path() { # $1=ref $2=путь → 0, если хоть один ствол касался пути
  local ref=$1 f=$2 tr b2
  for tr in "${TRUNKS[@]}"; do
    b2=$(git merge-base "$tr" "$ref" 2>/dev/null) || continue
    [ -n "$(git log --format=%H "$b2".."$tr" -- "$f" 2>/dev/null | head -1)" ] && return 0
  done
  return 1
}

# --- КЛАССИФИКАЦИЯ ФАЙЛОВ ВЕТКИ ----------------------------------------------
# Заполняет два массива вместо прежнего единственного списка «не поглощено»:
#   UNABS_PROVEN — непоглощение ДОКАЗАНО (ствол пути не касался);
#   UNABS_UNDET  — поглощение НЕ УСТАНОВЛЕНО (ствол путь правил, байты разошлись,
#                  перепись нашла отсутствующие строки).
# Разделение — предмет задачи #257: один предикат обслуживал два вопроса с
# противоположным направлением риска, и вопрос «пропала ли работа» получал
# строгость, отмеренную для вопроса «безопасно ли снимать».
# Первые три элемента списка — БЕЗ труб. `printf … | head -3` под `pipefail`
# роняет производителя сигналом обрыва, и вердикт всего прогона становится
# недействительным ровно тогда, когда список длинный, то есть когда он и нужен.
first3() { # $@ = элементы → строка из первых трёх, с многоточием если их больше
  local out="" n=0 e
  for e in "$@"; do
    n=$((n + 1))
    if [ "$n" -gt 3 ]; then out="$out…"; break; fi
    out="$out$e; "
  done
  printf '%s' "$out"
}

GEN_SKIPPED=0
UNABS_PROVEN=(); UNABS_UNDET=()
classify_files() { # $1 = ref → заполняет UNABS_PROVEN и UNABS_UNDET
  local ref=$1 base f bb tr found info
  UNABS_PROVEN=(); UNABS_UNDET=()

  for tr in "${TRUNKS[@]}"; do
    [ -n "${TRUNK_IDX[$tr]+x}" ] || continue
    base=$(git merge-base "$tr" "$ref" 2>/dev/null) || continue
    # Дешёвая проверка целиком: кумулятивный патч ложится обратно ⇒ поглощено
    # всё сразу, пофайлово ходить незачем.
    if git diff "$base" "$ref" > "$PATCH_TMP" 2>/dev/null; then
      [ -s "$PATCH_TMP" ] || return 0
      if GIT_INDEX_FILE="${TRUNK_IDX[$tr]}" git apply --cached -R --check "$PATCH_TMP" 2>/dev/null; then
        return 0
      fi
    fi
  done

  base=$(git merge-base "$TRUNK" "$ref" 2>/dev/null) || return 0
  while read -r f; do
    [ -n "$f" ] || continue
    git diff "$base" "$ref" -- "$f" > "$PATCH_TMP" 2>/dev/null || continue
    [ -s "$PATCH_TMP" ] || continue
    bb=$(git rev-parse "$ref:$f" 2>/dev/null || true)
    found=0
    for tr in "${TRUNKS[@]}"; do
      [ -n "${TRUNK_IDX[$tr]+x}" ] || continue
      if GIT_INDEX_FILE="${TRUNK_IDX[$tr]}" git apply --cached -R --check "$PATCH_TMP" 2>/dev/null; then
        found=1; break
      fi
      if [ -n "$bb" ] &&
         [ -n "$(git log "$tr" --format=%H --find-object="$bb" -- "$f" 2>/dev/null | head -1)" ]; then
        found=1; break
      fi
    done
    [ "$found" = 1 ] && continue

    census_asked=$((census_asked + 1))
    census_ok=0
    census_file "$ref" "$base" "$f" && census_ok=1
    if [ "$census_ok" = 1 ]; then census_found=$((census_found + 1)); fi

    info="добавлено ${CENSUS_ADD}, отсутствует ${CENSUS_MISS}; снято ${CENSUS_DEL}, уцелело ${CENSUS_STAY}"

    # ПОРЯДОК ЗДЕСЬ — СУЩЕСТВО, А НЕ СТИЛЬ. Первым спрашивается седьмой признак
    # (возможность), и только потом перепись (содержимое). Обратный порядок уже
    # давал дефект: ветка, добавившая второй экземпляр строк, которые в стволе
    # есть в одном, объявлялась поглощённой по содержимому — притом что ствол
    # этого пути не касался вовсе и попасть туда её работа не могла.
    # Машинно собираемый файл авторской работы не несёт: его дельта — свойство
    # генератора, а не ветки. Отсев СЧИТАЕТСЯ и печатается, иначе он был бы
    # неотличим от «находок не было».
    if is_generated "$f"; then
      GEN_SKIPPED=$((GEN_SKIPPED + 1))
      continue
    fi
    if trunk_touched_path "$ref" "$f"; then
      if [ "$census_ok" = 1 ]; then
        UNABS_UNDET+=("$f ($info; содержимое найдено построчно в ${CENSUS_TARGET}, но НЕ побайтово — ствол этот путь ПРАВИЛ)")
      else
        UNABS_UNDET+=("$f ($info; ствол этот путь ПРАВИЛ — ранний черновик и второй предмет содержанием неразличимы)")
      fi
    elif [ "$census_ok" = 1 ] && [ "$CENSUS_MOVED" = 1 ]; then
      # Единственный законный способ попасть в ствол, не тронув исходный путь, —
      # переезд реализации. Он подтверждается ТЕМ, ЧТО содержимое найдено по
      # ДРУГОМУ пути, а не тем, что оно нашлось хоть где-то.
      UNABS_UNDET+=("$f ($info; содержимое найдено по другому пути ${CENSUS_TARGET} — похоже на переезд реализации)")
    else
      UNABS_PROVEN+=("$f ($info; ствол этот путь после ответвления НЕ ТРОГАЛ — попасть туда содержимое не могло)")
    fi
  done < <(git diff --name-only "$base" "$ref" 2>/dev/null)
  return 0
}

absorbed_where() { # $1 = ref → печатает имя ствола, поглотившего ветку, либо пусто
  local ref=$1 tr out
  for tr in "${TRUNKS[@]}"; do
    out=$(git merge-tree --write-tree "$tr" "$ref" 2>/dev/null) || continue
    if [ "$(printf '%s\n' "$out" | head -1)" = "$(git rev-parse "$tr^{tree}")" ]; then
      printf '%s' "$tr"; return 0
    fi
  done
  return 0
}

fresh_mark() { # $1 = ref → метка, если ветка двигалась только что
  local ref=$1 ct age_min
  ct=$(git log -1 --format=%ct "$ref" 2>/dev/null || echo 0)
  age_min=$(( (NOW - ct) / 60 ))
  if [ "$ct" -gt 0 ] && [ "$age_min" -lt "$FRESH_MIN" ]; then
    printf ' [ДВИЖЕТСЯ: коммит %s мин назад]' "$age_min"
  fi
}

merged_local=(); orphan_remote=(); only_local=(); alive=(); split_work=(); prunable=()
undet_work=()
examined_local=0; examined_remote=0; delta_checked=0
sixth_checked=0; sixth_rescued=0
census_asked=0; census_found=0

# --- локальные ветки ----------------------------------------------------------
while read -r b; do
  [ "$b" = "${TRUNK#origin/}" ] && continue
  examined_local=$((examined_local + 1))

  on_origin=0
  [ -n "${ON_ORIGIN[$b]+x}" ] && on_origin=1

  ancestor=0
  git merge-base --is-ancestor "$b" "$TRUNK" 2>/dev/null && ancestor=1
  ahead=$(git rev-list --count "$TRUNK".."$b" 2>/dev/null || echo 0)

  empty=1; how=""
  UNABS_PROVEN=(); UNABS_UNDET=()
  delta_checked=$((delta_checked + 1))
  if [ "$ancestor" = 1 ]; then
    how="предок ствола"
  else
    src=$(absorbed_where "$b")
    if [ -n "$src" ]; then
      how="ДЕЛЬТА СЛИЯНИЯ ПУСТА относительно $src"
    else
      # Пятый признак сказал «конфликт» — а это не вердикт. Спрашиваем шестой,
      # а там, где и он молчит, — признак касания пути (7) и перепись (6в).
      #
      # ВЛИТОЙ ветку делают ТОЛЬКО байтовые признаки. Перепись сюда не входит и
      # входить не может: она — свидетельство, а не доказательство, и цена её
      # ошибки в эту сторону необратима (`--prune-merged` снимает ссылку). Её
      # работа — снять ТРЕВОГУ там, где тревожиться не о чем, и назвать числа.
      sixth_checked=$((sixth_checked + 1))
      classify_files "$b"
      if [ "${#UNABS_PROVEN[@]}" -eq 0 ] && [ "${#UNABS_UNDET[@]}" -eq 0 ]; then
        how="ПОГЛОЩЕНА ПОФАЙЛОВО (шестой признак, побайтово; пятый дал конфликт)"
        sixth_rescued=$((sixth_rescued + 1))
      else
        empty=0
      fi
    fi
  fi

  occ=""; [ -n "${OCCUPIED[$b]+x}" ] && occ=" [ЗАНЯТА рабочей копией: ${OCCUPIED[$b]}]"
  pr=""; [ -n "${PRSTATE[$b]+x}" ] && pr=" ${PRSTATE[$b]}"
  fresh=$(fresh_mark "$b")

  if [ "$empty" = 1 ]; then
    if [ "$ancestor" = 1 ] && [ "$ahead" = 0 ]; then
      merged_local+=("$b — $how${pr}${occ}${fresh}")
    else
      merged_local+=("$b — +$ahead коммит(ов), но $how${pr}${occ}${fresh}")
    fi
    prunable+=("$b")
  elif [ "$on_origin" = 0 ]; then
    ucnt=$(( ${#UNABS_PROVEN[@]} + ${#UNABS_UNDET[@]} ))
    ulist=$(first3 ${UNABS_PROVEN[@]+"${UNABS_PROVEN[@]}"} ${UNABS_UNDET[@]+"${UNABS_UNDET[@]}"})
    only_local+=("$b (+$ahead коммит(ов), НЕТ на origin) — не поглощено ни одним стволом: $ucnt файл(ов): $ulist${pr}${occ}${fresh}")
  else
    alive+=("$b (+$ahead)${pr}${occ}${fresh}")
  fi

  # Класс «одна ветка — две работы»: PR закрыт/влит, а содержимое поглощено не всё.
  # Тревога поднимается ТОЛЬКО на доказанном непоглощении (седьмой признак): ствол
  # пути не касался, значит работа туда не попадала. Файлы, по которым ствол путь
  # правил, а перепись всё же нашла отсутствующие строки, идут отдельным списком
  # «не установлено»: это ОТСУТСТВИЕ ДОКАЗАТЕЛЬСТВА, а не доказательство потери,
  # и подавать его тревогой значит звать человека к работе, которой нет.
  if [ "$empty" = 0 ] && [ -n "${PRSTATE[$b]+x}" ]; then
    case "${PRSTATE[$b]}" in
      *MERGED*|*CLOSED*)
        if [ "${#UNABS_PROVEN[@]}" -ne 0 ]; then
          split_work+=("$b — ${PRSTATE[$b]}, доказано не поглощено ${#UNABS_PROVEN[@]} файл(ов): $(first3 "${UNABS_PROVEN[@]}")")
        elif [ "${#UNABS_UNDET[@]}" -ne 0 ]; then
          undet_work+=("$b — ${PRSTATE[$b]}, поглощение не установлено по ${#UNABS_UNDET[@]} файл(ам): $(first3 "${UNABS_UNDET[@]}")")
        fi ;;
    esac
  fi
done < <(git branch --format='%(refname:short)')

# --- ветки на origin ----------------------------------------------------------
if [ "$remote_ok" = 1 ]; then
  for b in "${!ON_ORIGIN[@]}"; do
    [ "$b" = "${TRUNK#origin/}" ] && continue
    case "$b" in release/*) continue ;; esac
    examined_remote=$((examined_remote + 1))

    # Ветку origin читаем ПО ЕЁ SHA с origin, а не через возможно отставший
    # refs/remotes: если локальной копии ссылки нет, признак просто недоступен.
    rref="refs/remotes/origin/$b"
    git rev-parse --verify --quiet "$rref^{commit}" >/dev/null || {
      orphan_remote+=("$b — есть на origin, локальной копии ссылки нет: нужен git fetch")
      continue; }

    delta_checked=$((delta_checked + 1))
    if merge_delta_empty "$rref"; then
      orphan_remote+=("$b — ДЕЛЬТА СЛИЯНИЯ ПУСТА, содержимое в стволе${PRSTATE[$b]+ ${PRSTATE[$b]}}")
      continue
    fi

    if [ "$have_gh" = 1 ] && [ -z "${PRSTATE[$b]+x}" ]; then
      ct=$(git log -1 --format=%ct "$rref" 2>/dev/null || echo "$NOW")
      age_days=$(( (NOW - ct) / 86400 ))
      [ "$age_days" -gt 14 ] &&
        orphan_remote+=("$b — PR не заводился, последний коммит ${age_days} дн. назад, дельта НЕ пуста")
    fi
  done
fi

# --- резервные ссылки, которых обычное удаление не касается -------------------
backup_refs=()
while read -r r; do
  [ -n "$r" ] && backup_refs+=("$r")
done < <(git for-each-ref --format='%(refname)' 'refs/original/**' 2>/dev/null || true)

emit() {
  local title=$1; shift
  echo "── $title (${#@})"
  if [ "$#" -eq 0 ]; then echo "   —"; else printf '   %s\n' "$@"; fi
  echo
}

emit "ВЛИТЫ — содержимое в стволе, снимаются локально" "${merged_local[@]+"${merged_local[@]}"}"
emit "НА ORIGIN без предмета — проверить PR-преемника перед снятием" "${orphan_remote[@]+"${orphan_remote[@]}"}"
emit "ТОЛЬКО ЛОКАЛЬНО и дельта НЕ пуста — РАБОТА В ЕДИНСТВЕННОМ ЭКЗЕМПЛЯРЕ, снимать НЕЛЬЗЯ" \
     "${only_local[@]+"${only_local[@]}"}"
emit "ЖИВЫЕ — есть на origin, несут работу" "${alive[@]+"${alive[@]}"}"

if [ "${#split_work[@]}" -ne 0 ]; then
  emit "ВНИМАНИЕ: PR закрыт, а работа в стволе НЕ ВСЯ — ветка несла больше одного предмета" \
       "${split_work[@]}"
fi

if [ "${#undet_work[@]}" -ne 0 ]; then
  emit "ПОГЛОЩЕНИЕ НЕ УСТАНОВЛЕНО — тревоги нет, но и снятию не подлежит (перепись — свидетельство, не доказательство)" \
       "${undet_work[@]}"
fi

if [ "${#backup_refs[@]}" -ne 0 ]; then
  emit "РЕЗЕРВНЫЕ ССЫЛКИ — обычное удаление веток их НЕ касается (git update-ref -d <ссылка>)" \
       "${backup_refs[@]}"
fi

echo "branch-audit: отсеяно машинно собираемых файлов ${GEN_SKIPPED}" \
     "(ноль здесь значит «таких файлов в дельтах не было», а не «не проверяли»)"
echo "branch-audit: осмотрено локальных ${examined_local}, на origin ${examined_remote}," \
     "стволов в сверке ${#TRUNKS[@]}, дельта слияния посчитана ${delta_checked} раз," \
     "шестой признак спрошен ${sixth_checked} раз и снял ${sixth_rescued} ложных находок;" \
     "перепись строк спрошена по ${census_asked} файл(ам), содержимое найдено по ${census_found};" \
     "влитых ${#merged_local[@]}, без предмета на origin ${#orphan_remote[@]}," \
     "в единственном экземпляре ${#only_local[@]}, живых ${#alive[@]}," \
     "с расщеплённой работой ${#split_work[@]}, с неустановленным поглощением ${#undet_work[@]}," \
     "резервных ссылок ${#backup_refs[@]}"

# «Шестой признак спрошен 0 раз» — не успех: это значит, что пятый ни разу не дал
# конфликта, то есть проверять было нечего. Разные исходы для «проверено, находок
# ноль» и «проверять нечего» — требование `testing.md` §Гейт на класс.
if [ "$sixth_checked" -eq 0 ] && [ "${#only_local[@]}" -ne 0 ]; then
  echo "branch-audit: шестой признак не спрашивался ни разу при непустом разделе" >&2
  echo "              «единственный экземпляр» — это расхождение, а не чистота." >&2
fi

# То же требование к переписи: раздел тревоги, набранный без единого её вызова,
# означал бы, что классификация шла по признакам, которые задача #257 признала
# недостаточными. «Ноль спрошено» и «ноль находок» обязаны быть различимы.
if [ "$census_asked" -eq 0 ] && { [ "${#split_work[@]}" -ne 0 ] || [ "${#undet_work[@]}" -ne 0 ]; }; then
  echo "branch-audit: перепись строк не спрашивалась ни разу, а разделы про непоглощённое" >&2
  echo "              непусты — вердикт по ним получен без третьего замера." >&2
fi

if [ "$remote_ok" = 0 ]; then
  echo "branch-audit: origin не опрошен (git ls-remote не ответил) — признак «есть на origin»" >&2
  echo "              НЕ прочитан; всё локальное могло быть отнесено к единственным" >&2
  echo "              экземплярам ошибочно. Перепись неполна." >&2
fi

if [ "$have_gh" = 0 ]; then
  echo "branch-audit: gh недоступен — статус PR НЕ прочитан; из пяти признаков" >&2
  echo "              доступны четыре. Перепись неполна." >&2
fi

if [ "$examined_local" -eq 0 ] && [ "$examined_remote" -eq 0 ]; then
  echo "branch-audit: не осмотрено ни одной ветки — вердикт беспредметен" >&2
  exit 2
fi

echo "branch-audit: вердикт устаревает — ветка может быть влита или сдвинута соседней" \
     "сессией через минуты. Перед снятием прогони перепись заново."

# --- СНЯТИЕ ВЛИТЫХ ЛОКАЛЬНЫХ ССЫЛОК ------------------------------------------
# Только раздел «ВЛИТЫ» и только локальные ссылки. Каждая пропущенная ветка
# называется вместе с причиной: молчаливый пропуск неотличим от «снято».
if [ "$PRUNE" = 1 ]; then
  echo
  echo "── СНЯТИЕ влитых локальных ссылок (--prune-merged)"
  head_branch=$(git symbolic-ref --quiet --short HEAD 2>/dev/null || true)
  pruned=0; kept=0; abandoned=0
  for b in ${prunable[@]+"${prunable[@]}"}; do
    if [ -n "${OCCUPIED[$b]+x}" ]; then
      if worktree_abandoned "${OCCUPIED[$b]}"; then
        echo "   оставлена $b — держится БРОШЕННОЙ копией ${OCCUPIED[$b]}"
        echo "      (в ней никто не работает и её не трогали ≥${STALE_H}ч; снять — своим заходом:"
        echo "       git worktree remove --force ${OCCUPIED[$b]} && git branch -D $b)"
        abandoned=$((abandoned+1))
      else
        echo "   оставлена $b — занята ЖИВОЙ рабочей копией ${OCCUPIED[$b]}"
      fi
      kept=$((kept+1)); continue
    fi
    if [ "$b" = "$head_branch" ]; then
      echo "   оставлена $b — это текущая ветка HEAD"; kept=$((kept+1)); continue
    fi
    ct=$(git log -1 --format=%ct "$b" 2>/dev/null || echo 0)
    if [ "$ct" -gt 0 ] && [ $(( (NOW - ct) / 60 )) -lt "$FRESH_MIN" ]; then
      echo "   оставлена $b — двигалась $(( (NOW - ct) / 60 )) мин назад (соседняя сессия может писать в неё)"
      kept=$((kept+1)); continue
    fi
    if git branch -D "$b" >/dev/null 2>&1; then
      echo "   СНЯТА $b"; pruned=$((pruned+1))
    else
      echo "   НЕ снята $b — git отказал"; kept=$((kept+1))
    fi
  done
  echo "branch-audit: из оставленных держатся БРОШЕННЫМИ копиями ${abandoned}" \
       "(порог тишины ${STALE_H}ч; ноль здесь значит «все занятые копии живы», а не «не смотрели»)"
  echo "branch-audit: снято ${pruned}, оставлено ${kept} из ${#prunable[@]} влитых;" \
       "разделы «единственный экземпляр» и «живые» не трогались by construction"
fi

