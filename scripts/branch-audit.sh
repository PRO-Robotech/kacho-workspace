# --- СНЯТИЕ ВЛИТЫХ ЛОКАЛЬНЫХ ССЫЛОК ------------------------------------------
# Только раздел «ВЛИТЫ» и только локальные ссылки. Каждая пропущенная ветка
# называется вместе с причиной: молчаливый пропуск неотличим от «снято».
if [ "$PRUNE" = 1 ]; then
  echo
  echo "── СНЯТИЕ влитых локальных ссылок (--prune-merged)"
  head_branch=$(git symbolic-ref --quiet --short HEAD 2>/dev/null || true)
  self_top=$(git rev-parse --show-toplevel 2>/dev/null || true)
  main_wt=$(git worktree list --porcelain 2>/dev/null | awk '/^worktree /{print $2; exit}')

  # ПЕРЕЧЕНЬ К ОСВОБОЖДЕНИЮ ПЕЧАТАЕТСЯ ДО ПЕРВОГО НЕОБРАТИМОГО ДЕЙСТВИЯ, а не в
  # отчёте после: снятие рабочей копии обратного хода не имеет, и человек обязан
  # увидеть цель раньше, чем она исчезнет.
  declare -A TO_RELEASE=()
  if [ "$RELEASE_WT" = 1 ]; then
    for b in ${prunable[@]+"${prunable[@]}"}; do
      [ -n "${OCCUPIED[$b]+x}" ] || continue
      wp=${OCCUPIED[$b]}
      [ "$wp" = "$self_top" ] && continue
      [ "$wp" = "$main_wt" ] && continue
      wt_abandoned "$wp" || continue
      TO_RELEASE["$b"]="$wp"
    done
    echo "   ── рабочие копии, которые будут ОСВОБОЖДЕНЫ (${#TO_RELEASE[@]})," \
         "порог простоя ${WT_IDLE_H}ч:"
    if [ "${#TO_RELEASE[@]}" -eq 0 ]; then
      echo "      — брошенных копий, держащих влитые ветки, не найдено"
    else
      for b in "${!TO_RELEASE[@]}"; do
        echo "      $b ← ${TO_RELEASE[$b]} (простой $(( $(wt_idle_min "${TO_RELEASE[$b]}") / 60 ))ч)"
      done
    fi
    echo "      снятие идёт БЕЗ --force: копию с несданными или неотслеживаемыми"
    echo "      правками git откажется удалять, и ветка останется — это и есть"
    echo "      гарантия, что работа в единственном экземпляре не пропадёт."
  fi

  pruned=0; kept=0; released=0
  for b in ${prunable[@]+"${prunable[@]}"}; do
    if [ -n "${OCCUPIED[$b]+x}" ]; then
      wp=${OCCUPIED[$b]}
      if [ -n "${TO_RELEASE[$b]+x}" ]; then
        if git worktree remove "$wp" >/dev/null 2>&1; then
          echo "   ОСВОБОЖДЕНА брошенная рабочая копия $wp (ветка $b)"
          released=$((released+1))
        else
          echo "   оставлена $b — брошенная копия $wp не снимается: в ней несданные" \
               "или неотслеживаемые правки (git отказал без --force)"
          kept=$((kept+1)); continue
        fi
      elif wt_abandoned "$wp"; then
        echo "   оставлена $b — занята БРОШЕННОЙ рабочей копией $wp" \
             "(простой $(( $(wt_idle_min "$wp") / 60 ))ч); освободить:" \
             "--release-abandoned-worktrees"
        kept=$((kept+1)); continue
      else
        echo "   оставлена $b — занята рабочей копией $wp"; kept=$((kept+1)); continue
      fi
    fi
    if [ "$b" = "$head_branch" ]; then
      echo "   оставлена $b — это текущая ветка HEAD"; kept=$((kept+1)); continue
    fi
    ct=$(git log -1 --format=%ct "$b" 2>/dev/null || echo 0)
    if [ "$ct" -gt 0 ] && [ $(( (NOW - ct) / 60 )) -lt "$FRESH_MIN" ]; then
      echo "   оставлена $b — двигалась $(( (NOW - ct) / 60 )) мин назад (соседняя сессия может писать в неё)"
      kept=$((kept+1)); continue
    fi
    if git branch -D "$b" >/dev/null 2>&1; then
      echo "   СНЯТА $b"; pruned=$((pruned+1))
    else
      echo "   НЕ снята $b — git отказал"; kept=$((kept+1))
    fi
  done
  echo "branch-audit: снято ${pruned}, оставлено ${kept} из ${#prunable[@]} влитых," \
       "брошенных рабочих копий освобождено ${released};" \
       "разделы «единственный экземпляр» и «живые» не трогались by construction"
fi

