# branch-audit.sh — перепись веток репозитория по ЖИВОСТИ, а не по имени.
#
# ПРЕДМЕТ. Ветки копятся тремя разными способами, и все три невидимы поодиночке:
#
#   1. ПЕРЕНОС. Работу переносят с отставшей ветки на свежую базу; PR-преемник
#      влит, `delete_branch_on_merge` снимает ЕГО ветку — а исходная остаётся
#      навсегда, потому что head-веткой ни одного PR она не была.
#   2. СНИМОК. Ветка вида `wip: снимок незакоммиченного состояния` заводится,
#      чтобы не потерять чужую грязную копию. Её предмет уезжает другим путём,
#      а снимок живёт вечно и выглядит как незаконченная работа.
#   3. ЕДИНСТВЕННЫЙ ЭКЗЕМПЛЯР. Локальная ветка, которой НЕТ на origin и которая
#      не влита. Её снятие уничтожает работу без следа — и именно она внешне
#      неотличима от мусора первых двух видов.
#
# СЕМЬ ПРИЗНАКОВ ВЛИВАНИЯ, и последние три строже первых четырёх вместе.
#
#   (1) `merge-base --is-ancestor` — ноль коммитов сверх ствола;
#   (2) статус PR по head-ветке;
#   (3) присутствие на origin — спрашивается У ORIGIN (`git ls-remote`), НИКОГДА
#       через `refs/remotes/*`: локальные копии ссылок отстают, и ответ по ним
#       бывает неверен в обе стороны;
#   (4) возраст последнего коммита — в ЕДИНОМ времени (эпоха, `%ct`);
#   (5) ДЕЛЬТА СЛИЯНИЯ: слить ветку в ствол во временной копии и посмотреть, что
#       изменилось. Пусто ⇒ содержимое уже в стволе;
#   (6) ПОГЛОЩЕНИЕ ПОФАЙЛОВО — объединение двух проверок, которые врут в РАЗНЫЕ
#       стороны, поэтому применяются вместе:
#         (6а) обратное применение патча файла во временный индекс ствола
#              (`git apply --cached -R --check`) — доказывает поглощение;
#              ЛОЖНО ОТРИЦАЕТ, когда ствол правил тот же файл ПОСЛЕ вливания;
#         (6б) блоб ветки встречался в истории ствола по этому пути
#              (`git log <ствол> --find-object=<blob> -- <путь>`) — доказывает,
#              что содержимое через ствол проходило; МОЛЧИТ, когда в PR были
#              правки по ревью и блоб ветки в ствол не попал дословно.
#       Файл считается непоглощённым, только если ОБЕ сказали «нет»;
#         (6в) ПОСТРОЧНАЯ ПЕРЕПИСЬ — добавленные веткой непустые строки ищутся
#              в стволовой версии файла, а снятые веткой — там же, но с обратным
#              ожиданием. Содержимое найдено, если найдены ВСЕ добавленные и не
#              уцелела НИ ОДНА снятая; строки считаются С КРАТНОСТЬЮ. Обе
#              половины обязательны: без второй ветка, чья работа — снятие, была
#              бы объявлена поглощённой молча.
#              ПЕРЕПИСЬ — СВИДЕТЕЛЬСТВО, А НЕ ДОКАЗАТЕЛЬСТВО, и влитой ветку она
#              не делает: совпадение строк не есть совпадение работы. Её исход
#              читается только в сторону «тревожиться не о чем».
#
# СЕДЬМОЙ ПРИЗНАК — не о содержимом, а о ВОЗМОЖНОСТИ: касался ли ствол этого
# пути после ответвления. Если НЕ касался ни один ствол, то содержимое ветки
# туда попасть не могло — это ДОКАЗАТЕЛЬСТВО непоглощения, а не догадка. Если
# касался, а перепись всё же нашла отсутствующие строки, различить «ветка —
# ранний черновик того, что доехало в переработанном виде» и «ветка несёт второй
# предмет» СОДЕРЖАНИЕМ нельзя: обе формы выглядят одинаково.
#
# ОТСЮДА — ДВА РАЗНЫХ ВОПРОСА, ДВА РАЗНЫХ ПРЕДИКАТА И РАЗНОЕ НАПРАВЛЕНИЕ РИСКА.
#   «БЕЗОПАСНО ЛИ СНИМАТЬ» — необратимо, поэтому требует ДОКАЗАТЕЛЬСТВА
#      поглощения, и им остаются только байтовые признаки (1), (5), (6а), (6б).
#   «ПРОПАЛА ЛИ РАБОТА» — обратимо (человек посмотрит), поэтому требует
#      ДОКАЗАТЕЛЬСТВА непоглощения, и им служит седьмой признак.
#   Всё, что не доказано ни в одну сторону, называется отдельным разделом с
#      числами — и не снимается, и не поднимает тревоги.
# До 2026-08-19 на оба вопроса отвечал один предикат: «байты не совпали». Он годится для вопроса «безопасно ли
# снимать» (там ошибаться можно только в сторону осторожности) и НЕ годится для
# вопроса «пропала ли работа» — там та же строгость превращается в тревогу без
# предмета. Замер 2026-08-17: раздел «работа в стволе НЕ ВСЯ» назвал 7 веток,
# ложными оказались 7 из 7. Перемер 2026-08-19 на том же дереве: 5 находок, из
# них 3 ложные — и все три одного вида, «ранний черновик того, что доехало».
#
# Пятый и шестой не зависят от СПОСОБА вливания — слияние, схлопывание, перенос,
# черри-пик, — тогда как первые четыре зависят все. Седьмой не зависит ещё и от
# того, доехала ли работа ДОСЛОВНО: он сравнивает содержимое, а не байты.
#
# ЗАЧЕМ ШЕСТОЙ, если есть пятый. Пятый асимметричен: пустая дельта ДОКАЗЫВАЕТ
# поглощение, а конфликт не доказывает ничего — он одинаково означает и «ветка
# несёт своё», и «ствол правил тот же файл дальше». Замер 2026-08-16 на
# монорепо продукта (`origin/main@cd7bcc5c`): пятый признак назвал расщеплёнными
# 12 веток, шестой оставил 7 — пять находок были отставанием, а не работой.
# Инструмент, у которого 42 % находок ложные, перестают читать; перестав читать,
# возвращаются к `git branch --merged`, а он на схлопнутом вливании даёт НОЛЬ
# при 63 ветках, из которых 13 влиты. Предикат перепроверки — прогон этого
# скрипта: доли выводятся из его же разделов, а не из этого комментария.
#
# СТВОЛОВ БОЛЬШЕ ОДНОГО. Работа копится в накопительных ветках (`git-issues.md`
# §«Накопительная релизная ветка»), поэтому «нет в origin/main» и «нет нигде» —
# РАЗНЫЕ вердикты. Скрипт сверяет с origin/main И с каждой origin/release/*;
# ветка, поглощённая накопительной веткой, помечается источником поглощения, а
# не объявляется единственным экземпляром. В том же замере это сняло две ложные
# находки из пяти (`issue-489`, `issue-mutation-outcome-signal`).
#
# ЧЕГО ПРИЗНАКИ НЕ ДОКАЗЫВАЮТ ПООДИНОЧКЕ:
#
#   * `git branch --merged` — здесь вливают схлопыванием и через накопительную
#     ветку, поэтому HEAD ветки предком ствола не становится: `--merged
#     origin/main` дал НОЛЬ при 63 ветках, из которых 13 были влиты;
#   * сравнение содержимого — лжёт в обратную сторону: ствол уходит вперёд по тем
#     же файлам, и у заведомо влитой ветки насчитывается тысяча строк «различий»;
#   * статус PR — ветка может нести ДВЕ работы, а закрыть её могут по одной:
#     PR «поглощён», первая работа в стволе, вторая нет. Ловят это только (5)
#     и (6), причём (5) в одиночку даёт при этом ложные находки: конфликт от
#     ушедшего вперёд ствола он не отличает от второй работы.
#
# ВЕРДИКТ УСТАРЕВАЕТ. Он верен в момент замера и не позже: ветка, измеренная как
# единственный экземпляр, через 35 минут оказывалась влитой, а локальная ветка
# переезжала сама, потому что на ней работала живая сессия. Поэтому скрипт
# печатает время замера и метит ветки, двигавшиеся только что.
#
# Использование:
#   scripts/branch-audit.sh [путь-к-репозиторию]                  # перепись
#   scripts/branch-audit.sh --prune-merged [путь-к-репозиторию]   # + снять влитые
#   scripts/branch-audit.sh [--prune-merged] <путь> <ветка>…      # только кандидаты
#
# РЕЖИМ КАНДИДАТОВ (ws#813). Полная перепись клона продукта (≈500 веток) не
# укладывается в один вызов: ветка, ответвлённая до переезда дерева, несёт
# тысячи файлов, и каждый проходит признаки (6а)–(7) по всем стволам. Снятию
# нужен вердикт по снимаемой ветке, поэтому перечень после пути судит ТОЛЬКО
# названные ветки — тем же кодом: их строки и разделы совпадают с полной
# переписью, локальные и те, что есть только на origin; чужие ветки не судятся
# ни там, ни там. Ненайденный кандидат называется, найденный — нет, и без
# находки код 2 даёт именно ненайденный, а не пустой обход. Время прогона
# печатается всегда. Держит `scripts/branch-audit-inject.sh`: AF–AI, AQ–AS, а
# мутация каждого из этих фактов красит своё утверждение (AT–AW).
#
# ПАКЕТОМ И ПАРАЛЛЕЛЬНО (ws#813). Поштучная форма звала git на каждую пару
# «файл × ствол»: замер 2026-09-24 на снимке клона продукта (6 локальных веток,
# 230 на origin, 9 стволов) — 25 мин 12 с и 44 тыс. вызовов git; время ушло на
# пофайловый `git diff` (811 с), `git log --find-object` (423 с), `merge-tree`
# (263 с, 0,94 с на слияние — это поиск переименований: с `-X no-renames` то же
# слияние 0,03 с) и пофайловый `git apply` (96 с). Ветка, ответвлённая до
# переезда дерева, несёт 3470 файлов дельты — и одна шла полчаса.
#
# Ускорение не меняет ни одного признака: каждый ускоритель либо ДОКАЗЫВАЕТ тот
# исход, который дала бы поштучная форма, либо отступает к ней. Доказательства —
# у каждого ускорителя ниже; эталон — те же признаки поштучно (BRANCH_AUDIT_EXACT=1),
# и `scripts/branch-audit-inject.sh` сверяет оба режима дословно, а мутацией
# каждого ускорителя показывает, что сверка краснеет (AJ–AP).
#   * ветки разбираются заданиями параллельно, вердикт собирается в исходном
#     порядке теми же строками;
#   * пятый признак не сливает там, где непустота дельты доказана деревьями;
#   * пофайловые признаки (6а)–(7) считаются одним разбором дельты на ветку и
#     одной проверкой патча на ствол; отказ git apply, доказанный перечнем
#     ствола, git apply не зовёт; история пути обходится один раз на прогон и
#     делится между ветками; перепись строк идёт одним потоком на ветку;
#     поштучные вызовы остаются там, где пакетный ответ не доказателен.
# Объём ускорения печатается: сколько слияний сделано и сколько доказано без
# них, сколько файлов пошло пакетом и сколько поштучно, сколько вопросов к
# истории задано поштучно и какая ветка разбиралась дольше всех.
#
# Переменные: BRANCH_AUDIT_TRUNK (ствол, умолчание origin/main),
#             BRANCH_AUDIT_FRESH_MIN (окно «движется прямо сейчас», умолчание 45),
#             BRANCH_AUDIT_NO_ACCUM=1 (не искать накопительные ветки — для проб),
#             BRANCH_AUDIT_JOBS (параллельных заданий, умолчание — половина ядер,
#               не больше 16), BRANCH_AUDIT_EXACT=1 (эталон: всё поштучно).
#
# БЕЗ `--prune-merged` скрипт НИЧЕГО НЕ УДАЛЯЕТ: он печатает списки и объём
# осмотренного, решение принимает человек — третий вид требует сдать работу, а
# не снять ветку.
#
# С `--prune-merged` снимаются ТОЛЬКО локальные ветки раздела «ВЛИТЫ», и по
# каждой печатается, снята она или оставлена и почему. Не снимаются никогда:
# занятые рабочей копией · двигавшиеся в окне FRESH_MIN · ветка ствола · текущая
# ветка HEAD · всё, что не попало в раздел «ВЛИТЫ». Причина ограничений — не
# осторожность, а замеренный класс: вердикт устаревает за минуты, а `git branch
# -D` необратим.
#
# ПОЧЕМУ СНЯТИЕ ЛОКАЛЬНОЙ ВЕТКИ ВООБЩЕ ЕСТЬ ПРЕДМЕТ. Висяк — это ССЫЛКА, а не
# коммит: при схлопывании исходный коммит не становится предком ствола НИКОГДА,
# и пока локальная ветка его держит, `git log --all --graph` рисует оборванную
# линию, неотличимую от брошенной работы. `delete_branch_on_merge` снимает
# head-ветку PR на origin — и только её; локальных копий он не видит by
# construction. Замер 2026-08-16 на монорепо продукта: 37 локальных веток при 4
# на origin, из них 20 влиты.
#
# Код возврата: 0 — работы в единственном экземпляре нет; 1 — найдена (находка,
# требующая действия); 2 — перепись беспредметна (нет ствола, нет веток).

set -euo pipefail

PRUNE=0
if [ "${1:-}" = "--prune-merged" ]; then PRUNE=1; shift; fi

REPO="${1:-$(pwd)}"
[ "$#" -eq 0 ] || shift
CANDIDATES=("$@")
declare -A CAND=()
for c in ${CANDIDATES[@]+"${CANDIDATES[@]}"}; do CAND["$c"]=0; done
# $1 = ветка → 0, если она судится этим прогоном (без перечня — любая); отмечает осмотр.
wanted() {
  [ "${#CANDIDATES[@]}" -eq 0 ] && return 0
  [ -n "${CAND[$1]+x}" ] || return 1
  CAND["$1"]=1
}
START=$(date +%s)
cd "$REPO" || { echo "branch-audit: каталог '$REPO' недоступен" >&2; exit 2; }

git rev-parse --git-dir >/dev/null 2>&1 || {
  echo "branch-audit: '$REPO' не репозиторий" >&2; exit 2; }

TRUNK="${BRANCH_AUDIT_TRUNK:-origin/main}"
FRESH_MIN="${BRANCH_AUDIT_FRESH_MIN:-45}"

git rev-parse --verify --quiet "$TRUNK^{commit}" >/dev/null || {
  echo "branch-audit: ствол '$TRUNK' не разрешается — перепись была бы беспредметна" >&2
  exit 2; }

# --- ССЫЛКИ ОБНОВЛЯЮТСЯ ДО ВЕРДИКТА ------------------------------------------
# Присутствие ветки перепись спрашивает У ORIGIN (`ls-remote`), а СОДЕРЖИМОЕ
# ствола берёт из локальной копии `origin/main` — и она отстаёт ровно тогда,
# когда это опаснее всего: сразу после чужого слияния.
#
# Наблюдалось 2026-08-22: работа, влитая минутой раньше, объявлена «в стволе НЕ
# ВСЯ, ствол этого пути не трогал» — то есть самой сильной формулировкой,
# какую инструмент выдаёт. Файл при этом лежал в стволе и совпадал побайтово;
# ложной была не проверка, а её основание.
#
# Цена промаха несимметрична: ложная тревога дороже пропуска, потому что
# инструмент, у которого находки ложные, перестают читать — и тогда настоящая
# потеря проходит незамеченной. Обновление стоит одного сетевого вызова.
#
# Отказ сети не роняет перепись: она продолжает на локальных копиях и ГОВОРИТ об
# этом — «ноль находок» обязано быть отличимо от «ноль прочитанного».
if [ "${BRANCH_AUDIT_NO_FETCH:-0}" != "1" ]; then
  if ! timeout 60 git fetch --quiet origin 2>/dev/null; then
    echo "branch-audit: origin не опрошен (git fetch не ответил) — вердикты о содержимом" >&2
    echo "  ствола вынесены по ЛОКАЛЬНЫМ копиям ссылок и могут отставать: работа," >&2
    echo "  влитая только что, будет названа непоглощённой." >&2
  fi
fi

TRUNK_SHA=$(git rev-parse "$TRUNK")
TRUNK_TREE=$(git rev-parse "$TRUNK^{tree}")
NOW=$(date +%s)

# --- СТВОЛЫ: ствол плюс каждая накопительная ветка ----------------------------
# Работа копится в release/*, поэтому «нет в origin/main» и «нет нигде» — разные
# вердикты. Перечень ВЫВОДИТСЯ из ссылок, а не выписывается: рукописный список
# разошёлся бы с деревом молча, и новая накопительная ветка осталась бы вне
# сверки — невидимо, потому что отсутствие проверки не производит сигнала.
TRUNKS=("$TRUNK")
if [ "${BRANCH_AUDIT_NO_ACCUM:-0}" != "1" ]; then
  while read -r r; do
    [ -n "$r" ] && [ "$r" != "$TRUNK" ] && TRUNKS+=("$r")
  done < <(git for-each-ref --format='%(refname:short)' \
             'refs/remotes/origin/release/*' 'refs/remotes/origin/release/*/*' 2>/dev/null || true)
fi

# Временный индекс на КАЖДЫЙ ствол: обратное применение патча идёт в него, а не
# в индекс репозитория и не в рабочую копию. Это не стилистика — испорченный
# индекс заставляет проверки, читающие дерево, выдумывать красные вердикты
# (`multi-agent-flow.md` §НЕПРИКОСНОВЕННОСТЬ ЧУЖОГО СОСТОЯНИЯ).
declare -A TRUNK_IDX=()
BA_TMP=$(mktemp -d)
cleanup_tmp() { rm -rf "$BA_TMP"; }
trap cleanup_tmp EXIT
for tr in "${TRUNKS[@]}"; do
  idx="$BA_TMP/idx.$(printf '%s' "$tr" | tr '/' '_')"
  if GIT_INDEX_FILE="$idx" git read-tree "$tr" 2>/dev/null; then
    TRUNK_IDX["$tr"]="$idx"
  fi
done
PATCH_TMP="$BA_TMP/p.diff"

# --- ПАКЕТНЫЙ РАЗБОР: что считается один раз на прогон ------------------------
# Задание разбирает ветку в своём каталоге ($BA_TMP переназначается), общее —
# здесь, в $BA_SHARED: перечни стволов, множества блобов их истории, кэш
# нормализованных строк. Общее только читается либо пишется переименованием
# готового файла, поэтому соседние задания не видят половины записи.
BA_SHARED="$BA_TMP"
mkdir -p "$BA_SHARED/norm"
EXACT="${BRANCH_AUDIT_EXACT:-0}"
if [ -n "${BRANCH_AUDIT_JOBS:-}" ]; then
  JOBS=$BRANCH_AUDIT_JOBS
else
  JOBS=$(( $(nproc 2>/dev/null || echo 2) / 2 ))
  [ "$JOBS" -le 16 ] || JOBS=16
fi
