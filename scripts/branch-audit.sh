# ноль при тринадцати влитых.
#
# Перечень ВЫВОДИТСЯ, а не выписывается: у каждого генератора спрашивается, что
# он производит (`--outputs`). Выпишешь список сюда — добавится второй выход, и
# список отстанет молча, то есть заведётся ровно тот класс, который перепись и
# ловит. Генератор, не знающий такого ключа, пропускается, и это видно в
# переписи: «ноль машинно собираемых» обязано быть отличимо от «не спросили».
GENERATED_PATHS=()
GEN_ASKED=0
GEN_MUTE=0
collect_generated() {
  local g out
  while IFS= read -r g; do
    [ -n "$g" ] || continue
    GEN_ASKED=$((GEN_ASKED + 1))
    if out=$(python3 "$REPO/$g" --outputs 2>/dev/null) && [ -n "$out" ]; then
      while IFS= read -r line; do
        [ -n "$line" ] && GENERATED_PATHS+=("$line")
      done <<< "$out"
    else
      GEN_MUTE=$((GEN_MUTE + 1))
    fi
  done < <(git -C "$REPO" ls-files -- 'scripts/*/generate.py' 2>/dev/null)
}

is_generated() { # $1 = путь → 0, если файл производится машинно
  local f=$1 g
  for g in "${GENERATED_PATHS[@]}"; do
    [ "$f" = "$g" ] && return 0
  done
  return 1
}

