#!/usr/bin/env bash
# Общие помощники набора change-graph-gate. Только для подключения, не исполняется.
#
# Предмет набора: оснастка контура SDD-1 ИСПОЛНЯЕТСЯ, а не лежит текстом. Каждая
# проверка — тонкая обёртка над `lanes.py`: ведомость полос объявлена там в
# единственном экземпляре, и второе место об одном предмете здесь не заводится.

# shellcheck disable=SC2317  # функции вызываются из подключающих check-*.sh
cg_gate_pass() { echo "[PASS] $1${2:+ — $2}"; }
# shellcheck disable=SC2317
cg_gate_fail() { echo "[FAIL] $1${2:+ — $2}" >&2; }
# shellcheck disable=SC2317
cg_gate_void() { echo "[VOID] $1${2:+ — $2}" >&2; }   # «сверять не с чем» ≠ «находок 0»

# cg_gate_run <имя проверки> <заголовок> <аргументы lanes.py…>
#
# Вердикт берётся из КОДА ВОЗВРАТА, а не из вида печати: строка `[CENSUS] …`
# выходит и на чистом дереве, и рядом с находками, поэтому чтение вывода глазами
# дало бы зелёное на красном.
#
# Вывод предиката НЕ перехватывается: полоса `hook` идёт около минуты и печатает
# ход прогона по мере продвижения. Перехват вывода в переменную вернул бы то
# самое молчание, из-за которого «идёт» и «повис» неотличимы.
# shellcheck disable=SC2317
cg_gate_run() {
    local name="$1" title="$2"; shift 2
    local dir rc
    dir="$(cd "$(dirname "${BASH_SOURCE[1]}")" && pwd)"
    python3 "$dir/lanes.py" "$@"; rc=$?
    case "$rc" in
        0) cg_gate_pass "$name" "$title" ;;
        2) cg_gate_void "$name" "$title — предпосылка не резолвится, см. строку [VOID] выше" ;;
        *) cg_gate_fail "$name" "$title — есть находки (код $rc)" ;;
    esac
    return "$rc"
}
