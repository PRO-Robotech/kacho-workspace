#!/usr/bin/env bash
# check-03 — все артефакты набора зовёт конвейер, а при автозапуске — на стволе.
#
# ЧТО УТВЕРЖДАЕТ. Каждый артефакт набора — `run-all.sh` (дешёвая
# полоса), `inject.sh` (доказательство падучести набора) и `prove-all.sh`
# (дорогая полоса) — исполняется хотя бы одним заданием конвейера; при
# автозапуске в дереве процесс, которому задание принадлежит, срабатывает на
# `main`; названный скрипт в дереве есть.
#
# ДОМ ВЫЗОВА — ОДИН (ws#753). Прогон и доказательство набора законно зовёт вывод
# перечня наборов (`scripts/lib/run-suites.sh`; доказательство — с `--proofs`), и
# тогда набор обязан быть в переписи `scripts/lib/suites.py`: выпавший из неё
# набор вывод не исполнит, хотя строка вызова цела. Поимённый вызов того же
# артефакта рядом с выводом — находка: второй выписанный дом одного вызова
# расходится с первым молча. Дорогая полоса в перечень наборов не входит и
# зовётся поимённо.
#
# ПОЧЕМУ ТРИ АРТЕФАКТА, А НЕ ОДНА ДОРОГАЯ ПОЛОСА. Конвейер обязан быть
# НАДМНОЖЕСТВОМ хука. Обход хука объявлен законным (`KACHO_SKIP_PREPUSH=1`,
# `git push --no-verify`), и если дешёвую полосу зовёт только он, то отправка в
# обход означает, что её не гонял НИКТО — ни локально, ни на слиянии.
#
# ПОЧЕМУ «СРАБАТЫВАЕТ НА `main`» — ОТДЕЛЬНОЕ УСЛОВИЕ. Задание, объявленное в
# процессе, который на стволе не срабатывает, не зеленеет и не краснеет — оно не
# начинается вовсе, и его молчание неотличимо от исправной работы. Это тот же
# класс, что и сам ws#504, только этажом выше. Пока автозапуска нет ни у
# одного процесса (решение владельца 2026-09-20, цитата — в шапке `ci.yaml`),
# условие не судится: оно было бы верно о каждом задании и стало бы вечной
# находкой.
#
# ЧИТАЕТСЯ ИСПОЛНЯЕМОЕ, А НЕ ТЕКСТ. Объявление разбирается как YAML, вызов узнаёт
# ОБЩИЙ распознаватель `scripts/lib/ci_calls.py` — тот же, что у
# `scripts/suites-gate/check-04-ci-calls-every-suite.py` (прежде у каждого был
# свой поиск подстроки, и оба молчали одинаково). Вызов — путь в положении
# команды, не в комментарии и не в строке `echo`; засчитывается, только если его
# вердикт доходит до задания: не `|| …`, не звено трубы, не фон, не условие, у
# задания и шага нет `if:` и `continue-on-error`. Незасчитанный вызов — находка с
# причиной.
#
# ЧЕГО ЭТА ПРОВЕРКА НЕ УТВЕРЖДАЕТ — названо прямо. Что красное этого задания
# БЛОКИРУЕТ слияние, она не проверяет, и сервер его не блокирует: у процесса
# одно событие — ручной `workflow_dispatch`, обязательных контекстов у `main`
# воркспейса нет тем же решением. Красное видно в check-runs ручного прогона на
# голове PR, и этот прогон — вердикт PR (ws#788): его читают
# `scripts/merge-readiness.sh`, а перед вливанием `ci-watcher` и
# `landing-reviewer`, не защита ветки. Что защита не требует контекста, которого
# никто не начнёт, держит сетевая половина
# `scripts/tooling-gate/check-05-workflow-triggers-narrowed.sh`
# (ручка KACHO_BRANCH_PROTECTION_CHECK=1).
#
# Коды выхода: 0 — все три артефакта зовёт конвейер (при автозапуске — со
# ствола); 1 — находка; 2 — файлов конвейера нет либо разборщик YAML недоступен.
set -uo pipefail
# shellcheck source=_lib.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/_lib.sh"
cg_gate_run "check-03-ci-calls-every-artifact-of-the-set" \
    "конвейер зовёт все три артефакта набора; при автозапуске — со ствола" --ci-declares
