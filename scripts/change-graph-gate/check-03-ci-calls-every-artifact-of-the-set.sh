#!/usr/bin/env bash
# check-03 — все артефакты набора зовёт конвейер, и зовёт на стволе.
#
# ЧТО УТВЕРЖДАЕТ. Каждый из трёх артефактов набора — `run-all.sh` (дешёвая
# полоса), `inject.sh` (доказательство падучести набора) и `prove-all.sh`
# (дорогая полоса) — исполняется хотя бы одним заданием конвейера; процесс,
# которому задание принадлежит, срабатывает на `main`; названный скрипт в дереве
# есть.
#
# ПОЧЕМУ ТРИ АРТЕФАКТА, А НЕ ОДНА ДОРОГАЯ ПОЛОСА. Конвейер обязан быть
# НАДМНОЖЕСТВОМ хука. Обход хука объявлен законным (`KACHO_SKIP_PREPUSH=1`,
# `git push --no-verify`), и если дешёвую полосу зовёт только он, то отправка в
# обход означает, что её не гонял НИКТО — ни локально, ни на слиянии.
#
# ПОЧЕМУ «СРАБАТЫВАЕТ НА `main`» — ОТДЕЛЬНОЕ УСЛОВИЕ. Задание, объявленное в
# процессе, который на стволе не срабатывает, не зеленеет и не краснеет — оно не
# начинается вовсе, и его молчание неотличимо от исправной работы. Это тот же
# класс, что и сам ws#504, только этажом выше.
#
# ЧИТАЕТСЯ ИСПОЛНЯЕМОЕ, А НЕ ТЕКСТ. Объявление разбирается как YAML, а внутри
# блока `run:` снимаются комментарии: имя скрипта стоит и в объяснении рядом с
# ним, поэтому предикат по подстроке зеленел бы на собственном комментарии.
#
# ЧЕГО ЭТА ПРОВЕРКА НЕ УТВЕРЖДАЕТ — названо прямо. Что красное этого задания
# БЛОКИРУЕТ слияние, она не проверяет: перечень обязательных контекстов живёт в
# защите ветки `main`, это настройка репозитория, а не дерево, и читается она
# только по сети. Половина, доступная дереву, закрыта здесь; вторая — сетевой
# половиной `scripts/tooling-gate/check-05-workflow-triggers-narrowed.sh`
# (ручка KACHO_BRANCH_PROTECTION_CHECK=1), и она сверяет обязательное с
# производимым, а не наоборот.
#
# Коды выхода: 0 — полоса объявлена и срабатывает на стволе; 1 — находка;
# 2 — файлов конвейера нет либо разборщик YAML недоступен.
set -uo pipefail
# shellcheck source=_lib.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/_lib.sh"
cg_gate_run "check-03-ci-calls-every-artifact-of-the-set" \
    "конвейер зовёт все три артефакта набора и срабатывает на стволе" --ci-declares
