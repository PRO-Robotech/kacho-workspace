#!/usr/bin/env bash
# check-02 — ведомость полос покрывает КАЖДУЮ точку входа контура, и полосы не
# пересекаются.
#
# ЧТО УТВЕРЖДАЕТ. Множество точек входа, ВЫВЕДЕННОЕ из дерева (отслеживаемый
# файл в `selftest/` либо `tests/`, несущий `if __name__ ==` для `.py` или
# шебанг для `.sh`), совпадает с множеством путей ведомости `lanes.py` — в обе
# стороны. Точка входа без строки — находка; строка без точки входа — тоже
# находка: исключению нечего исключать.
#
# ПОЧЕМУ ЭТА ПРОВЕРКА ЕСТЬ ГЕЙТ НА КЛАСС, А НЕ НА ЭКЗЕМПЛЯР. Дефект ws#504 —
# «проба не исполняется никем» — родился ровно от того, что перечня не было:
# каталог остался вне вывода хука молча и без строки в переписи. Починить один
# контур значило бы закрыть находку и оставить класс: следующая заведённая проба
# выпала бы из обеих полос тем же способом. Ведомость делает выпадение
# невозможным by construction — новая точка входа обязана получить полосу либо
# строку `none` с написанной причиной.
#
# ПРИЗНАК СТРУКТУРНЫЙ, А НЕ ПО ИМЕНИ. Соглашение контура называет пробы
# `prove*`/`inject*`, но `selftest/laneparity.py` под него не подходит — перечень
# по имени потерял бы её молча.
#
# Коды выхода: 0 — покрытие полное; 1 — находка; 2 — точек входа не найдено
# (предикат остался без предмета) либо git не отвечает.
set -uo pipefail
# shellcheck source=_lib.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/_lib.sh"
cg_gate_run "check-02-lane-roster-covers-every-entry-point" \
    "ведомость полос сверена с деревом в обе стороны" --audit
