#!/usr/bin/env bash
# check-04 — закрытый набор канонических входов §10 сходится с манифестом дерева.
#
# ЧТО УТВЕРЖДАЕТ. Множество `REGISTERED_CANONICAL_INPUTS` семейства `cg.adapter`
# и список `canonical_inputs` манифеста `.claude/adapters.yaml` — ОДИН предмет,
# записанный в двух местах. Проверка требует их равенства и печатает обе стороны
# расхождения отдельно.
#
# ПОЧЕМУ ЭТО НЕ ЛОВИТСЯ ОСТАЛЬНЫМ НАБОРОМ. Семейство судит МИР ФИКСТУРЫ, а не
# дерево, поэтому о манифесте не знает by construction; соседний
# `scripts/adapter-gate` сверяет, что каждый объявленный вход СУЩЕСТВУЕТ, а не
# что он состоит в закрытом наборе. Между двумя предикатами лежала щель, и
# расхождение в ней прожило молча: дом нормы раздвоился (`.claude/rulebook/`
# рядом с `.claude/rules/`), манифест новый вход объявил, а контур продолжал
# судить его неканоническим — при зелёном прогоне обеих сторон.
#
# ЦЕНА МОЛЧАНИЯ. Первый же пакет изменения, объявивший свои входы ПО МАНИФЕСТУ,
# получил бы RED `CG_ADAPTER_INPUT_NOT_CANONICAL` по причине, которой в дереве
# нет. Обратное прочтение не лучше: если верен набор, то дерево объявило вход, о
# котором никто не решал. Различить это может только человек — и здесь он об
# этом хотя бы узнаёт.
#
# ЧИТАЕТСЯ ИСПОЛНЯЕМОЕ, А НЕ ТЕКСТ: набор импортируется из модуля семейства.
# Разбор его исходника по образцу зеленел бы на комментарии, который перечисляет
# те же имена, — а такой комментарий там есть.
#
# Коды выхода: 0 — перечни совпали; 1 — расхождение; 2 — манифеста нет, он не
# разбирается, в нём нет непустого `canonical_inputs` либо семейство не
# импортируется (VOID: «сверять не с чем» ≠ «находок 0»).
set -uo pipefail
# shellcheck source=_lib.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/_lib.sh"
cg_gate_run "check-04-canonical-inputs-match-manifest" \
    "закрытый набор §10 сверен с манифестом владения" --inputs-match-manifest
