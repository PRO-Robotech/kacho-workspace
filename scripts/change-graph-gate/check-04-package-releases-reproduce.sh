#!/usr/bin/env bash
# check-04 — каждое освобождение роли в пакете изменения воспроизводится по реестру.
#
# ЧТО УТВЕРЖДАЕТ. Для КАЖДОГО пакета `docs/changes/<id>/holders.yaml` на коммите
# HEAD (не в индексе):
#
#   * каждая роль `review_authority` либо освобождена строкой
#     `role_applicability`, либо держится держателем с её `owner` — третьего нет;
#     пакет без раздела не освобождает ничего, и держатель нужен каждой роли;
#   * строки раздела совпадают с реестром В ОБЕ СТОРОНЫ, держатель без роли
#     реестра и держатель без `owner` — находки;
#   * применимая роль имеет держателя, и названный строкой держатель — её;
#   * каждое «not-applicable» стоит на зарегистрированном предикате ЭТОЙ роли и
#     на его поле;
#   * `evidence_command` — каноническая строка производителя для ТОГО пакета, в
#     каталоге которого лежит `holders.yaml` (команда, называющая чужой пакет,
#     освобождения не покупает — опыт N2 приёмки 2026-09-22);
#   * поле, пересчитанное производителем на коммите, равно `evidence_value` и
#     выполняет условие предиката;
#   * у освобождённой роли нет ни держателя в `required_holders`, ни следов в
#     пакете — иначе предмет был, и ложно освобождение, а не след.
#
# ПОЧЕМУ ЭТО ПРОВЕРКА, А НЕ ВНИМАНИЕ. До 2026-09-22 эту сверку держал только
# `convergence-reviewer` чтением прозы, а число поля производила строка оболочки
# в самом пакете и на непрочитанном дереве давала ноль — то есть освобождение.
#
# Пакет без `holders.yaml` (есть только манифест) не сверяется и называется в
# переписи поимённо: «не сверен» отличим от «сошёлся».
#
# Коды выхода: 0 — все освобождения пересчитаны и сошлись; 1 — находка; 2 —
# сверять нечего либо часть освобождений пересчитать не удалось (нет клона
# продукта с опубликованными ревизиями линии, нет разборщика YAML) — «не
# выполнилось».
set -uo pipefail
# shellcheck source=_lib.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/_lib.sh"

NAME="check-04-package-releases-reproduce"
TITLE="освобождения ролей в пакетах пересчитаны по реестру"
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="${CG_GATE_ROOT:-$(cd "$DIR/../.." && pwd)}"

python3 "$DIR/applicability.py" verify --rev HEAD --home "$ROOT"
rc=$?
case "$rc" in
    0) cg_gate_pass "$NAME" "$TITLE" ;;
    2) cg_gate_void "$NAME" "$TITLE — пересчитать не удалось, см. строки [UNREAD] выше" ;;
    *) cg_gate_fail "$NAME" "$TITLE — есть находки (код $rc)" ;;
esac
exit "$rc"
