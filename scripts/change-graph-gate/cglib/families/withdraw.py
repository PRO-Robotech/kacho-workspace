"""cg.withdraw — терминальное боковое состояние WITHDRAWN.

Приёмка §«Landing и terminal states»: владелец вправе отозвать ДЕЙСТВУЮЩЕЕ, ещё
не приземлённое изменение; событие несёт основание и предмет, история при этом
сохраняется. Отсюда два предмета, и приёмка объявляет по диагностике на каждый:

    source_state    приземлённое изменение отзыву не подлежит
    event.reason    отзыв без основания не является отзывом

**Авторизованность — ПРЕДПОСЫЛКА, а не находка, и это решение, а не пропуск.**
Базовый кейс приёмки начинается словами «authorized owner event», а два
производных наследуют это условие через twin, меняя ровно один другой факт: то
есть авторизованность дана условием, а не проверяется. Диагностик этому
семейству приёмка объявляет РОВНО ДВЕ — обе названы выше, и ни одна не про
актора. Заводить третью значило бы предъявить код, которого приёмка не объявляла
и которого не предъявит ни один кейс. Поэтому мир, где
отзыва уполномоченным владельцем не запрашивали, семейство не судит вовсе —
ядро отвечает собственным отказом «мир не судим», а НЕ зелёным вердиктом.
Ответить GREEN значило бы объявить неавторизованный отзыв законным, то есть
завести проверку с формой, но без содержания.

Асимметрия с соседним `cg.conv` намеренная и не является расхождением: там
неуполномоченный актор — НАХОДКА, потому что приёмка объявляет для него
диагностику (`CG_CONVERGENCE_OWNER_UNAUTHORIZED`); здесь диагностики нет,
поэтому находки нет тоже — заводить её значило бы предъявить код, которого
приёмка не объявляла. Разница в том, что объявлено, а не в том, что кому-то
показалось строже.

**Событие потребляется ЦЕЛИКОМ, и это не вольность с `read_all`.** Запрос на
отзыв есть тройка «кто просит · почему · о чём»: `actor`, `reason`,
`subject_digest`. Судить одну её часть, не прочитав остальных, значило бы
судить запрос, которого никто не делал, — поэтому предпосылка читает событие
целиком и там же устанавливает, что оно исходит от владельца из списка и
называет предмет.

**Порядок объявлен и несущий:** сперва состояние источника, затем полнота
запроса. Приземлённое изменение отозвать нельзя ни при каком основании, поэтому
находка о состоянии содержит в себе находку о форме запроса: спорить о качестве
запроса, который невыполним в принципе, незачем.

**Чего это семейство НЕ судит — сказано прямо, чтобы GREEN не читался шире.**
Состояние источника семейство различает ДВОИЧНО: «приземлено» и «не
приземлено», — потому что именно это различие называет приёмка и несёт сама
диагностика. Законность прочих состояний как таковых — предмет семейства
жизненного цикла, а взаимные ссылки замещения — предмет `cg.super`; здесь они
не дублируются: второе место об одном предмете разошлось бы с первым молча.
Поэтому GREEN этого семейства означает ровно «не приземлено и основание
названо», а не «отзыв законен по всем осям» — объём осмотренного печатает
перепись.
"""

from .. import outcome
from ..rules import Rule

FAMILY = "withdraw"

EVENT = "event"
SOURCE_STATE = "source_state"
POLICY_ALLOWLIST = "policy_allowlist"

# Роль, чьё разрешение делает отзыв авторизованным. Имя роли берётся из мира
# (ключ списка), а не выводится из имени актора.
OWNER_ROLE = "owner"
ALLOWED_OWNER = "%s.%s" % (POLICY_ALLOWLIST, OWNER_ROLE)

# Состояние, после которого отзыв невыполним: изменение уже приземлено.
LANDED_STATE = "LANDED"

EVENT_ACTOR = "actor"
EVENT_REASON = "reason"
EVENT_SUBJECT_DIGEST = "subject_digest"

SUBJECT = (EVENT, SOURCE_STATE, POLICY_ALLOWLIST)
REQUIRES = (EVENT, SOURCE_STATE, POLICY_ALLOWLIST)


def _blank(value):
    """Отсутствующее либо пустое значение. Пробелы значением не считаются."""
    if value is None:
        return True
    return not str(value).strip()


def _allowed_owners(world):
    """Множество акторов, которым разрешён отзыв.

    Читается ОДНА запись списка — та, чью роль семейство и потребляет. Брать
    список целиком значило бы объявить прочитанным то, чего правило не
    смотрело.
    """
    if not world.has(ALLOWED_OWNER):
        return set()
    declared = world.read(ALLOWED_OWNER)
    if isinstance(declared, (list, tuple, set)):
        return {str(item).strip() for item in declared}
    return {str(declared).strip()}


def _withdrawal_by_authorized_owner(world):
    """Предпосылка семейства: отзыв запрошен владельцем и называет предмет.

    Читает событие целиком и разрешение роли владельца. Возвращает False на
    мире, который отзывом уполномоченного владельца не является, — тогда ни
    одно правило неприменимо, и ядро отвечает собственным отказом, а не GREEN.
    """
    event = world.read_all(EVENT)
    if not isinstance(event, dict):
        return False
    actor = event.get(EVENT_ACTOR)
    if _blank(actor):
        return False
    if str(actor).strip() not in _allowed_owners(world):
        return False
    return not _blank(event.get(EVENT_SUBJECT_DIGEST))


def _withdraw_after_landing(world):
    """Изменение уже приземлено — отзывать нечего.

    Приземление терминально по содержанию: применённое содержимое существует в
    стволе, и снятие записи об изменении его оттуда не убирает. Отзыв после
    приземления объявил бы несуществующим то, что наблюдаемо есть.
    """
    return str(world.read(SOURCE_STATE)).strip() == LANDED_STATE


def _withdraw_reason_missing(world):
    """Отзыв без основания.

    Основание — не украшение записи: история сохраняется, и без него запись
    говорит, что изменение сняли, но не говорит, почему. Читателю такой истории
    не восстановить решения, а значит она не история.
    """
    event = world.read_all(EVENT)
    if not isinstance(event, dict):
        return True
    return _blank(event.get(EVENT_REASON))


RULES = [
    Rule(
        rule_id="withdraw.after-landing",
        diagnostic="CG_WITHDRAW_AFTER_LANDING",
        category=outcome.CATEGORY_RED,
        subject_keys=SUBJECT,
        requires=REQUIRES,
        applicability=_withdrawal_by_authorized_owner,
        predicate=_withdraw_after_landing,
        why="§«Landing и terminal states»: WITHDRAWN доступен ДЕЙСТВУЮЩЕМУ, ещё "
            "не приземлённому изменению; после приземления отзывать нечего",
    ),
    Rule(
        rule_id="withdraw.reason-missing",
        diagnostic="CG_WITHDRAW_REASON_MISSING",
        category=outcome.CATEGORY_RED,
        subject_keys=SUBJECT,
        requires=REQUIRES,
        applicability=_withdrawal_by_authorized_owner,
        predicate=_withdraw_reason_missing,
        why="событие отзыва обязано нести основание: история сохраняется, и "
            "запись без причины не восстанавливает принятого решения",
    ),
]
