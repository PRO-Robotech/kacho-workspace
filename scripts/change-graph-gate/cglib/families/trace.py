"""cg.trace — exact-set трасса acceptance ID и держатели одного ID.

Приёмка §9, дословно: «Acceptance ID set A должен exact-set совпасть с design,
tasks и evidence plan. Missing, orphan и equal-count/different-members → RED.
Одному ID разрешены несколько независимых holders».

Отсюда у семейства ДВЕ полосы, и они не пересекаются ни одной координатой:

1. **множества идентификаторов** — acceptance против трёх нижележащих наборов;
2. **держатели одного идентификатора** — сколько их и своё ли у каждого
   доказательство.

Мир кейса несёт либо первую полосу, либо вторую, поэтому применимость правил
решают их координаты: правило нижележащих наборов неприменимо там, где наборов
нет, и наоборот. Ни один мир при этом не остаётся без применимого правила —
иначе ядро ответило бы собственным отказом «мир не судим», и это правильно:
«правил не нашлось» и «нарушений не найдено» — разные вещи.

## Различает находки НАПРАВЛЕНИЕ расхождения, а не число элементов

Приёмка называет три исхода, и соблазн развести их по мощности множеств велик:
кейс «равное число, разные ID» прямо называет мощность. Мощность здесь —
СЛЕДСТВИЕ, а не признак, и разводить по ней неверно.

| что с набором | как это называется |
|---|---|
| ТЕРЯЕТ объявленные ID и ничего не добавляет | `CG_TRACE_ID_MISSING` |
| ДОБАВЛЯЕТ чужие ID и ничего не теряет | `CG_TRACE_ID_ORPHAN` |
| и то и другое сразу | `CG_TRACE_SET_MISMATCH` |

Потеря означает требование без нижележащего покрытия; сирота — работу,
запланированную тому, чего никто не требовал; двустороннее расхождение — случай,
который ни одно из двух односторонних имён не описывает целиком.

Равная мощность при разном составе выразима ТОЛЬКО третьей строкой: чтобы
число совпало, а состав нет, надо и потерять, и добавить. То есть кейс приёмки
про «равное число» — частный случай двустороннего расхождения, а не отдельное
явление.

Разводить по мощности было бы хуже наблюдаемо: набор, потерявший два ID и
добавивший один, получил бы имя `CG_TRACE_ID_MISSING` — то есть половину
находки, и вторая половина осталась бы невидимой до следующего прогона.

## Ту же диагностику производят вызывающие — но ДРУГИМ предикатом

`CG_TRACE_ID_MISSING` предъявляется не только здесь: её же производят семейства
вызывающих (workspace/product pre-push и CI). Расхождение предикатов РЕШЕНО, а
не возникло само, и потому названо здесь.

Различает их **наличие эталона в мире**. Здесь эталонный набор идентификаторов
приёмки лежит координатой `acceptance_ids`, поэтому сравнение прямое: множество
против множества, по §9. В мирах вызывающих эталона нет ни одной координатой —
там лежит только перечень задач package, — и вопрос «удалён ли существующий
кейс приёмки» по такому миру неразрешим вовсе. Поэтому вызывающие вынуждены
вводить СВОЙ, внутренний инвариант перечня (покрытие обеих половин инверсии
рождения) под ту же диагностику.

Сужать здешний предикат до этого общего знаменателя было бы ПОТЕРЕЙ: мир трассы
даёт больше, а внутренний инвариант перечня не отличает «потеряли объявленный
ID» от «добавили чужой» и потому не производит ни `CG_TRACE_ID_ORPHAN`, ни
`CG_TRACE_SET_MISMATCH`.

**Слово «РЕШЕНО» выше держится механизмом, а не этим абзацем** (задача #489).
Сверка полос `selftest/laneparity.py` выводит полосы обходом реестра, класс
мира — из `subject_keys` правила, и требует двух разных вещей от двух разных
случаев. От полос ОДНОГО класса — одинакового ответа на выведенном из дерева
корпусе: у четырёх вызывающих судья с тех пор ОДИН
(`tasksmapping.lost_acceptance_id`), а прежние четыре копии расходились и это
было невидимо. От полос РАЗНЫХ классов — не сравнения, а ЗАПИСИ: класс,
которого нет в её ведомости, объявляется находкой, поэтому различие обязано
быть решением, а не случайностью. Обе полосы ЭТОГО семейства (нижележащие
наборы и держатели) стоят там своими записями.

## Объявленный порядок правил и почему он такой

Сперва двустороннее расхождение, затем потеря, затем сирота.

Двустороннее стоит первым, потому что оно называет расхождение ЦЕЛИКОМ, а два
односторонних — каждое по половине; сработать одновременно на ОДНОМ наборе они
не могут by construction (условия взаимно исключают друг друга), но на РАЗНЫХ
наборах могут, и тогда вердикт обязан назвать то, что сказано полнее.

Потеря стоит раньше сироты, потому что она о требовании без покрытия, а сирота
— о покрытии без требования. Первое означает, что часть предмета не проверяет
никто; второе — что кто-то проверяет лишнее. Дыра в покрытии дороже избытка.

Полоса держателей объявлена после полосы наборов: пустой набор держателей
делает правило о собственном доказательстве вырожденно-молчаливым (держателей
нет — судить нечего), поэтому «держателей нет вовсе» обязано быть сказано
раньше.

## Чего это семейство НЕ судит — названо прямо

`driver_birth` — фактическая тройка САМОГО драйвера, записанная его цепочкой
рождения. К трассе идентификаторов она отношения не имеет, и взять её в предмет
трассы значило бы завести второе место об одном предмете с семейством цепочки
рождения драйвера. Перепись называет эту координату поимённо, поэтому «не
судим» здесь видно, а не подразумевается.

**Оговорка, которую надо сказать вслух, — ПЕРЕМЕРЕНА 2026-09-02.** Здесь стояло
«семейства цепочки рождения драйвера в дереве ещё нет». Запись была верна в час,
когда писалась эта полоса, и перестала быть верной в тот же день: волна 3
посадила `families/driver.py` ТЕМ ЖЕ коммитом, что и этот модуль. Оговорка
пережила свой предмет, не сдвинувшись ни на строку, — и утверждала, что строка
переписи ничем не подкреплена, ровно тогда, когда подкрепление уже стояло рядом.

**Что подкреплено сегодня, и чем.** Обход `subject_keys` всех объявленных
семейств даёт РОВНО ОДНО, называющее `driver_birth` своим предметом, — `cg.driver`
(33 семейства осмотрено, 1 объявляет). На мире `SDD-1-DRIVER-01` он выносит о
ней вердикт `RED · CG_DRIVER_BIRTH_TRIPLE_INVALID · exit 10`. Значит строка «судит
другое семейство» называет существующего судью, а не обещает будущего.

**Что осталось остатком — оно уже, и называется точно.** Правила `cg.driver` не
исполняет НИ ОДИН кейс матрицы: все три его кейса несут `sut_stub` и опрашивают
испытуемого только на `--capabilities` (замер обёрткой, считающей вызовы:
`DRIVER-01..03` — 1 вызов, `EVID-02` и `TRACE-01` — 2). Стаб навязан САМОЙ
приёмкой: её колонка «Expected actual SUT» у этих рядов несёт тройки,
невыразимые испытуемым (`GREEN · … · exit 10` и `RED · … · exit 0`), поэтому снять
стаб нельзя, не тронув приёмку, а её правка отзывает вердикт, привязанный к
отпечатку файла. Вердикт правил всё же предъявляется — парой F-DRIVER-1 и
F-DRIVER-2 секции C `selftest/prove.py`, а не матрицей.

Остаток ведёт задача #488, и закрывается он не здесь: захват чужой координаты в
предмет трассы СПРЯТАЛ бы его, сняв единственную строку, по которой он читается.
"""

from .. import outcome
from ..rules import Rule

FAMILY = "trace"

# Предмет полосы 1: объявленные идентификаторы и три нижележащих набора.
SET_KEYS = ("acceptance_ids", "design_ids", "tasks_ids", "evidence_plan_ids")
DOWNSTREAM_SETS = ("design_ids", "tasks_ids", "evidence_plan_ids")

# Предмет полосы 2: те же объявленные идентификаторы и держатели одного из них.
HOLDER_KEYS = ("acceptance_ids", "holders_for_id")

# Пустое значение обязано означать «пусто»: словарь отсутствия назван явно,
# чтобы «none» не пришлось угадывать по правдоподобию строки.
ABSENT_MARKERS = (None, "", "none", "—")


def _absent(value):
    if value in ABSENT_MARKERS:
        return True
    return isinstance(value, str) and not value.strip()


def _divergence(world):
    """Расхождение каждого нижележащего набора с объявленными ID.

    Читаются ВСЕ четыре набора: exact-set совпадение есть отношение множеств, и
    ответ «сошлось», полученный по одному из них, был бы получен, не взглянув на
    остальные. Возвращает по набору пару (потеряно, лишнее).
    """
    required = set(world.read_all("acceptance_ids"))
    divergence = {}
    for name in DOWNSTREAM_SETS:
        present = set(world.read_all(name))
        divergence[name] = (sorted(required - present), sorted(present - required))
    return divergence


def _any_set_diverges_both_ways(world):
    """Набор и теряет объявленный ID, и добавляет чужой — расхождение целиком."""
    return any(
        missing and orphan for missing, orphan in _divergence(world).values()
    )


def _any_set_only_loses_ids(world):
    """Набор теряет объявленные ID и ничего не добавляет: требование без покрытия."""
    return any(
        missing and not orphan for missing, orphan in _divergence(world).values()
    )


def _any_set_only_adds_ids(world):
    """Набор добавляет ID, которых acceptance не объявлял: покрытие без требования."""
    return any(
        orphan and not missing for missing, orphan in _divergence(world).values()
    )


def _declared_id_has_no_holder(world):
    """Идентификаторы объявлены, а держателей у них нет ни одного.

    Читаются оба набора: вопрос «прослежен ли объявленный ID до держателя» есть
    отношение между ними, и по одному не решается. Пустой набор держателей —
    самостоятельный факт мира, а не отсутствие факта.
    """
    required = world.read_all("acceptance_ids")
    holders = world.read_all("holders_for_id")
    return bool(required) and not holders


def _holder_without_its_own_evidence(world):
    """У названного держателя нет СВОЕЙ координаты доказательства.

    §9 разрешает одному ID несколько держателей, но независимых: два имени с
    одной координатой независимыми держателями не являются — доказательство у
    них общее, и второй молча занимает место первого. Поэтому отсутствующая
    координата и координата, совпавшая с чужой, — ОДНА находка: опереться на
    такого держателя нельзя ни в том, ни в другом случае.
    """
    holders = world.read_all("holders_for_id")
    seen = {}
    for name in sorted(holders):
        coordinate = holders[name]
        if _absent(coordinate):
            return True
        if coordinate in seen:
            return True
        seen[coordinate] = name
    return False


RULES = [
    Rule(
        rule_id="trace.downstream-set-mismatch",
        diagnostic="CG_TRACE_SET_MISMATCH",
        category=outcome.CATEGORY_RED,
        subject_keys=SET_KEYS,
        requires=SET_KEYS,
        predicate=_any_set_diverges_both_ways,
        why="§9 equal-count/different-members даёт RED; равная мощность при "
            "разном составе выразима только двусторонним расхождением, поэтому "
            "признак — направление, а не число",
    ),
    Rule(
        rule_id="trace.downstream-id-missing",
        diagnostic="CG_TRACE_ID_MISSING",
        category=outcome.CATEGORY_RED,
        subject_keys=SET_KEYS,
        requires=SET_KEYS,
        predicate=_any_set_only_loses_ids,
        why="§9 missing даёт RED: объявленный acceptance ID остался без "
            "нижележащего покрытия",
    ),
    Rule(
        rule_id="trace.downstream-id-orphan",
        diagnostic="CG_TRACE_ID_ORPHAN",
        category=outcome.CATEGORY_RED,
        subject_keys=SET_KEYS,
        requires=SET_KEYS,
        predicate=_any_set_only_adds_ids,
        why="§9 orphan даёт RED: нижележащий набор адресован тому, чего "
            "acceptance не объявлял",
    ),
    Rule(
        rule_id="trace.id-without-holder",
        diagnostic="CG_TRACE_ID_MISSING",
        category=outcome.CATEGORY_RED,
        subject_keys=HOLDER_KEYS,
        requires=HOLDER_KEYS,
        predicate=_declared_id_has_no_holder,
        why="§9 разрешает одному ID несколько держателей — то есть "
            "предполагает, что держатель у него ЕСТЬ; объявленный ID без "
            "единого держателя не прослежен никуда",
    ),
    Rule(
        rule_id="trace.holder-evidence-not-own",
        diagnostic="CG_HOLDER_EVIDENCE_COORDINATE_MISSING",
        category=outcome.CATEGORY_RED,
        subject_keys=HOLDER_KEYS,
        requires=HOLDER_KEYS,
        predicate=_holder_without_its_own_evidence,
        why="§9 держатели одного ID обязаны быть НЕЗАВИСИМЫМИ: держатель без "
            "своей координаты доказательства (её нет либо она чужая) "
            "сохранённым не является",
    ),
]
