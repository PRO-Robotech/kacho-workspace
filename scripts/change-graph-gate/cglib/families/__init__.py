"""Семейства правил. Каждый модуль объявляет FAMILY и RULES — и больше ничего.

Модуль на семейство — не стиль, а условие параллельной работы: полосы, ведущие
разные семейства, не правят один файл и не сталкиваются на нём. По той же
причине перечень семейств нигде не выписан: он собирается обходом этого
каталога (`cglib/registry.py`), поэтому положенный сюда модуль сам добавляет
свой признак в ответ `--capabilities`.

Контракт модуля семейства:

    FAMILY = "<буквы нижнего регистра>"   # признак получается как "cg." + FAMILY
    RULES = [Rule(...), ...]              # непустой, порядок ОБЪЯВЛЕННЫЙ

Имя семейства обязано совпадать с тем, что выводится из идентификатора кейса
(`SDD-1-<СЕМЕЙСТВО>-NN` -> нижний регистр) — тем же разбором, каким это делает
harness. Отдельной таблицы соответствий нет намеренно: она была бы вторым
местом об одном предмете.

Требования к правилу, каждое из которых проверяется ядром, а не обещанием:

* **предикат судит МИР, а не идентификатор кейса.** Идентификатор выбирает
  семейство и не участвует в предикате. Иначе испытуемый был бы таблицей
  соответствий, зелёной по построению;
* **`subject_keys`** перечисляет верхнеуровневые координаты, о которых правило
  судит. Их объединение по семейству и есть предмет семейства. Факт мира внутри
  предмета, не прочитанный ни одним ПРИМЕНИМЫМ правилом, — собственный отказ
  испытуемого: вердикт был бы заявлением шире осмотренного. Чтение вне
  объявленного предмета — тоже отказ, то есть проверка двусторонняя;
* **контейнер берут целиком через `read_all` только тогда, когда его целиком и
  потребляют** — сравнивают с эталоном либо обходят все записи. Правилу, которому
  нужна одна запись, полагается `read` по её координате: иначе перепись покроет
  то, чего никто не смотрел;
* **применимые правила исполняются ВСЕ**, вердикт берётся по первому нарушению в
  объявленном порядке, и порядок объясняется в модуле. Правило, содержащее в себе
  находку другого, объявляется раньше него;
* **диагностика берётся из приёмки.** Заводить диагностику, которой приёмка не
  объявляет, нельзя: она не будет предъявлена ни одним кейсом и останется кодом
  без пробы.
"""
