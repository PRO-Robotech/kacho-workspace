"""cg.driver — birth-запись самого драйвера: тройка, которую ему скормили.

**Наблюдение, с которого начинается этот модуль, а не допущение.** Драйвер
опрашивает испытуемого о мире НЕ у всех кейсов. Замер (обёртка над SUT,
считающая вызовы; управление — `KACHO_CG_SUT`):

    SDD-1-EVID-02  (fixture без `sut_stub`)  — вызовов SUT 2:
                   `--capabilities` и `--case-world`
    SDD-1-DRIVER-01..03 (fixture с `sut_stub`) — вызовов SUT 1: только
                   `--capabilities`

То есть у трёх кейсов этого семейства мир испытуемому не передаётся вовсе:
фактическую тройку драйвер берёт из fixture, о чём и печатает своей строкой
переписи. Приёмка §14 говорит то же прямо: «Три `DRIVER-*` birth fixtures меняют
ровно одно поле actual triple», то есть колонка «Expected actual SUT» у этих
трёх рядов — СКОРМЛЕННАЯ тройка, а не поведение испытуемого. Проверяется это
арифметикой самого испытуемого: `GREEN · … · exit 10` и `RED · … · exit 0`
невыразимы by construction (`outcome.py` выводит код из категории), поэтому
такие тройки не мог бы напечатать никакой SUT — их и незачем было бы ожидать.

**Что тогда является предметом семейства.** Мир кейса несёт `driver_birth` —
запись о рождении драйвера, и `cg.evid` намеренно объявляет её ВНЕ своего
предмета, называя переписью поимённо. Значит предмет здесь один и он свой:
**запись о рождении обязана содержать тройку, которая является вердиктом.**
Тройка, чей код возврата не следует из категории, вердиктом не является — она
сообщает о себе две разные вещи сразу; ровно поэтому `outcome.py` выводит код из
категории, а стабильный шов драйвера отказывается выбирать за испытуемого,
когда напечатанный код расходится с фактическим. Запись о рождении, несущая
такую тройку, фиксирует исход, которого не мог произвести ни один держатель, —
опереться на неё нельзя.

**Диагностика заведена этим модулем, и это названо находкой, а не решением по
умолчанию.** Замер по приёмке: из 134 объявленных ею диагностик `CG_*`/`CGA_*`
семейству `cg.driver` не адресована НИ ОДНА — в рядах `DRIVER-*` стоят коды
трассы (`CG_TRACE_ID_ORPHAN`, `CG_TRACE_ID_MISSING`, предмет `cg.evid` и
`cg.trace`) и holder-коды драйвера (`CASE_ASSERTION_*_MISMATCH`, их производит
сам драйвер). Взять чужой код значило бы завести второго производителя одной
диагностики и назвать находку неверным именем — читатель пошёл бы искать не там.
Поэтому здесь заведён свой код, и норма «диагностика берётся из приёмки»
нарушена ОСОЗНАННО, с названной ценой: код, которого приёмка не объявляет, не
предъявляется ни одним кейсом матрицы. Довод нормы («останется кодом без
пробы») закрыт другим механизмом: код предъявляется парой секции C
`selftest/prove.py` (дефектный мир даёт его, чистый молчит) и доказан инъекцией.
**Предикат снятия:** приёмка объявила диагностику для birth-записи драйвера —
этот код заменяется объявленным тем же изменением.

**Правило одно, и это тоже решение.** Все три способа испортить тройку —
категория вне закрытого набора, код, не следующий из категории, и диагностика
из пространства собственного отказа — суть одна находка: «записанное не является
вердиктом». Разводить их по диагностикам значило бы завести ещё два кода без
предъявителя.
"""

from .. import outcome
from ..rules import Rule

FAMILY = "driver"

DRIVER_BIRTH = "driver_birth"
ACTUAL_TRIPLE = "driver_birth.actual_triple"

# Форма тройки: `КАТЕГОРИЯ · ДИАГНОСТИКА · exit N`. Разделитель и соответствие
# категории коду берутся из `outcome`, а не выписываются здесь второй раз.
EXIT_PREFIX = "exit"
TRIPLE_FIELDS = 3

SUBJECT = (DRIVER_BIRTH,)
REQUIRES = (ACTUAL_TRIPLE,)


def _parse_triple(text):
    """Разбирает записанную тройку. None — записанное тройкой не является."""
    fields = [part.strip() for part in str(text).split(outcome.SEPARATOR)]
    if len(fields) != TRIPLE_FIELDS:
        return None
    category, diagnostic, tail = fields
    if not tail.startswith(EXIT_PREFIX):
        return None
    number = tail[len(EXIT_PREFIX):].strip()
    if not number.isdigit():
        return None
    return category, diagnostic, int(number)


def _birth_triple_not_a_verdict(world):
    """Записанная тройка не является вердиктом о предмете.

    Четыре способа перестать им быть, и все четыре — одна находка:
    форма не разбирается · категория вне закрытого набора · код возврата не
    следует из категории · диагностика принадлежит пространству собственного
    отказа испытуемого (такая запись объявляла бы поломку свойством мира).
    """
    parsed = _parse_triple(world.read(ACTUAL_TRIPLE))
    if parsed is None:
        return True
    category, diagnostic, exit_code = parsed
    if category not in outcome.SUBJECT_EXIT_CODES:
        return True
    if exit_code != outcome.SUBJECT_EXIT_CODES[category]:
        return True
    if not diagnostic:
        return True
    return diagnostic.startswith(outcome.SELF_DIAGNOSTIC_PREFIX)


RULES = [
    Rule(
        rule_id="driver.birth-triple-not-a-verdict",
        diagnostic="CG_DRIVER_BIRTH_TRIPLE_INVALID",
        category=outcome.CATEGORY_RED,
        subject_keys=SUBJECT,
        requires=REQUIRES,
        predicate=_birth_triple_not_a_verdict,
        why="§7 birth inversion опирается на ЗАФИКСИРОВАННЫЙ исход; тройка, чей "
            "код возврата не следует из категории, сообщает о себе две разные "
            "вещи и исходом не является — опереться на такую запись нельзя",
    ),
]
