"""Полнота package tasks mapping — ОДИН предикат на все вызывающие семейства.

Приёмка §9: acceptance ID set обязан exact-set совпасть с design, tasks и
evidence plan, а «missing» даёт RED (`CG_TRACE_ID_MISSING`). Приёмка §11: «у
каждого реального caller есть one-fact injection: valid fixture проходит, тот же
input с одним invalid Change Graph fact блокируется». Отсюда предмет модуля:
вызывающий подаёт гейту tasks mapping своего package'а, и гейт обязан заметить
потерянный в нём acceptance ID — иначе caller пропустит push либо job на
изменении, чей граф уже негоден.

> [!important] Почему предикат ОБЩИЙ, а не по одному на семейство
> Диагностику `CG_TRACE_ID_MISSING` производят ШЕСТЬ правил в ПЯТИ семействах,
> и миры у них структурно разные. У трассы эталонный набор идентификаторов
> приёмки лежит В МИРЕ (`acceptance_ids`), и сравнение множеств прямое; у
> ЧЕТЫРЁХ вызывающих (WSCI, WSPP, PPRE, PCI) эталона в мире нет ни одной
> координатой, поэтому «удалён существующий кейс приёмки» по самому миру
> неразрешим прямым сравнением — и каждая полоса вынуждена ввести инвариант
> ПЕРЕЧНЯ под одной и той же диагностикой.
>
> **Четыре независимые реализации этого инварианта были заведены и РАЗОШЛИСЬ.**
> Замер сверкой полос (`selftest/laneparity.py`, 70 входов корпуса): на входе
> «полная пара серии SDD-1-POST-NA» одна полоса давала находку, три молчали; на
> входе с неразбираемой записью две давали находку, две — собственный отказ.
> Ни матрица (196 из 196), ни сведение волны такого не найдут: кейсы зелёные у
> всех, и каждый предикат по отдельности верен.
>
> Поэтому судья живёт ЗДЕСЬ в единственном экземпляре, и все четыре вызывающих
> зовут его: `cg.wsci`, `cg.wspp`, `cg.ppre`, `cg.pci`. Расхождение между ними
> стало невозможным by construction, а не оставленным на усмотрение сведения.
> Предикат единственности судьи — обходом реестра: `python3
> selftest/laneparity.py`. Он печатает перепись, где «сравнено полос» равно
> числу вызывающих, а «находок» — ноль; разошедшийся судья дал бы находку с
> именем входа и ответом каждой полосы.
>
> **Полосы РАЗНЫХ классов сюда не сводятся, и это решение.** Сужать предикат
> трассы до инварианта перечня было бы потерей: её мир даёт больше, а инвариант
> перечня не отличает потерю объявленного ID от добавления чужого и потому не
> производит ни `CG_TRACE_ID_ORPHAN`, ни `CG_TRACE_SET_MISMATCH`. Само наличие
> второго класса стоит в ведомости сверки — то есть является решением, а не
> случайностью, и новый класс без записи в ней будет находкой.

**Инвариант.** Идентификаторы группируются по семейству, и каждая группа обязана
нести ОБЕ половины инверсии рождения:

* **базовый кейс серии** — порядковый 1. Это положительный вход, на котором
  проверка обязана молчать;
* **хотя бы один производный** — one-fact injection к нему (§11, §12), то есть
  вход, на котором она обязана падать.

Группа, потерявшая любую из половин, доказательства не несёт: держатель,
показавший один исход, неотличим от держателя, который другого показать не
может. Это ровно тот класс, ради которого приёмка требует birth inversion.

**Замер, на котором инвариант стоит** (`tests/testdata`, 196 кейсов, 33
семейства): семейств без кейса с порядковым 1 — **ноль**; семейств с
единственным кейсом (для которых пара была бы невыполнима) — **ноль**; кейсов с
порядковым 1, объявляющих positive twin, — **один** (`SDD-1-DRIVER-01`, чей
twin принадлежит другому семейству, и на членстве в группе это не сказывается).
Числа названы, чтобы предикат не читался как догадка о структуре приёмки.

**Пустой mapping — потеря, а не чистота.** Приёмка §7 прямо запрещает vacuous
GREEN на нулевой переписи: «Active package с 0 acceptance IDs → RED». Package,
подавший ноль ID, не подал ни одной половины.

**Дубликат половиной не является.** Один и тот же ID, названный дважды, второго
члена пары не даёт, поэтому члены группы считаются по идентификатору.

**Сироту здесь не ищут.** Обратная сторона — ID, которого в приёмке нет вовсе, —
это `CG_TRACE_ID_ORPHAN`, и она принадлежит семейству трассы (SDD-1-TRACE-03).
Заводить её здесь значило бы объявить диагностику, которую не предъявит ни один
кейс вызывающих семейств, — то есть код без пробы.

**Грамматика идентификатора — у `registry`, и второго её места нет.** Разбор
ведёт `registry.family_of` — та же функция, которой harness выводит семейство из
ID. Здесь читается ОДНО поле уже проверенного ею идентификатора — порядковый
номер; выписывать грамматику заново значило бы завести второе место об одном
предмете.

**Неразбираемый идентификатор поднимает СОБСТВЕННЫЙ ОТКАЗ, а не вердикт.**
Строка, не являющаяся идентификатором кейса, означает, что испытуемый не
понимает поданного, а «не знаю» никогда не выдаётся за «нет».
"""

import re

from . import outcome
from . import registry

# Порядковый номер базового кейса серии — первой половины инверсии рождения.
SERIES_BASE_ORDINAL = 1

# Читается ОДНО поле идентификатора, уже проверенного `registry.family_of`:
# грамматика ID целиком принадлежит ей, здесь берётся только хвост.
_ORDINAL = re.compile(r"-(\d+)$")


def _ordinal(case_id):
    """Порядковый номер кейса внутри его серии."""
    match = _ORDINAL.search(str(case_id))
    if not match:
        raise outcome.SelfFailure(
            outcome.SELF_CASE_ID_UNPARSEABLE,
            "у идентификатора кейса нет порядкового номера: %r" % (case_id,),
        )
    return int(match.group(1))


def lost_acceptance_id(mapping):
    """Потеряна ли в поданном package tasks mapping половина инверсии рождения.

    `mapping` — то, что вернул `world.read_all(...)`: последовательность
    идентификаторов кейсов.
    """
    if not isinstance(mapping, (list, tuple)):
        raise outcome.SelfFailure(
            outcome.SELF_WORLD_MALFORMED,
            "package tasks mapping обязан быть последовательностью "
            "идентификаторов кейсов, получено %s" % type(mapping).__name__,
        )
    if not mapping:
        return True
    groups = {}
    for case_id in mapping:
        family = registry.family_of(case_id)
        groups.setdefault(family, {})[str(case_id)] = _ordinal(case_id)
    for members in groups.values():
        base_present = SERIES_BASE_ORDINAL in members.values()
        derived_present = len(members) > 1
        if not (base_present and derived_present):
            return True
    return False
