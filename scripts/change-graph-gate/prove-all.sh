#!/usr/bin/env bash
# Прогонщик ДОРОГОЙ полосы контура SDD-1 — доказательства падучести.
#
# ПОЧЕМУ ОТДЕЛЬНО ОТ НАБОРА. Имя намеренно НЕ `run-all.sh`: хук отправки выводит
# свой перечень глобом `scripts/*/run-all.sh`, и попади эта полоса под него,
# каждая отправка воркспейса платила бы 17 минут за прогон, которого она не
# касается. Хук, отвечающий четверть часа, начинают обходить — и тогда он не
# защищает ничего.
#
# ЗАМЕР, НА КОТОРОМ ВЫБРАНА ГРАНИЦА (`61fddcc`, одна машина, последовательно):
#
#   selftest/inject.py                        865.7 с  46 инъекций с контролем
#   selftest/prove_run_progress.py             73.6 с  8 утверждений
#   tests/selfcheck/prove_matrix_listing.sh    58.0 с 11 утверждений
#   tests/selfcheck/inject.sh                  34.2 с 10 инъекций
#                                           ─────────
#                                            ~17.3 мин
#
# Граница совпала с ПРЕДМЕТОМ, и это не совпадение: дешёвое отвечает на вопрос
# «работает ли контур», дорогое — на вопрос «СПОСОБЕН ли контур упасть», а
# доказательство падучести есть повторный прогон испытуемого по разу на каждую
# инъекцию.
#
# ГДЕ ЭТО ИСПОЛНЯЕТСЯ И ЧЕМ ЗАМЕТНО КРАСНОЕ. Заданием конвейера на MR в `main` —
# в тот самый момент, когда работа садится; красное видно в перечне проверок PR
# и на стволе после слияния. Что задание вообще объявлено и что процесс, которому
# оно принадлежит, срабатывает на `main`, держит
# `check-03-ci-calls-every-artifact-of-the-set.sh`, читающий разобранный YAML.
#
# ЧЕГО ЭТО НЕ ДАЁТ — названо прямо. Имя задания не входит в перечень
# обязательных контекстов защиты ветки `main`, поэтому его красное ВИДНО, но
# слияние не блокирует. Предикат остатка:
#
#   gh api repos/PRO-Robotech/kacho-workspace/branches/main/protection \
#     --jq '.required_status_checks.contexts[]' | grep -c 'оснастка контура'
#
# Ноль означает, что вторая половина ещё не закрыта; закрывается она настройкой
# репозитория, а не деревом.
#
# Вердикт из числа: 0 — все пробы полосы зелены; 1 — находка; 2 — сверять не с чем.

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

python3 "$SCRIPT_DIR/lanes.py" --run ci
rc=$?

echo
case "$rc" in
    0) echo "change-graph-gate: дорогая полоса зелена" ;;
    2) echo "change-graph-gate: дорогая полоса БЕЗ ПРЕДМЕТА — условие не создано, в успех не засчитано" >&2 ;;
    *) echo "change-graph-gate: дорогая полоса КРАСНАЯ (код $rc)" >&2 ;;
esac
exit "$rc"
