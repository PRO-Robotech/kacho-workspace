#!/usr/bin/env bash
# Прогонщик набора change-graph-gate — ДЕШЁВАЯ полоса оснастки контура SDD-1.
#
# Хук отправки выводит свой перечень из дерева (`git ls-files
# 'scripts/*/run-all.sh'`), поэтому одно существование этого файла и включает
# набор в локальную отправку — правки хука не требуется. До ws#504 каталога
# контура в этом выводе не было, и его кейсы, инъекции и пробы исполнялись
# только вручную; поломки прожили на стволе незамеченными.
#
# «Сверять не с чем» (код 2) не засчитывается за успех: один и тот же ноль
# иначе означал бы и сошедшийся контур, и контур, который не с чем было сверить.
#
# Устройство прогона — одно на все наборы: `scripts/lib/suite-runner.sh` (три
# исхода и их коды, пустой обход — находка, объём осмотренного обязателен,
# рабочий каталог проверки — пустой чужой репозиторий). Своей копии цикла у
# набора нет: свойство, заведённое в одной копии, до ws#762 не доезжало до
# соседних.
# shellcheck source-path=SCRIPTDIR
set -uo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=../lib/suite-runner.sh
. "$here/../lib/suite-runner.sh"
suite_run "$here"
