#!/usr/bin/env bash
# Прогонщик набора change-graph-gate — ДЕШЁВАЯ полоса оснастки контура SDD-1.
#
# Хук отправки выводит свой перечень из дерева (`git ls-files
# 'scripts/*/run-all.sh'`), поэтому одно существование этого файла и включает
# набор в локальную отправку — правки хука не требуется. До ws#504 каталога
# контура в этом выводе не было, и его 196 кейсов, 42 инъекции и пять проб
# исполнялись только вручную; две поломки прожили на стволе незамеченными.
#
# Вердикт выносится ИЗ ЧИСЛА, а не из печати. «Сверять не с чем» (код 2) не
# засчитывается за успех и печатается отдельной строкой: один и тот же ноль
# иначе означал бы и сошедшийся контур, и контур, который не с чем было сверить.

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

ok=0; bad=0; void=0; count=0
for c in "$SCRIPT_DIR"/check-*.sh; do
    # Глоб, не нашедший ни одного файла, подставляет САМ СЕБЯ. Счётчик делает
    # пустой обход РЕШЕНИЕМ, а не случайностью, и позволяет назвать объём
    # осмотренного отдельной строкой.
    [ -f "$c" ] || continue
    count=$((count + 1))
    bash "$c"
    case $? in
        0) ok=$((ok + 1)) ;;
        2) void=$((void + 1)) ;;
        *) bad=$((bad + 1)) ;;
    esac
done

echo
if [ "$count" -gt 0 ]; then
    echo "change-graph-gate: рассмотрено проверок $count; пройдено $ok, провалено $bad, без предмета $void"
else
    echo "change-graph-gate: рассмотрено проверок 0 в $SCRIPT_DIR — предпосылка не резолвится, прогонять нечего" >&2
fi

# ── ВЕРДИКТ: ТРИ ИСХОДА, И У КАЖДОГО СВОЙ КОД ────────────────────────────────
#
#   0 — рассмотрено N, находок 0, у каждой проверки был предмет;
#   1 — НАХОДКА: проверка упала, либо обход пуст (о дереве не прочитано ничего);
#   2 — БЕЗ ПРЕДМЕТА: находок нет, но часть проверок не с чем было сверять.
#
# ПОРЯДОК ПРОВЕРКИ КОДОВ НЕСУЩИЙ. Находка объявляется ПЕРВОЙ: набор, где есть и
# находка, и беспредметная проверка, обязан выйти единицей. Обратный порядок
# сделал бы «без предмета» маской — достаточно одной беспредметной проверки,
# чтобы настоящая находка перестала блокировать. Это свойство держит не
# комментарий, а `scripts/tooling-gate/check-07-runner-void-distinct-from-finding.sh`:
# он кладёт рядом с копией этого файла заглушки с заданными кодами и читает
# исход.
#
# ПУСТОЙ ОБХОД ОСТАЁТСЯ НАХОДКОЙ (код 1): ноль рассмотренных проверок означает,
# что каталог переехал и о дереве не прочитано НИЧЕГО, — это отказ самого
# набора, а не отсутствие условия у отдельной проверки.

[ "$count" -gt 0 ] || exit 1
[ "$bad" -eq 0 ] || exit 1
[ "$void" -eq 0 ] || exit 2
exit 0
