"""ЕДИНСТВЕННЫЙ резолв ствола дерева ПРОДУКТА для проверок оснастки.

ЗАЧЕМ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ. Проверки оснастки судят ЧУЖОЕ дерево — репозиторий
продукта, склонированный рядом. Судить его можно по двум разным полосам, и они
дают РАЗНЫЕ ответы: индекс рабочей копии (`ls-files`) отвечает о том, на чём
копия стоит СЕЙЧАС, а ствол (`ls-tree <ссылка>`) — о том, к чему сходится работа
всех. Копия общая, её парконули на чужой релизной линии, и первая полоса начала
объявлять несуществующим то, что на стволе есть.

Цена измерена, а не предположена (2026-09-12, ws#621): `check-03-holding-claim-
resolves` читал индекс и назвал 11 претензий приёмки непроверяемыми, а
`skills-gate/06` — объявление «сайтов 8» разошедшимся с деревом, где их 7. Оба
вердикта ЛОЖНЫ о продукте: на стволе все 11 координат резолвятся, а восьмой сайт
документации есть. Отправка любой ветки воркспейса при этом была остановлена
хуком — то есть класс перестал быть тихим и стал блокирующим.

ПОЧЕМУ РЕЗОЛВ ОДИН, А НЕ ПО ОДНОМУ У ЧИТАТЕЛЯ. До этого файла об одном предмете
говорили ПЯТЬ читателей на ЧЕТЫРЕ разные полосы:

  * `ls-files` — индекс копии; так читали ДВА (`docs-gate/check-03-holding-claim-
    resolves`, `skills-gate/check-06-docs-layout-matches-tree`), и оба ошибались;
  * `refs/remotes/origin/main` иначе `refs/heads/main` — выписанная пара имён;
  * `origin/main` с МОЛЧАЛИВЫМ откатом на индекс, когда ссылка не резолвится;
  * `HEAD..origin/main` — ради одного лишь числа отставания.

Два кодека об одном предмете расходятся молча — и расходятся там, где расхождение
не видно: пока копия стоит на стволе, различие ненаблюдаемо, а обнаруживается оно
ровно тогда, когда копию парконули.

ЧТО ЗДЕСЬ НЕ ДЕЛАЕТСЯ. Ссылка слежения НЕ ПОДТЯГИВАЕТСЯ: `fetch` — сеть, время и
запись в ЧУЖОЙ репозиторий, а проверки гоняются перед каждой отправкой. Вместо
этого возраст вершины ствола называется числом (`trunk_age_days`), чтобы «ствол
сам не обновлялся» было видно, а не подразумевалось.

ЧИТАТЕЛИ (перечень обязан сходиться с деревом; предикат —
`git grep -l 'product_trunk' -- scripts`):

  * `scripts/docs-gate/_lib.py` → и через него все четыре проверки набора;
  * `scripts/skills-gate/_lib.sh` → и через него `check-06-docs-layout-matches-tree.sh`.

РЕЖИМ CLI — для читателей на shell. Печатает `ключ<TAB>значение` по строке на
поле и выходит 0, когда ствол разрешён, и 1, когда нет. Поля НЕ склеиваются в
строку под `eval`: значение несёт имя ссылки, а подстановка чужого имени в
исполняемый текст — тот самый класс, который эти же проверки ловят в дереве.
"""
import os
import subprocess
import sys
import time
from collections import namedtuple

# Ручку читает РОВНО ОДНА функция (`forced_ref`), и это решение: три вызова
# `os.environ.get` об одном предмете разошлись бы молча на первой правке имени.
FORCE_ENV = "KACHO_PRODUCT_TRUNK_REF"

# Имена линий интеграции. Локальной ветки НЕДОСТАТОЧНО, и это не мелочь
# настройки: `refs/heads/main` двигает только тот, кто его подтянул, а в общей
# копии продукта он отстаёт от `refs/remotes/origin/main`. Полоса ствола,
# прочитанная по такой ссылке, объявляет несуществующим ВСЁ, что посажено за это
# время, — то есть ровно свежую работу, ради которой вторая полоса и заводилась.
# Поэтому ветки слежения входят в кандидаты наравне с локальными и при равном
# перевесе выигрывают: линия интеграции — то, к чему сходится работа ВСЕХ, а не
# копия имени в одном клоне.
TRUNK_BRANCH_NAMES = ("main", "master")

Trunk = namedtuple("Trunk", (
    "ref",            # имя ссылки ствола либо None
    "rev",            # полная ревизия вершины ствола либо None
    "behind",         # коммитов ствола, которых нет в HEAD копии
    "ahead",          # коммитов HEAD копии, которых нет в стволе
    "head",           # полная ревизия HEAD копии
    "trunk_age_days", # возраст ВЕРШИНЫ ствола в сутках либо None
    "candidates",     # что искали, когда не нашли
))


def _git(repo, *args):
    out = subprocess.run(["git", "-C", repo] + list(args),
                         capture_output=True, text=True)
    if out.returncode != 0:
        return []
    return [line for line in out.stdout.split("\n") if line]


def _count(repo, spec):
    out = _git(repo, "rev-list", "--count", spec)
    return int(out[0]) if out and out[0].strip().isdigit() else 0


def forced_ref():
    """ЕДИНСТВЕННЫЙ читатель ручки назначения ствола.

    Ручку читают два места — перечень кандидатов и отбор, — и второму нужен
    ответ «назначали ли вообще», чтобы не подменять осознанное назначение
    проверкой родства.
    """
    return os.environ.get(FORCE_ENV) or None


def candidates(repo, ignore_forced=False):
    """Кандидаты ствола ВЫВОДЯТСЯ из ссылок дерева, а не выписываются.

    Ветки слежения перечисляются `for-each-ref` по образцу `refs/remotes/*/<имя>`,
    а не собираются из выписанного имени удалённого: «наверное origin» разошлось
    бы с деревом молча — ровно тот класс, который эти проверки ловят в чужой
    прозе. У общей копии продукта удалённых ДВА, и второй зовётся не `origin`.

    Порядок (сначала слежение, потом локальные) задаёт разрешение ничьей.

    Назначенный ствол резолвится ЗДЕСЬ, а не отдельной ветвью выше: перечень
    кандидатов печатается в переписи, когда ствол не найден, и обязан называть
    то, что искали НА САМОМ ДЕЛЕ.
    """
    forced = None if ignore_forced else forced_ref()
    if forced:
        return [forced]
    remote = _git(repo, "for-each-ref", "--format=%(refname:short)",
                  *["refs/remotes/*/%s" % n for n in TRUNK_BRANCH_NAMES])
    local = [n for n in TRUNK_BRANCH_NAMES
             if _git(repo, "rev-parse", "--verify", "--quiet", n + "^{commit}")]
    return remote + local


def resolve(repo):
    """Ствол ВЫВОДИТСЯ из дерева, а не назначается именем. → Trunk.

    Из кандидатов берётся тот, у кого больше всего коммитов, которых нет в HEAD,
    — наиболее продвинутая линия интеграции. Правило измеримое, поэтому оно
    переживает смену ствола само; назначенное имя при той же смене стало бы
    ложью молча. Ничья разрешается ПОРЯДКОМ кандидатов (`>`, не `>=`): победа
    остаётся за первым, а первыми идут ветки слежения.

    КАНДИДАТ С НЕСВЯЗНОЙ ИСТОРИЕЙ СТВОЛОМ ЭТОГО ДЕРЕВА НЕ БЫВАЕТ — и это не
    эвристика, а определение: линия интеграции обязана делить с HEAD хотя бы
    один коммит. Правило «больше всего коммитов вне HEAD» писалось при допущении,
    что все кандидаты — линии ОДНОГО продукта; второй удалённый с чужой историей
    это допущение снимает, и снимает МОЛЧА: чем архив дальше от дерева, тем
    увереннее он выигрывает отбор.

    Наблюдалось 2026-09-12 на общей копии продукта: рядом с `origin` стоял
    удалённый на архив прежнего полирепо службы доступа, и отбор без этого
    фильтра дал бы `archive/main` — 67 коммитов, которых нет в HEAD, против 0 у
    `origin/main`. Предикат исключения точный: `merge-base` отказывает ровно
    тогда, когда общего коммита нет (проверено в обе стороны — у архива отказ, у
    `origin/main` успех).

    Назначенный ствол фильтр родства НЕ проходит: его назначают осознанно, и
    подменять это решение проверкой родства значило бы отменять вход пробы её же
    основанием.
    """
    forced = forced_ref()
    head_out = _git(repo, "rev-parse", "HEAD")
    head = head_out[0] if head_out else ""
    best_ref, best_rev, best_behind = None, None, -1
    for cand in candidates(repo):
        rev = _git(repo, "rev-parse", "--verify", "--quiet", cand + "^{commit}")
        if not rev:
            continue
        if not forced and not _git(repo, "merge-base", "HEAD", cand):
            continue
        behind = _count(repo, "HEAD..%s" % cand)
        if behind > best_behind:
            best_ref, best_rev, best_behind = cand, rev[0], behind

    if best_ref is None:
        return Trunk(None, None, 0, 0, head, None, candidates(repo))

    ahead = _count(repo, "%s..HEAD" % best_ref)
    age = None
    # Возраст ВЕРШИНЫ ствола — то есть основания, по которому вынесен вердикт.
    # Меряется дата КОММИТА вершины, а не время обновления ссылки: журнал ссылки
    # может быть обрезан или отключён вовсе, и тогда молчание было бы неотличимо
    # от свежести. Дата вершины отвечает на нужный вопрос напрямую — вердикт не
    # свежее того, с чем сравнивали.
    ts = _git(repo, "log", "-1", "--format=%ct", best_ref)
    if ts and ts[0].strip().isdigit():
        age = max(0, int((time.time() - int(ts[0])) // 86400))
    return Trunk(best_ref, best_rev, best_behind, ahead, head, age, [])


def lag(t):
    """Расхождение копии со стволом — ЧИСЛОМ, а не словом.

    «Вровень» — утверждение о РАВЕНСТВЕ РЕВИЗИЙ, а не о нуле в одном счётчике:
    ноль в `behind` означает лишь «ствол не содержит ничего, чего нет у меня», и
    копия, ушедшая вперёд, даёт тот же ноль. Поэтому равенство проверяется
    сравнением ревизий, а оба направления печатаются, когда расходятся: ветка,
    ушедшая вперёд и отставшая одновременно, — законное состояние, и молчать о
    нём нельзя.
    """
    if t.ref is None:
        return "ствол НЕ РАЗРЕШЁН (искали: %s)" % (", ".join(t.candidates) or "нечего")
    where = "ствол %s %s" % (t.ref, t.rev[:8])
    if t.trunk_age_days is not None and t.trunk_age_days > 7:
        where += " (вершина старше %d дн. — ссылку никто не тянул)" % t.trunk_age_days
    if t.rev == t.head:
        return where + "; рабочая копия ВРОВЕНЬ с ним"
    parts = []
    if t.behind:
        parts.append("ОТСТАЁТ на %d" % t.behind)
    if t.ahead:
        parts.append("ушла вперёд на %d" % t.ahead)
    return "%s; рабочая копия @%s %s" % (
        where, t.head[:8] or "?", " и ".join(parts) or "иная ревизия")


def files(repo, t, *pathspec):
    """Состав дерева продукта на СТВОЛЕ. Ствол не разрешён — пусто, а не индекс.

    Молчаливый откат на индекс запрещён: он и есть тот дефект, ради которого этот
    модуль заведён. Читатель обязан увидеть `ref is None` и ответить третьей
    категорией сам — своим текстом, потому что «проверять нечего» у каждого своё.
    """
    if t.ref is None:
        return set()
    return set(_git(repo, "ls-tree", "-r", "--name-only", t.ref, "--", *pathspec))


def show(repo, t, rel):
    """Содержимое файла на стволе либо None. Ствол не разрешён — None."""
    if t.ref is None:
        return None
    out = subprocess.run(["git", "-C", repo, "show", "%s:%s" % (t.ref, rel)],
                         capture_output=True, text=True)
    return out.stdout if out.returncode == 0 else None


def _cli(argv):
    if len(argv) != 2:
        print("usage: product_trunk.py <каталог дерева продукта>", file=sys.stderr)
        return 2
    t = resolve(argv[1])
    rows = (
        ("ref", t.ref or ""),
        ("rev", t.rev or ""),
        ("rev_short", (t.rev or "")[:8]),
        ("behind", t.behind),
        ("ahead", t.ahead),
        ("head", t.head),
        ("head_short", (t.head or "")[:8]),
        ("age_days", "" if t.trunk_age_days is None else t.trunk_age_days),
        ("candidates", " ".join(t.candidates)),
        ("lag", lag(t)),
    )
    for key, value in rows:
        sys.stdout.write("%s\t%s\n" % (key, value))
    return 0 if t.ref else 1


if __name__ == "__main__":
    sys.exit(_cli(sys.argv))
