#!/usr/bin/env bash
# run-suites — исполнить КАЖДЫЙ набор проверок дерева: перечень выводится, а не
# выписывается.
#
# ЗАЧЕМ. Конвейер звал наборы поимённо, и набор, заведённый в дереве, но не
# вписанный в конвейер, не исполнялся на стволе — молча (ws#753: в дереве наборов
# было больше, чем вызовов; ws#817 — у одного из них не было задания вовсе).
# Выписанный перечень — второй носитель факта «какие наборы есть», и отстаёт он в
# ту сторону, где «не выполнено» читается как «зелено». Здесь перечень выводит
# перепись `scripts/lib/suites.py` из индекса git, и второго дома у него нет. Что
# конвейер зовёт ИМЕННО вывод, а не перечень, держит
# `scripts/suites-gate/check-04-ci-calls-every-suite.py`.
#
# ИСХОД НЕ ИЗ ОДНОГО КАНАЛА. Код набора сверяется с его машинной строкой
# переписи (`SUITE_SUMMARY`, её пишет общий прогонщик): набор, вернувший код, но
# не отчитавшийся о числе рассмотренных проверок, — находка, а не зелёное.
# Строка не просто существует, а СОГЛАСНА с кодом: исполнено больше нуля;
# пройдено + провалено + без предмета = исполнено; код 0 — без провалов и
# беспредметных, код 2 — без провалов и хотя бы с одной беспредметной, код 1 —
# хотя бы с одним провалом. Набор, вышедший нулём над «исполнено 0», — находка.
# Расхождение «наборов в дереве × исполнено» печатается числом и краснит.
#
# ЧЕМ ЭТО ДЕРЖИТСЯ — проба исхода, а не текст вызова:
# `scripts/suites-gate/check-09-derived-run-reads-every-channel.py` гоняет ЭТОТ
# файл в песочнице с синтетическими наборами (беспредметный при
# `--void-is-failure`, не отчитавшийся, с красным и с отсутствующим
# доказательством, «исполнено 0», код, разошедшийся со строкой, пустая
# перепись) и требует единицы; близнецы — ноль и двойка. `check-04` и
# `change-graph-gate/check-03` судят только то, что конвейер ЗОВЁТ этот файл.
#
# ПО ЗАДАНИЯМ (`--job`, возврат по #816). Защита `main` требует контексты конвейера
# поимённо, а имя контекста — `name:` задания: одно задание на все наборы дало бы
# один контекст вместо требуемых. Поэтому задание зовёт этот файл с
# `--job "$GITHUB_JOB"` и исполняет наборы, объявившие его ключ файлом
# `scripts/<набор>/ci-job`. Перечень по-прежнему выводится из индекса — выбор
# делается по объявлению набора, а не по списку в конвейере. Прежде чем исполнить
# своё, задание спрашивает `scripts/lib/ci_suites.py`, покрывает ли разметка ВСЁ
# дерево: набор, который не исполняет ни одно задание (объявления нет, объявлено
# несуществующее задание, задание не зовёт вывод), роняет КАЖДОЕ задание, а не
# только то, что его потеряло, — иначе задание, лишившееся шага вывода, зеленело
# бы под своим именем, ничего не исполнив, и сказать об этом было бы некому.
# Ни один набор не объявил задание — находка: пустой выбор был бы зелёным.
#
# ИСПОЛЬЗОВАНИЕ:
#   bash scripts/lib/run-suites.sh [--proofs] [--void-is-failure] [--job <ключ задания>]
#     --proofs           перед прогоном набора исполнить его доказательство
#                        (`inject.sh`) — так делает конвейер;
#     --void-is-failure  «без предмета» роняет прогон: в конвейере предпосылки
#                        создаёт само задание, и их отсутствие — поломка, а не факт
#                        расписания. Локально (хук отправки) код 2 остаётся своим;
#     --job <ключ>       исполнить только наборы, объявившие это задание; без
#                        ключа — каждый набор переписи.
#
# Исходы: 0 — все наборы исполнены и зелены; 1 — находка у набора или его
# доказательства, либо набор не отчитался; 2 — без предмета (без --void-is-failure).
set -uo pipefail

LIB="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$LIB/../.." && pwd)"

proofs=0; void_fails=0; job=""; by_job=0
while [ "$#" -gt 0 ]; do
    case "$1" in
        --proofs) proofs=1 ;;
        --void-is-failure) void_fails=1 ;;
        --job)
            if [ "$#" -lt 2 ] || [ -z "$2" ]; then
                echo "run-suites: ключ --job без ключа задания" >&2; exit 2
            fi
            job="$2"; by_job=1; shift ;;
        --job=*)
            job="${1#--job=}"; by_job=1
            [ -n "$job" ] || { echo "run-suites: ключ --job без ключа задания" >&2; exit 2; } ;;
        *) echo "run-suites: неизвестный ключ $1" >&2; exit 2 ;;
    esac
    shift
done

if ! mapfile -t SUITES < <(python3 "$LIB/suites.py" suites "$ROOT"); then
    echo "[VOID] run-suites — перепись наборов не снята" >&2
    exit 2
fi
# `mapfile` из пустого вывода даёт массив из одной пустой строки не всегда —
# отсекаем пустые имена явно.
names=()
for s in "${SUITES[@]}"; do [ -n "$s" ] && names+=("$s"); done
if [ "${#names[@]}" -eq 0 ]; then
    echo "[FAIL] run-suites — в дереве нет ни одного scripts/*/run-all.sh: пустой обход здесь был бы зелёным при снятых проверках" >&2
    exit 1
fi
in_tree="${#names[@]}"

if [ "$by_job" -eq 1 ]; then
    # Выбор — ответ `ci_suites.py` о ВСЁМ дереве: код 1 — разметка не покрывает
    # дерево, и задание не исполняет своё, пока она не исправлена.
    members="$(python3 "$LIB/ci_suites.py" members "$ROOT" "$job")"; mrc=$?
    if [ "$mrc" -eq 2 ]; then
        echo "[VOID] run-suites — разметку наборов по заданиям не прочитать: что исполняет задание $job, не выводится" >&2
        [ "$void_fails" -eq 1 ] && exit 1
        exit 2
    fi
    if [ "$mrc" -ne 0 ]; then
        echo "[FAIL] run-suites — разметка наборов по заданиям не покрывает дерево (код $mrc): задание $job не исполняется, пока она не исправлена" >&2
        exit 1
    fi
    names=()
    while IFS= read -r s; do [ -n "$s" ] && names+=("$s"); done <<<"$members"
    if [ "${#names[@]}" -eq 0 ]; then
        echo "[FAIL] run-suites — ни один набор не объявил задание $job (scripts/<набор>/ci-job): задание судило бы пустоту" >&2
        exit 1
    fi
fi

summary="$(mktemp)"
trap 'rm -f "$summary"' EXIT

# _row_disagrees <код> <исполнено> <пройдено> <провалено> <без предмета> —
# печатает, чем строка переписи расходится с кодом набора; пусто — согласны.
_row_disagrees() {
    local rc="$1" n="$2" ok="$3" b="$4" v="$5" x
    for x in "$n" "$ok" "$b" "$v"; do
        case "$x" in
            ''|*[!0-9]*) echo "строка переписи не числовая: «$n $ok $b $v»"; return ;;
        esac
    done
    if [ "$n" -eq 0 ]; then
        echo "исполнено 0 — о дереве не прочитано ничего"; return
    fi
    if [ $((ok + b + v)) -ne "$n" ]; then
        echo "пройдено $ok + провалено $b + без предмета $v не равно исполнено $n"; return
    fi
    case "$rc" in
        0) { [ "$b" -eq 0 ] && [ "$v" -eq 0 ]; } || echo "код 0 при провалено $b, без предмета $v" ;;
        1) [ "$b" -gt 0 ] || echo "код 1 при провалено 0" ;;
        2) { [ "$b" -eq 0 ] && [ "$v" -gt 0 ]; } || echo "код 2 при провалено $b, без предмета $v" ;;
    esac
}

red=(); voided=(); unreported=(); proof_red=(); disagree=(); lines=()
ran=0
for s in "${names[@]}"; do
    echo "══ $s"
    prc="—"
    if [ "$proofs" -eq 1 ]; then
        if [ -f "$ROOT/scripts/$s/inject.sh" ]; then
            bash "$ROOT/scripts/$s/inject.sh"; prc=$?
            [ "$prc" -eq 0 ] || proof_red+=("$s (код $prc)")
        else
            prc="нет"
            proof_red+=("$s (доказательства inject.sh нет)")
        fi
    fi
    SUITE_SUMMARY="$summary" bash "$ROOT/scripts/$s/run-all.sh"; rc=$?
    ran=$((ran + 1))
    # Строка набора — ПОСЛЕДНЯЯ с его именем: прогон набора пишет её, закончив
    # все свои проверки.
    row="$(awk -F'\t' -v s="$s" '$1 == s {r = $0} END {print r}' "$summary")"
    if [ -z "$row" ]; then
        unreported+=("$s")
        lines+=("$s · исполнено ? · красных ? · не выполнилось ? · код $rc · доказательство $prc — набор не отчитался о переписи")
        continue
    fi
    IFS=$'\t' read -r _ n ok b v <<<"$row"
    lines+=("$s · исполнено $n · красных $b · не выполнилось $v · код $rc · доказательство $prc")
    why="$(_row_disagrees "$rc" "$n" "$ok" "$b" "$v")"
    [ -z "$why" ] || disagree+=("$s ($why)")
    case "$rc" in
        0) ;;
        2) voided+=("$s") ;;
        *) red+=("$s") ;;
    esac
done

echo
if [ "$by_job" -eq 1 ]; then
    echo "── наборы: в дереве $in_tree · объявили задание $job ${#names[@]} · исполнено $ran"
else
    echo "── наборы: в дереве $in_tree · исполнено $ran"
fi
printf '   %s\n' "${lines[@]}"

fail=0
if [ "$ran" -ne "${#names[@]}" ]; then
    echo "[FAIL] run-suites — наборов к исполнению ${#names[@]}, исполнено $ran" >&2; fail=1
fi
if [ "${#unreported[@]}" -gt 0 ]; then
    echo "[FAIL] run-suites — не отчитались о переписи: ${unreported[*]} (прогонщик набора не общий либо оборвался)" >&2; fail=1
fi
if [ "${#disagree[@]}" -gt 0 ]; then
    echo "[FAIL] run-suites — код набора расходится с его строкой переписи: ${disagree[*]}" >&2; fail=1
fi
if [ "${#proof_red[@]}" -gt 0 ]; then
    echo "[FAIL] run-suites — доказательство не сошлось: ${proof_red[*]}" >&2; fail=1
fi
if [ "${#red[@]}" -gt 0 ]; then
    echo "[FAIL] run-suites — красные наборы: ${red[*]}" >&2; fail=1
fi
[ "$fail" -eq 0 ] || exit 1
if [ "${#voided[@]}" -gt 0 ]; then
    if [ "$void_fails" -eq 1 ]; then
        echo "[FAIL] run-suites — без предмета: ${voided[*]}; предпосылки здесь создаёт само задание, их отсутствие — поломка" >&2
        exit 1
    fi
    echo "[VOID] run-suites — без предмета: ${voided[*]}; находок нет, но эти наборы не выполнились целиком" >&2
    exit 2
fi
if [ "$by_job" -eq 1 ]; then
    echo "[PASS] run-suites — задание $job: наборов ${#names[@]} из $in_tree в дереве, все исполнены и зелены; разметка покрывает дерево"
else
    echo "[PASS] run-suites — наборов ${#names[@]}, все исполнены и зелены"
fi
