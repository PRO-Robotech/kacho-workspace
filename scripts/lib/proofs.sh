#!/usr/bin/env bash
# Части доказательства набора и его окружение. Только для подключения из
# `scripts/<набор>/inject.sh`.
#
# ЗАЧЕМ. Вход доказательства набора — ОДИН: `inject.sh` (так его зовёт конвейер —
# `scripts/lib/run-suites.sh --proofs`, и так считает перепись
# `scripts/lib/suites.py`). Части (`inject-<N>*.sh` рядом) вход обязан исполнить
# сам: часть, которую не зовёт никто, отличается от отсутствующей только тем, что
# создаёт уверенность. Прежде один набор делал это своим циклом, другой полагался
# на то, что части выпишет конвейер поимённо, — два устройства одного правила.
#
# Перечень частей ВЫВОДИТСЯ из каталога. Ноль найденных — отказ: пустой обход здесь
# означал бы «доказано всё» ровно тогда, когда не доказано ничего.
#
# proof_parts <каталог набора>
#   исполняет каждую часть; выставляет PROOF_PARTS (сколько исполнено) и
#   PROOF_PARTS_BAD (сколько не сошлось; «не выполнилось» тоже не сошлось).
#   Возврат: 0 — все сошлись; 1 — есть несошедшаяся; 2 — частей нет.
# shellcheck disable=SC2034  # PROOF_PARTS* читает подключивший файл
proof_parts() {
    local dir="$1" p
    local -a parts=()
    PROOF_PARTS=0
    PROOF_PARTS_BAD=0
    while IFS= read -r p; do
        parts+=("$p")
    done < <(find "$dir" -maxdepth 1 -name 'inject-[0-9]*.sh' -type f | sort)
    if [ "${#parts[@]}" -eq 0 ]; then
        echo "inject: ОТКАЗ — рядом нет НИ ОДНОЙ части inject-<N>*.sh; доказывать нечем" >&2
        return 2
    fi
    for p in "${parts[@]}"; do
        echo
        echo "── $(basename "$p")"
        PROOF_PARTS=$((PROOF_PARTS + 1))
        if ! bash "$p"; then
            PROOF_PARTS_BAD=$((PROOF_PARTS_BAD + 1))
        fi
    done
    [ "$PROOF_PARTS_BAD" -eq 0 ]
}

# ── Окружение доказательства — его собственное, а не унаследованное (ws#757) ──
#
# Доказательство строит СИНТЕТИЧЕСКИЙ мир и судит, как проверка ведёт себя в нём.
# Проверка же берёт часть мира из окружения: дом репозитория продукта
# (`KACHO_HOME_<ИМЯ>`) и переопределение корня (`GATE_ROOT`, `<НАБОР>_GATE_ROOT`)
# сильнее того, что доказательство положило в песочницу. Унаследовав их от
# вызывающего, проверка судит настоящий дом вместо синтетического — и вердикт
# доказательства зависит от того, КТО его запустил: измерено на crossrepo-gate
# (при заданных `KACHO_HOME_*` ось A краснела на настоящих парах) и docs-gate
# («дома рядом нет» ждала код 2, получала 0).
#
# `proof_own_environment` снимает все унаследованные указатели этих двух родов в
# ТЕКУЩЕЙ оболочке (вызывать не в подоболочке) и печатает, сколько снято. Перечень
# переменных выводится из окружения (`compgen -e`), а не выписывается. Проба,
# которой указатель нужен, ставит его сама на своём вызове. `KACHO_MONOREPO` —
# ОБЪЯВЛЕННЫЙ вход доказательств (дерево продукта для замеров), не снимается.
#
# Что доказательство набора, чей код читает `KACHO_HOME_*`, эту функцию зовёт,
# держит `scripts/suites-gate/check-08-proof-owns-its-environment.py`; что она
# действительно делает исход независимым от унаследованного, — проба-пара в
# `scripts/suites-gate/inject.sh`.
proof_own_environment() {
    local v
    local -a dropped=()
    for v in $(compgen -e); do
        case "$v" in
            KACHO_HOME_*|GATE_ROOT|*_GATE_ROOT)
                dropped+=("$v")
                unset "$v"
                ;;
        esac
    done
    echo "окружение доказательства: снято унаследованных указателей на деревья ${#dropped[@]}${dropped[*]:+ (${dropped[*]})}"
}
