#!/usr/bin/env bash
# Общий прогонщик наборов проверок. Только для подключения: его зовёт
# `scripts/<набор>/run-all.sh` одной строкой `suite_run <каталог набора>`.
#
# ЗАЧЕМ ОДИН ПРОГОНЩИК. До ws#762 у каждого набора был свой — по копии одного
# цикла на набор, и каждое новое свойство прогона (третий исход, пустой обход,
# перепись) заводилось по разу на копию и расходилось между ними молча: у одного
# набора глоб `check-*.sh`, у другого `check-*` с битом исполнения, у третьего
# любой `check-*`. Свойство, написанное здесь, есть у всех наборов сразу, и набор,
# который перестал звать этот файл, виден пробе
# `scripts/suites-gate/check-03-runner-demands-a-printed-volume.py`.
#
# ЧТО ПРОГОН ГАРАНТИРУЕТ — и чем каждое держится:
#
#   ТРИ ИСХОДА, И У КАЖДОГО СВОЙ КОД: 0 — рассмотрено N, находок нет, у каждой
#   проверки был предмет; 1 — находка (либо обход пуст: о дереве не прочитано
#   ничего); 2 — без предмета: находок нет, но часть проверок сверять было не с
#   чем. Находка объявляется ПЕРВОЙ: беспредметная проверка рядом с находкой не
#   делает набор беспредметным — иначе «без предмета» стало бы маской.
#   Держат `scripts/tooling-gate/check-04-*` и `check-07-*`.
#
#   ИСХОД НЕ ИЗ ОДНОГО КАНАЛА (ws#762 п.1–2). Код сверяется с выводом проверки
#   (оба потока — то, что видит читатель):
#     * код 0 засчитывается, только если проверка НАПЕЧАТАЛА объём осмотренного —
#       отдельное число: цифры, не входящие в слово, адрес или номер
#       (`check-04`, `ws#757`, `2026-09-28`, `v2` числом не считаются). Строку
#       `[PASS] check-NN-<имя>` печатает каждая проверка дерева, и прежнее
#       «в выводе есть цифра» выполнялось номером в её собственном имени — ноль
#       без объёма засчитывался любой проверке. Что найденное число — именно
#       знаменатель, прогонщик не судит: это нижняя граница формы, и она названа;
#     * код 2 засчитывается за «без предмета», только если проверка напечатала
#       строку `[VOID] <причина>`. Код 2 отдаёт и сам интерпретатор (синтаксическая
#       ошибка оболочки, отказ разбора аргументов у python), и сломанная проверка
#       без этого условия неотличима от «нет клона продукта», а хук отправки на
#       коде 2 не останавливается. Код 2 без такой строки — находка.
#   Держит `scripts/suites-gate/check-03-runner-demands-a-printed-volume.py`:
#   заглушка, напечатавшая только свой адрес, и заглушка с синтаксической
#   ошибкой обязаны дать 1, их близнецы (объём; `[VOID]` с причиной) — 0 и 2.
#
#   РАБОЧИЙ КАТАЛОГ ПРОВЕРКИ — ПУСТОЙ ЧУЖОЙ РЕПОЗИТОРИЙ (ws#757). Проверка,
#   взявшая корень из рабочего каталога, увидит пустое дерево и не выйдет нулём
#   над настоящим. Каталог заводится `git init`, а не просто `mktemp -d`: временный
#   каталог внутри рабочей копии (`TMPDIR` под воркспейсом) иначе отдал бы
#   `git rev-parse --show-toplevel` сам воркспейс — и защита молча исчезла бы.
#   `git init`, который не удался, — «без предмета» набора, а не молчаливое
#   продолжение без защиты. Держит check-03: его проба кладёт `TMPDIR` внутрь
#   рабочей копии песочницы и не наследует его у вызывающего.
#
#   ПЕРЕПИСЬ ОТДЕЛЬНОЙ СТРОКОЙ и, если задан `SUITE_SUMMARY`, машинной строкой в
#   этот файл — для `scripts/lib/run-suites.sh`, которому нужен второй канал
#   помимо кода: набор, не отчитавшийся о переписи, он объявляет находкой.
#
# ОБРАЗЕЦ ИМЕНИ ПРОВЕРКИ — `check-*`, ТОТ ЖЕ, ЧТО В ПЕРЕПИСИ `scripts/lib/suites.py`.
# Прогонщик обходит ДИСК (исполняет лежащее), перепись — ИНДЕКС (судит
# отправляемое). Способ исполнения — по расширению: `.py` — python3, `.sh` —
# bash, иначе — сам файл при бите исполнения; файл без способа исполнения —
# находка, а не молчаливый пропуск (прежде один из наборов пропускал его молча).

# _suite_volume_printed <журнал> — в выводе есть отдельное число: цифры, по
# обе стороны которых нет ни буквы, ни цифры, ни `_`, ни `-`, ни `#`. Так
# отсекаются адрес проверки (`check-04-…`), номер задачи (`ws#757`), дата и
# версия; в `C.UTF-8` кириллица — буква, и «проверок8» числом тоже не считается.
_suite_volume_printed() {
    LC_ALL=C.UTF-8 grep -Eq -- '(^|[^[:alnum:]_#-])[0-9]+([^[:alnum:]_#-]|$)' "$1"
}

# _suite_void_declared <журнал> — проверка объявила «без предмета» строкой
# `[VOID]` с непустой причиной.
_suite_void_declared() {
    grep -Eq -- '\[VOID\][[:space:]]*[^[:space:]]' "$1"
}

# suite_run <каталог набора>
suite_run() {
    local dir="$1"
    local name ok=0 bad=0 void=0 count=0 rc c neutral log
    local -a argv
    name="$(basename "$dir")"
    neutral="$(mktemp -d)" || { echo "[VOID] $name — не завёлся рабочий каталог проверок" >&2; return 2; }
    log="$(mktemp)" || { rm -rf "$neutral"; echo "[VOID] $name — не завёлся журнал проверки" >&2; return 2; }
    if ! git -C "$neutral" init -q; then
        rm -rf "$neutral" "$log"
        echo "[VOID] $name — рабочий каталог проверок не стал своим git-репозиторием: без него проверка внутри рабочей копии увидела бы её дерево" >&2
        return 2
    fi

    for c in "$dir"/check-*; do
        # Глоб без совпадений подставляет САМ СЕБЯ: без этой строки пустой
        # каталог давал бы одну «проверку», и ветка пустого обхода стала бы
        # недостижимой.
        [ -f "$c" ] || continue
        count=$((count + 1))
        case "$c" in
            *.py) argv=(python3 "$c") ;;
            *.sh) argv=(bash "$c") ;;
            *)
                if [ -x "$c" ]; then
                    argv=("$c")
                else
                    echo "[FAIL] $name — $(basename "$c"): ни расширения, ни бита исполнения — проверку нечем исполнить" >&2
                    bad=$((bad + 1))
                    continue
                fi
                ;;
        esac
        # Код берётся у ПРОВЕРКИ (PIPESTATUS[0]), а не у трубы: `tee` не выходит
        # раньше писателя, и его код о проверке не говорит ничего. Журнал несёт
        # ОБА потока: причину `[VOID]` и перепись проверки пишут и в stderr.
        # `SUITE_SUMMARY` — канал ЭТОГО прогона: проверка, пробующая прогонщики
        # в песочнице, писала бы в него строки чужих (песочных) наборов.
        ( cd "$neutral" && env -u SUITE_SUMMARY "${argv[@]}" ) 2>&1 | tee "$log"
        rc=${PIPESTATUS[0]}
        case "$rc" in
            0)
                if _suite_volume_printed "$log"; then
                    ok=$((ok + 1))
                else
                    echo "[FAIL] $name — $(basename "$c"): вышла нулём, не напечатав объёма осмотренного (в выводе нет ни одного числа вне адресов и номеров) — «ноль находок» неотличим от «ноль прочитанного»" >&2
                    bad=$((bad + 1))
                fi
                ;;
            2)
                if _suite_void_declared "$log"; then
                    void=$((void + 1))
                else
                    echo "[FAIL] $name — $(basename "$c"): вышла кодом 2 без строки «[VOID] <причина>» — код 2 отдал интерпретатор (синтаксис, разбор аргументов), а не проверка; сломанная проверка неотличима от «без предмета»" >&2
                    bad=$((bad + 1))
                fi
                ;;
            *) bad=$((bad + 1)) ;;
        esac
    done
    rm -rf "$neutral" "$log"

    if [ "$count" -gt 0 ]; then
        echo
        echo "$name: рассмотрено проверок $count; пройдено $ok, провалено $bad, без предмета $void"
    else
        echo "$name: рассмотрено проверок 0 в $dir — о дереве не прочитано ничего" >&2
    fi
    if [ -n "${SUITE_SUMMARY:-}" ]; then
        printf '%s\t%s\t%s\t%s\t%s\n' "$name" "$count" "$ok" "$bad" "$void" >> "$SUITE_SUMMARY"
    fi

    [ "$count" -gt 0 ] || return 1
    [ "$bad" -eq 0 ] || return 1
    [ "$void" -eq 0 ] || return 2
    return 0
}
