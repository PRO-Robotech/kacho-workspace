#!/usr/bin/env bash
# Общий прогонщик наборов проверок. Только для подключения: его зовёт
# `scripts/<набор>/run-all.sh` одной строкой `suite_run <каталог набора>`.
#
# ТРИ ИСХОДА, И У КАЖДОГО СВОЙ КОД: 0 — рассмотрено N, находок нет, у каждой
# проверки был предмет; 1 — находка (либо обход пуст: о дереве не прочитано
# ничего); 2 — без предмета: находок нет, но часть проверок сверять было не с
# чем. Находка объявляется ПЕРВОЙ: беспредметная проверка рядом с находкой не
# делает набор беспредметным — иначе «без предмета» стало бы маской.
# Держат `scripts/tooling-gate/check-04-*` и `check-07-*`.
#
# ОБРАЗЕЦ ИМЕНИ ПРОВЕРКИ — `check-*`, ТОТ ЖЕ, ЧТО В ПЕРЕПИСИ `scripts/lib/suites.py`.
# Прогонщик обходит ДИСК (исполняет лежащее), перепись — ИНДЕКС (судит
# отправляемое). Способ исполнения — по расширению: `.py` — python3, `.sh` —
# bash, иначе — сам файл при бите исполнения; файл без способа исполнения —
# находка, а не молчаливый пропуск.

# suite_run <каталог набора>
suite_run() {
    local dir="$1"
    local name ok=0 bad=0 void=0 count=0 rc c
    local -a argv
    name="$(basename "$dir")"

    for c in "$dir"/check-*; do
        # Глоб без совпадений подставляет САМ СЕБЯ: без этой строки пустой
        # каталог давал бы одну «проверку», и ветка пустого обхода стала бы
        # недостижимой.
        [ -f "$c" ] || continue
        count=$((count + 1))
        case "$c" in
            *.py) argv=(python3 "$c") ;;
            *.sh) argv=(bash "$c") ;;
            *)
                if [ -x "$c" ]; then
                    argv=("$c")
                else
                    echo "[FAIL] $name — $(basename "$c"): ни расширения, ни бита исполнения — проверку нечем исполнить" >&2
                    bad=$((bad + 1))
                    continue
                fi
                ;;
        esac
        "${argv[@]}"
        rc=$?
        case "$rc" in
            0) ok=$((ok + 1)) ;;
            2) void=$((void + 1)) ;;
            *) bad=$((bad + 1)) ;;
        esac
    done

    if [ "$count" -gt 0 ]; then
        echo
        echo "$name: рассмотрено проверок $count; пройдено $ok, провалено $bad, без предмета $void"
    else
        echo "$name: рассмотрено проверок 0 в $dir — о дереве не прочитано ничего" >&2
    fi

    [ "$count" -gt 0 ] || return 1
    [ "$bad" -eq 0 ] || return 1
    [ "$void" -eq 0 ] || return 2
    return 0
}
