#!/usr/bin/env python3
"""check-01 — у предмета со второй пропиской есть ЗАПИСАННОЕ решение.

ЧТО ЭТА ПРОВЕРКА СУДИТ

Требование владельца 2026-09-20 дословно: «все общие библиотеки, которые могут
быть вынесены должны быть вынесены в corelib а не хорониться в проекте». Норма,
которую оно порождает, ОБЯЗЫВАЕТ, а не разрешает; но обязывает она к тому, что
предикат УМЕЕТ ИЗМЕРИТЬ. «Переносимость» он не измеряет — это показано семью
контрпримерами опровержения 2026-09-20, из которых два несут вывод компилятора.
Отсутствие РЕШЕНИЯ он измеряет точно: кандидат без записи в
`docs/foundation-candidates.yaml` — находка; запись, которой в деревьях не
соответствует предмет, — тоже находка.

ПОЧЕМУ НЕ «ОБЯЗАН БЫТЬ ВЫНЕСЕН»

Ложно зачисленный опаснее ложно исключённого: он ломает направление
зависимостей, и ошибка НЕОБРАТИМА — опубликованный тег фундамента из базы
контрольных сумм не отзывается. Поэтому исход записи — два: `move` с задачей
либо `keep` с доводом. Похоронить предмет молчанием нельзя: молчание и есть
находка.

ЧЕМ ДЕРЖИТСЯ СОДЕРЖАТЕЛЬНОСТЬ ДОВОДА `keep` (исправлено приёмкой 2026-09-21)

Прежняя редакция судила довод НЕПУСТОТОЙ, и потому `why: "по усмотрению"`
проходила зелёной, хотя норма эту самую формулировку и запрещает. Перечень
запрещённых формулировок распознавателя не имеет и здесь не заводится:
чёрный список форм обходится дописыванием ЛЮБОГО другого текста, и вместе с ним
норма остаётся пожеланием ровно там, где выглядит проверенной.

Довод разложен на ДВА МАШИННЫХ ФАКТА, ни один из которых текстом не производится:

  `class`     — класс отказа из ЗАКРЫТОГО словаря ВОСЬМИ исключений
                (`_core.EXCLUSIONS` — девять строк на восемь исключений:
                лицензионное записано двумя режимами, 4а и 4б, обязательства у
                них противоположные). Девятого нет по норме
                `arch-second-home-exclusions-closed`, поэтому отказ, не
                относящийся ни к одному из восьми, отказом не является.
  `evidence`  — координата `<продукт>:<путь>`, которая ОБЯЗАНА резолвиться в
                файл `.go` ИМЕННО ТОГО пакета, о котором запись, в стволе его
                продукта. Дописать её нельзя: требуется настоящий файл предмета.

`why` остаётся, но несущим больше НЕ является: это фраза для человека. Поэтому
подстановка «по усмотрению» вместо довода теперь краснеет не на словах, а на
отсутствующих `class` и `evidence`.

ГРАНИЦА НАЗВАНА ВСЛУХ. Машина проверяет, что класс назван из закрытых восьми и
что координата указывает на настоящий файл предмета. ИСТИННОСТЬ класса для этой
координаты — «этот файл действительно несёт политику по существу» — машинно не
проверяется и ДЕРЖИТСЯ ВНИМАНИЕМ: приёмкой записи человеком и `check-verifier`.
Имитации здесь нет: то, что не проверяется, названо, а не подменено счётом
символов.

СЕГОДНЯШНЯЯ СИЛА ЭТОЙ ПРОВЕРКИ НАЗЫВАЕТСЯ ЧЕСТНО. Ярус 0 нормы — предусловие:
пока решение владельца о перелицензировании не опубликовано, исключения 4а/4б
держат класс целиком и очередь пуста ПО ПОСТРОЕНИЮ. Значит сегодня здесь
работает вторая половина — САМОИСТЕЧЕНИЕ записи; первая включается в день
публикации. Зубы яруса 1 (третья прописка запрещена) — в `check-02`, и они
работают сегодня.

ПРЕДПОСЫЛКА — СТВОЛ КЛОНА НЕ ПОЗАДИ ЗАКРЕПЛЁННОГО (возврат check-verifier, #724).
Судится ствол клона, а он есть то, что в клон последний раз подтянули: отставший
клон назвал бы «кандидатом без решения» предмет, давно решённый на стволе
продукта, и «записью без предмета» — запись о предмете, который на стволе есть.
Поэтому до замера сверяется закрепление ведомости (`ceiling.rev`, его судит
`check-02`): ствол позади закреплённой ревизии либо закрепление не установлено —
«считать не по чему», а не находка о решениях.

Исходы: 0 — каждый кандидат несёт решение, записей без предмета нет;
1 — находка; 2 — считать не по чему (клонов нет, ствол клона позади
закреплённого, обход пуст).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "docs-gate"))
import _core  # noqa: E402
import _lib  # noqa: E402

NAME = "check-01-every-candidate-carries-a-decision"
LEDGER = "docs/foundation-candidates.yaml"
DECISIONS = ("move", "keep", "sunset")


FIELDS = ("decision", "issue", "why", "class", "evidence")


def parse(text):
    """{пакет: {поле: значение, "line": номер строки}}."""
    rows, cur, key = {}, None, None

    def flush():
        if cur:
            rows[key] = cur

    for i, raw in enumerate(text.split("\n"), 1):
        s = raw.strip()
        if s.startswith("#"):
            continue
        if s.startswith("- package:"):
            flush()
            key = s.split(":", 1)[1].strip().strip('"')
            cur = dict.fromkeys(FIELDS, "")
            cur["line"] = i
            continue
        if cur is None:
            continue
        for f in FIELDS:
            if s.startswith(f + ":"):
                cur[f] = s.split(":", 1)[1].strip().strip('"')
                break
    flush()
    return rows


def main():
    root = _lib.workspace_root()
    threshold = float(os.environ.get("J", "0.70"))
    busl = os.environ.get("RELICENSE_BUSL_DECIDED") == "1" or \
        os.environ.get("RELICENSE_DECIDED") == "1"
    agpl = os.environ.get("RELICENSE_AGPL_DECIDED") == "1"

    text = _lib.read(root, LEDGER) if os.path.exists(os.path.join(root, LEDGER)) else None
    if text is None:
        _lib.void(NAME, "ведомость %s не прочитана — судить решения не по чему" % LEDGER)
        return 2
    revs, bad = _core.declared_revs(text)
    ps = _core.pin_state(root, revs)
    premise = ["ведомость не разобрана в блоке `ceiling.rev`: %s" % "; ".join(bad)] if bad \
        else ps["voids"] + ps["findings"]
    if premise:
        _lib.void(NAME, "предпосылка не установлена — %s. Ствол клона, не сверенный с "
                        "закреплённым, судил бы решения по тому, что в клон подтянули, а не "
                        "по продукту; закрепление судит check-02" % "; ".join(premise))
        return 2

    m = _core.measure(root, threshold, busl, agpl, revs=ps["trunks"])
    if "void" in m:
        _lib.void(NAME, "%s — второй прописки считать не по чему" % m["void"])
        return 2
    if m["walked"] == 0:
        _lib.void(NAME, "обход ПУСТ — ни одного `.go` ни в одном стволе; «кандидатов 0» "
                        "здесь означало бы «ноль прочитанного»")
        return 2

    rows = parse(text)

    _lib.census("%s: стволов %d (%s); осмотрено `.go` %d, сравнимых %d; ПРЕДМЕТОВ со "
                "второй пропиской %d (файлов %d); КАНДИДАТОВ после восьми исключений %d; "
                "записей ведомости %d"
                % (NAME, len(m["trees"]),
                   ", ".join("%s@%s=%d" % (n, m["trees"][n][2], m["trees"][n][3])
                             for n in sorted(m["trees"])),
                   m["walked"], m["comparable"], m["subjects"], m["subject_files"],
                   len(m["candidates"]), len(rows)))

    findings = []
    for c in m["candidates"]:
        pkgs = sorted({"%s:%s" % (f.split(":", 1)[0], os.path.dirname(f.split(":", 1)[1]))
                       for f in c["files"]})
        if not any(p in rows for p in pkgs):
            findings.append("предмет в домах %s (адрес выноса: %s) НЕ несёт решения: "
                            "копии %s. Исходы два — `move` с задачей либо `keep` с доводом; "
                            "молчание исходом не является"
                            % ("+".join(c["homes"]), c["address"], ", ".join(c["files"])))
    for pkg, row in sorted(rows.items()):
        dec, issue, why, ln = row["decision"], row["issue"], row["why"], row["line"]
        cls, ev = row["class"], row["evidence"]
        if dec not in DECISIONS:
            findings.append("%s:%d — решение %r вне закрытого словаря %s"
                            % (LEDGER, ln, dec, list(DECISIONS)))
            continue
        if dec in ("move", "sunset") and not issue:
            findings.append("%s:%d — %s без задачи: за обязанностью никто не отвечает"
                            % (LEDGER, ln, dec))
            continue
        if dec == "keep":
            # ДОВОД СУДИТСЯ ПО СУЩЕСТВУ, а не по непустоте: непустота
            # производится дописыванием любого текста, эти два факта — нет.
            bad = False
            if not why:
                findings.append("%s:%d — отказ от выноса без фразы `why`" % (LEDGER, ln))
                bad = True
            if cls not in _core.EXCLUSIONS:
                findings.append("%s:%d — `class: %s` вне ЗАКРЫТОГО словаря исключений "
                                "(их восемь; лицензионное записано двумя режимами, 4а и "
                                "4б, потому что обязательства у них противоположные): %s. "
                                "Девятого исключения нет "
                                "(arch-second-home-exclusions-closed), поэтому отказ, не "
                                "относящийся ни к одному из восьми, отказом не является; "
                                "непустой `why` этого не заменяет"
                                % (LEDGER, ln, cls or "<пусто>", list(_core.EXCLUSIONS)))
                bad = True
            own = m["package_files"].get(pkg, [])
            if not ev:
                findings.append("%s:%d — `keep` без `evidence`: довод обязан указать "
                                "координату `<продукт>:<путь>` в СВОЁМ предмете. Файлов "
                                "у пакета в стволе %d" % (LEDGER, ln, len(own)))
                bad = True
            elif ev not in own:
                findings.append("%s:%d — `evidence: %s` не резолвится в файл пакета %s: в "
                                "стволе у него %d `.go` (%s). Координата довода "
                                "дописыванием текста не производится"
                                % (LEDGER, ln, ev, pkg, len(own),
                                   ", ".join(own[:3]) + ("…" if len(own) > 3 else "")))
                bad = True
            if bad:
                continue
        if pkg not in m["second_home_dirs"]:
            findings.append("%s:%d — запись о %s, у которого второй прописки в стволах "
                            "БОЛЬШЕ НЕТ: самоистечение. Снимите запись тем же изменением, "
                            "которым снят её предмет" % (LEDGER, ln, pkg))

    if findings:
        for f in findings:
            _lib.fail(NAME, f)
        return 1

    if not m["candidates"]:
        _lib.passed(NAME, "очередь пуста при %d предметах со второй пропиской — сегодня "
                          "по построению: решение владельца о перелицензировании не "
                          "опубликовано, исключения 4а/4б держат класс целиком. Пустая "
                          "ведомость есть ЦЕЛЬ; записей без предмета нет (%d)"
                    % (m["subjects"], len(rows)))
    else:
        _lib.passed(NAME, "решение несут все %d кандидатов; записей без предмета нет "
                          "(записей %d)" % (len(m["candidates"]), len(rows)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
