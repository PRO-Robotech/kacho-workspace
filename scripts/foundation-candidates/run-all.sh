#!/usr/bin/env bash
# Прогон набора foundation-candidates. Вердикт стоит в КОДЕ ВЫХОДА, а не в печати.
#
# ПРЕДМЕТ НАБОРА — требование владельца 2026-09-20, дословно: «все общие
# библиотеки, которые могут быть вынесены должны быть вынесены в corelib а не
# хорониться в проекте». Норма `arch-second-home-needs-a-decision`
# (`.claude/rules/architecture.md` §«Переиспользование») сама называет этот
# набор своим держателем.
#
# ПОЧЕМУ ДОМ ЗДЕСЬ, А НЕ В ДЕРЕВЕ ПРОДУКТА. Вторая прописка есть свойство ДВУХ
# деревьев: каждое по себе исправно, и расхождение наступает молча. Воркспейс —
# единственное место, где под рукой все три клона. Так же устроен и по той же
# причине `scripts/crossrepo-gate`.
#
# ТРИ ИСХОДА, А НЕ ДВА:
#   0 — рассмотрено N проверок, находок 0, у каждой был предмет;
#   1 — НАХОДКА: проверка упала, либо обход пуст;
#   2 — БЕЗ ПРЕДМЕТА: клона нет либо ствол не резолвится — второй прописки
#       считать не по чему.
# Третий исход НЕ засчитывается за успех: «кандидатов ноль» и «ноль прочитанных
# деревьев» — разные вещи, и вторая опаснее.
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

ok=0; bad=0; void=0; count=0
for c in "$SCRIPT_DIR"/check-*; do
    [ -f "$c" ] || continue
    count=$((count + 1))
    case "$c" in
        *.py) python3 "$c" ;;
        *)    bash "$c" ;;
    esac
    case $? in
        0) ok=$((ok + 1)) ;;
        2) void=$((void + 1)) ;;
        *) bad=$((bad + 1)) ;;
    esac
done

if [ "$count" -gt 0 ]; then
    echo
    echo "foundation-candidates: рассмотрено проверок $count; пройдено $ok, провалено $bad, без предмета $void"
else
    echo "foundation-candidates: рассмотрено проверок 0 в $SCRIPT_DIR — прогонять нечего" >&2
fi

[ "$count" -gt 0 ] || exit 1
[ "$bad" -eq 0 ] || exit 1
[ "$void" -eq 0 ] || exit 2
exit 0
