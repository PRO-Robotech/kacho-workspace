#!/usr/bin/env bash
# check-02 — отслеживаемое производное побайтово равно регенерации.
#
# ЧТО УТВЕРЖДАЕТ. Каждый объявленный выход, лежащий в дереве, побайтово равен
# тому, что генератор производит из канонических входов ВО ВРЕМЕННЫЙ каталог.
#
# ПОЧЕМУ ПОБАЙТОВО, А НЕ «примерно совпадает». Расхождение в один байт — это и
# есть правка производного руками либо правка входа без регенерации. Оба
# состояния выглядят как исправное дерево и не дают ни конфликта при слиянии,
# ни красного где-либо ещё.
#
# ПОЧЕМУ ВО ВРЕМЕННЫЙ КАТАЛОГ. Регенерация поверх дерева стёрла бы расхождение
# ровно в тот момент, когда его надо предъявить.
#
# Коды выхода: 0 — осмотрено N, находок 0; 1 — находка; 2 — сверять не с чем.
set -uo pipefail
# shellcheck source=_lib.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/_lib.sh"
adapter_gate_run "check-02-derived-matches-regeneration" "derived-drift" "производное сверено с регенерацией побайтово"
