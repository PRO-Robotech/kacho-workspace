#!/usr/bin/env bash
# check-07 — перечень пакетов манифеста совпадает со скилами оснастки.
#
# ЧТО УТВЕРЖДАЕТ. Множество `skills` манифеста совпадает с множеством
# отслеживаемых директорий `.claude/skills/*/`. В обе стороны: имя без
# директории и директория без имени — обе находки.
#
# ПОЧЕМУ ЭТО ВАЖНО ИМЕННО ЗДЕСЬ. Скил, не попавший в манифест, не получает
# пакета для второй среды — и это невидимо: отсутствие проверки сигнала не
# производит. Скил, снятый из оснастки, но оставшийся в манифесте, роняет
# генератор — то есть замечен будет сразу, и это верное поведение.
#
# Коды выхода: 0 — осмотрено N, находок 0; 1 — находка; 2 — сверять не с чем.
set -uo pipefail
# shellcheck source=_lib.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/_lib.sh"
adapter_gate_run "check-07-skills-roster-matches-tree" "skills-roster" "перечень пакетов сверен с оснасткой в обе стороны"
