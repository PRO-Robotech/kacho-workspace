#!/usr/bin/env bash
# check-05 — генератор не вносит в производное абсолютных путей машины.
#
# ЧТО УТВЕРЖДАЕТ. В объявленных выходах нет абсолютного пути, которого НЕТ ни в
# одном каноническом входе.
#
# ПОЧЕМУ «ВНЕСЁННЫЙ», А НЕ «ЛЮБОЙ». Порождённый текст наследует прозу входа
# дословно, и в ней законно встречается абсолютный путь — как ЦИТАТА наблюдения,
# а не координата, по которой пойдут. Запрет на любой абсолютный путь краснел бы
# на верном дереве, а гейт, краснеющий на верном, отключают первым. Находка —
# путь, которого во входах нет: его ввёл генератор, и он не переносится ни на
# другую машину, ни в другой клон, оставаясь на вид рабочим.
#
# Коды выхода: 0 — осмотрено N, находок 0; 1 — находка; 2 — сверять не с чем.
set -uo pipefail
# shellcheck source=_lib.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/_lib.sh"
adapter_gate_run "check-05-generated-paths-portable" "portable" "порождённые прочитаны на внесённый абсолютный путь"
