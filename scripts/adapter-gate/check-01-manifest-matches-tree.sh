#!/usr/bin/env bash
# check-01 — точный набор владеемых выходов совпадает с отслеживаемым деревом.
#
# ЧТО УТВЕРЖДАЕТ. Множество `owned_outputs` из `.claude/adapters.yaml` побайтово
# совпадает с множеством ОТСЛЕЖИВАЕМЫХ файлов внутри владеемых пространств.
# Строка без файла и файл без строки — обе находки, и обе печатаются отдельно.
#
# ПОЧЕМУ В ОБЕ СТОРОНЫ. Совпадение ЧИСЛА не доказывает ничего: множества равной
# мощности бывают разными, и именно так перечень расходится с деревом незаметно.
#
# ЧУЖОЙ ПАКЕТ НЕ СЧИТАЕТСЯ. Пакет внутри `.agents/skills/`, которого нет среди
# `skills`, принадлежит другой установке: он не лишний выход. И он НЕ маскирует
# расхождение владеемого — оно считается по владеемым путям, куда чужой не входит.
#
# Коды выхода: 0 — осмотрено N, находок 0; 1 — находка; 2 — сверять не с чем.
set -uo pipefail
# shellcheck source=_lib.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/_lib.sh"
adapter_gate_run "check-01-manifest-matches-tree" "manifest-tree" "точный набор манифеста сверен с деревом в обе стороны"
