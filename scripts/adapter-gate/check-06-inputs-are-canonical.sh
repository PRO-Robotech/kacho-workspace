#!/usr/bin/env bash
# check-06 — генератор читает только канонические входы, и они все существуют.
#
# ЧТО УТВЕРЖДАЕТ. Две вещи сразу: каждый объявленный вход существует и задан
# относительным путём; и генератор ОТКАЗЫВАЕТ при попытке прочитать путь вне
# набора.
#
# ПОЧЕМУ ВТОРАЯ ПОЛОВИНА ПРОВЕРЯЕТСЯ ИСХОДОМ. Чтение исходника генератора ловило
# бы форму: комментарий про запрет прошёл бы за сам запрет. Предикат подаёт
# неканонический путь и читает, что произошло.
#
# Коды выхода: 0 — осмотрено N, находок 0; 1 — находка; 2 — сверять не с чем.
set -uo pipefail
# shellcheck source=_lib.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/_lib.sh"
adapter_gate_run "check-06-inputs-are-canonical" "canonical-inputs" "канонические входы сверены и отказ генератора проверен исходом"
