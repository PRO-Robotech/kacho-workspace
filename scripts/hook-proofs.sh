#!/usr/bin/env bash
# ГЕЙТ НАД ХУКАМИ: доказательство инъекцией обязано ИСПОЛНЯТЬСЯ.
#
# Форма взята у монорепо (`deploy/scripts/run-gate-self-tests.sh`) и не изобретается
# заново: перечень НАХОДИТСЯ по исполняемому признаку, а не ведётся руками, и
# найденное обязано совпадать с объявленным в обе стороны.
#   • нашлось доказательство, которого нет в списке → ПРОВАЛ (новое забыли внести,
#     и оно бы тихо не исполнялось — тот же дефект классом ниже);
#   • в списке запись, для которой доказательства больше нет → ПРОВАЛ (исключение
#     живёт, пока у него есть предмет; запись без предмета — находка).
#
# Почему это нужно было завести. `class-guard` несёт `prove.sh` с несколькими
# десятками проб (своё число он печатает сам — часть проб выводится из дерева, и
# выписанное здесь устарело бы на первом же изменении продукта), и на момент
# написания этого файла его не звал НИКТО: ни workflow, ни Makefile, ни другой гейт.
# Доказательство существовало как текст и ни разу не проверялось — ровно то, ради
# борьбы с чем оно и писалось.
#
# ПРИЗНАК — МЕСТО И ИМЯ: `.claude/hooks/<хук>/prove.sh`. Место здесь законно как
# признак: каталог однородный, в нём живут только хуки, и у каждого доказательство
# лежит под одним именем. Перечень читается из индекса git (`--others
# --exclude-standard`), то есть включает ЕЩЁ НЕ закоммиченное, но не игнорируемое:
# иначе новое доказательство не исполнялось бы ровно в тот день, когда его пишут.
#
# Три исхода, а не два: 0 — исполнено N, все сошлись; 1 — есть разошедшиеся;
# 2 (VOID) — доказательств не найдено вовсе, проверять нечего. VOID считается
# провалом набора: «ноль находок» и «ноль прочитанного» — разные вещи.
set -uo pipefail

WS="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$WS" || exit 2

# Объявленный состав, путями от корня воркспейса. Держится СИНХРОННЫМ с находкой
# ниже — расхождение в любую сторону роняет проверку.
DECLARED="
.claude/hooks/class-guard/prove.sh
.claude/hooks/docfresh/prove.sh
.claude/hooks/hooks-wiring-notice/prove.sh
"

FOUND="$(git ls-files --cached --others --exclude-standard '.claude/hooks/*/prove.sh' | sort -u)"

if [ -z "$FOUND" ]; then
    echo "[VOID] hook-proofs — доказательств не найдено ни одного." >&2
    echo "       Либо признак разошёлся с деревом, либо хуки остались без доказательств." >&2
    exit 2
fi

DECL_SORTED="$(printf '%s\n' "$DECLARED" | grep -v '^[[:space:]]*$' | sed 's/^[[:space:]]*//' | sort -u)"

rc=0
extra="$(comm -13 <(printf '%s\n' "$DECL_SORTED") <(printf '%s\n' "$FOUND"))"
missing="$(comm -23 <(printf '%s\n' "$DECL_SORTED") <(printf '%s\n' "$FOUND"))"
if [ -n "$extra" ]; then
    echo "[FAIL] hook-proofs — доказательство есть в дереве, но не объявлено (и потому не исполнялось бы):" >&2
    printf %s\\n "$extra" | sed "s/^/       /" >&2
    rc=1
fi
if [ -n "$missing" ]; then
    echo "[FAIL] hook-proofs — объявлено доказательство, которого в дереве нет (запись без предмета):" >&2
    printf %s\\n "$missing" | sed "s/^/       /" >&2
    rc=1
fi

ran=0; bad=0
while IFS= read -r proof; do
    [ -n "$proof" ] || continue
    ran=$((ran + 1))
    echo "── $proof"
    if bash "$proof"; then :; else
        echo "[FAIL] $proof — доказательство инъекцией разошлось" >&2
        bad=$((bad + 1))
    fi
done <<< "$FOUND"

echo "[CENSUS] hook-proofs: объявлено $(printf '%s\n' "$DECL_SORTED" | wc -l), найдено $(printf '%s\n' "$FOUND" | wc -l), исполнено $ran, разошлось $bad"
if [ "$rc" -ne 0 ] || [ "$bad" -ne 0 ]; then
    echo "[FAIL] hook-proofs — набор красный" >&2
    exit 1
fi
echo "[PASS] hook-proofs — исполнено $ran, все доказательства сошлись"
