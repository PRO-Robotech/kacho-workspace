#!/usr/bin/env bash
# ГЕЙТ НАД ХУКАМИ: доказательство инъекцией обязано ИСПОЛНЯТЬСЯ.
#
# Форма взята у монорепо (`deploy/scripts/run-gate-self-tests.sh`) и не изобретается
# заново: перечень ИСПОЛНЯЕМОГО находится по признаку дерева, а не берётся из
# списка, и найденное обязано совпадать с объявленным в обе стороны.
#   • нашлось доказательство, которого нет в списке → ПРОВАЛ. Исполняется оно при
#     этом ВСЁ РАВНО: цикл ниже идёт по НАЙДЕННОМУ, а не по объявленному. Здесь
#     стояло обратное — «оно бы тихо не исполнялось», — то есть комментарий против
#     кода, и верным был код (перепись 2026-09-02: «объявлено 2, найдено 3,
#     исполнено 3»). Предмет провала другой: объявленное число обязано остаться
#     чьим-то утверждением, иначе сверять с ним нечего;
#   • в списке запись, для которой доказательства больше нет → ПРОВАЛ (исключение
#     живёт, пока у него есть предмет; запись без предмета — находка).
#
# ПОЧЕМУ СПИСОК ВЕДЁТСЯ РУКАМИ, хотя перечни в этом репозитории ВЫВОДЯТСЯ
# (`ai-tooling.md`). Выведенный из дерева список совпал бы с находкой ПО
# ПОСТРОЕНИЮ: обе сверки стали бы пусты всегда, и гейт потерял бы единственное
# свойство, которое несёт объявление, — ХРАПОВИК ПРОТИВ ТИХОГО СЖАТИЯ ПРИЗНАКА.
# Признак есть место и имя; переименуй `prove.sh` у одного хука — находка тихо
# уменьшится, а «исполнено 2» ничем не отличается от «исполнено 3», пока рядом
# нет объявленного числа. Замер инъекцией на синтетическом дереве (2026-09-02):
# с объявленным списком переименование даёт код 1 и имя записи без предмета; с
# выведенным — код 0 и «исполнено 1». Запрет `ai-tooling.md` — про перечни,
# которые НИКТО не сверяет; этот сверяется на каждом прогоне и своё расхождение
# нашёл сам в тот же день, когда оно возникло.
#
# Почему это нужно было завести. `class-guard` несёт `prove.sh` с несколькими
# десятками проб (своё число он печатает сам — часть проб выводится из дерева, и
# выписанное здесь устарело бы на первом же изменении продукта), и на момент
# написания этого файла его не звал НИКТО: ни workflow, ни Makefile, ни другой гейт.
# Доказательство существовало как текст и ни разу не проверялось — ровно то, ради
# борьбы с чем оно и писалось.
#
# ПРИЗНАК — МЕСТО И ИМЯ: `.claude/hooks/<хук>/prove.sh`. Место здесь законно как
# признак: каталог однородный, в нём живут только хуки, и у каждого доказательство
# лежит под одним именем. Перечень читается из индекса git (`--others
# --exclude-standard`), то есть включает ЕЩЁ НЕ закоммиченное, но не игнорируемое:
# иначе новое доказательство не исполнялось бы ровно в тот день, когда его пишут.
#
# Три исхода, а не два: 0 — исполнено N, все сошлись; 1 — есть разошедшиеся;
# 2 (VOID) — доказательств не найдено вовсе, проверять нечего. VOID считается
# провалом набора: «ноль находок» и «ноль прочитанного» — разные вещи.
set -uo pipefail

WS="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$WS" || exit 2

# Объявленный состав, путями от корня воркспейса. Держится СИНХРОННЫМ с находкой
# ниже — расхождение в любую сторону роняет проверку.
DECLARED="
.claude/hooks/change-graph/prove.sh
.claude/hooks/class-guard/prove.sh
.claude/hooks/docfresh/prove.sh
"

FOUND="$(git ls-files --cached --others --exclude-standard '.claude/hooks/*/prove.sh' | sort -u)"

if [ -z "$FOUND" ]; then
    echo "[VOID] hook-proofs — доказательств не найдено ни одного." >&2
    echo "       Либо признак разошёлся с деревом, либо хуки остались без доказательств." >&2
    exit 2
fi

DECL_SORTED="$(printf '%s\n' "$DECLARED" | grep -v '^[[:space:]]*$' | sed 's/^[[:space:]]*//' | sort -u)"

rc=0
extra="$(comm -13 <(printf '%s\n' "$DECL_SORTED") <(printf '%s\n' "$FOUND"))"
missing="$(comm -23 <(printf '%s\n' "$DECL_SORTED") <(printf '%s\n' "$FOUND"))"
if [ -n "$extra" ]; then
    # Текст называет ТО, что произошло. Прежняя редакция обещала «и потому не
    # исполнялось бы» — и печаталась прямо над строкой «исполнено N», куда это
    # доказательство уже вошло: находка отрицала соседнюю перепись.
    echo "[FAIL] hook-proofs — доказательство есть в дереве, но не объявлено (исполнено оно всё равно; объявленное число перестало быть чьим-то утверждением — внесите путь в DECLARED):" >&2
    printf %s\\n "$extra" | sed "s/^/       /" >&2
    rc=1
fi
if [ -n "$missing" ]; then
    echo "[FAIL] hook-proofs — объявлено доказательство, которого в дереве нет (запись без предмета):" >&2
    printf %s\\n "$missing" | sed "s/^/       /" >&2
    rc=1
fi

ran=0; bad=0; void=0
while IFS= read -r proof; do
    [ -n "$proof" ] || continue
    ran=$((ran + 1))
    echo "── $proof"
    # Исход читается ПО КОДУ, а не по факту «не ноль»: 1 — расхождение (дефект
    # в доказываемом), 2 — «не выполнилось» (вход не построить). Назвать второе
    # первым значит послать читателя искать дефект там, где его нет.
    prc=0; bash "$proof" || prc=$?
    case "$prc" in
        0) : ;;
        2) echo "[VOID] $proof — часть входов в этой среде не построена: доказательство НЕПОЛНО" >&2
           void=$((void + 1)) ;;
        *) echo "[FAIL] $proof — доказательство инъекцией разошлось" >&2
           bad=$((bad + 1)) ;;
    esac
done <<< "$FOUND"

echo "[CENSUS] hook-proofs: объявлено $(printf '%s\n' "$DECL_SORTED" | wc -l), найдено $(printf '%s\n' "$FOUND" | wc -l), исполнено $ran, разошлось $bad"
# Причина называется ТА, которая сработала. Прежняя редакция печатала одно число —
# разошедшиеся доказательства, — и на расхождении СПИСКА с деревом выходила строкой
# «набор красный: расхождений 0», то есть отрицала собственную находку. Диагностика
# — часть свойства, а не украшение: находка, называющая не свою причину, посылает
# читателя искать не там (`testing.md` §«Гейт на класс», п.8).
if [ "$rc" -ne 0 ] || [ "$bad" -ne 0 ]; then
    if [ "$rc" -ne 0 ] && [ "$bad" -ne 0 ]; then
        echo "[FAIL] hook-proofs — набор красный: объявленный список разошёлся с деревом (выше) И доказательств разошлось $bad из $ran" >&2
    elif [ "$rc" -ne 0 ]; then
        echo "[FAIL] hook-proofs — набор красный: объявленный список разошёлся с деревом (выше); сами доказательства сошлись все $ran" >&2
    else
        echo "[FAIL] hook-proofs — набор красный: доказательств разошлось $bad из $ran" >&2
    fi
    exit 1
fi
# Неполное доказательство зелёным не бывает: гейт, часть входов которого не
# построена, не доказан — но и дефектом это не является, поэтому исход отдельный.
if [ "$void" -ne 0 ]; then
    echo "[VOID] hook-proofs — доказательств неполных $void из $ran: гейт НЕ доказан" >&2
    exit 2
fi
echo "[PASS] hook-proofs — исполнено $ran, все доказательства сошлись"
