# от того, куда эту копию сегодня переставили. Ровно так класс и обезоружил одну из
# них — инъекция «объявлено 7 вместо 8» на копии, припаркованной там, где сайтов 7,
# СХОДИТСЯ с индексом, и проба, доказывавшая падучесть, зеленела наоборот.
#
# Поэтому вход ниже проба ПРОИЗВОДИТ САМА: крохотное дерево продукта, где на стволе
# сайтов ТРИ, а в припаркованной вершине ДВА (`scripts/lib/product-fixture.sh`).
# Различие по каждой оси однофактное, и от состояния чужой копии оно не зависит.
