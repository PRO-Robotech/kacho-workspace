# На стволе три сайта, в припаркованной вершине два: сайт службы доступа снят —
# ровно то, чем отличается настоящая припаркованная копия от ствола. Рядом заводятся
# каталоги, которые требует ВТОРОЙ предикат гейта (рабочий каталог процитированной
# сборки), иначе пробы краснели бы по причине, к полосе чтения не относящейся.
mkprod06() {
    PROD_SEQ=$((PROD_SEQ + 1))
    local dir="$TMP/prod06-$PROD_SEQ" site
    product_fixture_init "$dir"
    for site in gateway/docs services/vpc/docs services/iam/docs; do
        mkdir -p "$dir/$site/engineering" "$dir/$site/content"
        # Ключ `path` пресета docs — его читает сам гейт, а не выписанное имя.
        printf 'export default {\n  presets: [["classic", { docs: {\n    path: %s,\n  } }]],\n};\n' \
            "'content'" > "$dir/$site/docusaurus.config.ts"
        printf '# инженерная часть\n' > "$dir/$site/engineering/00-index.md"
        printf '# страница\n' > "$dir/$site/content/index.md"
    done
    # Рабочий каталог второй процитированной сборки (`ui-future/<модуль>`): рецепт
    # на семейство, и подставить в него обязано быть что.
    mkdir -p "$dir/ui-future/host"
    printf '{}\n' > "$dir/ui-future/host/package.json"
    product_fixture_seal_trunk "$dir"
    # Припаркованная вершина: сайт службы доступа снят. Индекс копии знает ДВА сайта.
    rm -rf "$dir/services/iam"
    product_fixture_seal_parked "$dir"
    printf '%s' "$dir"
}

# declare_sites <число> — объявить в регламенте столько сайтов, сколько сказано.
declare_sites() {
    sed -i "s/^| сайтов в дереве | \`[0-9]*\` |/| сайтов в дереве | \`$1\` |/" "$DW"
}

# forbid <подстрока> <пояснение> — находка обязана называть СВОЮ полосу и не чужую.
# Без этого «покраснело» не говорит, ЧТО покраснело, и вакуумная полоса выглядела бы
# доказанной находкой соседа.
forbid() {
    if grep -qF -- "$1" <<<"${LAST_OUT:-}"; then
        printf '  [БЕДА] %s: в выводе есть запрещённое «%s»\n' "$2" "$1"; fail=$((fail + 1))
    else
        printf '  [ok]   %s\n' "$2"; pass=$((pass + 1))
    fi
}

SAY_COUNT="объявлено сайтов"
SAY_SITE="объявлен каталог сайта"

# ── ПРОГОН 1: КОНТРОЛЬ. Объявление сходится со СТВОЛОМ (3), копия припаркована на
# вершине, где сайтов 2. Прежняя полоса краснела здесь — это и был вердикт, ложный
# о продукте и верный лишь о состоянии одной копии.
restore
prod06="$(mkprod06)"
declare_sites 3
run 0 "контроль: объявление = ствол (3), копия припаркована на 2 ⇒ молчание" \
    check-06-docs-layout-matches-tree.sh KACHO_MONOREPO="$prod06"

# ── ПРОГОН 1б: ТО ЖЕ дерево, копия ВЕРНУТА НА СТВОЛ. Отличие однофактное —
# положение HEAD, и только оно. Вердикт обязан совпасть: это и есть свойство,
# которое заводится, — вердикт перестал зависеть от состояния копии.
product_fixture_park_on_trunk "$prod06"
run 0 "то же дерево, копия ВЕРНУТА на ствол ⇒ тот же вердикт" \
    check-06-docs-layout-matches-tree.sh KACHO_MONOREPO="$prod06"

# ── ПРОГОН 2: ИНЪЕКЦИЯ НОВОГО СВОЙСТВА. Объявлено столько, сколько знает ИНДЕКС
# припаркованной копии (2), а не ствол (3). Прежняя полоса молчала бы — она этот
# индекс и читала; новая обязана покраснеть и назвать ЧИСЛО, а не каталог.
restore
prod06="$(mkprod06)"
declare_sites 2
run 1 "инъекция НОВОГО: объявлено по индексу припаркованной копии (2) ⇒ находка" \
    check-06-docs-layout-matches-tree.sh KACHO_MONOREPO="$prod06"
forbid "$SAY_SITE" "инъекция НОВОГО: покраснело ЧИСЛО, а не каталог сайта"

# ── ПРОГОН 3: ИНЪЕКЦИЯ СУЩЕСТВУЮЩЕГО утверждения. Число объявлено верно по стволу,
# а имя каталога сайта неверно. Краснеет ПРЕЖНЕЕ утверждение, полоса числа молчит:
# без этого прогона её молчание было бы неотличимо от молчания мёртвого.
restore
prod06="$(mkprod06)"
declare_sites 3
sed -i 's/^| каталог сайта у компонента | `docs` |/| каталог сайта у компонента | `docs-site` |/' "$DW"
run 1 "инъекция СТАРОГО: каталог сайта назван неверно, число верно ⇒ находка" \
    check-06-docs-layout-matches-tree.sh KACHO_MONOREPO="$prod06"
forbid "$SAY_COUNT" "инъекция СТАРОГО: покраснел КАТАЛОГ, а не число"

# ── ТРЕТЬЯ КАТЕГОРИЯ: ствола нет вовсе. Индекс копии при этом на месте и раскладку
# бы «подтвердил» — тем ценнее, что отката на него нет: VOID, а не успех и не
# находка. Дерево продукта существует, у него есть индекс git; не разрешается ровно
# ствол, и текст обязан называть именно это.
restore
prod06="$(mkprod06)"
product_fixture_drop_trunk "$prod06"
declare_sites 2
run 2 "ствол не разрешён ⇒ ТРЕТЬЯ КАТЕГОРИЯ, а не успех и не находка" \
    check-06-docs-layout-matches-tree.sh KACHO_MONOREPO="$prod06"
grep -qF -- "ствол дерева продукта" <<<"${LAST_OUT:-}" \
    && { printf '  [ok]   третья категория названа своим текстом\n'; pass=$((pass + 1)); } \
    || { printf '  [БЕДА] код 2 верен, но текст не называет ствол\n'; fail=$((fail + 1)); }

restore
echo
echo "итог инъекций: проб пройдено $pass, провалено $fail, не выполнялось $void"
[ "$fail" -eq 0 ] && [ "$void" -eq 0 ]
