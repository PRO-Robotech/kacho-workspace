#!/usr/bin/env bash
# Доказательство КАЖДОГО гейта набора инъекцией — В ОБЕ СТОРОНЫ.
#
# Гейт, доказанный только красной половиной, ловит форму, а не существо: первый
# ложный срабат его отключит. Поэтому у каждой инъекции дефекта здесь стоит
# ЗАКОННЫЙ БЛИЗНЕЦ той же формы, на котором гейт обязан молчать
# (`gate-authoring` §Инъекция).
#
# Работает на ВРЕМЕННОЙ копии дерева (`SKILLS_GATE_ROOT`) — рабочее не трогается.
# Копия делается из git-состояния workspace + рабочих файлов скилов и правил.

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WS="$(cd "$SCRIPT_DIR/../.." && pwd)"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

mkdir -p "$TMP/.claude"
cp -r "$WS/.claude/skills" "$TMP/.claude/skills"
# Нормативный корпус едет ЦЕЛИКОМ, одним каталогом: гейт 01 резолвит §-имя в
# нём, а гейт 03 читает перечень скилов из `ai-tooling.md`, который лежит там же.
# Копия без части корпуса убивает обе половины инъекции гейта 01 МОЛЧА (ссылка на
# норму, которой нет в копии, пропускается как «вне корпуса»), а гейт 03 отвечает
# VOID. Домов было два (`.claude/rulebook/` снят 2026-09-13), и вторая строка
# копирования стояла здесь именно поэтому.
cp -r "$WS/.claude/rules"  "$TMP/.claude/rules"
cp -r "$WS/.claude/agents" "$TMP/.claude/agents"
# .gitignore едет вместе: без него временное дерево «отслеживает» и посторонние
# скилы, и перепись гейта 03 разойдётся с настоящей по причине, к предмету
# отношения не имеющей.
cp "$WS/.gitignore" "$TMP/.gitignore"
git -C "$TMP" init -q
git -C "$TMP" add -A >/dev/null 2>&1

# Дерево продукта — предмет проб гейта 06 (у остальных его нет). Оно под игнором,
# поэтому в индекс временной копии не попадает и `restore` его не трогает.
MONO_SRC="${KACHO_MONOREPO:-$WS/project/kacho}"
if [ -d "$MONO_SRC" ]; then
    mkdir -p "$TMP/project"
    ln -s "$MONO_SRC" "$TMP/project/kacho"
    HAVE_MONO=1
else
    HAVE_MONO=0
fi

CA="$TMP/.claude/skills/code-authoring/SKILL.md"
GA="$TMP/.claude/skills/gate-authoring/SKILL.md"
SS="$TMP/.claude/skills/security-surface/SKILL.md"
DT="$TMP/.claude/skills/doc-truthfulness/SKILL.md"
AT="$TMP/.claude/rules/ai-tooling.md"
DW="$TMP/.claude/skills/kacho-docs-writer/SKILL.md"
# Файл ПРАВИЛА, а не скила: гейт 06 обходит оснастку маской по свойству
# (`.claude/*.md`), и без пробы по этому пути доказано было бы только то, что он
# читает скилы. Перечень каталогов, стоявший в гейте до этой пары, молча терял
# правила и оставался PASS.
UI="$TMP/.claude/rules/ui.md"

pass=0
fail=0
void=0

# run <ожидаемый-код> <имя-пробы> <скрипт> [ПЕРЕМЕННАЯ=значение …]
run() {
    local want="$1" label="$2" script="$3" out got
    shift 3
    out="$(env "$@" SKILLS_GATE_ROOT="$TMP" bash "$SCRIPT_DIR/$script" 2>&1)"; got=$?
    if [ "$got" -eq "$want" ]; then
        pass=$((pass + 1)); printf '  [ok]   %-58s код %s\n' "$label" "$got"
    else
        fail=$((fail + 1)); printf '  [БЕДА] %-58s ждали %s, получили %s\n' "$label" "$want" "$got"
        printf '%s\n' "$out" | sed 's/^/         /'
    fi
    LAST_OUT="$out"
}

restore() { git -C "$TMP" checkout -- . >/dev/null 2>&1; }

# bit <что подставлялось> — подстановка обязана ИЗМЕНИТЬ дерево копии.
#
# Инъекция, чей образец исчез из входа, — пустая операция: `perl`/`sed` молчат,
# дерево остаётся чистым, а ожидание «код 1» может сойтись от постороннего
# красного. Ровно это и случилось с гейтом 07, когда цитата уехала вместе со
# снятым каталогом. Сравнивается СОСТОЯНИЕ ИНДЕКСА против рабочих файлов: `restore`
# возвращает копию к нему, значит «дифф пуст» = «ничего не подставилось».
bit() {
    if git -C "$TMP" diff --quiet -- . 2>/dev/null; then
        fail=$((fail + 1))
        printf '  [БЕДА] инъекция НЕ СОСТОЯЛАСЬ: %s во входе не найден — проба ничего не доказывает\n' "$1"
    fi
}

echo "== гейт 01 — ссылка на норму по имени раздела =="

restore
run 0 "чистое дерево (законный близнец: все ссылки по имени)" check-01-section-refs.sh

restore
printf '\nВременная строка: норма — `security.md:361`.\n' >> "$GA"
run 1 "инъекция: ссылка номером строки" check-01-section-refs.sh
grep -q 'gate-authoring/SKILL.md' <<<"${LAST_OUT:-}" \
    && printf '  [ok]   инъекция названа координатой\n' && pass=$((pass + 1)) \
    || { printf '  [БЕДА] гейт покраснел, но координату не назвал\n'; fail=$((fail + 1)); }

restore
# Близнец обязан ссылаться на раздел, ЖИВУЩИЙ в названном файле: §Hardening-инварианты
# уехал в `security-hardening.md` разрезом корпуса 2026-09-13, и прежняя фикстура стала
# находкой — то есть доказывала обратное тому, ради чего стоит.
printf '\nВременная строка: норма — `security.md` §Internal-vs-external.\n' >> "$GA"
run 0 "законный близнец: та же ссылка по имени раздела" check-01-section-refs.sh

restore
printf '\nВременная строка: норма — `security.md` §Такого-раздела-здесь-нет.\n' >> "$GA"
run 1 "инъекция: §-имя, которое не резолвится" check-01-section-refs.sh

restore
# предпосылка гейта: корпус без ссылок на нормы вообще ⇒ VOID, не успех
find "$TMP/.claude/skills" -name SKILL.md -exec sed -i 's/\.md/·md/g' {} +
run 2 "предпосылка: ссылок на нормы нет ⇒ VOID, не успех" check-01-section-refs.sh

echo
echo "== гейт 02 — семь частей записи =="

restore
run 0 "чистое дерево (законный близнец: все записи полны)" check-02-record-parts.sh

restore
# снять предикат снятия у одной записи
perl -0pi -e 's/^> \*\*Предикат снятия:\*\*.*?\n//m' "$CA"
run 1 "инъекция: у записи снят предикат снятия" check-02-record-parts.sh
grep -q '### ' <<<"${LAST_OUT:-}" \
    && printf '  [ok]   инъекция названа записью\n' && pass=$((pass + 1)) \
    || { printf '  [БЕДА] гейт покраснел, но запись не назвал\n'; fail=$((fail + 1)); }

restore
# законный близнец: запись БЕЗ предметного содержания вне §1–§7 (в §9) гейт не трогает
printf '\n### 9.9. Служебная запись без семи частей\n\nПросто текст.\n' >> "$CA"
run 0 "законный близнец: «### N.N» вне §1–§7 не считается записью" check-02-record-parts.sh

restore
# дата без ревизии — половина части, обязана ловиться
perl -0pi -e 's/^(> \*\*Наблюдение:\*\* [0-9]{4}-[0-9]{2}-[0-9]{2}).*$/$1./m' "$CA"
run 1 "инъекция: дата есть, ревизии нет" check-02-record-parts.sh

restore
# предпосылка гейта: сменилась форма объявления разделов ⇒ VOID, не успех
sed -i 's/^## §1\./## Раздел 1./' "$CA"
run 2 "предпосылка: форма объявления разделов сменилась ⇒ VOID" check-02-record-parts.sh

echo
echo "== гейт 03 — перечень сходится с деревом =="

restore
run 0 "чистое дерево (законный близнец: перечень = дерево)" check-03-roster-matches-tree.sh

restore
perl -0pi -e 's/^- `measurement-discipline` \(workspace\).*?\n//ms' "$AT"
run 1 "инъекция: скил есть в дереве, но выпал из перечня" check-03-roster-matches-tree.sh
grep -q 'measurement-discipline' <<<"${LAST_OUT:-}" \
    && printf '  [ok]   инъекция названа именем скила\n' && pass=$((pass + 1)) \
    || { printf '  [БЕДА] гейт покраснел, но имя не назвал\n'; fail=$((fail + 1)); }

restore
perl -0pi -e 's/^(## Канонические скилы.*?\n)/$1\n- `skil-kotorogo-net` (workspace) — просроченное объявление.\n/ms' "$AT"
run 1 "инъекция: перечень называет скил, которого в дереве нет" check-03-roster-matches-tree.sh

restore
# законный близнец: строка про repo-скил `<svc>-load-testing` исключается намеренно
run 0 "законный близнец: строка repo-скила в счёт не идёт" check-03-roster-matches-tree.sh

restore
sed -i 's/^## Канонические скилы.*/## Список скилов/' "$AT"
run 2 "предпосылка: заголовок перечня скилов сменился ⇒ VOID" check-03-roster-matches-tree.sh

restore
perl -0pi -e 's/^- `wave-reviewer`.*?\n//ms' "$AT"
run 1 "инъекция: агент есть в дереве, но выпал из перечня" check-03-roster-matches-tree.sh
grep -q 'wave-reviewer' <<<"${LAST_OUT:-}" \
    && printf '  [ok]   инъекция названа именем агента\n' && pass=$((pass + 1)) \
    || { printf '  [БЕДА] гейт покраснел, но имя агента не назвал\n'; fail=$((fail + 1)); }

restore
perl -0pi -e 's/^(## Канонические агенты.*?\n)/$1\n- `agent-kotorogo-net` — просроченное объявление.\n/ms' "$AT"
run 1 "инъекция: перечень называет агента, которого в дереве нет" check-03-roster-matches-tree.sh

restore
# ЗАКОННЫЙ БЛИЗНЕЦ: domain-агенты объявлены строкой «- домен …: `имя`, …» и в счёт
# не идут by construction. Без этой половины гейт требовал бы от них файла в
# `.claude/agents/`, которого у них нет и быть не должно.
perl -0pi -e 's/^(## Канонические агенты.*?\n)/$1\n- домен storage: `storage-volume-specialist`, `storage-newman-author`.\n/ms' "$AT"
run 0 "законный близнец: строка domain-агентов в счёт не идёт" check-03-roster-matches-tree.sh

restore
sed -i 's/^## Канонические агенты.*/## Список агентов/' "$AT"
run 2 "предпосылка: заголовок перечня агентов сменился ⇒ VOID" check-03-roster-matches-tree.sh

# ── ПРИВЯЗКА ПРАВИЛА ПРОТИВ ЭКСПЕРТИЗЫ: пара, доказывающая предикат исключения ──
#
# Исключение `rule-*` из перечня скилов держится СВОЙСТВОМ ФАЙЛА («SKILL.md —
# символьная ссылка»), а не именем каталога. Доказать это можно только парой:
# законная привязка обязана молчать, а каталог под тем же именем с НАСТОЯЩИМ
# файлом — краснеть. Проверь одну половину — и исключение по имени прошло бы за
# исключение по свойству, то есть экспертиза под зарезервированным именем
# выпадала бы из каждого перечня молча.
restore
# ЗАКОННЫЙ БЛИЗНЕЦ: новая привязка нового правила — ссылка, как все тридцать.
printf '# Временное правило\n\n## Раздел\n\nтело\n' > "$TMP/.claude/rules/vremennoe.md"
mkdir -p "$TMP/.claude/skills/rule-vremennoe"
ln -sfn ../../rules/vremennoe.md "$TMP/.claude/skills/rule-vremennoe/SKILL.md"
run 0 "законный близнец: новая привязка rule-* (ссылка) в перечень скилов не просится" check-03-roster-matches-tree.sh
rm -rf "$TMP/.claude/skills/rule-vremennoe" "$TMP/.claude/rules/vremennoe.md"

restore
# ДЕФЕКТ: то же имя, но SKILL.md — настоящий файл. Это экспертиза под
# зарезервированным именем: её не перечислит во `skills:` ни один агент.
mkdir -p "$TMP/.claude/skills/rule-poddelka"
printf -- '---\nname: rule-poddelka\ndescription: экспертиза под зарезервированным именем\n---\n\nтело\n' \
    > "$TMP/.claude/skills/rule-poddelka/SKILL.md"
run 1 "инъекция: каталог rule-*, чей SKILL.md НЕ ссылка ⇒ находка, а не тихий пропуск" check-03-roster-matches-tree.sh
grep -q 'rule-poddelka' <<<"${LAST_OUT:-}" \
    && printf '  [ok]   инъекция названа координатой каталога\n' && pass=$((pass + 1)) \
    || { printf '  [БЕДА] гейт покраснел, но каталога не назвал\n'; fail=$((fail + 1)); }
rm -rf "$TMP/.claude/skills/rule-poddelka"

restore
# ДЕФЕКТ ВТОРОЙ СТОРОНЫ: привязка расшита — ссылка заменена копией текста правила.
# Копия правила разойдётся с оригиналом молча, и перечень скилов объявит правило
# экспертизой. Инъекция бьёт ровно в предикат: имя каталога не тронуто.
# ЦЕЛЬ ВЫВОДИТСЯ ИЗ ДЕРЕВА, А НЕ ПОМНИТСЯ ИМЕНЕМ. Прежде здесь стояло `vault.md`
# жёстко, и проба сломалась молча, когда правило уехало в `.claude/backup/`
# (решение владельца 2026-09-20): `cp` не нашёл входа, инъекция не состоялась, а
# счётчик доложил провал — то есть проба обвиняла гейт в своём собственном
# отсутствии входа. Берём ЛЮБОЕ правило, у которого есть парный каталог-ссылка;
# если таких нет вовсе — это третья категория, а не находка.
VICTIM=""
for _r in "$TMP"/.claude/rules/*.md; do
    _b="$(basename "$_r" .md)"
    if [ -L "$TMP/.claude/skills/rule-$_b/SKILL.md" ]; then VICTIM="$_b"; break; fi
done
if [ -z "$VICTIM" ]; then
    printf '  [⊘]    инъекция расшитой привязки НЕ ВЫПОЛНЕНА: ни одно правило не несёт парного каталога-ссылки — входа нет\n'
else
    cp --remove-destination "$TMP/.claude/rules/$VICTIM.md" "$TMP/.claude/skills/rule-$VICTIM/SKILL.md"
    run 1 "инъекция: привязка расшита в копию — каталог rule-* перестал быть ссылкой ($VICTIM)" check-03-roster-matches-tree.sh
    grep -q "rule-$VICTIM" <<<"${LAST_OUT:-}" \
        && printf '  [ok]   расшитая привязка названа координатой\n' && pass=$((pass + 1)) \
        || { printf '  [БЕДА] гейт покраснел, но расшитой привязки не назвал\n'; fail=$((fail + 1)); }
    ln -sfn "../../rules/$VICTIM.md" "$TMP/.claude/skills/rule-$VICTIM/SKILL.md"
fi

restore
# ГЕЙТ 01 НА ТОЙ ЖЕ ПАРЕ. Исключение живёт в `_lib.sh` и читается ОБОИМИ гейтами;
# доказанное на одном не доказано на другом — у них разный вход и разный вердикт.
run 0 "законный близнец (гейт 01): текст правила через ссылку меркой скила не судится" check-01-section-refs.sh

echo
echo "== гейт 07 — объявленное число исполняется, а не помнится =="

restore
run 0 "чистое дерево (законный близнец: каждое число сошлось)" check-07-declared-counts-match-tree.sh

restore
# ИНЪЕКЦИЯ ПО ФОРМЕ, А НЕ ПО ЛИТЕРАЛУ. Прежняя редакция подставляла число в одну
# названную цитату (`git ls-files .claude/rulebook/ … (**15**)`). Цитата уехала
# вместе со снятым 2026-09-13 каталогом, `perl` образца не нашёл — и инъекция
# стала ПУСТОЙ ОПЕРАЦИЕЙ: `run 1` при этом зеленел, потому что гейт краснел по
# постороннему поводу. Проба доказывала не своё и сказать об этом не могла.
# Берётся ПЕРВАЯ пара «цитата git + число» формы A, какой бы ни была цитата.
perl -0pi -e 's/(`git [^`\n]*` \(\*\*)(\d+)(\*\*\))/${1}4242${3}/' "$AT"
bit 'образец формы A (цитата git-команды рядом с числом)'
run 1 "инъекция: объявленное число разошлось с выводом предиката" check-07-declared-counts-match-tree.sh
grep -q 'объявлено 4242' <<<"${LAST_OUT:-}" \
    && printf '  [ok]   названы и координата, и оба числа\n' && pass=$((pass + 1)) \
    || { printf '  [БЕДА] гейт покраснел, но чисел не назвал\n'; fail=$((fail + 1)); }

restore
# ФОРМА B — число ПЕРЕД командой. Без её разбора эта инъекция молчала бы, и
# просроченный счёт агентов (ровно тот, что прожил на стволе) остался бы невидим.
# Образец берётся ПО ФОРМЕ, а не по окончанию слова: «generic-агентов» стало
# «generic-агента», когда счёт с 16 вырос до 32, и проба перестала подставлять
# хоть что-нибудь — `bit` назвал это, `run 1` при этом зеленел бы от соседнего
# красного. Берётся «Счёт: **N**» и первое слово за ним, каким бы оно ни было.
perl -0pi -e 's/^> Счёт: \*\*\d+\*\*/> Счёт: **4242**/m' "$AT"
bit 'образец формы B (строка «Счёт: **N** …» рядом с цитатой предиката)'
run 1 "инъекция: число ПЕРЕД командой (форма B) разошлось с предикатом" check-07-declared-counts-match-tree.sh

restore
# ЗАКОННЫЙ БЛИЗНЕЦ №1: жирное число в прозе, рядом с которым нет цитаты команды.
# Историческая врезка обязана иметь право называть прежние числа.
printf '\n> Историческая справка: когда-то их было **999**, и это верно для своей ревизии.\n' >> "$AT"
run 0 "законный близнец: число без цитаты рядом ⇒ молчание" check-07-declared-counts-match-tree.sh

restore
# ЗАКОННЫЙ БЛИЗНЕЦ №2: цитата НЕ команды git рядом с числом — не предикат о дереве.
printf '\nПример вывода: `ls -l .claude` (**999**) — форма показа, а не предикат.\n' >> "$AT"
run 0 "законный близнец: не-git цитата рядом с числом ⇒ молчание" check-07-declared-counts-match-tree.sh

restore
# ИНЪЕКЦИЯ: цитата ВНЕ разбираемой формы, объявленная числом. Молчать здесь
# нельзя — непрочитанная цитата неотличима от сошедшейся (правило форм записи).
printf '\nПредикат: `git ls-files .claude/rules/ | xargs wc -l` (**3**).\n' >> "$AT"
run 1 "инъекция: цитата вне разбираемой формы ⇒ находка, а не молчание" check-07-declared-counts-match-tree.sh
grep -q 'вне разбора' <<<"${LAST_OUT:-}" \
    && printf '  [ok]   сказано, что цитата не прочитана\n' && pass=$((pass + 1)) \
    || { printf '  [БЕДА] гейт покраснел, но причину не назвал\n'; fail=$((fail + 1)); }

restore
# предпосылка гейта: цитат команд в файле не осталось ⇒ VOID, не успех
perl -0pi -e 's/`git [^`\n]*`/«команда»/g' "$AT"
run 2 "предпосылка: цитат команд git не осталось ⇒ VOID" check-07-declared-counts-match-tree.sh

restore
