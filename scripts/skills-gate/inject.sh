#!/usr/bin/env bash
# Доказательство КАЖДОГО гейта набора инъекцией — В ОБЕ СТОРОНЫ.
#
# Гейт, доказанный только красной половиной, ловит форму, а не существо: первый
# ложный срабат его отключит. Поэтому у каждой инъекции дефекта здесь стоит
# ЗАКОННЫЙ БЛИЗНЕЦ той же формы, на котором гейт обязан молчать
# (`gate-authoring` §Инъекция).
#
# Работает на ВРЕМЕННОЙ копии дерева (`SKILLS_GATE_ROOT`) — рабочее не трогается.
# Копия делается из git-состояния workspace + рабочих файлов скилов и правил.

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WS="$(cd "$SCRIPT_DIR/../.." && pwd)"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

mkdir -p "$TMP/.claude"
cp -r "$WS/.claude/skills" "$TMP/.claude/skills"
cp -r "$WS/.claude/rules"  "$TMP/.claude/rules"
cp -r "$WS/.claude/agents" "$TMP/.claude/agents"
# .gitignore едет вместе: без него временное дерево «отслеживает» и посторонние
# скилы, и перепись гейта 03 разойдётся с настоящей по причине, к предмету
# отношения не имеющей.
cp "$WS/.gitignore" "$TMP/.gitignore"
git -C "$TMP" init -q
git -C "$TMP" add -A >/dev/null 2>&1

# Дерево продукта — предмет проб гейта 06 (у остальных его нет). Оно под игнором,
# поэтому в индекс временной копии не попадает и `restore` его не трогает.
MONO_SRC="${KACHO_MONOREPO:-$WS/project/kacho}"
if [ -d "$MONO_SRC" ]; then
    mkdir -p "$TMP/project"
    ln -s "$MONO_SRC" "$TMP/project/kacho"
    HAVE_MONO=1
else
    HAVE_MONO=0
fi

CA="$TMP/.claude/skills/code-authoring/SKILL.md"
GA="$TMP/.claude/skills/gate-authoring/SKILL.md"
SS="$TMP/.claude/skills/security-surface/SKILL.md"
DT="$TMP/.claude/skills/doc-truthfulness/SKILL.md"
AT="$TMP/.claude/rules/ai-tooling.md"
DW="$TMP/.claude/skills/kacho-docs-writer/SKILL.md"

pass=0
fail=0
void=0

# run <ожидаемый-код> <имя-пробы> <скрипт> [ПЕРЕМЕННАЯ=значение …]
run() {
    local want="$1" label="$2" script="$3" out got
    shift 3
    out="$(env "$@" SKILLS_GATE_ROOT="$TMP" bash "$SCRIPT_DIR/$script" 2>&1)"; got=$?
    if [ "$got" -eq "$want" ]; then
        pass=$((pass + 1)); printf '  [ok]   %-58s код %s\n' "$label" "$got"
    else
        fail=$((fail + 1)); printf '  [БЕДА] %-58s ждали %s, получили %s\n' "$label" "$want" "$got"
        printf '%s\n' "$out" | sed 's/^/         /'
    fi
    LAST_OUT="$out"
}

restore() { git -C "$TMP" checkout -- . >/dev/null 2>&1; }

echo "== гейт 01 — ссылка на норму по имени раздела =="

restore
run 0 "чистое дерево (законный близнец: все ссылки по имени)" check-01-section-refs.sh

restore
printf '\nВременная строка: норма — `security.md:361`.\n' >> "$GA"
run 1 "инъекция: ссылка номером строки" check-01-section-refs.sh
grep -q 'gate-authoring/SKILL.md' <<<"${LAST_OUT:-}" \
    && printf '  [ok]   инъекция названа координатой\n' && pass=$((pass + 1)) \
    || { printf '  [БЕДА] гейт покраснел, но координату не назвал\n'; fail=$((fail + 1)); }

restore
printf '\nВременная строка: норма — `security.md` §Hardening-инварианты п.8.\n' >> "$GA"
run 0 "законный близнец: та же ссылка по имени раздела" check-01-section-refs.sh

restore
printf '\nВременная строка: норма — `security.md` §Такого-раздела-здесь-нет.\n' >> "$GA"
run 1 "инъекция: §-имя, которое не резолвится" check-01-section-refs.sh

restore
# предпосылка гейта: корпус без ссылок на нормы вообще ⇒ VOID, не успех
find "$TMP/.claude/skills" -name SKILL.md -exec sed -i 's/\.md/·md/g' {} +
run 2 "предпосылка: ссылок на нормы нет ⇒ VOID, не успех" check-01-section-refs.sh

echo
echo "== гейт 02 — семь частей записи =="

restore
run 0 "чистое дерево (законный близнец: все записи полны)" check-02-record-parts.sh

restore
# снять предикат снятия у одной записи
perl -0pi -e 's/^> \*\*Предикат снятия:\*\*.*?\n//m' "$CA"
run 1 "инъекция: у записи снят предикат снятия" check-02-record-parts.sh
grep -q '### ' <<<"${LAST_OUT:-}" \
    && printf '  [ok]   инъекция названа записью\n' && pass=$((pass + 1)) \
    || { printf '  [БЕДА] гейт покраснел, но запись не назвал\n'; fail=$((fail + 1)); }

restore
# законный близнец: запись БЕЗ предметного содержания вне §1–§7 (в §9) гейт не трогает
printf '\n### 9.9. Служебная запись без семи частей\n\nПросто текст.\n' >> "$CA"
run 0 "законный близнец: «### N.N» вне §1–§7 не считается записью" check-02-record-parts.sh

restore
# дата без ревизии — половина части, обязана ловиться
perl -0pi -e 's/^(> \*\*Наблюдение:\*\* [0-9]{4}-[0-9]{2}-[0-9]{2}).*$/$1./m' "$CA"
run 1 "инъекция: дата есть, ревизии нет" check-02-record-parts.sh

restore
# предпосылка гейта: сменилась форма объявления разделов ⇒ VOID, не успех
sed -i 's/^## §1\./## Раздел 1./' "$CA"
run 2 "предпосылка: форма объявления разделов сменилась ⇒ VOID" check-02-record-parts.sh

echo
echo "== гейт 03 — перечень сходится с деревом =="

restore
run 0 "чистое дерево (законный близнец: перечень = дерево)" check-03-roster-matches-tree.sh

restore
perl -0pi -e 's/^- `measurement-discipline` \(workspace\).*?\n//ms' "$AT"
run 1 "инъекция: скил есть в дереве, но выпал из перечня" check-03-roster-matches-tree.sh
grep -q 'measurement-discipline' <<<"${LAST_OUT:-}" \
    && printf '  [ok]   инъекция названа именем скила\n' && pass=$((pass + 1)) \
    || { printf '  [БЕДА] гейт покраснел, но имя не назвал\n'; fail=$((fail + 1)); }

restore
perl -0pi -e 's/^(## Канонические скилы.*?\n)/$1\n- `skil-kotorogo-net` (workspace) — просроченное объявление.\n/ms' "$AT"
run 1 "инъекция: перечень называет скил, которого в дереве нет" check-03-roster-matches-tree.sh

restore
# законный близнец: строка про repo-скил `<svc>-load-testing` исключается намеренно
run 0 "законный близнец: строка repo-скила в счёт не идёт" check-03-roster-matches-tree.sh

restore
sed -i 's/^## Канонические скилы.*/## Список скилов/' "$AT"
run 2 "предпосылка: заголовок перечня сменился ⇒ VOID" check-03-roster-matches-tree.sh

echo
echo "== гейт 04 — три части записи каталога поверхностей =="

restore
run 0 "чистое дерево (законный близнец: все записи полны)" check-04-surface-record-parts.sh

restore
# снять противоядие у одной записи
perl -0pi -e 's/^\*\*Противоядие\.\*\* /ЗАМЕНЕНО: /m' "$SS"
run 1 "инъекция: у записи снято противоядие" check-04-surface-record-parts.sh
grep -q '### S' <<<"${LAST_OUT:-}" \
    && printf '  [ok]   инъекция названа записью\n' && pass=$((pass + 1)) \
    || { printf '  [БЕДА] гейт покраснел, но запись не назвал\n'; fail=$((fail + 1)); }

restore
# снять держателя у одной записи
perl -0pi -e 's/^> \*\*Держится:\*\* /> Держится: /m' "$SS"
run 1 "инъекция: у записи не сказано, чем она держится" check-04-surface-record-parts.sh

restore
# ЗАКОННЫЙ БЛИЗНЕЦ: заголовок ТОЙ ЖЕ формы, но вне каталога поверхностей.
# Без этой половины гейт ловил бы форму «### S<N>.<M>» где угодно в файле.
perl -0pi -e 's/^## §12\./### S9.9. Пример формы, не запись\n\nТекст без частей.\n\n## §12./m' "$SS"
run 0 "законный близнец: «### S<N>.<M>» вне каталога записью не считается" check-04-surface-record-parts.sh

restore
# счёт и проверка полноты обязаны читать ОДНО множество
perl -0pi -e 's/^\*\*Записей класса — [0-9]+\*\*/**Записей класса — 999**/m' "$SS"
run 1 "инъекция: объявленное число разошлось с осмотренным" check-04-surface-record-parts.sh

restore
# предпосылка гейта: сменилась форма объявления поверхностей ⇒ VOID, не успех
sed -i 's/^## S1\./## Поверхность 1./' "$SS"
run 2 "предпосылка: форма объявления поверхностей сменилась ⇒ VOID" check-04-surface-record-parts.sh

echo
echo "== гейт 05 — четыре части записи каталога долговечности утверждений =="

restore
run 0 "чистое дерево (законный близнец: все записи полны)" check-05-doc-truth-record-parts.sh

restore
# снять держателя у одной записи
perl -0pi -e 's/^> \*\*Держится:\*\* /> Держится: /m' "$DT"
run 1 "инъекция: у записи не сказано, чем она держится" check-05-doc-truth-record-parts.sh
grep -qE '### [0-9]+\.[0-9]+\.' <<<"${LAST_OUT:-}" \
    && printf '  [ok]   инъекция названа записью\n' && pass=$((pass + 1)) \
    || { printf '  [БЕДА] гейт покраснел, но запись не назвал\n'; fail=$((fail + 1)); }

restore
# снять «наблюдалось» — часть, отличающая наблюдение от догадки
perl -0pi -e 's/^> \*\*Наблюдалось/> Наблюдалось/m' "$DT"
run 1 "инъекция: у записи снято «наблюдалось»" check-05-doc-truth-record-parts.sh

restore
# ЗАКОННЫЙ БЛИЗНЕЦ №1: заголовок ТОЙ ЖЕ формы, но вне каталога классов (§9 —
# процедуры, там части не требуются). Без этой половины гейт требовал бы четыре
# части от каждого «### N.M» в файле и был бы отключён первым же ложным срабатом.
perl -0pi -e 's/^### 9\.5\./### 9.6. Пример формы, не запись\n\nТекст процедуры без частей.\n\n### 9.5./m' "$DT"
run 0 "законный близнец: «### N.M» вне §2..§7 записью не считается" check-05-doc-truth-record-parts.sh

restore
# ЗАКОННЫЙ БЛИЗНЕЦ №2: запись с ДВУМЯ признаками («Признак-А»/«Признак-Б») —
# форма, реально встречающаяся в каталоге; предикат обязан читать её как признак.
perl -0pi -e 's/^\*\*Признак\.\*\* /**Признак-А.** /m' "$DT"
run 0 "законный близнец: «Признак-А» засчитывается за признак" check-05-doc-truth-record-parts.sh

restore
# счёт и проверка полноты обязаны читать ОДНО множество
perl -0pi -e 's/^\*\*Записей класса — [0-9]+\*\*/**Записей класса — 999**/m' "$DT"
run 1 "инъекция: объявленное число разошлось с осмотренным" check-05-doc-truth-record-parts.sh

restore
# предпосылка гейта: сменилась форма объявления разделов ⇒ VOID, не успех
sed -i 's/^## §2\. /## Раздел 2. /' "$DT"
run 2 "предпосылка: форма объявления разделов сменилась ⇒ VOID" check-05-doc-truth-record-parts.sh

restore
# ГРАНИЦА РАЗДЕЛА. Прочие инъекции этого файла правят ПЕРВОЕ вхождение (perl без
# /g), а оно лежит в середине раздела — то есть внутреннюю границу они не
# проверяют вовсе. Здесь часть снята у ПОСЛЕДНЕЙ записи §2, а такая же строка
# подложена в преамбулу §3: пока заголовок раздела не закрывал запись, буфер
# дотягивался до первого «### N.M» следующего раздела и запись зеленела от
# строки, лежащей ЗА её границей.
perl -0pi -e 's/^> \*\*Держится:\*\* (?=[^\n]*declaredcardinality)/> Держится: /m' "$DT"
perl -0pi -e 's/^(## §3\.[^\n]*\n)/$1\n> **Держится:** посторонняя строка в преамбуле следующего раздела.\n/m' "$DT"
run 1 "граница: часть снята у последней записи §2, маркер лежит в преамбуле §3" check-05-doc-truth-record-parts.sh
grep -q '### 2\.7\.' <<<"${LAST_OUT:-}" \
    && printf '  [ok]   названа именно запись за границей\n' && pass=$((pass + 1)) \
    || { printf '  [БЕДА] гейт покраснел, но запись 2.7 не назвал\n'; fail=$((fail + 1)); }

restore
# ЗАКОННЫЙ БЛИЗНЕЦ к границе: маркер в преамбуле есть, но НИ У ОДНОЙ записи
# часть не снята ⇒ гейт обязан молчать. Без этой половины «фикс» мог бы просто
# начать краснеть на любой преамбуле, содержащей маркер.
perl -0pi -e 's/^(## §3\.[^\n]*\n)/$1\n> **Держится:** посторонняя строка в преамбуле следующего раздела.\n/m' "$DT"
run 0 "законный близнец: маркер в преамбуле, но все записи полны ⇒ молчание" check-05-doc-truth-record-parts.sh

restore
# ГРАНИЦА РАЗДЕЛА для гейта 02 — тот же механизм, тот же радиус.
perl -0pi -e 's/^> \*\*Держится:\*\* (?=[^\n]*pipefailguard)/> Держится: /m' "$CA"
perl -0pi -e 's/^(## §2\.[^\n]*\n)/$1\n> **Держится:** посторонняя строка в преамбуле следующего раздела.\n/m' "$CA"
run 1 "граница: часть снята у последней записи §1, маркер в преамбуле §2" check-02-record-parts.sh

restore
perl -0pi -e 's/^(## §2\.[^\n]*\n)/$1\n> **Держится:** посторонняя строка в преамбуле следующего раздела.\n/m' "$CA"
run 0 "законный близнец: маркер в преамбуле, но все записи полны ⇒ молчание" check-02-record-parts.sh

restore
# ГРАНИЦА ПОВЕРХНОСТИ для гейта 04 — тот же механизм.
perl -0pi -e 's/^> \*\*Держится:\*\* (?=[^\n]*selftest-assertions)/> Держится: /m' "$SS"
perl -0pi -e 's/^(## S2\.[^\n]*\n)/$1\n> **Держится:** посторонняя строка в преамбуле следующей поверхности.\n/m' "$SS"
run 1 "граница: часть снята у последней записи S1, маркер в преамбуле S2" check-04-surface-record-parts.sh

restore
perl -0pi -e 's/^(## S2\.[^\n]*\n)/$1\n> **Держится:** посторонняя строка в преамбуле следующей поверхности.\n/m' "$SS"
run 0 "законный близнец: маркер в преамбуле, но все записи полны ⇒ молчание" check-04-surface-record-parts.sh

restore
echo
echo "== гейт 06 — объявленная раскладка документации сходится с деревом =="

if [ "$HAVE_MONO" -eq 0 ]; then
    void=$((void + 1))
    printf '  [VOID] пробы гейта 06 НЕ ВЫПОЛНЯЛИСЬ: дерева продукта нет (%s).\n' "$MONO_SRC"
    printf '         Это не «зелено» — предмет проб недоступен. Укажите KACHO_MONOREPO.\n'
else
    restore
    run 0 "чистое дерево (законный близнец: объявление = дерево)" check-06-docs-layout-matches-tree.sh

    restore
    # Инъекция настоящим входом: имя каталога сайта, снятое в дереве продукта.
    sed -i 's/^| каталог сайта у компонента | `docs` |/| каталог сайта у компонента | `docs-site` |/' "$DW"
    run 1 "инъекция: объявлен каталог сайта, которого в дереве нет" check-06-docs-layout-matches-tree.sh
    grep -q 'kacho-docs-writer/SKILL.md' <<<"${LAST_OUT:-}" \
        && printf '  [ok]   инъекция названа координатой\n' && pass=$((pass + 1)) \
        || { printf '  [БЕДА] гейт покраснел, но координату не назвал\n'; fail=$((fail + 1)); }

    restore
    # ЗАКОННЫЙ БЛИЗНЕЦ той же формы: то же снятое имя, но в исторической прозе, а не
    # в объявлении. Без этой половины гейт ловил бы встречаемость строки — и запретил
    # бы разбирать собственную ошибку, то есть ровно то письмо, ради которого он есть.
    printf '\n> Историческая справка: прежде каталог сайта назывался `docs-site`.\n' >> "$DW"
    run 0 "законный близнец: снятое имя в исторической прозе ⇒ молчание" check-06-docs-layout-matches-tree.sh

    restore
    sed -i 's/^| сайтов в дереве | `8` |/| сайтов в дереве | `7` |/' "$DW"
    run 1 "инъекция: объявленное число сайтов разошлось с деревом" check-06-docs-layout-matches-tree.sh

    restore
    sed -i 's|^cd services/vpc/docs \&\& npm run build.*|cd services/vpc/docs-site \&\& npm run build|' "$DW"
    run 1 "инъекция: сборка процитирована из каталога, которого нет" check-06-docs-layout-matches-tree.sh
    grep -q 'docs-site' <<<"${LAST_OUT:-}" \
        && printf '  [ok]   инъекция названа каталогом\n' && pass=$((pass + 1)) \
        || { printf '  [БЕДА] гейт покраснел, но каталог не назвал\n'; fail=$((fail + 1)); }

    restore
    # ЗАКОННЫЙ БЛИЗНЕЦ: цитата той же формы из СУЩЕСТВУЮЩЕГО каталога.
    sed -i 's|^cd services/vpc/docs \&\& npm run build.*|cd gateway/docs \&\& npm run build|' "$DW"
    run 0 "законный близнец: сборка из существующего каталога ⇒ молчание" check-06-docs-layout-matches-tree.sh

    # ── подстановка в рабочем каталоге: рецепт на семейство каталогов ────────────
    # Оснастка пишет рецепт на семейство одной строкой (`ui-future/<модуль>`,
    # `services/<svc>/docs`) — это НОРМАЛЬНАЯ форма корпуса, а не небрежность.
    # Требовать от неё дословного существования значит запретить рецепт на
    # семейство вовсе; пропускать её целиком — вернуть слепое пятно, ради которого
    # гейт и заведён (хук свежести подстановку НЕ резолвит, см. шапку гейта).
    # Поэтому подстановка РАЗРЕШАЕТСЯ: сегмент с `<…>` обязан иметь хотя бы одну
    # существующую подстановку, и внутри неё обязано что-то лежать.
    restore
    printf '\n```sh\ncd services/<svc>/docs && npm run build\n```\n' >> "$DW"
    run 0 "законный близнец: подстановка резолвится (services/<svc>/docs) ⇒ молчание" \
        check-06-docs-layout-matches-tree.sh

    restore
    # ИНЪЕКЦИЯ той же формы: литеральный сегмент переименован ⇒ подставлять некуда.
    printf '\n```sh\ncd services-nope/<svc>/docs && npm run build\n```\n' >> "$DW"
    run 1 "инъекция: подстановка под несуществующим каталогом" check-06-docs-layout-matches-tree.sh
    grep -q 'services-nope' <<<"${LAST_OUT:-}" \
        && printf '  [ok]   инъекция названа каталогом\n' && pass=$((pass + 1)) \
        || { printf '  [БЕДА] гейт покраснел, но каталог не назвал\n'; fail=$((fail + 1)); }

    restore
