#!/usr/bin/env bash
# skills-gate #06 — раскладка каталогов документации ОБЪЯВЛЕНА машинно и сходится с деревом.
#
# ЧТО УТВЕРЖДАЕТ. Регламент документации (`kacho-docs-writer`) описывает, где у
# компонента продукта лежит сайт документации, страницы и инженерная часть. Эти
# имена — утверждение о ЧУЖОМ дереве: оно живёт в другом репозитории и переезжает
# там без единого конфликта здесь. Поэтому регламент обязан объявить раскладку
# машинно-сверяемым блоком, а гейт выводит те же значения из дерева продукта и
# сверяет их. Расхождение — находка с координатой.
#
# Вторым предикатом сверяется рабочий каталог КАЖДОЙ процитированной оснасткой
# команды сборки сайта (`cd <каталог> && npm …`): каталог обязан существовать в
# дереве продукта либо в воркспейсе. Команда, которую негде выполнить, — не
# рецепт, а тупик для того, кто ей поверил.
#
# Рецепт на СЕМЕЙСТВО каталогов законен и проверяется, а не пропускается. Сегмент
# с подстановкой (`ui-future/<модуль>`) сходится с любым одним существующим
# сегментом, поэтому находкой остаются оба настоящих дефекта: литеральной части
# нет в дереве (каталог переименован или переехал) и подставить в неё нечего
# (семейство пусто). Пропуск подстановки целиком был бы не послаблением предиката,
# а возвратом слепого пятна: именно подстановку НЕ резолвит хук свежести, и ровно
# поэтому самое читаемое утверждение о раскладке оказалось вне всякой проверки.
#
# ПОЧЕМУ ЭТО НЕ ДУБЛЬ ХУКА СВЕЖЕСТИ. Тот резолвит координаты в обратных кавычках и
# НАМЕРЕННО пропускает токен с подстановкой (`project/<svc>/…`) — резолвить в нём
# нечего. Ровно в такой форме раскладка и записана в нормативном регламенте, то
# есть самое читаемое утверждение о ней было вне всякого предиката. Здесь
# сверяются ИМЕНА уровней, а не отдельные пути, поэтому подстановка предикату не
# мешает.
#
# ГДЕ СУДИТСЯ — НА СТВОЛЕ ПРОДУКТА, А НЕ В ИНДЕКСЕ ЛЕЖАЩЕЙ РЯДОМ КОПИИ.
# Раскладка выводится из СТВОЛА дерева продукта (`ls-tree <ссылка>`), а не из
# индекса рабочей копии (`ls-files`). Копия общая, парковку её никто не объявляет,
# и индекс тогда отвечает о том, на чём она стоит СЕЙЧАС, а не о том, что у
# продукта есть. Цена измерена, а не предположена (2026-09-12, ws#621): на копии,
# припаркованной на ревизии, где каталог службы доступа снят, гейт назвал
# объявление «сайтов 8» разошедшимся с деревом, где их 7. На стволе восьмой сайт
# ЕСТЬ — вердикт был ложен о продукте и верен лишь о состоянии одной копии, а
# отправку любой ветки воркспейса он при этом остановил.
#
# Хуже того, тем же состоянием была ОБЕЗОРУЖЕНА собственная проба падучести:
# инъекция «объявлено 7 вместо 8» на припаркованной копии СХОДИТСЯ с индексом, и
# проба, доказывавшая способность гейта краснеть, зеленела наоборот. Гейт,
# доказанный на такой копии, не доказан ни в одну сторону.
#
# Резолв ствола ОДИН на оба набора — `scripts/lib/product_trunk.py`, тот же, что
# читает `docs-gate`. Своя копия была бы вторым кодеком об одном предмете, а два
# кодека расходятся молча и расходятся там, где это не видно.
#
# ПРЕДПОСЫЛКА ГЕЙТА (проверяется здесь же). Основание — СТВОЛ дерева продукта и то,
# что на нём есть хотя бы один сайт (признак сайта — его `docusaurus.config.ts`, а
# не выписанное имя каталога: имя как раз и переезжает). Нет дерева, НЕ РАЗРЕШЁН
# его ствол или нет ни одного конфига — VOID, а не успех: «ноль расхождений» и
# «ноль прочитанного» обязаны различаться. Откат на индекс копии запрещён — он и
# есть дефект, ради которого полоса выровнена; вердикт, вынесенный о чужом
# состоянии, строкой переписи не исправляется, потому что перепись читают ПОСЛЕ.
#
# ОТСУТСТВИЕ ОБЪЯВЛЕНИЯ — НАХОДКА, А НЕ VOID. Иначе гейт снимается удалением блока:
# послабление, которое отключает проверку, стоит дороже проверки.
#
# Коды выхода: 0 — объявление сошлось со стволом; 1 — расхождение; 2 — VOID.

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=_lib.sh
source "$SCRIPT_DIR/_lib.sh"

WS="$(skills_gate_workspace_root)"
NAME="06-docs-layout-matches-tree"
SKILL_REL=".claude/skills/kacho-docs-writer/SKILL.md"
SKILL="$WS/$SKILL_REL"
MARKER="РАСКЛАДКА-ДОКУМЕНТАЦИИ"

# Дерево продукта: рядом (`project/kacho`) либо названное явно. Переменная — та же,
# что у соседних наборов, чтобы гейт гонялся из рабочей копии, где клона продукта нет.
MONO="${KACHO_MONOREPO:-$WS/project/kacho}"

[ -d "$MONO" ] || {
    skills_gate_void "$NAME" "дерева продукта нет ($MONO) — выводить раскладку не из чего"
    exit 2
}

# Ствол чужого дерева. Не разрешён — VOID: выводить раскладку не из чего, и
# индекс копии полосой НЕ является (см. шапку).
if ! skills_gate_product_trunk "$MONO"; then
    skills_gate_void "$NAME" "ствол дерева продукта ($MONO) не разрешён — ${TRUNK_LAG:-причина не названа}. Раскладку выводить не из чего; индекс рабочей копии полосой НЕ является: припаркованная копия объявляет несуществующим то, что на стволе есть"
    exit 2
fi

# Состав чужого дерева спрашивается у его СТВОЛА, а не у диска и не у индекса:
# каталог продукта в этом репозитории под игнором, обход диска принёс бы собранные
# сайты и чужие черновики, а индекс отвечает о состоянии одной копии.
mono_files="$(skills_gate_product_files "$MONO" "$TRUNK_REF")"
[ -n "$mono_files" ] || {
    skills_gate_void "$NAME" "на стволе дерева продукта ($MONO, $TRUNK_REF) состава нет — читать нечем"
    exit 2
}

# ── основание: что дерево говорит о себе само ────────────────────────────────────
configs="$(printf '%s\n' "$mono_files" | grep -E '(^|/)docusaurus\.config\.ts$' | sort || true)"
n_cfg="$(printf '%s\n' "$configs" | grep -c . || true)"

if [ "$n_cfg" -eq 0 ]; then
    skills_gate_void "$NAME" "на стволе дерева продукта ($TRUNK_REF) нет ни одного docusaurus.config.ts — сверять не с чем"
    exit 2
fi

tree_sites=""       # пути каталогов сайтов относительно корня продукта
tree_site_dirs=""   # их имена
tree_pages_dirs=""  # каталоги страниц, объявленные самими конфигами
while IFS= read -r cfg; do
    [ -n "$cfg" ] || continue
    site="$(dirname "$cfg")"
    tree_sites="$tree_sites$site"$'\n'
    tree_site_dirs="$tree_site_dirs$(basename "$site")"$'\n'
    # Каталог страниц объявляет сам конфиг — ключ `path` пресета docs. Регистр
    # значим: `sidebarPath`/`routeBasePath` под `path:` не подпадают.
    pg="$(skills_gate_product_show "$MONO" "$TRUNK_REF" "$cfg" \
          | grep -oE "^[[:space:]]*path:[[:space:]]*['\"][^'\"]+['\"]" | head -1 \
          | sed -E "s/.*['\"]([^'\"]+)['\"].*/\1/")"
    tree_pages_dirs="$tree_pages_dirs${pg:-docs}"$'\n'
done <<<"$configs"

tree_site_dirs="$(printf '%s' "$tree_site_dirs" | sort -u | grep . || true)"
tree_pages_dirs="$(printf '%s' "$tree_pages_dirs" | sort -u | grep . || true)"

# ── объявление регламента ────────────────────────────────────────────────────────
[ -f "$SKILL" ] || {
    skills_gate_void "$NAME" "нет $SKILL_REL — объявлять раскладку некому"
    exit 2
}

# Блок объявления: строки таблицы после маркерного комментария, до первой пустой.
declared="$(awk -v m="$MARKER" '
    index($0, m) {inside=1; next}
    inside && /^[[:space:]]*$/ {exit}
    inside && /^\|/ {print}
' "$SKILL")"

get_declared() {   # get_declared <ключ> → значение в обратных кавычках или пусто
    printf '%s\n' "$declared" \
        | awk -F'|' -v k="$1" 'index($2, k) {print $3; exit}' \
        | sed -nE 's/.*`([^`]+)`.*/\1/p'
}

d_site="$(get_declared 'каталог сайта')"
d_pages="$(get_declared 'каталог страниц')"
d_eng="$(get_declared 'каталог инженерной части')"
d_count="$(get_declared 'сайтов в дереве')"

n_rows="$(printf '%s\n' "$declared" | grep -cE '^\|.*`' || true)"

# ── второй предикат: рабочий каталог процитированной сборки ──────────────────────
tooling_files="$(git -C "$WS" ls-files --cached --others --exclude-standard \
                    '.claude/rules/*.md' '.claude/skills/*/*.md' '.claude/agents/*.md' | sort -u)"
n_files="$(printf '%s\n' "$tooling_files" | grep -c . || true)"

cites="$(cd "$WS" && printf '%s\n' "$tooling_files" | grep . \
            | xargs -r grep -nE 'cd[[:space:]]+[^[:space:]&|;]+[[:space:]]*&&[[:space:]]*npm' 2>/dev/null || true)"
n_cites="$(printf '%s\n' "$cites" | grep -c . || true)"

ws_files="$(git -C "$WS" ls-files --cached --others --exclude-standard)"

# Есть ли такой каталог — посегментным сравнением с путями индекса. Сравнение
# ДОСЛОВНОЕ, посегментно, без регулярных выражений: путь несёт точки и дефисы, и
# всякое экранирование здесь — источник тихого ложного ответа в обе стороны.
#
# Сегмент вида `<модуль>` — ПОДСТАНОВКА: рецепт на семейство каталогов, обычная
# форма записи в оснастке (`ui-future/<модуль>`, `services/<svc>/docs`). Он
# сходится с любым ОДНИМ существующим сегментом — то есть проверяется не буква, а
# наличие хотя бы одной подстановки, дающей настоящий каталог. Пропускать такие
# цитаты целиком нельзя: подстановку не резолвит хук свежести, и ровно ради этого
# слепого пятна гейт заведён (см. шапку).
#
# Совпадением считается строка, у которой сегментов БОЛЬШЕ, чем в образце: путь
# индекса — файл, поэтому «внутри каталога что-то лежит» и «каталог существует»
# здесь одно и то же. Следствие, ради которого это важно: `deploy/kind/<модуль>`
# не сходится ни с чем, хотя `deploy/kind` существует, — подставлять в него нечего.
#
# Читающая сторона дочитывает вход ДО КОНЦА и не выходит на первом совпадении.
# Ранний выход закрывал бы канал под пишущим `printf`, тот получал бы SIGPIPE, и
# при `pipefail` вердикт пайплайна становился 141 — «каталога нет» для КАЖДОГО
# каталога. Дефект найден на своей же зелёной ветке: гейт краснел на верном дереве.
dir_in_index() {   # dir_in_index <список файлов> <каталог>
    [ "$2" = "." ] && return 0
    printf '%s\n' "$1" | awk -v pat="$2" '
        BEGIN { np = split(pat, P, "/") }
        {
            nf = split($0, F, "/")
            if (nf <= np) next
            ok = 1
            for (i = 1; i <= np; i++) {
                if (index(P[i], "<") && index(P[i], ">")) {
                    if (F[i] == "") { ok = 0; break }
                } else if (F[i] != P[i]) { ok = 0; break }
            }
            if (ok) found = 1
        }
        END { exit !found }'
}

# Литеральная часть пути до первой подстановки — чтобы находка называла ПРИЧИНУ:
# «такого каталога нет» и «подставить в него нечего» — разные починки.
literal_prefix() {   # literal_prefix <каталог с подстановкой>
    printf '%s' "$1" | awk -F/ '{
        out = ""
        for (i = 1; i <= NF; i++) {
            if (index($i, "<") && index($i, ">")) break
            out = (out == "" ? $i : out "/" $i)
        }
        print out
    }'
}

rc=0
fails=""
note() { fails="$fails  $1"$'\n'; rc=1; }

# ── сверка ───────────────────────────────────────────────────────────────────────
echo "перепись: дерево продукта — $TRUNK_LAG; путей на стволе — $(printf '%s\n' "$mono_files" | grep -c . || true); конфигов сайтов прочитано — $n_cfg; строк объявления разобрано — $n_rows; файлов оснастки прочитано — $n_files; цитат сборки разобрано — $n_cites"

if [ "$n_rows" -eq 0 ]; then
    note "$SKILL_REL: раскладка описана, но не ОБЪЯВЛЕНА — блока «$MARKER» нет, сверять нечем"
else
    if [ -z "$d_site" ]; then
        note "$SKILL_REL: в объявлении нет строки «каталог сайта»"
    elif ! printf '%s\n' "$tree_site_dirs" | grep -qxF "$d_site"; then
        note "$SKILL_REL: объявлен каталог сайта «$d_site», дерево знает: $(printf '%s' "$tree_site_dirs" | tr '\n' ' ')"
    fi

    if [ -z "$d_pages" ]; then
        note "$SKILL_REL: в объявлении нет строки «каталог страниц»"
    elif ! printf '%s\n' "$tree_pages_dirs" | grep -qxF "$d_pages"; then
        note "$SKILL_REL: объявлен каталог страниц «$d_pages», конфиги называют: $(printf '%s' "$tree_pages_dirs" | tr '\n' ' ')"
    fi

    if [ -z "$d_eng" ]; then
        note "$SKILL_REL: в объявлении нет строки «каталог инженерной части»"
    else
        missing=""
        while IFS= read -r site; do
            [ -n "$site" ] || continue
            dir_in_index "$mono_files" "$site/$d_eng" || missing="$missing $site"
        done <<<"$(printf '%s' "$tree_sites" | grep . || true)"
        [ -z "$missing" ] || note "$SKILL_REL: объявлен каталог инженерной части «$d_eng», его нет у сайтов:$missing"
    fi

    if [ -z "$d_count" ]; then
        note "$SKILL_REL: в объявлении нет строки «сайтов в дереве»"
    elif [ "$d_count" != "$n_cfg" ]; then
        note "$SKILL_REL: объявлено сайтов «$d_count», на стволе дерева ($TRUNK_REF $TRUNK_REV_SHORT) $n_cfg"
    fi
fi

while IFS= read -r cite; do
    [ -n "$cite" ] || continue
    where="${cite%%:*}"; rest="${cite#*:}"; lineno="${rest%%:*}"
    dir="$(printf '%s' "$cite" | sed -nE 's/.*cd[[:space:]]+([^[:space:]&|;]+).*/\1/p' | head -1)"
    dir="${dir%/}"
    # Путь может быть записан от воркспейса — там читатель и стоит.
    case "$dir" in
        project/kacho) dir="." ;;
        project/kacho/*) dir="${dir#project/kacho/}" ;;
    esac
    if ! dir_in_index "$mono_files" "$dir" && ! dir_in_index "$ws_files" "$dir"; then
        if [ "$dir" != "${dir#*<}" ] && [ "$dir" != "${dir%>*}" ]; then
            # Подстановка не резолвится — назвать, ЧТО именно чинить.
            pfx="$(literal_prefix "$dir")"
            if [ -n "$pfx" ] && { dir_in_index "$mono_files" "$pfx" || dir_in_index "$ws_files" "$pfx"; }; then
                note "$where:$lineno: сборка процитирована из «$dir» — «$pfx» существует, но ни одна подстановка не даёт каталога с содержимым"
            else
                note "$where:$lineno: сборка процитирована из «$dir» — литеральной части «$pfx» нет ни на стволе дерева продукта, ни в индексе воркспейса"
            fi
        else
            note "$where:$lineno: сборка процитирована из каталога «$dir» — его нет ни на стволе дерева продукта, ни в индексе воркспейса"
        fi
    fi
done <<<"$cites"

if [ "$rc" -ne 0 ]; then
    printf '%s' "$fails" >&2
    skills_gate_fail "$NAME" "объявленная раскладка документации разошлась с деревом"
    exit 1
fi

skills_gate_pass "$NAME" "раскладка сошлась: сайтов $n_cfg, каталог сайта «$d_site», страницы «$d_pages», инженерная часть «$d_eng»"
exit 0
