#!/usr/bin/env bash
# Прогоняет все проверки набора и выносит ОДИН вердикт из числа, а не из печати.
#
# «Проверять нечего» (код 2) НЕ засчитывается за успех и печатается отдельной
# строкой: один и тот же ноль иначе означал бы и чистое дерево, и неоткрытое
# (`gate-authoring` §Гейт заявляет предпосылку).

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

ok=0; bad=0; void=0; count=0
for c in "$SCRIPT_DIR"/check-*.sh; do
    # Глоб, не нашедший ни одного файла, подставляет САМ СЕБЯ, и `bash <глоб>`
    # даёт 127 — то есть пустой обход и раньше краснел, но по случайности, а не
    # по решению. Счётчик делает это решением и позволяет назвать объём
    # осмотренного отдельной строкой.
    [ -f "$c" ] || continue
    count=$((count + 1))
    bash "$c"
    case $? in
        0) ok=$((ok + 1)) ;;
        2) void=$((void + 1)) ;;
        *) bad=$((bad + 1)) ;;
    esac
done

echo
if [ "$count" -gt 0 ]; then
    echo "skills-gate: рассмотрено проверок $count; пройдено $ok, провалено $bad, без предмета $void"
else
    echo "skills-gate: рассмотрено проверок 0 в $SCRIPT_DIR — предпосылка не резолвится, прогонять нечего" >&2
fi

# ── ВЕРДИКТ: ТРИ ИСХОДА, И У КАЖДОГО СВОЙ КОД ────────────────────────────────
#
#   0 — рассмотрено N, находок 0, у каждой проверки был предмет;
#   1 — НАХОДКА: проверка упала, либо обход пуст (о дереве не прочитано ничего);
#   2 — БЕЗ ПРЕДМЕТА: находок нет, но часть проверок не с чем было сверять.
#
# До 2026-08-30 второй и третий исход давали ОДИН код, и вызывающий не мог их
# различить: «гейт нашёл нарушение» и «гейту нечего было смотреть» приходили
# единицей. Из рабочей копии без клона продукта единицу получала КАЖДАЯ отправка
# — то есть красное приходило всегда и по причине, к дереву не относящейся, а
# такое красное перестают читать вместе с настоящими находками (ws#458).
#
# ПОРЯДОК ПРОВЕРКИ КОДОВ — НЕСУЩИЙ, А НЕ КОСМЕТИЧЕСКИЙ. Находка объявляется
# ПЕРВОЙ: набор, где есть и находка, и беспредметная проверка, обязан выйти
# единицей. Обратный порядок сделал бы «без предмета» маской — достаточно было бы
# одной беспредметной проверки, чтобы настоящая находка перестала блокировать.
#
# ПУСТОЙ ОБХОД ОСТАЁТСЯ НАХОДКОЙ (код 1), а не «без предмета»: ноль рассмотренных
# проверок означает, что каталог переехал и о дереве не прочитано НИЧЕГО, — это
# отказ самого набора, а не отсутствие условия у отдельной проверки.

[ "$count" -gt 0 ] || exit 1
[ "$bad" -eq 0 ] || exit 1
[ "$void" -eq 0 ] || exit 2
exit 0
