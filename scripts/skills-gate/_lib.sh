#!/usr/bin/env bash
# Shared helpers for skills-gate checks. Source-only — not directly executable.
#
# Предмет набора: утверждения, которые скилы делают САМИ О СЕБЕ и о дереве вокруг.
# Такие утверждения устаревают молча (`gate-authoring` §Читать исполняемое —
# «утверждение о дереве не есть проверка»), поэтому у каждого обязан быть
# исполняемый вопрос к git, а не абзац.

# Корень workspace. `SKILLS_GATE_ROOT` переопределяет его — этим пользуется
# ТОЛЬКО inject.sh, чтобы прогонять гейт по временному дереву с внесённым
# дефектом и не трогать рабочее (`gate-authoring` §Инъекция).
skills_gate_workspace_root() {
    if [ -n "${SKILLS_GATE_ROOT:-}" ]; then
        cd "$SKILLS_GATE_ROOT" && pwd
        return
    fi
    local script_dir
    script_dir="$(cd "$(dirname "${BASH_SOURCE[1]}")" && pwd)"
    cd "$script_dir/../.." && pwd
}

skills_gate_pass() { echo "[PASS] $1${2:+ — $2}"; }
skills_gate_fail() { echo "[FAIL] $1${2:+ — $2}" >&2; }
skills_gate_void() { echo "[VOID] $1${2:+ — $2}" >&2; }   # «проверять нечего» ≠ «находок 0»

# Состав дерева — из индекса git, не с диска: посторонний каталог рядом с репо
# иначе влияет на вердикт (`measurement-discipline` §Откуда читается предмет).
# `--others --exclude-standard` добавляет ЕЩЁ НЕ закоммиченный, но и не
# игнорируемый скил: иначе новый скил не проверяется ровно в тот день, когда его
# пишут, — а гейт молчит и это неотличимо от чистого дерева.
# Печатает пути SKILL.md относительно корня workspace, по одному на строку.
#
# ВСЕ КАТАЛОГИ, ПО ОДНОМУ ПУТИ НА КАЖДЫЙ. Разделение на экспертизу и привязку
# делает `skills_gate_skill_is_binding` ниже; тем, кто спрашивает «каковы скилы»,
# нужен `skills_gate_expertise_files`.
#
# `core.quotepath=false` — не косметика. По умолчанию git ЭКРАНИРУЕТ путь с
# не-ASCII именем и оборачивает его в кавычки (`".claude/skills/\320\277…"`).
# Такой путь не открывается ни на чтение, ни предикатом `-L`, то есть каталог с
# кириллическим именем становился бы для набора НЕВИДИМ — маской ровно на том,
# что проверка обязана ловить. Тот же довод стоит в `scripts/adapter-gate/probe.py`.
skills_gate_skill_files() {
    local ws="$1"
    git -C "$ws" -c core.quotepath=false ls-files --cached --others --exclude-standard \
        '.claude/skills/*/SKILL.md' | sort -u
}

# ── ПРИВЯЗКА ПРАВИЛА — НЕ СКИЛ. ЭТО ИСКЛЮЧЕНИЕ ОБЪЯВЛЕНО, А НЕ ПОДРАЗУМЕВАЕТСЯ ──
#
# Решением владельца 2026-09-17 правило доезжает до агента предзагрузкой: у
# правила заведён каталог `.claude/skills/rule-<имя>/`, чей `SKILL.md` —
# СИМВОЛЬНАЯ ССЫЛКА на `../../rules/<имя>.md`, а агент перечисляет свои правила во
# `skills:`. Такой каталог — АДРЕС, по которому харнесс берёт правило целиком, и
# экспертизой он не является: содержимого своего у него нет ни байта.
#
# Цена молчаливого счёта измерена: гейт 01 на этом дереве выдал 52 находки, и все
# 52 — о ТЕКСТЕ ПРАВИЛ, прочитанном второй раз через ссылку. Правила пишутся по
# своим нормам («§«Заголовок»» в кавычках-ёлочках), а не по нормам скилов, и гейт
# скилов судил их чужой меркой. Перечень скилов при этом вырос с 14 до 44 — то
# есть и перепись, и вердикт стали говорить не о своём предмете.
#
# ПРЕДИКАТ — СВОЙСТВО ФАЙЛА, А НЕ ИМЯ КАТАЛОГА. Имя `rule-*` подделывается одним
# `mkdir`, и тогда экспертиза под зарезервированным именем ТИХО выпала бы из
# каждого перечня — то есть исключение стало бы дырой. Привязка — это ссылка;
# каталог `rule-*`, чей `SKILL.md` не ссылка, привязкой не является и обязан быть
# НАХОДКОЙ (её печатает `check-03`), а не тихо пропущенным.
SKILLS_GATE_BINDING_PREFIX="rule-"

# Является ли каталог скила привязкой правила. Вход — путь SKILL.md ОТНОСИТЕЛЬНО
# корня; спрашивается диск, потому что «ссылка ли это» — свойство файла, а индекс
# git хранит его отдельным режимом и без второго вопроса не отдаёт.
skills_gate_skill_is_binding() {
    local ws="$1" rel="$2"
    [ -L "$ws/$rel" ]
}

# Имя каталога скила из пути его SKILL.md.
skills_gate_skill_name() {
    printf '%s' "$1" | cut -d/ -f3
}

# Скилы-ЭКСПЕРТИЗЫ: те же пути, из которых вычтены привязки правил. Это вход для
# всякой проверки, чей предмет — утверждения скила о себе.
skills_gate_expertise_files() {
    local ws="$1" rel
    while IFS= read -r rel; do
        [ -n "$rel" ] || continue
        skills_gate_skill_is_binding "$ws" "$rel" && continue
        printf '%s\n' "$rel"
    done < <(skills_gate_skill_files "$ws")
}

# Привязки правил — отдельным перечнем: их число печатается в переписи, иначе
# «скилов 14» не отличить от «тридцать штук молча выпали».
skills_gate_binding_files() {
    local ws="$1" rel
    while IFS= read -r rel; do
        [ -n "$rel" ] || continue
        skills_gate_skill_is_binding "$ws" "$rel" || continue
        printf '%s\n' "$rel"
    done < <(skills_gate_skill_files "$ws")
}

# Каталоги под зарезервированным именем `rule-*`, чей SKILL.md НЕ ссылка. Это
# находка, а не третья категория: имя занято привязкой правила, и экспертиза под
# ним не доедет ни до одного агента — её никто не перечислит во `skills:`.
skills_gate_reserved_name_misuse() {
    local ws="$1" rel name
    while IFS= read -r rel; do
        [ -n "$rel" ] || continue
        name="$(skills_gate_skill_name "$rel")"
        case "$name" in
            "$SKILLS_GATE_BINDING_PREFIX"*) ;;
            *) continue ;;
        esac
        skills_gate_skill_is_binding "$ws" "$rel" && continue
        printf '%s\n' "$rel"
    done < <(skills_gate_skill_files "$ws")
}

# Состав исполнителей — той же полосой, что и скилы: индекс git плюс ещё не
# закоммиченный, но не игнорируемый файл. Агент заводится и проверяется в один
# день, иначе перечень и дерево сходятся лишь назавтра после коммита.
skills_gate_agent_files() {
    local ws="$1"
    git -C "$ws" -c core.quotepath=false ls-files --cached --others --exclude-standard \
        '.claude/agents/*.md' | sort -u
}

# Из фрагмента вида "`security.md` §Hardening п.1 | ещё текст" достаёт токен
# раздела. Ссылка живёт в свободной прозе и закрывающего разделителя не имеет,
# поэтому режем по тем, что встречаются: `|` (ячейка таблицы), `. ` (конец
# предложения), ` — ` (тире), `»`. Хвост «п.N» — указатель ВНУТРИ раздела, не
# часть имени, и снимается.
skills_gate_section_token() {
    printf '%s' "$1" \
        | sed -E 's/.*§//' \
        | sed -E 's/\|.*$//; s/\. .*$//; s/ — .*$//; s/».*$//' \
        | sed -E 's/[[:space:]]*п\.[0-9]+([[:space:]]*,[[:space:]]*п\.[0-9]+)*[[:space:]]*$//' \
        | sed -E 's/[[:space:]]+$//'
}

# Резолвится ли токен в какой-нибудь заголовок файла нормы.
#
# Два послабления, каждое — против ложного ОТРИЦАНИЯ, оба намеренные:
#  (1) пробелы снимаются С ОБЕИХ сторон: иначе «§Concurrency/lifecycle» не находит
#      заголовок «## Concurrency / lifecycle / читаемость» — расхождение на
#      форматировании, а не на существе (`measurement-discipline` §Предикат);
#  (2) резолвится ЛЮБОЙ непустой ПРЕФИКС токена по словам: у ссылки в прозе нет
#      закрывающего разделителя («§Within-service требуют атомарности»), и без
#      этого гейт краснел бы на корректных ссылках.
# Цена (2) — предикат слабее: он доказывает, что раздел с таким началом имени в
# файле ЕСТЬ, а не что назван именно он. Отрицательный контроль обязателен и
# лежит рядом (`inject.sh`): выдуманное имя не резолвится ни одним префиксом.
skills_gate_section_resolves() {
    local rulefile="$1" token="$2" needle headers
    headers="$(grep -E '^#{2,3} ' "$rulefile" | sed -E 's/^#+[[:space:]]*//' | tr -d '[:space:]')"
    while [ -n "$token" ]; do
        needle="$(printf '%s' "$token" | tr -d '[:space:]')"
        if [ -n "$needle" ] && printf '%s\n' "$headers" | grep -qF -- "$needle"; then
            return 0
        fi
        # отбросить последнее слово и повторить
        case "$token" in
            *\ *) token="${token% *}" ;;
            *)    return 1 ;;
        esac
    done
    return 1
}

# ── Ствол дерева ПРОДУКТА: один резолв на оба набора ─────────────────────────
#
# Дерево продукта — ЧУЖОЕ: оно лежит рядом клоном, и парковку этого клона никто
# не объявляет. Судить его по индексу рабочей копии (`ls-files`) значит выносить
# вердикт о том, на чём копия стоит СЕЙЧАС: припаркованная на чужой релизной
# линии, она объявляет несуществующим то, что на стволе есть. Цена измерена
# (ws#621): гейт 06 назвал объявление «сайтов 8» разошедшимся с деревом, где их 7,
# — на стволе восьмой сайт есть, вердикт был ложен о продукте, а отправку любой
# ветки воркспейса он остановил.
#
# Резолв ОДИН и живёт в `scripts/docs-gate/_lib.py` — там же, откуда его читают все
# четыре проверки `docs-gate`; сюда он приходит РЕЖИМОМ CLI того же файла. Копия
# здесь была бы вторым кодеком об одном предмете: два кодека расходятся молча и
# расходятся там, где это не видно, — пока копия продукта стоит на стволе,
# различие полос ненаблюдаемо, а обнаруживается ровно тогда, когда её парконули.
#
# Читать `docs-gate` из `skills-gate` — намеренно: предмет у файла один (ствол
# ЧУЖОГО дерева), и переносить его в третье место значило бы заводить дом ради
# симметрии каталогов, а не ради предмета.
#
# Печатает `ключ<TAB>значение`; читается циклом, а НЕ через `eval`: значение несёт
# имя ссылки из чужого дерева, и подстановка чужого имени в исполняемый текст —
# тот самый класс, который эти же гейты ловят.
#
# Выставляет TRUNK_REF · TRUNK_REV_SHORT · TRUNK_LAG — их читает ВЫЗЫВАЮЩИЙ
# (`check-06`: полоса в переписи, ссылка в находке, причина в тексте VOID).
# Возвращает 0, когда ствол разрешён, и 1, когда нет: «не по чему судить» — ТРЕТЬЯ
# КАТЕГОРИЯ, и читатель обязан ответить VOID своим текстом, а не откатиться на
# индекс молча.
#
# SC2034 глушится НАРОЧНО и узко — на одной функции, а не пофайлово: linter
# разбирает `_lib.sh` в одиночку и читателя этих переменных не видит by
# construction (он в другом файле). Проверять их живость приходится предикатом, а
# не линтером: `grep -n 'TRUNK_' scripts/skills-gate/check-06-*.sh` обязан быть
# непуст. Четвёртая переменная (перечень кандидатов) здесь жила и была снята
# именно этим предикатом — её не читал никто, а её причина уже входит в TRUNK_LAG.
# shellcheck disable=SC2034
skills_gate_product_trunk() {
    local mono="$1" resolver key value
    resolver="$(cd "$(dirname "${BASH_SOURCE[0]}")/../docs-gate" && pwd)/_lib.py"
    TRUNK_REF=""; TRUNK_REV_SHORT=""; TRUNK_LAG=""
    [ -x "$resolver" ] || {
        TRUNK_LAG="резолв ствола не найден: $resolver"
        return 1
    }
    # Код возврата берётся у САМОГО резолва, а не у последнего звена трубы: после
    # `|` он принадлежит читающей стороне и о стволе не говорит ничего.
    local out
    out="$(python3 "$resolver" "$mono" 2>/dev/null)" || true
    while IFS=$'\t' read -r key value; do
        case "$key" in
            ref)        TRUNK_REF="$value" ;;
            rev_short)  TRUNK_REV_SHORT="$value" ;;
            lag)        TRUNK_LAG="$value" ;;
        esac
    done <<<"$out"
    [ -n "$TRUNK_REF" ]
}

# Состав дерева продукта НА СТВОЛЕ. Ствол не разрешён — пусто, а не индекс:
# молчаливый откат на индекс и есть дефект, ради которого полоса выровнена.
skills_gate_product_files() {
    local mono="$1" ref="$2"
    [ -n "$ref" ] || return 0
    git -C "$mono" ls-tree -r --name-only "$ref" 2>/dev/null
}

# Содержимое файла дерева продукта НА СТВОЛЕ. Диск не читается: он отвечает о
# том, на чём копия стоит сейчас, а припаркованная копия файла может не нести.
skills_gate_product_show() {
    local mono="$1" ref="$2" rel="$3"
    [ -n "$ref" ] || return 1
    git -C "$mono" show "$ref:$rel" 2>/dev/null
}
