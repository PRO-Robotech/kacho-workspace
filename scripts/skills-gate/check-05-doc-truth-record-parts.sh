#!/usr/bin/env bash
# skills-gate #05 — запись каталога `doc-truthfulness` несёт ВСЕ четыре части.
#
# ЧТО УТВЕРЖДАЕТ. Каждая предметная запись `doc-truthfulness` (заголовок вида
# `### <N>.<M>.` внутри разделов `## §2.`..`## §7.`) несёт: имя (сам заголовок) ·
# **Признак** · **Противоядие** · строку `> **Держится:**` · строку
# `> **Наблюдалось:**`. Плюс объявленное скилом число записей сверяется с тем,
# что гейт осмотрел.
#
# ПОЧЕМУ. Скил объявляет эти четыре части обязательными в собственном §11.2, и
# предмет у него — ровно утверждения, которые переживают свой предмет. Каталог без
# части «Держится» через полгода неотличим от закрытого; каталог без части
# «Наблюдалось» смешивает наблюдение с догадкой, а объявленное число, не связанное
# с осмотренным множеством, — это его же §4.3 («сверяет мощность, а не состав»),
# применённый к самому себе. Соседи стоят на том же: `check-02` держит семь частей
# у `code-authoring`, `check-04` — три у `security-surface`.
#
# ПРЕДПОСЫЛКА ГЕЙТА (проверяется здесь же). Запрет опирается на факт о дереве:
# предметные разделы объявлены как `## §2.`..`## §7.`, записи — как `### N.M.`.
# Сменится форма объявления — запрет станет ложью, поэтому «нашёл 0 записей» —
# отдельный исход (VOID), а не успех. По той же причине отдельно проверяется, что
# найдена и открывающая, и закрывающая граница каталога: без закрывающей гейт
# читал бы весь остаток файла, где `### N.M.` тоже встречаются, и молча менял бы
# собственный предмет.
#
# ЧЕГО ГЕЙТ НЕ ДЕЛАЕТ. Он не судит, верен ли класс, работает ли названный
# держатель и не устарело ли «Наблюдалось». Истинность прозы машинного предиката
# не имеет — это сказано в самом скиле (§12.3), и гейт, притворяющийся, что судит
# содержание, был бы экземпляром его же §8.2.
#
# Коды выхода: 0 — осмотрено N, неполных 0; 1 — неполные записи или расхождение
# объявленного числа; 2 — VOID (проверять нечего).

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=_lib.sh
source "$SCRIPT_DIR/_lib.sh"

WS="$(skills_gate_workspace_root)"
NAME="05-doc-truth-record-parts"
TARGET=".claude/skills/doc-truthfulness/SKILL.md"
F="$WS/$TARGET"

if [ ! -f "$F" ]; then
    skills_gate_void "$NAME" "$TARGET отсутствует — проверять нечего"
    exit 2
fi

# Границы каталога классов: от «## §2.» до «## §8.».
start="$(grep -n '^## §2\.' "$F" | head -1 | cut -d: -f1 || true)"
stop="$(grep -n '^## §8\.' "$F" | head -1 | cut -d: -f1 || true)"
if [ -z "${start:-}" ] || [ -z "${stop:-}" ]; then
    skills_gate_void "$NAME" "не нашёл границы §2..§8 — форма объявления разделов сменилась, запрет больше не опирается на факт"
    exit 2
fi
if [ "$stop" -le "$start" ]; then
    skills_gate_void "$NAME" "границы каталога классов не разобраны (§8 не ниже §2) — гейт без предмета"
    exit 2
fi

body="$(sed -n "${start},$((stop - 1))p" "$F")"

records=0
incomplete=0
sections=0
report=""
declare -A missing_count=()

check_record() {
    local head="$1" text="$2" miss=()
    [ -n "$head" ] || return 0
    records=$((records + 1))
    # `Признак-А`/`Признак-Б` — законная форма записи с двумя признаками, поэтому
    # префикс, а не точное слово (`gate-authoring` §Законный близнец).
    grep -q '^\*\*Признак'          <<<"$text" || miss+=("признак")
    grep -q '^\*\*Противоядие'      <<<"$text" || miss+=("противоядие")
    grep -q '^> \*\*Держится:\*\*'  <<<"$text" || miss+=("держится")
    grep -q '^> \*\*Наблюдалось'    <<<"$text" || miss+=("наблюдалось")

    if [ ${#miss[@]} -gt 0 ]; then
        incomplete=$((incomplete + 1))
        report+="  ${head}"$'\n'"      нет: $(IFS=', '; echo "${miss[*]}")"$'\n'
        for m in "${miss[@]}"; do
            missing_count["$m"]=$(( ${missing_count["$m"]:-0} + 1 ))
        done
    fi
}

current=""
buf=""
while IFS= read -r line; do
    case "$line" in
        '## §'[0-9]*) sections=$((sections + 1)); buf+="$line"$'\n' ;;
        '### '[0-9]*)
            check_record "$current" "$buf"
            current="$line"; buf=""
            ;;
        *) buf+="$line"$'\n' ;;
    esac
done <<<"$body"
check_record "$current" "$buf"

if [ "$records" -eq 0 ]; then
    skills_gate_void "$NAME" "в каталоге классов не нашлось ни одной записи «### N.M.» — форма сменилась, гейт без предмета"
    exit 2
fi

# Перепись отдельным утверждением: «неполных 0» обязано быть отличимо от
# «прочитано 0» (`measurement-discipline` §Форма числа).
echo "перепись: разделов — $sections; осмотрено записей — $records; полных — $((records - incomplete)); неполных — $incomplete"

# Счёт и проверка полноты читают ОДНО множество, иначе разойдутся by construction —
# это §4.3 самого скила, применённый к нему же.
declared="$(grep -oE '^\*\*Записей класса — ([0-9]+)\*\*' "$F" | head -1 | grep -oE '[0-9]+' || true)"
if [ -z "${declared:-}" ]; then
    skills_gate_fail "$NAME" "скил не объявляет число записей строкой «**Записей класса — N**» — счёт и проверка полноты не связаны ничем"
    exit 1
fi
if [ "$declared" -ne "$records" ]; then
    echo "  объявлено записей: $declared; гейт осмотрел: $records" >&2
    skills_gate_fail "$NAME" "объявленное число записей разошлось с деревом ($declared против $records)"
    exit 1
fi

if [ "$incomplete" -gt 0 ]; then
    printf '%s' "$report" >&2
    detail=""
    for m in "${!missing_count[@]}"; do detail+="$m:${missing_count[$m]} "; done
    skills_gate_fail "$NAME" "неполных записей $incomplete из $records (по частям: ${detail% })"
    exit 1
fi

skills_gate_pass "$NAME" "$sections разделов, все $records записей несут четыре части; объявленное число сходится"
exit 0
