#!/usr/bin/env bash
# skills-gate #03 — перечни канонической оснастки сходятся с деревом.
#
# ЧТО УТВЕРЖДАЕТ. Два перечня `.claude/rules/ai-tooling.md` — §Канонические
# скилы и §Канонические агенты — побайтово совпадают с множествами
# **отслеживаемых git** директорий `.claude/skills/*/` (за вычетом привязок
# правил, см. ниже) и файлов `.claude/agents/*.md`. Строка без файла и файл без
# строки — обе находки, и обе печатаются отдельно.
#
# ПОЧЕМУ. Перечень — утверждение о дереве, а утверждение о дереве устаревает
# молча. Заведённый скил (агент) не попадает в перечень — его никто не найдёт;
# снятый остаётся просроченным объявлением. Оба состояния уже наблюдались, и
# перечень агентов до 2026-09-07 не держало НИЧТО: семнадцатый агент
# (`wave-reviewer`) сел в дерево, а перечень остался на шестнадцати вместе с
# числом при предикате — при зелёном прогоне всех четырёх наборов.
#
# ПОЧЕМУ ОБА ПЕРЕЧНЯ ЗДЕСЬ, А НЕ В РАЗНЫХ ПРОВЕРКАХ. Предмет один — «объявленный
# состав оснастки равен дереву», — и механизм разбора один. Две проверки об одном
# предмете разошлись бы формой разбора ровно так же, как расходятся два перечня.
#
# ЧТО В СЧЁТ НЕ ИДЁТ И ПОЧЕМУ. `<svc>-load-testing` живёт в репозитории сервиса —
# строка отбрасывается по имени. Domain-агенты (`vpc-*`, `compute-*`) объявлены
# строками вида «- домен vpc: …» и под разбор не подпадают **by construction**:
# имя в них не стоит сразу за дефисом. Это не послабление, а форма записи, и
# рядом стоит проба, требующая от неё молчания.
#
# ПРИВЯЗКИ ПРАВИЛ СКИЛАМИ НЕ СЧИТАЮТСЯ — И ЭТО ОБЪЯВЛЕНО ЗДЕСЬ, А НЕ ПОДРАЗУМЕВАЕТСЯ.
# Каталог `.claude/skills/rule-<имя>/`, чей `SKILL.md` — символьная ссылка в
# `.claude/rules/`, есть АДРЕС правила для предзагрузки (решение владельца
# 2026-09-17), а не экспертиза: своего содержимого у него нет ни байта, и в
# перечне §Канонические скилы ему делать нечего. Без этого исключения перечень 14
# сверялся бы с деревом 44 и гейт краснел бы тридцатью находками на верном дереве.
# Предикат — «SKILL.md является символьной ссылкой» (`_lib.sh` §ПРИВЯЗКА ПРАВИЛА),
# а не имя каталога: имя подделывается одним `mkdir`, и исключение по имени было
# бы дырой, через которую экспертиза выпадает из перечня молча.
#
# ОБРАТНАЯ СТОРОНА ИСКЛЮЧЕНИЯ — СВОЯ ОСЬ. Каталог под зарезервированным именем
# `rule-*`, чей `SKILL.md` НЕ ссылка, — находка, а не третья категория: имя занято
# привязкой, такую экспертизу никто не перечислит во `skills:` агента, и доехать
# до агента ей нечем. Перечень привязок печатается в переписи отдельным числом:
# «скилов 14» без него неотличимо от «тридцать штук молча выпали».
#
# ПРЕДПОСЫЛКА ГЕЙТА (проверяется здесь же). Запрет опирается на форму перечня:
# имена объявлены как `- \`<имя>\` …`. Сменится форма — гейт останется без
# предмета, поэтому «нашёл 0 имён» — отдельный исход (VOID), а не успех. То же
# для пустого индекса git.
#
# Коды выхода: 0 — оба множества совпали; 1 — расхождение; 2 — VOID.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=_lib.sh
source "$SCRIPT_DIR/_lib.sh"

WS="$(skills_gate_workspace_root)"
NAME="03-roster-matches-tree"
RULE="$WS/.claude/rules/ai-tooling.md"

[ -f "$RULE" ] || { skills_gate_void "$NAME" "нет $RULE"; exit 2; }

# roster <заголовок раздела> — имена, объявленные строками «- `имя` …».
# Тело — от заголовка до следующего «## »/«### ».
roster() {
    awk -v head="$1" '
        index($0, head) == 1 {inside=1; next}
        inside && /^#{2,3} /{exit}
        inside {print}
    ' "$RULE" | sed -nE 's/^- `([a-z0-9<>/-]+)`.*/\1/p' | sort -u \
        | grep -v '^<svc>' || true
}

skills_roster="$(roster '## Канонические скилы')"
agents_roster="$(roster '## Канонические агенты')"

# Полоса чтения дерева — одна на весь набор (`_lib.sh`): индекс git плюс ещё не
# закоммиченный, но не игнорируемый файл. Скил и агент заводятся и проверяются в
# ОДИН день; иначе перечень и дерево сходились бы лишь назавтра после коммита, а
# до него гейт молчал бы — и молчание было бы неотличимо от чистоты.
skills_tree="$(skills_gate_expertise_files "$WS" | cut -d/ -f3 | sort -u)"
bindings="$(skills_gate_binding_files "$WS" | cut -d/ -f3 | sort -u)"
misuse="$(skills_gate_reserved_name_misuse "$WS")"
agents_tree="$(skills_gate_agent_files "$WS" \
                 | sed 's|.*/||; s|\.md$||' | sort -u)"

count() { printf '%s\n' "$1" | grep -c . || true; }

n_sr="$(count "$skills_roster")"; n_st="$(count "$skills_tree")"
n_ar="$(count "$agents_roster")"; n_at="$(count "$agents_tree")"
n_bind="$(count "$bindings")"

# VOID объявляется ДО переписи расхождений: пустой разбор дал бы «в дереве есть,
# в перечне нет» по каждому имени — то есть находку, произведённую собственной
# слепотой, а не деревом.
if [ "$n_sr" -eq 0 ] || [ "$n_ar" -eq 0 ]; then
    skills_gate_void "$NAME" \
        "разобрано имён: скилов $n_sr, агентов $n_ar — форма перечня сменилась, гейт без предмета"
    exit 2
fi
if [ "$n_st" -eq 0 ] || [ "$n_at" -eq 0 ]; then
    skills_gate_void "$NAME" \
        "в индексе git: скилов $n_st, агентов $n_at — проверять нечего"
    exit 2
fi

echo "перепись: имён в перечне — скилов $n_sr, агентов $n_ar; в дереве — скилов $n_st, агентов $n_at; привязок правил (не скилы, в счёт не идут) — $n_bind"

rc=0
compare() {   # compare <вид> <перечень> <дерево>
    local kind="$1" only_roster only_tree
    only_roster="$(comm -23 <(printf '%s\n' "$2") <(printf '%s\n' "$3"))"
    only_tree="$(comm -13 <(printf '%s\n' "$2") <(printf '%s\n' "$3"))"
    if [ -n "$only_roster" ]; then
        echo "  $kind: в перечне есть, в дереве нет (просроченное объявление):" >&2
        printf '    %s\n' $only_roster >&2
        rc=1
    fi
    if [ -n "$only_tree" ]; then
        echo "  $kind: в дереве есть, в перечне нет (его никто не найдёт):" >&2
        printf '    %s\n' $only_tree >&2
        rc=1
    fi
}

compare "скилы"  "$skills_roster" "$skills_tree"
compare "агенты" "$agents_roster" "$agents_tree"

# Зарезервированное имя, занятое НЕ привязкой. Печатается отдельной строкой, а не
# в общем расхождении: причина другая и лечится другим — не строкой в перечне, а
# переименованием каталога либо заведением ссылки.
if [ -n "$misuse" ]; then
    echo "  скилы: каталог под зарезервированным именем rule-*, чей SKILL.md НЕ символьная ссылка —" >&2
    echo "         имя занято привязкой правила, экспертизу под ним не перечислит во skills: ни один агент:" >&2
    printf '    %s\n' $misuse >&2
    rc=1
fi

if [ "$rc" -ne 0 ]; then
    skills_gate_fail "$NAME" "перечень разошёлся с деревом"
    exit 1
fi

skills_gate_pass "$NAME" "перечни и дерево совпали: скилов $n_st, агентов $n_at; привязок правил вне счёта $n_bind"
exit 0
