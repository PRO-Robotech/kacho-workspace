#!/usr/bin/env bash
# shellcheck disable=SC2016
#   Вносимые и разыскиваемые строки — markdown таблицы закреплений: бэктики в них
#   разметка ревизии, а `**` — выделение числа, не подстановка. Одинарные кавычки
#   здесь намеренны на весь файл, как и в соседнем `inject.sh`. Директива стоит
#   пофайлово, а не построчно, ровно потому, что намерение общее у всех пяти
#   мест: подстановки не хотим НИГДЕ, и точечное глушение прятало бы это решение.
# Доказательство check-03 инъекцией — на ВРЕМЕННОЙ копии дерева воркспейса.
# Настоящий документ не трогается; дерево продукта читается только на чтение.
#
# У каждого запрета — настоящий вход из дерева, законный близнец той же формы, на
# котором гейт обязан МОЛЧАТЬ, и отдельная проба на ПРЕДПОСЫЛКУ: оставшись без
# документа, без таблицы или без дерева продукта, гейт обязан ответить VOID, а не
# успехом. Гейт, печатающий «сошлось» на пустом месте, тем зеленее, чем меньше
# видит (`gate-authoring` §Инъекция; `testing.md` §«Гейт на класс», п. 2-3).
#
# Отдельно проверяется СОДЕРЖАНИЕ вердикта, а не только код выхода: находка
# обязана называть ОБА числа — объявленное документом и полученное предикатом.
# Ошибка, ради которой гейт заведён, была ошибкой содержания при верном виде
# строки: клетка говорила «шесть», предикат отвечал «три», и оба числа выглядели
# одинаково правдоподобно.
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WS="$(cd "$HERE/../.." && pwd)"
CHECK="check-03-acceptance-tree-claims.py"
DOC="docs/specs/sub-phase-XC-7-iam-unified-contour-acceptance.md"

: "${KACHO_MONOREPO:?inject-03.sh требует KACHO_MONOREPO — предикаты закреплений меряются по дереву продукта}"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

seq_n=0
probes=0
failed=0

# Сколько проб файл ОБЯЗАН исполнить. Число объявлено здесь, чтобы «исполнено» и
# «написано» можно было сверить: харнесс, у которого ветка пропуска молча
# уменьшает знаменатель, отчитывается «провалов 0» тем увереннее, чем меньше он
# сделал. Заводишь пробу — правишь это число, иначе прогон объявит себя неполным.
DECLARED=12

# mksandbox — копия отслеживаемого дерева воркспейса тем же предикатом, что у
# самих проверок (`--cached --others --exclude-standard`).
mksandbox() {
    seq_n=$((seq_n + 1))
    local dir="$TMP/s$seq_n"
    mkdir -p "$dir"
    ( cd "$WS" && git ls-files --cached --others --exclude-standard -z ) \
        | ( cd "$WS" && xargs -0 tar cf - ) \
        | ( cd "$dir" && tar xf - )
    git -C "$dir" init -q
    git -C "$dir" add -A -f >/dev/null 2>&1
    printf '%s' "$dir"
}

# run <ожидаемый-код> <песочница> <монорепо> <имя-пробы> [обязательная-подстрока]
run() {
    local want="$1" box="$2" mono="$3" name="$4" need="${5:-}" got out
    probes=$((probes + 1))
    out="$(DOCS_GATE_ROOT="$box" KACHO_MONOREPO="$mono" "$HERE/$CHECK" 2>&1)"; got=$?
    if [ "$got" -ne "$want" ]; then
        echo "  ПРОВАЛ $name — ждали код $want, получили $got" >&2
        printf '%s\n' "${out//$'\n'/$'\n'         }" >&2
        failed=$((failed + 1))
        return
    fi
    if [ -n "$need" ] && [[ "$out" != *"$need"* ]]; then
        echo "  ПРОВАЛ $name — код $got верен, но в выводе нет «$need»" >&2
        printf '%s\n' "${out//$'\n'/$'\n'         }" >&2
        failed=$((failed + 1))
        return
    fi
    echo "  ok   $name (код $got)"
}

echo "== check-03: закреплённое число приёмки меряется по дереву продукта =="

# (1) Положительный контроль. Без него отрицания ниже зеленели бы на гейте,
# который краснеет всегда (`gate-authoring` §Отрицание только в паре с положительным).
b="$(mksandbox)"
run 0 "$b" "$KACHO_MONOREPO" "настоящий документ на настоящем дереве — сходится" \
    "" "все 16 закреплений сошлись"

# (2) Инъекция НАСТОЯЩИМ дефектом: то самое расхождение, ради которого гейт
# заведён, — «шесть» там, где предикат отвечает «три».
b="$(mksandbox)"
sed -i 's#^| \*\*Д7\*\* | обёрток вывода карты прав | `ccc6918ef` | \*\*3\*\* |#| **Д7** | обёрток вывода карты прав | `ccc6918ef` | **6** |#' "$b/$DOC"
grep -q '| \*\*Д7\*\* | обёрток вывода карты прав | `ccc6918ef` | \*\*6\*\* |' "$b/$DOC" \
    || { echo "  ПРОВАЛ подготовки (2): строка Д7 не подменилась" >&2; failed=$((failed + 1)); }
git -C "$b" add -A -f >/dev/null 2>&1
run 1 "$b" "$KACHO_MONOREPO" "число разошлось с деревом — краснеет и называет ОБА числа" \
    "документ объявляет **6**, предикат даёт **3**"

# (3) ЗАКОННЫЙ БЛИЗНЕЦ той же формы: строка правится, число остаётся верным.
# Без него гейт ловил бы «строку Д7 трогали», а не расхождение числа.
b="$(mksandbox)"
sed -i 's#^| \*\*Д7\*\* | обёрток вывода карты прав |#| **Д7** | обёрток вывода карты прав (переформулировано) |#' "$b/$DOC"
git -C "$b" add -A -f >/dev/null 2>&1
run 0 "$b" "$KACHO_MONOREPO" "близнец: текст строки другой, число верное — молчит"

# (4) Самоистечение вниз: строка закрепления исчезла из документа.
# Оставленный предикат укрыл бы следующее число, которое здесь заведут.
b="$(mksandbox)"
sed -i '/^| \*\*Д15\*\* /d' "$b/$DOC"
git -C "$b" add -A -f >/dev/null 2>&1
run 1 "$b" "$KACHO_MONOREPO" "закрепление исчезло из документа — находка, а не тишина" \
    "Д15 — предикат зарегистрирован, а строки закрепления в документе больше нет"

# (5) Самоистечение вверх: документ закрепил величину, которой никто не мерит.
b="$(mksandbox)"
sed -i 's#^| \*\*Д15\*\* |#| **Д99** | нечто, чего никто не мерит | `ccc6918ef` | **7** | выдуманный предикат |\n| **Д15** |#' "$b/$DOC"
git -C "$b" add -A -f >/dev/null 2>&1
run 1 "$b" "$KACHO_MONOREPO" "закреплено то, чего гейт не умеет мерить — находка" \
    "Д99 — документ закрепил"

# (6) Ревизия, которой в дереве продукта нет: замер на ней повторить нечем.
b="$(mksandbox)"
sed -i 's#^| \*\*Д15\*\* | экземпляров файла каталога прав (П14) | `ccc6918ef` |#| **Д15** | экземпляров файла каталога прав (П14) | `deadbee` |#' "$b/$DOC"
git -C "$b" add -A -f >/dev/null 2>&1
run 1 "$b" "$KACHO_MONOREPO" "ревизия не резолвится — находка, а не молчаливый пропуск" \
    "в дереве продукта не резолвится"

# (7) Предпосылка: таблицы закреплений в документе нет вовсе → VOID, не успех.
b="$(mksandbox)"
sed -i '/^| \*\*Д[0-9]\+\*\* /d' "$b/$DOC"
git -C "$b" add -A -f >/dev/null 2>&1
run 2 "$b" "$KACHO_MONOREPO" "таблицы закреплений нет — VOID, а не «сошлось»" \
    "нет ни одной строки закрепления"

# (8) Предпосылка: документа нет → VOID.
b="$(mksandbox)"
rm -f "$b/$DOC"
git -C "$b" add -A -f >/dev/null 2>&1
run 2 "$b" "$KACHO_MONOREPO" "документа нет — VOID, а не «сошлось»" "в индексе не найден"

# (9) Предпосылка: дерева продукта нет → VOID. Мерить не на чем, и это НЕ успех.
b="$(mksandbox)"
run 2 "$b" "$TMP/нет-такого-дерева" "монорепо недостижимо — VOID, а не «сошлось»" \
    "монорепо продукта не найдено"

# (10) Закрепление в-12 истекает в НУЖНУЮ сторону: рубеж снимут — предикат даст 0,
# и документ, продолжающий утверждать «жив», обязан покраснеть. Проверяется
# зеркально — правкой числа в документе на 0 при живом рубеже.
b="$(mksandbox)"
sed -i 's#^| \*\*Д16\*\* \(.*\)`ccc6918ef` | \*\*1\*\* |#| **Д16** \1`ccc6918ef` | **0** |#' "$b/$DOC"
git -C "$b" add -A -f >/dev/null 2>&1
run 1 "$b" "$KACHO_MONOREPO" "в-12: «рубежа нет» при живом рубеже — краснеет" \
    "документ объявляет **0**, предикат даёт **1**"

# (11) и (12) — ревизия РЕЗОЛВИТСЯ, но недостижима из `main` продукта.
#
# Вход проба ПРОИЗВОДИТ САМА, а не берёт из дерева: коммит, живущий только в чужой
# рабочей копии, — ровно то, чего в общем дереве завтра может не быть, и проба,
# опирающаяся на такой коммит, разделила бы судьбу дефекта, который ловит. Поэтому
# рядом заводится клон с общими объектами, база в нём пинится на ту же базу, что
# видит проверка, и поверх базы кладётся коммит С ТЕМ ЖЕ ДЕРЕВОМ (`commit-tree`):
# он резолвится, предком базы не является, а числа при нём — базовые, так что
# краснеть ему не от чего, кроме проверяемого свойства.
SIDE="$TMP/side"
BASE_SHA=""
for r in refs/remotes/origin/main refs/heads/main; do
    BASE_SHA="$(git -C "$KACHO_MONOREPO" rev-parse --verify --quiet "$r" || true)"
    [ -n "$BASE_SHA" ] && break
done

if [ -z "$BASE_SHA" ]; then
    echo "  ПРОПУСК (11)(12) — в дереве продукта нет ни origin/main, ни main: вход для пробы" >&2
    echo "  произвести НЕЧЕМ. Это не «ноль находок»: две пробы НЕ исполнены и в итог не входят" >&2
else
    git clone -q --shared --no-checkout "$KACHO_MONOREPO" "$SIDE" 2>/dev/null
    git -C "$SIDE" update-ref refs/remotes/origin/main "$BASE_SHA"
    # Подпись — В КОНФИГЕ ВЫБРОШЕННОГО КЛОНА, а не через `-c`/`GIT_AUTHOR_*`: правило
    # про подпись владельца связывает коммиты РЕПОЗИТОРИЯ, а этот клон живёт до конца
    # пробы и на origin не попадает НИКОГДА. Без подписи `commit-tree` отказывает
    # (`empty ident name`) везде, где нет глобального конфига, — то есть на ранере,
    # где `actions/checkout` подменяет HOME на временный. Локально проба при этом
    # зеленела: там подпись брали из ~/.gitconfig разработчика.
    git -C "$SIDE" config user.name  'docs-gate probe'
    git -C "$SIDE" config user.email 'probe@invalid'
    OFFSHOOT="$(git -C "$SIDE" commit-tree "$BASE_SHA^{tree}" -p "$BASE_SHA" -m 'проба: вершина, ушедшая в сторону от main' 2>/dev/null || true)"
    OFFSHOOT_SHORT="$(git -C "$SIDE" rev-parse --short=9 "$OFFSHOOT" 2>/dev/null || true)"
fi

# Вход проверяется НА НЕПУСТОТУ отдельно от подмены: пустая ревизия подставляется
# без ошибки, а `grep -q ""` истинен ВСЕГДА — то есть проверка подготовки ниже её
# бы не заметила и обе пробы (11)(12) судили бы о строке без ревизии вместо
# недостижимости. Ровно так это и наблюдалось на ранере.
if [ -n "$BASE_SHA" ] && [ -z "$OFFSHOOT_SHORT" ]; then
    echo "  ПРОПУСК (11)(12) — коммит в сторону не создан (нет подписи?): вход" >&2
    echo "  произвести НЕЧЕМ. Две пробы НЕ исполнены и в итог не входят" >&2
    BASE_SHA=""
fi

if [ -n "$BASE_SHA" ]; then

    b="$(mksandbox)"
    sed -i "s#^| \*\*Д15\*\* | экземпляров файла каталога прав (П14) | \`ccc6918ef\` |#| **Д15** | экземпляров файла каталога прав (П14) | \`$OFFSHOOT_SHORT\` |#" "$b/$DOC"
    { [ -n "$OFFSHOOT_SHORT" ] && grep -q "$OFFSHOOT_SHORT" "$b/$DOC"; } \
        || { echo "  ПРОВАЛ подготовки (11): ревизия Д15 не подменилась" >&2; failed=$((failed + 1)); }
    git -C "$b" add -A -f >/dev/null 2>&1
    run 1 "$b" "$SIDE" "ревизия резолвится, но недостижима из main — находка, а не тишина" \
        "НЕ достижима из refs/remotes/origin/main"

    # Законный близнец: ТА ЖЕ подмена строки, но на ревизию, достижимую из base.
    # Без него проба доказывала бы «строку Д15 трогали», а не недостижимость.
    b="$(mksandbox)"
    sed -i "s#^| \*\*Д15\*\* | экземпляров файла каталога прав (П14) | \`ccc6918ef\` |#| **Д15** | экземпляров файла каталога прав (П14) | \`$BASE_SHA\` |#" "$b/$DOC"
    git -C "$b" add -A -f >/dev/null 2>&1
    run 0 "$b" "$SIDE" "близнец: другая запись ревизии, но достижима — молчит" \
        "достижимость каждой ревизии проверена"
fi

echo
echo "inject-03: проб исполнено $probes, провалено $failed (проб в файле объявлено $DECLARED)"

# Три исхода, а не два. «Провалов 0» на непрогнанной пробе не утверждает НИЧЕГО,
# поэтому число исполненных сверяется с числом объявленных, а ноль исполненных —
# отказ, а не успех. Без этой сверки харнесс тем зеленее, чем меньше он сделал:
# любая ветка пропуска (нет дерева продукта, нет базы для входа) молча вычиталась
# бы из вердикта — тот самый класс, который проверяют сами пробы.
if [ "$probes" -eq 0 ]; then
    echo "[VOID] inject-03 — не исполнено НИ ОДНОЙ пробы: доказывать работоспособность нечем" >&2
    exit 2
fi
if [ "$probes" -lt "$DECLARED" ]; then
    echo "[VOID] inject-03 — исполнено $probes проб из $DECLARED: часть предпосылок в этой среде" >&2
    echo "       создать не удалось, и вердикт по ним не выносится" >&2
    exit 2
fi
if [ "$failed" -gt 0 ]; then
    echo "[FAIL] inject-03 — гейт не доказан: провалов $failed из $probes" >&2
    exit 1
fi
echo "[PASS] inject-03 — гейт доказан в обе стороны: проб $probes, провалов 0"
