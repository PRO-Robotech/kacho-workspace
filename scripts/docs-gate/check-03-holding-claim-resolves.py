import os
import re as _re
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import _lib  # noqa: E402

NAME = "check-03-holding-claim-resolves"

# Закрытый набор состояний. Расширять — только вместе с правилом, что новое
# состояние требует от строки: состояние без требования есть та же проза.
STATES = {
    "держится": "held",
    "наполовину": "half",
    "не начат": "none",
}

HOLDS_COL = re.compile(r"чем\s+держится", re.I)
STATE_COL = re.compile(r"состояние", re.I)
# Первая колонка таблицы состояния кейсов. Дискриминатор объявляет сам документ:
# без него под предмет попали бы таблица слоёв и таблица цены плана, где колонка
# «чем держится» законна и говорит о механизме, а не о кейсе.
CASE_COL = re.compile(r"^\s*(кейс|сценари)", re.I)
# Идентификатор кейса: XC-11-04, GEO-1-20, IAM-USR-BLK-NEG-PENDING не подходит
# (кейс нумерован), — предмет именно нумерованные кейсы приёмки.
CASE_ID = re.compile(r"([A-Z][A-Z0-9]*(?:-[A-Z0-9]+)*-\d+)")
# Сценарий объявляется строкой тела: **XC-11-04 — …**
SCENARIO = re.compile(r"^\s*\*\*([A-Z][A-Z0-9]*(?:-[A-Z0-9]+)*-\d+)\s*[—-]")
TICK = re.compile(r"`([^`]+)`")
PATHISH = re.compile(r"^[A-Za-z0-9_./-]+/[A-Za-z0-9_.-]+\.[a-z]+$")
# Координата с ДОМОМ: `owner/name:<путь>`. Двоеточие здесь то же, что у git в
# `<ревизия>:<путь>`, и спутать эти две формы нельзя: слева от двоеточия требуется
# `owner/name` со слэшем, которого у ревизии не бывает.
HOMED = re.compile(r"^(?P<home>[A-Za-z0-9][A-Za-z0-9_.-]*/[A-Za-z0-9][A-Za-z0-9_.-]*)"
                   r":(?P<path>.+)$")
CHECKISH = re.compile(r"^Test[A-Za-z0-9_]*$")
SCRIPTISH = (".sh", ".py")


def strip_cell(text):
    """Клетка без разметки: жирный, курсив, обратные кавычки, значки."""
    t = re.sub(r"[*_`✅❌⚠️·]+", " ", text)
    return re.sub(r"\s+", " ", t).strip()


def split_row(line):
    body = line.strip()
    if body.startswith(">"):
        body = body.lstrip(">").strip()
    if not body.startswith("|"):
        return None
    return [c.strip() for c in body.strip().strip("|").split("|")]


def tables(text):
    """Таблицы состояния документа: (номер строки заголовка, индексы колонок, строки)."""
    lines = text.split("\n")
    out = []
    i = 0
    while i < len(lines):
        cells = split_row(lines[i])
        if (not cells
                or not any(HOLDS_COL.search(c) for c in cells)
                or not CASE_COL.match(strip_cell(cells[0]))):
            i += 1
            continue
        holds = next(n for n, c in enumerate(cells) if HOLDS_COL.search(c))
        state = next((n for n, c in enumerate(cells) if STATE_COL.search(c)), None)
        rows, j = [], i + 1
        # Разделитель заголовка markdown пропускается, дальше — тело таблицы.
        while j < len(lines):
            r = split_row(lines[j])
            if not r:
                break
            if all(re.fullmatch(r":?-{2,}:?", c) for c in r if c):
                j += 1
                continue
            rows.append((j + 1, r))
            j += 1
        out.append({"line": i + 1, "holds": holds, "state": state, "rows": rows})
        i = j
    return out


def coordinates(cells):
    """Координаты строки: список `(дом|None, путь)` и имена проверок.

    Дом принадлежит КООРДИНАТЕ, а не строке: строка вправе назвать несколько
    путей, и дом на строку означал бы, что второй путь наследует дом первого
    молча. `None` — дом по умолчанию, дерево продукта.
    """
    paths, checks = [], []
    for c in cells:
        for tok in TICK.findall(c):
            tok = tok.strip()
            homed = HOMED.match(tok)
            if homed and PATHISH.match(homed.group("path")):
                paths.append((homed.group("home"), homed.group("path")))
            elif PATHISH.match(tok):
                paths.append((None, tok))
            elif CHECKISH.match(tok):
                checks.append(tok)
    return paths, checks


def shown(home, path):
    """Координата так, как её написал документ, — вместе с домом, если он назван."""
    return "%s:%s" % (home, path) if home else path


def home_slot(homes, root, product, product_ref, identity):
    """Дерево, в котором судится координата этого дома. Резолвится ОДИН раз.

    Слот несёт либо ствол и его состав, либо причину, по которой судить не по
    чему. Кеш здесь не оптимизация: без него один и тот же дом резолвился бы на
    каждой координате, а перепись печатала бы его столько же раз.
    """
    key = identity or ""
    if key in homes:
        return homes[key]
    if identity is None:
        slot = {
            "ok": True, "repo": product, "ref": product_ref,
            "index": _lib.trunk_files(product, product_ref),
            "where": "стволе продукта %s" % product_ref,
            "say": "дерево продукта, ствол %s" % product_ref,
            "coords": 0, "reason": None,
        }
        homes[key] = slot
        return slot
    path, reason = _lib.home_tree(root, identity, product)
    if path is None:
        slot = {"ok": False, "coords": 0, "reason": reason,
                "say": "НЕ РЕЗОЛВИТСЯ — %s" % reason}
        homes[key] = slot
        return slot
    ref = _lib.trunk(path)
    if not ref:
        # Та же полоса, что у дерева продукта: молчаливого отката на индекс копии
        # нет и здесь. Копия дома тоже общая, и её парковку никто не объявляет.
        reason = ("копия дома %s найдена (%s), но ствол %s в ней НЕ РЕЗОЛВИТСЯ — "
                  "судить не по чему. Условие создаётся так: git -C %s fetch origin main"
                  % (identity, path, _lib.TRUNK_REF, path))
        slot = {"ok": False, "coords": 0, "reason": reason,
                "say": "НЕ РЕЗОЛВИТСЯ — %s" % reason}
        homes[key] = slot
        return slot
    prov = _lib.provenance(path)
    slot = {
        "ok": True, "repo": path, "ref": ref,
        "index": _lib.trunk_files(path, ref),
        "where": "стволе дома %s %s" % (identity, ref),
        "say": _lib.provenance_line(path, prov),
        "coords": 0, "reason": None,
    }
    homes[key] = slot
    return slot


def declares(repo, ref, rel, name):
    """Объявлена ли функция `name` в файле `rel` НА СТВОЛЕ продукта.

    Содержимое берётся из объекта ссылки, а не с диска: файл рабочей копии
    принадлежит той ветке, на которую её переключили, и читать его значило бы
    выносить вердикт о чужом переключении. Без ствола сюда не доходят вовсе —
    проверка отвечает третьей категорией раньше (см. `main`).
    """
    body = _lib.trunk_show(repo, ref, rel)
    if body is None:
        return False
    return re.search(r"^func\s+%s\s*\(" % re.escape(name), body, re.M) is not None


def audit(root, repo, ref, homes, rel, findings, voids, stats):
    text = _lib.read(root, rel)
    tabs = tables(text)
    if not tabs:
        return False
    scenarios = set()
    for line in text.split("\n"):
        m = SCENARIO.match(line)
        if m:
            scenarios.add(m.group(1))
    listed = set()

    for tab in tabs:
        stats["tables"] += 1
        if tab["state"] is None:
            findings.append(
                "%s:%d — у таблицы состояния нет колонки состояния: «держится» и "
                "«держится наполовину» в ней неотличимы, и половина уезжает в зачёт "
                "целого" % (rel, tab["line"]))
            continue
        for lineno, cells in tab["rows"]:
            stats["rows"] += 1
            if len(cells) <= max(tab["holds"], tab["state"]):
                findings.append("%s:%d — в строке меньше клеток, чем колонок заголовка"
                                % (rel, lineno))
                continue
            cid = CASE_ID.search(strip_cell(cells[0]))
            if not cid:
                findings.append("%s:%d — первая клетка не называет кейса: %s"
                                % (rel, lineno, strip_cell(cells[0])[:60]))
                continue
            listed.add(cid.group(1))
            state = strip_cell(cells[tab["state"]]).lower()
            kind = next((v for k, v in STATES.items() if state.startswith(k)), None)
            if kind is None:
                findings.append(
                    "%s:%d — состояние «%s» вне закрытого набора (%s): свободная "
                    "формулировка возвращает прозу, которую таблица и заменяет"
                    % (rel, lineno, state[:40], " · ".join(sorted(STATES))))
                continue

            paths, checks = coordinates(cells)
            if any(home for home, _ in paths):
                stats["homed"] += 1
            if kind == "none":
                if paths:
                    findings.append(
                        "%s:%d — кейс %s объявлен не начатым и при этом называет "
                        "координату (%s): строка противоречит себе"
                        % (rel, lineno, cid.group(1),
                           ", ".join(shown(h, p) for h, p in paths)))
                continue

            if not paths:
                findings.append("%s:%d — кейс %s объявлен держащимся и не называет ни "
                                "одного файла" % (rel, lineno, cid.group(1)))
                continue
            # `alive` — тройки (слот дома, дом, путь): в одной строке пути бывают из
            # РАЗНЫХ деревьев, и находка обязана назвать то дерево, где искали.
            alive, blind = [], []
            for home, p in paths:
                slot = home_slot(homes, root, repo, ref, home)
                slot["coords"] += 1
                if not slot["ok"]:
                    # Третья категория: дом назван, судить не по чему. Это НЕ находка
                    # (документ мог быть верен) и НЕ проход (никто ничего не читал).
                    if home not in blind:
                        blind.append(home)
                    voids.append(
                        "%s:%d — кейс %s называет координату %s, и ДОМ её не "
                        "резолвится: %s. Вердикт по этой строке НЕ вынесен — это "
                        "«не выполнилось», и в проход оно не засчитывается"
                        % (rel, lineno, cid.group(1), shown(home, p), slot["reason"]))
                    continue
                stats["paths"] += 1
                if p in slot["index"]:
                    alive.append((slot, home, p))
                else:
                    findings.append(
                        "%s:%d — кейс %s ссылается на %s, которого в %s нет: "
                        "свидетельство не проверяемо"
                        % (rel, lineno, cid.group(1), p, slot["where"]))
            scripts = [p for _, _, p in alive if p.endswith(SCRIPTISH)]
            # Скрипт, названный в НЕрезолвнутом доме, форму «проверка названа»
            # удовлетворяет: не названа она документом, а не деревом. Иначе строка
            # получила бы находку о своей форме по причине, к форме не относящейся.
            blind_scripts = [p for h, p in paths
                             if h in blind and p.endswith(SCRIPTISH)]
            if not checks and not scripts and not blind_scripts:
                findings.append(
                    "%s:%d — кейс %s называет файл, но не называет ПРОВЕРКУ. Файл "
                    "переживает снятие теста, который в нём лежал, поэтому имя файла "
                    "свидетельством не является" % (rel, lineno, cid.group(1)))
            for name in checks:
                gofiles = [(slot, home, p) for slot, home, p in alive
                           if p.endswith(".go")]
                if any(declares(slot["repo"], slot["ref"], p, name)
                       for slot, _, p in gofiles):
                    stats["checks"] += 1
                    continue
                if blind:
                    voids.append(
                        "%s:%d — кейс %s называет проверку %s, и дом её координаты "
                        "(%s) не резолвится: искать имя НЕ В ЧЕМ. Вердикт по этому "
                        "имени НЕ вынесен"
                        % (rel, lineno, cid.group(1), name, ", ".join(blind)))
                    continue
                stats["checks"] += 1
                findings.append(
                    "%s:%d — кейс %s называет проверку %s, которой нет ни в одном из "
                    "названных им файлов (%s)"
                    % (rel, lineno, cid.group(1), name,
                       "; ".join("%s — искали в %s" % (shown(home, p), slot["where"])
                                 for slot, home, p in gofiles)
                       if gofiles else "файлов .go не названо"))

    if scenarios:
        for cid in sorted(scenarios - listed):
            findings.append(
                "%s — кейс %s объявлен сценарием и не имеет строки в таблице состояния: "
                "из счёта он уходит молча" % (rel, cid))
        for cid in sorted(listed - scenarios):
            findings.append(
                "%s — кейс %s стоит в таблице состояния, а сценария с таким "
                "идентификатором в документе нет" % (rel, cid))
    return True



# Координата-файл в инлайн-коде. Верхняя оценка НЕВИДИМОГО: считает всё, что
# похоже на путь к файлу, — включая координаты, законно названные мёртвыми
# (см. три вида в шапке). Число нужно не как вердикт, а чтобы «находок ноль»
# было отличимо от «прочитано ноль»: предмет проверки — 69 строк таблиц, а
# рядом лежат тысячи координат, которых не судит никто.
_PROSE_COORD = _re.compile(
    r"`([A-Za-z0-9_.-]+(?:/[A-Za-z0-9_.@-]+)+"
    r"\.(?:go|py|sh|sql|proto|ts|tsx|yaml|yml|md|json))")


def prose_scale(root, docs):
    """Сколько координат приёмок лежит ВНЕ предмета: (вхождений, приёмок)."""
    total = 0
    carriers = 0
    for rel in docs:
        try:
            with open(os.path.join(root, rel), encoding="utf-8",
                      errors="replace") as fh:
                n = len(_PROSE_COORD.findall(fh.read()))
        except OSError:
            continue
        total += n
        if n:
            carriers += 1
    return total, carriers

def main():
    root = _lib.workspace_root()
    repo = _lib.monorepo(root)
    if repo is None:
        _lib.void(NAME, "дерево продукта не найдено (ни KACHO_MONOREPO, ни "
                        "project/kacho) — координату проверить не по чему")
        return 2

    docs = _lib.tracked(root, "docs/specs/*-acceptance.md")
    if not docs:
        _lib.void(NAME, "отслеживаемых docs/specs/*-acceptance.md нет — читать нечего")
        return 2

    prov = _lib.provenance(repo)
    ref = prov["ref"]
    # СТВОЛ НЕ РАЗРЕШЁН — ЭТО ТРЕТЬЯ КАТЕГОРИЯ, А НЕ НАХОДКА И НЕ ЗЕЛЁНОЕ.
    #
    # Прежде здесь был МОЛЧАЛИВЫЙ ОТКАТ на индекс рабочей копии, и он давал два
    # разных ложных исхода, оба неотличимых от исправной работы:
    #   * копия припаркована в стороне → координата, живая на стволе, объявлялась
    #     несуществующей: НАХОДКА (код 1), которой в продукте нет, и отправка
    #     останавливалась работой, к которой отправляющий не причастен;
    #   * копия случайно стоит на стволе → код 0, то есть «проверено», хотя ствол
    #     не читался вовсе и вердикт был о чужом переключении.
    # Второй исход опаснее первого: он молчит. Замер обеих полос — ws#622.
    #
    # Поэтому: по чему судить, тем и судим, а если судить не по чему — говорим это
    # прямо. Код 2 отправку не останавливает и в успех НЕ засчитывается; условие
    # создаётся в дереве продукта (`git fetch`), а не послаблением здесь.
    if not ref:
        _lib.void(NAME, "ствол дерева продукта (%s) не резолвится в клоне %s — "
                        "координату проверить НЕ ПО ЧЕМУ. Индекс рабочей копии "
                        "отвечает о том, на что её переключили, и молчаливый откат "
                        "на него был бы вердиктом о чужой парковке. Условие "
                        "создаётся так: git -C %s fetch origin main"
                  % (_lib.TRUNK_REF, repo, repo))
        return 2
    findings = []
    voids = []
    # Дома резолвятся ОДИН раз на прогон. Ключ `""` — дом по умолчанию, дерево
    # продукта: он заводится здесь, чтобы перепись могла назвать его состав даже
    # тогда, когда ни одна строка координат не назвала.
    homes = {}
    stats = {"tables": 0, "rows": 0, "homed": 0, "paths": 0, "checks": 0}
    base = home_slot(homes, root, repo, ref, None)
    carriers = [rel for rel in docs
                if audit(root, repo, ref, homes, rel, findings, voids, stats)]

    _lib.census(
        "%s: приёмок осмотрено %d; несут таблицу состояния %d (%s); таблиц %d, "
        "строк %d, из них называют дом координаты %d"
        % (NAME, len(docs), len(carriers),
           ", ".join(carriers) if carriers else "ни одной",
           stats["tables"], stats["rows"], stats["homed"]))
    # Числа проверенного — СУММА ПО ВСЕМ ДОМАМ, и сказано это в самой строке: стоя
    # рядом с составом дерева продукта, «проверено 17» читалось бы как «в нём 17»,
    # тогда как часть из них проверена в другом дереве.
    _lib.census(
        "%s: дом по умолчанию — дерево продукта %s; путей в его стволе %d. Проверено "
        "ВСЕГО, по всем домам: путей %d, имён проверок %d"
        % (NAME, _lib.provenance_line(repo, prov), len(base["index"]),
           stats["paths"], stats["checks"]))
    # Дома, названные документами, печатаются ПОИМЁННО и вместе с исходом резолюции.
    # Без этой строки «дом назван» и «дом прочитан» были бы неотличимы, а перепись
    # обязана отличать ноль находок от нуля прочитанного.
    named = sorted(k for k in homes if k)
    if named:
        for identity in named:
            slot = homes[identity]
            _lib.census("%s: дом %s — %s; координат в нём названо %d"
                        % (NAME, identity, slot["say"], slot["coords"]))
    else:
        _lib.census("%s: домов документы не называют ни одного — все координаты "
                    "судятся в дереве продукта" % NAME)
    prose_n, prose_docs = prose_scale(root, docs)
    _lib.census(
        "%s: ВНЕ ПРЕДМЕТА — проза приёмок: координат-файлов в инлайн-коде %d "
        "в %d приёмках из %d (верхняя оценка). Их не судит ни эта проверка, ни "
        "хук свежести (docs/specs/*-acceptance.md выведены из LIVE_WS намеренно: "
        "приёмка — датированная запись). «Находок ноль» ниже относится ТОЛЬКО к "
        "таблицам состояния"
        % (NAME, prose_n, prose_docs, len(docs)))

    if not carriers:
        _lib.void(NAME, "ни одна приёмка не несёт таблицы состояния — предмет не найден; "
                        "это НЕ «находок ноль»")
        return 2

    # ТРЕТЬЯ КАТЕГОРИЯ ПЕЧАТАЕТСЯ ВСЕГДА И ПЕРВОЙ, но вердикта не решает: находка
    # ниже объявляется раньше. Обратный порядок сделал бы «дома нет» маской —
    # одной нерезолвнутой координаты хватило бы, чтобы настоящая находка перестала
    # блокировать отправку. Тот же порядок у `run-all.sh` и `hook-proofs.sh`.
    for v in voids:
        _lib.void(NAME, v)

    if findings:
        for f in findings:
            _lib.fail(NAME, f)
        _lib.fail(NAME, "претензий без проверяемой координаты: %d%s"
                        % (len(findings),
                           "; сверх них координат без резолвимого дома %d — вердикт "
                           "по ним НЕ вынесен (строки [VOID] выше)" % len(voids)
                           if voids else ""))
        return 1

    if voids:
        _lib.void(NAME, "координат, чей дом не резолвится: %d — проверить их НЕ ПО "
                        "ЧЕМУ, и это НЕ «находок ноль». Остальные проверены: путей %d, "
                        "имён проверок %d" % (len(voids), stats["paths"], stats["checks"]))
        return 2

    _lib.passed(NAME, "координата резолвится у всех %d строк в %d таблицах (домов "
                      "названо %d)" % (stats["rows"], stats["tables"], len(named)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
