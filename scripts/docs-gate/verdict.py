#!/usr/bin/env python3
"""Вердикт приёмки — ВХОД для читателя, а не второй распознаватель.

ЗАЧЕМ ЭТОТ ФАЙЛ. Распознаватель вердикта живёт в `_lib.py` и владеет предметом
один: у приёмок два дома, шапка пишется десятком законных написаний, и второе
объявление разошлось бы с первым молча. Но у него не было ВХОДА для человека и
для чужого дерева: ведомость приёмок продукта
(`PRO-Robotech/kacho:docs/acceptance-ledger.yaml`) объявляла рецептом
воспроизведения вердикта НОМЕР СТРОКИ — `sed -n 3p`, — и на записи NLB-4.0 он
давал врезку о суперсежении, тогда как состояние стоит девятнадцатой строкой.

Номер строки распознавателем не является: он верен ровно для тех шапок, на
которых его подобрали. Замер 2026-09-16 по 187 приёмкам воркспейса дал больше
десятка законных написаний объявления — с цитатой и без, с меткой по-русски и
по-английски, с двоеточием внутри выделения и снаружи, со значком и без.

ФОРМЫ ВЫЗОВА. Путь файла либо `-` для чтения из стандартного ввода:

    scripts/docs-gate/verdict.py docs/specs/<приёмка>.md
    git show <ревизия>:docs/specs/<приёмка>.md | scripts/docs-gate/verdict.py -

Печатает ОДНО слово вердикта и выходит нулём. Вердикта в шапке нет — печатает
строку-объявление, если она была, и выходит **кодом 3**: это «не выполнилось»,
а не «вердикта нет» и не находка. Код 2 — вход не прочитан.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from _lib import verdict  # noqa: E402


def main(argv):
    if len(argv) != 2:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    src = argv[1]
    try:
        text = sys.stdin.read() if src == "-" else open(src, encoding="utf-8").read()
    except OSError as exc:
        print(f"вход не прочитан: {exc}", file=sys.stderr)
        return 2

    got, line = verdict(text)
    if got is None:
        where = f"; строка-объявление: {line}" if line else "; объявления в шапке нет вовсе"
        print(f"вердикт не прочитан{where}", file=sys.stderr)
        return 3
    print(got)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
