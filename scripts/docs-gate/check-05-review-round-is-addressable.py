#!/usr/bin/env python3
"""check-05 — раздел, ОБЪЯВЛЯЮЩИЙ вердикт круга, называет РЕВИЗИЮ.

Что запрещает эта проверка. Приёмка несёт разделы «ход круга»: вердикт
рецензента, его замечания, ответ автора. Текст самой рецензии приходит
сообщением между сессиями и вместе с ними исчезает, поэтому утверждение
«рецензент сказал X» проверить нечем — ни тому, кто его написал, ни тому, кто
его читает через месяц. Наблюдалось на кругах 5–7 линии identity: спор о
принадлежности числа разрешился согласием сторон, а не замером, потому что
мерить было нечего (задача воркспейса #469).

ЧТО ЭТА ПРОВЕРКА ЗАКРЫВАЕТ, А ЧТО НЕТ — сказано прямо, иначе она обещает
больше, чем делает.

  • НЕ закрывает авторство. Автор вправе написать раздел за рецензента, и
    предикат этого не отличит. Тот же предел, что у `_lib.verdict`: она судит
    ОБЪЯВЛЕНИЕ, а не одобрение. Удостоверения авторства в публичном дереве не
    бывает by construction, и правило это признаёт (`git-issues.md`
    §«Круг ревью адресуем: чья речь и на какой ревизии»).
  • ЗАКРЫВАЕТ локализуемость. Вердикт, названный вместе с ревизией, делает
    каждое замечание круга ПЕРЕПРОГОНЯЕМЫМ: предикат замечания исполняется на
    том же дереве, и спор о содержании разрешается замером, а не памятью.
    Вердикт без ревизии сказан о дереве, которое нельзя найти.

ПРЕДМЕТ — ОБЪЯВЛЕНИЕ вердикта, а не упоминание слова. Признак объявления
структурный, а не словарный: токен вердикта помечен `✅`/`❌` либо стоит в
обратных кавычках. Разница несущая — заголовки вида «Критерии APPROVED», «Ранее
открытые вопросы, закрытые до APPROVED» и «производители, названные ПОСЛЕ
APPROVED» слово несут, а вердикта не объявляют; счёт по слову втянул бы их в
предмет и потребовал ревизии от разделов, у которых её и не должно быть
(`testing.md` §«Гейт на класс», п. 7 — распознаватель обязан знать формы, и п. 4
— читать существо, а не слово).

СЛЕПАЯ ЗОНА ОБЪЯВЛЯЕТСЯ ЧИСЛОМ, а не умолчанием. Заголовок круга, несущий
вердикт БЕЗ пометки («Круг 7 — CHANGES REQUESTED»), — форма законная и в предмет
не попадает; сколько таких заголовков в дереве, печатается переписью каждым
прогоном. Ноль находок обязано быть отличимо от нуля прочитанного.

ВЕДОМОСТЬ (`review-round-legacy.txt`) — точный перечень разделов, заведённых ДО
нормы, у которых ревизия не записана и восстановить её нечем. Она ИСТЕКАЕТ САМА
в обе стороны: запись, чей раздел ревизию уже называет, — находка; запись, чьего
раздела в дереве нет, — находка. Потолка у ведомости нет намеренно: потолок не
краснеет на сокращении долга и потому не истекает никогда (`testing.md`
§«Ведомость, записанная ШИРЕ предмета»).

Исходы: 0 — у каждого объявленного вердикта ревизия названа либо запись ведомости
имеет предмет; 1 — находки (каждая с координатой); 2 — читать нечего.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import _lib  # noqa: E402

NAME = "check-05-review-round-is-addressable"
LEDGER = "review-round-legacy.txt"

_HEADING = re.compile(r"^(#{2,6})\s+(.*)$")

# Заголовок называет КРУГ либо РЕВЬЮ своим предметом.
_ROUND = re.compile(r"(?:круг|раунд|round)\s*\d|§\s*R\.?\d?\b|ревью", re.I)

_VERDICT = r"APPROVED|CHANGES\s+REQUESTED|NOT\s+APPROVED"
# ОБЪЯВЛЕНИЕ вердикта: токен помечен ✅/❌ либо взят в обратные кавычки.
_DECLARED = re.compile(
    r"[✅❌]\s*`?\s*(?:" + _VERDICT + r")|`\s*[✅❌]?\s*(?:" + _VERDICT + r")\s*`"
)
_MENTIONED = re.compile(_VERDICT)

# Ревизия названа ОБЪЯВЛЕНИЕМ, а не случайной шестнадцатеричной строкой: в одной
# строке обязаны сойтись координата и слово, объявляющее её ревизией/деревом/
# веткой. Мягкая форма («любой hex где-нибудь в разделе») проверена на корпусе и
# даёт ТО ЖЕ множество — 11 из 11, — то есть строгость здесь ничего не стоит и
# закрывает случай, когда в разделе оказался хеш совсем другого предмета.
_HEX = re.compile(r"`[0-9a-f]{7,40}`|\b[0-9a-f]{9,40}\b")
_REV_WORD = re.compile(r"ревизи|revision|дерев|ветк|на\s+`[0-9a-f]{7,40}`|@\s*`?[0-9a-f]{7,40}", re.I)


def sections(text):
    """[(строка, заголовок, тело)] — тело до следующего заголовка ТОГО ЖЕ ИЛИ ВЫШЕ уровня.

    Уровень несущий, а не косметика: раздел круга объявляет ревизию собственным
    подразделом («14.0 Ревизии этого ревью»), и нарезка до ПЕРВОГО встречного
    заголовка отрезала бы ровно то, что проверяется. Первая редакция предиката
    так и делала и дала 7 находок вместо 4 — число, верное для другого предиката
    (`doc-truthfulness` §4.1).
    """
    lines = text.split("\n")
    heads = [(i, len(m.group(1))) for i, l in enumerate(lines)
             for m in [_HEADING.match(l)] if m]
    out = []
    for k, (i, lvl) in enumerate(heads):
        end = len(lines)
        for j, lvl2 in heads[k + 1:]:
            if lvl2 <= lvl:
                end = j
                break
        out.append((i + 1, _HEADING.match(lines[i]).group(2).strip(), lines[i:end]))
    return out


def names_revision(body):
    return any(_HEX.search(l) and _REV_WORD.search(l) for l in body)


def read_ledger(root):
    """{(путь, заголовок)} — записи ведомости; комментарии и пустые строки опускаются.

    Читается ОТ КОРНЯ ОБХОДА, а не от каталога скрипта: иначе инъекция не может
    подать гейту другую ведомость, и самоистечение остаётся недоказанным —
    проверка, у которой один вход нельзя изменить, по этому входу не проверена.
    """
    path = os.path.join(root, "scripts", "docs-gate", LEDGER)
    if not os.path.exists(path):
        return None
    entries = set()
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            if "::" not in line:
                continue
            rel, head = line.split("::", 1)
            entries.add((rel.strip(), head.strip()))
    return entries


def main():
    root = _lib.workspace_root()
    docs = _lib.tracked(root, "docs/specs/*-acceptance.md")
    if not docs:
        _lib.void(NAME, "отслеживаемых docs/specs/*-acceptance.md нет — читать нечего")
        return 2

    ledger = read_ledger(root)
    if ledger is None:
        _lib.void(NAME, "ведомости %s нет — предпосылка проверки не выполнена" % LEDGER)
        return 2

    declared, mentioned_only, missing, seen = [], 0, [], set()
    round_sections = 0
    for rel in docs:
        for line_no, head, body in sections(_lib.read(root, rel)):
            if not _ROUND.search(head):
                continue
            round_sections += 1
            if not _DECLARED.search(head):
                if _MENTIONED.search(head):
                    mentioned_only += 1
                continue
            declared.append((rel, line_no, head))
            seen.add((rel, head))
            if not names_revision(body):
                missing.append((rel, line_no, head))

    if not round_sections:
        _lib.void(NAME, "разделов круга в %d приёмках не найдено — обход пуст, "
                        "судить нечего" % len(docs))
        return 2

    exempt = [m for m in missing if (m[0], m[2]) in ledger]
    findings = [m for m in missing if (m[0], m[2]) not in ledger]
    # Самоистечение в обе стороны: запись, чей раздел ревизию уже называет, и
    # запись, чьего раздела в дереве нет, — обе находки, а не тишина.
    stale = sorted(e for e in ledger if e not in {(m[0], m[2]) for m in missing})

    _lib.census(
        "%s: приёмок прочитано %d; разделов круга %d; из них ОБЪЯВЛЯЮТ вердикт %d; "
        "называют ревизию %d; без ревизии %d (унаследованных по ведомости %d, находок %d)"
        % (NAME, len(docs), round_sections, len(declared),
           len(declared) - len(missing), len(missing), len(exempt), len(findings))
    )
    _lib.census(
        "%s: заголовков круга, УПОМИНАЮЩИХ вердикт без пометки ✅/❌ и без обратных "
        "кавычек, — %d; они вне предмета (пометка и есть признак объявления), и это "
        "объявленная слепая зона, а не ноль находок" % (NAME, mentioned_only)
    )
    _lib.census("%s: записей в ведомости %s — %d, из них с предметом %d"
                % (NAME, LEDGER, len(ledger), len(ledger) - len(stale)))

    rc = 0
    for rel, line_no, head in findings:
        _lib.fail(NAME, "%s:%d — вердикт круга объявлен, ревизия не названа: «%s». "
                        "Замечания этого круга неперепрогоняемы — назови дерево и "
                        "ревизию, на которых вердикт вынесен" % (rel, line_no, head))
        rc = 1
    for rel, head in stale:
        why = ("раздел ревизию уже называет" if (rel, head) in seen
               else "раздела с таким заголовком в дереве нет")
        _lib.fail(NAME, "%s — записи ведомости нечего исключать (%s): «%s». "
                        "Снимите запись" % (rel, why, head))
        rc = 1

    if rc:
        return 1
    _lib.passed(NAME, "объявленных вердиктов круга %d; ревизия названа у %d, "
                      "унаследованных без ревизии %d — у каждой запись ведомости с предметом"
                      % (len(declared), len(declared) - len(missing), len(exempt)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
