#!/usr/bin/env bash
# shellcheck disable=SC2016
#   Вносимые строки — markdown: обратные кавычки в них разметка ревизии, а не
#   подстановка команды. Одинарные кавычки здесь намеренны на весь файл, как и в
#   соседних inject.sh / inject-03.sh.
# Доказательство check-05 инъекцией — на ВРЕМЕННОЙ копии дерева. Рабочее дерево
# не трогается.
#
# ФОРМА ИНЪЕКЦИИ ВЫБРАНА ПО `testing.md` §«Гейт на класс», п. 2в: дефект вносится
# СНЯТИЕМ НОВОГО свойства у элемента, чьё СТАРОЕ на месте, — а не заведением
# лишнего элемента, который нарушает всё, что требуется от элементов вообще.
# Поэтому вход у пар отличается РОВНО одной строкой (объявление ревизии), а
# прогонов три, а не два:
#
#   контроль        — всё цело: молчат ОБА гейта (check-01 и check-05);
#   инъекция нового — снята строка ревизии: краснеет ТОЛЬКО check-05;
#   инъекция старого— сломан вердикт в шапке: краснеет ТОЛЬКО check-01.
#
# Третий прогон обязателен: без него молчание check-01 неотличимо от молчания
# мёртвого гейта, и «краснеет только новый» осталось бы недоказанным.
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WS="$(cd "$HERE/../.." && pwd)"
CHECK="check-05-review-round-is-addressable.py"
LEDGER="scripts/docs-gate/review-round-legacy.txt"
SPEC="docs/specs/sub-phase-injected-round-acceptance.md"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

sandbox_seq=0

# mksandbox [путь-который-выбросить] — печатает путь свежей песочницы.
# Состав берётся тем же предикатом, что и у самой проверки.
mksandbox() {
    local drop="${1:-}"
    sandbox_seq=$((sandbox_seq + 1))
    local dir="$TMP/s$sandbox_seq"
    mkdir -p "$dir"
    ( cd "$WS" && git ls-files --cached --others --exclude-standard -z ) \
        | ( cd "$WS" && xargs -0 tar cf - ) \
        | ( cd "$dir" && tar xf - )
    [ -n "$drop" ] && rm -rf "${dir:?}/$drop"
    git -C "$dir" init -q
    git -C "$dir" add -A -f >/dev/null 2>&1
    printf '%s' "$dir"
}

# Приёмка-носитель. Всё, кроме ОДНОЙ строки, одинаково во всех парах:
#   $1 — строка объявления вердикта в ШАПКЕ (предмет check-01, «старое» свойство);
#   $2 — строка объявления ревизии в разделе круга (предмет check-05, «новое»).
# Пустая строка означает «свойство снято».
mkspec() {
    local box="$1" header="$2" revline="$3"
    mkdir -p "$box/docs/specs"
    {
        printf '# Приёмка для инъекции check-05\n\n'
        printf '%s\n\n' "$header"
        printf '## §1 Обзор\n\nТело приёмки.\n\n'
        printf '## §7 Круг 2 — ревью `acceptance-reviewer`: ❌ CHANGES REQUESTED\n\n'
        printf 'Четыре блокирующих замечания, каждое со своим предикатом.\n\n'
        [ -n "$revline" ] && printf '%s\n\n' "$revline"
        printf '### 7.1 Замечание Б1\n\nПредикат замечания и его результат.\n'
    } > "$box/$SPEC"
    git -C "$box" add -A -f >/dev/null 2>&1
}

HDR='> **Статус:** ✅ APPROVED (`acceptance-reviewer`, проба)'
REV='Ревизия, на которой вынесен вердикт: воркспейс `9d0fadd23ee7`, продукт `da709bd5eb46`.'

probes=0
failed=0

# run <ожидаемый-код> <песочница> <имя-пробы> <скрипт> [обязательная-подстрока]
run() {
    local want="$1" box="$2" name="$3" script="$4" need="${5:-}" got out
    probes=$((probes + 1))
    out="$(DOCS_GATE_ROOT="$box" "$HERE/$script" 2>&1)"; got=$?
    if [ "$got" -ne "$want" ]; then
        echo "  ПРОВАЛ $name — ждали код $want, получили $got" >&2
        printf '%s\n' "${out//$'\n'/$'\n'         }" >&2
        failed=$((failed + 1))
        return
    fi
    if [ -n "$need" ] && [[ "$out" != *"$need"* ]]; then
        echo "  ПРОВАЛ $name — код $got верен, но в выводе нет «$need»" >&2
        printf '%s\n' "${out//$'\n'/$'\n'         }" >&2
        failed=$((failed + 1))
        return
    fi
    echo "  ok   $name (код $got)"
}

echo "== check-05: три прогона одной пары (п. 2в) =="

# 1. КОНТРОЛЬ — всё цело. Молчат оба гейта.
b="$(mksandbox)"; mkspec "$b" "$HDR" "$REV"
run 0 "$b" "контроль: вердикт круга объявлен и ревизия названа — check-05 молчит" "$CHECK"
run 0 "$b" "контроль: шапка объявляет вердикт — check-01 молчит" check-01-acceptance-verdict.py

# 2. ИНЪЕКЦИЯ НОВОГО — снята ровно строка ревизии. Краснеет только check-05.
b="$(mksandbox)"; mkspec "$b" "$HDR" ""
run 1 "$b" "инъекция нового: ревизия снята — check-05 краснеет" "$CHECK" \
    "вердикт круга объявлен, ревизия не названа"
run 0 "$b" "инъекция нового НЕ трогает чужой предмет — check-01 молчит" \
    check-01-acceptance-verdict.py

# 3. ИНЪЕКЦИЯ СТАРОГО — сломан вердикт шапки, ревизия на месте. Наоборот.
b="$(mksandbox)"; mkspec "$b" 'Здесь про APPROVED сказано прозой.' "$REV"
run 1 "$b" "инъекция старого: шапка без вердикта — check-01 краснеет" \
    check-01-acceptance-verdict.py
run 0 "$b" "инъекция старого НЕ ловится check-05 — он молчит" "$CHECK"

echo
echo "== check-05: находка называет КООРДИНАТУ и ЗАГОЛОВОК, а не только факт =="
b="$(mksandbox)"; mkspec "$b" "$HDR" ""
run 1 "$b" "находка называет путь приёмки" "$CHECK" "$SPEC"
b="$(mksandbox)"; mkspec "$b" "$HDR" ""
run 1 "$b" "находка называет заголовок раздела дословно" "$CHECK" \
    'Круг 2 — ревью `acceptance-reviewer`: ❌ CHANGES REQUESTED'

echo
echo "== check-05: законные близнецы — гейт обязан МОЛЧАТЬ =="

# Близнец 1 — заголовок круга УПОМИНАЕТ вердикт без пометки. Ревизии нет, и не
# должно быть: вердикта он не объявляет. Без этого близнеца гейт ловил бы слово,
# а не объявление, и потребовал бы ревизию от семи разделов корпуса, которые
# вердикта не выносят («Критерии APPROVED», «вопросы, закрытые до APPROVED»).
b="$(mksandbox)"
mkdir -p "$b/docs/specs"
{
    printf '# Приёмка с разделом, лишь упоминающим вердикт\n\n'
    printf '%s\n\n' "$HDR"
    printf '## §8 Критерии APPROVED — по чему ревьюер поймёт, что документ готов\n\n'
    printf 'Перечень критериев.\n\n'
    printf '## §9 Круг 5 — производители, названные ПОСЛЕ APPROVED\n\n'
    printf 'Разбор автора.\n'
} > "$b/$SPEC"
git -C "$b" add -A -f >/dev/null 2>&1
run 0 "$b" "близнец: круг УПОМИНАЕТ вердикт без пометки — молчит" "$CHECK"
run 0 "$b" "близнец: и он объявлен слепой зоной ЧИСЛОМ, а не умолчанием" "$CHECK" \
    "УПОМИНАЮЩИХ вердикт без пометки"

# Близнец 2 — координата в разделе есть, но она НЕ объявлена ревизией. Строгая
# форма предиката обязана считать это отсутствием: иначе хеш чужого предмета,
# попавший в раздел, засчитывался бы за ревизию круга.
b="$(mksandbox)"
mkspec "$b" "$HDR" 'Фикс посажен коммитом `a1b2c3d4e5f6`.'
run 1 "$b" "близнец: хеш БЕЗ объявления ревизией за ревизию не считается" "$CHECK" \
    "ревизия не названа"

echo
echo "== check-05: ведомость истекает САМА, в обе стороны =="

# А. Записи нечего исключать — раздел ревизию уже называет.
b="$(mksandbox)"; mkspec "$b" "$HDR" "$REV"
printf '%s::§7 Круг 2 — ревью `acceptance-reviewer`: ❌ CHANGES REQUESTED\n' "$SPEC" \
    >> "$b/$LEDGER"
git -C "$b" add -A -f >/dev/null 2>&1
run 1 "$b" "самоистечение А: раздел ревизию называет — запись ведомости краснеет" \
    "$CHECK" "нечего исключать"

# Б. Записи нечего исключать — раздела с таким заголовком в дереве нет.
b="$(mksandbox)"
printf 'docs/specs/sub-phase-nonexistent-acceptance.md::§1 Круг 1 — ✅ APPROVED\n' \
    >> "$b/$LEDGER"
git -C "$b" add -A -f >/dev/null 2>&1
run 1 "$b" "самоистечение Б: раздела нет — запись ведомости краснеет" \
    "$CHECK" "раздела с таким заголовком в дереве нет"

# В. Зеркало к А и Б: запись, у которой предмет ЕСТЬ, обязана молчать. Без неё
# «краснеет на любой записи» прошло бы обе пробы выше.
b="$(mksandbox)"; mkspec "$b" "$HDR" ""
printf '%s::§7 Круг 2 — ревью `acceptance-reviewer`: ❌ CHANGES REQUESTED\n' "$SPEC" \
    >> "$b/$LEDGER"
git -C "$b" add -A -f >/dev/null 2>&1
run 0 "$b" "зеркало: запись с живым предметом — молчит" "$CHECK" \
    "унаследованных без ревизии 5"

echo
echo "== check-05: предпосылки — VOID, а не успех =="

b="$(mksandbox docs/specs)"
run 2 "$b" "предпосылка: приёмок нет — VOID" "$CHECK" "читать нечего"

b="$(mksandbox)"; rm -f "$b/$LEDGER"
run 2 "$b" "предпосылка: ведомости нет — VOID" "$CHECK" "предпосылка проверки не выполнена"

# Обход пуст: приёмки есть, а разделов круга в них ни одного. «Ноль находок»
# обязано быть отличимо от «ноль прочитанного».
b="$(mksandbox docs/specs)"
mkdir -p "$b/docs/specs"
{
    printf '# Приёмка без единого раздела круга\n\n'
    printf '%s\n\n' "$HDR"
    printf '## §1 Обзор\n\nТело.\n'
} > "$b/$SPEC"
git -C "$b" add -A -f >/dev/null 2>&1
run 2 "$b" "предпосылка: разделов круга ноль — VOID, обход пуст" "$CHECK" "обход пуст"

echo
echo "== check-05: идеал НЕ превращён в поломку =="
# Пустая ведомость — это ЦЕЛЬ (весь долг закрыт), а не отказ. Гейт, падающий на
# достижении собственной цели, толкает держать запись ради зелёного
# (`testing.md` §«Проба не имеет права падать на ДОСТИЖЕНИИ СВОЕЙ ЦЕЛИ»).
b="$(mksandbox docs/specs)"; mkspec "$b" "$HDR" "$REV"
printf '# ведомость пуста — долг закрыт\n' > "$b/$LEDGER"
git -C "$b" add -A -f >/dev/null 2>&1
run 0 "$b" "пустая ведомость при закрытом долге — проходит, а не падает" "$CHECK" \
    "записей в ведомости"

echo
echo "inject-05: проб исполнено $probes, провалов $failed"
[ "$failed" -eq 0 ] || exit 1
# Знаменатель объявлен, чтобы «провалов 0» нельзя было получить пропуском проб:
# харнесс, у которого ветка пропуска молча уменьшает число прогонов, тем зеленее,
# чем меньше исполнил.
EXPECTED=18
[ "$probes" -eq "$EXPECTED" ] || {
    echo "inject-05: исполнено $probes проб, объявлено $EXPECTED — расхождение" >&2
    exit 1
}
exit 0
