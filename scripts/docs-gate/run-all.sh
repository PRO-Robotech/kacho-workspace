#!/usr/bin/env bash
# Прогон набора docs-gate. Вердикт стоит в КОДЕ ВЫХОДА, а не в печати.
#
# Три исхода, а не два: 0 — осмотрено N, находок 0; 1 — находки, каждая названа
# координатой; 2 — проверить не удалось (предпосылка не выполнена). Третий исход
# НЕ засчитывается за успех. Ровно это различие держало прогонщик снятого
# набора заморозки зелёным при нуле пройденных проверок: он
# считал пропуски в переменную, печатал её в итоговой строке и ни разу не читал
# в предикате выхода. Свойство теперь держится не обещанием, а поведенческой
# пробой — `scripts/tooling-gate/check-04-runner-void-is-not-pass.sh`.
#
# Число РАССМОТРЕННЫХ проверок печатается отдельной строкой: прогонщик,
# сообщающий «провалено 0» и не назвавший, сколько проверок он вообще
# рассмотрел, зеленеет сильнее всего именно тогда, когда каталог переехал и цикл
# не выполнился ни разу.
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

ok=0; bad=0; void=0; count=0
# Глоб намеренно шире `check-*.sh`: проверки набора — python (разбор markdown),
# а прогонщик обязан находить их по РОЛИ в имени, а не по расширению.
for c in "$SCRIPT_DIR"/check-*; do
    [ -f "$c" ] || continue
    [ -x "$c" ] || continue
    count=$((count + 1))
    "$c"
    case $? in
        0) ok=$((ok + 1)) ;;
        2) void=$((void + 1)) ;;
        *) bad=$((bad + 1)) ;;
    esac
done

if [ "$count" -gt 0 ]; then
    echo
    echo "docs-gate: рассмотрено проверок $count; пройдено $ok, провалено $bad, без предмета $void"
else
    echo "docs-gate: рассмотрено проверок 0 в $SCRIPT_DIR — предпосылка не резолвится, прогонять нечего" >&2
fi

# Вердикт стоит в предикате выхода, а не в печати выше.
[ "$count" -gt 0 ] && [ "$bad" -eq 0 ] && [ "$void" -eq 0 ]
