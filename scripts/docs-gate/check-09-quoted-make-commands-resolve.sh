#!/usr/bin/env bash
# check-09 — ЦИТАТА `make` В ДОКУМЕНТАХ ИСПОЛНИМА ИЗ КОРНЯ МОНОРЕПО (ws#816).
#
# Сам гейт — `scripts/check-doc-commands.py`, и он остаётся ЕДИНСТВЕННЫМ: этот
# файл — его место в наборе, а не вторая реализация. Адрес гейта процитирован
# по полному имени одобренными приёмками и записями ревью, чей вердикт привязан
# к отпечатку содержимого, поэтому гейт не переезжает, а входит в набор отсюда.
#
# ЗАЧЕМ МЕСТО В НАБОРЕ. Ветку до отправки судит хук `scripts/hooks/pre-push`, и
# перечень того, что он исполняет, выводится из дерева — `scripts/*/run-all.sh`.
# Гейт лежал в корне `scripts/`, ни в один набор не входил, и цитата неисполнимой
# команды доезжала до ветки волны: отказ случался только при ручном прогоне
# конвейера. Набор `docs-gate` судит то, что документы объявляют, — цитата
# команды и есть такое объявление. Рукописного списка в хуке не появляется: хук
# видит гейт тем же глобом, что и все наборы.
#
# ИСХОДЫ — гейта, без перевода: 0 — каждая цитата исполнима, объём прочитанного
# напечатан; 1 — находка, файл и строка названы; 2 — `[VOID]`: дерева продукта
# нет либо в нём нет ни одного Makefile — сверять не с чем (ws#463). Корень
# судимого дерева гейт берёт общим резолвером наборов (`scripts/lib/gate_root.py`
# через `scripts/docs-gate/_lib.py`): `DOCS_GATE_ROOT`, `GATE_ROOT`, расположение.
#
# Что хук действительно исполняет гейт и различает три его исхода, держит
# поведенческая проба `scripts/tooling-gate/check-17-push-hook-runs-the-quote-gate.sh`;
# что гейт способен упасть — `scripts/check-doc-commands-inject.sh`, которую
# доказательство набора зовёт частью `inject-09.sh`.
set -uo pipefail
SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
exec python3 "$SELF_DIR/../check-doc-commands.py"
