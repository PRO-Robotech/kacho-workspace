#!/usr/bin/env bash
# shellcheck disable=SC2016
#   Вносимые строки — markdown: бэктики в них разметка, а не подстановка команды.
#   Одинарные кавычки здесь намеренны на весь файл, как в соседних inject.sh и
#   inject-03.sh.
# Доказательство check-04 инъекцией — на ВРЕМЕННЫХ копиях.
# Настоящее дерево продукта читается ТОЛЬКО на чтение; дефекты вносятся в
# синтетическое монорепо, а не в него.
#
# У каждого запрета — настоящий вход, законный близнец той же формы, на котором
# гейт обязан МОЛЧАТЬ, и отдельная проба на ПРЕДПОСЫЛКУ: оставшись без дерева
# продукта или без приёмок в нём, гейт обязан ответить VOID, а не успехом
# (`gate-authoring` §Инъекция; `testing.md` §«Гейт на класс», п. 2-3).
#
# ПРОГОНОВ ТРИ, А НЕ ДВА (`testing.md` §«Гейт на класс», п. 2в). Инъекция обязана
# ронять ТОЛЬКО проверяемое. check-04 заведён рядом с check-01 и делит с ним
# распознаватель вердикта, поэтому доказывать надо три вещи: на целом дереве
# молчат ОБА; дефект второго дома роняет ТОЛЬКО check-04; дефект первого дома
# роняет ТОЛЬКО check-01. Без третьего прогона молчание соседа неотличимо от
# молчания мёртвого.
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WS="$(cd "$HERE/../.." && pwd)"
NEW="check-04-product-acceptance-verdict.py"
OLD="check-01-acceptance-verdict.py"

: "${KACHO_MONOREPO:?inject-04.sh требует KACHO_MONOREPO — второй дом приёмок живёт в дереве продукта}"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

probes=0
failed=0

# Сколько проб файл ОБЯЗАН исполнить. Число объявлено здесь, чтобы «исполнено» и
# «написано» можно было сверить: харнесс, у которого ветка пропуска молча
# уменьшает знаменатель, отчитывается «провалов 0» тем увереннее, чем меньше он
# сделал. Заводишь пробу — правишь это число, иначе прогон объявит себя неполным.
DECLARED=16

# mksandbox — копия отслеживаемого дерева ВОРКСПЕЙСА тем же предикатом, что у
# самих проверок. Нужна там, где в прогоне участвует check-01.
mksandbox() {
    local drop="${1:-}"
    local dir
    dir="$(mktemp -d -p "$TMP" w.XXXXXX)"
    ( cd "$WS" && git ls-files --cached --others --exclude-standard -z ) \
        | ( cd "$WS" && xargs -0 tar cf - ) \
        | ( cd "$dir" && tar xf - )
    [ -n "$drop" ] && rm -rf "${dir:?}/$drop"
    git -C "$dir" init -q
    git -C "$dir" add -A -f >/dev/null 2>&1
    printf '%s' "$dir"
}

# mkmono <относительный-путь> <содержимое> [ещё-путь ещё-содержимое …] —
# синтетическое дерево продукта. Ссылка origin/main заводится намеренно: гейт
# судит СТВОЛ продукта, и проба обязана исполнять тот же путь, а не запасной.
mkmono() {
    local dir
    dir="$(mktemp -d -p "$TMP" m.XXXXXX)"
    git -C "$dir" init -q
    while [ "$#" -ge 2 ]; do
        mkdir -p "$dir/$(dirname "$1")"
        printf '%s\n' "$2" > "$dir/$1"
        shift 2
    done
    git -C "$dir" add -A -f >/dev/null 2>&1
    git -C "$dir" -c user.email=probe@invalid -c user.name=probe \
        commit -qm 'синтетическое дерево продукта' >/dev/null 2>&1
    git -C "$dir" update-ref refs/remotes/origin/main HEAD
    printf '%s' "$dir"
}

# run <ожидаемый-код> <проверка> <песочница-воркспейса> <монорепо> <имя> [подстрока]
run() {
    local want="$1" check="$2" box="$3" mono="$4" name="$5" need="${6:-}" got out
    probes=$((probes + 1))
    out="$(DOCS_GATE_ROOT="$box" KACHO_MONOREPO="$mono" "$HERE/$check" 2>&1)"; got=$?
    if [ "$got" -ne "$want" ]; then
        echo "  ПРОВАЛ $name — ждали код $want, получили $got" >&2
        printf '%s\n' "${out//$'\n'/$'\n'         }" >&2
        failed=$((failed + 1))
        return
    fi
    if [ -n "$need" ] && [[ "$out" != *"$need"* ]]; then
        echo "  ПРОВАЛ $name — код $got верен, но в выводе нет «$need»" >&2
        printf '%s\n' "${out//$'\n'/$'\n'         }" >&2
        failed=$((failed + 1))
        return
    fi
    echo "  ok   $name (код $got)"
}

DOC="services/iam/docs/engineering/acceptance/probe-subject.md"
SPEC="docs/specs/sub-phase-injected-acceptance.md"

echo "== ПРОГОН 1: контроль — всё цело, молчат ОБА =="
b="$(mksandbox)"
run 0 "$OLD" "$b" "$KACHO_MONOREPO" "контроль: check-01 на целом дереве воркспейса — молчит"
# ОЖИДАЕМАЯ ПОДСТРОКА СМЕНЕНА — 2026-09-13. Прежде ось требовала, чтобы перепись
# назвала форму «приёмка в каталоге `acceptance/`»: на НАСТОЯЩЕМ дереве продукта
# такие приёмки были. Их больше нет — вынос службы (#2598) увёз все 30, — и
# требование стало ложным о дереве, а не о гейте. Ось при этом сохраняет свой
# предмет: контроль обязан молчать И называть ОБЪЁМ прочитанного, иначе «молчит»
# неотличимо от «не читал».
run 0 "$NEW" "$b" "$KACHO_MONOREPO" "контроль: check-04 на настоящем дереве продукта — молчит и называет объём" \
    'документов `.md` прочитано'

echo
echo "== ПРОГОН 2: инъекция НОВОГО — краснеет только check-04 =="
m="$(mkmono "$DOC" '# Приёмка без объявления вердикта

Здесь про APPROVED сказано прозой, объявления состояния нет.')"
b="$(mksandbox)"
run 1 "$NEW" "$b" "$m" "инъекция: приёмка продукта без строки состояния — краснеет и НАЗЫВАЕТ файл" \
    "$DOC"
run 0 "$OLD" "$b" "$m" "сосед цел: check-01 на том же прогоне — молчит"

echo
echo "== ПРОГОН 3: инъекция СТАРОГО — краснеет только check-01 =="
b="$(mksandbox)"
printf '# Приёмка воркспейса без объявления вердикта\n\nЗдесь про APPROVED сказано прозой.\n' > "$b/$SPEC"
git -C "$b" add -A -f >/dev/null 2>&1
run 1 "$OLD" "$b" "$KACHO_MONOREPO" "инъекция: приёмка воркспейса без состояния — краснеет" "$SPEC"
run 0 "$NEW" "$b" "$KACHO_MONOREPO" "новый цел: check-04 на том же прогоне — молчит"

echo
echo "== Законные близнецы: та же форма, состояние объявлено =="
# Близнец ровно той формы, из-за которой второй дом был невидим: маркер списка.
# Прежний распознаватель читал такую строку как «вердикта нет» — то есть ВСЕ
# приёмки продукта числились бы находками, а гейт ловил бы форму, а не существо.
b="$(mksandbox)"
m="$(mkmono "$DOC" '# Приёмка со списочным объявлением

- **Статус:** **✅ APPROVED** — круг 2, вердикт вынесен `acceptance-reviewer`')"
run 0 "$NEW" "$b" "$m" "близнец: списочное объявление читается — молчит" "APPROVED 1"

m="$(mkmono "$DOC" '# Приёмка с цитатным объявлением

> **Статус:** ✅ APPROVED (`acceptance-reviewer`, проба)')"
run 0 "$NEW" "$b" "$m" "близнец: цитатное объявление во втором доме тоже читается" "APPROVED 1"

echo
echo "== Содержание вердикта, а не только код выхода =="
# Порядок токенов несёт смысл: счёт по упоминанию слова закрыл бы эту строку как
# одобренную. Ошибка, ради которой оба гейта заведены, была ошибкой содержания
# при верном коде выхода.
m="$(mkmono "$DOC" '# Приёмка, ожидающая одобрения

- **Статус:** DRAFT v1 — awaiting `acceptance-reviewer` APPROVED')"
run 0 "$NEW" "$b" "$m" 'содержание: «DRAFT — awaiting APPROVED» отнесено к DRAFT' \
    "вердикты — DRAFT 1"

m="$(mkmono "$DOC" '# Приёмка с меткой без вердикта

- **Статус:** в работе, решение принимает владелец')"
run 1 "$NEW" "$b" "$m" "метка есть, значение вердиктом не читается — находка называет СТРОКУ" \
    "значение вердиктом не читается"

echo
echo "== Предикат меряет ВИД документа, а не каталог =="
# Вторая форма имени в дереве продукта обязана попадать в предмет: предикат,
# знающий одно имя, мерил бы каталог, и приёмка, названная по-другому, ушла бы
# из-под наблюдения молча.
m="$(mkmono "services/iam/docs/sub-phase-PROBE-1-acceptance.md" '# Приёмка вне каталога acceptance

- **Статус:** ✅ APPROVED (проба)')"
run 0 "$NEW" "$b" "$m" "вторая форма имени тоже в предмете — перепись называет её отдельно" \
    'имя `*-acceptance.md`: 1'

# Зеркало: файл без обоих признаков предметом НЕ является. Без него предикат,
# берущий любой .md, прошёл бы предыдущую пробу.
#
# ОЖИДАЕМЫЙ ИСХОД СМЕНЁН С VOID НА ПРОХОД — 2026-09-13, вместе с решением
# `check-04`. Предмета у проверки здесь нет, но дерево ПРОЧИТАНО: документ `.md`
# в нём есть, он просто не приёмка. «Условие не создано» и «предмета нет при
# созданном условии» — разные исходы; прежняя редакция сливала их в один и тем
# делала код 2 постоянным после выноса службы (приёмок второго дома в дереве
# продукта 0 против 30 на родителе #2598), то есть держала задание конвейера
# красным на факте. Свойство оси НЕ ослаблено: она по-прежнему требует, чтобы
# обычный документ сервиса в предмет НЕ попал, — это проверяется текстом ниже,
# а страж «смотрели не там» стоит отдельной осью следом.
m="$(mkmono "services/iam/docs/engineering/architecture/known-divergences.md" '# Не приёмка

- **Статус:** DRAFT')"
run 0 "$NEW" "$b" "$m" "зеркало: обычный документ сервиса предметом НЕ является — проход, обход УСТАНОВИЛ" \
    "приёмок второго дома в дереве продукта нет"

echo
echo "== Предпосылки: «нечего проверять» ≠ «находок ноль» =="
run 2 "$NEW" "$b" "$TMP/dereva-net" "предпосылка: дерева продукта нет — VOID, а не успех" \
    "дерево продукта не найдено"

m="$(mkmono "README.md" 'дерево продукта без единой приёмки')"
run 0 "$NEW" "$b" "$m" "приёмок нет, но документы прочитаны — проход, и число названо" \
    "документов прочитано 1"

# СТРАЖ ОТ «СМОТРЕЛИ НЕ ТАМ» — ОСЬ, БЕЗ КОТОРОЙ ПРЕДЫДУЩАЯ БЫЛА БЫ ВСЕРАЗРЕШЕНИЕМ.
# Дерево, в котором документов `.md` НЕТ ВОВСЕ, даёт третью категорию: пустой
# перечень приёмок там означает пустой обход, а не отсутствие предмета. Промах
# шаблонов и неразрешённый ствол выглядели бы ровно так же, поэтому различает их
# объём, и он печатается.
m="$(mkmono "go.mod" 'module probe')"
run 2 "$NEW" "$b" "$m" "страж: документов .md ноль — VOID, а не проход" \
    "не прочитано НИ ОДНОГО документа"

echo
echo "== Ствол не разрешён — ТРЕТЬЯ КАТЕГОРИЯ, а не молчаливый откат на индекс =="
# Здесь проба ждала КОДА 0: прежняя редакция судила тогда индекс копии, говоря это
# переписью. Довод «сказали прямо» не держит, и это переписано осознанно (ws#621):
# строку переписи читают ПОСЛЕ вердикта, а вердикт к тому моменту уже вынесен — о
# чужом состоянии и с полной уверенностью. Индекс копии в этот момент на месте и
# вердикт бы «подтвердил» — тем ценнее, что отката на него больше нет.
#
# Полоса выровнена по всему набору: ту же третью категорию на неразрешённом стволе
# отдаёт и `check-03-holding-claim-resolves`. Две разные реакции на одно состояние
# внутри одного набора и были предметом ws#621.
noref="$(mktemp -d -p "$TMP" noref.XXXXXX)"
mkdir -p "$noref/services/iam/docs/engineering/acceptance"
git -C "$noref" init -q
printf '%s\n' '# Приёмка

- **Статус:** ✅ APPROVED (проба)' > "$noref/services/iam/docs/engineering/acceptance/probe-subject.md"
git -C "$noref" add -A -f >/dev/null 2>&1
run 2 "$NEW" "$b" "$noref" "ствол не разрешён — VOID, а не вердикт по индексу копии" \
    "ствол дерева продукта"

echo
echo "[CENSUS] inject-04: проб объявлено $DECLARED, исполнено $probes, провалов $failed"
if [ "$probes" -ne "$DECLARED" ]; then
    echo "[VOID] inject-04 — исполнено $probes из объявленных $DECLARED: прогон неполон, а «провалов 0» на неполном прогоне не вердикт" >&2
    exit 2
fi
if [ "$failed" -gt 0 ]; then
    echo "[FAIL] inject-04 — гейт не доказан: провалов $failed из $probes" >&2
    exit 1
fi
echo "[PASS] inject-04 — гейт доказан в обе стороны: проб $probes, провалов 0"
