#!/usr/bin/env python3
"""check-02 — каждая записка журнала работ объявляет своё состояние.

Что запрещает эта проверка. `.claude/rules/vault.md` требует KAC-trail на каждый
тикет и запрещает stale-данные; `obsidian/kacho/CLAUDE.md` §«Frontmatter
discipline» называет для записок KAC поле `status` в шапке YAML. Записка без
состояния неотличима от активной задачи, брошенной и уже решённой в другом
потоке, — то есть журнал перестаёт быть журналом.

Предыдущая проверка этого свойства была неверна дважды, и оба раза в сторону
тишины, поэтому здесь обе ошибки исправлены явно:

  * ПРЕДМЕТ. Она перечисляла `find … -maxdepth 1 -name 'KAC-*.md'` — 113 файлов
    из 208 отслеживаемых записок каталога. Девяносто пять записок она не
    открывала вовсе, и это ровно те, чей тикет назван не номером, а слагом
    (`SEC-A-…`, `GEO-1`, `IAM-INT-1-…`, `NLB-1c-…`). Здесь предмет берётся из
    индекса git по всему каталогу на любой глубине: имя файла и глубина
    вложенности перестают решать, читается записка или нет.

  * ФОРМА. Она признавала только строку тела `**Status**:`. Канон — поле `status`
    в шапке YAML, и им пользовались 168 записок из 205; сто одна несла обе формы
    (замер на момент починки проверки). Из-за этого шестнадцать записок
    объявлялись «без состояния», хотя каждая из них состояние объявляет — в
    канонической форме, — а сама проверка при этом была красной и «известной
    красной». Признаются ОБЕ формы: шапка YAML `status:` и строка тела
    `**Status**:` / `**Статус**:`.

    Числа выше — ДАТИРОВАННЫЕ, и предмет у них с тех пор изменился: волна сверки
    KAC 2026-08-05 свела состояние к одной форме — строка тела снята со ВСЕХ 156
    записок, которые её несли (там, где она сообщала что-то сверх статуса, она
    переименована в `**Состояние на момент записи**:` — датированный факт о
    прошлом). Терпимость к форме тела оставлена НАМЕРЕННО как приём вперёд: её
    может написать следующий автор. Но «ноль находок» здесь обязано быть отличимо
    от «ноль прочитанного», поэтому перепись печатается в каждом прогоне (`в
    шапке N, в теле M, в обеих K`) — если строка тела вернётся, это будет видно
    числом, а не догадкой.

Из предмета выведены только записки, объявившие себя указателем (`category: hub`)
— у них нет собственного состояния, они перечисляют чужие. Перечень выведенных
печатается поимённо: исключение, которому нечего исключать, обязано быть видно
как находка следующему читателю, а не молча пропасть.

Исходы: 0 — состояние объявлено везде; 1 — есть записки без состояния (каждая
названа); 2 — читать нечего.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import _lib  # noqa: E402

NAME = "check-02-kac-trail-status"
TRAILS = "obsidian/kacho/KAC/*"

BODY = re.compile(r"^\*\*(?:Status|Статус)\*\*\s*[:：]\s*\S", re.I | re.M)
FM_STATUS = re.compile(r"^status\s*:\s*\S", re.I)
FM_CATEGORY = re.compile(r"^category\s*:\s*(\S+)", re.I)


def frontmatter(text):
    """Строки шапки YAML; пустой список, если шапки нет."""
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        return []
    out = []
    for line in lines[1:]:
        if line.strip() == "---":
            return out
        out.append(line)
    return []  # шапка не закрыта — считаем, что её нет


def main():
    root = _lib.workspace_root()
    notes = [p for p in _lib.tracked(root, TRAILS) if p.endswith(".md")]
    if not notes:
        _lib.void(NAME, "отслеживаемых записок %s нет — читать нечего" % TRAILS)
        return 2

    hubs, missing = [], []
    by_form = {"шапка": 0, "тело": 0, "обе": 0}
    for rel in notes:
        text = _lib.read(root, rel)
        fm = frontmatter(text)
        cat = next((m.group(1).strip('"\'').lower()
                    for m in (FM_CATEGORY.match(l) for l in fm) if m), None)
        if cat == "hub":
            hubs.append(rel)
            continue
        in_fm = any(FM_STATUS.match(l) for l in fm)
        in_body = bool(BODY.search(text))
        if in_fm and in_body:
            by_form["обе"] += 1
        elif in_fm:
            by_form["шапка"] += 1
        elif in_body:
            by_form["тело"] += 1
        else:
            missing.append(rel)

    _lib.census(
        "%s: записок в каталоге %d; предмет %d (выведено указателей %d%s); "
        "состояние объявлено — в шапке %d, в теле %d, в обеих %d"
        % (NAME, len(notes), len(notes) - len(hubs), len(hubs),
           (": " + ", ".join(hubs)) if hubs else "",
           by_form["шапка"], by_form["тело"], by_form["обе"])
    )

    if missing:
        for rel in missing:
            _lib.fail(NAME, "%s — состояние не объявлено ни в шапке YAML "
                            "(`status:`), ни строкой тела (`**Status**:`)" % rel)
        _lib.fail(NAME, "записок без состояния: %d" % len(missing))
        return 1

    _lib.passed(NAME, "состояние объявлено во всех %d записках предмета"
                      % (len(notes) - len(hubs)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
