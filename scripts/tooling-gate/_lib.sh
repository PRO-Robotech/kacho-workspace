#!/usr/bin/env bash
# Общие помощники набора tooling-gate. Только для `source`, не исполняется сам.
#
# Предмет набора: КОНВЕЙЕР и АГЕНТЫ утверждают о дереве то, чего в нём нет.
# Такое утверждение устаревает молча — от чужого коммита, без конфликта и без
# единой красной проверки, — поэтому у каждого обязан быть исполняемый вопрос к
# дереву, а не абзац (`gate-authoring` §Читать исполняемое).
#
# Форма набора намеренно повторяет scripts/skills-gate: три исхода, перепись
# отдельной строкой, корень переопределяется ради инъекции.

# Корень workspace. `TOOLING_GATE_ROOT` переопределяет его — этим пользуется
# ТОЛЬКО inject.sh, чтобы прогонять гейт по временной копии дерева с внесённым
# дефектом и не трогать рабочее (`gate-authoring` §Инъекция).
tooling_gate_workspace_root() {
    if [ -n "${TOOLING_GATE_ROOT:-}" ]; then
        cd "$TOOLING_GATE_ROOT" && pwd
        return
    fi
    local script_dir
    script_dir="$(cd "$(dirname "${BASH_SOURCE[1]}")" && pwd)"
    cd "$script_dir/../.." && pwd
}

tooling_gate_pass() { echo "[PASS] $1${2:+ — $2}"; }
tooling_gate_fail() { echo "[FAIL] $1${2:+ — $2}" >&2; }
tooling_gate_void() { echo "[VOID] $1${2:+ — $2}" >&2; }   # «проверять нечего» ≠ «находок 0»

# Перепись — ОТДЕЛЬНОЕ утверждение, а не следствие успеха: иначе «ноль находок»
# на неоткрытом дереве неотличимо от чистого (`measurement-discipline` §Объём
# осмотренного).
tooling_gate_census() { echo "[CENSUS] $1"; }

# Состав дерева — из индекса git, не с диска: посторонний каталог рядом с репо
# иначе влияет на вердикт. `--others --exclude-standard` добавляет ещё не
# закоммиченный, но и не игнорируемый файл: иначе новый агент не проверяется
# ровно в тот день, когда его пишут.
tooling_gate_files() {
    local ws="$1" pattern="$2"
    git -C "$ws" ls-files --cached --others --exclude-standard "$pattern" | sort -u
}

# Отслеживаемые элементы ВЕРХНЕГО уровня — словарь, по которому опознаётся
# «этот токен претендует на путь В ЭТОМ репозитории». Каталог `project/`
# игнорируется git и в словарь не попадает намеренно: пути под ним материализует
# отдельный шаг checkout, и утверждением этого репозитория о себе они не являются
# (границу набор объявляет, а не умалчивает — см. README §Что гейт НЕ проверяет).
# Словарь выводится из ИНДЕКСА, а не из `ls-tree HEAD`: иначе ещё не
# закоммиченный каталог верхнего уровня не опознаётся как свой, и проверка молчит
# ровно в тот коммит, где его заводят.
tooling_gate_toplevel() {
    local ws="$1"
    git -C "$ws" ls-files --cached --others --exclude-standard \
        | awk -F/ 'NF>1 {print $1; next} {print $1}' \
        | sort -u
}
