#!/usr/bin/env bash
# check-04 — «не проверено» ни у одного прогонщика не засчитывается за «пройдено».
#
# Что запрещает эта проверка. Прогонщик набора получает от своих проверок три
# разных исхода: прошло, не прошло, ПРОВЕРИТЬ НЕ УДАЛОСЬ (предпосылка не
# выполнена — нет соседнего дерева, нет инструмента, каталог переехал). Если
# третий исход не отделён от первого, набор, не проверивший НИЧЕГО, выходит
# успехом — и печатает это словами. Так и было: прогонщик считал пропуски в
# переменную, печатал её в итоговой строке и НИ РАЗУ не читал её в предикате
# выхода, а завершающую строку «все N проверок пройдены» выдавал по единственному
# условию «нет провалов». На нулевом числе пройденных она читается как успех.
#
# Проверка поведенческая, а не текстовая. Искать в исходнике слово «skip» или
# имя переменной значит ловить форму: прогонщик мог назвать исход иначе, мог
# считать его в массив, мог вынести решение в функцию. Спрашивается ИСХОД: в
# песочнице рядом с копией прогонщика кладётся одна-единственная проверка,
# возвращающая «проверить не удалось», и требуется НЕнулевой код выхода. Рядом —
# положительный контроль той же формы: та же песочница с проверкой, возвращающей
# успех, обязана дать ноль. Без второго прогонщик, всегда падающий, прошёл бы
# отрицательную половину и был бы объявлен исправным.
#
# Предпосылка проверки (исход VOID): в дереве есть хотя бы один прогонщик
# `scripts/*/run-all.sh`, и его копия в песочнице вообще запускается. Пропала
# предпосылка — находка, а не успех.
#
# Договорённость о кодах, по которой набор и живёт: 0 — прошло, 1 — находки,
# 2 — проверить не удалось. ЭТА проверка требует не конкретного числа, а того,
# чтобы исход «не удалось» НЕ был нулём.
#
# ЧИСЛО ТРЕБУЕТ СОСЕД — `check-07-runner-void-distinct-from-finding.sh`: ему
# мало ненулевого кода, он требует РОВНО 2 и отдельно проверяет, что находка
# рядом с беспредметной проверкой по-прежнему даёт 1. Здесь эта строгость
# намеренно НЕ дублируется: проверки об одном предмете разошлись бы молча.
# Границу видно по вопросу: check-04 спрашивает «не засчитано ли за успех»,
# check-07 — «отличимо ли от находки». До ws#458 первый был зелёным, а второй
# красным на всех прогонщиках сразу.
set -euo pipefail

# shellcheck source=_lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/_lib.sh"

WS="$(tooling_gate_workspace_root)"
NAME="check-04-runner-void-is-not-pass"

mapfile -t RUNNERS < <(tooling_gate_files "$WS" 'scripts/*/run-all.sh')
if [ "${#RUNNERS[@]}" -eq 0 ]; then
    tooling_gate_void "$NAME" "прогонщиков scripts/*/run-all.sh в дереве нет — проверять нечего"
    exit 2
fi

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# probe <прогонщик> <код-заглушки> — печатает код выхода прогонщика в песочнице,
# где единственная проверка возвращает заданный код.
probe() {
    local runner="$1" stub_rc="$2" dir sdir
    dir="$(mktemp -d "$TMP/p.XXXXXX")"
    # Прогонщик кладётся на СВОЁ место — `scripts/<набор>/run-all.sh` — рядом с
    # копией общей библиотеки наборов: прогонщик, подключающий
    # `scripts/lib/suite-runner.sh`, вне этой раскладки не запускается вовсе, и
    # проба судила бы устройство песочницы, а не его исход.
    sdir="$dir/$(dirname "$runner")"
    mkdir -p "$sdir"
    if [ -d "$WS/scripts/lib" ]; then cp -R "$WS/scripts/lib" "$dir/scripts/lib"; fi
    cp "$WS/$runner" "$sdir/run-all.sh"
    chmod +x "$sdir/run-all.sh"
    # Имя заглушки подходит под глоб любого прогонщика набора: `check-*.sh`.
    # Заглушка печатает объём осмотренного — строку с числом: общий прогонщик
    # (ws#762) не засчитывает ноль проверке, которая объёма не назвала, и
    # молчаливая заглушка сорвала бы положительный контроль по чужой причине.
    # «Без предмета» заглушка объявляет строкой `[VOID]` с причиной: код 2 без неё
    # общий прогонщик судит поломкой (ws#762), и проба мерила бы не то.
    # Вердикт этой пробы по-прежнему берётся только из кода выхода прогонщика.
    { printf '#!/usr/bin/env bash\necho "осмотрено 1"\n'
      [ "$stub_rc" -ne 2 ] || printf 'echo "[VOID] заглушка — сверять не с чем" >&2\n'
      printf 'exit %s\n' "$stub_rc"; } > "$sdir/check-99-stub.sh"
    chmod +x "$sdir/check-99-stub.sh"
    ( cd "$sdir" && ./run-all.sh >/dev/null 2>&1 )
    echo $?
}

findings=0
examined=0
for runner in "${RUNNERS[@]}"; do
    # Положительный контроль первым: прогонщик, который не умеет отвечать нулём
    # даже на единственной пройденной проверке, к отрицательной пробе непригоден —
    # она прошла бы на нём тождественно и ничего не доказала.
    green="$(probe "$runner" 0)"
    if [ "$green" -ne 0 ]; then
        tooling_gate_void "$NAME" \
            "$runner — на единственной ПРОЙДЕННОЙ проверке вернул $green; отрицательная проба на нём недоказательна"
        exit 2
    fi

    examined=$((examined + 1))
    void_rc="$(probe "$runner" 2)"
    if [ "$void_rc" -eq 0 ]; then
        tooling_gate_fail "$NAME" \
            "$runner — единственная проверка ответила «проверить не удалось», прогонщик вышел успехом (0); «не проверено» засчитано за «пройдено»"
        findings=$((findings + 1))
    fi
done

tooling_gate_census "$NAME: прогонщиков осмотрено $examined (по две пробы на каждый — пройдено и «не удалось»)"

if [ "$findings" -gt 0 ]; then
    tooling_gate_fail "$NAME" "прогонщиков с находкой: $findings"
    exit 1
fi

tooling_gate_pass "$NAME" "у всех $examined прогонщиков «не проверено» даёт ненулевой исход"
