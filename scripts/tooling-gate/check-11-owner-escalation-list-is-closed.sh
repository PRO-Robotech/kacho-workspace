#!/usr/bin/env bash
# check-11 — РЕШЕНИЯ ПРИНИМАЕТ ДИСПЕТЧЕР, а перечень исполнимо-невозможного,
# оставленный владельцу, ЗАКРЫТ и состоит ровно из ТРЁХ пунктов.
#
# ОСНОВАНИЕ. Решение владельца 2026-09-20: «Все решения принимаешь сам меня не
# спрашиваешь». Прежний перечень поводов спросить (продуктовый выбор, конфликт
# объёма, спор вердиктов, снятие гейта, послабление, отказ по критерию) отменён
# целиком; взамен владельцу оставлено ТОЛЬКО то, что без него физически не
# исполняется, — три пункта базы маршрутизации §11.
#
# ЧТО УТВЕРЖДАЕТ — две оси, ни одна не выводится из другой.
#
#   ОСЬ A. ПЯТЬ ЦИТАТ 2026-09-20 ЖИВЫ. База `.claude/agents/dispatcher.md`
#   несёт дословные слова владельца по четырём требованиям, общий протокол
#   `CLAUDE.md` — по пятому («решения принимаешь ты на человеке не блокируемся»),
#   а ядро `.claude/rules/00-kacho-core.md` — нормы, которыми записаны критерии
#   продукта, автономия решения и поведение при ПРЕПЯТСТВИИ (`ban18-criteria`,
#   `ban18-decides-dispatcher`, `ban18-no-human-block`,
#   `ban18-three-outcomes-at-obstacle`, `ban18-workaround-is-not-a-breach`).
#   Якорем взята ЦИТАТА, а не пересказ: пересказ переживает снятие своего
#   основания молча, цитата — нет.
#
#   Почему пятая цитата живёт в `CLAUDE.md`, а не в базе: база упёрлась в свой
#   потолок (измерено — тело 95 869 Б при потолке 96 000 Б, `scripts/rules-gate/
#   check-02-nothing-lost.sh`), а `CLAUDE.md` видят ОБА конца — и диспетчер, и
#   исполнитель, — так что требование доезжает до адресата обоими путями.
#
#   ОСЬ B. ПЕРЕЧЕНЬ ЗАКРЫТ. В §11 базы нумерованных пунктов ровно ТРИ. Четвёртый
#   пункт — не мелочь, а тот самый способ, которым перечень исполнимо-невозможного
#   превращается в лазейку: под «ещё один повод» подводится любое неудобное
#   решение, и автономия, ради которой правило писалось, отменяется дописыванием
#   строки. Меньше трёх — обратная порча: пункт выпал, и действие, которое без
#   владельца НЕ исполняется, некому поднять.
#
# ПОЧЕМУ ЭТО ГЕЙТ, А НЕ ПОЖЕЛАНИЕ. Оба разрыва МОЛЧАЛИВЫ: ни один прогон продукта
# от них не меняется, обнаруживаются они поведением диспетчера на следующей волне
# и ценой волны. База при этом — файл, правимый чаще прочих: норма выпадает из
# неё одной строкой диффа.
#
# ЧЕГО ЭТОТ ГЕЙТ НЕ ДЕРЖИТ — ГРАНИЦА ОБЪЯВЛЕНА, А НЕ УМОЛЧАНА.
#
#   1. Он судит ТЕКСТ базы, а не ПОВЕДЕНИЕ диспетчера. «Диспетчер всё же спросил
#      владельца о продуктовом выборе» отсюда не видно и машинно не выводится:
#      ход диспетчера следа в дереве не оставляет. Держится вниманием владельца
#      и приёмкой волны.
#
#   2. Четвёртый повод, записанный ПРОЗОЙ вместо нумерованного пункта («ещё
#      владельцу уходит…»), — молчание. Перечень пересказов деревом не
#      производится, а признак «любое предложение со словом владелец» дал бы
#      красное на каждом законном абзаце. Держится вниманием `tooling-maintainer`
#      и `landing-reviewer`.
#
#   3. ПЕРЕБОР при препятствии он не считает. «Диспетчер объявил недостижимость
#      после ОДНОЙ попытки» и «отказ пересказан вместо цитаты» отсюда не видны:
#      попытка следа в дереве не оставляет, как и сам ход диспетчера (п.1).
#      Гейт держит только ПРИСУТСТВИЕ нормы и цитаты. Держится вниманием
#      `wave-reviewer` при приёмке волны.
#
#   4. Требование 8 (ввоз чужого кода поддеревом вместе с его пробами,
#      `ban21-*`, `polyrepo.md` §«Внесение ЧУЖОГО (стороннего) кода») здесь НЕ
#      держится и якорем сюда не заводится: предмет другой, и у него в этом
#      дереве нет ни одного экземпляра — ввезённых поддеревьев ноль. Гейт на
#      пустом предмете дал бы зелёное, неотличимое от «не проверяли».
#
# Коды выхода: 0 — обе оси сошлись; 1 — находка либо пустой обход; 2 — предмета
# нет (базы маршрутизации в этом дереве не существует).

set -euo pipefail

# shellcheck source=_lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/_lib.sh"

WS="$(tooling_gate_workspace_root)"
NAME="check-11-owner-escalation-list-is-closed"

BASE_REL=".claude/agents/dispatcher.md"
CORE_REL=".claude/rules/00-kacho-core.md"
PROTO_REL="CLAUDE.md"

if [ ! -f "$WS/$BASE_REL" ] || [ ! -f "$WS/$CORE_REL" ] || [ ! -f "$WS/$PROTO_REL" ]; then
    tooling_gate_void "$NAME" "нет $BASE_REL, $CORE_REL либо $PROTO_REL — базы маршрутизации, ядра или общего протокола здесь нет, судить нечего"
    exit 2
fi

findings=0
anchors_want=0
anchors_have=0

anchor() {   # <файл> <дословный якорь> <что он держит>
    anchors_want=$((anchors_want + 1))
    if grep -qF -- "$2" "$WS/$1"; then
        anchors_have=$((anchors_have + 1))
    else
        tooling_gate_fail "$NAME" "$1 — нормы нет: не найдено «$2» ($3). Решение владельца 2026-09-20 записано в корпусе этим местом; выпав отсюда, оно перестаёт доезжать до кого бы то ни было"
        findings=$((findings + 1))
    fi
}

# ── ОСЬ A: четыре цитаты владельца 2026-09-20 и две нормы ядра ───────────────
anchor "$BASE_REL" "Все решения принимаешь сам меня не спрашиваешь" \
    "требование 3: диспетчер решает сам, владельцу — только неисполнимое"
anchor "$BASE_REL" "максимальная производительность, безопасность, иновационность, узнаваемость относительно рынка, перспективность" \
    "требование 4: пять критериев продукта словами владельца"
anchor "$BASE_REL" "следи что бы волны планировались согласно расходу и емкости в 5 часовом лимите" \
    "требование 5: волны планируются по расходу и ёмкости окна"
anchor "$BASE_REL" "разбей на волны задач и каждую волну оберни ворк флоу" \
    "требование 6: волна — это воркфлоу, исполнителя выбирает диспетчер внутри него"
anchor "$PROTO_REL" "решения принимаешь ты на человеке не блокируемся" \
    "требование 7: препятствие не исход — ищется обход, «жду человека» исходом полосы не является"
anchor "$CORE_REL" "ban18-criteria" "норма «критерии продукта, «нет» на любом одном — ОТКАЗ»"
anchor "$CORE_REL" "ban18-decides-dispatcher" "норма «решение по критериям принимает диспетчер, не владелец»"
anchor "$CORE_REL" "ban18-no-human-block" "норма «препятствие исходом НЕ является: ищется обход»"
anchor "$CORE_REL" "ban18-three-outcomes-at-obstacle" \
    "норма «исходов при препятствии три, недостижимость доказывается перебором с дословными отказами»"
anchor "$CORE_REL" "ban18-workaround-is-not-a-breach" \
    "норма «обход ищется СРЕДИ безопасных способов, а не вместо безопасности» — без неё требование 7 читается как разрешение обходить защиту"

# Числа ёмкости — часть требования 5: без них «планируй по расходу» остаётся
# лозунгом, а лозунг не проверяем ни человеком, ни машиной.
anchor "$BASE_REL" "не больше ТРЁХ, и только при непересекающихся областях" \
    "ёмкость: одновременно идущих воркфлоу не больше трёх"
anchor "$BASE_REL" "300–500 тысяч токенов, измерено по одиннадцати полосам и семи воркфлоу одной сессии" \
    "ёмкость: расход на полосу высокого усилия с единицей счёта и объёмом замера"

# ── ОСЬ B: перечень исполнимо-невозможного закрыт тремя пунктами ─────────────
# Раздел берётся по НОМЕРУ заголовка: на §11 ссылаются §3, §4, §7 и §12, номер
# переживает переименование раздела, а текст заголовка — нет.
section="$(awk '/^## 11\./{f=1;next} /^## /{f=0} f' "$WS/$BASE_REL")"
section_lines=0
if [ -n "$section" ]; then
    section_lines="$(printf '%s\n' "$section" | wc -l)"
fi

items=0
if [ "$section_lines" -gt 0 ]; then
    items="$(printf '%s\n' "$section" | grep -cE '^[0-9]+\. ' || true)"
fi

if [ "$section_lines" -eq 0 ]; then
    tooling_gate_fail "$NAME" "$BASE_REL — раздела «## 11.» нет либо он пуст: перечень исполнимо-невозможного не записан нигде, и любой повод обратиться к владельцу становится допустимым"
    findings=$((findings + 1))
elif [ "$items" -gt 3 ]; then
    tooling_gate_fail "$NAME" "$BASE_REL §11 — нумерованных пунктов $items при закрытом перечне из ТРЁХ: перечень исполнимо-невозможного расширен, и под лишний пункт подводится любое неудобное решение. Четвёртый пункт заводится только новым решением владельца, и тогда правится этот гейт — тем же изменением"
    findings=$((findings + 1))
elif [ "$items" -lt 3 ]; then
    tooling_gate_fail "$NAME" "$BASE_REL §11 — нумерованных пунктов $items при закрытом перечне из ТРЁХ: пункт выпал, и действие, которое без владельца физически не исполняется, некому поднять"
    findings=$((findings + 1))
fi

# ── ПЕРЕПИСЬ ОБЪЁМА — всегда и до вердикта ──────────────────────────────────
tooling_gate_census "$NAME: осмотрено файлов 3 ($BASE_REL, $CORE_REL, $PROTO_REL); §11 — строк $section_lines, нумерованных пунктов $items при закрытом перечне 3; якорей нормы требовалось $anchors_want, найдено $anchors_have"

if [ "$anchors_want" -eq 0 ]; then
    tooling_gate_void "$NAME" "ни одного якоря не проверено — предикат остался без предмета"
    exit 2
fi

if [ "$findings" -gt 0 ]; then
    tooling_gate_fail "$NAME" "находок $findings"
    exit 1
fi

tooling_gate_pass "$NAME" "решения за диспетчером: якорей нормы $anchors_have из $anchors_want, перечень исполнимо-невозможного закрыт тремя пунктами (§11, строк $section_lines)"
