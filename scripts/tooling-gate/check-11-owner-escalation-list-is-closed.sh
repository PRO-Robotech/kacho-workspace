        anchors_have=$((anchors_have + 1))
        ;;
    *)
        tooling_gate_fail "$NAME" "$BASE_REL — постулаты НЕ ПЕРВИЧНЫ: первый нумерованный раздел базы — «$first_section», а не «## 0. ». Дословность цитат этого не покрывает: блок, уехавший ниже других разделов, читается как ещё один раздел среди прочих, и объявленное старшинство перестаёт быть первым, что видит главный поток. Разделов в обходе $sections_n"
        findings=$((findings + 1))
        ;;
esac

# ── ОСЬ B: перечень исполнимо-невозможного закрыт тремя пунктами ─────────────
# Раздел берётся по НОМЕРУ заголовка: на §11 ссылаются §3, §4, §7 и §12, номер
# переживает переименование раздела, а текст заголовка — нет.
