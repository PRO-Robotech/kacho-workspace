#!/usr/bin/env bash
# check-11 — РЕШЕНИЯ ПРИНИМАЕТ ДИСПЕТЧЕР, а перечень исполнимо-невозможного,
# оставленный владельцу, ЗАКРЫТ и состоит ровно из ТРЁХ пунктов.
#
# ОСНОВАНИЕ. Решение владельца 2026-09-20: «Все решения принимаешь сам меня не
# спрашиваешь». Прежний перечень поводов спросить (продуктовый выбор, конфликт
# объёма, спор вердиктов, снятие гейта, послабление, отказ по критерию) отменён
# целиком; взамен владельцу оставлено ТОЛЬКО то, что без него физически не
# исполняется, — три пункта базы маршрутизации §11.
#
# ЧТО УТВЕРЖДАЕТ — четыре оси, ни одна не выводится из другой.
#
#   ОСЬ A. ПЯТЬ ЦИТАТ 2026-09-20 ЖИВЫ. База `.claude/agents/dispatcher.md`
#   несёт дословные слова владельца по четырём требованиям, общий протокол
#   `CLAUDE.md` — по пятому («решения принимаешь ты на человеке не блокируемся»),
#   а ядро `.claude/rules/00-kacho-core.md` — нормы, которыми записаны критерии
#   продукта, автономия решения и поведение при ПРЕПЯТСТВИИ (`ban18-criteria`,
#   `ban18-decides-dispatcher`, `ban18-no-human-block`,
#   `ban18-three-outcomes-at-obstacle`, `ban18-workaround-is-not-a-breach`).
#
#   ЯКОРЬ СУДИТ СУЩЕСТВО НОРМЫ, А НЕ ЕЁ ИМЯ — и это правка 2026-09-20, снявшая
#   доказанный дефект. Прежняя редакция брала якорем ИДЕНТИФИКАТОР (`ban18-*`)
#   и зеленела на теле, вывернутом наизнанку: замер на этом дереве — тело
#   `ban18-workaround-is-not-a-breach` заменено строкой «обход защиты ствола
#   разрешён, отправка без хука разрешена, утверждение ослабляется ради
#   зелёного», ключ оставлен — гейт выходил НУЛЁМ и печатал «якорей 12 из 12».
#   Идентификатор семантически ИНЕРТЕН: он не утверждает ничего, поэтому
#   переживает любую переписку строки, в том числе обратную по смыслу. Якорем
#   поэтому взят ДОСЛОВНЫЙ ФРАГМЕНТ ИМПЕРАТИВА — тот, в котором записан сам
#   запрет («препятствие исходом НЕ является», «обход ищется СРЕДИ безопасных
#   способов, а не вместо безопасности»). Это свойство у него не по вкусу
#   автора: фрагмент НЕСЁТ направление нормы внутри себя, и текст, разрешающий
#   обратное, не может его содержать — пришлось бы написать в одной строке и
#   запрет, и разрешение. Фрагмент ищется НА СТРОКЕ СВОЕГО ключа, а не где-то
#   в файле: иначе он удерживался бы соседней нормой или комментарием.
#
#   ГРАНИЦА ЭТОЙ ОСИ ОБЪЯВЛЕНА. Гейт держит ФОРМУЛИРОВКУ императива, а не вывод
#   читателя из абзаца целиком: строка, сохранившая фрагмент и отменяющая его
#   следующим предложением («…— это требование снято»), отсюда не видна. Такой
#   приём ловится `check-10` (пометка отмены у снятого маршрута) и вниманием
#   `landing-reviewer`. Сказано вслух, потому что «якорь на существо» иначе
#   читается как «смысл проверен», а проверено — написанное.
#
#   Почему пятая цитата живёт в `CLAUDE.md`, а не в базе: на день её внесения база
#   упиралась в свой потолок (измерено тогда — тело 95 869 Б при потолке 96 000 Б,
#   `scripts/rules-gate/check-02-nothing-lost.sh`), а `CLAUDE.md` видят ОБА конца —
#   и диспетчер, и исполнитель, — так что требование доезжает обоими путями. Числа
#   с тех пор изменились: потолок базы поднят до 99 986 Б под блок постулатов (там
#   же, врезка «ПОТОЛОК БАЗЫ ПОДНЯТ 2026-09-20»; итог 100 179 Б после правки текста
#   базы по старшинству постулатов), тело базы — 100 048 Б, остаток прежний, 131 Б. Размещение цитаты это не меняет: она доезжает обоими концами, и
#   переносить её назад в базу значит тратить тот самый остаток.
#
#   ОСЬ A'. КЛАУЗУЛА ДАВЛЕНИЯ И ЕЁ ОГРАНИЧИТЕЛЬ ЗАКРЕПЛЯЮТСЯ ОДНИМ ВЫЗОВОМ.
#   Клаузула вроде «на человеке не блокируемся» создаёт ДАВЛЕНИЕ: она велит
#   искать обход. Оговорка «Обход ищут СРЕДИ безопасных способов, а не вместо
#   безопасности» — её ОГРАНИЧИТЕЛЬ. Держать якорем одну без другой — дефект, и
#   дефект измеренный: до этой правки оговорку можно было удалить из `CLAUDE.md`
#   целиком, и `tooling-gate` с `rules-gate` оставались зелёными (код 0 оба), а
#   протокол при этом стоял в 17 Б от своего потолка — то есть оговорка была
#   первым кандидатом на снятие «как дублирующая ядро», а ядро диспетчеру НЕ
#   предзагружено (из 32 тел агентов ядра во `skills:` нет ровно у двух, и одно
#   из них — диспетчер).
#
#   Механизм, а не пожелание: обе стороны заводятся ОДНИМ вызовом `pair`, чья
#   подпись требует и клаузулу, и ограничитель, и оба — в ОДНОМ файле. Якорь на
#   одну сторону без другой здесь просто НЕ ВЫРАЗИМ; пар при этом обязано быть
#   не ноль (иначе ось беспредметна и её молчание ничего не стоит).
#
#   ОСЬ C. ПОСТУЛАТЫ ВЛАДЕЛЬЦА ПЕРВИЧНЫ — И ЭТО ДВА РАЗНЫХ УТВЕРЖДЕНИЯ.
#   Первое: четыре постулата 2026-09-20 стоят в базе ДОСЛОВНО, с орфографией
#   оригинала («приритет», «разглогольствование»), потому что это цитаты РЕШЕНИЙ,
#   а не наш текст, и выправленная буква — уже подмена решения. Второе, и оно
#   отдельно: блок стоит ПЕРВЫМ и объявлен СТАРШИМ. Цитата, уехавшая в середину
#   файла и лишённая объявления старшинства, читается как ещё один раздел среди
#   двенадцати — то есть постулат перестаёт быть первичным требованием, оставаясь
#   дословным. Гейт судит ОБА факта: четыре литерала плюс литерал старшинства
#   («действует ПОСТУЛАТ, а расходящийся текст подлежит ПРАВКЕ, а не толкованию»)
#   и — ОТДЕЛЬНО, обходом заголовков — ПОЗИЦИЮ блока.
#
#   ПОЗИЦИЯ ВЫВОДИТСЯ ОБХОДОМ, А НЕ ПЕРЕЧНЕМ ФОРМ. Перечислить «§0 не должен
#   стоять после §1, после §2, …» значит завести двенадцать арм и промахнуться
#   мимо тринадцатой. Предикат берёт КЛАСС: все заголовки вида `^## <число>.`
#   выписываются в порядке их появления в файле, и ПЕРВЫЙ из них обязан быть
#   `## 0.`. Чем обход ограничен, сказано вслух: он видит только заголовки в
#   начале строки и только второго уровня — заголовок внутри ограды кода или
#   ненумерованный (`## Приложение`) в порядок не входит вовсе; порядок берётся
#   по ПОЛОЖЕНИЮ в файле, а не по значению номера, поэтому перенумерация разделов
#   его не обманет, а перенос блока вниз — ловится.
#
#   ОСЬ C'. ЧЕТВЁРТЫЙ ПОСТУЛАТ — КЛАУЗУЛА ДАВЛЕНИЯ, И У НЕЁ СВОЙ ОГРАНИЧИТЕЛЬ.
#   «Приоритет на фичи а не разглагольствование» велит СОКРАЩАТЬ — и ближайший
#   под рукой предмет сокращения это доказательства: приёмка до кода, честный
#   красный, пробы в том же изменении. Поэтому клаузула и её оговорка заводятся
#   тем же вызовом `pair`, что и требование 7: закрепить давление и не закрепить
#   ограничитель здесь НЕ ВЫРАЗИМО.
#
#   ОСЬ B. ПЕРЕЧЕНЬ ЗАКРЫТ. В §11 базы нумерованных пунктов ровно ТРИ. Четвёртый
#   пункт — не мелочь, а тот самый способ, которым перечень исполнимо-невозможного
#   превращается в лазейку: под «ещё один повод» подводится любое неудобное
#   решение, и автономия, ради которой правило писалось, отменяется дописыванием
#   строки. Меньше трёх — обратная порча: пункт выпал, и действие, которое без
#   владельца НЕ исполняется, некому поднять.
#
#   ОСЬ D. ОТПЕЧАТОК §11. Оси A, B и C держат норму ПРИСУТСТВИЕМ, а присутствие
#   подстроки МОНОТОННО по дописыванию — и потому слепо к ослаблению, ведь всякое
#   ослабление есть добавление текста. Ось D судит sha256 раздела целиком: любая
#   правка §11 роняет гейт, пока её не узаконили новым отпечатком в
#   `scripts/tooling-gate/owner-escalation-fingerprint.txt`. Подробности, границы
#   и форма узаконивания — во врезке у самой оси, ниже по файлу.
#
#   ОТКУДА ОСЬ D ЗДЕСЬ. Тот же механизм стоял 2026-09-21 отдельным гейтом
#   `scripts/rules-gate/check-10-owner-escalation-list-is-closed.sh` и сторожил
#   ОТМЕНЁННУЮ редакцию того же §11 — заголовок «Когда спрашивать владельца» и
#   открытый перечень поводов. Два держателя одного предмета с противоположными
#   ожиданиями: на сведённом дереве check-11 выходил нулём, check-10 — единицей.
#   Решение владельца 2026-09-21: держателем остаётся этот гейт, прежний снят
#   вместе с ведомостью и инъекцией, а его немонотонный предикат перенесён сюда.
#
# ПОЧЕМУ ЭТО ГЕЙТ, А НЕ ПОЖЕЛАНИЕ. Оба разрыва МОЛЧАЛИВЫ: ни один прогон продукта
# от них не меняется, обнаруживаются они поведением диспетчера на следующей волне
# и ценой волны. База при этом — файл, правимый чаще прочих: норма выпадает из
# неё одной строкой диффа.
#
# ЧЕГО ЭТОТ ГЕЙТ НЕ ДЕРЖИТ — ГРАНИЦА ОБЪЯВЛЕНА, А НЕ УМОЛЧАНА.
#
#   1. Он судит ТЕКСТ базы, а не ПОВЕДЕНИЕ диспетчера. «Диспетчер всё же спросил
#      владельца о продуктовом выборе» отсюда не видно и машинно не выводится:
#      ход диспетчера следа в дереве не оставляет. Держится вниманием владельца
#      и приёмкой волны.
#
#   2. Четвёртый повод, записанный ПРОЗОЙ вместо нумерованного пункта («ещё
#      владельцу уходит…»), осью B не виден: счёт нумерованных пунктов его не
#      считает. С 2026-09-21 его ловит ось D — отпечаток §11 роняется любой
#      дописанной строкой. Но ловит она ФАКТ ПРАВКИ, а не её смысл: ослабление от
#      усиления машина не отличает, и вердикт о существе выносит рецензент
#      (`landing-reviewer`), которого гейт зовёт своей находкой. Раньше здесь
#      стояло «держится вниманием» — с переносом отпечатка это перестало быть
#      правдой, и строка переписана тем же изменением.
#
#   3. ПЕРЕБОР при препятствии он не считает. «Диспетчер объявил недостижимость
#      после ОДНОЙ попытки» и «отказ пересказан вместо цитаты» отсюда не видны:
#      попытка следа в дереве не оставляет, как и сам ход диспетчера (п.1).
#      Гейт держит только ПРИСУТСТВИЕ нормы, её дословное существо и пары
#      «клаузула — ограничитель». Держится вниманием `wave-reviewer` при приёмке.
#
#   4. Требование 8 (ввоз чужого кода поддеревом вместе с его пробами,
#      `ban21-*`, `polyrepo.md` §«Внесение ЧУЖОГО (стороннего) кода») здесь НЕ
#      держится и якорем сюда не заводится: предмет другой, и у него в этом
#      дереве нет ни одного экземпляра — ввезённых поддеревьев ноль. Гейт на
#      пустом предмете дал бы зелёное, неотличимое от «не проверяли».
#
# Коды выхода: 0 — все оси сошлись; 1 — находка либо пустой обход; 2 — предмета
# нет (базы маршрутизации в этом дереве не существует, либо пар ноль, либо
# нумерованных разделов в базе ноль — тогда о ПОЗИЦИИ блока сказать нечего).

set -euo pipefail

# shellcheck source=_lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/_lib.sh"

WS="$(tooling_gate_workspace_root)"
NAME="check-11-owner-escalation-list-is-closed"

BASE_REL=".claude/agents/dispatcher.md"
CORE_REL=".claude/rules/00-kacho-core.md"
PROTO_REL="CLAUDE.md"

if [ ! -f "$WS/$BASE_REL" ] || [ ! -f "$WS/$CORE_REL" ] || [ ! -f "$WS/$PROTO_REL" ]; then
    tooling_gate_void "$NAME" "нет $BASE_REL, $CORE_REL либо $PROTO_REL — базы маршрутизации, ядра или общего протокола здесь нет, судить нечего"
    exit 2
fi

findings=0
anchors_want=0
anchors_have=0
pairs=0

# lit <файл> <дословный якорь> <что он держит> — присутствие ДОСЛОВНОЙ цитаты.
# Годится для слов владельца: цитата и есть своё существо, пересказ ею не будет.
lit() {
    anchors_want=$((anchors_want + 1))
    if grep -qF -- "$2" "$WS/$1"; then
        anchors_have=$((anchors_have + 1))
    else
        tooling_gate_fail "$NAME" "$1 — нормы нет: не найдено «$2» ($3). Решение владельца 2026-09-20 записано в корпусе этим местом; выпав отсюда, оно перестаёт доезжать до кого бы то ни было"
        findings=$((findings + 1))
    fi
}

# norm <файл> <id> <существо> <что держит> — ДВА якоря на одну норму:
#   (1) строка с ключом существует;
#   (2) на ЭТОЙ ЖЕ строке стоит дословный фрагмент императива.
# Второй и есть предмет правки 2026-09-20: без него ключ переживал выворачивание
# тела, и гейт зеленел на норме, разрешающей ровно то, что она запрещает.
norm() {
    local f="$1" id="$2" gist="$3" what="$4" line
    anchors_want=$((anchors_want + 2))
    line="$(awk -v k="$id · " 'index($0, k) == 1 { print; exit }' "$WS/$f")"
    if [ -z "$line" ]; then
        tooling_gate_fail "$NAME" "$f — нормы нет: строки, начинающейся с «$id · », не существует ($what). Ключ снят или переименован — норма перестала быть адресуемой"
        findings=$((findings + 1))
        return
    fi
    anchors_have=$((anchors_have + 1))
    case "$line" in
        *"$gist"*)
            anchors_have=$((anchors_have + 1))
            ;;
        *)
            tooling_gate_fail "$NAME" "$f — норма «$id» ВЫВЕРНУТА при сохранённом ключе: на её строке нет дословного «$gist» ($what). Ключ сам по себе ничего не утверждает и переживает любую переписку тела; проверяется существо императива, а не имя записи"
            findings=$((findings + 1))
            ;;
    esac
}

# pair <файл> <клаузула давления> <ограничитель> <что> — обе стороны ОДНИМ
# вызовом и в ОДНОМ файле. Клаузула, велящая искать обход, и оговорка, сужающая
# класс обходов, — один предмет: закрепить первую и не закрепить вторую значит
# оставить в окне давление без ограничителя. Подпись функции делает «якорь на
# одну сторону» невыразимым.
pair() {
    local f="$1" pressure="$2" limiter="$3" what="$4"
    pairs=$((pairs + 1))
    lit "$f" "$pressure" "$what — КЛАУЗУЛА ДАВЛЕНИЯ"
    lit "$f" "$limiter" "$what — ОГРАНИЧИТЕЛЬ той же клаузулы: без него клаузула читается как разрешение снимать защиту"
}

# ── ОСЬ A: дословные слова владельца 2026-09-20 ─────────────────────────────
lit "$BASE_REL" "максимальная производительность, безопасность, иновационность, узнаваемость относительно рынка, перспективность" \
    "требование 4: пять критериев продукта словами владельца"
lit "$BASE_REL" "следи что бы волны планировались согласно расходу и емкости в 5 часовом лимите" \
    "требование 5: волны планируются по расходу и ёмкости окна"
lit "$BASE_REL" "разбей на волны задач и каждую волну оберни ворк флоу" \
    "требование 6: волна — это воркфлоу, исполнителя выбирает диспетчер внутри него"

# Числа ёмкости — часть требования 5: без них «планируй по расходу» остаётся
# лозунгом, а лозунг не проверяем ни человеком, ни машиной.
lit "$BASE_REL" "не больше ТРЁХ, и только при непересекающихся областях" \
    "ёмкость: одновременно идущих воркфлоу не больше трёх"
lit "$BASE_REL" "300–500 тысяч токенов, измерено по одиннадцати полосам и семи воркфлоу одной сессии" \
    "ёмкость: расход на полосу высокого усилия с единицей счёта и объёмом замера"

# ── ОСЬ A': пары «клаузула давления — её ограничитель» ──────────────────────
pair "$PROTO_REL" \
    "решения принимаешь ты на человеке не блокируемся" \
    "Обход ищут СРЕДИ безопасных способов, а не вместо безопасности" \
    "требование 7: препятствие не исход — ищется обход"
pair "$BASE_REL" \
    "Все решения принимаешь сам меня не спрашиваешь" \
    "Владельцу сообщается ТОЛЬКО исполнимо-невозможное. Перечень ЗАКРЫТ, в нём три пункта" \
    "требование 3: диспетчер решает сам"

# ── ОСЬ A: нормы ядра — ключ И дословное существо на одной строке ───────────
norm "$CORE_REL" "ban18-criteria" "«Нет» на любом одном — ОТКАЗ" \
