fi

if [ "$section_lines" -eq 0 ]; then
    tooling_gate_fail "$NAME" "$BASE_REL — раздела «## 11.» нет либо он пуст: перечень исполнимо-невозможного не записан нигде, и любой повод обратиться к владельцу становится допустимым"
    findings=$((findings + 1))
elif [ "$items" -gt 3 ]; then
    tooling_gate_fail "$NAME" "$BASE_REL §11 — нумерованных пунктов $items при закрытом перечне из ТРЁХ: перечень исполнимо-невозможного расширен, и под лишний пункт подводится любое неудобное решение. Четвёртый пункт заводится только новым решением владельца, и тогда правится этот гейт — тем же изменением"
    findings=$((findings + 1))
elif [ "$items" -lt 3 ]; then
    tooling_gate_fail "$NAME" "$BASE_REL §11 — нумерованных пунктов $items при закрытом перечне из ТРЁХ: пункт выпал, и действие, которое без владельца физически не исполняется, некому поднять"
    findings=$((findings + 1))
fi

# ── ОСЬ D: ОТПЕЧАТОК §11 — ПРЕДИКАТ, КОТОРЫЙ НЕ ОБОЙТИ ДОПИСЫВАНИЕМ ──────────
#
# ЗАЧЕМ ОНА ПРИ УЖЕ ЕСТЬ ОСЯХ A, B, C. Все они держат норму ПРИСУТСТВИЕМ: якорь
# ищет дословную цитату, счёт пунктов ловит четвёртый номер. Присутствие
# подстроки МОНОТОННО по дописыванию: есть она в тексте T — есть и в T + X при
# любом X. А всякое ослабление нормы и ЕСТЬ дописывание: оговорку, исключение,
# «кроме случаев», абзац «перечень — ориентир» добавляют, не трогая ни одной
# старой буквы и не заводя нумерованного пункта. Измерено на этом дереве: абзац
# «Перечень выше — ориентир, а не закрытый список» внутри §11 оставлял гейт
# зелёным по всем трём осям (код 0, якорей 27 из 27, пунктов 3).
#
# Отпечаток немонотонен: sha256 раздела меняется от ЛЮБОЙ правки — добавления,
# удаления, перестановки, правки разметки. Дописать что-либо в §11, не уронив
# гейт, нельзя by construction.
#
# ГРАНИЦА ОСИ НАЗВАНА, А НЕ УМОЛЧАНА. Отпечаток ловит ИЗМЕНЕНИЕ нормы и НЕ
# отличает ослабление от усиления: «перечень — ориентир» и «перечень закрыт» для
# него два разных текста и больше ничего. Судит ослабление РЕЦЕНЗЕНТ, и гейт
# обязан его позвать — он печатает, ЧТО именно изменилось. «Зелёный» здесь значит
# «норму не трогали», а НЕ «правка безопасна». Хвостовые пустые строки раздела в
# отпечаток не входят: нормы они не несут, а дрожали бы от правки соседнего §12.
#
# УЗАКОНИВАНИЕ СВЯЗАНО С ОТПЕЧАТКОМ, А НЕ ПРОСТО ПРИСУТСТВУЕТ. Строка
# «# узаконено: <дата> · <основание> · отпечаток <16 знаков>» обязана называть
# ТОТ отпечаток, который она узаконивает. Прежняя редакция механизма (снятый
# `scripts/rules-gate/check-10`) судила основание НА ПРИСУТСТВИЕ — и новый
# отпечаток со старым основанием давал зелёное: ведомость начинала нести
# утверждение, пережившее свой предмет, а узаконивание превращалось в ритуал.
# Теперь основание меняется ВМЕСТЕ с отпечатком или не сходится вовсе.
#
# ГЕНЕРАТОРА ВЕДОМОСТИ НЕТ НАМЕРЕННО: скрипт «обнови отпечаток» вернул бы
# поступок в разряд побочных эффектов. Гейт печатает готовые строки хешей, но
# дату и основание оставляет угловыми скобками — и ведомость, куда их вписали
# как есть, объявляет находкой: вставленное не глядя зелёным не становится.
LEDGER_REL="scripts/tooling-gate/owner-escalation-fingerprint.txt"
# Ведомость берётся ИЗ ДЕРЕВА, а не рядом со скриптом: песочница инъекции —
# полная копия дерева, и ось «ведомость пропала» иначе недоказуема. В CI и
# локально `TOOLING_GATE_ROOT` не задан, и это тот же самый файл.
LEDGER="$WS/$LEDGER_REL"

anchors_want=$((anchors_want + 1))
fp_rc=0
fp_out="$(python3 - "$WS/$BASE_REL" "$LEDGER" "$LEDGER_REL" <<'PY'
import hashlib
import os
import re
import sys

BASE, LEDGER, LEDGER_REL = sys.argv[1], sys.argv[2], sys.argv[3]
LABEL_CAP = 64


def h64(s):
    return hashlib.sha256(s.encode("utf-8")).hexdigest()


def h16(s):
    return h64(s)[:16]


lines = open(BASE, encoding="utf-8").read().split("\n")
start = next((i for i, ln in enumerate(lines) if re.match(r"^## 11\.", ln)), None)
if start is None:
    # §11 нет — это находка ОСИ B, и она её уже назвала. Второе красное о том же
    # факте посылало бы читателя чинить две вещи вместо одной.
    print("раздела «## 11.» нет — судить отпечатком нечего, находку назвала ось B")
    sys.exit(2)

end = next((j for j in range(start + 1, len(lines)) if lines[j].startswith("## ")),
           len(lines))
section = lines[start:end]
while section and not section[-1].strip():
    section.pop()

body = "\n".join(section) + "\n"
total_now = h64(body)
norm_lines = [ln.rstrip() for ln in section if ln.strip()]
entries_now = [(h16(ln), ln[:LABEL_CAP]) for ln in norm_lines]


def expected_ledger_text():
    out = ["# узаконено: <дата> · <основание> · отпечаток " + total_now[:16],
           "ИТОГО\t" + total_now]
    out += ["%s\t%s" % (hh, lb) for hh, lb in entries_now]
    return "\n".join(out)


def print_expected():
    print("  ── ожидаемая ведомость целиком ──")
    for ln in expected_ledger_text().split("\n"):
        print("  " + ln)


if not os.path.isfile(LEDGER):
    print("КРАСНОЕ — ведомости ожидаемого отпечатка нет: %s" % LEDGER_REL)
    print("  Без неё сверять не с чем, и молчание означало бы «не смотрели».")
    print("  Носитель гейта снимают ВМЕСТЕ с гейтом, а не отдельно.")
    print("  Осмотрено строк §11: %d, из них норм %d." % (len(section), len(norm_lines)))
    print_expected()
    sys.exit(1)

total_want = None
entries_want = []
sanction = ""
sanction_fp = ""
for ln in open(LEDGER, encoding="utf-8").read().split("\n"):
    if ln.startswith("#"):
        m = re.match(r"#\s*узаконено:\s*(.+?)\s*$", ln)
        if m:
            sanction = m.group(1)
            mm = re.search(r"отпечаток\s+([0-9a-f]{16})\b", sanction)
            sanction_fp = mm.group(1) if mm else ""
        continue
    if "\t" not in ln or not ln.strip():
        continue
    left, right = ln.split("\t", 1)
    if left == "ИТОГО":
        total_want = right.strip()
    else:
        entries_want.append((left.strip(), right))

problems = []
if total_want is None:
    problems.append("нет строки «ИТОГО <sha256>» — отпечатка раздела не объявлено")
if not entries_want:
    problems.append("нет ни одной построчной записи — перестановку ловить нечем")
if not sanction:
    problems.append("нет строки «# узаконено: <дата> · <основание> · отпечаток <16 знаков>»"
                    " — отпечаток обновлён без названного основания")
elif "<дата>" in sanction or "<основание>" in sanction:
    problems.append("строка узаконивания вставлена как есть, с угловыми скобками:"
                    " ведомость скопировали не глядя, а узаконивание — поступок")
elif not sanction_fp:
    problems.append("строка узаконивания не называет отпечаток («… · отпечаток <16 знаков>»):"
                    " основание судилось бы НА ПРИСУТСТВИЕ и пережило бы любой новый"
                    " отпечаток — ровно дефект, ради снятия которого механизм перенесён")
elif total_want is not None and sanction_fp != total_want[:16]:
    problems.append("ОСНОВАНИЕ ПЕРЕЖИЛО СВОЙ ПРЕДМЕТ: узаконен отпечаток %s…,"
                    " а ведомость ожидает %s… — отпечаток обновили, основание оставили"
                    " прежним" % (sanction_fp, total_want[:16]))
if problems:
    print("КРАСНОЕ — ведомость %s не годится как ожидание:" % LEDGER_REL)
    for p in problems:
        print("  · %s" % p)
    print("  Ведомость, которой нечего утверждать, делает проверку всегда зелёной.")
    print_expected()
    sys.exit(1)

if total_want == total_now:
    # На stdout — ровно то, что попадёт в перепись. Основание берётся ПЕРВЫМ
    # полем (дата): целиком оно длиннее самой переписи и делает её нечитаемой,
    # а прочесть его целиком можно в ведомости, координата которой тут же рядом.
    print("%s… · узаконено %s · норм %d"
          % (total_now[:16], sanction.split(" · ")[0], len(norm_lines)))
    sys.exit(0)

want_h = [hh for hh, _ in entries_want]
now_h = [hh for hh, _ in entries_now]
want_label = dict(entries_want)
now_label = dict(entries_now)
added = [hh for hh in now_h if hh not in set(want_h)]
removed = [hh for hh in want_h if hh not in set(now_h)]

print("КРАСНОЕ %s §11 — ОХРАНЯЕМАЯ НОРМА ИЗМЕНЕНА." % BASE)
print("  раздел: «%s»" % section[0].strip())
print("  отпечаток ожидался %s" % total_want)
print("  отпечаток в дереве %s" % total_now)
if added:
    print("  ДОПИСАНО строк: %d — и это класс, ради которого ось судит отпечаток,"
          " а не присутствие слов:" % len(added))
    for hh in added:
        print("    + [%s] %s" % (hh, now_label.get(hh, "")))
if removed:
    print("  СНЯТО строк: %d:" % len(removed))
    for hh in removed:
        print("    - [%s] %s" % (hh, want_label.get(hh, "")))
if not added and not removed:
    if want_h != now_h:
        print("  ПЕРЕСТАВЛЕНО: состав строк тот же, порядок другой — перечень читается"
              " иначе, хотя ни одной буквы не изменилось.")
    else:
        print("  ПРАВКА РАЗМЕТКИ: состав и порядок норм те же, различаются пустые"
              " строки либо хвостовые пробелы.")
print()
print("  ЧЕМ ЭТО УЗАКОНИВАЕТСЯ. Правка законна, если вердикт о ней вынес РЕЦЕНЗЕНТ:")
print("  гейт назвал, ЧТО изменилось, но ослабление от усиления НЕ отличает.")
print("  Узаконив правку, впиши строки ниже в %s ТЕМ ЖЕ изменением," % LEDGER_REL)
print("  подставив дату и основание вместо угловых скобок — вставленные как есть,")
print("  они сами объявляются находкой.")
print_expected()
sys.exit(1)
PY
)" || fp_rc=$?

case "$fp_rc" in
    0)
        anchors_have=$((anchors_have + 1))
        fp_note="$fp_out"
        ;;
    2)
        # §11 нет: находку уже назвала ось B, второго красного о том же факте нет.
        fp_note="$fp_out"
        ;;
    *)
        printf '%s\n' "$fp_out" >&2
        tooling_gate_fail "$NAME" "$BASE_REL §11 — отпечаток охраняемой нормы не сошёлся либо ведомость $LEDGER_REL не годится как ожидание (что именно — строками выше). Зелёное здесь значит «норму не трогали», а не «правка безопасна»: ослабление от усиления машина не отличает, её судит рецензент"
        findings=$((findings + 1))
        fp_note="РАЗОШЁЛСЯ"
        ;;
esac

# ── ПЕРЕПИСЬ ОБЪЁМА — всегда и до вердикта ──────────────────────────────────
tooling_gate_census "$NAME: осмотрено файлов 3 ($BASE_REL, $CORE_REL, $PROTO_REL); §11 — строк $section_lines, нумерованных пунктов $items при закрытом перечне 3; нумерованных разделов базы в обходе $sections_n, первый — «$first_section»; пар «клаузула давления — ограничитель» $pairs; якорей нормы требовалось $anchors_want, найдено $anchors_have (из них на ДОСЛОВНОЕ существо нормы — 5, на дословные постулаты владельца — 4, на объявленное старшинство — 1, на ПОЗИЦИЮ блока — 1, на ОТПЕЧАТОК §11 — 1); отпечаток §11 — $fp_note; ведомость $LEDGER_REL"

if [ "$anchors_want" -eq 0 ]; then
    tooling_gate_void "$NAME" "ни одного якоря не проверено — предикат остался без предмета"
    exit 2
fi

if [ "$pairs" -eq 0 ]; then
    tooling_gate_void "$NAME" "ни одной пары «клаузула давления — ограничитель» не заведено: ось A' беспредметна, и её молчание ничего не стоит"
    exit 2
fi

if [ "$findings" -gt 0 ]; then
    tooling_gate_fail "$NAME" "находок $findings"
    exit 1
fi

tooling_gate_pass "$NAME" "решения за диспетчером: якорей нормы $anchors_have из $anchors_want (существо нормы судится дословным фрагментом императива, не ключом), постулаты владельца дословны и стоят ПЕРВЫМ разделом («$first_section» из $sections_n нумерованных), пар «клаузула — ограничитель» $pairs, перечень исполнимо-невозможного закрыт тремя пунктами (§11, строк $section_lines), отпечаток §11 сошёлся ($fp_note) — норму НЕ ТРОГАЛИ, что не равно «правка безопасна»"
