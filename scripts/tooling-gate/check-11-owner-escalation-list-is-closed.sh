# ── ОСЬ C: ПОЗИЦИЯ блока постулатов — обходом заголовков, а не перечнем форм ─
# Класс: все заголовки `^## <число>.` в порядке ПОЛОЖЕНИЯ в файле. Ограничения
# обхода названы в шапке и повторены предикатом: только начало строки, только
# второй уровень, только нумерованные. Ограды кода из обхода вычитаются — иначе
# пример разметки внутри ``` подменил бы первый настоящий заголовок.
first_section="$(awk '
    /^[ \t]*(```|~~~)/ { fence = !fence; next }
    fence { next }
    /^## [0-9]+\./ { print; exit }
' "$WS/$BASE_REL")"
sections_n="$(awk '
    /^[ \t]*(```|~~~)/ { fence = !fence; next }
    fence { next }
    /^## [0-9]+\./ { n++ }
    END { print n + 0 }
' "$WS/$BASE_REL")"

if [ "$sections_n" -eq 0 ]; then
