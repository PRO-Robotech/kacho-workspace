#!/usr/bin/env bash
# check-10 — МАРШРУТ ПОСАДКИ И СРОК ЗАВЕДЕНИЯ ЗАДАЧИ О БЕЗОПАСНОСТИ, записанные
# в корпусе, соответствуют РЕШЕНИЯМ ВЛАДЕЛЬЦА 2026-09-20.
#
# ЧТО УТВЕРЖДАЕТ — два разных утверждения, ни одно не выводится из другого.
#
#   ОСЬ A. НОРМА НА МЕСТЕ. База маршрутизации `.claude/agents/dispatcher.md` несёт
#   обе дословные цитаты владельца («не забывай агрегировать мр = волна» и «не
#   забывай по ходу создавать задачи в гитхаб ишуе если это важное и влияет на
#   безопасность»), а правило `.claude/rules/git-issues.md` — нормы, которыми они
#   записаны (`gi-wave-one-mr`, `gi-no-pr-per-lane`, `gi-security-finding-issue-now`).
#   Цитата, а не пересказ, взята якорем намеренно: пересказ переживает снятие
#   своего основания молча, цитата — нет, а база диспетчера правится чаще любого
#   другого файла корпуса, и норма исчезает из неё одной строкой диффа.
#
#   ОСЬ B. ОТМЕНЁННЫЙ МАРШРУТ НЕ ЧИТАЕТСЯ ДЕЙСТВУЮЩИМ. Решение 2026-09-17 «заливай
#   сразу в мастер» в части «PR прямо в `main` без накопительной ветки, слияние
#   сразу по зелёному CI» ОТМЕНЕНО решением 2026-09-20. Строка корпуса вправе его
#   называть — но только вместе с пометкой отмены В ТОЙ ЖЕ СТРОКЕ. Строка,
#   называющая отменённый маршрут без пометки, читается исполнителем как
#   действующее основание: именно это и стоило нам россыпи PR в ствол.
#
# ПОЧЕМУ ЭТО ВООБЩЕ ГЕЙТ, А НЕ ПОЖЕЛАНИЕ. Оба разрыва МОЛЧАЛИВЫ: ни один прогон
# продукта, ни одна проверка дерева не меняется от того, что норма выпала из базы
# или что отменённый маршрут остался стоять рядом с действующим. Обнаруживается
# это поведением агентов — то есть на следующей волне и ценой волны.
#
# ЧЕГО ЭТОТ ГЕЙТ НЕ ДЕРЖИТ, И ГРАНИЦА ОБЪЯВЛЕНА, А НЕ УМОЛЧАНА. Он судит ТЕКСТ
# корпуса, а не git: ни «в стволе открыто два PR одной волны», ни «ветка полосы
# отправлена мимо сборки» отсюда не видны — у этого дерева нет ни сети, ни права
# спрашивать `gh`, а вердикт, зависящий от сети, приходит по жребию. Порядок
# сборки волны держится вниманием `git-operator` и приёмкой посадки; здесь
# держится только то, что НОРМА ЖИВА И ОДНА.
#
# СЛЕПАЯ ЗОНА ОСИ B НАЗВАНА: признак строчный. Абзац, где отменённый маршрут
# стоит одной строкой, а пометка отмены — соседней, гейт пропустит. Строчный
# признак выбран потому, что читатель корпуса принимает решение по строке, а
# расширение до абзаца сделало бы пометку, стоящую за десять строк, оправданием
# любой строки абзаца.
#
# Коды выхода: 0 — обе оси сошлись; 1 — находка либо пустой обход; 2 — предмета
# нет (ни одного файла корпуса в этом дереве).

set -euo pipefail

# shellcheck source=_lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/_lib.sh"

WS="$(tooling_gate_workspace_root)"
NAME="check-10-landing-route-is-one-mr-per-wave"

BASE_REL=".claude/agents/dispatcher.md"
RULE_REL=".claude/rules/git-issues.md"

# Отменённый маршрут — три его законные записи в корпусе. Перечень выведен
# обходом дерева в день правки (`grep -rnE` по всем `*.md` корпуса), а не по
# памяти: форма, о которой распознаватель не знает, не даёт ни красного, ни
# зелёного — она даёт молчание.
REVOKED_RE='прямо в `?main|прямой PR|без накопительной ветки'
# Пометка отмены. Регистр перечислен явно, а не снят `grep -i`: под LC_ALL=C
# регистронезависимость кириллицы не работает, и `-i` дал бы здесь тихий недобор.
MARK_RE='[Оо]тмен|ОТМЕН|[Оо]тозв|[Пп]озднейш|[Уу]старел|не служит основанием'

# Обход: ВЕСЬ markdown корпуса плюс общий протокол `CLAUDE.md` — его читают оба
# конца, и отменённый маршрут, записанный там, доезжает до каждого исполнителя.
mapfile -t DOCS < <(
    tooling_gate_files "$WS" '.claude/*.md'
    tooling_gate_files "$WS" 'CLAUDE.md'
)
if [ "${#DOCS[@]}" -eq 0 ]; then
    tooling_gate_void "$NAME" "markdown корпуса в дереве нет — предмета у проверки не существует"
    exit 2
fi
if [ ! -f "$WS/$BASE_REL" ] || [ ! -f "$WS/$RULE_REL" ]; then
    tooling_gate_void "$NAME" "нет $BASE_REL либо $RULE_REL — база маршрутизации и правило трекера здесь не живут, судить нечего"
    exit 2
fi

findings=0
lines_read=0
carriers=0
marked=0

# ── ОСЬ A: норма на месте ────────────────────────────────────────────────────
anchors_want=0
anchors_have=0
anchor() {   # <файл> <дословный якорь> <что он держит>
    anchors_want=$((anchors_want + 1))
    if grep -qF -- "$2" "$WS/$1"; then
        anchors_have=$((anchors_have + 1))
    else
        tooling_gate_fail "$NAME" "$1 — нормы нет: не найдено «$2» ($3). Решение владельца 2026-09-20 записано в корпусе только этим местом; выпав отсюда, оно перестаёт доезжать до кого бы то ни было"
        findings=$((findings + 1))
    fi
}

anchor "$BASE_REL" "не забывай агрегировать мр = волна" \
    "МР равен волне: сборка, прогон на сведённом, сверка полос рядом, ОДИН MR"
anchor "$BASE_REL" "не забывай по ходу создавать задачи в гитхаб ишуе если это важное и влияет на безопасность" \
    "задача о безопасности заводится по ходу работы, а не в конце волны"
anchor "$RULE_REL" "gi-wave-one-mr" "норма «волна уходит ОДНИМ MR»"
anchor "$RULE_REL" "gi-no-pr-per-lane" "норма «PR на полосу и отправка веток по отдельности запрещены»"
anchor "$RULE_REL" "gi-security-finding-issue-now" "норма «находка о безопасности — задачей НЕМЕДЛЕННО»"

# ── ОСЬ B: отменённый маршрут назван только вместе с пометкой отмены ──────────
for d in "${DOCS[@]}"; do
    n="$(wc -l < "$WS/$d")"
    lines_read=$((lines_read + n))
    while IFS= read -r hit; do
        [ -n "$hit" ] || continue
        ln="${hit%%:*}"
        text="${hit#*:}"
        carriers=$((carriers + 1))
        if printf '%s\n' "$text" | grep -qE -- "$MARK_RE"; then
            marked=$((marked + 1))
        else
            tooling_gate_fail "$NAME" "$d:$ln — отменённый маршрут посадки назван БЕЗ пометки отмены: ${text:0:160}"
            findings=$((findings + 1))
        fi
    done < <(grep -nE -- "$REVOKED_RE" "$WS/$d" || true)
done

# ── ПЕРЕПИСЬ ОБЪЁМА — всегда и до вердикта ───────────────────────────────────
tooling_gate_census "$NAME: файлов корпуса ${#DOCS[@]}, строк $lines_read; строк с отменённым маршрутом $carriers, из них с пометкой отмены $marked; якорей нормы требовалось $anchors_want, найдено $anchors_have"

if [ "$lines_read" -eq 0 ]; then
    tooling_gate_void "$NAME" "файлы корпуса прочитаны, но пусты — предикат остался без предмета"
    exit 2
fi

if [ "$findings" -gt 0 ]; then
    tooling_gate_fail "$NAME" "находок $findings"
    exit 1
fi

tooling_gate_pass "$NAME" "прочитано строк $lines_read; норма 2026-09-20 на месте ($anchors_have якорей), отменённый маршрут назван $carriers раз и каждый раз с пометкой отмены"
