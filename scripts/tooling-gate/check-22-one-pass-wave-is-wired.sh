import os, re, sys
root, name = sys.argv[1], sys.argv[2]
RULE = '.claude/rules/ai-tooling.md'
ARCH = '.claude/backup/ai-tooling.md'
BASE = '.claude/agents/dispatcher.md'
GO = '.claude/agents/git-operator.md'
WAVE = '.claude/workflows/wave.js'
PROBE = 'scripts/wave-template-inject.sh'
QUOTE = ('На сколько реально начать писать код сразу продовый от начала до конца в рамках всей '
         'волны которая закроет сразу все задачи при этом быстро с минимумом токенов, минимумом '
         'времени и так же качественно?')


def void(msg):
    print('[VOID] %s — %s' % (name, msg), file=sys.stderr)
    sys.exit(2)


def flat(t):
    return re.sub(r'\s+', ' ', t)


texts = {}
for p in (RULE, ARCH, BASE, GO, WAVE, PROBE):
    try:
        texts[p] = open(os.path.join(root, p), encoding='utf-8').read()
    except OSError:
        void('носителя %s нет: судить нечего' % p)
finds = []


def need(where, text, frags, what):
    t = flat(text)
    for f in frags:
        if f not in t:
            finds.append('%s: %s — не найдено «%s»' % (where, what, f))


def unit(text, start, stop_re):
    """Норма от якоря до начала следующей единицы (строка-норма, заголовок, пункт)."""
    k = text.find(start)
    if k < 0:
        return ''
    m = re.compile(stop_re).search(text, k + len(start))
    return text[k:m.start() if m else len(text)]


# A. правило и архив.
r = texts[RULE]
line = unit(r, '\nat-one-pass-wave · ', r'\n(?:\n|#|[a-z][a-z0-9-]* · )')
if not line:
    finds.append('%s: нормы at-one-pass-wave нет' % RULE)
else:
    need(RULE, line, ['предполёт до кода ≤ 45 мин — карта влияния, критерии рецензентов, поверхность, имитация клиента',
                      'пункт карты закрывает та же полоса правкой либо «не затронуто — потому что …», пункт чужого класса — полосой его исполнителя',
                      'зависимая другого репозитория — в той же волне, пин — на ревизию с опубликованным образом',
                      'сборка непрерывная, CI — на сведённом',
                      'каскад щадит держателя ведомости',
                      'метрики — в `reports`',
                      'tooling-gate check-22',
                      'red: зависимый поправлен лишь после красного сведённого; второй PR в ветку эпика при незакрытой волне; пин без образа'],
         'at-one-pass-wave без требования')
need(ARCH, texts[ARCH], [QUOTE, '«запиши новую механику в рулы»', 'код полосы 30–90 мин',
                         '10–14 ч волны', '(~24 % токенов)', 'страж — ws#1052',
                         'Уточнение 2026-10-13 (ws#1058)', 'дал 404 в реестре'],
     'архив: цитата владельца 2026-10-13 и замеры')

# B. база диспетчера.
b = texts[BASE]
need(BASE, unit(b, '\n- Пакет (', r'\n- '), ['и пункты карты (§8а п.9)'], '§3 «Пакет»: пункты карты в задании')
row = unit(b, '\n| Волна | ', r'\n')
if not row:
    finds.append('%s: строки «Волна» §6 нет' % BASE)
else:
    need(BASE, row, ['предполёт до разреза (§8а п.9)', 'зависимая другого репозитория — в ту же (§8а п.3)'],
         'строка «Волна» §6')
need(BASE, unit(b, '\n3. Зависимые полосы — в одну волну', r'\n\d+\. '),
     ['зависимая другого репозитория — тоже: пин — на ревизию производителя с опубликованным образом, до его вливания — последний опубликованный, перенос — строкой; проба «пин модуля = тег образа» остаётся'],
     '§8а п.3')
need(BASE, unit(b, '\n8. Повтор ревью — только ролями с ⛔', r'\n\d+\. |\n\n'),
     ['только по `git diff <прошлая голова>..<новая>` и лишь при дельте, меняющей предмет ревью'], '§8а п.8 (один круг)')
p9 = unit(b, '\n9. Волна одним проходом', r'\n\n|\n\d+\. ')
if not p9:
    finds.append('%s: §8а п.9 «Волна одним проходом» нет' % BASE)
else:
    need(BASE, p9, ['`ai-tooling.md#at-one-pass-wave`',
                    'до кода, ≤ 45 мин, — предполёт `wave.js`: карта влияния, критерии рецензентов, поверхность (`security-auditor`), консультация схемы, имитация клиента по замыслу смены контракта',
                    'пункт карты закрывает та же полоса правкой либо «не затронуто — потому что …», чужого класса — полосой его исполнителя',
                    'прошедшая полоса — сразу в пробную сборку, CI — только на сведённом',
                    'механика — скриптами (`ci-read.sh`, один перезапуск отказа среды, `merge-readiness.sh`)',
                    'каскад щадит держателя ведомости (до ws#1052 — сверка вручную)',
                    'метрики — `reports/metrics.json`, сверка с оценкой предполёта, цель — 0 красных на сведённом',
                    '· Зависимый поправлен лишь после красного сведённого; второй PR в ветку эпика при незакрытой волне и BASE-STALE у соседних; пункт чужого класса без полосы'],
         '§8а п.9')

# C. шаблон волны: провязка и ПОЗИЦИЯ предполёта.
w = texts[WAVE]
meta_end = w.find('\n}\n')
mp, ml = w.find("{ title: 'Предполёт'"), w.find("{ title: 'Полосы'")
if not (0 <= mp < ml < meta_end):
    finds.append("%s: meta — фазы «Предполёт» до «Полосы» нет" % WAVE)
bp, bpre, bl = w.find("phase('Предполёт')"), w.find("agentType: 'scout', label: 'preflight'"), w.find("phase('Полосы')")
if not (0 <= bp < bpre < bl):
    finds.append("%s: предполёт (phase и scout preflight) не стоит в теле ДО фазы «Полосы»" % WAVE)
need(WAVE, w, ["if (noMap.length) return { ok: false, stage: 'предполёт",
               "+ mapText(l) + '\\n' + FILES_RULE",
               "'issues', 'impact', 'report', 'lesson'] }",
               'if (r.ok) r = await trialIn(l, r)',
               "`git push --dry-run origin HEAD:refs/heads/' + l.branch + '`",
               "const METRICS = R + '/metrics.json'",
               "label: 'mech:metrics'",
               '; КРОМЕ держателей записей ведомостей',
               'пин — на ревизию производителя с опубликованным образом (ветки волны образов не публикуют)',
               'Пункт чужого класса (консоль — ui-implementer) назови классом: его закрывает отдельная полоса этого исполнителя в ЭТОЙ волне'], 'провязка волны одним проходом')
need(PROBE, texts[PROBE], ["console.log('== волна одним проходом (ws#1053): предполёт, карта влияния, пробная сборка, метрики')",
                           'mutant "предполёт не зовётся"', 'mutant "пробной сборки нет"',
                           'mutant "пин на ветку без образа"', 'mutant "пункт чужого класса — без своей полосы"'],
     'поведение доказывается исполнением шаблона')

# D. каскад.
need(GO, texts[GO], ['держатель ведомости каскадом не закрывается (ws#1053',
                     'на задаче держится запись — задачу не закрываю',
                     'Сверка вручную — до посадки стража ws#1052'], 'каскад щадит держателя ведомости')

print('[CENSUS] %s: носителей осмотрено %d (правило, архив, база, git-operator, шаблон, проба шаблона); находок %d'
      % (name, len(texts), len(finds)))
for f in finds:
    print('[FAIL] %s — %s' % (name, f), file=sys.stderr)
if finds:
    sys.exit(1)
print('[PASS] %s — волна одним проходом провязана: норма с признаком в правиле и архиве, §3/§6/§8а базы, '
      'предполёт до полос в wave.js с картой, пробной сборкой и метриками, каскад щадит держателя' % name)
PY
