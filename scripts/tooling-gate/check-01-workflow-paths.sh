#!/usr/bin/env bash
# check-01 — каждый путь ЭТОГО репозитория, названный конвейером, существует.
#
# Что запрещает эта проверка: шаг конвейера, который называет файл, удалённый
# другим коммитом. Такая ссылка не конфликтует ни с чем при мёрже и обнаруживает
# себя только на прогоне, а часть шагов проглатывает её молча — например
# «информационный» линт под `|| true` остаётся зелёным и когда файла нет вовсе,
# потому что `|| true` не различает «замечаний нет» и «читать было нечего».
# Поэтому существование проверяется ОТДЕЛЬНО от того шага, который файл читает.
#
# Предпосылка проверки (объявляется исходом VOID): в дереве есть файлы конвейера
# и в них есть хоть одна ссылка на путь этого репозитория. Пропала предпосылка —
# это находка, а не успех.
set -euo pipefail

# shellcheck source=_lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/_lib.sh"

WS="$(tooling_gate_workspace_root)"
NAME="check-01-workflow-paths"

mapfile -t WORKFLOWS < <(tooling_gate_files "$WS" '.github/workflows/*')
if [ "${#WORKFLOWS[@]}" -eq 0 ]; then
    tooling_gate_void "$NAME" "файлов конвейера в дереве нет — проверять нечего"
    exit 2
fi

mapfile -t TOPLEVEL < <(tooling_gate_toplevel "$WS")
if [ "${#TOPLEVEL[@]}" -eq 0 ]; then
    tooling_gate_void "$NAME" "словарь элементов верхнего уровня пуст — опознать путь репозитория нечем"
    exit 2
fi

is_repo_claim() {
    # Токен претендует на путь В ЭТОМ репозитории, если он либо явно относителен
    # (`./x`), либо начинается с отслеживаемого элемента верхнего уровня. Первое
    # правило существует ровно ради удалённого файла верхнего уровня: его имени
    # в словаре уже нет, и без «./» он опознан бы как посторонняя строка —
    # то есть ровно тот случай, который проверка обязана ловить.
    local tok="$1" first
    case "$tok" in
        ./*) return 0 ;;
    esac
    first="${tok%%/*}"
    local t
    for t in "${TOPLEVEL[@]}"; do
        [ "$first" = "$t" ] && return 0
    done
    return 1
}

refs=0
findings=0
for wf in "${WORKFLOWS[@]}"; do
    lineno=0
    while IFS= read -r line; do
        lineno=$((lineno + 1))
        # `uses:` адресует чужое действие (`actions/checkout@v4`), а не путь;
        # `repository:` — чужой репозиторий. Ни то, ни другое не является
        # утверждением о собственном дереве.
        case "$line" in
            *uses:*|*repository:*) continue ;;
        esac
        # URL целиком снимается: в нём косые черты, но путь он адресует не здесь.
        cleaned="$(printf '%s' "$line" | sed -E 's#[a-z]+://[^[:space:]"'"'"']+##g')"
        for raw in $(printf '%s' "$cleaned" | tr -s " \t\"'\`,;()<>{}[]" '\n'); do
            # Хвостовая пунктуация прозы и экранирующая косая: внутри
            # двойных кавычек шага бэктик пишется как \` и прилипает к имени
            # файла. Обрезка нужна ради ЛОЖНОГО ОТРИЦАНИЯ гейта, а не ради
            # мягкости: без неё существующий путь читался бы как отсутствующий,
            # и первое же такое срабатывание отключило бы проверку целиком.
            tok="$(printf '%s' "$raw" | sed -E 's/[.,;:\\]+$//')"
            case "$tok" in
                */*) : ;;
                *) continue ;;
            esac
            case "$tok" in
                /*|*@*|*'*'*|*'$'*|*'{'*) continue ;;   # абсолютный / версия / шаблон / подстановка
            esac
            is_repo_claim "$tok" || continue
            refs=$((refs + 1))
            path="${tok#./}"
            if [ ! -e "$WS/$path" ]; then
                tooling_gate_fail "$NAME" "$wf:$lineno — конвейер называет '$tok', которого в дереве нет"
                findings=$((findings + 1))
            fi
        done
    done < "$WS/$wf"
done

tooling_gate_census "$NAME: прочитано файлов конвейера ${#WORKFLOWS[@]}, разобрано ссылок на пути репозитория $refs"

if [ "$refs" -eq 0 ]; then
    tooling_gate_void "$NAME" "ни одной ссылки на путь репозитория не разобрано — предикат остался без предмета"
    exit 2
fi

if [ "$findings" -gt 0 ]; then
    tooling_gate_fail "$NAME" "находок $findings"
    exit 1
fi

tooling_gate_pass "$NAME" "осмотрено ссылок $refs, находок 0"
