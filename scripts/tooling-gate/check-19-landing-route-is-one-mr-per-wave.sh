#!/usr/bin/env bash
# check-19 — МАРШРУТ ПОСАДКИ И СРОК ЗАВЕДЕНИЯ ЗАДАЧИ О БЕЗОПАСНОСТИ, записанные
# в корпусе, соответствуют РЕШЕНИЯМ ВЛАДЕЛЬЦА 2026-09-20.
#
# ЧТО УТВЕРЖДАЕТ — два разных утверждения, ни одно не выводится из другого.
#
#   ОСЬ A. НОРМА НА МЕСТЕ. База маршрутизации `.claude/agents/dispatcher.md` несёт
#   обе дословные цитаты владельца («не забывай агрегировать мр = волна» и «не
#   забывай по ходу создавать задачи в гитхаб ишуе если это важное и влияет на
#   безопасность»), а правило `.claude/rules/git-issues.md` — нормы, которыми они
#   записаны (`gi-wave-one-mr`, `gi-no-pr-per-lane`, `gi-security-finding-issue-now`).
#   Цитата, а не пересказ, взята якорем намеренно: пересказ переживает снятие
#   своего основания молча, цитата — нет, а база диспетчера правится чаще любого
#   другого файла корпуса, и норма исчезает из неё одной строкой диффа.
#
#   ОСЬ B. ОТМЕНЁННЫЙ МАРШРУТ НЕ ЧИТАЕТСЯ ДЕЙСТВУЮЩИМ. Решение 2026-09-17 «заливай
#   сразу в мастер» в части «PR прямо в `main` без накопительной ветки, слияние
#   сразу по зелёному CI» ОТМЕНЕНО решением 2026-09-20. Строка корпуса вправе его
#   называть — но только вместе с пометкой отмены В ТОЙ ЖЕ СТРОКЕ. Строка,
#   называющая отменённый маршрут без пометки, читается исполнителем как
#   действующее основание: именно это и стоило нам россыпи PR в ствол.
#
#   ПРЕДМЕТ ОСИ B — ЧЕТЫРЕ ЛИТЕРАЛА, А НЕ «ПРОЗА ПРО ПОСАДКУ», и это сужение
#   намеренное. Пересказ отменённого маршрута своими словами — множество, деревом
#   не производимое: сколько его ни перечисляй, форма вне перечня даёт не красное
#   и не зелёное, а молчание. Поэтому гейт судит ровно те записи, которыми корпус
#   отменённый маршрут ФАКТИЧЕСКИ несёт (перечень выведен обходом, см. ниже), и
#   граница названа в README, а не умолчана.
#
# ПОЧЕМУ ЭТО ВООБЩЕ ГЕЙТ, А НЕ ПОЖЕЛАНИЕ. Оба разрыва МОЛЧАЛИВЫ: ни один прогон
# продукта, ни одна проверка дерева не меняется от того, что норма выпала из базы
# или что отменённый маршрут остался стоять рядом с действующим. Обнаруживается
# это поведением агентов — то есть на следующей волне и ценой волны.
#
# ЧЕГО ЭТОТ ГЕЙТ НЕ ДЕРЖИТ, И ГРАНИЦА ОБЪЯВЛЕНА, А НЕ УМОЛЧАНА. Он судит ТЕКСТ
# корпуса, а не git: ни «в стволе открыто два PR одной волны», ни «ветка полосы
# отправлена мимо сборки» отсюда не видны — у этого дерева нет ни сети, ни права
# спрашивать `gh`, а вердикт, зависящий от сети, приходит по жребию. Порядок
# сборки волны держится вниманием `git-operator` и приёмкой посадки; здесь
# держится только то, что НОРМА ЖИВА И ОДНА.
#
# СЛЕПЫЕ ЗОНЫ ОСИ B НАЗВАНЫ ПОИМЁННО И ЗАМЕРЕНЫ, А НЕ ОБЕЩАНЫ ЗАКРЫТЫМИ.
#
#   1. Признак строчный. Абзац, где отменённый маршрут стоит одной строкой, а
#      пометка отмены — соседней, гейт пропустит. Строчный признак выбран потому,
#      что читатель корпуса принимает решение по строке, а расширение до абзаца
#      сделало бы пометку, стоящую за десять строк, оправданием любой строки.
#
#   2. Пересказ мимо всех четырёх литералов — МОЛЧАНИЕ, и это измерено. Строка
#      `- Полоса сама отправляет ветку на origin и открывает свой PR в ствол.`
#      восстанавливает отменённый порядок целиком и ни одного литерала не
#      содержит: гейт на ней зелен. Машинно это не закрывается — перечень
#      пересказов не выводится обходом дерева, а сочиняется пишущим. Держится
#      вниманием `landing-reviewer` и `wave-reviewer`, читающих базу перед
#      посадкой; здесь оно записано, чтобы следующий не открывал заново.
#
# ПОЧЕМУ ЭТИ ТРИ ДЕФЕКТА ТЕПЕРЬ ЛОВЯТСЯ (перемер 2026-09-20, первая редакция
# молчала на всех трёх):
#   * пересказ через «сразу по зелёному CI» — литерал добавлен в перечень;
#   * дословная цитата «заливай сразу в мастер», поданная действующей, — литерал
#     добавлен: это ИМЯ снятого решения, и переписать его нельзя, не потеряв
#     ссылку на решение;
#   * пометка отмены, стоящая в ОТРИЦАНИИ («этого никто не отменял»), — отрицания
#     вычитаются из строки ДО поиска пометки.
#
# ЧЕТВЁРТАЯ НАХОДКА ПЕРЕМЕРА — АРМА РАСПОЗНАВАТЕЛЯ БЕЗ ПРЕДМЕТА. В первой
# редакции перечень нёс `прямой PR`, не совпадающий НИ С ОДНОЙ строкой корпуса:
# рука вписала форму, которой в дереве нет, и гейт был уже своей шапки молча.
# Теперь у каждого литерала считается число строк, и литерал с нулём — находка,
# а не мелочь: два законных исхода у него те же, что у любого снятого предмета —
# снять арму вместе с предметом ОДНИМ изменением либо вернуть предмет.
#
# Коды выхода: 0 — обе оси сошлись; 1 — находка либо пустой обход; 2 — предмета
# нет (ни одного файла корпуса в этом дереве).

set -euo pipefail

# shellcheck source=_lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/_lib.sh"

WS="$(tooling_gate_workspace_root)"
NAME="$(basename "${BASH_SOURCE[0]}" .sh)"

BASE_REL=".claude/agents/dispatcher.md"
RULE_REL=".claude/rules/git-issues.md"

# ПРЕДМЕТ ОСИ B — закрытый перечень литералов, которыми корпус отменённый маршрут
# ФАКТИЧЕСКИ несёт. Перечень выводится обходом, а не памятью, и обход
# воспроизводим:
#
#   for f in $(git ls-files '.claude/*.md' CLAUDE.md); do \
#       grep -nE 'заливай сразу в мастер|прямо в `?main|без накопительной ветки|сразу по зелёному CI' "$f"; done
#
# Литерал, не совпадающий ни с одной строкой, — находка (см. ПРЕМИСС ниже), иначе
# перечень молча расходится с деревом, как разошёлся `прямой PR` в первой редакции.
REVOKED_SUBJECTS=(
    'заливай сразу в мастер'
    'прямо в `?main'
    'без накопительной ветки'
    'сразу по зелёному CI'
)
REVOKED_RE="$(printf '%s|' "${REVOKED_SUBJECTS[@]}")"; REVOKED_RE="${REVOKED_RE%|}"

# Пометка отмены. Регистр перечислен явно, а не снят `grep -i`: под LC_ALL=C
# регистронезависимость кириллицы не работает, и `-i` дал бы здесь тихий недобор.
MARK_RE='[Оо]тмен|ОТМЕН|[Оо]тозв|[Пп]озднейш|[Уу]старел|не служит основанием|основанием не служит'

# ОТРИЦАНИЕ ПОМЕТКИ — НЕ ПОМЕТКА. «эту часть никто НЕ отменял» содержит `отмен` и
# в первой редакции засчитывалось за отмену: строка, ПОДТВЕРЖДАЮЩАЯ действие
# снятого маршрута, читалась гейтом как его снятие — в точности наоборот. Формы
# перечислены литералами, а не диапазоном `[а-яё]*`: под LC_ALL=C диапазон
# кириллицы не работает, и вычет молча стал бы пустым.
NEG_RE='([Нн]икто )?не (отмен(яет|ял|яла|яли|ялась|ено|ена|ён|ена)|отозв(ан|ана|ано)|устарел(о|а|и)?)'

# Обход: ВЕСЬ markdown корпуса плюс общий протокол `CLAUDE.md` — его читают оба
# конца, и отменённый маршрут, записанный там, доезжает до каждого исполнителя.
mapfile -t DOCS < <(
    tooling_gate_files "$WS" '.claude/*.md'
    tooling_gate_files "$WS" 'CLAUDE.md'
)
if [ "${#DOCS[@]}" -eq 0 ]; then
    tooling_gate_void "$NAME" "markdown корпуса в дереве нет — предмета у проверки не существует"
    exit 2
fi
if [ ! -f "$WS/$BASE_REL" ] || [ ! -f "$WS/$RULE_REL" ]; then
    tooling_gate_void "$NAME" "нет $BASE_REL либо $RULE_REL — база маршрутизации и правило трекера здесь не живут, судить нечего"
    exit 2
fi

findings=0
lines_read=0
carriers=0
marked=0

# Перепись обязана говорить правду о том, ЧТО прочитано: `.claude/skills/rule-*/SKILL.md`
# — символьные ссылки на файлы `.claude/rules/`, и каждая такая пара приезжает в
# обход дважды. Двойной счёт слепой зоны не создаёт (содержимое то же), но число
# «файлов корпуса» без этой оговорки завышено, а число в переписи читают как факт.
# Форма `if`, а не `[ -L … ] && …`: под `set -e` AND-список, чей левый конец ложен
# на ПОСЛЕДНЕЙ итерации, делает ложным весь цикл и обрывает проверку молча — с
# кодом, который вызывающий прочитает как находку.
symlinks=0
for d in "${DOCS[@]}"; do
    if [ -L "$WS/$d" ]; then symlinks=$((symlinks + 1)); fi
done

# ── ОСЬ A: норма на месте ────────────────────────────────────────────────────
anchors_want=0
anchors_have=0
anchor() {   # <файл> <дословный якорь> <что он держит>
    anchors_want=$((anchors_want + 1))
    if grep -qF -- "$2" "$WS/$1"; then
        anchors_have=$((anchors_have + 1))
    else
        tooling_gate_fail "$NAME" "$1 — нормы нет: не найдено «$2» ($3). Решение владельца 2026-09-20 записано в корпусе только этим местом; выпав отсюда, оно перестаёт доезжать до кого бы то ни было"
        findings=$((findings + 1))
    fi
}

anchor "$BASE_REL" "не забывай агрегировать мр = волна" \
    "МР равен волне: сборка, прогон на сведённом, сверка полос рядом, ОДИН MR"
anchor "$BASE_REL" "не забывай по ходу создавать задачи в гитхаб ишуе если это важное и влияет на безопасность" \
    "задача о безопасности заводится по ходу работы, а не в конце волны"
anchor "$RULE_REL" "gi-wave-one-mr" "норма «волна уходит ОДНИМ MR»"
anchor "$RULE_REL" "gi-no-pr-per-lane" "норма «PR на полосу и отправка веток по отдельности запрещены»"
anchor "$RULE_REL" "gi-security-finding-issue-now" "норма «находка о безопасности — задачей НЕМЕДЛЕННО»"

# ── ОСЬ B: отменённый маршрут назван только вместе с пометкой отмены ──────────
declare -A subj_hits=()
for subj in "${REVOKED_SUBJECTS[@]}"; do subj_hits["$subj"]=0; done

for d in "${DOCS[@]}"; do
    n="$(wc -l < "$WS/$d")"
    lines_read=$((lines_read + n))
    while IFS= read -r hit; do
        [ -n "$hit" ] || continue
        ln="${hit%%:*}"
        text="${hit#*:}"
        carriers=$((carriers + 1))
        for subj in "${REVOKED_SUBJECTS[@]}"; do
            if printf '%s\n' "$text" | grep -qE -- "$subj"; then
                cur="${subj_hits["$subj"]}"
                subj_hits["$subj"]=$((cur + 1))
            fi
        done
        # Отрицания вычитаются ДО поиска пометки: остаток — то, что строка
        # УТВЕРЖДАЕТ, а не то, что в ней встречается.
        stripped="$(printf '%s' "$text" | sed -E "s/$NEG_RE//g")"
        if printf '%s\n' "$stripped" | grep -qE -- "$MARK_RE"; then
            marked=$((marked + 1))
        elif printf '%s\n' "$text" | grep -qE -- "$MARK_RE"; then
            tooling_gate_fail "$NAME" "$d:$ln — отменённый маршрут посадки назван, а пометка отмены стоит в ОТРИЦАНИИ («не отменял» / «не отозвано»): строка подтверждает снятый маршрут, а не снимает его: ${text:0:160}"
            findings=$((findings + 1))
        else
            tooling_gate_fail "$NAME" "$d:$ln — отменённый маршрут посадки назван БЕЗ пометки отмены: ${text:0:160}"
            findings=$((findings + 1))
        fi
    done < <(grep -nE -- "$REVOKED_RE" "$WS/$d" || true)
done

# ── ПРЕМИСС ОСИ B: у каждой армы распознавателя есть предмет ──────────────────
# Литерал, не встретившийся ни разу, — не «чисто», а слепая арма: гейт уже своей
# шапки, и молча. Исходов два и оба одним изменением: снять арму вместе с её
# предметом либо вернуть предмет в корпус.
for subj in "${REVOKED_SUBJECTS[@]}"; do
    if [ "${subj_hits["$subj"]}" -eq 0 ]; then
        tooling_gate_fail "$NAME" "распознаватель оси B несёт арму «$subj», не совпадающую НИ С ОДНОЙ строкой корпуса: перечень разошёлся с деревом, и гейт уже своей шапки. Снять арму вместе с предметом либо вернуть предмет — одним изменением"
        findings=$((findings + 1))
    fi
done

# ── ПЕРЕПИСЬ ОБЪЁМА — всегда и до вердикта ───────────────────────────────────
arm_census=""
for subj in "${REVOKED_SUBJECTS[@]}"; do arm_census+="«$subj» ${subj_hits["$subj"]}; "; done
tooling_gate_census "$NAME: файлов корпуса ${#DOCS[@]} (из них символьных ссылок на другой файл обхода $symlinks), строк $lines_read; строк с отменённым маршрутом $carriers, из них с пометкой отмены $marked; армы распознавателя — ${arm_census%; }; якорей нормы требовалось $anchors_want, найдено $anchors_have"

if [ "$lines_read" -eq 0 ]; then
    tooling_gate_void "$NAME" "файлы корпуса прочитаны, но пусты — предикат остался без предмета"
    exit 2
fi

if [ "$findings" -gt 0 ]; then
    tooling_gate_fail "$NAME" "находок $findings"
    exit 1
fi

tooling_gate_pass "$NAME" "прочитано строк $lines_read; норма 2026-09-20 на месте ($anchors_have якорей), отменённый маршрут назван $carriers раз и каждый раз с пометкой отмены"
