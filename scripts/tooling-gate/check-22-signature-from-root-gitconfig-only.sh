#!/usr/bin/env bash
# check-22 — ПОДПИСЬ ГИТА БЕРЁТСЯ ТОЛЬКО ИЗ КОРНЕВОГО GITCONFIG, И В ПЕСОЧНИЦЕ
# ПРОБЫ ТОЖЕ.
#
# ПРЕДМЕТ. П.7 правила подписи (`.claude/rules/git-issues.md`,
# gi-identity-owner-only): author и committer — только корневой gitconfig;
# переопределение на команду, на репозиторий и окружением запрещено. Решение
# диспетчера 2026-09-27 (ws#785): норма действует и на песочницы проб, в том
# числе на те, что на origin не попадают никогда, — оговорки для них нет.
# Подпись песочницы — её HOME со своим `.gitconfig`, в котором та же корневая
# учётная запись (`scripts/lib/sandbox-git-home.sh`).
#
# ПОЧЕМУ СТРАЖ ПО ДЕРЕВУ, А НЕ ПО ИСТОРИИ. Держатель нормы — `git log --format=
# '%an %ae'` — видит только то, что доехало до истории. Песочница пробы в историю
# не попадает, и её переопределение держатель не увидит никогда: форма живёт в
# исполняемом коде дерева и копируется следующей пробой как образец. Поэтому
# судится код: оболочка, Python, конвейер — все отслеживаемые файлы этих видов,
# без исключений по роли и по пути.
#
# ФОРМЫ И ЗАКОННЫЕ БЛИЗНЕЦЫ — в шапке распознавателя `signature_forms.py`. Время
# коммита (`GIT_AUTHOR_DATE`, `GIT_COMMITTER_DATE`) подписью не является и не
# судится: держатель п.7 меряет имя и почту.
#
# ПРЕДПОСЫЛКА (VOID, код 2): индекс git читается и в дереве есть хотя бы один
# файл судимых видов; Python-файл, который не разобрался, — тоже VOID для себя
# (вердикта о нём нет), если находок нет вовсе.
#
# Коды: 0 — находок нет; 1 — находка с координатой; 2 — предмета нет.
set -uo pipefail

name="$(basename "${BASH_SOURCE[0]}" .sh)"
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
root="${TOOLING_GATE_ROOT:-$(cd "$here/../.." && pwd)}"

exec python3 "$here/signature_forms.py" "$root" "$name"
