#!/usr/bin/env bash
# check-08 — ВЫЗЫВАЮЩИЙ читает три исхода набора, а не два.
#
# Соседи `check-04` и `check-07` судят ПРОГОНЩИКА: что он не засчитывает
# беспредметность за успех и отдаёт её кодом, отличным от кода находки. Оба
# молчат о том, что с этим кодом делает тот, кто прогонщика зовёт, — а различие
# заводилось ради вызывающего и без него бесполезно: код 2, прочитанный как
# «любое ненулевое», блокирует отправку ровно так же, как единица, и вся правка
# ws#458 сводится к смене цифры в выводе.
#
# ВЫЗЫВАЮЩИЙ ЗДЕСЬ ОДИН И НАЗВАН: хук отправки `scripts/hooks/pre-push`. Конвейер
# в предмет не входит намеренно — он зовёт прогонщики шагом `run:` под `bash -e`,
# где любой ненулевой код роняет job, и это верное поведение: предпосылку там
# создаёт сама job'а (клон продукта выкладывается её шагом), поэтому VOID в
# конвейере есть поломка, а не факт расписания. Различие делает не `if`, а то,
# КТО спрашивает.
#
# ЧТО ТРЕБУЕТСЯ ОТ ХУКА — четыре утверждения, и третье двойное:
#
#   все наборы 0        → хук выходит 0 (положительный контроль; иначе VOID);
#   какой-то набор 1    → хук выходит 1 — отправка ОСТАНОВЛЕНА;
#   какой-то набор 2    → хук выходит 0 — отправку НЕ останавливает,
#                         И его завершающая строка ОТЛИЧАЕТСЯ от строки чистого
#                         прогона: «не выполнилось» в успех не засчитано;
#   наборы 1 и 2 вместе → хук выходит 1 (АНТИМАСКА).
#
# ПОЧЕМУ «ОТЛИЧАЕТСЯ ОТ СТРОКИ ЧИСТОГО ПРОГОНА», А НЕ ПОИСК СЛОВА. Искать в
# выводе фразу значит закреплять формулировку: её перепишут, и проверка покраснеет
# на верном хуке — а такую отключают первой. Спрашивается ПОВЕДЕНИЕ: два разных
# исхода обязаны быть различимы для читателя. Совпадение завершающих строк и есть
# ровно то, что запрещено, — беспредметный прогон, отрапортовавший себя чистым.
#
# ПОЧЕМУ ПОВЕДЕНЧЕСКАЯ, А НЕ ТЕКСТОВАЯ. Искать в исходнике `case $? in 2)` значит
# ловить форму: хук волен считать исходы в массив, вынести разбор в функцию,
# назвать переменную иначе. Рядом с копией хука в песочнице кладутся прогонщики с
# ЗАДАННЫМИ кодами, и читается то, что хук вернул и напечатал.
#
# ПРЕДПОСЫЛКА (исход VOID): вызывающий есть в дереве, песочница строится, и его
# копия отвечает НУЛЁМ на наборах, которые все зелены. Хук, красный даже на них,
# к остальным пробам непригоден — они прошли бы на нём тождественно и не доказали
# бы ничего.
set -euo pipefail

# shellcheck source=_lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/_lib.sh"

WS="$(tooling_gate_workspace_root)"
NAME="check-08-caller-reads-the-three-outcomes"
CALLER="scripts/hooks/pre-push"

mapfile -t CALLERS < <(tooling_gate_files "$WS" "$CALLER")
if [ "${#CALLERS[@]}" -eq 0 ]; then
    tooling_gate_void "$NAME" "вызывающего $CALLER в дереве нет — проверять нечего"
    exit 2
fi

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# probe <вызывающий> <код>… — печатает «<код выхода>|<завершающая строка>» для
# песочницы, где лежит по одному прогонщику на каждый переданный код.
#
# Песочница — СВОЙ репозиторий во временном каталоге, и трогать он может только
# себя: хук выводит корень через `git rev-parse --show-toplevel`, а перечень
# наборов — через `git ls-files`, поэтому без индекса он не найдёт ничего. Все
# обращения к git идут с явным `-C`, а переменные окружения git снимаются перед
# запуском: унаследованный `GIT_DIR` сильнее рабочего каталога и увёл бы запись в
# ЭТУ рабочую копию.
#
# Коммит делается пустым и «через силу не берётся»: на машине без объявленной
# личности он не состоится, HEAD останется неродившимся, и хук получит пустое имя
# ветки — черновиком (`wip/`, `tmp/`) оно не является, поэтому путь пробы тот же.
probe() {
    local caller="$1"; shift
    local dir i=90 rc out code
    dir="$(mktemp -d "$TMP/p.XXXXXX")"
    mkdir -p "$dir/scripts/hooks"
    cp "$WS/$caller" "$dir/scripts/hooks/pre-push"
    chmod +x "$dir/scripts/hooks/pre-push"
    for rc in "$@"; do
        mkdir -p "$dir/scripts/stub-$i"
        printf '#!/usr/bin/env bash\necho "stub-%s: исход %s"\nexit %s\n' "$i" "$rc" "$rc" \
            > "$dir/scripts/stub-$i/run-all.sh"
        chmod +x "$dir/scripts/stub-$i/run-all.sh"
        i=$((i + 1))
    done
    git -C "$dir" init -q
    git -C "$dir" add -A -f >/dev/null 2>&1
    git -C "$dir" commit -q --allow-empty -m fixture >/dev/null 2>&1 || true

    out="$(
        cd "$dir" || exit 111
        unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
              GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_COMMON_DIR GIT_PREFIX \
              KACHO_MONOREPO KACHO_SKIP_PREPUSH
        bash ./scripts/hooks/pre-push 2>&1
    )"; code=$?
    printf '%s|%s\n' "$code" "$(printf '%s\n' "$out" | grep -v '^[[:space:]]*$' | tail -1)"
}

findings=0
examined=0
for caller in "${CALLERS[@]}"; do
    green="$(probe "$caller" 0 0)"
    if [ "${green%%|*}" -ne 0 ]; then
        tooling_gate_void "$NAME" \
            "$caller — на наборах, которые ВСЕ зелены, вернул ${green%%|*}; остальные пробы на нём недоказательны"
        exit 2
    fi
    green_tail="${green#*|}"
    examined=$((examined + 1))

    find_rc="$(probe "$caller" 0 1)"
    if [ "${find_rc%%|*}" -ne 1 ]; then
        tooling_gate_fail "$NAME" \
            "$caller — набор вернул НАХОДКУ (1), вызывающий вышел ${find_rc%%|*} вместо 1: отправка не остановлена"
        findings=$((findings + 1))
    fi

    void_rc="$(probe "$caller" 0 2)"
    if [ "${void_rc%%|*}" -ne 0 ]; then
        tooling_gate_fail "$NAME" \
            "$caller — набор остался БЕЗ ПРЕДМЕТА (2), вызывающий вышел ${void_rc%%|*} вместо 0: условие не создано, а отправка остановлена как на находке"
        findings=$((findings + 1))
    elif [ "${void_rc#*|}" = "$green_tail" ]; then
        tooling_gate_fail "$NAME" \
            "$caller — беспредметный прогон закончился ТОЙ ЖЕ строкой, что и чистый («${green_tail}»): «не выполнилось» подано как успех"
        findings=$((findings + 1))
    fi

    # Антимаска: находка рядом с беспредметным набором обязана остановить отправку.
    mixed_rc="$(probe "$caller" 1 2)"
    if [ "${mixed_rc%%|*}" -ne 1 ]; then
        tooling_gate_fail "$NAME" \
            "$caller — находка РЯДОМ с беспредметным набором дала ${mixed_rc%%|*} вместо 1: «без предмета» стало маской для нарушения"
        findings=$((findings + 1))
    fi
done

tooling_gate_census "$NAME: вызывающих осмотрено $examined (по четыре пробы на каждого — всё зелено, находка, без предмета, находка+без предмета)"

if [ "$findings" -gt 0 ]; then
    tooling_gate_fail "$NAME" "проб с находкой: $findings"
    exit 1
fi

tooling_gate_pass "$NAME" "у всех $examined вызывающих находка останавливает отправку, отсутствие предмета — нет, и беспредметный прогон не выдаётся за чистый"
