#!/usr/bin/env bash
# check-12 — ПРЕДИКАТ, ВЫПИСАННЫЙ ДЛЯ ПРОГОНА РУКАМИ, ОБЯЗАН ДАВАТЬ ОДИН И ТОТ ЖЕ
# ВЕРДИКТ В ОБОИХ ДВИЖКАХ `grep`, КОТОРЫЕ ЕСТЬ В ЭТОМ ВОРКСПЕЙСЕ.
#
# ЗАМЕР, РАДИ КОТОРОГО ПРОВЕРКА ЗАВЕДЕНА (2026-09-21, воспроизводим командой).
# В Bash-инструменте агента имя `grep` разрешается НЕ в бинарь: харнесс Claude
# Code (2.1.278) определяет в стартовой оболочке функцию-обёртку, которая зовёт
# свой встроенный ugrep 7.8.4 с принудительным `-G`. Предикат:
#
#     type -t grep            # -> function      (в Bash-инструменте агента)
#     command grep --version  # -> GNU grep 3.12 (настоящий /usr/bin/grep)
#     bash -c 'type -t grep'  # -> file          (функция НЕ экспортируется)
#
# Отсюда два следствия, и второе опаснее первого:
#   1. дочерний процесс — а значит КАЖДЫЙ скрипт набора и КАЖДЫЙ шаг конвейера —
#      получает GNU grep; расхождение живёт только там, где команду набирают
#      руками в инструменте;
#   2. на части образцов ugrep отдаёт ПУСТО и код 1 там, где GNU находит строку.
#      Пусто и код 1 — это «не найдено», то есть ФАКТ о дереве. Ни ошибки, ни
#      предупреждения не печатается, и перепись, построенная на таком образце,
#      состоит из ложных отрицаний целиком.
#
# ФОРМА РАСХОЖДЕНИЯ ИЗМЕРЕНА, А НЕ УГАДАНА. Расходится образец, у которого ЯКОРЬ
# СТОИТ ВЕТВЬЮ АЛЬТЕРНАТИВЫ внутри группы. Замер на строке `x-NNNN-z`, литерал
# после группы длиной от 1 до 8 знаков: длины 1, 2, 3, 5, 6, 7, 8 сходятся, а на
# длине 4 обёртка отдаёт пусто, и GNU — находку. Ни цифры, ни буквы значения не
# имеют; сходится и `([^0-9])NNNN` без альтернативы. То есть ловушка зависит от
# ШИРИНЫ совпадения, и запомнить, на какой ширине пишущий сейчас находится,
# нельзя. Поэтому запрещается форма целиком, а не «опасная её часть»: цена
# запрета — одна лишняя буква `P` в команде, цена пропуска — молчаливый ноль.
#
# ЧТО ПИСАТЬ ВМЕСТО. Граница слова: `grep -P '(?<![0-9])N(?![0-9])'` либо
# `\bN\b` — обе формы сошлись в обоих движках на всех замеренных длинах.
#
# ПРЕДМЕТ И ЕГО ГРАНИЦА. Судится ТОЛЬКО то, что прогоняют руками: всякая строка
# файла `.md` и КОММЕНТАРИЙ в `.sh`/`.py` внутри `.claude/**`, `scripts/**` и
# корневого `CLAUDE.md`. Исполняемая строка скрипта НЕ судится, и это не
# послабление: она исполняется дочерним bash, то есть настоящим GNU grep, —
# запрещать там форму значило бы запрещать запись, которая в своём доме верна
# (`gate-authoring` §«Отношение, выполнимое подстановкой, не сужает ничего»).
#
# ПРИЗНАК ИСКЛЮЧАЕТ СЕБЯ ДВУМЯ СПОСОБАМИ, И ОБА ОБЪЯВЛЕНЫ.
#   · Распознаватель требует вызова grep-семейства НА ТОЙ ЖЕ строке. Примеры
#     формы в этой шапке стоят на строках без такого вызова и потому находками
#     не являются. Если их когда-нибудь сольют в одну строку с командой — гейт
#     покраснеет на самом себе, и это ВЕРНЫЙ исход: строка станет ровно тем, что
#     запрещено.
#   · Харнессы инъекции (`inject*.sh`) исключены по роли: они СТРОЯТ дефект, и
#     строка, вносящая его, обязана нести запрещённую форму. Число исключённых
#     файлов печатается переписью — «исключено 0» обязано быть отличимо от
#     «исключение сработало молча».
#
# ТРИ ИСХОДА. 0 — обход непуст, находок нет; 1 — находка либо пустой обход;
# 2 — предмета нет (в дереве не нашлось ни одного файла области).
set -uo pipefail

# САМОИМЯ ВЫВОДИТСЯ ИЗ ИМЕНИ ФАЙЛА, А НЕ ПИШЕТСЯ ЛИТЕРАЛОМ. Здесь стоял
# литерал `check-10-…`, и переномерацию 2026-09-22 он пережил бы МОЛЧА:
# файл `check-12-…` печатал бы вердикт о `check-10`, а читающий пошёл бы
# искать гейт, которого в наборе нет. Признак проверяется переименованием.
name="$(basename "${BASH_SOURCE[0]}" .sh)"
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=/dev/null
. "$here/_lib.sh" 2>/dev/null || true
root="${TOOLING_GATE_ROOT:-$(cd "$here/../.." && pwd)}"

python3 - "$root" "$name" <<'PY'
import re, sys, pathlib, subprocess

root = pathlib.Path(sys.argv[1]); name = sys.argv[2]

try:
    listing = subprocess.run(
        ["git", "-C", str(root), "ls-files", "--cached", "--others", "--exclude-standard"],
        capture_output=True, text=True, check=True).stdout.split("\n")
except (subprocess.CalledProcessError, FileNotFoundError):
    print(f"[VOID] {name} — индекс git не читается, состав дерева не выведен", file=sys.stderr)
    sys.exit(2)

AREA = (".claude/", "scripts/")
def in_area(p):
    return p == "CLAUDE.md" or p.startswith(AREA)

# Архив называет координаты, верные на момент снятия, и живым предписанием не
# является — та же граница, что у `claudeMdExcludes` и `TRUTH_EXCLUDE`.
def excluded(p):
    return p.startswith(".claude/backup/") or pathlib.PurePath(p).name.startswith("inject")

paths = [p for p in listing if p and in_area(p)]
subject = [p for p in paths if not excluded(p)]
skipped = len(paths) - len(subject)
if not subject:
    print(f"[VOID] {name} — файлов области не найдено, судить нечего", file=sys.stderr)
    sys.exit(2)

GREP_CALL = re.compile(r"(?<![\w-])(?:grep|egrep|ugrep|zgrep)(?![\w-])")
# Якорь ветвью альтернативы: открывающая скобка — захватывающая или нет —
# сразу с якорем, либо якорь сразу перед закрывающей. `\$` внутри одинарных
# кавычек — тот же якорь. Незахватывающая скобка внесена в распознаватель
# отдельно: без неё та же форма проходила бы молча, а молчание на законной
# форме предмета и есть слепая зона.
ANCHOR_ALT = re.compile(r"\((?:\?:)?(?:\^|\\?\$)\||\|(?:\^|\\?\$)\)")
COMMENT = re.compile(r"^\s*#")

findings = []
files_read = 0
lines_read = 0
handrun_lines = 0
for rel in subject:
    f = root / rel
    try:
        text = f.read_text(encoding="utf-8", errors="replace")
    except (OSError, IsADirectoryError):
        continue
    files_read += 1
    prose = f.suffix in (".md", ".txt", ".json", ".yaml", ".yml") or f.suffix == ""
    for i, line in enumerate(text.split("\n"), 1):
        lines_read += 1
        handrun = prose or COMMENT.match(line)
        if not handrun:
            continue
        if not GREP_CALL.search(line):
            continue
        handrun_lines += 1
        if ANCHOR_ALT.search(line):
            findings.append((rel, i, line.strip()))

print(f"[CENSUS] {name}: файлов области {files_read} (исключено по роли и архиву {skipped}); "
      f"строк {lines_read}; предикатов для прогона руками {handrun_lines}; находок {len(findings)}")

if handrun_lines == 0:
    print(f"[VOID] {name} — ни одного выписанного предиката не найдено: "
          f"обход прошёл, но предмета в нём нет", file=sys.stderr)
    sys.exit(2)

if findings:
    print(f"[FAIL] {name} — выписанный предикат несёт якорь ветвью альтернативы: "
          f"в обёртке `grep` агента такой образец молча не совпадает", file=sys.stderr)
    for rel, i, line in findings:
        print(f"       {rel}:{i}: {line[:160]}", file=sys.stderr)
    print("       чинится подстановкой границы слова: -P '(?<![0-9])N(?![0-9])' либо \\bN\\b",
          file=sys.stderr)
    sys.exit(1)

print(f"[PASS] {name} — все {handrun_lines} выписанных предикатов свободны от формы, "
      f"на которой два движка расходятся")
PY
