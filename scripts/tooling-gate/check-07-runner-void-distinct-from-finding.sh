#!/usr/bin/env bash
# check-07 — «без предмета» ни у одного прогонщика не приходит тем же кодом, что
# находка.
#
# Что запрещает эта проверка. Сосед `check-04` требует от прогонщика ровно одного:
# чтобы «проверить не удалось» не засчитывалось за «пройдено», то есть давало
# ЛЮБОЙ ненулевой код. Этого достаточно, чтобы беспредметный набор не зеленел, и
# НЕДОСТАТОЧНО, чтобы вызывающий мог с ним что-то сделать: единица от находки и
# единица от отсутствия предмета неразличимы, а решения по ним прямо
# противоположные.
#
#   находка          → отправку остановить, дефект чинить;
#   без предмета      → отправку пропустить, условие создать (клон продукта,
#                       разборщик, инструмент) — в дереве чинить нечего.
#
# Цена неразличения измерена (ws#458): из рабочей копии воркспейса без клона
# продукта три набора из четырёх возвращали единицу, беспредметных проверок было
# пять. То есть красное приходило КАЖДУЮ отправку и по причине, к дереву не
# относящейся. Красное, приходящее всегда, перестают читать — и вместе с ним
# перестают читать настоящую находку.
#
# Договорённость о кодах, которую проверка закрепляет как свойство ДЕРЕВА, а не
# сегодняшних четырёх прогонщиков: 0 — прошло, 1 — находка, 2 — без предмета.
#
# ЧЕТВЁРТАЯ ПРОБА — АНТИМАСКА, И ОНА ЗДЕСЬ ГЛАВНАЯ. Набор, где есть И находка, И
# беспредметная проверка, обязан ответить ЕДИНИЦЕЙ. Прогонщик, объявляющий
# беспредметность раньше находки, превратил бы новый код в способ молча
# пропускать нарушения: хватило бы одной проверки без предмета, чтобы настоящая
# находка перестала блокировать отправку. Без этой пробы правка ws#458 открывала
# бы дыру ровно там, где закрывала шум.
#
# Проверка ПОВЕДЕНЧЕСКАЯ, а не текстовая — по той же причине, что и у check-04:
# искать в исходнике `exit 2` значит ловить форму. Прогонщик волен считать исходы
# в массив, вынести вердикт в функцию, назвать переменную иначе. Спрашивается
# ИСХОД: рядом с копией прогонщика в песочнице кладутся заглушки с заданными
# кодами, и читается код, который прогонщик вернул.
#
# Предпосылка проверки (исход VOID): в дереве есть хотя бы один прогонщик
# `scripts/*/run-all.sh`, и его копия в песочнице отвечает нулём на единственной
# ПРОЙДЕННОЙ проверке. Прогонщик, красный даже на ней, к остальным пробам
# непригоден — они прошли бы на нём тождественно и ничего не доказали.
set -euo pipefail

# shellcheck source=_lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/_lib.sh"

WS="$(tooling_gate_workspace_root)"
NAME="check-07-runner-void-distinct-from-finding"

mapfile -t RUNNERS < <(tooling_gate_files "$WS" 'scripts/*/run-all.sh')
if [ "${#RUNNERS[@]}" -eq 0 ]; then
    tooling_gate_void "$NAME" "прогонщиков scripts/*/run-all.sh в дереве нет — проверять нечего"
    exit 2
fi

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# probe <прогонщик> <код>… — печатает код выхода прогонщика в песочнице, где
# лежит по одной заглушке на каждый переданный код.
#
# Имена заглушек подходят под глоб ЛЮБОГО прогонщика набора (`check-*.sh` у трёх,
# `check-*` + бит исполнения у docs-gate), поэтому бит ставится всегда. Заглушки
# молчат: вердикт берётся только из кода выхода, печать на него не влияет.
probe() {
    local runner="$1"; shift
    local dir i=90 rc
    dir="$(mktemp -d "$TMP/p.XXXXXX")"
    cp "$WS/$runner" "$dir/run-all.sh"
    chmod +x "$dir/run-all.sh"
    for rc in "$@"; do
        printf '#!/usr/bin/env bash\nexit %s\n' "$rc" > "$dir/check-${i}-stub.sh"
        chmod +x "$dir/check-${i}-stub.sh"
        i=$((i + 1))
    done
    ( cd "$dir" && ./run-all.sh >/dev/null 2>&1 )
    echo $?
}

findings=0
examined=0
for runner in "${RUNNERS[@]}"; do
    green="$(probe "$runner" 0)"
    if [ "$green" -ne 0 ]; then
        tooling_gate_void "$NAME" \
            "$runner — на единственной ПРОЙДЕННОЙ проверке вернул $green; остальные пробы на нём недоказательны"
        exit 2
    fi

    examined=$((examined + 1))

    find_rc="$(probe "$runner" 1)"
    if [ "$find_rc" -ne 1 ]; then
        tooling_gate_fail "$NAME" \
            "$runner — единственная проверка НАШЛА нарушение, прогонщик вернул $find_rc вместо 1"
        findings=$((findings + 1))
    fi

    void_rc="$(probe "$runner" 2)"
    if [ "$void_rc" -ne 2 ]; then
        tooling_gate_fail "$NAME" \
            "$runner — единственная проверка осталась БЕЗ ПРЕДМЕТА, прогонщик вернул $void_rc вместо 2; вызывающий не отличит её от находки"
        findings=$((findings + 1))
    fi

    # Антимаска: находка и беспредметность вместе обязаны дать находку.
    mixed_rc="$(probe "$runner" 1 2)"
    if [ "$mixed_rc" -ne 1 ]; then
        tooling_gate_fail "$NAME" \
            "$runner — находка РЯДОМ с беспредметной проверкой дала $mixed_rc вместо 1; «без предмета» стало маской для нарушения"
        findings=$((findings + 1))
    fi
done

tooling_gate_census "$NAME: прогонщиков осмотрено $examined (по четыре пробы на каждый — пройдено, находка, без предмета, находка+без предмета)"

if [ "$findings" -gt 0 ]; then
    tooling_gate_fail "$NAME" "проб с находкой: $findings"
    exit 1
fi

tooling_gate_pass "$NAME" "у всех $examined прогонщиков находка даёт 1, отсутствие предмета — 2, и находка рядом с беспредметной проверкой по-прежнему 1"
