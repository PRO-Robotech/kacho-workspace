python3 - "$root" "$name" <<'PY'
import os, re, sys
root, name = sys.argv[1], sys.argv[2]
RULE = '.claude/rules/ai-tooling.md'
ARCH = '.claude/backup/ai-tooling.md'
BASE = '.claude/agents/dispatcher.md'
CIW = '.claude/agents/ci-watcher.md'
WAVE = '.claude/workflows/wave.js'
PROBE = 'scripts/wave-template-inject.sh'
QUOTE = ('Мы при прогоне через мастер си узнаваем где ошибок мы исправляем их и проверяем все '
         'точечно без ci или опять гоним через мастер си ?')


def void(msg):
    print('[VOID] %s — %s' % (name, msg), file=sys.stderr)
    sys.exit(2)


def flat(t):
    return re.sub(r'\s+', ' ', t)


texts = {}
for p in (RULE, ARCH, BASE, CIW, WAVE, PROBE):
    try:
        texts[p] = open(os.path.join(root, p), encoding='utf-8').read()
    except OSError:
        void('носителя %s нет: судить нечего' % p)
finds = []


def need(where, text, frags, what):
    t = flat(text)
    for f in frags:
        if f not in t:
            finds.append('%s: %s — не найдено «%s»' % (where, what, f))


def unit(text, start, stop_re):
    """Норма от якоря до начала следующей единицы (строка-норма, заголовок, пункт, строка таблицы)."""
    k = text.find(start)
    if k < 0:
        return ''
    m = re.compile(stop_re).search(text, k + len(start))
    return text[k:m.start() if m else len(text)]


# A. правило и архив.
r = texts[RULE]
line = unit(r, '\nat-red-ci-one-round · ', r'\n(?:\n|#|[a-z][a-z0-9-]* · )')
if not line:
    finds.append('%s: нормы at-red-ci-one-round нет' % RULE)
else:
    need(RULE, line, ['перепись красноты по корням',
                      'класс корня — после цитаты отказа',
                      'среда с двумя признаками — один перезапуск без полосы',
                      'корень чинит исполнитель класса, проверка точечно без CI (тот же шаг: красный до, зелёный после; хук; `check-verifier`)',
                      'починки — одной сборкой, одним PR в ветку эпика',
                      'повтор CI MR эпика — один, после неё',
                      'после каждой волны — CI MR эпика и пробное схождение',
                      'событие и блок `event` — одним заходом',
                      'tooling-gate check-23',
                      'red: два PR починок одного круга со своим CI; класс без цитаты'],
         'at-red-ci-one-round без требования')
need(ARCH, texts[ARCH], [QUOTE, '«Запиши в рул и запомни что бы компакция не убила память»',
                         '#779, #781, #783, #3201, #3203', 'kaname 24 проверки, kacho 74, 40–90 мин',
                         '(~1,5 ч)', 'круг починки стоил 5–7 ч вместо 2–2,5'],
     'архив: цитата владельца 2026-10-13 и замер')

# B. база диспетчера.
b = texts[BASE]
row = unit(b, '\n| Красный конвейер | ', r'\n')
if not row:
    finds.append('%s: строки «Красный конвейер» §6 нет' % BASE)
else:
    need(BASE, row, ['ОДИН круг (`ai-tooling.md#at-red-ci-one-round`)',
                     '`ci-watcher` — перепись ВСЕЙ красноты по корням с дословным текстом отказа',
                     'класс корня (продукт · проба · среда · прибор) — лишь после цитаты',
                     'среда с двумя признаками (§4) — один перезапуск без полосы',
                     'корень — исполнителю его класса',
                     'проверка ТОЧЕЧНО без CI: тот же шаг локально, красный до и зелёный после, полный хук, `check-verifier` — до CI',
                     'все починки круга — ОДНОЙ сборкой `git-operator` (`--no-ff`), ОДНИМ PR в ветку эпика, его CI (`ci-watcher` read) — единственный прогон круга',
                     'два PR починок круга — нарушение',
                     'полный CI MR эпика — ОДИН повтор, после её вливания'],
         'строка «Красный конвейер» §6 (пп. 1–4)')
wrow = unit(b, '\n| Волна | ', r'\n')
if not wrow:
    finds.append('%s: строки «Волна» §6 нет' % BASE)
else:
    need(BASE, wrow, ['после КАЖДОЙ влитой волны — полный CI MR эпика и пробное схождение (отпечатки пакета, недостающие записи ролей и событий; записи ролей — по ходу, на сведённом)'],
         'строка «Волна» §6 (п.5)')
need(BASE, unit(b, '\n- Неполон, если:', r'\n- '), ['диагноз или класс корня раньше цитаты текста отказа'],
     '§4 «Неполон»: класс корня раньше цитаты')
need(BASE, b, ['событие опубликовано — блок `event` записи к факту тем же заходом'], '§7: событие и блок event (п.6)')
need(BASE, unit(b, '\n1. Пилот «код сразу»', r'\n\d+\. '),
     ['замысел и запись схождения — окончательно перед PR эпика в `main`, пробой — после каждой волны (§6)'],
     '§8а п.1: пробой — после каждой волны')

# C. шаблон волны: порядок круга в итоге красного, схождение и CI MR эпика ПОСЛЕ вливания.
w = texts[WAVE]
need(WAVE, w, ["const RED_ROUND = 'красный круг одним заходом (ai-tooling.md#at-red-ci-one-round)",
               'перепись ВСЕЙ красноты по корням, класс корня — лишь после дословной цитаты отказа, среда с двумя признаками — один перезапуск без полосы',
               'проверка точечно без CI (тот же шаг локально: красный до, зелёный после) и полный хук, check-verifier — до CI',
               'все починки круга — ОДНОЙ сборкой и ОДНИМ PR в ветку эпика; полный CI MR эпика — один повтор, после её вливания',
               "const redOf = r => ciState(r) === 'red' ? { redRound: RED_ROUND } : {}",
               '...redOf(ci), errors', '...redOf(ciL), ',
               "const epicMr = landedOk && !!A.epic && A.epic !== 'main'",
               'пересчитай отпечатки пакета изменения и дай перечень недостающих записей ролей и событий',
               'без ожидания: код 3 (идёт) — законный исход'],
     'провязка круга одним заходом')
im, itc, iec = w.find("label: 'mech:merge'"), w.find("label: 'trial-convergence'"), w.find("label: 'mech:ci-epic'")
if not (0 <= im < itc and im < iec):
    finds.append("%s: пробное схождение и чтение CI MR эпика не стоят в теле ПОСЛЕ шага вливания" % WAVE)
need(PROBE, texts[PROBE], ["console.log('== красный CI — одним кругом; после волны — пробное схождение и CI MR эпика (ws#1063)')",
                           'mutant "пробного схождения после волны нет (ws#1063)"',
                           'mutant "CI MR эпика после волны не читается (ws#1063)"',
                           'mutant "починки поштучными PR (ws#1063)"',
                           'mutant "повтор MR эпика после каждого фикса (ws#1063)"',
                           'mutant "класс до цитаты (ws#1063)"',
                           'mutant "среда — полосой починки (ws#1063)"',
                           'mutant "проверка починки — через CI (ws#1063)"'],
     'поведение доказывается исполнением шаблона')

# D. ci-watcher.
need(CIW, texts[CIW], ['класс корня (продукт · проба · среда · прибор) называется только ПОСЛЕ цитаты отказа, класс без цитаты — не класс',
                       'корень среды с двумя признаками — один перезапуск (rerun), без полосы починки',
                       'проверка починки — точечно тем же шагом локально и полным хуком, до любого CI',
                       'все починки круга — ОДНОЙ сборкой и ОДНИМ PR в ветку эпика',
                       'полный CI MR эпика — один повтор, после вливания сборки починок'],
     'triage и заказ на K корней')

print('[CENSUS] %s: носителей осмотрено %d (правило, архив, база, ci-watcher, шаблон, проба шаблона); находок %d'
      % (name, len(texts), len(finds)))
for f in finds:
    print('[FAIL] %s — %s' % (name, f), file=sys.stderr)
if finds:
    sys.exit(1)
print('[PASS] %s — красный CI одним кругом провязан: норма с признаком в правиле и архиве, §4/§6/§7/§8а базы, '
      'порядок круга и схождение после вливания в wave.js, triage ci-watcher' % name)
PY
