def unit(text, start, stop_re):
    """Норма от якоря до начала следующей единицы (строка-норма, заголовок, пункт, строка таблицы)."""
    k = text.find(start)
    if k < 0:
        return ''
    m = re.compile(stop_re).search(text, k + len(start))
    return text[k:m.start() if m else len(text)]


