#!/usr/bin/env bash
# check-10 — СТРАЖ МОНИТОРА ФЛОУ заговаривает на своих признаках и молчит на
# законных близнецах.
#
# ЧТО УТВЕРЖДАЕТ. `.claude/hooks/wave-monitor.sh` — страж, а не проза: он обязан
# печатать сигнал ровно тогда, когда предмет открыт, и молчать, когда закрыт.
# Проверяется ПОВЕДЕНИЕ: рядом с хуком кладутся ведомость волн, база модели
# исполнения и транскрипт с ЗАДАННЫМ содержимым, и читается то, что хук напечатал
# и каким кодом вышел.
#
# ПОЧЕМУ ПОВЕДЕНЧЕСКАЯ, А НЕ ТЕКСТОВАЯ. Искать в исходнике `if [ "$monitor" =` —
# значит ловить форму: хук волен считать строки awk'ом, вынести разбор в функцию,
# переименовать переменную. Текст сигнала тоже не закрепляется дословно: он
# переписывается вместе с нормой, и проверка на фразу покраснела бы на исправном
# страже — такую отключают первой. Закрепляются ДВА РАЗЛИЧИМЫХ ИСХОДА: «находка»
# и «осмотреть было нечем», и то, что второй не выдаётся за первый.
#
# ОСИ — ТРИ, И У КАЖДОЙ СВОЙ ЗАКОННЫЙ БЛИЗНЕЦ (`testing.md` §«Гейт на класс», п.2):
#
#   ось 1  строка ведомости открыта (поле «монитор» = «—»)     → сигнал
#          та же строка закрыта                                 → молчание
#   ось 2  посадок после курсора ≥ 4 при закрытой ведомости      → сигнал
#          посадок 1 — одна посадка самой полосы монитора        → молчание
#   ось 3  базовая модель ≠ модели транскрипта                   → сигнал
#          моделей в транскрипте больше одной                    → сигнал
#          базовая модель не записана                            → сигнал
#          базовая совпала, модель одна                          → молчание
#
# КАЖДАЯ ИНЪЕКЦИЯ МЕНЯЕТ РОВНО ОДИН ФАКТ против контрольной фикстуры — иначе
# неизвестно, который из двух дал сигнал, и вердикт недействителен, оставаясь на
# вид зелёным (`change-graph.md` §6).
#
# ФИКСТУРЫ ПОДАЮТ И КРИВОЙ ВХОД — иначе гейт его не видит by construction.
# Первая редакция этого файла держала фикстуры, заполненные ЦЕЛИКОМ: у каждой
# строки ведомости и базы все поля непусты. На таком входе разборщик на
# `read -r` с `IFS=$'\t'` выглядел исправным, а он схлопывал подряд идущие
# табуляции (табуляция — IFS-пробельный знак) и давал СРАЗУ ДВА ложных вердикта:
# страж молчал на открытой волне (поле «исход» въезжало на место «монитора») и
# печатал несуществующую смену модели («сменилась «2026-09-19»»). Ни одну из
# семнадцати проб это не уронило.
#
# ВТОРАЯ РЕДАКЦИЯ ОБЕЩАЛА БОЛЬШЕ, ЧЕМ ПОДАВАЛА: шапка говорила «в каждой
# позиции», а пустое поле шло в ЧЕТЫРЁХ из девяти, и обе непокрытые ветви были
# живыми — сломай их, и страж объявлял сведённой волну, которую никто не сводил.
# Заявление шире сделанного не ловится ничем, поэтому позиций теперь ровно
# столько, сколько полей у двух файлов, и ЧИСЛО ПЕЧАТАЕТСЯ переписью, а не
# обещается прозой: `пустое поле подано в N позициях из 9`.
#
# Правило для автора любой проверки над разбором: пустое поле подаётся в каждой
# позиции, и покрытие называется числом. Класс шире этого файла и заведён
# отдельным предметом для `testing.md` §«Гейт на класс» — сюда он записан как
# урок места, а не как норма корпуса.
#
# ТРЕТЬЯ КАТЕГОРИЯ ПРОВЕРЯЕТСЯ ОТДЕЛЬНО. Нет транскрипта, нет ведомости — это
# «не проверяли», а не «чисто» и не находка. Хук обязан сказать это ДРУГОЙ
# строкой; совпади они, молчание монитора читалось бы как отработавший монитор.
#
# ХУК НЕ РОНЯЕТ СЕССИЮ. Код выхода 0 требуется в КАЖДОЙ пробе, включая те, где
# сигнал печатается: это указатель, а не гейт, и ненулевой код оборвал бы
# обращение к сессии.
#
# ПРЕДПОСЫЛКА (исход VOID, а не успех): хук есть в дереве, есть python3 (без него
# третья ось не разбирается вовсе), и на контрольной фикстуре хук МОЛЧИТ. Страж,
# кричащий на закрытом предмете, к остальным пробам непригоден — они прошли бы на
# нём тождественно и не доказали бы ничего.
set -euo pipefail

# shellcheck source=_lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/_lib.sh"

WS="$(tooling_gate_workspace_root)"
NAME="check-10-wave-monitor-fires-on-its-triggers"
HOOK_REL=".claude/hooks/wave-monitor.sh"

mapfile -t HOOKS < <(tooling_gate_files "$WS" "$HOOK_REL")
if [ "${#HOOKS[@]}" -eq 0 ]; then
    tooling_gate_void "$NAME" "стража $HOOK_REL в дереве нет — проверять нечего"
    exit 2
fi
if ! command -v python3 >/dev/null 2>&1; then
    tooling_gate_void "$NAME" "python3 нет — ось модели исполнения не разбирается, вердикта по ней не будет"
    exit 2
fi

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

MARK_FIND="МОНИТОР ФЛОУ: предмет открыт"
MARK_UNEX="осмотреть удалось НЕ ВСЁ"

# Транскрипты фикстуры: одна модель и две. Форма записи снята с настоящего
# транскрипта (`message.model` у ассистентской записи главного потока), а не
# придумана: хук читает ровно её.
printf '%s\n' \
    '{"type":"assistant","isSidechain":false,"message":{"model":"model-alpha"}}' \
    > "$TMP/one.jsonl"
printf '%s\n' \
    '{"type":"assistant","isSidechain":false,"message":{"model":"model-gamma"}}' \
    '{"type":"assistant","isSidechain":false,"message":{"model":"model-alpha"}}' \
    > "$TMP/two.jsonl"
# Посторонние записи, которые хук обязан пропускать: побочная ветвь и отметка,
# сочинённая харнессом. Без них «одна модель» доказывалось бы на входе, где
# второй модели и не предлагали.
printf '%s\n' \
    '{"type":"assistant","isSidechain":true,"message":{"model":"model-sidechain"}}' \
    '{"type":"assistant","isSidechain":false,"message":{"model":"<synthetic>"}}' \
    '{"type":"assistant","isSidechain":false,"message":{"model":"model-alpha"}}' \
    > "$TMP/noise.jsonl"

# state <каталог> <строка ведомости> <строка базы> — кладёт состояние монитора.
state() {
    local dir="$1" row="$2" base="$3"
    mkdir -p "$dir"
    # «НЕТ» — ведомости не существует вовсе: это проба третьей категории, и она
    # обязана давать ДРУГУЮ строку, а не молчание.
    rm -f "$dir/ledger.tsv"
    if [ "$row" != "НЕТ" ]; then
        {
            printf '# волна\tсведена\tствол\tполос\tмонитор\tисход\n'
            printf '%s\n' "$row"
        } > "$dir/ledger.tsv"
    fi
    {
        printf '# модель\tзамерено\tориентиры\n'
        printf '%s\n' "$base"
    } > "$dir/model-baseline.tsv"
}

# repo <каталог> <сколько коммитов> — печатает ревизию ПЕРВОГО коммита `main`.
#
# Личность задаётся ключами вызова, а не настройкой машины: на ранере её может
# не быть вовсе, и коммит бы не состоялся, оставив ось 2 без предмета молча.
# Переменные окружения git снимаются: унаследованный GIT_DIR сильнее рабочего
# каталога и увёл бы запись в ЭТУ рабочую копию.
repo() {
    local dir="$1" n="$2" i
    mkdir -p "$dir"
    (
        unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
              GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_COMMON_DIR GIT_PREFIX
        git -C "$dir" init -q -b main
        for ((i = 0; i < n; i++)); do
            git -C "$dir" -c user.name=fixture -c user.email=fixture@invalid \
                commit -q --allow-empty -m "c$i"
        done
    ) >/dev/null 2>&1
    git -C "$dir" rev-list --max-parents=0 main
}

# remote <каталог> <ревизия> — заводит remote-tracking ссылку БЕЗ сети.
#
# Без неё класс «локальный main отстаёт» выпадал из охвата by construction:
# `git init` удалённого не заводит, и проба доказывала бы только запасной путь.
remote() { git -C "$1" update-ref refs/remotes/origin/main "$2" >/dev/null 2>&1; }

# rewind <каталог> <ревизия> — отводит локальный main назад, оставляя origin/main
# впереди: ровно то расхождение, что живёт в рабочем дереве.
rewind() { git -C "$1" reset -q --hard "$2" >/dev/null 2>&1; }

# probe <имя> <ждём: FIND|UNEX|SILENT> <каталог> <корень> <транскрипт> [что ОБЯЗАН назвать]…
#
# УТВЕРЖДЕНИЕ ЧИТАЕТ СТРОКУ НАХОДКИ, А НЕ ВЕСЬ ВЫВОД, И У НЕГО ЕСТЬ ОТРИЦАТЕЛЬНАЯ
# ПОЛОВИНА. Прежняя редакция спрашивала `case "$out" in *"$must"*` — по всему
# тексту разом, — и приёмка опытом показала три следствия сразу:
#   · `must="main"` было ВАКУУМНО: подстрока `main` всегда есть внутри
#     `tooling-maintainer`, поэтому обнулённый текст находки оси 2 проходил;
#   · адресат засчитывался из ЧУЖОГО блока — строка третьей категории тоже
#     называет полосу, а страж умеет печатать оба блока разом;
#   · все пять текстов находок, заменённые одним общим блобом со всеми токенами,
#     давали PASS: ось со своим предметом не связывалась ничем.
# Первые два снимает чтение по блоку и по строке. Третье — только ОТРИЦАНИЕ:
# строка находки обязана назвать свои токены И НЕ НАЗВАТЬ чужие. Блоб называет
# все, поэтому падает на каждой пробе.
findings=0
probes=0
empties=0
n_find=0; n_unex=0; n_silent=0
ADDRESSEE="tooling-maintainer"

# Словарь предметов осей. Он же даёт отрицательную половину: чего в строке быть
# НЕ ДОЛЖНО, выводится как «весь словарь минус объявленное пробой», а не
# выписывается — выписанное разошлось бы с первой новой пробой.
ALL_TOKENS=(
    "w1" "без имени" "не названо"
    "по ссылке origin/main" "по ссылке main"
    "model-alpha" "model-beta" "model-gamma"
)

# block <вывод> <маркер заголовка> — строки ОДНОГО блока вывода.
# Оба блока начинаются со своего значка, поэтому граница читается без
# закрепления формулировок: меняется текст — граница остаётся.
block() { printf '%s\n' "$1" | awk -v mark="$2" '/^🌊/ { inb = (index($0, mark) > 0) } inb { print }'; }

probe() {
    local name="$1" want="$2" st="$3" root="$4" tr="$5" out code has_find has_unex
    shift 5
    local -a musts=( "$@" )
    probes=$((probes + 1))
    out="$(
        printf '{"hook_event_name":"UserPromptSubmit","transcript_path":"%s"}' "$tr" |
        KACHO_WAVE_MONITOR_DIR="$st" CLAUDE_PROJECT_DIR="$root" \
            bash "$WS/$HOOK_REL" 2>&1
    )" && code=0 || code=$?

    if [ "$code" -ne 0 ]; then
        tooling_gate_fail "$NAME" "$name — страж вышел кодом $code: указатель обязан выходить нулём, иначе он роняет обращение к сессии"
        findings=$((findings + 1))
        return 0
    fi

    local find_block unex_block
    find_block="$(block "$out" "$MARK_FIND")"
    unex_block="$(block "$out" "$MARK_UNEX")"
    has_find=0; [ -n "$find_block" ] && has_find=1
    has_unex=0; [ -n "$unex_block" ] && has_unex=1

    case "$want" in
        FIND)
            n_find=$((n_find + 1))
            if [ "$has_find" -ne 1 ]; then
                tooling_gate_fail "$NAME" "$name — предмет открыт, а сигнала НЕТ: страж молчит там, где обязан звать"
                findings=$((findings + 1))
                return 0
            fi
            # Адресат — ИЗ БЛОКА НАХОДКИ. В блоке третьей категории он тоже стоит,
            # и засчитывать его оттуда значит не проверять ничего.
            case "$find_block" in
                *"$ADDRESSEE"*) ;;
                *)  tooling_gate_fail "$NAME" "$name — находка напечатана, а полоса «$ADDRESSEE» в ЕЁ блоке не названа: диспетчеру нечего поставить"
                    findings=$((findings + 1)) ;;
            esac
            [ "${#musts[@]}" -eq 0 ] && return 0

            # Одна строка обязана нести ВСЕ объявленные токены и НИ ОДНОГО чужого.
            local line ok matched=0 tok m mine
            while IFS= read -r line; do
                case "$line" in *"·"*) ;; *) continue ;; esac
                ok=1
                for tok in "${musts[@]}"; do
                    case "$line" in *"$tok"*) ;; *) ok=0 ;; esac
                done
                for tok in "${ALL_TOKENS[@]}"; do
                    mine=0
                    for m in "${musts[@]}"; do [ "$tok" = "$m" ] && mine=1; done
                    [ "$mine" = 1 ] && continue
                    case "$line" in *"$tok"*) ok=0 ;; esac
                done
                [ "$ok" = 1 ] && matched=1
            done <<< "$find_block"

            if [ "$matched" -ne 1 ]; then
                tooling_gate_fail "$NAME" "$name — НИ ОДНА строка находки не называет ровно свой предмет (${musts[*]}) и только его: ось со своим предметом не связана"
                findings=$((findings + 1))
            fi
            ;;
        UNEX)
            n_unex=$((n_unex + 1))
            if [ "$has_unex" -ne 1 ]; then
                tooling_gate_fail "$NAME" "$name — осматривать было нечем, а строки об этом НЕТ: «не проверяли» неотличимо от «чисто»"
                findings=$((findings + 1))
            elif [ "$has_find" -eq 1 ]; then
                tooling_gate_fail "$NAME" "$name — отсутствие предмета подано как НАХОДКА: третья категория не отличена от находки"
                findings=$((findings + 1))
            fi
            ;;
        SILENT)
            n_silent=$((n_silent + 1))
            if [ "$has_find" -eq 1 ] || [ "$has_unex" -eq 1 ]; then
                tooling_gate_fail "$NAME" "$name — законный близнец ЗАГОВОРИЛ: страж ловит форму, а не предмет. Напечатано: ${out%%$'\n'*}"
                findings=$((findings + 1))
            fi
            ;;
    esac
}

# empty_probe — та же проба, но объявляющая себя пробой КРИВОГО ВХОДА. Счётчик
# позиций выводится из вызовов, а не выписывается: выписанный уже разошёлся с
# замером (обещано «в каждой», подано в четырёх из девяти).
empty_probe() { empties=$((empties + 1)); probe "$@"; }

# ── Общий корень фикстур: репозиторий с пятью посадками на `main` ────────────
ROOT="$TMP/root"
FIRST="$(repo "$ROOT" 5 2>/dev/null || true)"
if [ -z "$FIRST" ]; then
    tooling_gate_void "$NAME" "репозиторий фикстуры не собрался — ось «строки о волне нет» осталась без предмета"
    exit 2
fi
NEAR="$(git -C "$ROOT" rev-parse 'main~1')"

ROW_CLOSED="$(printf 'w1\t2026-09-19\t%s\t6\t2026-09-19\t.claude/rules/multi-agent-flow.md §«Седьмой шаг»' "$NEAR")"
ROW_OPEN="$(printf 'w1\t2026-09-19\t%s\t6\t—\t—' "$NEAR")"
BASE_SAME="$(printf 'model-alpha\t2026-09-19\tориентиры')"
BASE_OTHER="$(printf 'model-beta\t2026-09-01\tориентиры')"
BASE_NONE="$(printf 'не-записана\t—\tориентиры')"

# ── ПРЕДПОСЫЛКА: на закрытом предмете страж молчит ───────────────────────────
state "$TMP/s0" "$ROW_CLOSED" "$BASE_SAME"
control="$(
    printf '{"hook_event_name":"UserPromptSubmit","transcript_path":"%s"}' "$TMP/one.jsonl" |
    KACHO_WAVE_MONITOR_DIR="$TMP/s0" CLAUDE_PROJECT_DIR="$ROOT" bash "$WS/$HOOK_REL" 2>&1
)" || true
if [ -n "$control" ]; then
    tooling_gate_void "$NAME" "на контрольной фикстуре страж ЗАГОВОРИЛ — остальные пробы на нём недоказательны; напечатано: ${control%%$'\n'*}"
    exit 2
fi
probes=$((probes + 1))

# ── ОСЬ 1: открытая строка ведомости ─────────────────────────────────────────
state "$TMP/s1" "$ROW_OPEN" "$BASE_SAME"
probe "ось 1: строка волны открыта (поле «монитор» = «—»)" FIND "$TMP/s1" "$ROOT" "$TMP/one.jsonl" "w1"

# ── КРИВОЙ ВХОД: пустое поле в КАЖДОЙ из шести позиций ведомости ────────────
#
# поле 1 «волна»: находка состоится и скажет, что имени нет.
state "$TMP/e1" "$(printf '\t2026-09-19\t%s\t6\t—\t—' "$NEAR")" "$BASE_SAME"
empty_probe "ведомость, поле 1 «волна» пусто — находка скажет это" \
    FIND "$TMP/e1" "$ROOT" "$TMP/one.jsonl" "без имени"

# поле 2 «сведена»: волна НЕ сведена — находки нет. Сломай разбор пустоты здесь,
# и страж объявит сведённой волну, которую никто не сводил.
state "$TMP/e2" "$(printf 'w1\t\t%s\t6\t—\t—' "$NEAR")" "$BASE_SAME"
empty_probe "ведомость, поле 2 «сведена» пусто — волна не сведена, молчит" \
    SILENT "$TMP/e2" "$ROOT" "$TMP/one.jsonl"

# поле 3 «ствол»: знаменателя обхода нет — третья категория, а не тишина.
state "$TMP/e3" "$(printf 'w1\t2026-09-01\t\t6\t2026-09-01\tкоордината')" "$BASE_SAME"
empty_probe "ведомость, поле 3 «ствол» пусто — «не проверяли»" \
    UNEX "$TMP/e3" "$ROOT" "$TMP/one.jsonl"

# поле 4 «полос»: находка состоится и скажет, что число не названо.
state "$TMP/e4" "$(printf 'w1\t2026-09-19\t%s\t\t—\t—' "$NEAR")" "$BASE_SAME"
empty_probe "ведомость, поле 4 «полос» пусто — находка скажет это" \
    FIND "$TMP/e4" "$ROOT" "$TMP/one.jsonl" "w1" "не названо"

# поле 5 «монитор»: ровно тот вход, на котором страж дважды молчал об открытой
# волне — «исход» въезжал на место «монитора» у разборщика на IFS-табуляции.
state "$TMP/e5" "$(printf 'w1\t2026-09-19\t%s\t6\t\tкоордината' "$NEAR")" "$BASE_SAME"
empty_probe "ведомость, поле 5 «монитор» пусто при заполненном «исход» — находка" \
    FIND "$TMP/e5" "$ROOT" "$TMP/one.jsonl" "w1"

# поле 6 «исход»: строка закрыта датой — молчание.
state "$TMP/e6" "$(printf 'w1\t2026-09-19\t%s\t6\t2026-09-19\t' "$NEAR")" "$BASE_SAME"
empty_probe "ведомость, поле 6 «исход» пусто при закрытом «монитор» — молчит" \
    SILENT "$TMP/e6" "$ROOT" "$TMP/one.jsonl"

# ── ОСЬ 2: строки о волне нет вовсе ──────────────────────────────────────────
#
# Курсор на ПЕРВОМ коммите — после него четыре посадки, ровно нижняя граница
# вилки волны. Требуется ссылка ПОЛНОЙ фразой и ревизия курсора: подстрока
# `main` вакуумна, она всегда есть внутри имени полосы `tooling-maintainer`.
state "$TMP/s2" "$(printf 'w1\t2026-09-01\t%s\t6\t2026-09-01\tкоордината' "$FIRST")" "$BASE_SAME"
probe "ось 2: удалённой ссылки нет — считать по main, назвать её и курсор" \
    FIND "$TMP/s2" "$ROOT" "$TMP/one.jsonl" "по ссылке main" "$FIRST"

state "$TMP/s2b" "$ROW_CLOSED" "$BASE_SAME"
probe "ось 2, близнец: посадка ОДНА — молчит" SILENT "$TMP/s2b" "$ROOT" "$TMP/one.jsonl"

# ОТСТАВШИЙ ЛОКАЛЬНЫЙ `main` — живой класс: на день правки в рабочем дереве
# `main` = 870e3132 при `origin/main` = cf15f29d, посадок 0 против 1. Здесь то же:
# локальный отведён назад, удалённый стоит на пятом коммите. По `main` посадок 1
# (страж молчал бы), по `origin/main` — 4.
BEHIND="$TMP/behind"
BEHIND_FIRST="$(repo "$BEHIND" 5 2>/dev/null || true)"
remote "$BEHIND" "$(git -C "$BEHIND" rev-parse main)"
rewind "$BEHIND" "$(git -C "$BEHIND" rev-parse 'main~3')"
state "$TMP/s2c" "$(printf 'w1\t2026-09-01\t%s\t6\t2026-09-01\tкоордината' "$BEHIND_FIRST")" "$BASE_SAME"
probe "ось 2: локальный main отстал — считать по origin/main и назвать ссылку" \
    FIND "$TMP/s2c" "$BEHIND" "$TMP/one.jsonl" "по ссылке origin/main" "$BEHIND_FIRST"

# Ни одна ссылка ствола не разрешается — ТРЕТЬЯ КАТЕГОРИЯ, а не тишина.
NOMAIN="$TMP/nomain"
repo "$NOMAIN" 3 >/dev/null 2>&1 || true
git -C "$NOMAIN" branch -m main master >/dev/null 2>&1 || true
state "$TMP/s2e" "$(printf 'w1\t2026-09-01\t%s\t6\t2026-09-01\tкоордината' "$FIRST")" "$BASE_SAME"
probe "ось 2: ни origin/main, ни main не разрешаются — «не проверяли»" \
    UNEX "$TMP/s2e" "$NOMAIN" "$TMP/one.jsonl"

# ── ОСЬ 3: модель исполнения ─────────────────────────────────────────────────
state "$TMP/s3" "$ROW_CLOSED" "$BASE_OTHER"
probe "ось 3: базовая модель ≠ модели транскрипта" \
    FIND "$TMP/s3" "$ROOT" "$TMP/one.jsonl" "model-beta" "model-alpha"

state "$TMP/s3b" "$ROW_CLOSED" "$BASE_SAME"
probe "ось 3: в одном транскрипте две модели" \
    FIND "$TMP/s3b" "$ROOT" "$TMP/two.jsonl" "model-gamma" "model-alpha"

state "$TMP/s3c" "$ROW_CLOSED" "$BASE_NONE"
probe "ось 3: базовая модель не записана" FIND "$TMP/s3c" "$ROOT" "$TMP/one.jsonl" "model-alpha"

state "$TMP/s3d" "$ROW_CLOSED" "$BASE_SAME"
probe "ось 3, близнец: побочная ветвь и синтетическая запись не считаются моделями" \
    SILENT "$TMP/s3d" "$ROOT" "$TMP/noise.jsonl"

# ── КРИВОЙ ВХОД: пустое поле в КАЖДОЙ из трёх позиций базы ──────────────────
state "$TMP/b1" "$ROW_CLOSED" "$(printf '\t2026-09-19\tориентиры')"
empty_probe "база, поле 1 «модель» пусто — «не проверяли», а не смена модели" \
    UNEX "$TMP/b1" "$ROOT" "$TMP/one.jsonl"

state "$TMP/b2" "$ROW_CLOSED" "$(printf 'model-alpha\t\tориентиры')"
empty_probe "база, поле 2 «замерено» пусто — модель читается, молчит" \
    SILENT "$TMP/b2" "$ROOT" "$TMP/one.jsonl"

state "$TMP/b3" "$ROW_CLOSED" "$(printf 'model-alpha\t2026-09-19\t')"
empty_probe "база, поле 3 «ориентиры» пусто — модель читается, молчит" \
    SILENT "$TMP/b3" "$ROOT" "$TMP/one.jsonl"

# ── ТРЕТЬЯ КАТЕГОРИЯ: осматривать нечем ──────────────────────────────────────
state "$TMP/s4" "$ROW_CLOSED" "$BASE_SAME"
probe "нет транскрипта — «не проверяли», а не находка" UNEX "$TMP/s4" "$ROOT" "$TMP/нет-такого.jsonl"

state "$TMP/s5" "НЕТ" "$BASE_SAME"
probe "нет ведомости — «не проверяли», а не находка" UNEX "$TMP/s5" "$ROOT" "$TMP/one.jsonl"


# Подпись переписи ВЫВОДИТСЯ из счётчиков, а не выписывается: выписанная уже
# разошлась дважды — «9» при десяти пробах и «в каждой позиции» при четырёх из
# девяти. Позиций кривого входа ровно столько, сколько полей у двух файлов: 6 + 3.
tooling_gate_census "$NAME: стражей осмотрено ${#HOOKS[@]}; проб исполнено $probes — контроль 1, ждали находку $n_find, ждали «не проверяли» $n_unex, ждали молчание $n_silent; пустое поле подано в $empties позициях из 9 (ведомость 6 + база 3); у каждой находки строка проверена на СВОЙ предмет и на отсутствие чужих из словаря ${#ALL_TOKENS[@]}"

if [ "$findings" -gt 0 ]; then
    tooling_gate_fail "$NAME" "проб с находкой: $findings"
    exit 1
fi

tooling_gate_pass "$NAME" "страж зовёт на каждом из своих признаков, молчит на законных близнецах и не выдаёт «не проверяли» за находку"
