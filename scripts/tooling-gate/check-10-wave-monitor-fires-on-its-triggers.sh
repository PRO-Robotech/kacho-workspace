# Пустое поле в ПОСЛЕДНЕЙ строке решает, откатится ли курсор на предыдущую, и
# перепись печатает обе величины рядом.
#
# ХУК НЕ РОНЯЕТ СЕССИЮ. Код выхода 0 требуется в КАЖДОЙ пробе, включая те, где
