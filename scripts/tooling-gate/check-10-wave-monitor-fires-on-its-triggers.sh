    "$TMP/e4" "$ROOT" "$TMP/one.jsonl" "$(toks "$WAVE" "не названо")" "" КРИВОЙ

# поле 5 «монитор»: ровно тот вход, на котором страж дважды молчал об открытой
# волне — «исход» въезжал на место «монитора» у разборщика на IFS-табуляции.
state "$TMP/e5" "$(printf '%s\t2026-09-19\t%s\t6\t\tкоордината' "$WAVE" "$TIP")" "$BASE_SAME"
plan "ведомость, поле 5 «монитор» пусто при заполненном «исход» — находка" \
    "$TMP/e5" "$ROOT" "$TMP/one.jsonl" "$(toks "$WAVE")" "" КРИВОЙ

# поле 6 «исход»: строка закрыта датой — молчание.
state "$TMP/e6" "$(printf '%s\t2026-09-19\t%s\t6\t2026-09-19\t' "$WAVE" "$TIP")" "$BASE_SAME"
plan "ведомость, поле 6 «исход» пусто при закрытом «монитор» — молчит" \
    "$TMP/e6" "$ROOT" "$TMP/one.jsonl" "" "" КРИВОЙ

# ── ОСЬ 2: строки о волне нет вовсе ──────────────────────────────────────────
#
# Курсор на ПЕРВОМ коммите — после него четыре посадки, ровно нижняя граница
# вилки волны. Требуется ссылка ПОЛНОЙ фразой и ревизия курсора: подстрока
# `main` вакуумна, она всегда есть внутри имени полосы `tooling-maintainer`.
state "$TMP/s2" "$(printf '%s\t2026-09-01\t%s\t6\t2026-09-01\tкоордината' "$WAVE" "$FIRST")" "$BASE_SAME"
plan "ось 2: удалённой ссылки нет — считать по main, назвать её и курсор" \
    "$TMP/s2" "$ROOT" "$TMP/one.jsonl" "$(toks "по ссылке main" "$FIRST")" ""

# БЛИЗНЕЦ НА САМОМ ПОРОГЕ: посадок ровно на одну меньше вилки. Отрицательный
# исход у него ДОСТИЖИМ — понижение порога до трёх роняет именно его, и на
# контроле (ноль посадок) не сказывается никак.
state "$TMP/s2a" "$(printf '%s\t2026-09-01\t%s\t6\t2026-09-01\tкоордината' "$WAVE" "$EDGE")" "$BASE_SAME"
plan "ось 2, близнец: посадок ТРИ — порог минус один, молчит" \
    "$TMP/s2a" "$ROOT" "$TMP/one.jsonl" "" ""

state "$TMP/s2b" "$(printf '%s\t2026-09-01\t%s\t6\t2026-09-01\tкоордината' "$WAVE" "$NEAR")" "$BASE_SAME"
plan "ось 2, близнец: посадка ОДНА — молчит" \
    "$TMP/s2b" "$ROOT" "$TMP/one.jsonl" "" ""

state "$TMP/s2c" "$(printf '%s\t2026-09-01\t%s\t6\t2026-09-01\tкоордината' "$WAVE" "$BEHIND_FIRST")" "$BASE_SAME"
plan "ось 2: локальный main отстал — считать по origin/main и назвать ссылку" \
    "$TMP/s2c" "$BEHIND" "$TMP/one.jsonl" "$(toks "по ссылке origin/main" "$BEHIND_FIRST")" ""

# Ни одна ссылка ствола не разрешается — ТРЕТЬЯ КАТЕГОРИЯ, а не тишина.
state "$TMP/s2e" "$(printf '%s\t2026-09-01\t%s\t6\t2026-09-01\tкоордината' "$WAVE" "$FIRST")" "$BASE_SAME"
plan "ось 2: ни origin/main, ни main не разрешаются — «не проверяли»" \
    "$TMP/s2e" "$NOMAIN" "$TMP/one.jsonl" "" "$(toks "ни origin/main, ни main")"

# Курсор есть, ссылка есть, а ревизии в репозитории НЕТ: ветвь жива в работе —
# ревизия из подчищенной ветки перестаёт резолвиться после уборки.
state "$TMP/s2f" "$(printf '%s\t2026-09-01\t%s\t6\t2026-09-01\tкоордината' "$WAVE" "$BOGUS")" "$BASE_SAME"
plan "ось 2: курсор ведомости не резолвится — «не проверяли»" \
    "$TMP/s2f" "$ROOT" "$TMP/one.jsonl" "" "$(toks "$BOGUS")"

# ── КУРСОР НЕСЁТ ПОСЛЕДНЯЯ СТРОКА ВЕДОМОСТИ, А НЕ ПЕРВАЯ ────────────────────
#
# Знаменатель обхода оси 2 — ревизия ствола из ПОСЛЕДНЕЙ строки ведомости: она
# самая свежая, и посадки считаются после неё. Контракт объявлен дважды — в шапке
# стража и в шапке самой `ledger.tsv`, — и до пятого круга не держался ничем: все
# фикстуры несли ОДНУ строку данных, а на одной строке «первая» и «последняя»
# тождественны. Опыт «курсор берётся из первой строки» (`cursor == ""` в условии
# присваивания) оставлял гейт зелёным, код 0.
#
# КЛАСС ЖИВОЙ, А НЕ УМОЗРИТЕЛЬНЫЙ: строку открывает `git-operator` на КАЖДОМ
# сведении волны, и вторая строка данных появляется со следующей волной.
#
# ПРОБ ДВЕ, ПОТОМУ ЧТО У ОШИБКИ ДВА ИСХОДА, и односторонняя проба ловит один:
#   · курсор уехал НАЗАД — страж считает посадки от старой волны и печатает
#     ЛОЖНУЮ находку там, где волна объявлена и закрыта;
#   · курсор уехал ВПЕРЁД — страж МОЛЧИТ о волне, строки о которой нет.
# Обе строки закрыты (поле «монитор» заполнено), поэтому ось 1 в обеих пробах
# молчит: меняется ровно один факт — какая из двух ревизий стала курсором.
# ДВЕ СТРОКИ МНОГОСТРОЧНОЙ ФИКСТУРЫ — ОДИН ИСТОЧНИК НА ВСЮ ОСЬ. Из них же
# строятся и все состояния последней строки ниже: подменяется РОВНО ОДНО поле,
# остальные пять остаются значениями, и потому находка (или её отсутствие)
# принадлежит подменённому полю, а не набору сразу.
ROW_PREV="$(printf '%s-1\t2026-09-01\t%s\t6\t2026-09-01\tкоордината' "$WAVE" "$FIRST")"
ROW_LAST="$(printf '%s-2\t2026-09-19\t%s\t6\t2026-09-19\tкоордината' "$WAVE" "$TIP")"

# tail_row <номер поля> <значение> — ПОСЛЕДНЯЯ строка с подменённым полем.
# Подмена идёт awk'ом, а не оболочкой: `read -r` с `IFS=$'\t'` схлопывает
# табуляции — ровно та поломка, которую эти фикстуры и стерегут (см. шапку
# стража, ось 1). Присваивание `$n` заставляет awk пересобрать запись с OFS,
# поэтому пустое поле остаётся ПОЛЕМ, а не исчезает.
tail_row() { printf '%s' "$ROW_LAST" | awk -F'\t' -v OFS='\t' -v n="$1" -v v="$2" '{ $n = v; print }'; }

state "$TMP/s12" "$ROW_PREV" "$BASE_SAME" "$ROW_LAST"
plan "ведомость из ДВУХ строк: курсор — ПОСЛЕДНЯЯ, после неё посадок 0 — молчит" \
    "$TMP/s12" "$ROOT" "$TMP/one.jsonl" "" ""

state "$TMP/s13" \
    "$(printf '%s-1\t2026-09-01\t%s\t6\t2026-09-01\tкоордината' "$WAVE" "$TIP")" \
    "$BASE_SAME" \
    "$(printf '%s-2\t2026-09-19\t%s\t6\t2026-09-19\tкоордината' "$WAVE" "$FIRST")"
plan "ведомость из ДВУХ строк: курсор — ПОСЛЕДНЯЯ, после неё посадок 4 — находка называет ЕЁ ревизию" \
    "$TMP/s13" "$ROOT" "$TMP/one.jsonl" "$(toks "по ссылке main" "$FIRST")" ""

# ── СОСТОЯНИЕ ПОСЛЕДНЕЙ СТРОКИ: ВСЕ КЛЕТКИ «ПОЛЕ × КЛАСС ЗНАЧЕНИЯ» ──────────
#
# ЧЕМ ЭТА ОСЬ ОТЛИЧАЕТСЯ ОТ КРИВОГО ВХОДА ВЫШЕ. Тот подаёт пустое поле в
# ОДНОСТРОЧНУЮ ведомость, и знаменатель у него — число полей. Здесь ведомость
# МНОГОСТРОЧНАЯ, и предмет другой: последняя строка задаёт курсор, поэтому её
# состояние решает, какая ревизия станет знаменателем обхода оси 2 и состоится
# ли находка оси 1. На однострочной этого не проверить by construction — там
# «последняя» строка единственная.
#
# ЗНАМЕНАТЕЛЬ ВЫВОДИТСЯ, А НЕ ВЫПИСЫВАЕТСЯ: полей столько, сколько их в шапке
# фикстуры, классов — столько, сколько меток страж отличает от значения, плюс
# само значение (см. HOOK_MARKS). Покрытие при этом МЕРИТСЯ ПО САМИМ ФАЙЛАМ
# фикстур, а не по объявлениям проб: снятая фикстура роняет покрытие, даже если
# её `plan` кто-то оставил.
#
# ЧЕГО ЖДЁМ ОТ КАЖДОЙ КЛЕТКИ — РЕШАЕТ АВТОР, И ЭТО НЕ ГЕНЕРИРУЕТСЯ. Ветвь, в
# которую ведёт метка, выводится из поведения стража, а не из формы поля:
# у «ствол» она даёт откат курсора на предыдущую строку (находка о ЕЁ ревизии),
# у «монитор» — открытую волну (находка оси 1), у остальных четырёх — молчание.
# Генератор, раздающий одно ожидание всем клеткам, закрепил бы догадку.
tail_probe() {   # tail_probe <каталог> <поле> <значение> <ярлык> <находки> <не-проверяли>
    state "$1" "$ROW_PREV" "$BASE_SAME" "$(tail_row "$2" "$3")"
    plan "многострочная ведомость: поле $2 «${FIELD_NAMES[$(($2 - 1))]}» последней строки — $4" \
        "$1" "$ROOT" "$TMP/one.jsonl" "$5" "$6"
}

# Поле 1 «волна»: имени нет либо стоит метка — строка закрыта, курсор её.
tail_probe "$TMP/m1e" 1 ""  "пусто" "" ""
tail_probe "$TMP/m1d" 1 "—" "метка «—»" "" ""

# Поле 2 «сведена»: волна не сведена — ось 1 её не берёт, курсор всё равно её.
tail_probe "$TMP/m2e" 2 ""  "пусто" "" ""
tail_probe "$TMP/m2d" 2 "—" "метка «—»" "" ""

# Поле 3 «ствол»: КУРСОРА В ЭТОЙ СТРОКЕ НЕТ — он откатывается на предыдущую, и
# находка обязана назвать ЕЁ ревизию. Ровно это и означает «последняя строка С
# НЕПУСТЫМ полем»: до шестого круга оговорка стояла в шапке ведомости и не
# держалась ничем — ни одна фикстура пустого «ствола» в последней строке не
# подавала.
tail_probe "$TMP/m3e" 3 ""  "пусто — курсор откатывается на предыдущую строку" \
    "$(toks "по ссылке main" "$FIRST")" ""
tail_probe "$TMP/m3d" 3 "—" "метка «—» — курсор откатывается на предыдущую строку" \
    "$(toks "по ссылке main" "$FIRST")" ""

# Поле 4 «полос»: число не названо, но строка закрыта — находки нет.
tail_probe "$TMP/m4e" 4 ""  "пусто" "" ""
tail_probe "$TMP/m4d" 4 "—" "метка «—»" "" ""

# Поле 5 «монитор»: обе метки открывают волну — находка оси 1 по ПОСЛЕДНЕЙ строке.
tail_probe "$TMP/m5e" 5 ""  "пусто — волна открыта" "$(toks "$WAVE")" ""
tail_probe "$TMP/m5d" 5 "—" "метка «—» — волна открыта" "$(toks "$WAVE")" ""

# Поле 6 «исход»: закрывает строку поле «монитор», а не оно — молчание.
tail_probe "$TMP/m6e" 6 ""  "пусто" "" ""
tail_probe "$TMP/m6d" 6 "—" "метка «—»" "" ""

# ВОЛНА, КОТОРАЯ ИДЁТ, — НЕ НАХОДКА, И ЭТО ОТДЕЛЬНАЯ ФИКСТУРА. Метка стоит сразу
# в трёх полях («сведена», «монитор», «исход»), потому что предмет здесь —
# СОСТОЯНИЕ волны, а не поле: `git-operator` открывает такую строку в начале
# волны, и живёт она до сведения. Фикстура гасит ОБЕ оси: ось 1 не берёт
# несведённую волну, ось 2 берёт её ревизию курсором и насчитывает ноль посадок.
# Поклеточные пробы выше этого не ловят: у них «монитор» заполнен датой, поэтому
# подмена «сведена» одной лишь пустотой оставляет их закрытыми и молчащими.
state "$TMP/w1" "$ROW_PREV" "$BASE_SAME" \
    "$(printf '%s-2\t—\t%s\t6\t—\t—' "$WAVE" "$TIP")"
plan "многострочная ведомость: последняя строка о волне, которая ИДЁТ — обе оси молчат" \
    "$TMP/w1" "$ROOT" "$TMP/one.jsonl" "" ""

# ── ПОРЯДОК СТРОК ПРОТИВ СВЕЖЕСТИ ДАТЫ ──────────────────────────────────────
#
# Курсор берётся по ПОЛОЖЕНИЮ строки, а дата «сведена» в выборе не участвует
# вовсе. Отличить одно от другого можно только на ведомости, где порядок и
# свежесть РАСХОДЯТСЯ, — а до шестого круга обе многострочные фикстуры несли
# даты по возрастанию, то есть совпадали. Подмена курсора на «самую свежую»
# оставляла гейт зелёным (код 0), меняя вердикт стража на противоположный.
#
# ЗНАМЕНАТЕЛЬ ЗДЕСЬ — НЕ СВОЙСТВО ДЕРЕВА, а число исходов сравнения двух
# величин: их ровно три, и вывести это неоткуда — трихотомия замкнута. Поэтому
# перечень классов выписан, а ПОКРЫТИЕ мерится по самим фикстурам (какие даты в
# них стоят), и снятая фикстура роняет его.
#
# ЖИВОЙ ВХОД — РАВЕНСТВО: две волны, сведённые в один день, — обычная смена.
# Убывание приходит с досыпанной задним числом строкой.
ORDER_KINDS=("возрастание" "равенство" "убывание")

state "$TMP/o1" \
    "$(printf '%s-1\t2026-09-19\t%s\t6\t2026-09-19\tкоордината' "$WAVE" "$FIRST")" \
    "$BASE_SAME" \
    "$(printf '%s-2\t2026-09-19\t%s\t6\t2026-09-19\tкоордината' "$WAVE" "$TIP")"
plan "две волны сведены В ОДИН ДЕНЬ: курсор — последняя ПО ПОРЯДКУ, молчит" \
    "$TMP/o1" "$ROOT" "$TMP/one.jsonl" "" ""

state "$TMP/o2" \
    "$(printf '%s-1\t2026-09-19\t%s\t6\t2026-09-19\tкоордината' "$WAVE" "$FIRST")" \
    "$BASE_SAME" \
    "$(printf '%s-2\t2026-09-01\t%s\t6\t2026-09-01\tкоордината' "$WAVE" "$TIP")"
plan "даты УБЫВАЮТ: курсор — последняя ПО ПОРЯДКУ, а не самая свежая, молчит" \
    "$TMP/o2" "$ROOT" "$TMP/one.jsonl" "" ""

# ── ОСЬ 3: модель исполнения ─────────────────────────────────────────────────
state "$TMP/s3" "$ROW_CLOSED" "$BASE_OTHER"
plan "ось 3: базовая модель ≠ модели транскрипта" \
    "$TMP/s3" "$ROOT" "$TMP/one.jsonl" "$(toks "model-beta" "model-alpha")" ""

state "$TMP/s3b" "$ROW_CLOSED" "$BASE_SAME"
plan "ось 3: в одном транскрипте две модели" \
    "$TMP/s3b" "$ROOT" "$TMP/two.jsonl" "$(toks "model-gamma" "model-alpha")" ""

state "$TMP/s3c" "$ROW_CLOSED" "$BASE_NONE"
plan "ось 3: базовая модель не записана" \
    "$TMP/s3c" "$ROOT" "$TMP/one.jsonl" "$(toks "model-alpha")" ""

state "$TMP/s3d" "$ROW_CLOSED" "$BASE_SAME"
plan "ось 3, близнец: побочная ветвь и синтетическая запись не считаются моделями" \
    "$TMP/s3d" "$ROOT" "$TMP/noise.jsonl" "" ""

# ── КРИВОЙ ВХОД: пустое поле в КАЖДОЙ позиции базы ──────────────────────────
state "$TMP/b1" "$ROW_CLOSED" "$(printf '\t2026-09-19\tориентиры')"
plan "база, поле 1 «модель» пусто — «не проверяли», а не смена модели" \
    "$TMP/b1" "$ROOT" "$TMP/one.jsonl" "" "$(toks "model-baseline.tsv" "ПУСТЫМ полем модели")" КРИВОЙ

state "$TMP/b2" "$ROW_CLOSED" "$(printf 'model-alpha\t\tориентиры')"
plan "база, поле 2 «замерено» пусто — модель читается, молчит" \
    "$TMP/b2" "$ROOT" "$TMP/one.jsonl" "" "" КРИВОЙ

state "$TMP/b3" "$ROW_CLOSED" "$(printf 'model-alpha\t2026-09-19\t')"
plan "база, поле 3 «ориентиры» пусто — модель читается, молчит" \
    "$TMP/b3" "$ROOT" "$TMP/one.jsonl" "" "" КРИВОЙ

# ── ТРЕТЬЯ КАТЕГОРИЯ: осматривать нечем ──────────────────────────────────────
#
# Пять ветвей ниже прошлый круг не достигал НИ ОДНОЙ пробой, и все пять живы в
# работе: `git-operator` заводит ведомость шапкой до первой волны; ревизия из
# подчищенной ветки перестаёт резолвиться; файл базы сносят; файл из одних
# комментариев; хук зовут руками при разборе, без полезной нагрузки.
state "$TMP/s4" "$ROW_CLOSED" "$BASE_SAME"
plan "нет транскрипта — «не проверяли», а не находка" \
    "$TMP/s4" "$ROOT" "$TMP/нет-такого.jsonl" "" "$(toks "транскрипт сессии не прочитан")"

state "$TMP/s5" "НЕТ" "$BASE_SAME"
plan "ведомости нет вовсе — «не проверяли», а не находка" \
    "$TMP/s5" "$ROOT" "$TMP/one.jsonl" "" "$(toks "ledger.tsv" "не читается")"

state "$TMP/s6" "ШАПКА" "$BASE_SAME"
plan "ведомость есть, строк данных нет — «не проверяли»" \
    "$TMP/s6" "$ROOT" "$TMP/one.jsonl" "" "$(toks "ledger.tsv" "НИ ОДНОЙ строки")"

state "$TMP/s7" "$ROW_CLOSED" "НЕТ"
plan "базы модели нет вовсе — «не проверяли»" \
    "$TMP/s7" "$ROOT" "$TMP/one.jsonl" "" "$(toks "model-baseline.tsv" "не читается")"

state "$TMP/s8" "$ROW_CLOSED" "ШАПКА"
plan "база модели есть, строк данных нет — «не проверяли»" \
    "$TMP/s8" "$ROOT" "$TMP/one.jsonl" "" "$(toks "model-baseline.tsv" "не несёт строки")"

state "$TMP/s9" "$ROW_CLOSED" "$BASE_SAME"
plan "полезной нагрузки на stdin нет — «не проверяли»" \
    "$TMP/s9" "$ROOT" "БЕЗ-НАГРУЗКИ" "" "$(toks "полезной нагрузки на входе нет")"

# ── ОБА БЛОКА РАЗОМ ──────────────────────────────────────────────────────────
#
