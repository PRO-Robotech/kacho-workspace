# объясняет разбор меток, и проза о сравнении засчиталась бы за сравнение —
# ровно класс «гейт читает текст, а не исполняемую часть» (`testing.md`
# §«Гейт на класс», п. 4). Отброшена строка, НАЧИНАЮЩАЯСЯ с `#`; сравнение,
# дописанное комментарием в конец строки кода, сюда попадёт и поднимет
# знаменатель — проверено: 18 из 24, код 1. Это единственный случай, где
# распознаватель ошибается в сторону РАЗБОРА (лишняя метка даёт красное), и
# только про него сказанное верно. ПО ФОРМЕ ЗАПИСИ он ошибается в сторону
