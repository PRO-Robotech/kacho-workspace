#!/usr/bin/env bash
# check-10 — СТРАЖ МОНИТОРА ФЛОУ заговаривает на своих признаках, называет ось
# КАЖДОЙ напечатанной строки — и находки, и «не проверяли», — и молчит на
# законных близнецах.
#
# ЧТО УТВЕРЖДАЕТ. `.claude/hooks/wave-monitor.sh` — страж, а не проза: он обязан
# печатать сигнал ровно тогда, когда предмет открыт, и молчать, когда закрыт.
# Проверяется ПОВЕДЕНИЕ: рядом с хуком кладутся ведомость волн, база модели
# исполнения и транскрипт с ЗАДАННЫМ содержимым, и читается то, что хук напечатал
# и каким кодом вышел.
#
# ПОЧЕМУ ПОВЕДЕНЧЕСКАЯ, А НЕ ТЕКСТОВАЯ. Искать в исходнике `if [ "$monitor" =` —
# значит ловить форму: хук волен считать строки awk'ом, вынести разбор в функцию,
# переименовать переменную. Текст сигнала тоже не закрепляется дословно: он
# переписывается вместе с нормой, и проверка на фразу покраснела бы на исправном
# страже — такую отключают первой. Закрепляются ДВА РАЗЛИЧИМЫХ ИСХОДА: «находка»
# и «осмотреть было нечем», и то, что второй не выдаётся за первый.
#
# ОСИ — ТРИ, И У КАЖДОЙ СВОЙ ЗАКОННЫЙ БЛИЗНЕЦ (`testing.md` §«Гейт на класс», п.2):
#
#   ось 1  строка ведомости открыта (поле «монитор» = «—»)     → сигнал
#          та же строка закрыта                                 → молчание
#   ось 2  посадок после курсора ≥ 4 при закрытой ведомости      → сигнал
#          посадок 3 — ровно порог минус один                    → молчание
#          посадок 1 — одна посадка самой полосы монитора        → молчание
#          ведомость из ДВУХ строк, курсор несёт ПОСЛЕДНЯЯ:
#              после последней посадок 0                         → молчание
#              после последней посадок 4                         → сигнал с ЕЁ ревизией
#              метка в поле «ствол» последней строки             → курсор откатывается
#                                                                  на предыдущую, сигнал
#                                                                  с ЕЁ ревизией
#              даты строк равны либо убывают                     → курсор всё равно
#                                                                  последний ПО ПОРЯДКУ,
#                                                                  молчание
#              последняя строка о волне, которая ИДЁТ            → молчание обеих осей
#   ось 3  базовая модель ≠ модели транскрипта                   → сигнал
#          моделей в транскрипте больше одной                    → сигнал
#          базовая модель не записана                            → сигнал
#          базовая совпала, модель одна                          → молчание
#
# КАЖДАЯ ИНЪЕКЦИЯ МЕНЯЕТ РОВНО ОДИН ФАКТ против контрольной фикстуры — иначе
# неизвестно, который из двух дал сигнал, и вердикт недействителен, оставаясь на
# вид зелёным (`change-graph.md` §6).
#
# ── ЧЕТВЁРТАЯ РЕДАКЦИЯ: ЧЕМ ОНА ОТЛИЧАЕТСЯ И ПОЧЕМУ ─────────────────────────
#
# Три предыдущие редакции приёмка опытом вернула по ОДНОМУ корню: утверждение
# оставалось зелёным при СНЯТОМ предмете. Опыты, которыми это показано, и то,
# что каждый из них теперь роняет:
#
#   `ALL_TOKENS=()`                    отрицательная половина была ВАКУУМНА:
#                                      словарь чужих предметов выписывался
#                                      литералом, и пустой словарь зеленил блоб
#   все `unexamined+=(…)` → константа  третья категория ни с какой осью не
#                                      связывалась: пробы утверждали лишь «блок
#                                      есть и он не блок находки»
#   `case "$find_block"` → `"$out"`    чтение по блоку не доказывалось ничем: ни
#   `done <<< "$find_block"` → `"$out"`один вход не печатал ОБА блока разом
#   снятые `musts` у FIND-пробы        проба без предмета молча становилась
#                                      утверждением «что-нибудь напечатано»
#   подмена ситуации оси 3             лишняя находка в блоке не замечалась:
#                                      сверялось наличие строки, не их ЧИСЛО
#
# Отсюда устройство, а не шесть заплат:
#
# 1. ПРОБЫ СНАЧАЛА ОБЪЯВЛЯЮТСЯ, ПОТОМ ИСПОЛНЯЮТСЯ. Объявление (`plan`) несёт
#    ожидаемое содержимое ОБОИХ блоков: сколько строк и какой предмет у каждой.
#    Словарь предметов `ALL_TOKENS` ВЫВОДИТСЯ из этих объявлений обходом, а не
#    выписывается. Опустеть незаметно он не может: у каждого объявленного набора
#    множество ЧУЖИХ предметов (словарь минус свои) обязано быть НЕПУСТО, иначе
#    отрицательная половина этого утверждения вакуумна — и это находка, а не
#    молчание.
#
# 2. МЕЖДУ ОБЪЯВЛЕННЫМИ ПРЕДМЕТАМИ И НАПЕЧАТАННЫМИ СТРОКАМИ ТРЕБУЕТСЯ ВЗАИМНО
#    ОДНОЗНАЧНОЕ СООТВЕТСТВИЕ. Каждый объявленный предмет обязан найти СВОЮ
#    строку (назвать все свои токены и ни одного чужого), и ни одна строка блока
#    не остаётся невостребованной. Прежняя редакция спрашивала «есть ли хоть одна
#    подходящая строка» — такое утверждение лишней находки не видит вовсе.
#
# 3. ТРЕТЬЯ КАТЕГОРИЯ СУДИТСЯ ТЕМ ЖЕ, ЧЕМ НАХОДКА. Строка «не проверяли» обязана
#    назвать СВОЮ ось (`ledger.tsv` и «не читается», `python3`, ревизию курсора)
#    и не назвать чужой. Раньше она не утверждала ничего, кроме факта своего
#    существования, — поэтому одна константа на все одиннадцать текстов проходила.
#
# 4. ЕСТЬ ФИКСТУРА, ПЕЧАТАЮЩАЯ ОБА БЛОКА РАЗОМ (открытая волна плюс нечитаемый
#    транскрипт). Без неё «читаем блок, а не весь вывод» было заявлением без
#    предмета: на входе с одним блоком `$out` и `$find_block` тождественны
#    посимвольно. На этом входе оба чтения расходятся, и расхождение ловится
#    двумя разными утверждениями: блок находки обязан назвать СВОЙ маршрут
#    (`tooling-maintainer`) и НЕ назвать маршрут третьей категории (`scout`), а
#    лишняя строка чужого блока становится невостребованной (п. 2).
#
# 5. ЗНАМЕНАТЕЛЬ ОБХОДА БЕРЁТСЯ ИЗ ИСХОДНИКА СТРАЖА. Число мест, где хук
#    печатает «не проверяли», считается по его тексту; объявленных РАЗЛИЧНЫХ
#    предметов третьей категории обязано быть не меньше. Заведённая в страже
#    двенадцатая такая ветвь краснит гейт, пока к ней не подана фикстура. Это
#    ровно то, чего не хватало прошлым кругам: недостижимая ветвь не давала ни
#    красного, ни зелёного — она молчала.
#    ПРЕДЕЛ НАЗВАН ЧЕСТНО: число ветвей выводится, а СООТВЕТСТВИЕ «эта фикстура
#    ведёт вот в ту ветвь» ведёт автор. Две фикстуры на одну ветвь при новой
#    ветви без фикстуры дадут сходящийся счёт и не будут замечены. Величина этой
#    слепой зоны — разность двух счётчиков, и она ПЕЧАТАЕТСЯ переписью; чем она
#    вызвана и почему не закрывается равенством — ниже, в разделе пятого круга.
#
# 6. ПОДПИСЬ ПЕРЕПИСИ ВЫВЕДЕНА ИЗ СЧЁТЧИКОВ ЦЕЛИКОМ. Прежняя несла фразу «у
#    каждой находки строка проверена на СВОЙ предмет» — и пережила свой предмет:
#    при снятых `musts` она печаталась по-прежнему. Теперь печатаются числа, а
#    числа расходиться с работой не умеют.
#
# ── ПЯТЫЙ КРУГ: ДВЕ ПРАВКИ, И ВТОРАЯ — ПРИЗНАНИЕ ЗАПАСА, А НЕ ЕГО СНЯТИЕ ────
#
# 1. ВЕДОМОСТЬ ИЗ ДВУХ СТРОК. Помощник `state` клал РОВНО ОДНУ строку данных,
#    поэтому ни одна из 28 проб четвёртого круга не подавала ведомость длиннее
#    одной строки, а на одной строке «первая» и «последняя» тождественны.
#    Контракт «ревизию ствола несёт ПОСЛЕДНЯЯ строка» объявлен дважды — в шапке
#    стража и в шапке самой `ledger.tsv` — и не держался ничем: опыт
#    `cursor == ""` (курсор берётся из первой строки) оставлял гейт ЗЕЛЁНЫМ,
#    код 0. Фикстур теперь две, по числу исходов ошибки — курсор уехал назад
#    (ложная находка) и вперёд (пропущенная), — и та же инъекция роняет обе.
#
# 2. ЗАПАС ПОКРЫТИЯ МЕСТ ПЕЧАТИ НАЗВАН ЧИСЛОМ, А НЕ ЗАКРЫТ РАВЕНСТВОМ. Сверка
#    п. 5 сравнивает ДВЕ РАЗНЫЕ ЕДИНИЦЫ: слева объявленные РАЗЛИЧНЫЕ ПРЕДМЕТЫ,
#    справа СТРОКИ ИСХОДНИКА стража. Одно место печати законно даёт несколько
#    различных предметов: строка ведомости — три (имя волны · «без имени» ·
#    «не названо»), ось 2 — два (по локальной ссылке и по удалённой). Поэтому
#    равенство ложно BY CONSTRUCTION, и это ИЗМЕРЕНО, а не выведено: сведение
#    обеих сверок по равенству краснит гейт на ИСПРАВНОМ дереве и исправном
#    страже — «страж печатает находку в 5 местах, а различных предметов находки
#    объявлено 8». Ложная находка отключает проверку первой, поэтому равенство
#    отвергнуто.
#    ЧТО ЭТО ЗНАЧИТ, СКАЗАНО ПРЯМО: разность двух счётчиков И ЕСТЬ слепая зона —
#    ровно столько НОВЫХ мест печати пройдёт МОЛЧА. Число здесь не выписано, его
#    печатает перепись строкой «запас покрытия»: выписанное рядом разошлось бы с
#    первой же новой пробой. Замер дня правки (2026-09-19): находки — 8
#    различных предметов при 5 местах печати, запас 3; третья категория — 11 при
#    11, запас 0. Обе стороны подтверждены опытом: шестое место `signals+=(` без
#    фикстуры гейт НЕ краснит (код 0), двенадцатое `unexamined+=(` — краснит
#    (код 1) и называет ветвь.
#    СНЯТЬ ЗАПАС МОЖЕТ ТОЛЬКО СМЕНА ЕДИНИЦЫ: соответствие «эта фикстура ведёт
#    вот в ту ветвь» обязано стать ИЗМЕРЯЕМЫМ (какая строка стража исполнилась),
#    а не выводимым из счёта предметов. Это другой предмет и другая работа; пока
#    она не сделана, запас читается как объявленный долг, а не как покрытие.
#
# ── ШЕСТОЙ КРУГ: У ВТОРОЙ ОСИ ПОЯВИЛСЯ ЗНАМЕНАТЕЛЬ ──────────────────────────
#
# Приёмка пятого круга разделила прибор на две оси и сказала прямо, чем они
# различаются. ОСЬ МЕСТ ПЕЧАТИ сходилась: знаменатель выводился из исходника
# стража, покрытие доказывалось убийством места. ОСЬ СОСТОЯНИЯ ВЕДОМОСТИ не
# сходилась, потому что знаменателя у неё НЕ БЫЛО ВОВСЕ: каждый круг находил
# ещё один непокрытый вход — четвёртый один, пятый ещё три. Класс, дважды
# отвергший работу, чинится не третьим кругом по тому же классу, а знаменателем.
#
# 1. ЗНАМЕНАТЕЛЬ СОСТОЯНИЙ ПОСЛЕДНЕЙ СТРОКИ — «ПОЛЕ × КЛАСС ЗНАЧЕНИЯ».
#    Полей столько, сколько их в шапке фикстуры; классов — столько меток
#    распознаватель нашёл в исходнике стража, плюс само значение. Поля
#    выводятся из `LEDGER_HEAD`. Метки выводятся из ОДНОЙ ФОРМЫ ЗАПИСИ
#    сравнения — `$N ==|!= "литерал"` — и только из неё. Метка в любой другой
#    законной форме (образец `~ /^—$/`, переменная `== DASH`, обратный порядок
#    `"—" == $N`, `index()`) знаменателю НЕВИДИМА, и её клетки уходят МОЛЧА.
#    Измерено приёмкой шестого круга и перемерено здесь: три сравнения стража
#    переписаны образцом при тождественном поведении — знаменатель 18 → 12,
#    код 0; третья метка добавлена обратным порядком `"н/д" == $2` — вердикт
#    стража перевёрнут, шесть новых клеток не поданы, код 0, перепись печатает
#    «18 из 18». Форма-образец при этом объявлена ЗАКОННЫМ БЛИЗНЕЦОМ в самом
#    `inject.sh`, дважды. Инъекция третьей метки там же доказывает ровно одно:
#    метка в ТОЙ ЖЕ форме записи поднимает знаменатель, — и ничего сверх.
#    ПОКРЫТИЕ МЕРИТСЯ ПО ФАЙЛАМ ФИКСТУР, а не по объявлениям проб: объявление
#    говорит, чего ЖДАЛИ, покрытие обязано говорить, что ПОДАЛИ. Снятая фикстура
#    роняет покрытие, даже если `plan` оставили на месте.
#
# 2. ПОРЯДОК СТРОК ПРОТИВ СВЕЖЕСТИ ДАТЫ — отдельный класс, и его знаменатель
#    НЕ ВЫВОДИТСЯ ИЗ ДЕРЕВА, а замкнут сам: сравнение двух величин даёт ровно
#    три исхода. Поэтому перечень классов здесь выписан, и сказано это прямо;
#    выводится ПОКРЫТИЕ — даты берутся из самих фикстур и классифицируются.
#    До шестого круга обе многострочные фикстуры несли даты по возрастанию, то
#    есть «последняя по положению» и «самая свежая» совпадали, и подмена одного
#    другим оставляла гейт ЗЕЛЁНЫМ (код 0) при вердикте стража, перевёрнутом на
#    противоположный.
#
# 3. ТРИ ОСТАТКА ПРИНЯТЫ ЧЕСТНО И НАЗВАНЫ ЧИСЛАМИ, а не закрыты. Два первых
#    названы приёмкой пятого круга, третий найден ОПЫТОМ на этой же правке — и
#    он не чинится здесь, потому что снимается той же сменой единицы, что и
#    второй.
#    · ПОБАЙТОВО СУДИТСЯ ОДИН ВХОД — контрольный: от него требуется ПУСТОЙ
#      вывод. Остальные судятся ПО БЛОКАМ, поэтому посторонняя строка, печатаемая
#      ПО УСЛОВИЮ вне обоих блоков, проходит молча: до первого заголовка `🌊`
#      разбор блока её не видит, а контроль её не вызывает. Погасить находку или
#      родить её такая строка не может, поэтому это остаток, а не дефект. Число
#      печатает перепись («побайтово судится 1 вход из N») и здесь не
#      выписывается: оно сдвигается с каждой новой пробой.
#    · ЗАПАС ПОКРЫТИЯ МЕСТ ПЕЧАТИ — слепая зона сверки п. 5 (ниже, раздел пятого
#      круга). Его величину печатает перепись, и на день правки он таков, что
#      ПРЕВЫШАЕТ цену любого одного места печати: у оси 2 на одном месте печати
#      объявлено ДВА различных предмета (по локальной ссылке и по удалённой),
#      значит снятие целого места вместе с его фикстурами сверка по числам не
#      заметит — заметят пробы, потерявшие свою находку. Снять запас может
#      только смена единицы (см. п. 2 пятого круга), и это другая работа.
#    · ФИКСТУРА, ВСЕ СОСТОЯНИЯ КОТОРОЙ ПОДАЁТ КТО-ТО ЕЩЁ, СНИМАЕТСЯ БЕЗ СЛЕДА.
#      Счётчики оси меряют ПОДАННОЕ, а не УТВЕРЖДАЕМОЕ, поэтому покрытие от
#      такого снятия не сдвигается, а утверждение исчезает. Число печатает
#      перепись: на день правки 6 из 17. СОСТАВ НЕОДНОРОДЕН, и назван:
#      5 из 6 — честная избыточность, их предмет поглощён матрицей шестого
#      круга (две фикстуры пятого круга подают одни значения; три поклеточные
#      пробы с меткой «—» делят клетки с фикстурой идущей волны); 1 из 6 — w1,
#      фикстура волны, которая ИДЁТ, — ЕДИНСТВЕННЫЙ ДЕРЖАТЕЛЬ своего
#      утверждения. Проверено перекрёстной матрицей приёмки (7 состояний × 9
#      инъекций) и перемерено здесь: сними w1 — гейт зелёный, «18 из 18», а
#      инъекция «метка «—» у поля «сведена» перестаёт означать «волна идёт»»
#      перестаёт краснеть: код 0, провалов 0. Утверждение шестого круга
#      снимается из гейта бесследно.
#      Требованием уникальности это НЕ чинится — оно снесло бы пять избыточных
#      вместе с w1 (разбор при самом счётчике). Единицей «какая строка стража
#      исполнилась» — ТОЖЕ НЕ чинится, и прежняя редакция это обещала ложно:
#      метки живут ВНУТРИ awk-программы (строки 152–154 стража), след bash их
#      не видит — 0 строк трассы на них; у w1 и у трёх соседних фикстур строки
#      стража исполняются одинаково.
#      ЧЕСТНАЯ ЕДИНИЦА ЗНАМЕНАТЕЛЯ НАЗВАНА, НО НЕ РЕАЛИЗОВАНА — ПО ПОВЕДЕНИЮ:
#      подать полю набор кандидатов и сосчитать РАЗЛИЧИМЫЕ выводы стража. Она
#      от формы записи независима by construction. Прогон приёмки дал по
