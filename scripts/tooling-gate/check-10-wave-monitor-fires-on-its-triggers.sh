# ── ОХВАТ СОСТОЯНИЙ ПОСЛЕДНЕЙ СТРОКИ — МЕРИТСЯ ПО ФАЙЛАМ ФИКСТУР ────────────
#
# Не по объявлениям проб, и это несущее: объявление говорит, чего ЖДАЛИ, а
# покрытие обязано говорить, что ПОДАЛИ. Снятая фикстура роняет покрытие, даже
# если её `plan` кто-то оставил на месте, — и наоборот, `plan` без фикстуры
# покрытия не даёт.
#
# Разбор строки — awk'ом: `read -r` с `IFS=$'\t'` схлопнул бы подряд идущие
# табуляции и объявил бы пустое поле отсутствующим. Измерять охват кривого входа
# прибором, слепым к кривому входу, значило бы получить зелёное по построению.
value_class() {   # класс значения ПО МЕТКАМ САМОГО СТРАЖА
    local v="$1" m
    for m in ${HOOK_MARKS[@]+"${HOOK_MARKS[@]}"}; do
        [ "$v" = "$m" ] && { mark_label "$m"; return 0; }
    done
    printf 'значение'
}

declare -A SUPPLY_N=()   # ключ состояния → СКОЛЬКО фикстур его подают
FIX_KEYS=()              # по фикстуре: её ключи, через пробел
multirow=0
for ((i = 0; i < ${#P_NAME[@]}; i++)); do
    led="${P_STATE[i]}/ledger.tsv"
    [ -r "$led" ] || continue
    mapfile -t data_rows < <(awk -F'\t' '/^[ \t]*#/ { next } NF == 0 { next } { print }' "$led")
    [ "${#data_rows[@]}" -ge 2 ] || continue
    multirow=$((multirow + 1))
    keys=""

    mapfile -t row_cells < <(printf '%s\n' "${data_rows[-1]}" |
        awk -F'\t' -v n="$LEDGER_FIELDS" '{ for (k = 1; k <= n; k++) print $k }')
    for ((f = 1; f <= LEDGER_FIELDS; f++)); do
        key="$f|$(value_class "${row_cells[$((f - 1))]:-}")"
        SUPPLY_N["$key"]=$(( ${SUPPLY_N["$key"]:-0} + 1 ))
        keys+="${keys:+ }$key"
    done

    # Порядок дат двух ПОСЛЕДНИХ строк — только когда обе несут дату: у метки
    # порядка нет, и классифицировать её значило бы сочинить четвёртый исход.
    d_last="$(printf '%s\n' "${data_rows[-1]}" | awk -F'\t' '{ print $2 }')"
    d_prev="$(printf '%s\n' "${data_rows[-2]}" | awk -F'\t' '{ print $2 }')"
    if [ "$(value_class "$d_last")" = "значение" ] && [ "$(value_class "$d_prev")" = "значение" ]; then
        key="порядок|$(awk -v a="$d_prev" -v b="$d_last" \
            'BEGIN { print (a < b) ? "возрастание" : ((a == b) ? "равенство" : "убывание") }')"
        SUPPLY_N["$key"]=$(( ${SUPPLY_N["$key"]:-0} + 1 ))
        keys+="${keys:+ }$key"
    fi
    FIX_KEYS+=("$keys")
done

# ── ТРЕТИЙ ОСТАТОК, НАЙДЕННЫЙ ОПЫТОМ И НАЗВАННЫЙ ЧИСЛОМ ─────────────────────
#
# Счётчики этой оси меряют ПОДАННОЕ, а не УТВЕРЖДАЕМОЕ. Поэтому фикстура, все
# состояния которой подаёт ещё какая-то другая, снимается БЕЗ следа: покрытие
# не сдвинется, а её утверждение исчезнет. Измерено опытом на этой же правке —
# снятие пробы «поле „монитор“ последней строки = метка» оставило гейт ЗЕЛЁНЫМ
# (код 0), потому что ту же клетку подаёт фикстура волны, которая идёт; снятие
# пробы «поле „ствол“ пусто» — покраснело (код 1) и назвало клетку.
#
# ЭТО НЕ ЧИНИТСЯ ТРЕБОВАНИЕМ УНИКАЛЬНОСТИ: оно снесло бы ровно те пробы, ради
# которых ось заводилась, — две фикстуры пятого круга подают одни значения и
# различаются ТЕМ, ЧТО УТВЕРЖДАЮТ (какая ревизия стала курсором), а фикстура
# идущей волны ценна СОЧЕТАНИЕМ меток, которого нет ни у одной поклеточной, и
# она среди этих N — ЕДИНСТВЕННЫЙ держатель своего утверждения (шапка, третий
# остаток шестого круга). Единицей «какая строка стража исполнилась» это тоже
# не снимается: метки решаются внутри awk-программы, и след bash по ним пуст.
# Величина печатается, а не умалчивается; честная единица названа в шапке.
shadowed=0
for keys in ${FIX_KEYS[@]+"${FIX_KEYS[@]}"}; do
    own=0
    for k in $keys; do [ "${SUPPLY_N[$k]}" -eq 1 ] && own=1; done
    [ "$own" = 0 ] && shadowed=$((shadowed + 1))
done

cells_missing=()
for ((f = 1; f <= LEDGER_FIELDS; f++)); do
    for cl in "${CLASS_LABELS[@]}"; do
        [ "${SUPPLY_N["$f|$cl"]:-0}" -gt 0 ] ||
            cells_missing+=("поле $f «${FIELD_NAMES[$((f - 1))]}» × $cl")
    done
done
cells_covered=$(( LAST_ROW_CELLS - ${#cells_missing[@]} ))
if [ "${#cells_missing[@]}" -ne 0 ]; then
    fail "состояние ПОСЛЕДНЕЙ строки многострочной ведомости покрыто $cells_covered клетками из $LAST_ROW_CELLS; без фикстуры: ${cells_missing[*]} — клетка без фикстуры не даёт ни красного, ни зелёного, она молчит"
fi

# Кривой вход на ПОСЛЕДНЕЙ строке — та же перепись, что у однострочной
# ведомости, и тем же числом полей: пустое поле обязано побывать в КАЖДОЙ
# позиции, иначе разборщик слеп к ней ровно там, где решается курсор.
EMPTY_CLASS="$(value_class "")"
empties_tail=0
for ((f = 1; f <= LEDGER_FIELDS; f++)); do
    [ "${SUPPLY_N["$f|$EMPTY_CLASS"]:-0}" -gt 0 ] && empties_tail=$((empties_tail + 1))
done
if [ "$empties_tail" -ne "$LEDGER_FIELDS" ]; then
    fail "кривой вход на ПОСЛЕДНЕЙ строке многострочной ведомости подан в $empties_tail позициях из $LEDGER_FIELDS: на однострочной ведомости «первая» и «последняя» тождественны, поэтому позиция без такой пробы вердикта о курсоре не даёт"
fi

orders_missing=()
for k in "${ORDER_KINDS[@]}"; do
    [ "${SUPPLY_N["порядок|$k"]:-0}" -gt 0 ] || orders_missing+=("$k")
done
orders_covered=$(( ${#ORDER_KINDS[@]} - ${#orders_missing[@]} ))
if [ "${#orders_missing[@]}" -ne 0 ]; then
    fail "порядок дат двух последних строк покрыт $orders_covered классами из ${#ORDER_KINDS[@]}; без фикстуры: ${orders_missing[*]} — там, где порядок и свежесть совпадают, «последняя по положению» и «самая свежая» неразличимы, и подмена одного другим проходит молча"
fi

# Перепись ВЫВЕДЕНА ИЗ СЧЁТЧИКОВ ЦЕЛИКОМ. Прежняя несла фразу «у каждой находки
# строка проверена на СВОЙ предмет» — и пережила свой предмет: при снятых
# объявлениях она печаталась по-прежнему. Число этого не умеет.
#
# ЗАПАС ПОКРЫТИЯ ПЕЧАТАЕТСЯ ОТДЕЛЬНОЙ ВЕЛИЧИНОЙ — это слепая зона сверки п. 5,
# а не её результат: ровно столько новых мест печати пройдёт молча. Ноль здесь
# означает, что следующая же новая ветвь стража покраснеет; положительное число
# означает объявленный долг (шапка, раздел пятого круга).
#
# ЧИСЛО ПОБАЙТОВО СУДИМЫХ ВХОДОВ — ВТОРОЙ ОБЪЯВЛЕННЫЙ ОСТАТОК, и он печатается
# рядом по той же причине: величина меняется с каждой новой пробой, и выписанная
# в прозе разошлась бы с ней молча (шапка, раздел шестого круга).
slack_find=$(( ${#UNIQ_FIND[@]} - hook_find_sites ))
slack_unex=$(( ${#UNIQ_UNEX[@]} - hook_unex_sites ))
tooling_gate_census "$NAME: стражей осмотрено ${#HOOKS[@]}; проб исполнено $probes (контроль 1 сверх них) — ждали находку $n_find, ждали «не проверяли» $n_unex, ждали ОБА блока разом $n_both, ждали молчание $n_silent; кривой вход подан в $empties позициях из $positions (ведомость $LEDGER_FIELDS + база $BASE_FIELDS); многострочных фикстур $multirow, кривой вход на их ПОСЛЕДНЕЙ строке подан в $empties_tail позициях из $LEDGER_FIELDS; состояние последней строки покрыто $cells_covered клетками из $LAST_ROW_CELLS (полей $LEDGER_FIELDS × классов ${#CLASS_LABELS[@]}: ${CLASS_LABELS[*]} — классы выведены из стража, меток сверки ${#HOOK_MARKS[@]}); порядок дат двух последних строк покрыт $orders_covered классами из ${#ORDER_KINDS[@]} (${ORDER_KINDS[*]}); фикстур, снятие которых счётчики НЕ заметят: $shadowed из $multirow — их состояния подаёт кто-то ещё; объявлено предметов: находок $declared_find (различных ${#UNIQ_FIND[@]} при $hook_find_sites местах печати), «не проверяли» $declared_unex (различных ${#UNIQ_UNEX[@]} при $hook_unex_sites местах печати); запас покрытия мест печати: находки $slack_find, третья категория $slack_unex — столько НОВЫХ мест печати пройдёт молча; побайтово судится 1 вход из $((probes + 1)); строк сверено с объявленным предметом $lines_checked из $((declared_find + declared_unex)); словарь чужих предметов выведен из объявлений, в нём ${#ALL_TOKENS[@]}"

if [ "$findings" -gt 0 ]; then
    tooling_gate_fail "$NAME" "проб с находкой: $findings"
    exit 1
fi

tooling_gate_pass "$NAME" "страж зовёт на каждом из своих признаков, называет ось каждой напечатанной строки, молчит на законных близнецах и не выдаёт «не проверяли» за находку"
