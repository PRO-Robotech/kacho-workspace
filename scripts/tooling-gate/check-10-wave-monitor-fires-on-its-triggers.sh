# У поля ведомости столько классов, сколько меток нашёл распознаватель ниже,
# плюс само значение. Распознаватель — греп по ОДНОЙ форме записи сравнения,
# `$N ==|!= "литерал"`. Метка, записанная любой другой законной формой
# (образец, переменная, обратный порядок, `index()`), ему невидима: знаменатель
# не растёт, клетки уходят молча. Предикат: прогон с метками стража,
# переписанными образцом, даёт код 0 при УМЕНЬШИВШЕМСЯ знаменателе (18 → 12);
# третья метка обратным порядком — код 0 при прежнем (18 из 18). Разбор шапки,
# п. 1 шестого круга.
