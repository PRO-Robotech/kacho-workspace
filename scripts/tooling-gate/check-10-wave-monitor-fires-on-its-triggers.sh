MARK_FIND="МОНИТОР ФЛОУ: предмет открыт"
MARK_UNEX="осмотреть удалось НЕ ВСЁ"

# Маршруты двух блоков. Они РАЗНЫЕ, и это несущее: блок находки зовёт полосу
# монитора, блок «не проверяли» — разведку. Утверждение «в блоке находки нет
# маршрута третьей категории» — половина доказательства того, что читается блок,
# а не весь вывод.
ROUTE_FIND="tooling-maintainer"
ROUTE_UNEX="scout"

# Разделители объявления. Байты выбраны неразмечаемые: предметы осей содержат и
# пробелы («без имени», «по ссылке origin/main»), и кириллицу, поэтому делить по
# пробелу нельзя.
US=$'\x1f'   # между предметами одной строки
RS=$'\x1e'   # между строками одного блока

# Транскрипты фикстуры: одна модель и две. Форма записи снята с настоящего
# транскрипта (`message.model` у ассистентской записи главного потока), а не
# придумана: хук читает ровно её.
printf '%s\n' \
    '{"type":"assistant","isSidechain":false,"message":{"model":"model-alpha"}}' \
    > "$TMP/one.jsonl"
printf '%s\n' \
    '{"type":"assistant","isSidechain":false,"message":{"model":"model-gamma"}}' \
    '{"type":"assistant","isSidechain":false,"message":{"model":"model-alpha"}}' \
    > "$TMP/two.jsonl"
# Посторонние записи, которые хук обязан пропускать: побочная ветвь и отметка,
# сочинённая харнессом. Без них «одна модель» доказывалось бы на входе, где
# второй модели и не предлагали.
printf '%s\n' \
    '{"type":"assistant","isSidechain":true,"message":{"model":"model-sidechain"}}' \
    '{"type":"assistant","isSidechain":false,"message":{"model":"<synthetic>"}}' \
    '{"type":"assistant","isSidechain":false,"message":{"model":"model-alpha"}}' \
    > "$TMP/noise.jsonl"

# Шапки фикстур — ЕДИНСТВЕННЫЙ источник числа полей: перепись кривого входа
# считает позиции по ним, а не по выписанному «9».
LEDGER_HEAD=$'# волна\tсведена\tствол\tполос\tмонитор\tисход'
BASE_HEAD=$'# модель\tзамерено\tориентиры'
LEDGER_FIELDS="$(printf '%s' "$LEDGER_HEAD" | awk -F'\t' '{print NF}')"
BASE_FIELDS="$(printf '%s' "$BASE_HEAD" | awk -F'\t' '{print NF}')"

# state <каталог> <строка ведомости> <строка базы> [ещё строки ведомости…]
#
# «НЕТ» — файла не существует вовсе; «ШАПКА» — файл есть, а строк данных в нём
# нет. Это РАЗНЫЕ ветви стража, и обе печатают свой текст: подменять одну другой
# значило бы оставить вторую недостижимой.
#
# ДОВОДЫ ПОСЛЕ ТРЕТЬЕГО — ВТОРАЯ И ДАЛЬШЕ СТРОКИ ДАННЫХ ведомости, в порядке
# записи. До пятого круга помощник клал РОВНО ОДНУ, и оттого ни одна из проб не
# подавала ведомость длиннее одной строки: на ней «первая» строка и «последняя»
# тождественны, поэтому контракт «ревизию ствола несёт ПОСЛЕДНЯЯ строка» не
# проверялся ничем — опыт «брать курсор из первой» оставлял гейт зелёным, код 0.
state() {
    local dir="$1" row="$2" base="$3" extra
    shift 3
    mkdir -p "$dir"
    rm -f "$dir/ledger.tsv" "$dir/model-baseline.tsv"
    if [ "$row" != "НЕТ" ]; then
        { printf '%s\n' "$LEDGER_HEAD"
          [ "$row" = "ШАПКА" ] || printf '%s\n' "$row"
          for extra in "$@"; do printf '%s\n' "$extra"; done; } > "$dir/ledger.tsv"
    fi
    if [ "$base" != "НЕТ" ]; then
        { printf '%s\n' "$BASE_HEAD"
          [ "$base" = "ШАПКА" ] || printf '%s\n' "$base"; } > "$dir/model-baseline.tsv"
    fi
}

# repo <каталог> <сколько коммитов> <метка> — печатает ревизию ПЕРВОГО коммита.
#
# Личность задаётся ключами вызова, а не настройкой машины: на ранере её может
# не быть вовсе, и коммит бы не состоялся, оставив ось 2 без предмета молча.
# Переменные окружения git снимаются: унаследованный GIT_DIR сильнее рабочего
# каталога и увёл бы запись в ЭТУ рабочую копию.
#
# МЕТКА ВХОДИТ В СООБЩЕНИЕ КОММИТА, и это не украшение: два пустых коммита с
# одинаковым сообщением, деревом, личностью и секундой дают ОДНУ И ТУ ЖЕ ревизию.
# Ревизии двух репозиториев-фикстур — предметы разных проб, и совпади они,
# отрицательная половина обеих утверждала бы про один токен.
repo() {
    local dir="$1" n="$2" tag="$3" i
    mkdir -p "$dir"
    (
        unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
              GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_COMMON_DIR GIT_PREFIX
        git -C "$dir" init -q -b main
        for ((i = 0; i < n; i++)); do
            git -C "$dir" -c user.name=fixture -c user.email=fixture@invalid \
                commit -q --allow-empty -m "$tag-c$i"
        done
    ) >/dev/null 2>&1
    git -C "$dir" rev-list --max-parents=0 main
}

# remote <каталог> <ревизия> — заводит remote-tracking ссылку БЕЗ сети.
#
# Без неё класс «локальный main отстаёт» выпадал из охвата by construction:
# `git init` удалённого не заводит, и проба доказывала бы только запасной путь.
remote() { git -C "$1" update-ref refs/remotes/origin/main "$2" >/dev/null 2>&1; }

# rewind <каталог> <ревизия> — отводит локальный main назад, оставляя origin/main
# впереди: ровно то расхождение, что живёт в рабочем дереве.
rewind() { git -C "$1" reset -q --hard "$2" >/dev/null 2>&1; }

# block <вывод> <маркер заголовка> — строки ОДНОГО блока вывода.
# Оба блока начинаются со своего значка, поэтому граница читается без
# закрепления формулировок: меняется текст — граница остаётся.
block() { printf '%s\n' "$1" | awk -v mark="$2" '/^🌊/ { inb = (index($0, mark) > 0) } inb { print }'; }

# ── ОБЪЯВЛЕНИЕ ПРОБ ──────────────────────────────────────────────────────────
#
# `plan` НИЧЕГО НЕ ИСПОЛНЯЕТ. Сначала объявляются все пробы, из объявлений
# выводится словарь предметов, и только потом пробы прогоняются. Порядок
# несущий: словарь, собранный по ходу исполнения, был бы неполон у первых проб.
P_NAME=(); P_STATE=(); P_ROOT=(); P_TR=(); P_FIND=(); P_UNEX=(); P_EMPTY=(); P_NOPY=()
empties=0

toks() { local out="" t; for t in "$@"; do out+="${out:+$US}$t"; done; printf '%s' "$out"; }
rows() { local out="" s; for s in "$@"; do out+="${out:+$RS}$s"; done; printf '%s' "$out"; }

plan() {   # plan <имя> <состояние> <корень> <транскрипт> <находки> <не-проверяли> [КРИВОЙ] [БЕЗ-PYTHON]
    P_NAME+=("$1"); P_STATE+=("$2"); P_ROOT+=("$3"); P_TR+=("$4")
    P_FIND+=("$5"); P_UNEX+=("$6")
    shift 6
    local flags=" $* "
    case "$flags" in *" КРИВОЙ "*) P_EMPTY+=(1); empties=$((empties + 1)) ;; *) P_EMPTY+=(0) ;; esac
    case "$flags" in *" БЕЗ-PYTHON "*) P_NOPY+=(1) ;; *) P_NOPY+=(0) ;; esac
}

