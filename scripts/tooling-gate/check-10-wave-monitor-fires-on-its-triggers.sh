        "$TMP/s11" "$ROOT" "$TMP/one.jsonl" "" "$(toks "python3")" БЕЗ-PYTHON
fi

# ── СЛОВАРЬ ПРЕДМЕТОВ: ВЫВЕДЕН ИЗ ОБЪЯВЛЕНИЙ, А НЕ ВЫПИСАН ──────────────────
#
# Он же даёт отрицательную половину утверждения: чужое для набора — это «весь
# словарь минус свои». Выписанный словарь разошёлся бы с первой новой пробой, а
# ПУСТОЙ зеленил бы всё — ровно это приёмка и показала опытом `ALL_TOKENS=()`.
# Опустеть незаметно он теперь не может: пустое множество чужих у любого набора
# объявляется находкой ниже.
ALL_TOKENS=()
UNIQ_FIND=()
UNIQ_UNEX=()
declared_find=0
declared_unex=0

add_token() {
    local t="$1" x
    [ -n "$t" ] || return 0
    for x in ${ALL_TOKENS[@]+"${ALL_TOKENS[@]}"}; do [ "$x" = "$t" ] && return 0; done
    ALL_TOKENS+=("$t")
}
add_uniq() {   # add_uniq <имя массива> <набор>
    local -n bag="$1"
    local s="$2" x
    for x in ${bag[@]+"${bag[@]}"}; do [ "$x" = "$s" ] && return 0; done
    bag+=("$s")
}

for ((i = 0; i < ${#P_NAME[@]}; i++)); do
    for side in FIND UNEX; do
        if [ "$side" = FIND ]; then decl="${P_FIND[i]}"; else decl="${P_UNEX[i]}"; fi
        [ -n "$decl" ] || continue
        mapfile -d "$RS" -t sets_a < <(printf '%s' "$decl")
        for s in "${sets_a[@]}"; do
            [ -n "$s" ] || continue
            if [ "$side" = FIND ]; then
                declared_find=$((declared_find + 1)); add_uniq UNIQ_FIND "$s"
            else
                declared_unex=$((declared_unex + 1)); add_uniq UNIQ_UNEX "$s"
            fi
            mapfile -d "$US" -t toks_a < <(printf '%s' "$s")
            for t in "${toks_a[@]}"; do add_token "$t"; done
        done
    done
done

# ── ЗНАМЕНАТЕЛЬ ОБХОДА: сколько мест страж вообще умеет печатать ────────────
#
# Считается ПО ИСХОДНИКУ СТРАЖА, а не по памяти автора. Новая ветвь без фикстуры
# роняет гейт: недостижимая ветвь иначе не даёт ни красного, ни зелёного —
# она молчит, и молчание неотличимо от исправной работы.
HOOK_SRC="$WS/$HOOK_REL"
hook_unex_sites="$(grep -c 'unexamined+=(' "$HOOK_SRC" || true)"
hook_find_sites="$(grep -c 'signals+=(' "$HOOK_SRC" || true)"

findings=0
probes=0
n_find=0; n_unex=0; n_both=0; n_silent=0
lines_checked=0

fail() { tooling_gate_fail "$NAME" "$1"; findings=$((findings + 1)); }

# ── СВЕРКА БЛОКА С ОБЪЯВЛЕНИЕМ ───────────────────────────────────────────────
#
# LINES — строки-находки разбираемого блока; заполняется вызывающим, чтобы
# чтение ИМЕННО блока (а не всего вывода) стояло на виду в `probe`.
LINES=()
match_sets() {   # match_sets <имя пробы> <ярлык блока> <объявление>
    local pname="$1" label="$2" decl="$3"
    local -a sets_a=() own=() used=()
    local s i j tok m mine ok foreign matched left
    mapfile -d "$RS" -t sets_a < <(printf '%s' "$decl")
    for s in "${sets_a[@]}"; do
        [ -n "$s" ] || continue
        mapfile -d "$US" -t own < <(printf '%s' "$s")

        # ОТРИЦАТЕЛЬНАЯ ПОЛОВИНА обязана иметь предмет. Пустое множество чужих
        # означает, что «и ни одного чужого» не проверяет ничего, — утверждение
        # вакуумно, и зелёное на нём есть ложь о работе.
        foreign=0
        for tok in ${ALL_TOKENS[@]+"${ALL_TOKENS[@]}"}; do
            mine=0; for m in "${own[@]}"; do [ "$tok" = "$m" ] && mine=1; done
            [ "$mine" = 0 ] && foreign=$((foreign + 1))
        done
        if [ "$foreign" -eq 0 ]; then
            fail "$pname — словарь предметов пуст либо целиком принадлежит этому набору (${own[*]}): отрицательная половина утверждения ВАКУУМНА, и блок $label ею не проверяется"
            continue
        fi

        matched=-1
        for ((j = 0; j < ${#LINES[@]}; j++)); do
            [ "${used[j]:-0}" = 1 ] && continue
            ok=1
            for tok in "${own[@]}"; do
                case "${LINES[j]}" in *"$tok"*) ;; *) ok=0 ;; esac
            done
            [ "$ok" = 1 ] || continue
            for tok in ${ALL_TOKENS[@]+"${ALL_TOKENS[@]}"}; do
                mine=0; for m in "${own[@]}"; do [ "$tok" = "$m" ] && mine=1; done
                [ "$mine" = 1 ] && continue
                case "${LINES[j]}" in *"$tok"*) ok=0 ;; esac
            done
            [ "$ok" = 1 ] || continue
            matched=$j; used[j]=1; break
        done

        if [ "$matched" -lt 0 ]; then
            fail "$pname — в блоке $label НИ ОДНА строка не называет объявленный предмет (${own[*]}) и только его: ось со своим предметом не связана"
        else
            lines_checked=$((lines_checked + 1))
        fi
    done

    # Невостребованная строка — это НАПЕЧАТАННОЕ, чего проба не объявляла.
    # Прежняя редакция спрашивала «есть ли подходящая строка» и лишней не
    # видела: подмена ситуации, дающая вторую находку, проходила молча.
    left=0
    for ((j = 0; j < ${#LINES[@]}; j++)); do
        [ "${used[j]:-0}" = 1 ] || { left=$((left + 1)); fail "$pname — в блоке $label строка, которой проба не объявляла: «${LINES[j]}»"; }
    done
    return 0
}

probe() {   # probe <индекс>
    local i="$1"
    local name="${P_NAME[i]}" st="${P_STATE[i]}" root="${P_ROOT[i]}" tr="${P_TR[i]}"
    local fdecl="${P_FIND[i]}" udecl="${P_UNEX[i]}"
    local out code find_block unex_block line
    probes=$((probes + 1))

    local -a env_pfx=(env)
    [ "${P_NOPY[i]}" = 1 ] && env_pfx=(env "PATH=$NOPY_BIN")

    if [ "$tr" = "БЕЗ-НАГРУЗКИ" ]; then
        out="$(
            printf '' |
            "${env_pfx[@]}" KACHO_WAVE_MONITOR_DIR="$st" CLAUDE_PROJECT_DIR="$root" \
                bash "$WS/$HOOK_REL" 2>&1
        )" && code=0 || code=$?
    else
        out="$(
            printf '{"hook_event_name":"UserPromptSubmit","transcript_path":"%s"}' "$tr" |
            "${env_pfx[@]}" KACHO_WAVE_MONITOR_DIR="$st" CLAUDE_PROJECT_DIR="$root" \
                bash "$WS/$HOOK_REL" 2>&1
        )" && code=0 || code=$?
    fi

    if [ "$code" -ne 0 ]; then
        fail "$name — страж вышел кодом $code: указатель обязан выходить нулём, иначе он роняет обращение к сессии"
        return 0
    fi

    find_block="$(block "$out" "$MARK_FIND")"
    unex_block="$(block "$out" "$MARK_UNEX")"

    if [ -n "$fdecl" ] && [ -n "$udecl" ]; then n_both=$((n_both + 1))
    elif [ -n "$fdecl" ]; then n_find=$((n_find + 1))
    elif [ -n "$udecl" ]; then n_unex=$((n_unex + 1))
    else n_silent=$((n_silent + 1)); fi

    # ── БЛОК НАХОДКИ ─────────────────────────────────────────────────────────
    if [ -n "$fdecl" ]; then
        if [ -z "$find_block" ]; then
            # ДИАГНОСТИКА НАЗЫВАЕТ ПРИЧИНУ, А НЕ СИМПТОМ. «Страж молчит» и
            # «страж напечатал, но заголовок не опознан» — разные починки, и
            # прежний текст посылал читателя не туда: он говорил «молчит» там,
            # где заголовок был сдвинут на один пробел.
            if [ -z "$out" ]; then
                fail "$name — предмет открыт, а страж не напечатал НИЧЕГО: он молчит там, где обязан звать"
            else
                fail "$name — страж напечатал $(printf '%s\n' "$out" | wc -l) строк, но блока находки среди них НЕТ: заголовок обязан начинаться со значка 🌊 и нести маркер «$MARK_FIND». Первая строка: «${out%%$'\n'*}»"
            fi
            return 0
        fi
        # Маршрут — ИЗ БЛОКА НАХОДКИ, и чужого маршрута в нём быть не должно.
        # Вторая половина не украшение: блок «не проверяли» зовёт разведку, и на
        # входе с ДВУМЯ блоками чтение всего вывода вместо блока ловится ровно ею.
        case "$find_block" in
            *"$ROUTE_FIND"*) ;;
            *)  fail "$name — находка напечатана, а полоса «$ROUTE_FIND» в ЕЁ блоке не названа: диспетчеру нечего поставить" ;;
        esac
        case "$find_block" in
            *"$ROUTE_UNEX"*)
                fail "$name — в блоке находки стоит маршрут третьей категории «$ROUTE_UNEX»: либо читается не свой блок, а весь вывод, либо страж смешал маршруты двух блоков — они обязаны различаться, иначе «предмет открыт» и «осмотреть было нечем» приходят диспетчеру одним заказом" ;;
        esac
        # Строки-находки берутся ИЗ БЛОКА, и чтение стоит на виду здесь, а не в
        # помощнике: подмена `$find_block` на `$out` — ровно тот дефект, ради
        # которого заведена фикстура «оба блока разом», и он обязан быть виден
        # в одной строке с утверждением, которое от него зависит.
        LINES=()
        while IFS= read -r line; do
            case "$line" in *"·"*) LINES+=("$line") ;; esac
        done <<< "$find_block"
        match_sets "$name" "находки" "$fdecl"
    elif [ -n "$find_block" ]; then
        fail "$name — блок находки напечатан, а проба его НЕ ОБЪЯВЛЯЛА: либо страж зовёт на закрытом предмете, либо утверждение пробы вакуумно — предмета у неё нет"
    fi

    # ── БЛОК «НЕ ПРОВЕРЯЛИ» ──────────────────────────────────────────────────
    if [ -n "$udecl" ]; then
        if [ -z "$unex_block" ]; then
            if [ -z "$out" ]; then
                fail "$name — осматривать было нечем, а страж не напечатал НИЧЕГО: «не проверяли» неотличимо от «чисто»"
            else
                fail "$name — страж напечатал $(printf '%s\n' "$out" | wc -l) строк, но блока «не проверяли» среди них НЕТ: заголовок обязан начинаться со значка 🌊 и нести маркер «$MARK_UNEX». Первая строка: «${out%%$'\n'*}»"
            fi
            return 0
        fi
        case "$unex_block" in
            *"$ROUTE_UNEX"*) ;;
            *)  fail "$name — «не проверяли» напечатано, а разведка «$ROUTE_UNEX» в ЕГО блоке не названа: диспетчеру нечего поставить" ;;
        esac
        LINES=()
        while IFS= read -r line; do
            case "$line" in *"·"*) LINES+=("$line") ;; esac
        done <<< "$unex_block"
        match_sets "$name" "«не проверяли»" "$udecl"
    elif [ -n "$unex_block" ]; then
        fail "$name — блок «не проверяли» напечатан, а проба его НЕ ОБЪЯВЛЯЛА: осмотрено не то, что задумано фикстурой"
    fi
}

for ((i = 0; i < ${#P_NAME[@]}; i++)); do probe "$i"; done

# ── СВЕРКА ОХВАТА ────────────────────────────────────────────────────────────
positions="$((LEDGER_FIELDS + BASE_FIELDS))"
if [ "$empties" -ne "$positions" ]; then
    fail "кривой вход подан в $empties позициях из $positions (ведомость $LEDGER_FIELDS + база $BASE_FIELDS): позиция без пробы — слепая зона разборщика"
fi
if [ "${#ALL_TOKENS[@]}" -eq 0 ]; then
    fail "словарь предметов пуст: он выводится из объявлений проб, и пустой означает, что ни одна проба предмета не объявила"
fi
if [ "${#UNIQ_UNEX[@]}" -lt "$hook_unex_sites" ]; then
    fail "страж печатает «не проверяли» в $hook_unex_sites местах, а различных предметов третьей категории объявлено ${#UNIQ_UNEX[@]}: ветвь без фикстуры не даёт ни красного, ни зелёного — она молчит"
fi
if [ "${#UNIQ_FIND[@]}" -lt "$hook_find_sites" ]; then
    fail "страж печатает находку в $hook_find_sites местах, а различных предметов находки объявлено ${#UNIQ_FIND[@]}: ветвь без фикстуры не даёт ни красного, ни зелёного — она молчит"
fi
if [ "$nopy" != 1 ]; then
    fail "ветвь «нет python3» осталась без фикстуры: урезанный PATH не собрался, и о ней вердикта НЕТ"
fi

# Перепись ВЫВЕДЕНА ИЗ СЧЁТЧИКОВ ЦЕЛИКОМ. Прежняя несла фразу «у каждой находки
# строка проверена на СВОЙ предмет» — и пережила свой предмет: при снятых
# объявлениях она печаталась по-прежнему. Число этого не умеет.
#
# ЗАПАС ПОКРЫТИЯ ПЕЧАТАЕТСЯ ОТДЕЛЬНОЙ ВЕЛИЧИНОЙ — это слепая зона сверки п. 5,
# а не её результат: ровно столько новых мест печати пройдёт молча. Ноль здесь
# означает, что следующая же новая ветвь стража покраснеет; положительное число
# означает объявленный долг (шапка, раздел пятого круга).
slack_find=$(( ${#UNIQ_FIND[@]} - hook_find_sites ))
slack_unex=$(( ${#UNIQ_UNEX[@]} - hook_unex_sites ))
tooling_gate_census "$NAME: стражей осмотрено ${#HOOKS[@]}; проб исполнено $probes (контроль 1 сверх них) — ждали находку $n_find, ждали «не проверяли» $n_unex, ждали ОБА блока разом $n_both, ждали молчание $n_silent; кривой вход подан в $empties позициях из $positions (ведомость $LEDGER_FIELDS + база $BASE_FIELDS); объявлено предметов: находок $declared_find (различных ${#UNIQ_FIND[@]} при $hook_find_sites местах печати), «не проверяли» $declared_unex (различных ${#UNIQ_UNEX[@]} при $hook_unex_sites местах печати); запас покрытия мест печати: находки $slack_find, третья категория $slack_unex — столько НОВЫХ мест печати пройдёт молча; строк сверено с объявленным предметом $lines_checked из $((declared_find + declared_unex)); словарь чужих предметов выведен из объявлений, в нём ${#ALL_TOKENS[@]}"

if [ "$findings" -gt 0 ]; then
    tooling_gate_fail "$NAME" "проб с находкой: $findings"
    exit 1
fi

tooling_gate_pass "$NAME" "страж зовёт на каждом из своих признаков, называет ось каждой напечатанной строки, молчит на законных близнецах и не выдаёт «не проверяли» за находку"
