#!/usr/bin/env bash
# Прогон набора tooling-gate. Вердикт стоит в КОДЕ ВЫХОДА, а не в печати.
#
# Три исхода, а не два: 0 — осмотрено N, находок 0; 1 — находки, каждая названа
# координатой; 2 (VOID) — проверять нечего, предпосылка проверки не выполнена.
# VOID НЕ засчитывается за успех: «ноль находок» и «ноль прочитанного» — разные
# вещи, и неразличение этих двух исходов уже держало один механизм этого репо
# невыполненным и ненаблюдаемым (см. `.claude/rules/ai-tooling.md`).
#
# До 2026-08-30 набор не различал VOID и находку вовсе: `bash "$check" || rc=1`
# схлопывал их в единицу, и беспредметная проверка приходила вызывающему тем же
# кодом, что и нарушение. Теперь исход у каждого свой — см. блок вердикта ниже.
set -uo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

ok=0; bad=0; void=0; ran=0
for check in "$here"/check-*.sh; do
    # Глоб без совпадений подставляет САМ СЕБЯ, и без этой строки `ran`
    # становился единицей на пустом каталоге — то есть ветка «ни одной проверки
    # не найдено» ниже была НЕДОСТИЖИМА, а пустой обход краснел как обычная
    # находка от `bash <глоб>` → 127.
    [ -f "$check" ] || continue
    ran=$((ran + 1))
    bash "$check"
    case $? in
        0) ok=$((ok + 1)) ;;
        2) void=$((void + 1)) ;;
        *) bad=$((bad + 1)) ;;
    esac
done

if [ "$ran" -eq 0 ]; then
    echo "[FAIL] run-all — ни одной проверки не найдено в $here; о дереве не прочитано ничего" >&2
    exit 1
fi

echo "[CENSUS] run-all: исполнено проверок $ran; пройдено $ok, провалено $bad, без предмета $void"

# ── ВЕРДИКТ: ТРИ ИСХОДА, И У КАЖДОГО СВОЙ КОД ────────────────────────────────
#
#   0 — рассмотрено N, находок 0, у каждой проверки был предмет;
#   1 — НАХОДКА: проверка упала, либо обход пуст (о дереве не прочитано ничего);
#   2 — БЕЗ ПРЕДМЕТА: находок нет, но часть проверок не с чем было сверять.
#
# До 2026-08-30 второй и третий исход давали ОДИН код, и вызывающий не мог их
# различить: «гейт нашёл нарушение» и «гейту нечего было смотреть» приходили
# единицей. Из рабочей копии без клона продукта единицу получала КАЖДАЯ отправка
# — то есть красное приходило всегда и по причине, к дереву не относящейся, а
# такое красное перестают читать вместе с настоящими находками (ws#458).
#
# ПОРЯДОК ПРОВЕРКИ КОДОВ — НЕСУЩИЙ, А НЕ КОСМЕТИЧЕСКИЙ. Находка объявляется
# ПЕРВОЙ: набор, где есть и находка, и беспредметная проверка, обязан выйти
# единицей. Обратный порядок сделал бы «без предмета» маской — достаточно было бы
# одной беспредметной проверки, чтобы настоящая находка перестала блокировать.
#
# ПУСТОЙ ОБХОД ОСТАЁТСЯ НАХОДКОЙ (код 1), а не «без предмета»: ноль рассмотренных
# проверок означает, что каталог переехал и о дереве не прочитано НИЧЕГО, — это
# отказ самого набора, а не отсутствие условия у отдельной проверки.

if [ "$bad" -gt 0 ]; then
    echo "[FAIL] run-all — набор красный: находок $bad" >&2
    exit 1
fi
if [ "$void" -gt 0 ]; then
    echo "[VOID] run-all — без предмета $void из $ran; находок нет, но эти проверки не выполнялись" >&2
    exit 2
fi
echo "[PASS] run-all — исполнено $ran, все зелёные"
