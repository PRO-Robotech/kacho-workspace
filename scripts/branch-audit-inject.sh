    fi
  else
    say "❌ AD" "старый comm-подход неожиданно дал верный ответ БЕЗ диагностики — предпосылка AD не подтвердилась при LOCALE_FIXTURE_TRIGGERS_COMM_BUG=1 (противоречие в самой пробе)"
    fail=1
