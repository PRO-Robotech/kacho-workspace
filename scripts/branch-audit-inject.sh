# --- AC/AD. КОНТРОЛЬ ПРЕДПОСЫЛКИ + ПРЯМОЕ ДОКАЗАТЕЛЬСТВО, ЧТО ПИННИНГ ОДИН ------
# НЕ СПАСАЕТ. AC отвечает на «даёт ли фикс (awk-хэш) верный ответ на входе,
# который ломает comm из PATH». AD — «дал бы верный ответ СТАРЫЙ подход (comm
# ОБОИХ концов под LC_ALL=C), будь он ещё в дереве». Если предпосылка не
# подтвердилась (comm из PATH этот вход не путает — другая машина, другая
# версия), AC/AD печатают «БЕЗ ПРЕДМЕТА» и не портят вердикт: находка тут не
# в самой пробе, а в том, что на ЭТОЙ машине класс не воспроизводится.
