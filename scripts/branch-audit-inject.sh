# branch-audit-inject.sh — доказательство того, что перепись веток СПОСОБНА
# упасть и способна смолчать. Инъекция в обе стороны на синтетическом
# репозитории, который скрипт создаёт сам и сносит за собой.
#
# ЗАЧЕМ. Перепись, которая не падала ни разу, неотличима от переписи, которая
# падать не умеет. Проверка «ноль находок» имеет смысл, только если рядом
# показано, что на настоящей находке она краснеет И называет имя.
#
# Число утверждений здесь не выписывается: его печатает последняя строка
# прогона, счётом вызовов say. Метки: A, A2, B–Z, R2, Y2, AA–AZ, BA–BZ, CA–CG;
# что держит каждая —
#   A. ветка-работа без origin и с непустой дельтой → код 1 + её имя в выводе;
#   B. влитая ветка → код 0, её имени в списке «единственный экземпляр» нет;
#   C. ПЯТЫЙ ПРИЗНАК: ветка не предок ствола, нет на origin, но содержимое
#      уже в стволе (внесено схлопыванием) → код 0, НЕ находка;
#   D. ветка, занятая рабочей копией, помечена как занятая;
#   E. резервная ссылка refs/original/** названа отдельно;
#   H. ветка на origin с работой → «живая», не находка;
#   I. ветка на origin, поглощённая стволом → «без предмета», найдена дельтой;
#   J. origin действительно опрошен (объём осмотренного не нулевой);
#   K. ШЕСТОЙ ПРИЗНАК, молчание: ветка поглощена, а ствол правил тот же файл
#      ПОСЛЕ вливания → пятый даёт конфликт, шестой обязан промолчать;
#   L. законный близнец к K: тот же силуэт, но содержимого ствол не видел →
#      ОСТАЁТСЯ находкой с именем (иначе шестой глушил бы настоящую работу);
#   M. работа влита в накопительную origin/release/* → не находка, источник назван;
#   N. объём по новым осям напечатан (стволов в сверке, шестой признак спрошен);
#   O/P/Q. --prune-merged снимает влитое, НЕ трогает единственные экземпляры и
#      занятые рабочей копией, и называет причину каждого пропуска;
#   R. ТРЕТИЙ ЗАМЕР (6в), сторона МОЛЧАНИЯ: содержимое ветки внесено в ствол
#      ДРУГИМ блобом (доработка в PR), поэтому (6а) и (6б) молчат — перепись
#      обязана узнать строки и отнести ветку к влитым;
#   S. половина переписи про СНЯТИЕ: ветка сняла строку, ствол её сохранил →
#      влитой ветка НЕ становится (иначе снятие терялось бы молча);
#   T. СЕДЬМОЙ ПРИЗНАК, тревога: ствол пути не касался вовсе → раздел «работа в
#      стволе НЕ ВСЯ» называет ветку ПО ИМЕНИ;
#   U. законный близнец к T: ранний черновик, чью переработку ствол принял в
#      том же файле → в тревогу НЕ попадает, а называется отдельным разделом
#      «поглощение не установлено» с числами переписи;
#   V. объём третьего замера напечатан (спрошена по N файлам, найдено по M);
#   W. правка, каждая строка которой в стволе уже есть, а путь ствол не трогал:
#      перепись говорит «отсутствует 0», ветка ВСЁ РАВНО остаётся работой;
#   X. перепись не расширяет `--prune-merged`: узнанное ею построчно не снимается.
#   AA. содержимое, доказанно ломающее СТОРОННИЙ `comm` (issue #540, второй
#      круг — на дереве продукта `LC_ALL=C comm` считала не отсортированными
#      файлы, которые `LC_ALL=C sort -c` на тех же байтах признаёт
#      отсортированными), у ФИКСА всё равно даёт верный счёт;
#   AB. во всём выводе прогона нет ни одной жалобы «not in sorted order»;
#   AC/AD. КОНТРОЛЬ ПРЕДПОСЫЛКИ + ПРЯМОЕ доказательство «пиннинг обеих сторон
#      недостаточен»: AC — починка (awk-хэш) даёт верный счёт на входе,
#      ломающем comm из PATH; AD — СТАРЫЙ подход (comm, оба конца LC_ALL=C)
#      на ЭТОМ ЖЕ входе даёт неверный счёт. Предпосылка (что вход вообще
#      ломает comm из PATH СЕГОДНЯ) проверяется отдельно и печатается как
#      «БЕЗ ПРЕДМЕТА», если не подтвердилась, — а не подделывается зелёным;
#   AE. один и тот же прогон под LC_ALL=C и под LANG=ru_RU.UTF-8 (LC_ALL
#      пуст — окружение из тела issue #540) даёт ДОСЛОВНО совпадающий раздел
#      по ветке AA и ни одной жалобы на порядок ни под одной локалью;
#   AF–AI. РЕЖИМ КАНДИДАТОВ: по двум названным веткам разделы и строки те же, что
#      у полной переписи; судятся только они — ни локальная, ни ветка origin
#      сверх названных в разделы и в счёт осмотренного не попадает; время и
#      объём напечатаны; ненайденный кандидат назван и даёт код 2, рядом с
#      находкой — 1;
#   AQ. найденный чистый кандидат рядом с ненайденным → код 2 от ненайденного, а
#      не от пустого обхода (AI этого не различает: один ненайденный даёт код 2
#      и строкой «не осмотрено ни одной ветки»);
#   AR. найденный кандидат не называется ненайденным: один — код 0 и «не найдено
#      0», рядом с ненайденным — в перечне ненайденных только тот;
#   AS. кандидат, который есть ТОЛЬКО на origin, судится: его строка та же, что у
#      полной переписи, осмотрен одной веткой origin, не назван ненайденным;
#   AT–AW. мутация каждого из четырёх фактов режима кандидатов (код 2 от
#      ненайденного · отметка осмотра · суд origin · отбор на origin) красит
#      своё утверждение (AQ, AR, AS, AG);
#   AX. мутация, которая не легла, — отказ, а не суд над прежней копией:
#      предпосылка AL–AP и AT–AW;
#   AJ–AP. САМОПРОБА ПАКЕТНОГО РАЗБОРА (ws#813): на отдельном репозитории, где у
#      каждого ускорителя и каждой формы отступления есть свой файл, пакетный
#      режим дословно равен поштучному эталону по всему перечню файлов и по
#      первым трём (AJ), ускорители действительно сработали (AK), а мутация
#      каждого ускорителя, чья ошибка меняет вердикт, делает сверку красной и
#      меняет вердикт названной ветки (AL–AP, AY);
#   AZ–BK. ФОРМЫ ЗАПИСИ ПРЕДМЕТА, дефект которых эталон и пакет делили (сверка
#      режимов к ним слепа, поэтому вердикт судится у каждого режима отдельно):
#      AZ — единственный экземпляр под пятью формами имени (нелатиница, табуляция,
#      хвостовой пробел, знак образца, ведущее «:») осмотрен и назван; BA —
#      близнецы тех же форм поглощены; BB — неосмотренный путь поглощением не
#      считается (мутант промаха); BC/BD/BE — PR: открытый новее закрытого, PR из
#      чужого репозитория, неполная перепись PR (подставной gh); BF — ветка под
#      именем тега; BG — неоднозначный ствол — отказ; BH — накопительная ветка
#      глубины три; BI — временные индексы release/a/b и release/a_b; BJ — рабочая
#      копия с пробелом в пути; BK — кандидат полным именем ссылки;
#   BL–BZ. МУТАНТЫ ЧЕТВЁРТОГО КРУГА: имя цели переименования (BL, M8), снятый как
#      добавленный (BM, M10), проверка целиком — всегда и по каждому члену
#      (BN–BQ); ускоритель без предмета красит счёт AK (BR — целиком, BS —
#      пофайлово); тёзка после любой «/» (BT, D1); ключ кэша (BU, D2 — счётом,
#      вердикт держит BV); незаписавшийся ответ истории (BV); пути истории и
#      касания — сами, с -z (BW, BX); перечень ствола не ASCII (BY, предпосылка —
#      BZ).
#   CA–CG. ЦЕЛИ КАСКАДА И ВЕТКА БЕЗ СВОЕГО КОММИТА (ws#847, круг 2): со стволом
#      эпика `--prune-merged` оставляет волну без своего коммита (CA), снимает
#      задачу, влитую в эпик коммитом слияния, — законный близнец (CB),
#      оставляет цель из BRANCH_AUDIT_KEEP (CC) и ветку по умолчанию, чья
#      голова — второй родитель догона (CD); итог считает «к снятию» за вычетом
#      целей и веток без своего коммита (CE); мутация исключения по первой
#      линии и мутация исключения целей красят свои утверждения (CF, CG).
#
# ЗАЧЕМ W и X. Первая редакция починки #257 давала переписи решать ОБА вопроса,
# и ветка «пропущенная проверка ошибки» — работа в единственном экземпляре, чьи
# строки все до одной есть в стволовом файле, — попадала в «ВЛИТЫ» и снималась.
# Починка ложных находок открыла дыру там, где ошибка необратима.
#
# ЗАЧЕМ T и U ВМЕСТЕ. До 2026-08-19 оба случая давали одну и ту же находку, и
# доля ложных в разделе тревоги достигала 100 % (задача #257). Инъекция обязана
# показывать ОБА исхода на одном силуэте — иначе «раздел молчит» неотличимо от
# «раздел разучился находить».
#
# Использование: scripts/branch-audit-inject.sh [путь-к-branch-audit.sh]

set -euo pipefail

HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
AUDIT="${1:-$HERE/branch-audit.sh}"
[ -x "$AUDIT" ] || { echo "inject: не найден исполняемый $AUDIT" >&2; exit 2; }

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# Синтетический «origin» + рабочая копия. Личность задаётся ЛОКАЛЬНО, только
# для этого одноразового репозитория, — настройки машины не трогаются.
git init -q --bare "$TMP/origin.git"
git init -q -b main "$TMP/work"
cd "$TMP/work"
git config user.email inject@example.invalid
git config user.name  inject
git config commit.gpgsign false
git remote add origin "$TMP/origin.git"

echo "ствол" > trunk.txt
git add trunk.txt && git commit -qm "исходный ствол"
git push -qu origin main

# --- A. работа в единственном экземпляре: нет на origin, дельта не пуста ------
git checkout -qb work-only-local
echo "правка, существующая в одном экземпляре" > only-local.txt
git add only-local.txt && git commit -qm "работа, которой нет нигде больше"

# --- B. влитая ветка: предок ствола -------------------------------------------
git checkout -q main
git checkout -qb work-merged
echo "влитое" > merged.txt
git add merged.txt && git commit -qm "работа, которая уедет в ствол"
git checkout -q main
git merge -q --no-ff -m "влить work-merged" work-merged
git push -q origin main

# --- C. пятый признак: содержимое в стволе, но ветка НЕ предок -----------------
# Схлопывание: тот же результат внесён другим коммитом, поэтому ни
# --is-ancestor, ни статус PR ветку влитой не считают, а дельта слияния пуста.
git checkout -q main
git checkout -qb work-squashed
echo "внесено схлопыванием" > squashed.txt
git add squashed.txt && git commit -qm "работа, которую внесут схлопыванием"
git checkout -q main
git merge -q --squash work-squashed
git commit -qm "схлопнуто из work-squashed"
git push -q origin main

# --- D. ветка, занятая рабочей копией -----------------------------------------
git branch occupied-branch main
git worktree add -q "$TMP/wt-occupied" occupied-branch

# Вторая занятая ветка — копией БРОШЕННОЙ: в ней никто не работает, и её не
# трогали дольше порога тишины. Возраст выставляется явно, а не ожиданием:
# проба, ждущая шесть часов, не проба.
git branch abandoned-branch main
git worktree add -q "$TMP/wt-abandoned" abandoned-branch
touch -d "30 hours ago" "$TMP/wt-abandoned"

# --- H. ветка НА ORIGIN, несущая работу → «живая», не находка -------------------
git checkout -q main
git checkout -qb pushed-alive
echo "работа, сданная на origin" > pushed.txt
git add pushed.txt && git commit -qm "работа, лежащая и на origin"
git push -qu origin pushed-alive
git checkout -q main

# --- I. ветка НА ORIGIN, чьё содержимое уже в стволе → «без предмета» ----------
git checkout -qb pushed-absorbed
echo "поглощённое" > absorbed.txt
git add absorbed.txt && git commit -qm "работа, которую поглотит ствол"
git push -qu origin pushed-absorbed
git checkout -q main
git merge -q --squash pushed-absorbed
git commit -qm "схлопнуто из pushed-absorbed"
git push -q origin main

# --- AS. ветка ТОЛЬКО НА ORIGIN: локальной ссылки нет, содержимое в стволе -----
# Остальные ветки origin в этом репозитории есть и локально, поэтому без неё
# режим кандидатов ни разу не судил бы ветку, которую видно лишь на origin.
git checkout -qb origin-only-absorbed
echo "сдано и поглощено, локальной ссылки нет" > origin-only.txt
git add origin-only.txt && git commit -qm "работа, которая останется только на origin"
git push -qu origin origin-only-absorbed
git checkout -q main
git merge -q --squash origin-only-absorbed
git commit -qm "схлопнуто из origin-only-absorbed"
git push -q origin main
git branch -q -D origin-only-absorbed

# --- K. ШЕСТОЙ ПРИЗНАК, сторона МОЛЧАНИЯ ---------------------------------------
# Ветка влита схлопыванием, а ПОТОМ ствол правил тот же файл. Пятый признак даёт
# конфликт (add/add), и в одиночку он объявил бы ветку расщеплённой работой —
# ровно тот ложный класс, ради которого шестой и заведён. Шестой обязан узнать
# блоб ветки в истории ствола и промолчать.
git checkout -q main
git checkout -qb absorbed-then-trunk-moved
printf 'строка один\n' > shared.txt
git add shared.txt && git commit -qm "работа, которую внесут схлопыванием"
git checkout -q main
git merge -q --squash absorbed-then-trunk-moved
git commit -qm "схлопнуто из absorbed-then-trunk-moved"
printf 'строка один\nствол дописал строку\n' > shared.txt
git add shared.txt && git commit -qm "ствол правит тот же файл ПОСЛЕ вливания"
git push -q origin main

# --- L. ШЕСТОЙ ПРИЗНАК, сторона НАХОДКИ ----------------------------------------
# Законный близнец к K: тот же файл, тот же силуэт конфликта — но содержимого
# ветки ствол не видел никогда. Обязана остаться находкой С ИМЕНЕМ, иначе
# шестой признак глушил бы настоящую работу заодно с ложной.
git checkout -qb never-landed main
printf 'строка один\nправка, которой в стволе не было\n' > shared.txt
git add shared.txt && git commit -qm "работа, не доехавшая никуда"
git checkout -q main

# --- M. НАКОПИТЕЛЬНАЯ ВЕТКА как второй ствол ------------------------------------
# Работа влита не в main, а в origin/release/*. «Нет в main» здесь не означает
# «нет нигде», и перепись обязана назвать источник поглощения.
git checkout -qb work-in-accum main
echo "работа, уехавшая в накопительную ветку" > accum.txt
git add accum.txt && git commit -qm "работа для накопительной ветки"
git checkout -qb release/accum main
git merge -q --squash work-in-accum
git commit -qm "схлопнуто в накопительную ветку"
git push -qu origin release/accum >/dev/null 2>&1
git checkout -q main

# --- R. ТРЕТИЙ ЗАМЕР, сторона МОЛЧАНИЯ ------------------------------------------
# Ветка создала файл; в ствол он попал ДРУГИМ блобом — с дописанной строкой,
# как бывает после доработки по ревью. Поэтому (6а) не ложится (содержимое
# ствола другое), (6б) молчит (блоба ветки в стволе не было НИКОГДА), и до
# третьего замера ветка объявлялась несущей непоглощённую работу. Перепись
# обязана узнать все добавленные строки и отнести ветку к влитым.
git checkout -q main
git checkout -qb draft-absorbed-by-lines
printf 'строка A\nстрока B\n' > absorbed-lines.txt
git add absorbed-lines.txt && git commit -qm "работа, которая доедет переработанной"
git checkout -q main
printf 'строка A\nстрока B\nстрока C\n' > absorbed-lines.txt
git add absorbed-lines.txt && git commit -qm "то же содержимое, но с доработкой"
git push -q origin main

# --- S. половина переписи про СНЯТИЕ ---------------------------------------------
# Работа ветки — УДАЛЕНИЕ строки, и ствол её не принял. Добавленных строк у
# ветки нет вовсе, поэтому перепись по одному лишь добавленному объявила бы
# ветку поглощённой и открыла бы её снятию. Половина про снятое обязана это
# отвергнуть.
git checkout -q main
printf 'строка одна\nстрока, которую ветка снимает\n' > removal.txt
git add removal.txt && git commit -qm "строка, которую ствол сохранит"
git push -q origin main
git checkout -qb removal-not-taken
printf 'строка одна\n' > removal.txt
git add removal.txt && git commit -qm "ветка снимает строку"
git checkout -q main
printf 'строка одна\nстрока, которую ветка снимает\nствол дописал третью\n' > removal.txt
git add removal.txt && git commit -qm "ствол правит файл, снятое сохраняет"
git push -q origin main

# --- T. СЕДЬМОЙ ПРИЗНАК, сторона ТРЕВОГИ -----------------------------------------
# Ствол этого пути после ответвления не касался ни одним коммитом — значит
# содержимое ветки туда попасть НЕ МОГЛО. Это доказательство непоглощения, и
# раздел «работа в стволе НЕ ВСЯ» обязан назвать ветку по имени.
git checkout -q main
git checkout -qb pr-closed-work-left
printf 'работа, до которой ствол не дотрагивался\n' > untouched-by-trunk.txt
git add untouched-by-trunk.txt && git commit -qm "второй предмет ветки, не доехавший никуда"
git checkout -q main

# --- Y/Z. машинно собираемый файл не делает работу расщеплённой -----------------
# Указатель хранилища пересобирается в каждой ветке, поэтому его дельта со
# стволом непуста ВСЕГДА. Перечень такого выводится опросом генераторов, а не
# выписывается: здесь заводится настоящий генератор с ключом `--outputs`.
mkdir -p scripts/vault-index
# Свой выход генератор выводит образцом pathspec, как генератор, спрашивающий
# git: буквальный pathspec переписи до него доходить не должен (иначе выход
# пуст, и Y/Y2 краснеют).
cat > scripts/vault-index/generate.py <<'GEN'
import subprocess, sys
if "--outputs" in sys.argv:
