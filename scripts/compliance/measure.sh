#!/usr/bin/env bash
# Прибор соблюдения регламента. НЕ ГЕЙТ ДЕРЕВА и потому НЕ `run-all.sh`:
# гейт обязан быть дёшев и прогоняться перед каждой отправкой, а этот прибор
# стоит 40-80 минут и порядка 2 млн токенов на посадку. Имя `run-all.sh`
# обещало бы дешёвую проверку — и его первым делом поймал `tooling-gate`,
# потребовав от прогонщика трёх исходов на подставном дереве.
#
# Прогоняется ПЕРЕД всяким изменением раскладки
# правил и ПОСЛЕ него — иначе изменение неопровержимо.
#
# Исходов три (как у прочих наборов дерева):
#   0  прогнано и посчитано
#   1  находка: соблюдение упало ниже полосы
#   2  без предмета: нет копий посадок либо не отвечает `claude -p`
#
# ВНИМАНИЕ, ЦЕНА НАЗВАНА ЧИСЛОМ: полный прогон одной посадки — восемь предметов
# настоящей работы, 40-80 минут и порядка 2 млн токенов. Это не проверка на
# каждый push; это гейт на ИЗМЕНЕНИЕ РЕГЛАМЕНТА.
set -uo pipefail
HERE="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
ПОСАДКА="${1:-}"
КОПИЯ="${2:-}"
if [ -z "$ПОСАДКА" ] || [ -z "$КОПИЯ" ]; then
  echo "применение: measure.sh <base|lane|lane2|pact> <путь к копии воркспейса>"
  echo "предмета нет: копия посадки не названа"
  exit 2
fi
[ -d "$КОПИЯ/.claude" ] || { echo "предмета нет: $КОПИЯ не похож на копию воркспейса"; exit 2; }
command -v claude >/dev/null || { echo "предмета нет: claude недоступен"; exit 2; }
python3 "$HERE/harness.py" "$ПОСАДКА" "$КОПИЯ" "$HERE/bench.json"
