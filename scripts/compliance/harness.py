#!/usr/bin/env python3
"""Прогон прибора соблюдения на одной посадке.

ЧТО МЕРИТСЯ. Не токены и не время — ДОЛЯ ВЫПОЛНЕННЫХ ТРЕБОВАНИЙ РЕГЛАМЕНТА.
Исполнителю даётся задание, НЕ перечисляющее требований; требования он обязан
знать из регламента. Произведённый файл судится выражениями, каждое из которых
проверено второй головой в обе стороны: не зеленеет на мусоре и не краснеет на
честной работе.

ПОЧЕМУ ДВЕ ПОСАДКИ И ЧЕМ ОНИ РАЗЛИЧАЮТСЯ РОВНО ОДНИМ. `base` — как сегодня: весь
корпус читается автоматически, задание несёт только предмет. `lane` —
предлагаемое: в автозагрузке ядро, а применимое правило кладётся В ЗАДАНИЕ, как
того и требует §14а («задание самодостаточно, у агента пустой контекст»).

ТРЕТЬЯ КАТЕГОРИЯ НАЗЫВАЕТСЯ ОТДЕЛЬНО. Файл не создан, прогон оборван по времени,
выражение не исполнилось — это «не выполнилось», а не «не соблюдено». В долю
соблюдения оно не вычитается и в успех не зачитывается: иначе упавший прогон
читался бы как нарушение регламента.
"""
from __future__ import annotations
import json, os, re, subprocess, sys, time

СТЕНД = "/home/dk/tmp/comp"
# Какое правило применимо к какому предмету — карта оркестратора.
# Это и есть предмет проверки: способен ли он выбрать верно.
# Чем работа будет СУДИТЬСЯ — то, что оркестратор знает, а исполнитель нет.
# Регламент этого дерева держится гейтами (393 пробы в продукте, 36 проверок в
# воркспейсе), и назвать судью дешевле, чем переслать весь текст правила.
ГЕЙТЫ = {
    "gate":      "scripts/*/inject.sh — доказательство инъекцией в обе стороны; "
                 "прогон гейта на пустом дереве обязан отличаться от прогона на чистом",
    "watcher":   "прогон самого наблюдателя: он обязан завершиться сам и назвать исход",
    "commit":    "чтение человеком в git log --oneline: заголовок обязан помещаться",
    "issue":     "предикат снятия из тела задачи — его прогоняет тот, кто закрывает",
    "probe":     "internal/repohygiene TestConsoleProbeIssueLinksNameATaskAndLive"
                 "InsideTheProbe — ссылка обязана стоять внутри вызова пробы",
    "report":    "повтор каждого названного числа его же командой",
    "migration": "internal/repohygiene TestNewMigrationOutranksEveryAppliedOne "
                 "плюс интеграционная проба с конкурирующими транзакциями",
    "rpc":       "buf lint · buf breaking · гейт каталога разрешений · "
                 "internal/repohygiene TestEmptyPageNeverPrecedesPaginationValidation",
}

КАРТА = {
    "gate":      ["testing.md"],
    "watcher":   ["multi-agent-flow.md"],
    "commit":    ["git-issues.md"],
    "issue":     ["multi-agent-flow.md"],
    "probe":     ["ui.md"],
    "report":    ["writing.md"],
    "migration": ["data-integrity.md"],
    "rpc":       ["api-conventions.md"],
}


def правило_текст(корень: str, имена: list[str]) -> str:
    куски = []
    for н in имена:
        for каталог in (".claude/rulebook", ".claude/rules"):
            p = os.path.join(корень, каталог, н)
            if os.path.exists(p):
                куски.append(f"# РЕГЛАМЕНТ, применимый к этой работе — {н}\n\n"
                             + open(p, encoding="utf-8").read())
                break
    return "\n\n".join(куски)


ВОРКСПЕЙС = "/home/dk/workspace/github/PRO-Robotech/cloud-demo/kacho-workspace"


def прогнать(посадка: str, корень: str, пункт: dict, вкладывать: str) -> dict:
    ид = пункт["id"]
    # Задания сочинялись с координатами НАСТОЯЩЕГО воркспейса. Оставить их —
    # значит писать обеими посадками в одно дерево и вдобавок пачкать рабочую
    # копию владельца: посадки перестали бы различаться, а замер — существовать.
    задание = пункт["task_text"].replace(ВОРКСПЕЙС, корень)
    # Координата ВНЕ воркспейса переписывается и в ЗАДАНИИ, а не только в том,
    # где я её ищу. Иначе агент пишет по названному ему адресу, а проверка
    # смотрит в другой — и честно сделанная работа читается как «не выполнилось».
    сыр = пункт["artifact_path"]
    if os.path.isabs(сыр) and ВОРКСПЕЙС not in сыр:
        задание = задание.replace(
            сыр, os.path.join(корень, "tmp/bench", os.path.basename(сыр)))
    if вкладывать == "lane":
        текст = правило_текст(корень, КАРТА.get(ид, []))
        if текст:
            задание = (текст
                       + "\n\n---\n\nЗАДАНИЕ. Регламент выше связывает эту работу.\n\n"
                       + задание)
    elif вкладывать == "lane2":
        # ДВА РЫЧАГА, названные до замера, а не подобранные после.
        # 1. Задание ПЕРВЫМ. В `lane` регламент стоял сверху и на `rpc` занимал
        #    41 000 символов, а задание — в самом низу: 2/5 против 4/5 у базы.
        #    Регламент не связал, он утопил предмет.
        # 2. Названо, ЧЕМ работа будет судиться. Оркестратор это знает, исполнитель
        #    нет; и это дешевле пересылки всего текста.
        текст = правило_текст(корень, КАРТА.get(ид, []))
        судья = ГЕЙТЫ.get(ид, "")
        куски = [задание]
        if судья:
            куски.append("\n\n---\n\nЧЕМ ЭТО БУДЕТ СУДИТЬСЯ: " + судья
                         + "\n\nСделай так, чтобы прошло.")
        if текст:
            куски.append(
                "\n\n---\n\nРЕГЛАМЕНТ, СВЯЗЫВАЮЩИЙ ЭТУ РАБОТУ. Он обязателен ровно так же,\n"
                "как если бы лежал в твоих постоянных инструкциях: это не справка и не\n"
                "пример, а норма, по которой работу примут или вернут.\n\n" + текст)
        задание = "".join(куски)
    # ПУТЬ ОБЯЗАН ЛЕЖАТЬ ВНУТРИ КОПИИ. Первая редакция резала абсолютный путь
    # грубо: координата ВНЕ воркспейса превращалась в `home/dk/tmp/...` внутри
    # копии, а координата в дереве ПРОДУКТА уезжала по симлинку в НАСТОЯЩИЙ
    # клон владельца — и туда записались девять файлов. Теперь у каждой посадки
    # своя рабочая копия продукта, а выход за её пределы — отказ, а не запись.
    сырой = пункт["artifact_path"]
    отн = сырой.replace(ВОРКСПЕЙС, "").lstrip("/")
    if os.path.isabs(сырой) and ВОРКСПЕЙС not in сырой:
        отн = os.path.join("tmp/bench", os.path.basename(сырой))
    путь = os.path.realpath(os.path.join(корень, отн))
    if not путь.startswith(os.path.realpath(корень) + os.sep):
        return {"id": ид, "посадка": посадка, "исход": "НЕ ВЫПОЛНИЛОСЬ",
                "почему": f"путь выходит за копию посадки: {путь}", "секунд": 0.0,
                "прошло": 0, "всего": len(пункт["checks"]), "вход_символов": 0}
    os.makedirs(os.path.dirname(путь), exist_ok=True)
    if os.path.exists(путь):
        os.remove(путь)
    t0 = time.time()
    # Задание подаётся СТДИНОМ. Аргументом оно упирается в ARG_MAX: посадка
    # `lane` кладёт в него текст правила (до 96 КБ) и падала с
    # «Argument list too long» ещё до первого предмета.
    оборван = ""
    try:
        subprocess.run(
            ["claude", "-p", "--permission-mode", "bypassPermissions", "--model", "sonnet"],
            cwd=корень, input=задание, capture_output=True, text=True, timeout=1200)
    except subprocess.TimeoutExpired:
        # Третья категория: вердикта нет. Прежняя редакция не ловила это вовсе,
        # и первый же истёкший предмет убивал прогон, оставляя три непрогнанными.
        оборван = "оборван по времени (1200 с)"
    except OSError as e:
        оборван = f"не запустился: {type(e).__name__}: {e}"
    dt = time.time() - t0
    if оборван or not os.path.exists(путь):
        return {"id": ид, "посадка": посадка, "исход": "НЕ ВЫПОЛНИЛОСЬ",
                "почему": оборван or "файл не создан", "секунд": round(dt, 1),
                "прошло": 0, "всего": len(пункт["checks"]), "вход_символов": len(задание)}
    text = open(путь, encoding="utf-8", errors="replace").read()
    прошло, разбор = 0, []
    for c in пункт["checks"]:
        try:
            # ИМЕНА В GLOBALS, А НЕ В LOCALS. Выражения проверок — лямбды, и тело
            # лямбды ищет свободные имена в globals модуля, а не в locals
            # вызывающего. Первая редакция клала `re` в locals: ВСЕ 39 проверок
            # падали с NameError и считались нарушением. Ноль по всем — это был
            # мой eval, а не работа исполнителя.
            окружение = {"__builtins__": {"len": len, "any": any, "all": all,
                                          "sum": sum, "min": min, "max": max,
                                          "sorted": sorted, "set": set, "list": list,
                                          "str": str, "int": int, "bool": bool,
                                          "enumerate": enumerate, "zip": zip,
                                          "map": map, "filter": filter, "abs": abs},
                         "re": re, "text": text}
            ок = bool(eval(c["python"], окружение, окружение))
        except Exception as e:
            разбор.append({"name": c["name"], "исход": f"выражение отказало: {type(e).__name__}"})
            continue
        прошло += int(ок)
        разбор.append({"name": c["name"], "исход": "соблюдено" if ок else "НАРУШЕНО",
                       "rule": c.get("rule_ref", "")})
    return {"id": ид, "посадка": посадка, "исход": "прогнан", "секунд": round(dt, 1),
            "прошло": прошло, "всего": len(пункт["checks"]), "разбор": разбор,
            "вход_символов": len(задание), "артефакт_байт": len(text)}


def main() -> int:
    посадка, корень, набор = sys.argv[1], sys.argv[2], sys.argv[3]
    вкладывать = посадка if посадка in ("lane", "lane2") else ""
    пункты = json.load(open(набор, encoding="utf-8"))
    итог = []
    for п in пункты:
        r = прогнать(посадка, корень, п, вкладывать)
        итог.append(r)
        print(f"  [{посадка}] {r['id']:10s} {r['прошло']}/{r['всего']} "
              f"· {r['секунд']}с · вход {r['вход_символов']:,} симв"
              + ("" if r["исход"] == "прогнан" else f"  ← {r['исход']}: {r.get('почему','')}"),
              flush=True)
    прошло = sum(r["прошло"] for r in итог)
    всего = sum(r["всего"] for r in итог)
    невып = sum(1 for r in итог if r["исход"] != "прогнан")
    print(f"\n  ПОСАДКА {посадка}: соблюдено {прошло}/{всего} = {прошло/всего*100:.0f}%"
          f" · не выполнилось пунктов: {невып}")
    json.dump(итог, open(f"{СТЕНД}/out/{посадка}.json", "w"), ensure_ascii=False, indent=1)
    return 0


if __name__ == "__main__":
    sys.exit(main())
