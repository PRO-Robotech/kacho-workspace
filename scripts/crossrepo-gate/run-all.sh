#!/usr/bin/env bash
# Прогон набора crossrepo-gate. Вердикт стоит в КОДЕ ВЫХОДА, а не в печати.
#
# ПРЕДМЕТ НАБОРА — запрет #20: файл, чей владелец другой репозиторий, в этом
# дереве не лежит. Правило (`.claude/rules/polyrepo.md` §«Копия между
# репозиториями ЗАПРЕЩЕНА») само называло своего держателя: «сегодня — НИЧЕМ,
# гейта на парные файлы между репозиториями в дереве нет; он выразим и
# заводится своим изменением». Это он.
#
# ПОЧЕМУ ДОМ ЗДЕСЬ. Пара — свойство ДВУХ деревьев, и ни одно из них себя с
# соседом не сверяет by construction: каждое по отдельности исправно, и
# расхождение наступит молча. Воркспейс — единственное место, где под рукой все
# три клона.
#
# ТРИ ИСХОДА, А НЕ ДВА:
#   0 — рассмотрено N проверок, находок 0, у каждой был предмет;
#   1 — НАХОДКА: проверка упала, либо обход пуст;
#   2 — БЕЗ ПРЕДМЕТА: клона нет либо ствол не резолвится — считать пары не по чему.
# Третий исход НЕ засчитывается за успех: «ноль пар» и «ноль прочитанных
# деревьев» — разные вещи, и вторая опаснее.
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

ok=0; bad=0; void=0; count=0
for c in "$SCRIPT_DIR"/check-*; do
    [ -f "$c" ] || continue
    count=$((count + 1))
    case "$c" in
        *.py) python3 "$c" ;;
        *)    bash "$c" ;;
    esac
    case $? in
        0) ok=$((ok + 1)) ;;
        2) void=$((void + 1)) ;;
        *) bad=$((bad + 1)) ;;
    esac
done

if [ "$count" -gt 0 ]; then
    echo
    echo "crossrepo-gate: рассмотрено проверок $count; пройдено $ok, провалено $bad, без предмета $void"
else
    echo "crossrepo-gate: рассмотрено проверок 0 в $SCRIPT_DIR — прогонять нечего" >&2
fi

[ "$count" -gt 0 ] || exit 1
[ "$bad" -eq 0 ] || exit 1
[ "$void" -eq 0 ] || exit 2
exit 0
