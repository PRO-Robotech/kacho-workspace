#!/usr/bin/env bash
# Прогон набора crossrepo-gate. Вердикт стоит в КОДЕ ВЫХОДА, а не в печати.
#
# ПРЕДМЕТ НАБОРА — запрет #20: файл, чей владелец другой репозиторий, в этом
# дереве не лежит. Правило (`.claude/rules/polyrepo.md` §«Копия между
# репозиториями ЗАПРЕЩЕНА») само называло своего держателя: «сегодня — НИЧЕМ,
# гейта на парные файлы между репозиториями в дереве нет; он выразим и
# заводится своим изменением». Это он.
#
# ПОЧЕМУ ДОМ ЗДЕСЬ. Пара — свойство ДВУХ деревьев, и ни одно из них себя с
# соседом не сверяет by construction: каждое по отдельности исправно, и
# расхождение наступит молча. Воркспейс — единственное место, где под рукой
# клоны всех репозиториев продукта.
#
# «Без предмета» (код 2) здесь — клона нет либо ствол не резолвится: считать пары
# не по чему, и «ноль пар» означал бы «ноль прочитанных деревьев».
#
# Устройство прогона — одно на все наборы: `scripts/lib/suite-runner.sh` (три
# исхода и их коды, пустой обход — находка, объём осмотренного обязателен,
# рабочий каталог проверки — пустой чужой репозиторий). Своей копии цикла у
# набора нет: свойство, заведённое в одной копии, до ws#762 не доезжало до
# соседних.
# shellcheck source-path=SCRIPTDIR
set -uo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=../lib/suite-runner.sh
. "$here/../lib/suite-runner.sh"
suite_run "$here"
