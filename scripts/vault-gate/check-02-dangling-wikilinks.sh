#!/usr/bin/env bash
# Ссылка между записками обязана куда-то вести.
#
# Хранилище держится на связях: записка ресурса → его RPC → рёбра, в которых он
# участвует. Ссылка, ведущая в пустоту, не просто «не открывается» — она
# утверждает, что предмет описан, и уводит от поиска в дереве. При этом
# висячая ссылка бывает двух совершенно разных родов, и путать их нельзя:
# опечатка в имени (чинится правкой ссылки) и НЕНАПИСАННАЯ записка (чинится
# только тем, что её напишут). Гейт считает и те и другие, но снижать число
# правкой ссылок в никуда — нельзя: см. §«Храповик» ниже.
#
# Храповик двусторонний. Число висячих ссылок сравнивается с записанным
# основанием: больше — заведены новые (находка); МЕНЬШЕ — основание отстало и
# обязано быть опущено тем же коммитом (тоже находка). Одностороннее «не хуже,
# чем было» умеет только расти вверх и через месяц перестаёт что-либо значить:
# исключение обязано истекать само (`testing.md` §Гейт на класс, п. 5).
#
# Исход: 0 — сходится с основанием; 1 — находки; 2 — предпосылки нет (VOID).
#
# Режим `--list` печатает сами висячие цели (вид · число ссылок · цель · пример
# источника) — им пользуются указатели категорий, чтобы не переписывать перечень
# руками.

set -uo pipefail

# shellcheck source=scripts/vault-gate/_lib.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/_lib.sh"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
exec python3 "$SCRIPT_DIR/check_02_dangling.py" "$@"
