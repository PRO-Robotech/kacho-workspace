#!/usr/bin/env bash
# Указатель хранилища собран из дерева и не отстал от него.
#
# Предмет — расхождение перечня с файлами. Оно копится молча и в одну сторону:
# записку заводят, строку в указатель добавить забывают, и «нет в указателе»
# начинает читаться как «нет предмета». Замер до введения генератора: 112 записок
# из 295 (38 %) в указателе не упоминались, при том что все ссылки самого
# указателя резолвились — то есть проверка одной стороны показывала порядок.
#
# Проверка не судит рукописную часть указателя: генератор трогает только область
# между маркерами. Нет маркеров — нет предпосылки: VOID, а не PASS.
#
# Исход: 0 — совпадает; 1 — отстал; 2 — предпосылки нет (VOID).

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WS="${VAULT_GATE_ROOT:-$(cd "$SCRIPT_DIR/../.." && pwd)}"
GEN="$WS/scripts/vault-index/generate.py"

if [ ! -x "$GEN" ] && [ ! -f "$GEN" ]; then
    echo "[VOID] указатель собран из дерева — генератора $GEN нет, сверять не с чем" >&2
    exit 2
fi

python3 "$GEN" --check
