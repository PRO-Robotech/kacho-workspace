#!/usr/bin/env bash
# Машинная половина указателя собрана из дерева и не отстала от него.
#
# Предмет — расхождение перечня с файлами. Оно копится молча и в одну сторону:
# записку заводят, строку в перечень добавить забывают, и «нет в указателе»
# начинает читаться как «нет предмета». Замер до введения генератора: 112 записок
# из 295 (38 %) в указателе не упоминались, при том что все ссылки самого
# указателя резолвились — то есть проверка одной стороны показывала порядок.
#
# Проверка судит ТОЛЬКО `obsidian/kacho/INDEX-notes.md` — файл, который генератор
# производит целиком. Прозаическая половина (`INDEX.md`) пишется человеком и
# здесь не судится вовсе: до разделения (2026-08-18) обе жили одним файлом, и
# граница между «моё» и «машинное» держалась парой маркеров внутри него.
#
# Три исхода различаются, и это не формальность:
#   · перечень отстал ИЛИ его нет вовсе — FAIL (1). Отсутствие файла — именно
#     расхождение: записки прочитаны, а перечня нет;
#   · записок не прочитано ни одной — VOID (2). Пустая перепись сходится
#     тривиально, и зелёный вердикт означал бы «ноль прочитанного», а не
#     «ноль находок»;
#   · совпадает — PASS (0), с числом рассмотренных записок в строке вывода.
#
# Чинится расхождение ОДНОЙ командой — `./scripts/vault-index/generate.py`, — и
# она названа в тексте отказа: гейт, требующий догадаться, снимут как непонятный.
#
# Исход: 0 — совпадает; 1 — отстал; 2 — предпосылки нет (VOID).

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WS="${VAULT_GATE_ROOT:-$(cd "$SCRIPT_DIR/../.." && pwd)}"
GEN="$WS/scripts/vault-index/generate.py"

if [ ! -x "$GEN" ] && [ ! -f "$GEN" ]; then
    echo "[VOID] перечень собран из дерева — генератора $GEN нет, сверять не с чем" >&2
    exit 2
fi

python3 "$GEN" --check
