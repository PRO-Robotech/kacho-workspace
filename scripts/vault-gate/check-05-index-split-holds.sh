#!/usr/bin/env bash
# Указатель разделён на две половины, и машинная несёт СВОЮ посадку слияния.
#
# Предмет — не опрятность файлов, а то, чью версию git спросит при слиянии.
# Указатель состоит из частей разной природы: прозаическая пишется человеком, и
# расхождение двух линий в ней ОСМЫСЛЕННО; перечень записок производен, и верного
# ответа среди двух версий нет вовсе — верен третий, полученный пересборкой.
#
# Замер до разделения (2026-08-18, синтетика на настоящем генераторе): две ветки
# от одной базы, по записке в каждой — слияние падало конфликтом. В форме, где
# конфликта не возникало (записки в разных категориях), указатель молча оставался
# НЕВЕРНЫМ: «Всего» 650 там, где в дереве 651. То есть конфликт был лишь видимой
# половиной дефекта.
#
# Почему проверка нужна ОТДЕЛЬНО от свежести (check-04). Свежесть судит
# содержимое; эта — механизм, которым содержимое доживает до слияния. Механизм
# отказывает молча: снимут `.gitattributes` — перечень снова начнёт спрашивать
# человека, а гейт свежести останется зелёным, потому что содержимое-то верное.
#
# Посадку спрашиваем у git (`check-attr`), а не читаем `.gitattributes` глазами:
# git консультируется и с рабочей копией, и с ИНДЕКСОМ, и с `info/attributes`.
# Проверка, грепающая файл, разошлась бы с тем, что git на самом деле применит.
#
# Отдельно проверяется, что посадка ВСТРОЕНА В GIT, а не установлена в клоне.
# Именованный драйвер (`merge=<имя>` + `git config merge.<имя>.driver`) держится
# установкой у каждого разработчика: в клоне без неё git молча откатывается к
# обычному трёхстороннему слиянию, конфликт возвращается, и ничто об этом не
# говорит. Встроенные драйверы (`text`, `binary`, `union`) везут посадку САМИМ
# ДЕРЕВОМ — их и требуем.
#
# Исход: 0 — держится; 1 — находки; 2 — предпосылки нет (VOID).

set -uo pipefail

# shellcheck source=scripts/vault-gate/_lib.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/_lib.sh"

CHECK="указатель разделён, и машинная половина несёт посадку слияния"

WS="$(vault_gate_workspace_root)" || exit 2

VAULT="obsidian/kacho"
PROSE="$VAULT/INDEX.md"
NOTES="$VAULT/INDEX-notes.md"
BEGIN_MARK="GENERATED:vault-index BEGIN"

# Встроенные в git драйверы слияния: их не надо ставить в клоне.
BUILTIN_MERGE_DRIVERS=(text binary union)

if ! git -C "$WS" rev-parse --git-dir >/dev/null 2>&1; then
    vault_gate_void "$CHECK" "в $WS нет git-дерева — посадку слияния спросить не у кого"
    exit 2
fi

# Перепись: сколько файлов хранилища вообще видно. Ноль означает, что смотрим не
# туда, — и тогда все утверждения ниже сошлись бы тривиально.
seen="$(git -C "$WS" ls-files --cached --others --exclude-standard "$VAULT/" | grep -c . || true)"
if [ "$seen" -eq 0 ]; then
    vault_gate_void "$CHECK" "в $WS/$VAULT не видно ни одного файла — судить не о чем"
    exit 2
fi

findings=()

# (1) Машинная половина существует.
if [ ! -f "$WS/$NOTES" ]; then
    findings+=("$NOTES: машинной половины указателя в дереве нет")
fi

# (2) Проза больше не несёт машинной части: два места об одном предмете
#     разошлись бы молча, и посадка слияния досталась бы не тому файлу.
if [ -f "$WS/$PROSE" ] && grep -qF "$BEGIN_MARK" "$WS/$PROSE"; then
    findings+=("$PROSE: несёт маркер генератора — машинная часть не уехала, посадку назначать нечему")
fi

# (3) Проза указывает на машинную половину. Без ссылки разделение осиротило бы
#     перечень: читатель, пришедший в указатель, не узнал бы, где он лежит.
#     Обычная ссылка `[[INDEX-notes]]`, а не только вложение `![[…]]`: вложения
#     проверка висячих ссылок (check-02) не разбирает by construction, поэтому
#     ссылка, оставленная только вложением, дотухла бы незамеченной.
if [ -f "$WS/$PROSE" ] && ! grep -qE '\[\[INDEX-notes(\||\]\])' "$WS/$PROSE"; then
    findings+=("$PROSE: не ссылается на [[INDEX-notes]] — машинная половина осиротела")
fi

# (4) Посадка слияния объявлена, git её резолвит, и она ВСТРОЕННАЯ.
attr="$(git -C "$WS" check-attr merge -- "$NOTES" 2>/dev/null | sed 's/.*: merge: //')"
case "$attr" in
    ""|unspecified|unset)
        findings+=("$NOTES: посадка слияния не объявлена (git check-attr merge → «${attr:-пусто}») — параллельные записки снова будут спрашивать человека")
        ;;
    *)
        builtin=no
        for d in "${BUILTIN_MERGE_DRIVERS[@]}"; do
            [ "$d" = "$attr" ] && builtin=yes
        done
        if [ "$builtin" = no ]; then
            configured="$(git -C "$WS" config --get "merge.$attr.driver" || true)"
            findings+=("$NOTES: посадка «$attr» не встроена в git (в этом клоне merge.$attr.driver = «${configured:-не задан}») — такая держится установкой в каждом клоне, а в клоне без неё git молча вернётся к обычному слиянию")
        fi
        ;;
esac

scope="осмотрено файлов хранилища $seen; посадка слияния у $NOTES — «${attr:-не объявлена}»; встроенных драйверов в словаре ${#BUILTIN_MERGE_DRIVERS[@]}"

if [ "${#findings[@]}" -gt 0 ]; then
    vault_gate_fail "$CHECK" "$scope; находок ${#findings[@]}"
    printf '        %s\n' "${findings[@]}" >&2
    exit 1
fi

vault_gate_pass "$CHECK" "$scope; находок 0"
exit 0
