#!/usr/bin/env bash
# Указатель разделён на две половины, и машинная несёт СВОЮ посадку слияния.
#
# Предмет — не опрятность файлов, а то, чью версию git спросит при слиянии.
# Указатель состоит из частей разной природы: прозаическая пишется человеком, и
# расхождение двух линий в ней ОСМЫСЛЕННО; перечень записок производен, и верного
# ответа среди двух версий нет вовсе — верен третий, полученный пересборкой.
#
# Замер до разделения (2026-08-18, синтетика на настоящем генераторе): две ветки
# от одной базы, по записке в каждой — слияние падало конфликтом. В форме, где
# конфликта не возникало (записки в разных категориях), указатель молча оставался
# НЕВЕРНЫМ: «Всего» 650 там, где в дереве 651. То есть конфликт был лишь видимой
# половиной дефекта.
#
# Почему проверка нужна ОТДЕЛЬНО от свежести (check-04). Свежесть судит
# содержимое; эта — механизм, которым содержимое доживает до слияния. Механизм
# отказывает молча: снимут `.gitattributes` — перечень снова начнёт спрашивать
# человека, а гейт свежести останется зелёным, потому что содержимое-то верное.
#
# Посадку спрашиваем у git (`check-attr`), а не читаем `.gitattributes` глазами:
# git консультируется и с рабочей копией, и с ИНДЕКСОМ, и с `info/attributes`.
# Проверка, грепающая файл, разошлась бы с тем, что git на самом деле применит.
#
# Отдельно проверяется, что посадка ВСТРОЕНА В GIT, а не установлена в клоне.
# Именованный драйвер (`merge=<имя>` + `git config merge.<имя>.driver`) держится
# установкой у каждого разработчика: в клоне без неё git молча откатывается к
# обычному трёхстороннему слиянию, конфликт возвращается, и ничто об этом не
# говорит. Встроенные драйверы (`text`, `binary`, `union`) везут посадку САМИМ
# ДЕРЕВОМ — их и требуем.
#
# «Драйвер встроен» и «объявление пришло из дерева» — РАЗНЫЕ вопросы, и первый на
# второй не отвечает. Источников атрибутов у git больше одного, и два из них
# принадлежат КЛОНУ, а не дереву: `.git/info/attributes` и `core.attributesFile`.
# Оба непрослеживаемы, оба отвечают `check-attr` неотличимо от объявления в
# дереве. Замер 2026-08-30: посадка, положенная ТОЛЬКО в `.git/info/attributes`,
# давала этой проверке «находок 0» при пустом дереве — здесь всё выглядело
# исполненным, а у всякого клонирующего слияние снова спрашивало бы человека.
# Поэтому тот же вопрос задаётся ОТДЕЛЬНО дереву и только ему: в чистом каталоге,
# куда положены лишь отслеживаемые файлы атрибутов, с обнулённой глобальной и
# системной конфигурацией.
#
# Исход: 0 — держится; 1 — находки; 2 — предпосылки нет (VOID).
#
# Окружение git снимается: проверка заводит СВОЙ временный репозиторий, а хуки
# запускаются с выставленным `GIT_DIR`, и его наследует всё, что они запускают.
# Без этого `git init` во временном каталоге писал бы в РАБОЧУЮ копию — индекс
# схлопывается, а падают потом проверки, ни к чему не причастные
# (`multi-agent-flow.md` §НЕПРИКОСНОВЕННОСТЬ ЧУЖОГО СОСТОЯНИЯ).
unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
      GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_COMMON_DIR GIT_PREFIX

set -uo pipefail

# shellcheck source=scripts/vault-gate/_lib.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/_lib.sh"

CHECK="указатель разделён, и машинная половина несёт посадку слияния"

WS="$(vault_gate_workspace_root)" || exit 2

VAULT="obsidian/kacho"
PROSE="$VAULT/INDEX.md"
NOTES="$VAULT/INDEX-notes.md"
BEGIN_MARK="GENERATED:vault-index BEGIN"

# Встроенные в git драйверы слияния: их не надо ставить в клоне.
BUILTIN_MERGE_DRIVERS=(text binary union)

# Ответ, который на тот же вопрос получит СВЕЖИЙ клон. Спрашиваем не «что написано
# в .gitattributes» (грепать объявление запрещено выше и по той же причине), а
# «что ответит git, если из источников оставить ТОЛЬКО дерево».
#
# Печатает ДВЕ величины через `|`: ответ и число отслеживаемых файлов атрибутов,
# из которых он получен. Обе — возвращаемым значением, а не глобальной
# переменной: вызов идёт через `$(…)`, то есть в ПОДОБОЛОЧКЕ, и присваивание
# внутри неё до вызывающего не доезжает. Первая редакция этой функции так и была
# написана — и печатала «ответ union по 0 файлам», то есть перепись,
# противоречащую собственному ответу. Ненулевой код — измерение не состоялось:
# вызывающий обязан ответить VOID, а не PASS.
# ГРАНИЦА измерения, названная честно: в дерево засчитываются и ещё не
# закоммиченные файлы атрибутов (`--others --exclude-standard`) — объявление,
# написанное сегодня, уедет в дерево тем же изменением, и краснеть на нём значило
# бы требовать коммита раньше проверки. Файл атрибутов, который так и НЕ
# закоммитят, эта проверка засчитает как «из дерева»; от этого её предмет не
# защищает — то ловит обычный обзор изменения. Предмет здесь другой:
# `.git/info/attributes` и `core.attributesFile` не попадают в `ls-files` НИКОГДА
# и потому отсеиваются by construction.
attr_as_a_fresh_clone_sees_it() {
    local ws="$1" path="$2" scratch answer n=0 f
    scratch="$(mktemp -d)" || return 1
    git -C "$scratch" init -q >/dev/null 2>&1 || { rm -rf "$scratch"; return 1; }
    while IFS= read -r f; do
        [ -n "$f" ] || continue
        install -D "$ws/$f" "$scratch/$f" >/dev/null 2>&1 && n=$((n + 1))
    done < <(git -C "$ws" ls-files --cached --others --exclude-standard \
                 | grep -E '(^|/)\.gitattributes$')
    answer="$(GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null \
              git -C "$scratch" check-attr merge -- "$path" 2>/dev/null \
              | sed 's/.*: merge: //')"
    rm -rf "$scratch"
    printf '%s|%s' "${answer:-unspecified}" "$n"
}

if ! git -C "$WS" rev-parse --git-dir >/dev/null 2>&1; then
    vault_gate_void "$CHECK" "в $WS нет git-дерева — посадку слияния спросить не у кого"
    exit 2
fi

# Перепись: сколько файлов хранилища вообще видно. Ноль означает, что смотрим не
# туда, — и тогда все утверждения ниже сошлись бы тривиально.
seen="$(git -C "$WS" ls-files --cached --others --exclude-standard "$VAULT/" | grep -c . || true)"
if [ "$seen" -eq 0 ]; then
    vault_gate_void "$CHECK" "в $WS/$VAULT не видно ни одного файла — судить не о чем"
    exit 2
fi

findings=()

# (1) Машинная половина существует.
if [ ! -f "$WS/$NOTES" ]; then
    findings+=("$NOTES: машинной половины указателя в дереве нет")
fi

# (2) Проза больше не несёт машинной части: два места об одном предмете
#     разошлись бы молча, и посадка слияния досталась бы не тому файлу.
if [ -f "$WS/$PROSE" ] && grep -qF "$BEGIN_MARK" "$WS/$PROSE"; then
    findings+=("$PROSE: несёт маркер генератора — машинная часть не уехала, посадку назначать нечему")
fi

# (3) Проза указывает на машинную половину. Без ссылки разделение осиротило бы
#     перечень: читатель, пришедший в указатель, не узнал бы, где он лежит.
#     Обычная ссылка `[[INDEX-notes]]`, а не только вложение `![[…]]`: вложения
#     проверка висячих ссылок (check-02) не разбирает by construction, поэтому
#     ссылка, оставленная только вложением, дотухла бы незамеченной.
if [ -f "$WS/$PROSE" ] && ! grep -qE '\[\[INDEX-notes(\||\]\])' "$WS/$PROSE"; then
    findings+=("$PROSE: не ссылается на [[INDEX-notes]] — машинная половина осиротела")
fi

# (4) Посадка слияния объявлена, git её резолвит, и она ВСТРОЕННАЯ.
attr="$(git -C "$WS" check-attr merge -- "$NOTES" 2>/dev/null | sed 's/.*: merge: //')"
case "$attr" in
    ""|unspecified|unset)
        findings+=("$NOTES: посадка слияния не объявлена (git check-attr merge → «${attr:-пусто}») — параллельные записки снова будут спрашивать человека")
        ;;
    *)
        builtin=no
        for d in "${BUILTIN_MERGE_DRIVERS[@]}"; do
            [ "$d" = "$attr" ] && builtin=yes
        done
        if [ "$builtin" = no ]; then
            configured="$(git -C "$WS" config --get "merge.$attr.driver" || true)"
            findings+=("$NOTES: посадка «$attr» не встроена в git (в этом клоне merge.$attr.driver = «${configured:-не задан}») — такая держится установкой в каждом клоне, а в клоне без неё git молча вернётся к обычному слиянию")
        fi
        ;;
esac

# (5) Посадку везёт ДЕРЕВО, а не этот клон. Проверка (4) отвечает на «нужно ли
#     драйвер ставить» и на «откуда взялось объявление» не отвечает вовсе:
#     `.git/info/attributes` и `core.attributesFile` дают неотличимый ответ и
#     принадлежат клону — свежий клон остался бы без посадки, а здесь всё
#     выглядело бы исполненным.
if ! tree_answer="$(attr_as_a_fresh_clone_sees_it "$WS" "$NOTES")"; then
    vault_gate_void "$CHECK" "дерево не удалось спросить отдельно от клона — измерение не состоялось"
    exit 2
fi
tree_attr="${tree_answer%|*}"
tree_files="${tree_answer##*|}"

case "$attr" in
    ""|unspecified|unset) : ;;   # уже названо в (4), второй раз не повторяем
    *)
        if [ "$tree_attr" != "$attr" ]; then
            findings+=("$NOTES: посадка «$attr» приходит НЕ из дерева (дерево отвечает «$tree_attr», отслеживаемых файлов атрибутов $tree_files) — её везёт файл ЭТОГО клона (.git/info/attributes либо core.attributesFile), и у всякого, кто клонирует, слияние снова будет спрашивать человека; объявить посадку в отслеживаемом .gitattributes")
        fi
        ;;
esac

scope="осмотрено файлов хранилища $seen; посадка слияния у $NOTES — «${attr:-не объявлена}», дерево отдельно от клона отвечает «$tree_attr», отслеживаемых файлов атрибутов $tree_files; встроенных драйверов в словаре ${#BUILTIN_MERGE_DRIVERS[@]}"

if [ "${#findings[@]}" -gt 0 ]; then
    vault_gate_fail "$CHECK" "$scope; находок ${#findings[@]}"
    printf '        %s\n' "${findings[@]}" >&2
    exit 1
fi

vault_gate_pass "$CHECK" "$scope; находок 0"
exit 0
