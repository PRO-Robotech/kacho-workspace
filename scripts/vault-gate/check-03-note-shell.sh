#!/usr/bin/env bash
# У записки есть предсказуемая оболочка: назначение, категория, состояние.
#
# Предмет — НЕ содержание, а те три ответа, которые читатель обязан получать, не
# читая записку целиком: `title` (про что), `category` (какого рода предмет),
# `status` (живо / история / в работе). Записка без них не «хуже написана» — она
# невидима для видов-таблиц: срез фильтрует статусы поимённо, поэтому запись без
# статуса и запись с неизвестным статусом ведут себя по-разному и обе молча.
#
# Словарь допустимых состояний ВЫВОДИТСЯ из контракта самого хранилища —
# `obsidian/kacho/CLAUDE.md`, §«Оболочка записки», таблица трёх вёдер. Рукописный
# список внутри скрипта разошёлся бы с контрактом молча и ровно в ту сторону, в
# которой гейт перестаёт ловить. Нет таблицы — нет предпосылки: VOID, а не PASS.
#
# Границы, осознанные и проверенные близнецами в inject-03.sh:
#   — витрина категории (`*/README.md`, `all-*.md`) состояния не обязана нести:
#     её предмет — перечень, а не сущность продукта;
#   — `KAC/_TEMPLATE.md` — шаблон, а не записка;
#   — правдивость самого `status` гейт не судит: «живо» вместо «истории» он не
#     отличит. Это предмет сверки с деревом, а не оболочки.
#
# Исход: 0 — чисто; 1 — находки; 2 — предпосылки нет (VOID).

set -uo pipefail

# shellcheck source=scripts/vault-gate/_lib.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/_lib.sh"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
exec python3 "$SCRIPT_DIR/check_03_shell.py" "$@"
