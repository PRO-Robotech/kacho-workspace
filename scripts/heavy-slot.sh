# shellcheck disable=SC2329  # зовётся ловушкой
on_signal() {
    kill_escaped "$P"   # до unit: со смертью корня потомки уходят к другому родителю
    if [ -n "$UNIT" ] && systemctl --user kill --signal=SIGTERM "$UNIT" 2>/dev/null; then
