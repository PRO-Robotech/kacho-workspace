        0|75) refuse_external "внешнего маршрута нет ($WHY_LOCAL) — до него команда не выполняется нигде: маршрут — задача $NO_ROUTE_TASK; «нет инструмента в образе», «слот занят», «быстрее локально» — не основания (ws#1301)" ;;
