# journal_early — запись журнала до входа в очередь (каталог может быть ещё не заведён).
journal_early() { mkdir -p "$DIR" 2>/dev/null; journal "$@"; }
# cluster_once [профиль [репозиторий]] — один опрос: код run.sh --available, его вывод —
# в CL_OUT. Репозиторий — запрос по замеру его прогонов (ws#1195), без него — наибольший.
# Не ответила за CHECK_S (124) — повтор, всего CHECK_TRIES попыток (ws#1141).
cluster_once() {
    local out rc try=1
    while :; do
        out="$(timeout "$CHECK_S" bash "$REMOTE_RUN" --available ${1:+--profile "$1"} ${1:+${2:+--repo "$2"}} 2>&1)"; rc=$?
        [ "$rc" -eq 124 ] && [ "$try" -lt "$CHECK_TRIES" ] || break
        try=$(( try + 1 ))
    done
    [ "$rc" -eq 124 ] && out="проверка доступности не ответила за $CHECK_S с, попыток $try (сеть до кластера)${out:+; $out}"
    CL_OUT="$(printf '%s' "$out" | tr '[:cntrl:]' ' ' | cut -c1-400)"
    return "$rc"
}
# cluster_check [профиль [репозиторий]] — 0, если кластер принимает прогон. Занят (75) — НЕ
# недоступен (решение диспетчера 2026-10-16: «занятость — не недоступность»): место
# ждётся до --wait N опросом раз в POLL_S, затем выход 74 (ожидания не было) либо 75 —
# локально команда не идёт. 69 и 124 — недоступен: 1, PROOF — вывод проверки с кодом;
# иной код — дефект обёртки: defect_exit, 69.
cluster_check() {
    local rc t0
    t0="${WAIT_T0:-${EXT_T0:-$(now)}}"   # срок заявки один на все фазы (ws#1176, ws#1244)
    while :; do
        cluster_once "${1:-}" "${2:-}"; rc=$?
        [ "$rc" -eq 0 ] && return 0
        [ "$rc" -eq 75 ] || break
        [ $(( $(now) - t0 + POLL_S )) -le "$WAIT_S" ] || busy_exit "$t0"
        sleep "$POLL_S"
    done
    case "$rc" in 69|124) ;; *) defect_exit "$rc" ;; esac
    PROOF="rc=$rc $CL_OUT"
    WHY_LOCAL="кластер недоступен: ${CL_OUT#remote-heavy: }"
    return 1
}
# defect_exit <код> — проверка кластера отказала НЕ сетевым признаком: недоступность —
# лишь 69 (run.sh: кластер не отвечает, не доказан, узла нет) и 124 (не ответила за
# CHECK_S); 70 — дефект обёртки run.sh, прочие — её вызов либо исполнение (ws#1210:
# «jq: Argument list too long» уводил тяжёлое локально как «кластер недоступен»).
# Команда не идёт ни туда, ни локально: 69 «механизм недоступен», «не выполнилось».
defect_exit() {
    journal_early "defect-external class=$CLASS proof=rc=$1 $CL_OUT who=$(git -C "$PWD" branch --show-current 2>/dev/null)@$PWD cmd=$(printf '%q ' "${CMD_R[@]}")"
    say "проверка кластера отказала не сетевым признаком (код $1): ${CL_OUT#remote-heavy: } — команда НЕ запускалась ни там, ни локально (код 69, не выполнилось, не красное): дефект обёртки — не недоступность кластера."
    say "почини обёртку (scripts/remote-heavy/run.sh) либо --local \"<причина>\" перед классом (testing-verdict.md#external-cluster-first)"
    exit 69
}
busy_exit() {
    local code=74
    [ "$WAIT_S" -gt 0 ] && code=75
    journal_early "busy-external class=$CLASS waited=$(( $(now) - $1 ))s proof=rc=75 $CL_OUT who=$(git -C "$PWD" branch --show-current 2>/dev/null)@$PWD cmd=$(printf '%q ' "${CMD_R[@]}")"
    say "кластер занят: ${CL_OUT#remote-heavy: } — команда НЕ запускалась ни там, ни локально (код $code, не выполнилось, не красное): занятость — не недоступность."
    say "повтори коротким шагом; ожидание места — --wait N (≤ $WAIT_MAX_S с) перед классом (testing-verdict.md#external-cluster-first)"
    exit "$code"
}
