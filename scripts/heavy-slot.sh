# enq_dir_in_tree <каталог> <класс> — 0 и ENQ_TOP, если файлы слота --enqueue (hs-<класс>-…
# .log .pid .rc .rc.tmp) в этом каталоге попадут в `git status` рабочего дерева: каталог в
# дереве git и git игнорирует НЕ все четыре. Кончилось плохо 2026-10-18 (kacho#3251, ws#1181):
# «грязную» копию хук отправки судил как временную без node_modules, проверки консоли ушли в
# «НЕ выполнено». Каталог вне git и каталог с игнорируемыми файлами слота законны.
enq_dir_in_tree() {
    local d n
    d="$(cd "$1" 2>/dev/null && pwd -P)" || return 1
    [ "$(git -C "$d" rev-parse --is-inside-work-tree 2>/dev/null)" = true ] || return 1
    ENQ_TOP="$(git -C "$d" rev-parse --show-toplevel 2>/dev/null)"
    for n in log pid rc rc.tmp; do
        git -C "$d" check-ignore -q --no-index -- "$d/hs-$2-00000000T000000-0.$n" 2>/dev/null || return 0
    done
    return 1
}

# git_push_form — команда — `git … push` с хуком (без --no-verify); GIT_IDX — индекс
# слова git, GDIR — каталог клона с учётом -C. --git-dir и --work-tree не разбираются:
# такая отправка идёт локально.
git_push_form() {
    local i=0 n=${#CMD_R[@]} w sub=""
    GDIR="$PWD"; GIT_IDX=""; PUSH_AT=""
    while [ "$i" -lt "$n" ] && [ "$(basename -- "${CMD_R[$i]}")" != git ]; do i=$(( i + 1 )); done
    [ "$i" -lt "$n" ] || return 1
    local gi="$i"; i=$(( i + 1 ))
    while [ "$i" -lt "$n" ]; do
        w="${CMD_R[$i]}"
        case "$w" in
            -C) GDIR="$(cd "$GDIR" 2>/dev/null && cd "${CMD_R[$(( i + 1 ))]:-}" 2>/dev/null && pwd)" || return 1; i=$(( i + 2 )) ;;
            -c) i=$(( i + 2 )) ;;
            --git-dir|--git-dir=*|--work-tree|--work-tree=*) return 1 ;;
            -*) i=$(( i + 1 )) ;;
            *) sub="$w"; break ;;
        esac
    done
    [ "$sub" = push ] || return 1
    PUSH_AT="$i"   # слово push — и у отправки с --no-verify: суждение «откуда» ей тоже нужно
    for w in "${CMD_R[@]:$(( i + 1 ))}"; do [ "$w" = --no-verify ] && return 1; done
    GIT_IDX="$gi"
}

# push_homes <корень git> — ci-local, отправка из копии ВОРКСПЕЙСА: наборам хука (change-graph-gate,
# docs-gate) нужны клоны kacho, kaname и corelib, а они лежат только в project/ ОСНОВНОГО клона
# воркспейса, не в копии под <корень>/tmp/…. Без переменных оба набора уходили в [VOID] («клон
# corelib не найден», «копия kaname рядом не найдена»), вершина уезжала не проверенной ими, а имена
# переменных нигде не назывались — их узнавали из текста [VOID] после отправки. Слот выставляет
# KACHO_HOME_<ИМЯ> на project/<имя> основного клона, если вызывающий их не задал (заданное сильнее),
# и называет выставленное; клона нет — называет переменную, которую выставить не из чего.
# ГРАНИЦА: хук во внешнем кластере идёт Job-ом, окружение слота в него не попадает.
push_homes() {
    local top="$1" root name var d set=() lacks=()
    git -C "$top" ls-files --error-unmatch scripts/heavy-slot.sh >/dev/null 2>&1 || return 0
    root="$(dirname "$(git -C "$top" rev-parse --path-format=absolute --git-common-dir 2>/dev/null)")"
    for name in kacho kaname corelib; do
        var="KACHO_HOME_$(printf '%s' "$name" | tr 'a-z' 'A-Z')"
        [ -z "${!var:-}" ] || continue
        d="$root/project/$name"
        if [ -e "$d/.git" ]; then
            export "$var=$d"; set+=("$var=$d")
        else
            lacks+=("$var (клона нет: $d)")
        fi
    done
    [ "${#set[@]}" -eq 0 ] || say "клоны для наборов хука отправки выставлены из основного клона воркспейса: ${set[*]} (заданную вами переменную слот не трогает)"
    [ "${#lacks[@]}" -eq 0 ] || say "НЕ выставлено — наборы хука уйдут в [VOID]: ${lacks[*]}"
    return 0
}
# push_where — для команды `git … push` (любой класс, обёртки перед git, -C) печатает, откуда и
# куда идёт отправка, и отказывает 64 до постановки в очередь, когда она кладёт голову ПЕРВИЧНОЙ
# копии воркспейса в иную ветку (ws#1182). Дважды за сутки (2026-10-17…18) `--enqueue` не менял
# рабочий каталог, отправка ушла из корня воркспейса, а не из копии задачи, и в чужом
# репозитории легла ветка с номером чужой задачи. Узнаватель — класс, а не перечень каталогов:
# корень git — первичная копия (git-dir совпадает с common-dir) того репозитория, где
# отслеживается сам слот, и ветка назначения не совпадает с текущей. Связанная копия
# (`git worktree`), клон другого репозитория и отправка в текущую ветку не судятся.
# ГРАНИЦА: `bash -c 'cd … && git push'` — смену каталога внутри строки оболочки слот не видит.
push_where() {
    local top url br head i n w rem="" bad="" specs=() shown=()
    CMD_R=("$@"); n=${#CMD_R[@]}
    git_push_form; [ -n "$PUSH_AT" ] || { GIT_IDX=""; GDIR="$PWD"; return 0; }
    top="$(git -C "$GDIR" rev-parse --show-toplevel 2>/dev/null)" || { GIT_IDX=""; GDIR="$PWD"; return 0; }
    url="$(git -C "$top" remote get-url origin 2>/dev/null | sed 's|//[^/@]*@|//|')"
    br="$(git -C "$GDIR" branch --show-current 2>/dev/null)"; head="$(git -C "$top" rev-parse --short=8 HEAD 2>/dev/null)"
    # Слова после push: опции (с значением отдельным словом: --repo, -o, --push-option, --receive-pack,
    # --exec; прочие — без него или через «=») и позиционные: первый — удалённый репозиторий, остальные —
    # refspec. Опции встают и после refspec (`git push origin main --force-with-lease`). --delete/-d
    # превращает refspec в имена удаляемых веток. Заменяющее суждение — только о refspec, кладущем
    # ГОЛОВУ копии (HEAD, @ либо имя её текущей ветки в роли источника) в иную ветку: прочее — отправка
    # названной ветки по имени (`origin 1182-lane`) либо удаление — голову корня никуда не кладёт.
    local del="" pos=() kind src dsta
    i=$(( PUSH_AT + 1 ))
    while [ "$i" -lt "$n" ]; do
        w="${CMD_R[$i]}"
        case "$w" in
            --repo|-o|--push-option|--receive-pack|--exec) [ "$w" != --repo ] || rem="${CMD_R[$(( i + 1 ))]:-}"; i=$(( i + 2 )) ;;
            --repo=*) rem="${w#*=}"; i=$(( i + 1 )) ;;
            --delete|-d) del=1; i=$(( i + 1 )) ;;
            --) pos+=("${CMD_R[@]:$(( i + 1 ))}"); break ;;
            -*) i=$(( i + 1 )) ;;
            *) pos+=("$w"); i=$(( i + 1 )) ;;
        esac
    done
    if [ "${#pos[@]}" -gt 0 ]; then
        if [ -z "$rem" ]; then rem="${pos[0]}"; specs=("${pos[@]:1}"); else specs=("${pos[@]}"); fi
    fi
    for w in "${specs[@]+"${specs[@]}"}"; do
        w="$(printf '%s' "$w" | sed 's|//[^/@]*@|//|')"
        if [ -n "$del" ]; then shown+=("удалить:$w"); continue; fi
        src="${w#+}"; dsta="$src"
        case "$src" in *:*) dsta="${src#*:}"; src="${src%%:*}" ;; *) { [ "$src" != HEAD ] && [ "$src" != @ ]; } || dsta="$br" ;; esac
        dsta="${dsta#refs/heads/}"
        case "$src" in
            HEAD|@) kind="HEAD→$dsta" ;;
            "$br") kind="${br:+ветка $br→$dsta}"; [ -n "$br" ] || kind="по имени:$src" ;;
            *) kind="по имени:$src" ;;
        esac
        shown+=("$kind")
        case "$dsta" in ''|refs/*) continue ;; esac
        { [ "$src" = HEAD ] || [ "$src" = @ ] || { [ -n "$br" ] && [ "$src" = "$br" ] && [[ "${w#+}" == *:* ]]; }; } || continue
        [ "$dsta" = "$br" ] || bad="${bad:+$bad }$dsta"
    done
    say "git push: каталог $PWD · корень git $top · origin ${url:-—} · ветка ${br:-отсоединённая} · голова ${head:-—} · отправляется: ${rem:+$(printf '%s' "$rem" | sed 's|//[^/@]*@|//|') }${shown[*]:-по настройкам git}"
    mkdir -p "$DIR" 2>/dev/null
    journal "push-where class=$CLASS top=$top origin=${url:-—} branch=${br:-detached} head=${head:-—} remote=${rem:+$(printf '%s' "$rem" | sed 's|//[^/@]*@|//|')} refs=${shown[*]:-—} cwd=$PWD"
    if [ -n "$bad" ] && push_to_foreign_branch "$top"; then
        say "git push из первичной копии воркспейса ($top) кладёт её голову в ветку «$bad» при текущей «${br:-отсоединённая}»: ветки, которой здесь нет, — а ветка задачи живёт в КОПИИ задачи (ws#1182: так ветка чужого репозитория легла в этот). Из копии: cd <копия> && heavy-slot.sh … либо git -C <копия> push …. Команда не запускалась"
        exit 64
    fi
    [ "$CLASS" != ci-local ] || push_homes "$top"
    GIT_IDX=""; GDIR="$PWD"
}
# push_to_foreign_branch <корень git> — 0, если корень — первичная копия воркспейса.
push_to_foreign_branch() {
    local top="$1" gdir cdir
    # если корень — первичная копия воркспейса: не связанная копия (git-dir ≠ common-dir)…
    gdir="$(cd "$top" && cd "$(git rev-parse --absolute-git-dir)" 2>/dev/null && pwd -P)"
    cdir="$(cd "$top" && cd "$(git rev-parse --path-format=absolute --git-common-dir)" 2>/dev/null && pwd -P)"
    [ -n "$gdir" ] && [ "$gdir" = "$cdir" ] || return 1
    # …и тот репозиторий, где отслеживается сам слот.
    git -C "$top" ls-files --error-unmatch scripts/heavy-slot.sh >/dev/null 2>&1 || return 1
    return 0
}

# cancel_without_ticket <база журнала> — у заявки --enqueue билета нет: печатает различимое пробой
# (ws#1250 K5): ИДЁТ — жив процесс из <база>.pid, и в его argv стоит та же база (вошла в слот,
# класс stand во внешний ns, маршрут кластера: очередь её не держит, снимать в очереди нечего —
# процесс не трогается, его группа названа); завершилась — есть <база>.rc, код назван; иначе — не
# выдавалась либо журналы сняты. Код у всех трёх — 69: отмена не выполнилась.
cancel_without_ticket() {
    local b="$1" p="" args=""
    [ -s "$b.pid" ] && p="$(head -n 1 -- "$b.pid" 2>/dev/null)"
    [[ "$p" =~ ^[1-9][0-9]*$ ]] && kill -0 "$p" 2>/dev/null && args="$(tr '\0' '\n' < "/proc/$p/cmdline" 2>/dev/null)"
    if [ -n "$args" ] && grep -qxF -- "$b" <<< "$args"; then
        say "у заявки «$b» билета нет, но она ИДЁТ: pid $p — вошла в слот либо идёт мимо очереди (stand во внешний ns, маршрут кластера); --cancel снимает лишь ждущую заявку, команду не трогаю; остановить — kill -TERM -- -$p (группа заявки) — не выполнилось (исход — $b.rc)"
    elif [ -s "$b.rc" ]; then
        say "у заявки «$b» билета нет: завершилась кодом $(head -c 16 -- "$b.rc" | tr -d '\n') (исполнилась либо снята) — не выполнилось"
    else
        say "у заявки «$b» билета нет, процесса и исхода тоже ($b.pid, $b.rc): не выдавалась либо журналы сняты — не выполнилось"
    fi
}

# console_adapter — ci-local локально, `git push` с хуком из клона, где в HEAD есть каталог
# ui-future/ (шапка, «ЗАВИСИМОСТИ КОНСОЛИ ЛОКАЛЬНО»): CMD получает -c core.hooksPath на
# переходник $P.hooks, чей pre-push отдаёт вход git суждению --console-deps, а затем — настоящему
# хуку клона. Прочие хуки клона — ссылками. Переходник снимает свой core.hooksPath и HS_* до хука:
# иначе фикстуры проверок (git init + commit) получили бы хуки клона. Исход суждения — $P.console.
console_adapter() {
    local top hooks h
    CMD_R=("${CMD[@]}"); git_push_form || return 0
    top="$(git -C "$GDIR" rev-parse --show-toplevel 2>/dev/null)" || return 0
    [ -n "$(git -C "$top" ls-tree -d --name-only HEAD -- ui-future 2>/dev/null)" ] || return 0
    hooks="$(cd "$GDIR" && cd "$(git rev-parse --git-path hooks 2>/dev/null)" 2>/dev/null && pwd -P)" || return 0
    [ -x "$hooks/pre-push" ] || return 0
    mkdir -p "$P.hooks" || { say "консоль — каталог переходника $P.hooks не создан: зависимости консоли слот не судит"; return 0; }
    for h in "$hooks"/*; do
        case "${h##*/}" in pre-push|*.sample) continue ;; esac
        [ -f "$h" ] && [ -x "$h" ] && ln -s "$h" "$P.hooks/${h##*/}"
    done
    # shellcheck disable=SC2016  # текст переходника раскрывает он сам
    printf '%s\n' '#!/usr/bin/env bash' 'set -uo pipefail' 'lines="$(cat)"' \
        'printf "%s\n" "$lines" | bash "$HS_SELF" --console-deps "$HS_RC" "$HS_RUNSH" || exit 1' \
        'ours="'"'"'core.hooksPath'"'"'='"'"'$HS_HOOKS'"'"'"; p="${GIT_CONFIG_PARAMETERS:-}"; p="${p//" $ours"/}"; p="${p//"$ours"/}"; p="${p# }"' \
        'if [ -n "$p" ]; then export GIT_CONFIG_PARAMETERS="$p"; else unset GIT_CONFIG_PARAMETERS; fi' \
        'orig="$HS_ORIG"; unset HS_ORIG HS_SELF HS_RC HS_HOOKS HS_RUNSH' \
        'printf "%s\n" "$lines" | exec "$orig" "$@"' > "$P.hooks/pre-push"
    chmod +x "$P.hooks/pre-push"
    CMD=("${CMD[@]:0:$(( GIT_IDX + 1 ))}" -c "core.hooksPath=$P.hooks" "${CMD[@]:$(( GIT_IDX + 1 ))}")
    CENV+=(HS_ORIG="$hooks/pre-push" HS_SELF="$SELF" HS_RC="$P.console" HS_HOOKS="$P.hooks"
        HS_RUNSH="$(dirname -- "$SELF")/remote-heavy/run.sh")
    GIT_IDX=""; GDIR="$PWD"
}

# console_deps <файл кода> <run.sh> — суждение переходника (вход git на stdin, каталог — корень
# отправляемой копии): зависимости консоли для ТОГО дерева, что будет судить хук. Код 0 — ход
# хуку; 1 — отказ до хука, код слота (64, 69) — в <файл кода>. Хук до проверок консоли не
# доходит — ход как есть, суждения нет. Производители решения хука kacho (scripts/hooks/pre-push)
# и как каждый взят здесь: обход всего — KACHO_SKIP_PREPUSH (прочитан); вход git — черновик
# (push_is_draft), одни удаления, число вершин (повторены: выражения хука); диапазон —
# prepush-range.sh (СПРОШЕН, вход git, KACHO_TRUNK_REF); группы — prepush-groups.sh (СПРОШЕН с
# KACHO_PUSH_RANGE = диапазоном, как ставит хук; KACHO_PREPUSH_GROUP, KACHO_TRUNK_REF); правка
# консоли — `*ui-future/*` по диапазону (повторено); дерево — subject_tree_for_push (повторено);
# готовность — предикат проверок (deps-ready.mjs, как ci-local.sh npm_deps_ready).
console_deps() {
    local rcf="$1" runsh="$2" lines top zero=0000000000000000000000000000000000000000
    local total=0 drafts=0 tips="" t _l lsha rref _r ntips rg rgc ch="" x grp head dirty why n m nn=0 miss="" blk t0
    lines="$(cat)"
    unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_COMMON_DIR GIT_PREFIX
    # Журнал — лишь суждению слота (файл кода — в его записи active/): ручной вызов события слота не пишет.
    cdj() { [[ "$rcf" == "$DIR/active/"* ]] || return 0; journal "console-deps decision=$1 top=${top:-—} tip=${tips:0:8} why=$2"; }
    cdpass() { say "консоль — $2: зависимости консоли слот не судит, ход хуку"; cdj "$1" "$2"; return 0; }
    cdrefuse() { printf '%s\n' "$2" > "$rcf"; say "$3"; cdj "$1" "$4"; return 1; }
    if ! top="$(git rev-parse --show-toplevel 2>/dev/null)" || ! cd "$top"; then cdpass pass "корень дерева отправки не найден"; return 0; fi
    [ "${KACHO_SKIP_PREPUSH:-0}" != 1 ] || { cdpass pass "KACHO_SKIP_PREPUSH=1 — хук проверок дерева не гонит"; return 0; }
    while read -r _l lsha rref _r; do
        [ -n "${rref:-}" ] || continue
        total=$(( total + 1 ))
        case "$rref" in refs/heads/wip/*|refs/heads/tmp/*) drafts=$(( drafts + 1 )) ;; esac
        [ "$lsha" != "$zero" ] || continue
        t="$(git rev-parse --verify --quiet "$lsha^{commit}" 2>/dev/null)" || continue
        tips="$tips$t"$'\n'
    done <<< "$lines"
    tips="$(printf '%s' "$tips" | sed '/^$/d' | sort -u)"; ntips="$(printf '%s' "$tips" | grep -c .)"
    [ "$total" -gt 0 ] || { cdpass pass "вход git пуст — отправляемой вершины нет"; return 0; }
    [ "$drafts" -lt "$total" ] || { cdpass pass "все ссылки — черновики (wip/, tmp/), хук проверок не гонит"; return 0; }
    [ "$ntips" -gt 0 ] || { cdpass pass "отправка — одни удаления ссылок, хук проверок не гонит"; return 0; }
    [ "$ntips" -eq 1 ] || { cdpass pass "вершин $ntips — хук откажет сам до проверок"; return 0; }
    [ -f scripts/hooks/prepush-range.sh ] || { cdpass pass "производителя диапазона scripts/hooks/prepush-range.sh в дереве нет — правку консоли не вывести"; return 0; }
    rg="$(printf '%s\n' "$lines" | bash scripts/hooks/prepush-range.sh 2>/dev/null)"; rgc=$?
    { [ "$rgc" -eq 0 ] && [ -n "$rg" ]; } || { cdpass pass "диапазон отправки не выбран (prepush-range.sh, код $rgc) — хук откажет тем же производителем"; return 0; }
    for x in $rg; do ch="$ch"$'\n'"$(git diff --name-only "$x" 2>/dev/null)"; done
    case "$ch" in *ui-future/*) ;; *)
        say "консоль — правка её не трогает (диапазон $rg): зависимости не судятся"; cdj untouched "ui-future/ не в диапазоне"; return 0 ;;
    esac
    # Набор групп — у производителя хука, с ТЕМ диапазоном, что хук экспортирует (KACHO_PUSH_RANGE
    # вызывающего хук перекрывает). Нет производителя — хук получит пустой набор, ci-local — all;
    # all гонит консоль лишь единственным словом (ci-local: case "$GROUP" in all), в списке — отказ 2.
    grp="$(KACHO_PUSH_RANGE="$rg" bash scripts/hooks/prepush-groups.sh 2>/dev/null)"
    grp="$(printf '%s' "$grp" | tr -s ' \t\n' '   ' | sed 's/^ //; s/ $//')"
    case " ${grp:-all} " in " all "|*" ui "*|*" ui-types "*) ;; *)
        say "консоль — правка её трогает, но набор групп хука «$grp» (prepush-groups.sh) её проверок не гонит: зависимости не судятся, ход хуку"
        cdj nogroup "групп консоли нет: $grp"; return 0 ;;
    esac
    head="$(git rev-parse --verify --quiet 'HEAD^{commit}' 2>/dev/null)"
    dirty="$(git status --porcelain 2>/dev/null)"
    if [ "$tips" != "$head" ] || [ -n "$dirty" ]; then
        why=""
        [ "$tips" = "$head" ] || why="рабочая копия на ${head:0:8}, а отправляется ${tips:0:8}"
        if [ -n "$dirty" ]; then
            n="$(printf '%s\n' "$dirty" | grep -c .)"
            why="${why:+$why; }копия грязна: путей $n (git status --porcelain), первые: $(printf '%s\n' "$dirty" | head -n 3 | cut -c4- | tr '\n' ' ' | sed 's/ $//')"
        fi
        cdrefuse temp 64 "ОТКАЗ до проверок хука: правка трогает консоль, а хук будет судить ВРЕМЕННУЮ копию ревизии ${tips:0:8} (git worktree add) — $why. Во временной копии node_modules нет по построению: проверки консоли уйдут в «НЕ выполнено», и хук откажет в конце прогона; npm ci в рабочей копии ей не поможет. Приведите копию к отправляемой ревизии (закоммитьте либо уберите правки, отправляйте её голову) — тогда слот поставит зависимости сам, как ui.yml; либо отправляйте из чистой копии на ${tips:0:8}. Отправка не запускалась (не выполнилось, не красное)" "$why"
        return 1
    fi
    command -v node >/dev/null 2>&1 || { cdrefuse fail 69 "ОТКАЗ до проверок хука: правка трогает консоль, а node нет в PATH — готовность зависимостей не судить, и проверки консоли не исполнятся. Отправка не запускалась (не выполнилось)" "node нет"; return 1; }
    [ -f ui-future/scripts/deps-ready.mjs ] || { cdrefuse fail 69 "ОТКАЗ до проверок хука: правка трогает консоль, а предиката готовности ui-future/scripts/deps-ready.mjs в дереве нет — проверки консоли (ci-local.sh, npm_deps_ready) не исполнятся и после npm ci. Отправка не запускалась (не выполнилось)" "deps-ready.mjs нет"; return 1; }
    for m in ui-future/*/package.json; do
        [ -f "$m" ] || continue
        nn=$(( nn + 1 ))
        node ui-future/scripts/deps-ready.mjs "${m%/package.json}" >/dev/null 2>&1 && continue
        [ -z "$miss" ] || continue
        miss="${m#ui-future/}"; miss="${miss%/package.json}"
    done
    if [ -z "$miss" ]; then
        say "консоль — правка её трогает, хук судит рабочую копию: зависимости стоят, готовы пакетов $nn из $nn (deps-ready.mjs) — установки нет"
        cdj ready "готовы $nn из $nn"; return 0
    fi
    say "консоль — правка её трогает, хук судит рабочую копию, пакет «$miss» не готов (deps-ready.mjs): ставлю как ui.yml — шаг ЗАВИСИМОСТИ КОНСОЛИ $runsh"
    blk="$(sed -n '/^# npmci-begin$/,/^# npmci-end$/p' "$runsh" 2>/dev/null)"
    [[ "$blk" == *$'\n# npmci-end' ]] || { cdrefuse fail 69 "ОТКАЗ до проверок хука: шага установки (маркеры npmci-begin/npmci-end) в $runsh нет — дефект оснастки. Отправка не запускалась (не выполнилось)" "шага нет"; return 1; }
    t0="$(now)"
    # shellcheck disable=SC2016  # строка дочерней оболочки, $1 раскрывает она
    if ! HEAVY_PUSH_INPUT="$lines" HEAVY_NPM_CACHE="${npm_config_cache:-$(getent passwd "$(id -u)" | cut -d: -f6)/.npm}" \
        bash -c 'pf() { printf "heavy-slot: консоль: %s\n" "$1" >&2; exit 69; }'$'\n'"$blk" >&2; then
        cdrefuse fail 69 "ОТКАЗ до проверок хука: зависимости консоли не поставлены — причина строкой «heavy-slot: консоль: …» выше. Отправка не запускалась (не выполнилось)" "установка отказала"
        return 1
    fi
    dirty="$(git status --porcelain 2>/dev/null)"
    if [ -n "$dirty" ]; then
        cdrefuse fail 69 "ОТКАЗ до проверок хука: после установки копия стала грязной ($(printf '%s\n' "$dirty" | head -n 3 | cut -c4- | tr '\n' ' ' | sed 's/ $//')) — хук судил бы временную копию без node_modules. Отправка не запускалась (не выполнилось)" "грязна после установки"
        return 1
    fi
    cdj install "поставлены за $(( $(now) - t0 )) с"
    return 0
}

# cancel_ticket <номер> — снять СВОЮ заявку очереди по билету (ws#1156): ждущую, отложенную (74/75)
# или внешнего входа, и её отсоединённое ожидание --enqueue (процесс слота получает TERM, его .rc
# запишет обёртка). Билет чужой — «who» (ветка@каталог) не совпал с вызвавшим — не снимается:
# отказ 64 с названным владельцем. Неизвестный билет — 69 «не выполнилось», а не успех. Запись
# cancel — в журнал. Билет ВОШЕДШЕГО в слот снять нечем: его уже нет в очереди (слот снимает сигнал).
cancel_ticket() {
    local n="${1:-}" k f="" kind="" me who pid st cls what b
    if [[ "$n" == */* ]]; then  # журнал заявки из строки ENQUEUED (ws#1244): билет — по полю enq
        b="$(realpath -m -- "$n")"; b="${b%.log}"; b="${b%.rc}"; b="${b%.pid}"
        f="$(grep -l -x -F -- "enq=$b" "$DIR"/queue/* "$DIR"/ext/* 2>/dev/null | head -n 1)"
        [ -n "$f" ] || { cancel_without_ticket "$b"; return 69; }
        n="$((10#${f##*/}))"; f=""
    fi
    [[ "$n" =~ ^[0-9]{1,12}$ ]] || { say "--cancel «$n» — номер билета (целое) либо журнал заявки из строки ENQUEUED; билеты и их владельцев показывает --status"; return 64; }
    n=$((10#$n)); k="$(printf '%012d' "$n")"
    mkdir -p "$DIR/queue" "$DIR/ext" 2>/dev/null
    me="$(git -C "$PWD" branch --show-current 2>/dev/null)@$PWD"
    elock
    if [ -e "$DIR/ext/$k" ]; then f="$DIR/ext/$k"; kind=ext; else eunlock; lock; [ ! -e "$DIR/queue/$k" ] || { f="$DIR/queue/$k"; kind=queue; }; fi
    if [ -z "$f" ]; then
        unlock
        say "билета $n в очереди нет: снят, исполнился либо не выдавался — не выполнилось"; return 69
    fi
    who="$(field "$f" who)"; cls="$(field "$f" class)"; pid="$(field "$f" pid)"; st="$(field "$f" pid_start)"
    if [ "$who" != "$me" ]; then
        if [ "$kind" = ext ]; then eunlock; else unlock; fi
        say "билет $n чужой: владелец «$who», вызвал «$me» — снимает только владелец, из своего каталога и ветки"; return 64
    fi
    what="ждал"; [ "$kind" = ext ] && what="внешний вход"; [ -z "$(field "$f" resume_until)" ] || what="отложенный"
    if [ -n "$pid" ] && [ "$(pid_start "$pid")" = "$st" ]; then kill -TERM "$pid" 2>/dev/null; what="$what, ожидание pid $pid снято"; fi
    rm -f "$f"
    journal "cancel ticket=$n kind=$kind class=$cls who=$who waiter_pid=${pid:-—}"
    if [ "$kind" = ext ]; then eunlock; else unlock; fi
    say "снято: билет $n ($cls: $what)"
    return 0
}

# subject_of <корень git> — предмет отправки: workspace (в корне отслеживается сам слот) либо kaname
# (origin PRO-Robotech/kaname); иное — предмета нет, бронь класса.
subject_of() {
    local url
    if git -C "$1" ls-files --error-unmatch scripts/heavy-slot.sh >/dev/null 2>&1; then echo workspace; return 0; fi
    url="$(git -C "$1" remote get-url origin 2>/dev/null)"
    case "$url" in *PRO-Robotech/kaname|*PRO-Robotech/kaname.git) echo kaname; return 0 ;; esac
    return 1
}
# subject_book <корень git> — «МиБ|предмет|основание» из SUBJECT_BUDGETS; нет предмета — 1.
subject_book() {
    local name line sb_budget
    name="$(subject_of "$1")" || return 1
    while IFS= read -r line; do
        [ "${line%%|*}" = "$name" ] || continue
        line="${line#*|}"
        sb_budget="${line%%|*}"
        printf '%s|%s|%s\n' "$sb_budget" "$name" "${line#*|}"
        return 0
    done <<< "$SUBJECT_BUDGETS"
    return 1
}
# book_cmd --book <класс> -- <команда…> — бронь, которую слот поставит этой команде из этого каталога
# (число на stdout, основание в stderr), ничего не занимая.
book_cmd() {
    local cls="${2:-}" b top sb rest
    b="$(class_budget "$cls")" || { say "класса «$cls» нет"; return 64; }
    { [ "${3:-}" = -- ] && [ "$#" -ge 4 ]; } || { say "форма вызова: heavy-slot.sh --book <класс> -- <команда> [аргументы…]"; return 64; }
    shift 3
    CMD_R=("$@"); git_push_form || true
    if [ "$cls" = ci-local ] && [ -n "$PUSH_AT" ] && top="$(git -C "$GDIR" rev-parse --show-toplevel 2>/dev/null)" && sb="$(subject_book "$top")"; then
        b="${sb%%|*}"; rest="${sb#*|}"
        say "бронь ci-local по предмету отправки «${rest%%|*}»: $(mib "$b") — ${rest#*|}"
    else
        say "бронь $cls: $(mib "$b") — бюджет класса (предмета отправки нет)"
    fi
    printf '%s\n' "$b"
}

