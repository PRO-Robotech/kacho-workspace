# ci-wait.sh — ОДНО ожидание вердикта конвейера вместо чтений с паузой (ws#1114).
#
# ЗАЧЕМ. Заказ владельца 2026-10-16 дословно: «Переделай ci флоу так что бы время
# потрачено на проверку состояния было минимально, очереди быстро рассасывались».
# Аудит двух недель: шаг ci шаблона волны держал до 30 чтений с паузой 240 с, медиана
# 10 агентов-читателей на голову; агенты ci-watcher ждали CI 239 агент-ч (27 %
# агент-времени). Здесь ожидание — одна команда ≤ 540 с: блокирующее чтение FIFO,
# в который демон состояния пишет при смене состояния PR, без цикла sleep.
#
# ИСПОЛЬЗОВАНИЕ
#   ci-wait.sh <владелец/репозиторий> <номер PR> <голова sha40> [--max <с>]
# --max — срок ожидания, 1…540 с (по умолчанию 540): вызов не держит ожидание
# дольше 10 минут (`CLAUDE.md` «Не жди»); больше — отказ кодом 2 до первого чтения.
#
# ПОРЯДОК
#   1. Первое чтение — сразу, до ожидания: код 4 («база устарела») и любой код,
#      кроме 3, выходят немедленно (у ci-read.sh старшинство 2 > 1 > 4 > 3).
#   2. Код 3 («идёт») — ждать: `read -t` из FIFO запроса. Строка в FIFO (сигнал
#      демона) либо шаг пробуждения CI_WAIT_TICK (по умолчанию 180 с — предел
#      годности снимка) — новое чтение. Демона нет — чтение раз в шаг, как прежде
#      пауза, но одним агентом и одной командой.
#   3. Голова из VERDICT не та, что передана, — REASON HEAD-MOVED, выход: ждать
#      заменённую голову нечего.
#   4. Срок истёк при коде 3 — REASON WAIT-EXPIRED, выход 3: «идёт», не провал.
# Код выхода — код последнего чтения (0 · 1 · 2 · 3 · 4 · 5 — словарь ci-read.sh);
# свой отказ (доводы, нет чтения, нет FIFO) — 2.
#
# ЧТЕНИЕ — scripts/ci-read.sh рядом (того же архива рецепта «ЗАПУСК»); доводы
# --from-state (снимок демона, ws#1113) и --head <голова> (ключ снимка) передаются,
# только если чтение их знает — в его тексте есть разбор `--from-state)` и `--head)`:
# иначе ci-read.sh отказал бы кодом 2.
#
# КОНТРАКТ С ДЕМОНОМ (scripts/ci-state/ci-stated.py, ws#1113): FIFO запроса
#   $CI_STATE_DIR/wait/<владелец>__<репозиторий>__<PR>.fifo   (каталог 0700, FIFO 0600)
# — ОДИН на PR, его заводит тот, кто первым к нему пришёл (демон либо ожидающий), и
# снимает демон вместе с закрытым запросом; ожидающий его не снимает. Демон при смене
# кода или ключа пишет строку, открывая FIFO без блокировки (O_WRONLY|O_NONBLOCK;
# читающего нет — пропуск). CI_STATE_DIR — по умолчанию ~/.cache/kacho-ci-state.
# ГРАНИЦА: два ожидающих одного PR делят строку — её получает один, второго будит шаг.
#
# ВЫВОД: строка WAIT на каждое чтение (номер, секунды, код, чем разбужено), затем
# вывод ПОСЛЕДНЕГО чтения целиком (REASON/CENSUS/VERDICT ci-read.sh) и итог
#   WAITED <с> · чтений N · пробуждений сигналом K · по шагу M
# — «ноль пробуждений» отличим от «не ждал».
#
# ПОДМЕНА ради доказательства (ci-wait-inject.sh): CI_WAIT_READ — чтение вместо
# ci-read.sh; CI_WAIT_TICK — шаг пробуждения; CI_STATE_DIR — каталог FIFO.
#
# ГРАНИЦА (названо): сигнал, пришедший между чтением и открытием ожидания, не теряется —
# FIFO открыт до первого чтения и держит строку; сигнал, записанный в FIFO другого PR,
# не будит — это свойство, а не дефект. Демон, переставший писать, ожидание не ломает:
# шаг пробуждения читает сам.
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
READ="${CI_WAIT_READ:-$HERE/../ci-read.sh}"
SD="${CI_STATE_DIR:-${XDG_CACHE_HOME:-$HOME/.cache}/kacho-ci-state}"
TICK="${CI_WAIT_TICK:-180}"
LIMIT=540

void() { printf 'VOID\t%s\n' "$1"; printf 'VERDICT\tunread\tкод 2 (ci-wait.sh)\n'; exit 2; }

[ $# -ge 3 ] || void "usage: ci-wait.sh <владелец/репозиторий> <номер PR> <голова sha40> [--max <с>]"
repo="$1" pr="$2" head="$3"; shift 3
max="$LIMIT"
while [ $# -gt 0 ]; do
    case "$1" in
        --max) [ $# -ge 2 ] || void "--max без числа"; max="$2"; shift 2 ;;
        --max=*) max="${1#--max=}"; shift ;;
        *) void "неизвестный довод «$1»" ;;
    esac
done
[[ "$repo" =~ ^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$ ]] || void "репозиторий «$repo» не формы <владелец>/<имя>"
[[ "$pr" =~ ^[0-9]+$ ]] || void "«$pr» не номер PR"
[[ "$head" =~ ^[0-9a-f]{40}$ ]] || void "голова «$head» не sha40"
[[ "$max" =~ ^[0-9]+$ ]] && [ "$max" -ge 1 ] && [ "$max" -le "$LIMIT" ] \
    || void "--max «$max» вне 1…$LIMIT с: вызов не держит ожидание дольше 10 минут («Не жди»)"
[[ "$TICK" =~ ^[0-9]+$ ]] && [ "$TICK" -ge 1 ] || void "CI_WAIT_TICK «$TICK» не число секунд ≥ 1"
[ -r "$READ" ] || void "чтения $READ нет"
from=()
grep -q -- '--from-state)' "$READ" && from+=(--from-state)
grep -q -- '--head)' "$READ" && from+=(--head "$head")

out="$(mktemp)" || void "временного файла нет"
cleanup() { exec 3>&- 2> /dev/null; rm -f "$out"; }
trap cleanup EXIT
# FIFO открывается ДО первого чтения: сигнал демона во время чтения ждёт в нём.
( umask 077; mkdir -p "$SD/wait" ) 2> /dev/null || void "каталога ожидания $SD/wait нет и не заводится"
fifo="$SD/wait/${repo//\//__}__$pr.fifo"
[ -p "$fifo" ] || mkfifo -m 0600 "$fifo" 2> /dev/null || [ -p "$fifo" ] || void "FIFO $fifo не заводится"
[ -O "$fifo" ] || void "FIFO $fifo не мой — не открываю"
# Открытие на чтение и запись не ждёт писателя (Linux) и не даёт EOF, пока FIFO открыт.
exec 3<> "$fifo" || void "FIFO $fifo не открывается"

t0="$(date +%s)"
deadline=$((t0 + max))
reads=0 wakes=0 ticks=0 by="первое"
while :; do
    reads=$((reads + 1))
    bash "$READ" "$repo" "$pr" "${from[@]+"${from[@]}"}" > "$out" 2>&1
    rc=$?
    now="$(date +%s)"
    vh="$(sed -n 's/^VERDICT\t.*голова \([0-9a-f]\{40\}\).*$/\1/p' "$out" | tail -1)"
    printf 'WAIT\tчтение %d\t%d с\tкод %d\t%s\n' "$reads" "$((now - t0))" "$rc" "$by"
    extra=""
    if [ "$rc" = 3 ] && [ -n "$vh" ] && [ "$vh" != "$head" ]; then
        extra="$(printf 'REASON\tHEAD-MOVED\tголова PR %s, ожидалась %s — заменённую голову не ждут' "${vh:0:12}" "${head:0:12}")"
    elif [ "$rc" = 3 ] && [ "$now" -ge "$deadline" ]; then
        extra="$(printf 'REASON\tWAIT-EXPIRED\tсрок %d с истёк, CI идёт — не провал' "$max")"
    elif [ "$rc" = 3 ]; then
        left=$((deadline - now)); t=$((left < TICK ? left : TICK))
        if read -r -t "$t" -u 3 _; then
            wakes=$((wakes + 1)); by="сигнал демона"
            # Пачка сигналов за одно чтение — одно пробуждение.
            while read -r -t 0.05 -u 3 _; do :; done
        else
            ticks=$((ticks + 1)); by="шаг ${t} с"
        fi
        continue
    fi
    cat "$out"
    [ -z "$extra" ] || printf '%s\n' "$extra"
    printf 'WAITED\t%d с\tчтений %d\tпробуждений сигналом %d\tпо шагу %d\n' "$(( $(date +%s) - t0 ))" "$reads" "$wakes" "$ticks"
    exit "$rc"
done
