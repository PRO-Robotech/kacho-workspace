# ════════════════════════════════════════════════════════════════════════════
# Четвёртый возврат ws#884 (⛔ на f790fdca1) и решение Д43: разборщик — fail-closed.
# Ячейка «зависит от», которую он не прочёл ЦЕЛИКОМ, — ОТКАЗ с координатой
# (файл:строка, полоса, текст ячейки), а не ребро, выпавшее молча. Форма из дерева
# (2918:S2-B1 ← «X2-F» @d3387fcd4, ветка issue-880) — id с буквенным суффиксом.
# 9130/9131: X2 (S), X2-F (L), B1 ← ячейка. Ребро на X2-F — путь 110; на X2 — 80.
