# inject.sh — доказательство, что `lane-schedule.py` СПОСОБЕН отказать, способен
# отличить пустой обход от расчёта и считает известный пример ТОЧНО.
#
# Входы СИНТЕТИЧЕСКИЕ (маршрут работ реальной под-фазы меняется от захода к
# заходу, и пример с известным ответом на нём не построить). Каждая ось меняет
# ОДИН факт против законного близнеца. Пример «известный путь» посчитан руками:
#
#   9001: B2 proto-sync corelib+kacho S │ B1 docs-writer kacho S │ A1←B1,B2 M,
#         A2←A1 M, A3←A2 L, A4←A3 S (go-implementer kacho) │ D1←A4 диспетчер
#   9002: X1 go-implementer L │ X2←X1 migration-writer L │ X3←X2,Е1 docs-writer S
#   S=15 M=25 L=45, ревью 25 на пакет.
#   Цепочка A1+A2+A3 = 4 единицы (предел), A4 — отдельным пакетом: 40+120+40 = 200.
#   literal склеивает X3 с B1 (однотипные, независимые): 70+70+55+120+40 = 355.
#   guard эту склейку отвергает: путь остаётся 200.
#   B (9002 Е1 → 9001): X3 ждёт всю 9001 — 200+40 = 240.
#   Слотов 2 → 220; путь достигается с 3 слотов.
#
#   K1 guard A        → код 0, путь 200, пакетов 8, 2 слота 220, минимум 3
#   K2 цепочка        → A1+A2+A3 одним пакетом, A4 — отдельным (предел 4 единицы)
#   K3 literal A      → путь 355 (склейка удлиняет путь — то, что guard запрещает)
#   K4 guard B        → путь 240 (смысловое ребро удлиняет срок)
#   C1 цикл явных рёбер           → код 1, путь цикла назван
#   C2 цикл только раскрытием стадии → код 0 (близнец C1), снятое ребро названо
#   E1 ноль полос в разделе       → код 2, не «срок 0»
#   E2 ноль файлов                → код 2
#   E3 ведомость без строк        → код 2
#   R1 строка ведомости без носителя → код 1
#   R2 строка таблицы не той ширины  → код 1 с координатой
#   R3 B без ведомости            → код 1
#   R4 повтор id полосы           → код 1
#   R5 нет раздела «Полосы»       → код 1
#
# Пары, заведённые после приёмки ws#884 (⛔ на fc25f8038: порчи guard `<=` → `<`
# и приоритета расписания проходили набор 21/21). Каждое решение инструмента
# держится пробой, которая краснеет на его однофактной порче; перечень порч и
# требование «набор краснеет на каждой» — `mutants.py` рядом.
#   K5 A на ведомости K4          → путь 200: межфазная строка в A не действует
#   G1/G2 guard на границе        → путь = базе: склейка принята; длиннее: отвергнута
#   U1/U2 предел склейки          → L+L = 4 единицы одним пакетом; +S — отдельно
#   H1/H2 цепочка и цикл пакетов  → цепочка через чужой пакет отвергнута / законна
#   M1 зависимые однотипные       → разные под-фазы, ребро ведомости: два пакета
#   I1 строка «под-фаза → она же» → фраза в ячейке; носители не ждут друг друга
#   X1 межфазная строка           → носитель одноимённого жетона ЦЕЛИ не исключён
#   Q1 расписание                 → 2 слота: длинный остаток пути первым, 110
#   Z1 пакет диспетчера           → 0 мин, слота не занимает и не отдаёт
#   E4 пустой файл среди непустых → код 2
#   N1 таблица без «зависит от»   → заметка; близнец — K1 без заметки
#
# `LANE_SCHEDULE_TOOL` подменяет путь к инструменту — им `mutants.py` гонит
# набор против испорченной копии.
# shellcheck disable=SC2016  # обратные кавычки в строках таблиц — разметка tasks.md, не подстановка
set -uo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
tool="${LANE_SCHEDULE_TOOL:-$here/lane-schedule.py}"
box="$(mktemp -d)"
trap 'rm -rf "$box"' EXIT

pass=0; fail=0
ok()  { pass=$((pass + 1)); printf 'ПРОЙДЕНО %s\n' "$1"; }
bad() { fail=$((fail + 1)); printf 'ПРОВАЛЕНО %s — %s\n' "$1" "$2"; }

HDR='| № | полоса | исполнитель | репозиторий · пути | зависит от | размер |
|---|---|---|---|---|---|'

# task <под-фаза> <строки таблицы…> — tasks.md в каталоге issue-<под-фаза>.
task() {
  local n=$1; shift
  mkdir -p "$box/issue-$n"
  {
    printf '# маршрут %s\n\n## 1. Внешние зависимости\n\nЕ1 — соседняя под-фаза на стенде.\n\n' "$n"
    printf '## 2. Полосы\n\n### Ярус 1 — S1\n\n%s\n' "$HDR"
    printf '%s\n' "$@"
    printf '\n## 3. Порядок по времени\n\n| шаг | полоса |\n|---|---|\n| 1 | Z9 |\n'
  } > "$box/issue-$n/tasks.md"
  echo "$box/issue-$n/tasks.md"
}

# run <метка> <ожидаемый код> <аргументы…> — вывод в $box/<метка>.out
run() {
  local label=$1 want=$2; shift 2
  python3 "$tool" "$@" > "$box/$label.out" 2>&1
  local rc=$?
  if [ "$rc" -ne "$want" ]; then
    bad "$label" "код $rc, ожидался $want; вывод: $(head -3 "$box/$label.out" | tr '\n' ' ')"
    return 1
  fi
  return 0
}

has() {  # has <метка> <подстрока> <что утверждается>
  if grep -qF -- "$2" "$box/$1.out"; then ok "$1: $3"; else bad "$1" "нет «$2» ($3)"; fi
}

lacks() {  # lacks <метка> <подстрока> <что утверждается> — законный близнец молчит
  if grep -qF -- "$2" "$box/$1.out"; then bad "$1" "есть «$2» ($3)"; else ok "$1: $3"; fi
}

t1=$(task 9001 \
  '| B2 | контракт | `proto-sync` | corelib · proto; kacho · proto | — | S |' \
  '| B1 | страница | `docs-writer` | kacho · docs | — | S |' \
  '| A1 | звено 1 | `go-implementer` | kacho · a | B1, B2 | M |' \
  '| A2 | звено 2 | `go-implementer` | kacho · a | A1 | M |' \
  '| A3 | звено 3 | `go-implementer` | kacho · a | A2 | L |' \
  '| A4 | звено 4 | `go-implementer` | kacho · a | A3 | S |' \
  '| D1 | закрыть | диспетчер | kacho-workspace · — | A4 | S |')
t2=$(task 9002 \
  '| X1 | служба | `go-implementer` | kacho · b | — | L |' \
  '| X2 | схема | `migration-writer` | kacho · m | X1 | L |' \
  '| X3 | страница | `docs-writer` | kacho · docs | X2, Е1 | S |')
printf '# под-фаза\tжетон\tцель\n9002\tЕ1\t9001\n' > "$box/sem.tsv"

# ── K: известный пример ─────────────────────────────────────────────────────
if run K1 0 "$t1" "$t2" --edges A --pack guard --slots 1,2,3; then
  has K1 'критический путь: 200 мин' 'guard A — путь 200'
  has K1 'пакетов: 8;' 'пакетов 8'
  has K1 'слотов 1: срок 420 мин' '1 слот — сумма длительностей 420'
  has K1 'слотов 2: срок 220 мин' '2 слота — 220'
  has K1 'слотов до срока = пути: 3' 'путь достигается с 3 слотов'
  has K1 'перепись: 9001' 'перепись названа по файлу'
  has K1 'критический путь до склейки: 200 мин' 'путь до склейки — той же длительностью пакета'
  lacks K1 'без колонки «зависит от»' 'таблица с колонкой зависимостей заметки не даёт'
  # K2 — предел цепочки в 4 единицы: A4 не входит в пакет A1..A3.
  if grep -qP '\t9001:A1 9001:A2 9001:A3\tgo-implementer\tkacho\t4\t120\t' "$box/K1.out" \
     && grep -qP '\t9001:A4\tgo-implementer\tkacho\t1\t40\t' "$box/K1.out"; then
    ok 'K2: цепочка A1+A2+A3 = 4 единицы, A4 отдельно'
  else
    bad K2 'пакеты цепочки не те'
  fi
fi
if run K3 0 "$t1" "$t2" --edges A --pack literal; then
  has K3 'критический путь: 355 мин' 'literal склеивает X3 с B1 и удлиняет путь до 355'
  has K3 '9001:B1 9002:X3' 'склейка названа в таблице'
fi
if run K4 0 "$t1" "$t2" --edges B --pack guard --semantic "$box/sem.tsv"; then
  has K4 'критический путь: 240 мин' 'B — смысловое ребро удлиняет путь до 240'
  has K4 'B: 9002 Е1 -> все полосы 9001 (7), носителей 1' 'ребро ведомости напечатано'
fi
# K5 — близнец K4 без одного факта: режим A на той же ведомости межфазной строки не берёт.
if run K5 0 "$t1" "$t2" --edges A --pack guard --semantic "$box/sem.tsv"; then
  has K5 'критический путь: 200 мин' 'A — межфазная строка ведомости срока не меняет'
  lacks K5 '9002 Е1 -> все полосы' 'A — межфазное ребро не заведено'
fi

# ── C: цикл ─────────────────────────────────────────────────────────────────
c1=$(task 9003 \
  '| C1 | первое | `go-implementer` | kacho · a | C2 | S |' \
  '| C2 | второе | `go-implementer` | kacho · a | C1 | S |')
if run C1 1 "$c1"; then
  has C1 'ОТКАЗ — цикл в графе полос: 9003:C1 <- 9003:C2 <- 9003:C1' 'цикл назван путём'
fi
c2=$(task 9004 \
  '| N0 | первое | `go-implementer` | kacho · a | N1 | S |' \
  '| N1 | второе | `go-implementer` | kacho · a | S1 | S |')
if run C2 0 "$c2"; then
  has C2 '9004:N1 ребро от N0 снято: раскрытие стадии замкнуло бы цикл' 'снятое ребро названо'
fi

# ── E: пустой обход ─────────────────────────────────────────────────────────
e1=$(task 9005)
if run E1 2 "$e1"; then has E1 'ПУСТОЙ ОБХОД' 'ноль полос — не расчёт'; fi
if run E2 2; then has E2 'ПУСТОЙ ОБХОД' 'ноль файлов — не расчёт'; fi
printf '# только комментарий\n' > "$box/empty.tsv"
if run E3 2 "$t1" "$t2" --edges B --semantic "$box/empty.tsv"; then
  has E3 'ПУСТОЙ ОБХОД' 'пустая ведомость — B не вырождается в A молча'
fi

# ── R: отказы входа ─────────────────────────────────────────────────────────
printf '9002\tЕ7\t9001\n' > "$box/orphan.tsv"
if run R1 1 "$t1" "$t2" --edges B --semantic "$box/orphan.tsv"; then
  has R1 'без полосы-носителя' 'строка ведомости без предмета — отказ'
fi
r2=$(task 9006 '| W1 | лишняя ячейка | `go-implementer` | kacho · a | — | S | x |')
if run R2 1 "$r2"; then has R2 "issue-9006/tasks.md:" 'координата строки названа'; fi
if run R3 1 "$t1" --edges B; then has R3 'без --semantic' 'B без ведомости — отказ'; fi
r4=$(task 9007 \
  '| Q1 | раз | `go-implementer` | kacho · a | — | S |' \
  '| Q1 | два | `go-implementer` | kacho · a | — | S |')
if run R4 1 "$r4"; then has R4 'повторяются' 'повтор id — отказ'; fi
mkdir -p "$box/issue-9008"; printf '# без раздела\n\n## 1. Прочее\n' > "$box/issue-9008/tasks.md"
if run R5 1 "$box/issue-9008/tasks.md"; then has R5 'раздела «## … Полосы» нет' 'нет раздела — отказ'; fi

# ── G: граница guard — склейка при пути, РАВНОМ базе, законна ───────────────
# Длительности S=15, L=30 (ревью 25): G1+G2 одним пакетом = 15+15+25 = 55.
#   9010: H1 L = 30+25 = 55 — склейка пути не удлиняет → пакетов 2, склеек 1.
#   9011: близнец, H1 M = 50 — склейка удлиняет путь 50 → 55 → отказ, пакетов 3.
g1=$(task 9010 \
  '| G1 | страница 1 | `docs-writer` | kacho · docs | — | S |' \
  '| G2 | страница 2 | `docs-writer` | kacho · docs | — | S |' \
  '| H1 | служба | `go-implementer` | kacho · a | — | L |')
if run G1 0 "$g1" --pack guard --minutes S=15,M=25,L=30; then
  has G1 'пакетов: 2; цепочек (>1 полосы): 0; склеек: 1;' 'путь равен базе — склейка принята'
  has G1 'критический путь: 55 мин' 'путь 55'
fi
g2=$(task 9011 \
  '| G1 | страница 1 | `docs-writer` | kacho · docs | — | S |' \
  '| G2 | страница 2 | `docs-writer` | kacho · docs | — | S |' \
  '| H1 | служба | `go-implementer` | kacho · a | — | M |')
if run G2 0 "$g2" --pack guard --minutes S=15,M=25,L=30; then
  has G2 'пакетов: 3; цепочек (>1 полосы): 0; склеек: 0;' 'путь длиннее базы — склейка отвергнута'
  has G2 'критический путь: 50 мин' 'путь 50'
fi

# ── U: предел склейки — ровно 4 единицы законны, 5 — нет ────────────────────
u1=$(task 9012 \
  '| U1 | глава 1 | `docs-writer` | kacho · docs | — | L |' \
  '| U2 | глава 2 | `docs-writer` | kacho · docs | — | L |')
if run U1 0 "$u1" --pack literal; then
  has U1 'пакетов: 1;' 'L+L = 4 единицы — одним пакетом'
fi
u2=$(task 9013 \
  '| U1 | глава 1 | `docs-writer` | kacho · docs | — | L |' \
  '| U2 | глава 2 | `docs-writer` | kacho · docs | — | L |' \
  '| U3 | глава 3 | `docs-writer` | kacho · docs | — | S |')
if run U2 0 "$u2" --pack literal; then
  has U2 'пакетов: 2;' 'L+L+S = 5 единиц — S отдельно'
fi

# ── H: цепочка не заводит цикла пакетов ─────────────────────────────────────
# 9014: CA2 ждёт CA1 и CB1, CB1 ждёт CA1. Пакет CA1+CA2 ждал бы CB1, а CB1 — его:
#   цепочка отвергнута, пакетов 3, путь 40+40+40 = 120.
# 9015: близнец без ребра CA2 ← CB1 — цепочка CA1+CA2 = 55, CB1 после неё: 95.
h1=$(task 9014 \
  '| CA1 | звено 1 | `go-implementer` | kacho · a | — | S |' \
  '| CB1 | страница | `docs-writer` | kacho · docs | CA1 | S |' \
  '| CA2 | звено 2 | `go-implementer` | kacho · a | CA1, CB1 | S |')
if run H1 0 "$h1"; then
  has H1 "отказов склейки: {'цепочка: цикл пакетов': 1}" 'цепочка через чужой пакет отвергнута'
  has H1 'критический путь: 120 мин' 'путь 120'
fi
h2=$(task 9015 \
  '| CA1 | звено 1 | `go-implementer` | kacho · a | — | S |' \
  '| CB1 | страница | `docs-writer` | kacho · docs | CA1 | S |' \
  '| CA2 | звено 2 | `go-implementer` | kacho · a | CA1 | S |')
if run H2 0 "$h2"; then
  has H2 'пакетов: 2; цепочек (>1 полосы): 1;' 'без обратного ребра цепочка законна'
  has H2 'критический путь: 95 мин' 'путь 95'
fi

# ── M: склеиваются только независимые пакеты; цепочка — внутри под-фазы ─────
# 9052:M2 ждёт всю 9051 (M1) по ведомости. Однотипны, но зависимы: пакетов 2,
# путь 40+40 = 80. Склейка или цепочка через границу под-фаз дала бы 1 и 55.
m1=$(task 9051 '| M1 | страница 1 | `docs-writer` | kacho · docs | — | S |')
m2=$(task 9052 '| M2 | страница 2 | `docs-writer` | kacho · docs | Е1 | S |')
printf '9052\tЕ1\t9051\n' > "$box/sem-m.tsv"
if run M1 0 "$m1" "$m2" --edges B --pack literal --semantic "$box/sem-m.tsv"; then
  has M1 'пакетов: 2;' 'зависимые однотипные полосы разных под-фаз — два пакета'
  has M1 'критический путь: 80 мин' 'путь 80'
fi

# ── I: внутризадачная строка ведомости (цель = своя под-фаза) ───────────────
# Жетон — фраза без «ёлочек» в двух ячейках. V2 и V4 ждут V1 и V3, но не друг
# друга: путь 40 + 70 = 110, пакетов 4. Действует и в режиме A.
i1=$(task 9018 \
  '| V1 | ручка | `rpc-implementer` | kacho · a | — | S |' \
  '| V2 | служба | `go-implementer` | kacho · a | на стенде | L |' \
  '| V3 | схема | `migration-writer` | kacho · m | — | S |' \
  '| V4 | страница | `docs-writer` | kacho · docs | на стенде | S |')
printf '9018\tна стенде\t9018\n' > "$box/sem-i.tsv"
if run I1 0 "$i1" --edges A --semantic "$box/sem-i.tsv"; then
  has I1 'критический путь: 110 мин' 'носители ждут остальных, но не друг друга'
  has I1 'A: 9018 на стенде -> все полосы 9018 (2), носителей 2' 'носители фразы найдены в ячейке'
fi

# ── X: межфазная строка — носители ЦЕЛИ тем же жетоном не исключаются ───────
# Жетоны `Е<n>` нумеруются в каждом файле заново: 9041:Y2 несёт свой Е1, но
# W1 (9042, Е1 → 9041) ждёт и его: путь 70 + 40 = 110, а не 80.
x1=$(task 9041 \
  '| Y1 | звено | `go-implementer` | kacho · a | — | S |' \
  '| Y2 | служба | `go-implementer` | kacho · b | Е1 | L |')
x2=$(task 9042 '| W1 | потребитель | `go-implementer` | kacho · c | Е1 | S |')
printf '9042\tЕ1\t9041\n' > "$box/sem-x.tsv"
if run X1 0 "$x1" "$x2" --edges B --semantic "$box/sem-x.tsv"; then
  has X1 'критический путь: 110 мин' 'W1 ждёт и носителя одноимённого жетона цели'
  has X1 'B: 9042 Е1 -> все полосы 9041 (2), носителей 1' 'целей 2'
fi

# ── Q: расписание — первым стартует готовый пакет с наибольшим остатком пути ─
# 9016: Q1, Q2, Q3 по 40, Q4 (70) после Q3. 2 слота по остатку пути: Q3 и Q1,
# затем Q4 и Q2 → 110. По порядку id: Q1, Q2, затем Q3, Q4 → 150.
q1=$(task 9016 \
  '| Q1 | звено 1 | `go-implementer` | kacho · a | — | S |' \
  '| Q2 | звено 2 | `go-implementer` | kacho · a | — | S |' \
  '| Q3 | звено 3 | `go-implementer` | kacho · a | — | S |' \
  '| Q4 | ручка | `rpc-implementer` | kacho · b | Q3 | L |')
if run Q1 0 "$q1" --slots 1,2; then
  has Q1 'слотов 1: срок 190 мин' '1 слот — сумма, от порядка не зависит'
  has Q1 'слотов 2: срок 110 мин' '2 слота — длинный остаток первым, срок = путь'
fi

# ── Z: пакет диспетчера длится 0 и слота не занимает и не отдаёт ────────────
# 9017: Z1 → Z2 (диспетчер) → Z3, Z4 независим. 1 слот: 40 + 0 + 40 + 40 = 120.
z1=$(task 9017 \
  '| Z1 | звено 1 | `go-implementer` | kacho · a | — | S |' \
  '| Z2 | решение | диспетчер | kacho-workspace · — | Z1 | S |' \
  '| Z3 | звено 2 | `go-implementer` | kacho · b | Z2 | S |' \
  '| Z4 | ручка | `rpc-implementer` | kacho · c | — | S |')
if run Z1 0 "$z1" --slots 1; then
  has Z1 'слотов 1: срок 120 мин' 'диспетчер лишнего слота не даёт'
  has Z1 'критический путь: 80 мин' 'путь 40 + 0 + 40'
