#!/usr/bin/env bash
# Прогон набора comment-language-gate. Вердикт стоит в КОДЕ ВЫХОДА, а не в печати.
#
# ПРЕДМЕТ НАБОРА — требование владельца 2026-09-21, дословно: «комментарии
# только на русском. Существующие правки привести к виду». Норма —
# `.claude/rules/00-kacho-core.md`, строки `ban22-*`; она сама называет этот
# набор своим держателем.
#
# ПОЧЕМУ ДОМ ЗДЕСЬ, А НЕ В ДЕРЕВЕ ПРОДУКТА. Предмет — ЧЕТЫРЕ дерева сразу:
# `kacho`, `kaname`, `corelib` и оснастка самого воркспейса. Гейт, поставленный
# в одном продукте, судил бы четверть предмета и печатал бы число, читаемое как
# целое. Воркспейс — единственное место, где под рукой все четыре клона; так же
# и по той же причине устроены `scripts/crossrepo-gate` и
# `scripts/foundation-candidates`.
#
# ТРИ ИСХОДА, А НЕ ДВА:
#   0 — рассмотрено N проверок, находок 0, у каждой был предмет;
#   1 — НАХОДКА: проверка упала, либо обход пуст;
#   2 — БЕЗ ПРЕДМЕТА: клона нет, ведомость не прочитана либо лексер отказал.
# Третий исход НЕ засчитывается за успех: «не-русской прозы 0» и «ноль
# прочитанных файлов» — разные вещи, и вторая опаснее.
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

ok=0; bad=0; void=0; count=0
for c in "$SCRIPT_DIR"/check-*; do
    [ -f "$c" ] || continue
    count=$((count + 1))
    case "$c" in
        *.py) python3 "$c" ;;
        *)    bash "$c" ;;
    esac
    case $? in
        0) ok=$((ok + 1)) ;;
        2) void=$((void + 1)) ;;
        *) bad=$((bad + 1)) ;;
    esac
done

if [ "$count" -gt 0 ]; then
    echo
    echo "comment-language-gate: рассмотрено проверок $count; пройдено $ok, провалено $bad, без предмета $void"
else
    echo "comment-language-gate: рассмотрено проверок 0 в $SCRIPT_DIR — прогонять нечего" >&2
fi

[ "$count" -gt 0 ] || exit 1
[ "$bad" -eq 0 ] || exit 1
[ "$void" -eq 0 ] || exit 2
exit 0
